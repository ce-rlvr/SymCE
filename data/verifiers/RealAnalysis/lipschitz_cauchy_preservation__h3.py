import sympy as sp
import itertools

# Top-level setup: named object bindings that the witness expression may reference.
x, n = sp.symbols('x n', real=True)

def conditions(witness) -> list[bool]:
    try:
        f_expr = witness['f']
        x_n_expr = witness['x_n']
        L = witness.get('L', 1.0)
        
        # H_1: (X, d_X) and (Y, d_Y) are metric spaces
        # We evaluate the witness in the context of the real numbers with the standard metric,
        # which trivially forms a valid metric space.
        h1 = True
        
        # H_2: f: X -> Y is Lipschitz continuous
        f_func = sp.lambdify(x, f_expr, modules=['math', 'sympy'])
        seq_func = sp.lambdify(n, x_n_expr, modules=['math', 'sympy'])
        
        # Build a set of test points to verify the Lipschitz condition
        points = [i / 10.0 for i in range(-100, 101)]
        
        # Add points generated by the sequence to ensure Lipschitz holds on the relevant domain
        for i in range(1, 50):
            try:
                val = float(seq_func(i))
                if abs(val) < 100000:
                    points.append(val)
            except Exception:
                pass
                
        # Add some large points to check for global Lipschitzness (e.g. to reject x^2)
        for large_pt in [100.0, -100.0, 1000.0, -1000.0, 10000.0, -10000.0]:
            points.append(large_pt)
            points.append(large_pt + 0.1)
            
        points = list(set(points))
        
        h2 = True
        valid_pairs = 0
        for a, b in itertools.combinations(points, 2):
            if abs(a - b) < 1e-9:
                continue
            try:
                val_a = complex(f_func(a))
                val_b = complex(f_func(b))
                # Ignore points where the function is not real-valued
                if abs(val_a.imag) > 1e-9 or abs(val_b.imag) > 1e-9:
                    continue
                val_a = val_a.real
                val_b = val_b.real
                valid_pairs += 1
                
                # Check Lipschitz condition: |f(a) - f(b)| <= L * |a - b|
                if abs(val_a - val_b) > float(L) * abs(a - b) + 1e-5:
                    h2 = False
                    break
            except Exception:
                continue
                
        if valid_pairs == 0:
            h2 = False
            
        # ¬Q: The sequence (f(x_n)) is NOT a Cauchy sequence in Y
        seq_expr = f_expr.subs(x, x_n_expr)
        seq_func_f = sp.lambdify(n, seq_expr, modules=['math', 'sympy'])
        
        neg_q = False
        try:
            # A sequence in R is Cauchy iff it converges to a finite limit
            L_limit = sp.limit(seq_expr, n, sp.oo)
            if L_limit.has(sp.AccumBounds):
                neg_q = True
            elif L_limit.is_real and L_limit.is_finite:
                neg_q = False
            else:
                neg_q = True
        except Exception:
            # Fallback to numerical check for convergence/Cauchy property
            try:
                vals = []
                for i in range(10000, 10050):
                    vals.append(complex(seq_func_f(i)))
                
                if any(abs(v.imag) > 1e-9 for v in vals):
                    neg_q = True
                else:
                    vals = [v.real for v in vals]
                    max_diff = max(abs(a - b) for a, b in itertools.combinations(vals, 2))
                    if max_diff > 1e-4:
                        neg_q = True
                    else:
                        vals2 = []
                        for i in range(20000, 20050):
                            vals2.append(complex(seq_func_f(i)).real)
                        diff_blocks = abs(vals[0] - vals2[0])
                        if diff_blocks > 1e-4:
                            neg_q = True
                        else:
                            neg_q = False
            except Exception:
                neg_q = True
                
    except Exception:
        h1 = False
        h2 = False
        neg_q = False
        
    return [bool(h1), bool(h2), bool(neg_q)]

