import sympy
from sympy.abc import x

# Top-level setup
# The witness is expected to be a dictionary with:
# - 'X': a tuple or list of two numbers (a, b) representing the compact interval [a, b]
# - 'generators': a list of sympy polynomial expressions in `x` that generate the subalgebra A

def conditions(witness):
    try:
        if not isinstance(witness, dict):
            return [False, False, False, False]
        X = witness.get('X')
        funcs = witness.get('generators', [])
    except Exception:
        return [False, False, False, False]

    # H1: X is a compact metric space (represented as a valid closed interval [a, b])
    try:
        h1_ok = isinstance(X, (tuple, list)) and len(X) == 2
        if h1_ok:
            a, b = X
            h1_ok = float(a) < float(b)
    except Exception:
        h1_ok = False

    # H2: A is a subalgebra of C(X, R)
    # Since A is generated by the given functions, it is automatically a subalgebra.
    # We just verify that the generators are valid continuous functions (polynomials in x).
    try:
        h2_ok = False
        if funcs and isinstance(funcs, (list, tuple)):
            h2_ok = True
            for f in funcs:
                if not isinstance(f, sympy.Expr) or not f.is_polynomial(x):
                    h2_ok = False
                    break
    except Exception:
        h2_ok = False

    # H3: A separates points
    # We check if at least one generator is strictly monotonic on the interior of X.
    # A polynomial is strictly monotonic if its derivative does not change sign (no roots of odd multiplicity).
    try:
        h3_ok = False
        if h1_ok and h2_ok:
            a, b = float(X[0]), float(X[1])
            for f in funcs:
                dp = sympy.diff(f, x)
                if dp == 0:
                    continue
                
                roots = sympy.real_roots(dp, multiple=True)
                root_counts = {}
                for r in roots:
                    if r.is_real:
                        r_val = float(r.evalf())
                        if a < r_val < b:
                            root_counts[r] = root_counts.get(r, 0) + 1
                            
                changes_sign = False
                for r, count in root_counts.items():
                    if count % 2 != 0:
                        changes_sign = True
                        break
                        
                if not changes_sign:
                    h3_ok = True
                    break
    except Exception:
        h3_ok = False

    # neg_Q: A is not dense in C(X, R)
    # By Stone-Weierstrass, a separating subalgebra is dense iff it vanishes nowhere.
    # Thus, it fails to be dense iff all generators share a common root in X.
    try:
        neg_q_ok = False
        if h1_ok and h2_ok:
            a, b = float(X[0]), float(X[1])
            roots = sympy.real_roots(funcs[0], multiple=False)
            for r in roots:
                if r.is_real:
                    r_val = float(r.evalf())
                    if a <= r_val <= b:
                        all_vanish = True
                        for f in funcs[1:]:
                            val = f.subs(x, r).evalf()
                            if abs(float(val)) > 1e-9:
                                all_vanish = False
                                break
                        if all_vanish:
                            neg_q_ok = True
                            break
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, h3_ok, neg_q_ok]

