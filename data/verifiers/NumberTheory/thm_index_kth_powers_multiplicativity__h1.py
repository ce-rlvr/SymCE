import math

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "The index of the subgroup of k-th powers modulo mn is the product of the indices modulo m and modulo n"
    
    The false conjecture arises from a mistranslation/typo of "subgroup of powers of k" (i.e., the subgroup 
    generated by k) as "subgroup of k-th powers". The index of the subgroup of k-th powers (U_n^k) is ALWAYS 
    multiplicative by the Chinese Remainder Theorem. However, the index of the subgroup generated by k (<k>) 
    is only multiplicative if gcd(ord_m(k), ord_n(k)) = 1.
    """
    try:
        # Witness can be a dictionary or a tuple (m, n, k)
        if isinstance(witness, dict):
            m = witness['m']
            n = witness['n']
            k = witness['k']
        else:
            m, n, k = witness
    except Exception:
        return [False, False, False]

    # H_1: m and n are positive integers
    try:
        h1 = isinstance(m, int) and isinstance(n, int) and m > 0 and n > 0
    except Exception:
        h1 = False

    # H_2: \gcd(m, n) = 1
    try:
        h2 = math.gcd(m, n) == 1
    except Exception:
        h2 = False

    # ¬Q: The index of the subgroup of k-th powers modulo mn is NOT the product of the indices modulo m and modulo n
    try:
        def get_index_of_generated_subgroup(modulus, base):
            if modulus == 1:
                return 1
            if math.gcd(base, modulus) != 1:
                return None
            
            # Compute Euler's totient function phi(modulus)
            temp = modulus
            phi = temp
            p = 2
            while p * p <= temp:
                if temp % p == 0:
                    while temp % p == 0:
                        temp //= p
                    phi -= phi // p
                p += 1
            if temp > 1:
                phi -= phi // temp
                
            # Find the multiplicative order of base modulo modulus
            # The order must divide phi(modulus)
            divisors = []
            for i in range(1, math.isqrt(phi) + 1):
                if phi % i == 0:
                    divisors.append(i)
                    if i * i != phi:
                        divisors.append(phi // i)
            divisors.sort()
            
            order = None
            for d in divisors:
                if pow(base, d, modulus) == 1:
                    order = d
                    break
                    
            if order is None:
                return None
                
            # The index of the subgroup generated by base in U_modulus is phi(modulus) / order
            return phi // order

        idx_mn = get_index_of_generated_subgroup(m * n, k)
        idx_m = get_index_of_generated_subgroup(m, k)
        idx_n = get_index_of_generated_subgroup(n, k)

        if idx_mn is None or idx_m is None or idx_n is None:
            # If k is not coprime to mn, the subgroup generated by k is not a valid subgroup of the units.
            # In the context of the false conjecture, this means the conclusion is undefined/fails.
            neg_q = True
        else:
            neg_q = idx_mn != idx_m * idx_n

    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

