def conditions(witness) -> list[bool]:
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    Hypothesis: gcd(m1, m2) = 1
    Conclusion: Z/(m1*m2)Z is isomorphic to (Z/m1Z) x (Z/m2Z)
    """
    try:
        if isinstance(witness, (tuple, list)) and len(witness) == 2:
            m1, m2 = witness
        else:
            return [False, False]
    except Exception:
        return [False, False]

    # H_1: gcd(m1, m2) = 1
    try:
        if isinstance(m1, int) and isinstance(m2, int):
            h1 = (math.gcd(m1, m2) == 1)
        else:
            m1_sym = sympy.sympify(m1)
            m2_sym = sympy.sympify(m2)
            h1 = (sympy.gcd(m1_sym, m2_sym) == 1)
    except Exception:
        h1 = False

    # neg_Q: Z/(m1*m2)Z is NOT isomorphic to (Z/m1Z) x (Z/m2Z)
    # In a Principal Ideal Domain like Z, gcd(m1, m2) = 1 implies the ideals are comaximal,
    # so they are always isomorphic. However, in a UFD that is not a PID (like Z[x]),
    # gcd(m1, m2) = 1 does not imply comaximality, and the isomorphism fails.
    try:
        if isinstance(m1, int) and isinstance(m2, int):
            # For integers, gcd=1 implies comaximal, so they are always isomorphic.
            neg_q = False
        else:
            m1_sym = sympy.sympify(m1)
            m2_sym = sympy.sympify(m2)
            vars_list = sorted(list(m1_sym.free_symbols | m2_sym.free_symbols), key=lambda x: x.name)
            if not vars_list:
                # They evaluate to constants
                neg_q = False
            else:
                # Check if they are comaximal over ZZ (i.e., if 1 is in the ideal generated by m1 and m2)
                gb = groebner([m1_sym, m2_sym], *vars_list, domain='ZZ')
                is_comaximal = (list(gb) == [1])
                neg_q = not is_comaximal
    except Exception:
        neg_q = False

    return [bool(h1), bool(neg_q)]

