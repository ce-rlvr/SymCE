import sympy
from sympy.combinatorics.named_groups import (
    SymmetricGroup, AlternatingGroup, DihedralGroup, CyclicGroup
)
from sympy.matrices import eye, zeros

# Top-level setup for standard algebra objects
S3 = SymmetricGroup(3)
S4 = SymmetricGroup(4)
A4 = AlternatingGroup(4)
D4 = DihedralGroup(4)
C4 = CyclicGroup(4)
V4 = AlternatingGroup(4)
Z2 = CyclicGroup(2)
Z3 = CyclicGroup(3)
Z4 = CyclicGroup(4)
Z6 = CyclicGroup(6)
trivial = CyclicGroup(1)
I2 = eye(2)
I3 = eye(3)
O2 = zeros(2, 2)
O3 = zeros(3, 3)

N_HYP = 2
NEG_Q_INDEX = 2

CONDITION_LABELS = [
    "H_1: a1 and a2 are integers",
    "H_2: a1 ≡ a2 (mod gcd(m1, m2))",
    "¬Q: The system does not have a unique solution modulo lcm(m1, m2)"
]

def conditions(witness) -> list[bool]:
    try:
        a1, a2, m1, m2 = witness
    except Exception:
        return [False, False, False]
        
    # H_1: a1 and a2 are integers
    try:
        a1_sym = sympy.sympify(a1)
        a2_sym = sympy.sympify(a2)
        h1 = bool(a1_sym.is_integer) and bool(a2_sym.is_integer)
    except Exception:
        h1 = False
        
    # H_2: a1 ≡ a2 (mod gcd(m1, m2))
    try:
        m1_sym = sympy.sympify(m1)
        m2_sym = sympy.sympify(m2)
        g = sympy.gcd(m1_sym, m2_sym)
        diff = a1_sym - a2_sym
        
        if g == 0:
            h2 = bool(diff == 0)
        else:
            syms = diff.free_symbols | g.free_symbols
            if not syms:
                h2 = bool((diff / g).is_integer)
            else:
                syms_list = list(syms)
                rem = sympy.reduced(diff, [g], syms_list)[1]
                h2 = bool(rem == 0)
    except Exception:
        h2 = False
        
    # ¬Q: The system does not have a unique solution modulo lcm(m1, m2)
    # In a UFD, if a solution exists, it is always unique modulo lcm(m1, m2).
    # The conclusion fails if and only if NO solution exists.
    # A solution exists iff (a1 - a2) is in the ideal generated by (m1, m2).
    try:
        m1_sym = sympy.sympify(m1)
        m2_sym = sympy.sympify(m2)
        diff = a1_sym - a2_sym
        
        if diff == 0:
            neg_q = False
        else:
            syms = diff.free_symbols | m1_sym.free_symbols | m2_sym.free_symbols
            if not syms:
                g_num = sympy.gcd(m1_sym, m2_sym)
                if g_num == 0:
                    neg_q = bool(diff != 0)
                else:
                    neg_q = not bool((diff / g_num).is_integer)
            else:
                syms_list = list(syms)
                try:
                    # Check ideal membership over ZZ (e.g., for Z[x])
                    gb = sympy.groebner([m1_sym, m2_sym], *syms_list, domain='ZZ')
                    rem = sympy.reduced(diff, gb, syms_list, domain='ZZ')[1]
                except Exception:
                    # Fallback to default domain (e.g., QQ)
                    gb = sympy.groebner([m1_sym, m2_sym], *syms_list)
                    rem = sympy.reduced(diff, gb, syms_list)[1]
                neg_q = bool(rem != 0)
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]