def conditions(witness) -> list[bool]:
    # witness is expected to be a tuple: (G, g, N, m, n, h, x)
    try:
        G, g, N, m, n, h, x = witness
    except Exception:
        return [False] * 5 + [False]

    # H_1: G is a group
    try:
        H_1 = isinstance(G, PermutationGroup)
    except Exception:
        H_1 = False

    # H_2: g is an element of G of order N
    try:
        H_2 = (g in G) and (g.order() == N)
    except Exception:
        H_2 = False

    # H_3: N = mn where m and n are positive integers
    try:
        H_3 = isinstance(m, int) and isinstance(n, int) and m > 0 and n > 0 and N == m * n
    except Exception:
        H_3 = False

    # H_4: h is an element of the subgroup generated by g
    try:
        # Check if h is in the cyclic group generated by g
        # Since g has order N, we can just check if h == g**k for some k
        H_4 = False
        if H_2:
            for k in range(N):
                if h == g**k:
                    H_4 = True
                    break
    except Exception:
        H_4 = False

    # H_5: x is an integer such that g^x = h
    try:
        H_5 = isinstance(x, int) and (g**x == h)
    except Exception:
        H_5 = False

    # ¬Q: The value of x modulo m is NOT the unique solution y \pmod m to the equation (g^n)^y = h^n
    try:
        neg_Q = False
        if H_1 and H_2 and H_3 and H_4 and H_5:
            gn = g**n
            hn = h**n
            
            # Find all solutions y modulo m to (g^n)^y = h^n
            solutions = []
            for y in range(m):
                if gn**y == hn:
                    solutions.append(y)
            
            x_mod_m = x % m
            
            # The conclusion is that x_mod_m is the UNIQUE solution modulo m.
            # So the negation is that x_mod_m is NOT a solution, OR there are other solutions modulo m.
            if len(solutions) != 1 or solutions[0] != x_mod_m:
                neg_Q = True
    except Exception:
        neg_Q = False

    return [H_1, H_2, H_3, H_4, H_5, neg_Q]

