def conditions(witness):
    try:
        T, v, W = witness
    except Exception:
        return [False, False, False, False]

    # H_1: V is a finite-dimensional vector space over F
    # We verify this by checking that T and v are matrices (representing operators/vectors over F^n)
    try:
        h1 = isinstance(T, Matrix) and isinstance(v, Matrix)
    except Exception:
        h1 = False

    # H_2: T is a linear operator on V
    try:
        h2 = T.is_square
    except Exception:
        h2 = False

    # H_3: v \in V is a non-zero vector
    try:
        h3 = v.shape == (T.shape[0], 1) and any(val != 0 for val in v)
    except Exception:
        h3 = False

    # ¬Q: The dimension of W is not equal to the degree of the minimal polynomial of v w.r.t T
    try:
        n = T.shape[0]
        
        # The degree of the minimal polynomial of v w.r.t T is exactly the dimension 
        # of the T-cyclic subspace generated by v. We find this by computing the rank 
        # of the Krylov matrix [v, Tv, T^2v, ..., T^{n-1}v].
        K = v
        curr = v
        for _ in range(n - 1):
            curr = T * curr
            K = K.row_join(curr)
            
        deg_p = K.rank()
        
        # Determine the dimension of W based on how the witness provides it
        if isinstance(W, Matrix):
            dim_W = W.rank()
        elif isinstance(W, (int, sympy.Integer)):
            dim_W = int(W)
        elif isinstance(W, list) and all(isinstance(w, Matrix) for w in W):
            if len(W) > 0:
                W_mat = W[0]
                for w in W[1:]:
                    W_mat = W_mat.row_join(w)
                dim_W = W_mat.rank()
            else:
                dim_W = 0
        else:
            dim_W = None
            
        if dim_W is not None:
            neg_q = (dim_W != deg_p)
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

