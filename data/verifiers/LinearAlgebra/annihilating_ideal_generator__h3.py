def matrix_pow(A, n, I):
    if n == 0:
        return I
    res = A
    for _ in range(1, n):
        res = res * A
    return res

def eval_poly_matrix(poly_expr, A, t_sym):
    p = Poly(poly_expr, t_sym)
    coeffs = p.all_coeffs()
    deg = p.degree()
    
    if hasattr(A, 'eye'):
        I = A.eye(A.rows)
    elif hasattr(A, 'shape'):
        I = eye(A.shape[0])
    else:
        I = eye(A.rows)
        
    if deg < 0:
        return I * 0
        
    res = coeffs[0] * matrix_pow(A, deg, I) if deg > 0 else coeffs[0] * I
    for i in range(1, deg + 1):
        power = deg - i
        term = coeffs[i] * matrix_pow(A, power, I) if power > 0 else coeffs[i] * I
        res = res + term
    return res

def is_zero_mat(M):
    if hasattr(M, 'is_zero_matrix'):
        if M.is_zero_matrix is not None:
            return M.is_zero_matrix
            
    if not hasattr(M, 'rows') and not hasattr(M, 'shape'):
        try:
            return simplify(M) == 0
        except Exception:
            return False
            
    try:
        rows = M.rows if hasattr(M, 'rows') else M.shape[0]
        cols = M.cols if hasattr(M, 'cols') else M.shape[1]
        for i in range(rows):
            for j in range(cols):
                val = M[i, j] if hasattr(M, 'rows') else M[i][j]
                if val != 0:
                    if hasattr(val, 'is_zero') and val.is_zero:
                        continue
                    if simplify(val) != 0:
                        return False
        return True
    except Exception:
        pass
    return False

def conditions(witness):
    try:
        q = None
        p_mult = None
        if isinstance(witness, dict):
            A = witness['A']
            m = witness['m']
            t_sym = witness.get('t', m.free_symbols.pop() if m.free_symbols else sympy.Symbol('t'))
            q = witness.get('q', None)
            p_mult = witness.get('p', None)
        else:
            if len(witness) == 5:
                A, m, t_sym, q, p_mult = witness
            elif len(witness) == 4:
                A, m, t_sym, q = witness
            elif len(witness) == 3:
                A, m, t_sym = witness
            else:
                A, m = witness
                t_sym = m.free_symbols.pop() if m.free_symbols else sympy.Symbol('t')
    except Exception:
        return [False, False, False, False]

    # H1: F is a field
    try:
        if hasattr(A, 'domain'):
            h1 = A.domain.is_Field
            if h1 is None:
                h1 = True
        else:
            h1 = True
    except Exception:
        h1 = True

    # H2: A is an n x n matrix over F
    try:
        h2 = False
        if hasattr(A, 'rows') and hasattr(A, 'cols'):
            h2 = A.rows == A.cols
        elif hasattr(A, 'shape'):
            h2 = len(A.shape) == 2 and A.shape[0] == A.shape[1]
    except Exception:
        h2 = False

    # H3: m(t) is the monic polynomial of least degree in I_A
    try:
        p_m = Poly(m, t_sym)
        is_monic = p_m.LC() == 1
        mA = eval_poly_matrix(m, A, t_sym)
        is_annihilating = is_zero_mat(mA)
        
        h3 = is_monic and is_annihilating
        
        if h3:
            try:
                minp = A.minpoly(t_sym)
                if Poly(minp, t_sym).degree() < p_m.degree():
                    h3 = False
            except Exception:
                pass
    except Exception:
        h3 = False

    # neg_Q: I_A is NOT a principal ideal generated by m(t)
    try:
        neg_q = False
        
        # Check if I_A is not an ideal (e.g. over a skew field)
        if q is not None and p_mult is not None:
            qA = eval_poly_matrix(q, A, t_sym)
            if is_zero_mat(qA):
                pq = p_mult * q
                pqA = eval_poly_matrix(pq, A, t_sym)
                if not is_zero_mat(pqA):
                    neg_q = True
                    
        # Check if there is an annihilating polynomial not divisible by m(t)
        if not neg_q and q is not None:
            qA = eval_poly_matrix(q, A, t_sym)
            if is_zero_mat(qA):
                rem = Poly(q, t_sym) % Poly(m, t_sym)
                if not rem.is_zero:
                    neg_q = True
                    
        # Fallback: check if the characteristic polynomial is not divisible by m(t)
        if not neg_q:
            try:
                charpoly = A.charpoly(t_sym)
                rem = Poly(charpoly, t_sym) % Poly(m, t_sym)
                if not rem.is_zero:
                    cA = eval_poly_matrix(charpoly, A, t_sym)
                    if is_zero_mat(cA):
                        neg_q = True
            except Exception:
                pass
                
    except Exception:
        neg_q = False

    return [bool(h1), bool(h2), bool(h3), bool(neg_q)]

