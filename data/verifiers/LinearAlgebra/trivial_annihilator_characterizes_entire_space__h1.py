def conditions(witness) -> list[bool]:
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "Let W be a subspace of V. Let W^0 be the annihilator of W. W^0 = {0} iff W = V."
    
    The conjecture is true for vector spaces over a field, but false for modules 
    over a ring (e.g., Z-modules). A valid counterexample will typically be a 
    proper submodule W of V such that its annihilator is trivial.
    """
    # 1. Try custom object with methods
    try:
        h1 = bool(witness.is_subspace())
        h2 = True
        q = bool(witness.is_annihilator_trivial() == witness.is_equal())
        return [h1, h2, not q]
    except Exception:
        pass

    # 2. Try tuple (V, W) representing modules/ideals
    try:
        if isinstance(witness, (tuple, list)) and len(witness) == 2:
            V, W = witness
            
            # 2a. Integers (Z-modules)
            if isinstance(V, (int, sp.Integer)) and isinstance(W, (int, sp.Integer)):
                V_val = int(V)
                W_val = int(W)
                if V_val != 0:
                    h1 = (W_val % V_val == 0)
                else:
                    h1 = (W_val == 0)
                h2 = True
                w0_is_trivial = (W_val != 0)
                w_equals_v = (abs(V_val) == abs(W_val))
                q = (w0_is_trivial == w_equals_v)
                return [h1, h2, not q]
                
            # 2b. Matrices (Z-modules / column spaces)
            if isinstance(V, Matrix) and isinstance(W, Matrix):
                try:
                    X = V.solve(W)
                    h1 = all(x.is_integer for x in X)
                except Exception:
                    h1 = False
                h2 = True
                w0_is_trivial = len(W.T.nullspace()) == 0
                try:
                    Y = W.solve(V)
                    w_equals_v = all(y.is_integer for y in Y)
                except Exception:
                    w_equals_v = False
                q = (w0_is_trivial == w_equals_v)
                return [h1, h2, not q]
                
            # 2c. Polynomials / Expressions (Ideals in F[x])
            if isinstance(V, sp.Expr) and isinstance(W, sp.Expr):
                rem = sp.rem(W, V)
                h1 = (rem == 0)
                h2 = True
                w0_is_trivial = (W != 0)
                rem2 = sp.rem(V, W)
                w_equals_v = (rem == 0 and rem2 == 0)
                q = (w0_is_trivial == w_equals_v)
                return [h1, h2, not q]
    except Exception:
        pass

    # 3. Try single integer (W is the ideal generated by witness, V is Z)
    try:
        if isinstance(witness, (int, sp.Integer)):
            W_val = int(witness)
            V_val = 1
            h1 = (W_val % V_val == 0)
            h2 = True
            w0_is_trivial = (W_val != 0)
            w_equals_v = (abs(V_val) == abs(W_val))
            q = (w0_is_trivial == w_equals_v)
            return [h1, h2, not q]
    except Exception:
        pass

    # 4. Try single Matrix (W is the column space, V is the full space Z^n)
    try:
        if isinstance(witness, Matrix):
            W = witness
            V = eye(W.rows)
            h1 = True
            h2 = True
            w0_is_trivial = len(W.T.nullspace()) == 0
            if W.rows == W.cols:
                w_equals_v = abs(W.det()) == 1
            else:
                w_equals_v = False
            q = (w0_is_trivial == w_equals_v)
            return [h1, h2, not q]
    except Exception:
        pass

    # 5. Try dictionary format
    try:
        if isinstance(witness, dict):
            if 'V' in witness and 'W' in witness:
                return conditions((witness['V'], witness['W']))
    except Exception:
        pass

    return [False, False, False]

