def conditions(witness):
    """
    Checks if the witness satisfies the remaining hypotheses and fails the conclusion.
    The dropped hypothesis from the true theorem is "T is a linear operator on V".
    A valid counterexample must provide a T that does not leave V invariant,
    making the dual operator T* ill-defined on V*, thus falsifying the conclusion.
    
    Expected witness format: (V, v, T) or (V, v, T, Z)
    where V is a basis matrix or list of vectors for the subspace,
    v is a column vector, T is a square matrix, and Z (optional) is the cyclic subspace.
    """
    try:
        if len(witness) == 2:
            T, v = witness
            V = eye(T.shape[0])
            Z = None
        elif len(witness) == 3:
            V, v, T = witness
            Z = None
        elif len(witness) == 4:
            V, v, T, Z = witness
        else:
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]

    try:
        if isinstance(v, list):
            v = Matrix(v)
        if isinstance(T, list):
            T = Matrix(T)
        if not isinstance(T, Matrix) or not isinstance(v, Matrix):
            return [False, False, False, False]
        if T.shape[0] != T.shape[1]:
            return [False, False, False, False]
        if v.shape[0] != T.shape[0] or v.shape[1] != 1:
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]

    # H1: V is a finite-dimensional vector space over a field F
    try:
        if isinstance(V, list):
            if len(V) == 0:
                V_mat = zeros(T.shape[0], 1)
            elif isinstance(V[0], Matrix):
                V_mat = Matrix.hstack(*V)
            else:
                V_mat = Matrix(V)
        else:
            V_mat = Matrix(V)
            
        if V_mat.shape[0] != T.shape[0]:
            H1 = False
        else:
            H1 = True
    except Exception:
        H1 = False

    # H2: v is a vector in V
    try:
        rk_V = V_mat.rank()
        rk_Vv = V_mat.row_join(v).rank()
        H2 = (rk_V == rk_Vv)
    except Exception:
        H2 = False

    # H3: Z(v, T) is the T-cyclic subspace generated by v
    try:
        n = T.shape[0]
        curr = v
        Z_cols = [curr]
        for _ in range(n):
            curr = T * curr
            Z_cols.append(curr)
        Z_mat = Matrix.hstack(*Z_cols)
        
        if Z is not None:
            if isinstance(Z, list):
                if len(Z) == 0:
                    Z_given = zeros(n, 1)
                elif isinstance(Z[0], Matrix):
                    Z_given = Matrix.hstack(*Z)
                else:
                    Z_given = Matrix(Z)
            else:
                Z_given = Matrix(Z)
                
            rk_Z = Z_mat.rank()
            rk_Z_given = Z_given.rank()
            rk_both = Z_mat.row_join(Z_given).rank()
            H3 = (rk_Z == rk_Z_given == rk_both)
        else:
            H3 = True
    except Exception:
        H3 = False

    # neg_Q: The conclusion FAILS
    # The conclusion holds for any valid linear operator on V.
    # It fails if and only if T does not leave V invariant, making T* undefined on V*.
    try:
        T_V = T * V_mat
        rk_V = V_mat.rank()
        rk_V_TV = V_mat.row_join(T_V).rank()
        T_leaves_V_invariant = (rk_V == rk_V_TV)
        
        neg_Q = not T_leaves_V_invariant
    except Exception:
        neg_Q = False

    return [H1, H2, H3, neg_Q]

