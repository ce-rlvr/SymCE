def conditions(witness) -> list[bool]:
    """
    Checks if the witness is a counterexample to the conjecture:
    "T is injective if and only if T^t is surjective."
    """
    # 1. Support for mock objects or dictionaries (for infinite-dimensional spaces)
    try:
        if isinstance(witness, dict):
            h1 = bool(witness.get('is_vector_space', True))
            h2 = bool(witness.get('is_linear_transformation', True))
            inj = bool(witness.get('is_injective', False))
            surj = bool(witness.get('is_dual_surjective', False))
            neg_q = (inj != surj)
            return [h1, h2, neg_q]
    except Exception:
        pass

    try:
        if hasattr(witness, 'is_injective') and hasattr(witness, 'is_dual_surjective'):
            h1 = bool(getattr(witness, 'is_vector_space', True))
            h2 = bool(getattr(witness, 'is_linear_transformation', True))
            inj = bool(witness.is_injective)
            surj = bool(witness.is_dual_surjective)
            neg_q = (inj != surj)
            return [h1, h2, neg_q]
    except Exception:
        pass

    # 2. Support for SymPy Matrices (evaluating surjectivity over Z to allow ring-module counterexamples)
    try:
        if isinstance(witness, Matrix):
            # A matrix represents a linear transformation. We return True for the hypotheses.
            h1 = True
            h2 = True
            
            # T is injective iff its nullspace is trivial
            inj = len(witness.nullspace()) == 0
            
            # T^t is represented by the transpose matrix A.T mapping Z^m to Z^n.
            # It is surjective over Z iff the ideal generated by its n x n minors is Z (i.e., GCD is 1).
            n = witness.shape[1]
            m = witness.shape[0]
            
            if m < n:
                surj = False
            else:
                minors = []
                for cols in itertools.combinations(range(m), n):
                    submatrix = witness.T[:, cols]
                    minors.append(submatrix.det())
                surj = abs(gcd(minors)) == 1
                
            neg_q = (inj != surj)
            return [h1, h2, neg_q]
    except Exception:
        pass

    return [False, False, False]

