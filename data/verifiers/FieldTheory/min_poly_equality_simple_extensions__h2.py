import sympy
from sympy import Symbol, Rational, Integer, pi, E, I

# Top-level setup for witness expressions
x = Symbol('x')
y = Symbol('y')
z = Symbol('z')
t = Symbol('t')

def conditions(witness) -> list[bool]:
    try:
        # The witness is expected to be a tuple containing alpha and beta.
        # It might also contain the field F, so we take the last two elements.
        if isinstance(witness, tuple) and len(witness) >= 2:
            alpha, beta = witness[-2], witness[-1]
        else:
            return [False, False, False]
            
        # H1: F is a field. 
        # We implicitly work over the field F generated by Q and any constants in alpha and beta.
        h1 = True
        
        # Identify the transcendental generator (variable)
        symbols = alpha.free_symbols | beta.free_symbols
        if symbols:
            var = list(symbols)[0]
        elif alpha.has(sympy.pi) or beta.has(sympy.pi):
            var = sympy.Symbol('x', real=True)
            alpha = alpha.subs(sympy.pi, var)
            beta = beta.subs(sympy.pi, var)
        elif alpha.has(sympy.E) or beta.has(sympy.E):
            var = sympy.Symbol('x', real=True)
            alpha = alpha.subs(sympy.E, var)
            beta = beta.subs(sympy.E, var)
        else:
            # If there are no variables or standard transcendentals, they are algebraic numbers.
            # The conclusion holds for all algebraic extensions, so no counterexample exists here.
            return [True, False, False]
            
        def is_subfield(a, b, v):
            """
            Checks if F(a) is a subfield of F(b), i.e., if 'a' is a rational function of 'b'.
            By Luroth's theorem, we can check this by computing the resultant.
            """
            if not a.has(v):
                return True
            if not b.has(v):
                return False
                
            dy = sympy.Dummy('y')
            dz = sympy.Dummy('z')
            
            a = sympy.cancel(a)
            b = sympy.cancel(b)
            
            num_a, den_a = sympy.fraction(a)
            num_b, den_b = sympy.fraction(b)
            
            P1 = num_b - dy * den_b
            P2 = num_a - dz * den_a
            
            res = sympy.resultant(P1, P2, v)
            if res == 0:
                return False
                
            res_sqf = sympy.sqf_part(res)
            deg_z = sympy.Poly(res_sqf, dz).degree()
            return deg_z == 1

        try:
            h2 = is_subfield(alpha, beta, var)
        except Exception:
            h2 = False
            
        try:
            f_alpha_eq_f_beta = is_subfield(alpha, beta, var) and is_subfield(beta, alpha, var)
        except Exception:
            f_alpha_eq_f_beta = False
            
        def deg_minpoly(expr, v):
            """
            Returns the degree of the minimal polynomial of expr over F.
            If expr is transcendental over F (contains v), its minimal polynomial is 0 (degree 0).
            If expr is in F (constant w.r.t v), its minimal polynomial is X - expr (degree 1).
            """
            if expr.has(v):
                return 0
            else:
                return 1
                
        try:
            deg_a = deg_minpoly(alpha, var)
            deg_b = deg_minpoly(beta, var)
            deg_eq = (deg_a == deg_b)
        except Exception:
            deg_eq = False
            
        try:
            conclusion = (f_alpha_eq_f_beta == deg_eq)
            neg_q = not conclusion
        except Exception:
            neg_q = False
            
        return [h1, h2, neg_q]
    except Exception:
        return [False, False, False]

