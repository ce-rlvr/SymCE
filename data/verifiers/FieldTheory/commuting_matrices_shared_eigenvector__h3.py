def conditions(witness):
    """
    Given a witness, checks whether it is a valid counterexample to the false conjecture.
    The witness is expected to be a tuple (A, B, n) where A and B are matrices and n is the dimension of V.
    If n is omitted, it defaults to the row dimension of A.
    """
    try:
        if isinstance(witness, tuple):
            if len(witness) == 3:
                A, B, n = witness
            elif len(witness) == 2:
                A, B = witness
                n = A.shape[0] if hasattr(A, 'shape') else 1
            else:
                return [False, False, False, False]
        else:
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]

    # H_1: K is an algebraically closed field
    # We assume K is the algebraic closure of the field generated by the entries of A and B.
    # This is satisfied as long as A and B are valid matrices.
    try:
        h1 = hasattr(A, 'shape') and hasattr(B, 'shape')
    except Exception:
        h1 = False

    # H_2: V is a vector space over K of finite dimension n >= 1
    try:
        h2 = isinstance(n, int) and n >= 1
    except Exception:
        h2 = False

    # H_3: A and B commute, meaning AB = BA
    try:
        h3 = bool(A * B == B * A)
    except Exception:
        h3 = False

    # ¬Q: There does NOT exist a non-zero vector v in V that is an eigenvector for both A and B
    try:
        if not h1 or not h2:
            neg_q = False
        elif A.shape[0] != n or B.shape[0] != n or A.shape[1] != n or B.shape[1] != n:
            # If the matrices do not act on V (i.e., their dimensions don't match n),
            # they cannot have an eigenvector in V.
            neg_q = True
        else:
            # Mathematically, any two commuting n x n matrices over an algebraically closed field
            # ALWAYS share at least one eigenvector. There are no exceptions.
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

