import sympy
import math

# Top-level setup
# No specific named objects needed for FieldTheory Primitive Element Theorem.
# The witness will provide its own symbols and polynomials.
# Expected witness format: (polys, vars, base_vars, char)
# where:
#   - polys: list of sympy expressions (minimal polynomials of the generators)
#   - vars: list of sympy symbols (generators of L over K)
#   - base_vars: list of sympy symbols (generators of K over its prime field)
#   - char: integer (characteristic of the field, 0 or prime)

def conditions(witness):
    try:
        if len(witness) != 4:
            return [False, False, False]
        polys, vars, base_vars, char = witness
    except Exception:
        return [False, False, False]
    
    # H1: The extension L/K is finite
    try:
        h1 = True
        if len(polys) != len(vars):
            h1 = False
        else:
            for i, v in enumerate(vars):
                p = polys[i]
                if not p.has(v):
                    h1 = False
                elif sympy.degree(p, v) < 1:
                    h1 = False
    except Exception:
        h1 = False

    # H2: The extension L/K is separable
    try:
        h2 = True
        for i, v in enumerate(vars):
            p = polys[i]
            dp = p.diff(v)
            if char > 0:
                dp_poly = sympy.Poly(dp, *(list(vars) + list(base_vars)))
                is_zero_mod = True
                for coeff in dp_poly.coeffs():
                    try:
                        num = sympy.fraction(coeff)[0]
                        if num % char != 0:
                            is_zero_mod = False
                            break
                    except Exception:
                        is_zero_mod = False
                        break
                if is_zero_mod:
                    h2 = False
            else:
                if dp.is_zero:
                    h2 = False
    except Exception:
        h2 = False

    # neg_Q: L/K is NOT simple
    try:
        neg_q = False
        if len(vars) <= 1:
            neg_q = False
        elif char > 0:
            # Find the purely inseparable generators over K
            q_list = []
            for i, v in enumerate(vars):
                p = polys[i]
                d = sympy.degree(p, v)
                if d > 1:
                    temp = d
                    while temp % char == 0 and temp > 1:
                        temp //= char
                    if temp == 1:
                        # Check if it's of the form v**q - c where c is in K
                        rest = p - sympy.LC(p, v) * v**d
                        if not any(rest.has(u) for u in vars):
                            q_list.append(d)
            
            # If the purely inseparable part is generated by multiple independent elements
            # such that their combined degree exceeds the maximum degree of any single element,
            # then the purely inseparable part is not simple, hence L/K is not simple.
            if len(q_list) > 0:
                max_q = max(q_list)
                insep_deg = math.prod(q_list)
                if insep_deg > max_q:
                    neg_q = True
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

