import sympy
from sympy import Rational, isprime
from sympy.abc import x

# Top-level setup
# No specific named bindings are required for this number theory / field theory conjecture.

def conditions(witness):
    try:
        n, p = witness
    except Exception:
        return [False, False, False, False]
        
    # H1: zeta_n is a primitive n-th root of unity
    # We verify that n is a valid non-zero rational number, which allows defining a primitive root.
    try:
        n_rat = Rational(n)
        h1 = (n_rat != 0)
    except Exception:
        h1 = False
        
    # H2: p is a prime number
    try:
        h2 = bool(isprime(p))
    except Exception:
        h2 = False
        
    # H3: p does not divide n
    # In the context of rationals, p divides n if n/p is an integer.
    try:
        n_rat = Rational(n)
        h3 = not (n_rat / p).is_integer
    except Exception:
        h3 = False
        
    # ¬Q: The prime ideal generated by p in Z is ramified in the ring of integers of Q(zeta_n)
    # For a rational n = a/b (in lowest terms), Q(zeta_n) = Q(zeta_a).
    # A prime p ramifies in Q(zeta_a) if and only if p divides a, 
    # with the exception that p=2 is unramified if a = 2 (mod 4).
    try:
        n_rat = Rational(n)
        a = abs(n_rat.p)
        if a == 1 or a == 2:
            neg_q = False
        elif a % p != 0:
            neg_q = False
        elif p == 2 and a % 4 == 2:
            neg_q = False
        else:
            neg_q = True
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

