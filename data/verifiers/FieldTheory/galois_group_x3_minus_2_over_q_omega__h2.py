def conditions(witness) -> list[bool]:
    try:
        if witness == QQ or witness == S.Rationals or witness == "Q" or witness == "QQ":
            gens = []
        elif hasattr(witness, 'gens'):
            try:
                gens = list(witness.gens)
            except TypeError:
                gens = [witness]
        elif isinstance(witness, str):
            gens = [sympy.Symbol('invalid')]
        elif hasattr(witness, '__iter__'):
            gens = list(witness)
        else:
            gens = [witness]
    except Exception:
        gens = [sympy.Symbol('invalid')]

    # H_1: omega is a primitive cube root of unity in C
    h1_ok = True

    # H_2: L is the splitting field of x^3 - 2 over K
    # We verify that the witness represents a valid algebraic extension of Q
    h2_ok = True
    try:
        from sympy import minpoly
        for g in gens:
            if not g.is_rational:
                minpoly(g, x)
    except Exception:
        h2_ok = False

    # ¬Q: The Galois group Gal(L/K) is not isomorphic to Z/3Z
    # For the splitting field L of x^3 - 2 over K, Gal(L/K) is Z/3Z iff [L : K] == 3
    neg_q = False
    try:
        if h2_ok:
            from sympy import sympify, minpoly, Poly
            from sympy.polys.numberfields import primitive_element
            
            def get_degree(generators):
                gs = [sympify(g) for g in generators]
                gs = [g for g in gs if not g.is_rational]
                unique_gs = []
                for g in gs:
                    if g not in unique_gs:
                        unique_gs.append(g)
                gs = unique_gs
                
                if not gs:
                    return 1
                if len(gs) == 1:
                    p = minpoly(gs[0], x)
                    return Poly(p, x).degree()
                
                p = primitive_element(gs, x)
                if isinstance(p, tuple):
                    p = p[0]
                return Poly(p, x).degree()

            d_K = get_degree(gens)
            
            # L is generated over K by the roots of x^3 - 2, which are generated by 2^(1/3) and I*sqrt(3)
            L_gens = gens + [2**(S(1)/3), I*sqrt(3)]
            d_L = get_degree(L_gens)
            
            if d_K is not None and d_L is not None:
                # neg_q is True when the conclusion FAILS (i.e., [L : K] != 3)
                neg_q = (d_L != 3 * d_K)
    except Exception:
        neg_q = False

    return [h1_ok, h2_ok, neg_q]

