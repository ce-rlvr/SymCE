def parse_poly(p, var):
    """Helper to parse the witness into a SymPy Poly over QQ."""
    if isinstance(p, (list, tuple)):
        return sp.Poly(p, var, domain='QQ')
    p = sp.sympify(p)
    if isinstance(p, sp.Poly):
        return sp.Poly(p.as_expr(), var, domain='QQ')
    if hasattr(p, 'free_symbols') and p.free_symbols:
        if len(p.free_symbols) > 1:
            raise ValueError("Polynomial must be univariate")
        old_var = list(p.free_symbols)[0]
        p = p.subs(old_var, var)
        return sp.Poly(p, var, domain='QQ')
    return sp.Poly(p, var, domain='QQ')

def conditions(witness):
    try:
        # The witness is expected to be a tuple of two polynomials defining K and L over F=Q.
        # If a single polynomial is provided, we assume K = L.
        if isinstance(witness, (tuple, list)):
            if len(witness) == 2:
                poly_K_raw, poly_L_raw = witness
            elif len(witness) == 3:
                _, poly_K_raw, poly_L_raw = witness
            else:
                return [False] * 5
        else:
            poly_K_raw = witness
            poly_L_raw = witness
            
        var = sp.Symbol('x')
        poly_K = parse_poly(poly_K_raw, var)
        poly_L = parse_poly(poly_L_raw, var)
    except Exception:
        return [False] * 5
        
    # H_1: F is a field (We implicitly work over F = Q, which is a field)
    h1 = True
    
    # H_2: K and L are finite field extensions of F
    try:
        h2 = bool(poly_K.degree() >= 1 and poly_L.degree() >= 1 and 
                  poly_K.is_irreducible and poly_L.is_irreducible)
    except Exception:
        h2 = False
        
    # H_3: K/F is a Galois extension
    # An irreducible polynomial over Q is Galois iff it splits completely in the field generated by any of its roots.
    try:
        root_K = sp.RootOf(poly_K, 0)
        factors_K = sp.factor_list(poly_K, extension=root_K)[1]
        h3 = bool(all(f[0].degree() == 1 for f in factors_K))
    except Exception:
        h3 = False
        
    # H_4: L/F is a Galois extension
    try:
        root_L = sp.RootOf(poly_L, 0)
        factors_L = sp.factor_list(poly_L, extension=root_L)[1]
        h4 = bool(all(f[0].degree() == 1 for f in factors_L))
    except Exception:
        h4 = False
        
    # ¬Q: The compositum field KL is not a Galois extension of F
    # Without the assumption that K and L are subfields of a common field, their compositum
    # is constructed via the tensor product K (x)_F L. This tensor product is a field iff 
    # poly_K remains irreducible over L. If it factors, the tensor product is not a field, 
    # hence the compositum is not a field and cannot be a Galois extension.
    try:
        root_L = sp.RootOf(poly_L, 0)
        factors_KL = sp.factor_list(poly_K, extension=root_L)[1]
        neg_q = bool(len(factors_KL) > 1)
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, h4, neg_q]