import sympy
from sympy import Symbol, factor_list

x = Symbol('x')

def conditions(witness) -> list[bool]:
    """
    Checks whether the given witness is a counterexample to the conjecture.
    The witness is expected to be a tuple (p, q).
    """
    try:
        if len(witness) >= 2:
            p = witness[0]
            q = witness[1]
        else:
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]
        
    # H_1: p is an odd prime number
    try:
        p_int = int(p)
        h1 = bool(sympy.isprime(p_int) and p_int % 2 != 0)
    except Exception:
        h1 = False
        
    # H_2: q is a prime number
    try:
        q_int = int(q)
        h2 = bool(sympy.isprime(q_int))
    except Exception:
        h2 = False
        
    # H_3: ζ_p is a primitive p-th root of unity
    # This is a contextual mathematical setup; we verify that p is valid.
    try:
        p_int = int(p)
        h3 = bool(p_int > 0)
    except Exception:
        h3 = False
        
    # ¬Q: The conclusion fails
    # Conclusion: The ideal (q) splits completely into p-1 distinct prime ideals iff q ≡ 1 (mod p).
    # By Dedekind's criterion, since Z[ζ_p] is the ring of integers, the splitting of (q) 
    # corresponds to the factorization of the p-th cyclotomic polynomial modulo q.
    try:
        p_int = int(p)
        q_int = int(q)
        
        # phi_p(x) = x^{p-1} + x^{p-2} + ... + 1
        phi_p = sum(x**i for i in range(p_int))
        
        # Factor phi_p modulo q
        factors = factor_list(phi_p, modulus=q_int)
        
        # Number of distinct prime ideals is the number of distinct irreducible factors
        num_distinct_factors = len(factors[1])
        
        lhs = (num_distinct_factors == p_int - 1)
        rhs = (q_int % p_int == 1)
        
        # The conclusion is the biconditional (lhs == rhs). We want its negation.
        neg_q = not (lhs == rhs)
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

