import sympy
from sympy import Symbol, cyclotomic_poly, discriminant

# Top-level setup
# No special named objects needed for this domain.

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, dict):
            n = witness.get('n')
            p = witness.get('p')
        elif isinstance(witness, (list, tuple)):
            if len(witness) == 2:
                n, p = witness
            elif len(witness) == 3:
                n, _, p = witness
            else:
                return [False, False, False, False]
        else:
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]

    # H_1: n is a positive integer
    try:
        h1 = isinstance(n, (int, sympy.Integer)) and n > 0
    except Exception:
        h1 = False

    # H_2: zeta_n is a primitive n-th root of unity
    try:
        # This is a definitional hypothesis establishing notation for the field Q(zeta_n).
        # It is structurally satisfied by the context of the problem.
        h2 = True
    except Exception:
        h2 = False

    # H_3: p is a prime number
    try:
        h3 = isinstance(p, (int, sympy.Integer)) and sympy.isprime(p)
    except Exception:
        h3 = False

    # neg_Q: The prime ideal generated by p in Z is RAMIFIED in the ring of integers of Q(zeta_n)
    try:
        if not (h1 and h3):
            neg_q = False
        else:
            # The ring of integers of Q(zeta_n) is Z[zeta_n].
            # A prime p ramifies in Q(zeta_n) if and only if it divides the discriminant of the field.
            # The field discriminant is exactly the discriminant of the n-th cyclotomic polynomial.
            x = Symbol('x')
            poly = cyclotomic_poly(n, x)
            disc = discriminant(poly, x)
            neg_q = (int(disc) % p == 0)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

