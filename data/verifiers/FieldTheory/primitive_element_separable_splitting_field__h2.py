def conditions(witness) -> list[bool]:
    # Extract F, f, E from the witness
    F = f = E = None
    try:
        if isinstance(witness, dict):
            F = witness.get('F')
            f = witness.get('f')
            E = witness.get('E')
        elif isinstance(witness, tuple) and len(witness) == 3:
            F, f, E = witness
        else:
            F = witness.F
            f = witness.f
            E = witness.E
    except Exception:
        return [False, False, False, False]

    # H_1: F is a field
    try:
        h1 = False
        if hasattr(F, 'is_Field'):
            h1 = F.is_Field
        elif hasattr(F, 'is_field'):
            h1 = F.is_field
        elif F in [QQ, sympy.RR, sympy.CC]:
            h1 = True
        elif isinstance(F, sympy.polys.domains.finitefield.FiniteField):
            h1 = True
    except Exception:
        h1 = False

    # H_2: All roots of f(x) in its splitting field are simple roots (f is separable)
    try:
        h2 = False
        if isinstance(f, Poly):
            h2 = f.is_squarefree
        elif hasattr(f, 'is_squarefree'):
            h2 = f.is_squarefree
        else:
            p = Poly(f)
            h2 = p.is_squarefree
    except Exception:
        h2 = False

    # H_3: E is the splitting field of f(x) over F
    try:
        h3 = False
        if hasattr(E, 'is_splitting_field'):
            h3 = E.is_splitting_field(f, F)
        elif hasattr(E, 'ring') and hasattr(E, 'base_ideal'):
            # If E is a QuotientRing (e.g., a splitting ring that is not a field)
            gens = E.ring.gens
            h3 = True
            p = Poly(f)
            for g in gens:
                val = p.eval(g)
                if E(val) != E.zero:
                    h3 = False
                    break
        else:
            # Fallback for custom or unknown representations
            h3 = True
    except Exception:
        h3 = False

    # ¬Q: E is not generated by a single element over F
    try:
        neg_q = False
        if isinstance(E, AlgebraicField):
            # Algebraic fields in sympy are always simple extensions
            neg_q = False
        elif hasattr(E, 'is_simple_extension'):
            neg_q = not E.is_simple_extension(F)
        elif hasattr(E, 'ring') and hasattr(E, 'base_ideal'):
            # A quotient ring like F_2[x, y]/(x^2+x, y^2+y) is not simple if it has >1 generators
            # and relations that prevent a single element from generating the whole algebra.
            neg_q = len(E.ring.gens) > 1
        elif isinstance(E, list):
            # E.g., a matrix algebra representation
            neg_q = len(E) > 2
        else:
            # Fallback for custom counterexamples
            neg_q = True
    except Exception:
        neg_q = False

    return [bool(h1), bool(h2), bool(h3), bool(neg_q)]

