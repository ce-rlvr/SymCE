import sympy

# Top-level setup
# (No special objects needed for this domain; we use integers directly)

def conditions(witness) -> list[bool]:
    h1, h2, h3, neg_q = False, False, False, False
    try:
        if isinstance(witness, dict):
            n = witness.get('n')
            p = witness.get('p')
        else:
            if len(witness) == 2:
                n, p = witness
            elif len(witness) == 3:
                n, _, p = witness
            else:
                n, p = witness[0], witness[1]
    except Exception:
        return [False, False, False, False]

    # H1: n is a positive integer
    try:
        h1 = isinstance(n, (int, sympy.Integer)) and n >= 1
    except Exception:
        pass

    # H2: \zeta_n is a primitive n-th root of unity
    # This is a definitional hypothesis. If n is a positive integer, such a root exists.
    try:
        h2 = bool(h1)
    except Exception:
        pass

    # H3: p does not divide n
    try:
        if isinstance(p, (int, sympy.Integer)) and p != 0:
            h3 = (n % p != 0)
    except Exception:
        pass

    # neg_Q: The prime ideal generated by p in Z is unramified in the ring of integers of Q(\zeta_n)
    # The conclusion fails if p does not generate a prime ideal (i.e., |p| is not prime),
    # or if |p| is prime but ramifies in Q(\zeta_n).
    try:
        if isinstance(p, (int, sympy.Integer)):
            p_val = int(abs(p))
            n_val = int(n)
            if not sympy.isprime(p_val):
                q_holds = False
            else:
                # A prime ramifies in Q(\zeta_n) iff it divides n, with the exception 
                # that 2 does not ramify if n = 2 * (odd integer).
                if n_val % 4 == 2:
                    ramifying = sympy.primefactors(n_val // 2)
                else:
                    ramifying = sympy.primefactors(n_val)
                q_holds = p_val not in ramifying
            neg_q = not q_holds
    except Exception:
        pass

    return [h1, h2, h3, neg_q]

