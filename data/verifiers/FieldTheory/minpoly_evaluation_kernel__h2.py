def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "The kernel of the evaluation homomorphism is the principal ideal <m(x)>, 
    where m(x) is the minimal polynomial of alpha over F."
    (The dropped hypothesis is that alpha must be algebraic over F).
    """
    # Extract alpha if witness is provided as a tuple (F, E, alpha)
    try:
        if isinstance(witness, tuple):
            alpha = witness[-1]
        else:
            alpha = witness
            
        # H_1: F is a field and E is an extension field of F
        # We verify that alpha is a valid scalar mathematical object (not a matrix, set, etc.)
        if isinstance(alpha, Expr):
            h1_ok = not getattr(alpha, 'is_Matrix', False)
        elif isinstance(alpha, (int, float, complex)):
            h1_ok = True
        else:
            h1_ok = False
    except Exception:
        h1_ok = False

    # H_2: phi is the evaluation homomorphism defined by phi(g(x)) = g(alpha)
    # This is a definitional setup that holds for any valid alpha.
    h2_ok = True

    # ¬Q: The conclusion fails.
    # The conclusion states the kernel is generated by the minimal polynomial m(x).
    # If alpha is transcendental (not algebraic), the minimal polynomial does not exist,
    # hence the kernel (which is just {0}) cannot be described as <m(x)> where m(x) is the minpoly.
    try:
        if isinstance(witness, tuple):
            alpha = witness[-1]
        else:
            alpha = witness
            
        # Attempt to compute the minimal polynomial over the rationals.
        # If alpha is algebraic, this succeeds and the conclusion holds (neg_q_ok = False).
        # If alpha is transcendental, this raises an exception (e.g., NotAlgebraic), 
        # meaning the conclusion fails (neg_q_ok = True).
        _ = sympy.minpoly(alpha)
        neg_q_ok = False
    except Exception:
        neg_q_ok = True

    return [h1_ok, h2_ok, neg_q_ok]

