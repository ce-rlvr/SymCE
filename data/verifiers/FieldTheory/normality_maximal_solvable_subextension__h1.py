def conditions(witness) -> list[bool]:
    """
    Given a witness (G, H, V) representing:
      - G: Galois group of the normal closure of L/K
      - H: Subgroup of G corresponding to the field L
      - V: Subgroup of G corresponding to an intermediate field E (H <= V <= G)
    
    Checks if the conclusion fails. The conclusion states that the unique maximal 
    solvable Galois intermediate field M contains all other solvable intermediate fields.
    """
    try:
        if not isinstance(witness, (list, tuple)) or len(witness) != 3:
            return [False]
            
        G, H, V = witness
        
        if not hasattr(G, 'is_group') or not G.is_group: return [False]
        if not hasattr(H, 'is_group') or not H.is_group: return [False]
        if not hasattr(V, 'is_group') or not V.is_group: return [False]
        if not hasattr(G, 'degree'): return [False]
        
        degree = G.degree
        
        # Helper to ensure all subgroups operate on the same degree as G
        def resize_group(grp):
            new_gens = []
            for g in grp.generators:
                if g.size != degree:
                    if g.size > degree:
                        # Ensure it doesn't move points outside the G's domain
                        if any(g(i) != i for i in range(degree, g.size)):
                            raise ValueError("Generator moves points beyond G.degree")
                        new_gens.append(Permutation(g.array_form[:degree]))
                    else:
                        new_gens.append(Permutation(g, size=degree))
                else:
                    new_gens.append(g)
            if not new_gens:
                new_gens = [Permutation(size=degree)]
            return PermutationGroup(new_gens)
            
        H = resize_group(H)
        V = resize_group(V)
        
        def is_subgroup(sub, supergroup):
            for g in sub.generators:
                if g not in supergroup:
                    return False
            return True
            
        # V must be an intermediate field (H <= V <= G)
        if not is_subgroup(H, V): return [False]
        if not is_subgroup(V, G): return [False]
        
        # Compute R = solvable residual of G (smallest normal subgroup with solvable quotient)
        series = G.derived_series()
        R = series[-1]
        
        # Compute N = normal closure of H in G
        N_gens = []
        for g in G.generate():
            for h in H.generators:
                N_gens.append(g * h * (~g))
        N = PermutationGroup(N_gens) if N_gens else PermutationGroup([Permutation(size=degree)])
        
        # U_min corresponds to the unique maximal solvable Galois intermediate field M.
        # It is the minimal normal subgroup containing H such that G/U_min is solvable.
        # Thus, U_min is generated by N (normal closure of H) and R (solvable residual).
        U_min_gens = list(N.generators) + list(R.generators)
        U_min = PermutationGroup(U_min_gens) if U_min_gens else PermutationGroup([Permutation(size=degree)])
        
        # Compute C = Core_G(V), which corresponds to the Galois closure of E/K
        core_elements = []
        for v in V.generate():
            in_core = True
            for g in G.generate():
                if (~g) * v * g not in V:
                    in_core = False
                    break
            if in_core:
                core_elements.append(v)
        C = PermutationGroup(core_elements) if core_elements else PermutationGroup([Permutation(size=degree)])
        
        # Check if E/K is solvable (which means G/C is a solvable group, i.e., R <= C)
        is_V_solvable_over_K = is_subgroup(R, C)
        
        if not is_V_solvable_over_K:
            return [False]
            
        # Check if M contains E (which means U_min <= V by Galois correspondence)
        M_contains_E = is_subgroup(U_min, V)
        
        # The conclusion fails if M does NOT contain the solvable intermediate field E
        neg_Q = not M_contains_E
        
        return [neg_Q]
    except Exception:
        return [False]

