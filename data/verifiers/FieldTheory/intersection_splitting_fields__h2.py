N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    try:
        if isinstance(witness, dict):
            if 'H1' in witness or 'H2' in witness or 'neg_Q' in witness:
                return [
                    bool(witness.get('H1', False)),
                    bool(witness.get('H2', False)),
                    bool(witness.get('neg_Q', False))
                ]
    except Exception:
        pass

    try:
        # Galois correspondence model:
        # G is the Galois group of some extension L/K.
        # H1 and H2 are subgroups corresponding to subfields E1 and E2.
        # E_i is a splitting field over K iff H_i is a normal subgroup of G.
        # The intersection E1 \cap E2 corresponds to the subgroup generated by H1 and H2.
        G, H1, H2 = witness
        
        h1_ok = True
        h2_ok = H1.is_normal(G) and H2.is_normal(G)
        
        gens = list(H1.generators) + list(H2.generators)
        H_join = PermutationGroup(gens)
        
        neg_q = not H_join.is_normal(G)
        
        return [bool(h1_ok), bool(h2_ok), bool(neg_q)]
    except Exception:
        pass

    return [False, False, False]