import sympy
from sympy import Poly, roots, degree
from sympy.polys import primitive_element
from sympy.abc import x

# Top-level setup
# The witness is expected to be a polynomial expression in one variable (e.g., x).
# We import x from sympy.abc to provide a default variable.

CONDITION_LABELS = [
    "H_1: F is a field of characteristic 0",
    "H_2: E is the splitting field of f(x) over F",
    "H_3: Gal(E/F) is a solvable group",
    "¬Q: There exist two distinct roots of f(x) that do not generate E"
]

N_HYP = 3
NEG_Q_INDEX = 3

def conditions(witness):
    # Determine the variable used in the witness polynomial
    try:
        free_syms = witness.free_symbols
        if len(free_syms) == 1:
            var = list(free_syms)[0]
        else:
            var = x
    except Exception:
        var = x
        
    # H_1: F is a field of characteristic 0
    try:
        f_poly = Poly(witness, var)
        h1 = (f_poly.domain.char == 0)
    except Exception:
        h1 = False
        
    # H_2: E is the splitting field of f(x) over F
    # This is definitional for the setup, we just require the witness to be a valid non-constant polynomial.
    try:
        deg_f = degree(witness, var)
        h2 = (deg_f >= 1)
    except Exception:
        h2 = False
        
    # H_3: Gal(E/F) is a solvable group
    # A polynomial over Q has a solvable Galois group iff it is solvable by radicals.
    # SymPy's `roots` function finds exactly the roots expressible in radicals.
    try:
        rts_dict = roots(witness, var)
        deg_f = degree(witness, var)
        h3 = (sum(rts_dict.values()) == deg_f) and (deg_f > 0)
    except Exception:
        h3 = False
        
    # ¬Q: There exist two distinct roots of f(x) that do not generate E
    try:
        rts_dict = roots(witness, var)
        distinct_roots = list(rts_dict.keys())
        
        if len(distinct_roots) < 2:
            neg_q = False
        else:
            # Compute the degree of the entire splitting field E over Q
            E_minpoly, _ = primitive_element(distinct_roots, var)
            deg_E = degree(E_minpoly, var)
            
            neg_q = False
            # Check all pairs of distinct roots
            for i in range(len(distinct_roots)):
                for j in range(i + 1, len(distinct_roots)):
                    r_i = distinct_roots[i]
                    r_j = distinct_roots[j]
                    
                    # Compute the degree of the subfield generated by r_i and r_j
                    sub_minpoly, _ = primitive_element([r_i, r_j], var)
                    deg_sub = degree(sub_minpoly, var)
                    
                    # If the subfield degree is strictly less than the splitting field degree,
                    # then these two roots do NOT generate the entire splitting field E.
                    if deg_sub < deg_E:
                        neg_q = True
                        break
                if neg_q:
                    break
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]