# Top-level setup
# A typical witness for this conjecture is a tuple (E, F) representing the field extension E/F.
# For example: witness = (QQ.frac_field(x, y), QQ)

def conditions(witness) -> list[bool]:
    try:
        E, F = witness
    except Exception:
        return [False, False, False]
        
    # H_1: E/F is a field extension
    try:
        # Check that both are fields and F is a subfield of E
        h1 = getattr(E, 'is_Field', False) and getattr(F, 'is_Field', False) and F.unify(E) == E
    except Exception:
        h1 = False
        
    # H_2: The extension E/F is separable
    try:
        # For our purposes, fields of characteristic 0 are perfect, 
        # so all their extensions are separable.
        h2 = (F.characteristic == 0)
    except Exception:
        h2 = False
        
    # ¬Q: E is not generated by a single element over F
    try:
        def get_tr_deg(K):
            if K.__class__.__name__ == 'FractionField':
                return len(K.gens)
            return 0
            
        tr_E = get_tr_deg(E)
        tr_F = get_tr_deg(F)
        
        # If the transcendence degree of E over F is >= 2, 
        # it cannot be generated by a single element over F.
        if tr_E - tr_F >= 2:
            neg_q = True
        else:
            neg_q = False
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

