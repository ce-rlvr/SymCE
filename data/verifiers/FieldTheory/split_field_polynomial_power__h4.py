def conditions(witness):
    """
    Checks the hypotheses and the negated conclusion for the conjecture:
    Hypotheses:
      - F is a field
      - f(x) is a polynomial in F[x]
      - m is an integer >= 1
    Conclusion:
      - K is the splitting field of (f(x))^m over F.
    """
    if isinstance(witness, dict):
        F = witness.get('F')
        f = witness.get('f')
        m = witness.get('m')
        K = witness.get('K')
    else:
        if len(witness) < 4:
            return [False, False, False, False]
        F, f, m, K = witness[:4]

    # H_1: F is a field
    try:
        h1 = hasattr(F, 'is_Field') and F.is_Field
    except Exception:
        h1 = False

    # H_2: f(x) is a polynomial in F[x]
    try:
        if isinstance(f, Poly):
            h2 = f.domain == F
        else:
            syms = getattr(f, 'free_symbols', set())
            if len(syms) > 1:
                h2 = False
            else:
                x_var = list(syms)[0] if syms else x
                poly_f = Poly(f, x_var, domain=F)
                h2 = True
    except Exception:
        h2 = False

    # H_3: m is an integer greater than or equal to 1
    try:
        h3 = (isinstance(m, int) or (hasattr(m, 'is_integer') and m.is_integer)) and m >= 1
    except Exception:
        h3 = False

    # neg_Q: K is NOT the splitting field of (f(x))^m over F
    try:
        if isinstance(f, Poly):
            P = f**m
            x_var = f.gen
        else:
            P = f**m
            syms = getattr(f, 'free_symbols', set())
            x_var = list(syms)[0] if syms else x

        is_split = True
        
        # 1. Check if P splits completely in K
        try:
            poly_K = Poly(P, x_var, domain=K)
            factors = poly_K.factor_list()[1]
            for factor, mult in factors:
                if factor.degree() != 1:
                    is_split = False
                    break
        except Exception:
            # If we cannot factor over K, it doesn't split completely or K is invalid
            is_split = False

        # 2. If it splits completely, check if K is minimal (generated by the roots)
        if is_split:
            if K == F:
                is_split = True
            elif hasattr(K, 'is_FiniteField') and K.is_FiniteField and hasattr(F, 'is_FiniteField') and F.is_FiniteField:
                poly_F = Poly(P, x_var, domain=F)
                factors_F = poly_F.factor_list()[1]
                d = 1
                for factor, mult in factors_F:
                    deg = factor.degree()
                    d = lcm(d, deg)
                expected_order = F.order ** d
                if K.order != expected_order:
                    is_split = False
            elif F == QQ and hasattr(K, 'ext'):
                from sympy import roots
                rts = roots(P, x_var)
                if sum(rts.values()) == Poly(P, x_var).degree():
                    alg_roots = [r for r in rts.keys() if r not in QQ]
                    if not alg_roots:
                        expected_deg = 1
                    else:
                        try:
                            expected_K = QQ.algebraic_field(*alg_roots)
                            expected_deg = expected_K.ext.degree()
                        except Exception:
                            expected_deg = None
                    if expected_deg is not None and K.ext.degree() != expected_deg:
                        is_split = False
            else:
                # If we cannot easily verify minimality, we assume it is the splitting field 
                # to avoid false positives for the negated conclusion.
                is_split = True

        neg_q = not is_split
    except Exception:
        # If evaluation fails, we cannot confirm it is a counterexample
        neg_q = False

    return [bool(h1), bool(h2), bool(h3), bool(neg_q)]


