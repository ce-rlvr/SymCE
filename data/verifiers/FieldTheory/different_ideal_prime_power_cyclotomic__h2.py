import sympy
from sympy import isprime

# Top-level setup
# (No specific named objects required for this number theory conjecture)

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, dict):
            p = witness.get('p')
            k = witness.get('k')
        else:
            p, k = witness
    except Exception:
        return [False, False, False]
        
    try:
        h1 = bool(isprime(p))
    except Exception:
        h1 = False
        
    try:
        # k must be a non-negative integer for p^k to be a valid cyclotomic field index
        h2 = isinstance(k, (int, sympy.Integer)) and k >= 0
    except Exception:
        h2 = False
        
    try:
        # The conclusion fails if k == 0.
        # For k = 0, the formula gives p^0 * zeta_1^{-1} / (zeta_1^{1/p} - 1),
        # which has a denominator of 1^{1/p} - 1. This is either 0 or undefined in Q,
        # so it cannot generate the different ideal of Q (which is the unit ideal).
        neg_q = (k == 0)
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

