import sympy
from sympy import Poly, Symbol, factor_list, RootOf, real_roots

# Top-level setup: named object bindings
x = Symbol('x')

def conditions(witness) -> list[bool]:
    """
    Check if the witness is a valid counterexample.
    The witness is expected to be a polynomial expression in x over Q,
    representing the minimal polynomial of an algebraic extension E = Q(alpha) over F = Q.
    """
    try:
        # H_1: E is an algebraic field extension of F
        expr = sympy.sympify(witness)
        P = Poly(expr, x, domain='QQ')
        # A valid algebraic extension of Q is defined by a non-constant irreducible polynomial
        h1 = P.degree() >= 1 and P.is_irreducible
    except Exception:
        h1 = False

    try:
        # ¬Q: The extension E/F is NOT a normal extension
        if not h1:
            neg_q = False
        else:
            deg = P.degree()
            if deg <= 1:
                # Degree 1 extensions are trivially normal
                neg_q = False
            else:
                # Count the number of real roots
                real_count = len(real_roots(P))
                
                # If the irreducible polynomial has both real and non-real roots,
                # the extension generated by a real root cannot contain the non-real roots.
                # Thus, it does not split completely and is not normal.
                if 0 < real_count < deg:
                    neg_q = True
                else:
                    # Fallback for totally real or totally complex extensions:
                    # Check if the polynomial splits completely into linear factors over Q(alpha)
                    r = RootOf(P, 0)
                    factors = factor_list(P, extension=r)[1]
                    # Since we are in characteristic 0, roots are distinct.
                    # It is normal iff it splits into exactly `deg` linear factors.
                    is_norm = (len(factors) == deg)
                    neg_q = not is_norm
    except Exception:
        neg_q = False

    return [bool(h1), bool(neg_q)]

