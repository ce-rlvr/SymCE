import sympy

# Top-level setup for witness expressions
x = sympy.Symbol('x')
y = sympy.Symbol('y')

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "Let K be a finite field extension of F. Then K is a normal extension of F."
    
    The witness is expected to be a polynomial over QQ (e.g., x**3 - 2) 
    that defines the finite field extension K = QQ[x]/(witness).
    """
    try:
        # Extract expression and variable
        if isinstance(witness, sympy.Poly):
            expr = witness.as_expr()
        else:
            expr = witness
            
        free_syms = expr.free_symbols
        if len(free_syms) != 1:
            h1 = False
            var = x
        else:
            var = list(free_syms)[0]
            P = sympy.Poly(expr, var, domain='QQ')
            # H_1: K is a finite field extension of F
            # This means the polynomial must be irreducible over QQ.
            h1 = P.degree() >= 1 and P.is_irreducible
    except Exception:
        h1 = False
        expr = witness
        var = x

    try:
        if not h1:
            neg_q = False
        else:
            # ¬Q: K is NOT a normal extension of F
            # A finite extension is normal iff the minimal polynomial splits completely.
            
            # Fast check: if the polynomial has both real and non-real roots, 
            # its splitting field cannot be generated by a single real root, 
            # so the extension QQ(alpha) for a real root alpha is not normal.
            roots = sympy.nroots(expr)
            n_real = sum(1 for r in roots if abs(sympy.im(r)) < 1e-9)
            
            if 0 < n_real < P.degree():
                neg_q = True
            else:
                # Rigorous check: factor the polynomial over the extension field QQ(alpha)
                var2 = y if var != y else x
                alpha = sympy.RootOf(expr, var, 0)
                factored = sympy.factor(expr.subs(var, var2), extension=alpha)
                
                if isinstance(factored, sympy.Mul):
                    factors = factored.args
                else:
                    factors = [factored]
                    
                is_normal = True
                for f in factors:
                    if f.has(var2):
                        # If any factor has degree > 1, it didn't split completely
                        if sympy.degree(f, var2) > 1:
                            is_normal = False
                            break
                neg_q = not is_normal
    except Exception:
        neg_q = False

    return [bool(h1), bool(neg_q)]

