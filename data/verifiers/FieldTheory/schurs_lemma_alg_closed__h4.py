def conditions(witness):
    """
    Checks if the given witness is a valid counterexample to the false conjecture.
    Expected witness format: a tuple (G_matrices, phi_matrix)
    where G_matrices is a list of sympy.Matrix representing the generators of the group G,
    and phi_matrix is a sympy.Matrix representing the linear map phi.
    """
    
    def check_H1():
        # K is an algebraically closed field
        # We implicitly assume K=C for valid sympy matrices.
        try:
            G_matrices, phi_matrix = witness
            if not isinstance(G_matrices, (list, tuple)): return False
            if not (hasattr(phi_matrix, 'shape') and hasattr(phi_matrix, 'det')): return False
            for M in G_matrices:
                if not (hasattr(M, 'shape') and hasattr(M, 'det')): return False
            return True
        except Exception:
            return False

    def check_H2():
        # G is a group
        # We check if G_matrices are invertible square matrices of the same size.
        try:
            G_matrices, phi_matrix = witness
            n = phi_matrix.shape[0]
            if n < 1: return False
            if phi_matrix.shape != (n, n): return False
            for M in G_matrices:
                if M.shape != (n, n): return False
                if M.det() == 0: return False
            return True
        except Exception:
            return False

    def check_H3():
        # V is a finite-dimensional irreducible representation of G over K
        # By Burnside's Theorem on matrix algebras, this is equivalent to the 
        # K-algebra generated by G_matrices having dimension n^2.
        try:
            G_matrices, phi_matrix = witness
            n = phi_matrix.shape[0]
            if n < 1: return False
            
            from sympy import eye, Matrix
            I = eye(n)
            span_vectors = [list(I)]
            current_level = [I]
            
            # If n=1, it's trivially irreducible
            if len(span_vectors) == n**2:
                return True
                
            while current_level:
                next_level = []
                for B in current_level:
                    for M in G_matrices:
                        new_M = B * M
                        new_vec = list(new_M)
                        
                        test_mat = Matrix(span_vectors + [new_vec])
                        if test_mat.rank() > len(span_vectors):
                            span_vectors.append(new_vec)
                            next_level.append(new_M)
                            if len(span_vectors) == n**2:
                                return True
                current_level = next_level
                
            return len(span_vectors) == n**2
        except Exception:
            return False

    def check_neg_Q():
        # phi is NOT a scalar multiple of the identity map
        try:
            G_matrices, phi_matrix = witness
            n = phi_matrix.shape[0]
            if n < 1: return False
            from sympy import eye
            I = eye(n)
            c = phi_matrix[0, 0]
            return bool(phi_matrix != c * I)
        except Exception:
            return False

    return [check_H1(), check_H2(), check_H3(), check_neg_Q()]

