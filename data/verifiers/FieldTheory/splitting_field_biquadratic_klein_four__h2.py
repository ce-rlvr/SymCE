import sympy
from sympy import sympify, sqrt, minpoly, Poly
from sympy.abc import x, y

# Top-level setup
# (No specific named objects required for the witness, which is expected to be a tuple of two expressions)

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness is expected to be a tuple (a, b) or (F, a, b).
    We evaluate the conditions assuming F is the field of rational numbers (QQ).
    """
    try:
        if len(witness) == 3:
            F_val, a, b = witness
        elif len(witness) == 2:
            a, b = witness
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]
        
    try:
        a = sympify(a)
        b = sympify(b)
    except Exception:
        return [False, False, False]
        
    # H_1: Let F be a field of characteristic not equal to 2
    # Since we evaluate over F = QQ, this is always True.
    h1 = True
    
    # H_2: Assume that none of a, b, or ab is a perfect square in F
    def is_sq_in_QQ(val):
        try:
            v = sympify(val)
            if not v.is_rational:
                return False
            if v < 0:
                return False
            return sqrt(v).is_rational
        except Exception:
            return False
            
    try:
        h2 = not is_sq_in_QQ(a) and not is_sq_in_QQ(b) and not is_sq_in_QQ(a * b)
    except Exception:
        h2 = False
        
    # neg_Q: The splitting field of (x^2 - a)(x^2 - b) over F does NOT have degree 4, 
    # OR its Galois group is NOT isomorphic to the Klein four-group.
    try:
        max_deg = 0
        best_mp = None
        # The splitting field over QQ is generated by sqrt(a) and sqrt(b).
        # We find the degree of the extension by computing the minimal polynomial 
        # of a primitive element candidate: sqrt(a) + c * sqrt(b).
        for c in [1, 2, 3, 4]:
            try:
                mp = minpoly(sqrt(a) + c * sqrt(b), x)
                deg = mp.degree()
                if deg > max_deg:
                    max_deg = deg
                    best_mp = mp
                # If degree > 4, we already know the conclusion fails.
                if max_deg > 4:
                    break
            except Exception:
                pass
                
        if max_deg == 0:
            neg_q = False
        elif max_deg != 4:
            neg_q = True
        else:
            # If the degree is 4, we check if the Galois group is V4.
            # For an irreducible quartic over QQ, the Galois group is V4 iff 
            # its resolvent cubic splits completely into linear factors over QQ.
            coeffs = best_mp.all_coeffs()
            coeffs = [c_val / coeffs[0] for c_val in coeffs]
            c3, c2, c1, c0 = coeffs[1], coeffs[2], coeffs[3], coeffs[4]
            
            # Coefficients of the resolvent cubic
            r2 = -c2
            r1 = c1 * c3 - 4 * c0
            r0 = -(c1**2 + c0 * c3**2 - 4 * c0 * c2)
            
            res_cubic = Poly(y**3 + r2 * y**2 + r1 * y + r0, y, domain='QQ')
            factors = res_cubic.factor_list()
            
            # Check if all factors are linear and their multiplicities sum to 3
            is_V4 = all(f.degree() == 1 for f, mult in factors[1]) and sum(mult for f, mult in factors[1]) == 3
            neg_q = not is_V4
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

