import sympy
from sympy import Poly, sympify, factor, Mul
from sympy.abc import x
from sympy.polys.rootoftools import rootof
from sympy.polys.numberfields import primitive_element

# Top-level setup
QQ = sympy.QQ

def conditions(witness):
    # H1: f(x) is a polynomial in F[x]
    try:
        f = sympify(witness['f'])
        if f == 0:
            h1 = True
        else:
            p = Poly(f, x)
            h1 = all(c.is_Rational for c in p.all_coeffs())
    except Exception:
        h1 = False

    # H2: E is a splitting field of f(x) over F
    try:
        if f == 0:
            h2 = True
        else:
            f_poly = Poly(f, x, domain='QQ')
            E_poly = Poly(witness['E_minpoly'], x, domain='QQ')
            
            if not E_poly.is_irreducible:
                h2 = False
            else:
                # 1. f must split completely in E
                alpha = rootof(E_poly, 0)
                factored = factor(f_poly.as_expr(), extension=alpha)
                
                if isinstance(factored, Mul):
                    factors = factored.args
                else:
                    factors = [factored]
                    
                splits = True
                for fac in factors:
                    if fac.has(x):
                        p_fac = Poly(fac, x)
                        if p_fac.degree() != 1:
                            splits = False
                            break
                            
                if not splits:
                    h2 = False
                else:
                    # 2. E must be generated by the roots of f
                    if f_poly.degree() <= 4:
                        rts = [rootof(f_poly, i) for i in range(f_poly.degree())]
                        pe = primitive_element(rts, x)
                        pe_poly = Poly(pe, x)
                        if E_poly.degree() != pe_poly.degree():
                            h2 = False
                        else:
                            h2 = True
                    else:
                        h2 = False
    except Exception:
        h2 = False

    # H3: K is an extension field of F
    try:
        K_poly = Poly(witness['K_minpoly'], x, domain='QQ')
        h3 = K_poly.is_irreducible and all(c.is_Rational for c in K_poly.all_coeffs())
    except Exception:
        h3 = False

    # H4: f(x) splits completely into linear factors in K[x]
    try:
        if f == 0:
            h4 = True
        else:
            f_poly = Poly(f, x, domain='QQ')
            K_poly = Poly(witness['K_minpoly'], x, domain='QQ')
            
            alpha = rootof(K_poly, 0)
            factored = factor(f_poly.as_expr(), extension=alpha)
            
            if isinstance(factored, Mul):
                factors = factored.args
            else:
                factors = [factored]
                
            splits = True
            for fac in factors:
                if fac.has(x):
                    p_fac = Poly(fac, x)
                    if p_fac.degree() != 1:
                        splits = False
                        break
            h4 = splits
    except Exception:
        h4 = False

    # neg_Q: There does NOT exist an F-homomorphism from E into K
    try:
        E_poly = Poly(witness['E_minpoly'], x, domain='QQ')
        K_poly = Poly(witness['K_minpoly'], x, domain='QQ')
        
        # An F-homomorphism exists iff E_poly has a root in K
        alpha = rootof(K_poly, 0)
        factored = factor(E_poly.as_expr(), extension=alpha)
        
        if isinstance(factored, Mul):
            factors = factored.args
        else:
            factors = [factored]
            
        has_root = False
        for fac in factors:
            if fac.has(x):
                p_fac = Poly(fac, x)
                if p_fac.degree() == 1:
                    has_root = True
                    break
        neg_q = not has_root
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]

