def conditions(witness) -> list[bool]:
    """
    Given a witness (G, H_K, H_L), checks the hypotheses and negated conclusion.
    G represents Gal(N/F) for some common normal extension N.
    H_K and H_L represent Gal(N/K) and Gal(N/L).
    """
    try:
        if not isinstance(witness, (list, tuple)) or len(witness) != 3:
            return [False, False, False, False]
            
        G, H_K_gens, H_L_gens = witness
        
        if not isinstance(G, PermutationGroup):
            return [False, False, False, False]
            
        def parse_subgroup(gens, group):
            if isinstance(gens, PermutationGroup):
                return gens
            if not gens:
                id_perm = Permutation(group.degree - 1) if group.degree > 0 else Permutation()
                return PermutationGroup([id_perm])
            return PermutationGroup(gens)
            
        H_K = parse_subgroup(H_K_gens, G)
        H_L = parse_subgroup(H_L_gens, G)
        
        # Prevent timeouts for excessively large groups
        if G.order() > 2000:
            return [False, False, False, False]
            
        # Ensure H_K and H_L are actually subgroups of G
        for g in H_K.generators:
            if not G.contains(g):
                return [False, False, False, False]
        for g in H_L.generators:
            if not G.contains(g):
                return [False, False, False, False]
                
        def is_normal(group, subgroup):
            if subgroup.order() == 1:
                return True
            for h in subgroup.generators:
                for g in group.generators:
                    conj = g * h * ~g
                    if not subgroup.contains(conj):
                        return False
            return True
            
        # H_1: K and L are finite Galois extensions of F
        # By Galois theory, this is true iff H_K and H_L are normal subgroups of G.
        h1 = is_normal(G, H_K) and is_normal(G, H_L)
        
        # H_2: K and L are contained in a common extension field
        # Trivially true in this representation, as both are subfields of N.
        h2 = True
        
        # H_3: The intersection K \cap L is equal to F
        # K \cap L corresponds to the subgroup generated by H_K and H_L.
        # So K \cap L = F iff <H_K, H_L> = G.
        H_KL_gens = list(H_K.generators) + list(H_L.generators)
        H_KL_subgroup = parse_subgroup(H_KL_gens, G)
        h3 = (H_KL_subgroup.order() == G.order())
        
        # ¬Q: Gal(KL/F) is NOT isomorphic to Gal(K/F) \times Gal(L/F)
        # Gal(KL/F) corresponds to G / (H_K \cap H_L).
        # Gal(K/F) corresponds to G / H_K, and Gal(L/F) to G / H_L.
        # The natural map is an injective homomorphism, so they are isomorphic iff their sizes are equal.
        elements_K = list(H_K.generate())
        int_elements = [g for g in elements_K if H_L.contains(g)]
        H_int_order = len(int_elements)
        
        size_A = G.order() // H_int_order
        size_B = (G.order() // H_K.order()) * (G.order() // H_L.order())
        
        neg_q = (size_A != size_B)
        
        return [bool(h1), bool(h2), bool(h3), bool(neg_q)]
        
    except Exception:
        return [False, False, False, False]

