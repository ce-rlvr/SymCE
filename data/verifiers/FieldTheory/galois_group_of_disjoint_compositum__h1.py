# Top-level setup: named object bindings that the witness expression may reference.
# We provide standard finite groups. The witness is expected to be a tuple (G, H_K, H_L)
# where G is a PermutationGroup representing Gal(N/F), and H_K, H_L are subgroups 
# representing Gal(N/K) and Gal(N/L) respectively.
