def get_bool_attr(obj, attr_names, default=False):
    """Helper to extract boolean properties from mock objects or dictionaries."""
    if isinstance(obj, dict):
        for name in attr_names:
            if name in obj:
                val = obj[name]
                try:
                    return bool(val()) if callable(val) else bool(val)
                except Exception:
                    pass
    else:
        for name in attr_names:
            if hasattr(obj, name):
                val = getattr(obj, name)
                try:
                    return bool(val()) if callable(val) else bool(val)
                except Exception:
                    pass
    return default

def conditions(witness) -> list[bool]:
    # H1: There exists a finite set of elements generating L over K
    h1_names = [
        'is_finitely_generated',
        'finitely_generated',
        'has_finite_generators',
        'finite_generators',
        'is_finite_set'
    ]
    
    # H2: Each element alpha_i is algebraic over K
    h2_names = [
        'are_generators_algebraic',
        'generators_algebraic',
        'is_algebraic',
        'are_elements_algebraic',
        'algebraic_elements',
        'elements_algebraic'
    ]
    
    # Q: The field extension L/K is finite
    q_names = [
        'is_finite_extension',
        'finite_extension',
        'is_finite',
        'is_finite_dimensional'
    ]
    
    try:
        h1 = get_bool_attr(witness, h1_names, default=False)
    except Exception:
        h1 = False
        
    try:
        h2 = get_bool_attr(witness, h2_names, default=False)
    except Exception:
        h2 = False
        
    try:
        q = get_bool_attr(witness, q_names, default=True)
    except Exception:
        q = True
        
    # Fallback for tuple representations like (K, L, alphas)
    if isinstance(witness, tuple) and len(witness) == 3:
        try:
            K, L, alphas = witness
            if isinstance(alphas, (list, tuple, set)):
                h1 = True
            
            if all(getattr(a, 'is_algebraic', False) for a in alphas):
                h2 = True
                
            if hasattr(L, 'degree'):
                deg = L.degree()
                if callable(deg):
                    deg = deg()
                q = deg < float('inf')
        except Exception:
            pass

    return [bool(h1), bool(h2), not bool(q)]