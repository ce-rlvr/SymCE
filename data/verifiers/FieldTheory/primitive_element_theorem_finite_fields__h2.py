def conditions(witness):
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            F_q, K = witness
        else:
            K = witness
            if hasattr(K, 'domain') and hasattr(K.domain, 'domain'):
                F_q = K.domain.domain
            else:
                F_q = None
    except Exception:
        return [False, False]
        
    # H1: F_q is a finite field
    try:
        h1 = isinstance(F_q, FiniteField)
    except Exception:
        h1 = False
        
    # neg_Q: K is not generated by a single element over F_q
    try:
        neg_q = False
        if hasattr(K, 'is_Field') and K.is_Field:
            if isinstance(K, FractionField):
                base_field = K.domain.domain
                if base_field == F_q:
                    # A fraction field with >= 2 generators has transcendence degree >= 2
                    # over its base field, so it cannot be generated by a single element.
                    if len(K.gens) >= 2:
                        neg_q = True
    except Exception:
        neg_q = False
        
    return [bool(h1), bool(neg_q)]

