import sympy
from sympy import isprime, Rational, Integer
from sympy.ntheory import factorint

# Top-level setup
# No specific named objects needed for this number theory conjecture.

def conditions(witness) -> list[bool]:
    """
    Check the hypotheses and negated conclusion for the conjecture:
    Hypotheses:
      - n is a positive integer
      - p is a prime number
      - p does not divide n
    Conclusion:
      The prime ideal generated by p in Z is unramified in the ring of integers of Q(zeta_n).
    """
    try:
        n, p = witness
    except Exception:
        return [False, False, False, False]

    # H_1: n is a positive integer
    try:
        h1 = isinstance(n, int) and n > 0
    except Exception:
        h1 = False

    # H_2: p is a prime number
    try:
        h2 = isprime(p)
    except Exception:
        h2 = False

    # H_3: p does not divide n
    try:
        h3 = (n % p != 0)
    except Exception:
        h3 = False

    # ¬Q: p IS ramified in Q(zeta_n)
    # The discriminant of Q(zeta_n) is composed of primes dividing n, EXCEPT when n=2.
    # Wait, if n=2, Q(zeta_2) = Q, discriminant is 1, no primes ramify.
    # Actually, a prime p ramifies in Q(zeta_n) iff p divides n, EXCEPT that 2 ramifies in Q(zeta_n) 
    # if 4 divides n, or if n is odd and... wait, the exact primes that ramify in Q(zeta_n) are 
    # the prime factors of n, except that if n = 2 * (odd), Q(zeta_n) = Q(zeta_{n/2}), so the primes 
    # ramifying are the prime factors of n/2.
    # Let's compute the discriminant of Q(zeta_n) exactly.
    # The primes ramifying in Q(zeta_n) are exactly the prime factors of the discriminant.
    # For n=1, Q(zeta_1) = Q, discriminant is 1, no primes ramify.
    # For n=2, Q(zeta_2) = Q, discriminant is 1, no primes ramify.
    # For n>2, the primes ramifying are exactly the prime factors of n, EXCEPT if n = 2 * m where m is odd,
    # in which case Q(zeta_n) = Q(zeta_m), so the primes ramifying are the prime factors of m (i.e. 2 does not ramify).
    try:
        if n == 1 or n == 2:
            ramified_primes = set()
        elif n % 2 == 0 and (n // 2) % 2 != 0:
            # n = 2 * m where m is odd
            m = n // 2
            ramified_primes = set(factorint(m).keys())
        else:
            ramified_primes = set(factorint(n).keys())
            
        neg_q = p in ramified_primes
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

