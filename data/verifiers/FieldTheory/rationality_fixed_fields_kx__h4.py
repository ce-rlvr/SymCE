# Top-level setup
# The conjecture is actually true (Lüroth's Theorem guarantees that the fixed field
# of a finite subgroup of Aut(K(x)/K) is rational). However, since we are required
# to write a verifier for a "false" conjecture, we will implement the checks
# exactly as requested. If the witness is a valid counterexample, it must satisfy
# the hypotheses and fail the conclusion.

def conditions(witness) -> list[bool]:
    """
    Checks if the witness is a valid counterexample to the conjecture.
    
    The witness should be a tuple (K, K_x, G) where:
      - K is a field.
      - K_x is the field of rational functions K(x).
      - G is a finite subgroup of Aut(K(x)/K).
    """
    try:
        K, K_x, G = witness
    except Exception:
        return [False, False, False, False]

    # H1: K is a field
    try:
        # In sympy, we can check if K is a field by checking its properties
        # or if it's an instance of a Field class.
        h1 = hasattr(K, 'is_Field') and K.is_Field
        if not h1:
            # Fallback for sympy domains
            h1 = K.is_Field
    except Exception:
        h1 = False

    # H2: K(x) is the field of rational functions in one variable over K
    try:
        # Check if K_x is generated by a single transcendental element over K
        h2 = hasattr(K_x, 'gens') and len(K_x.gens) == 1 and K_x.domain == K
    except Exception:
        h2 = False

    # H3: G is a finite subgroup of the automorphism group Aut(K(x)/K)
    try:
        # Check if G is finite
        is_finite = hasattr(G, 'order') and G.order() < float('inf')
        if not is_finite:
            is_finite = len(G) < float('inf')
        
        # Check if elements of G are automorphisms of K(x) fixing K
        # This is a structural check on the witness
        is_subgroup = True
        for g in G:
            if not callable(g):
                is_subgroup = False
                break
        h3 = is_finite and is_subgroup
    except Exception:
        h3 = False

    # ¬Q: The conclusion FAILS at the witness
    # Conclusion: There exists a rational function f(x) in K(x) such that K(x)^G = K(f(x))
    # Negation: For all rational functions f(x) in K(x), K(x)^G != K(f(x))
    # Since Lüroth's theorem states this is always true, a true counterexample
    # would make this negated conclusion True.
    try:
        # We evaluate the fixed field K(x)^G.
        # If the witness is a true counterexample, it will provide a fixed field
        # that is not generated by a single rational function.
        # For the sake of the verifier, we check if the witness explicitly
        # demonstrates the failure of rationality.
        
        # If the witness provides a property 'is_rational_over_K' for the fixed field:
        fixed_field = witness.fixed_field if hasattr(witness, 'fixed_field') else None
        if fixed_field is not None:
            neg_q = not fixed_field.is_rational_over_K
        else:
            # If we cannot determine, we assume it fails to be a counterexample
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

