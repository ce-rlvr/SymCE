# Top-level setup for witness expressions
# Field theory witnesses typically use algebraic numbers and polynomials over QQ.

def conditions(witness):
    """
    Checks the hypotheses and negated conclusion for the conjecture:
    "The normal closure of E over K is identical to the splitting field of f(x) over K."
    """
    def get_attr(obj, attr, default=None):
        if isinstance(obj, dict):
            return obj.get(attr, default)
        return getattr(obj, attr, default)

    # H_1: E/K is a finite extension generated by elements alpha_1, ..., alpha_n
    try:
        alphas = get_attr(witness, 'alphas')
        p_list = get_attr(witness, 'p_list')
        h1 = True
        if not alphas or not p_list or len(alphas) != len(p_list):
            h1 = False
        else:
            for alpha, p in zip(alphas, p_list):
                p_expr = p.as_expr() if hasattr(p, 'as_expr') else sympify(p)
                free_syms = p_expr.free_symbols
                gen = list(free_syms)[0] if free_syms else Symbol('x')
                
                # Check if alpha is a root of its minimal polynomial
                val = simplify(p_expr.subs(gen, alpha))
                if val != 0 and val.is_zero is not True:
                    h1 = False
                    break
                
                # Check if the polynomial is irreducible
                p_poly = Poly(p_expr)
                if not p_poly.is_irreducible:
                    h1 = False
                    break
    except Exception:
        h1 = False

    # H_2: f(x) = p_1(x) ... p_n(x) is the product of these minimal polynomials
    try:
        f = get_attr(witness, 'f')
        p_list = get_attr(witness, 'p_list')
        if not p_list or f is None:
            h2 = False
        else:
            prod_p = p_list[0]
            for p in p_list[1:]:
                prod_p = prod_p * p
            
            f_expr = f.as_expr() if hasattr(f, 'as_expr') else sympify(f)
            prod_expr = prod_p.as_expr() if hasattr(prod_p, 'as_expr') else sympify(prod_p)
            
            diff = simplify(f_expr - prod_expr)
            h2 = (diff == 0 or diff.is_zero is True)
    except Exception:
        h2 = False

    # ¬Q: The normal closure of E over K is NOT identical to the splitting field of f(x) over K
    try:
        nc_deg = get_attr(witness, 'normal_closure_degree')
        sf_deg = get_attr(witness, 'splitting_field_degree')
        
        # If degrees over K differ, the fields cannot be identical
        if nc_deg is not None and sf_deg is not None:
            neg_q = (nc_deg != sf_deg)
        else:
            # Fallback to a boolean property if degrees are not provided
            neg_q = not get_attr(witness, 'normal_closure_is_splitting_field', True)
    except Exception:
        neg_q = False

    return [bool(h1), bool(h2), bool(neg_q)]

