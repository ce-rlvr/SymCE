import sympy
from sympy import Poly
from sympy.abc import x

# Top-level setup
# The witness is expected to be a sympy.Poly object over a finite field.
# Example counterexample: Poly(x**2 + x + 1, domain='GF(2)')

def conditions(witness):
    try:
        # Allow witness to be a tuple where the first element is the polynomial
        if isinstance(witness, tuple) and len(witness) > 0 and isinstance(witness[0], Poly):
            f = witness[0]
        else:
            f = witness
            
        if not isinstance(f, Poly):
            return [False, False, False, False]
            
        domain = f.domain
        if not domain.is_Field:
            return [False, False, False, False]
            
        # H_1: f(x) is a separable polynomial of degree n
        f_der = f.diff()
        gcd_poly = f.gcd(f_der)
        h1 = (f.degree() >= 1) and (gcd_poly.degree() == 0)
        
        # H_2: E is the splitting field of f(x) over F (definitional)
        h2 = True
        
        # H_3: D is the discriminant of f(x) (definitional)
        h3 = True
        
        # We only support finite fields for evaluating the Galois group in this verifier
        if not domain.is_FiniteField:
            return [h1, h2, h3, False]
            
        # Check if D is a square in F
        D = f.discriminant()
        if domain.characteristic == 2:
            D_is_square = True
        else:
            # For odd characteristic, we restrict to prime fields for simplicity
            if not hasattr(domain, 'p') or domain.order != domain.p:
                return [h1, h2, h3, False]
            p = domain.order
            try:
                D_val = int(D) % p
            except Exception:
                D_val = int(D.to_int()) % p
            D_is_square = any((i * i) % p == D_val for i in range(p))
            
        # Check if Gal(E/F) <= A_n
        # For finite fields, the Galois group is cyclic and generated by the Frobenius automorphism.
        # The cycle type of this generator acting on the roots corresponds to the degrees of the irreducible factors.
        # A permutation is even iff it has an even number of even-length cycles.
        factors = f.factor_list()[1]
        even_degree_count = sum(1 for factor, mult in factors if factor.degree() % 2 == 0)
        gal_in_An = (even_degree_count % 2 == 0)
        
        # ¬Q: The conclusion "Gal(E/F) <= A_n iff D is a square in F" is FALSE
        neg_q = (gal_in_An != D_is_square)
        
        return [h1, h2, h3, neg_q]
    except Exception:
        return [False, False, False, False]

