import sympy
from sympy import Dummy, sympify, minpoly, sqrt, I, pi, Rational, Integer
from sympy.polys import primitive_element

# Top-level setup
# Witnesses for this domain are expected to be tuples: (F_gens, K_gens, alpha)
# where F_gens and K_gens are lists of algebraic numbers generating the fields over QQ.
# Example witness: ([], [sqrt(2), sqrt(3)], sqrt(2))
# This represents F = QQ, K = QQ(sqrt(2), sqrt(3)), and alpha = sqrt(2).

def field_degree(gens):
    """
    Computes the degree of the field extension QQ(gens) over QQ.
    """
    if not gens:
        return 1
    gens = [sympify(g) for g in gens]
    x = Dummy('x')
    pe = primitive_element(gens, x)
    # Handle different SymPy versions where primitive_element might return a tuple
    if isinstance(pe, tuple):
        pe = pe[0]
    mp = minpoly(pe, x)
    return mp.degree()

def conditions(witness):
    try:
        F_gens, K_gens, alpha = witness
        F_gens = list(F_gens)
        K_gens = list(K_gens)
    except Exception:
        return [False, False, False]
        
    # H_1: K is a finite extension field of F
    try:
        deg_K = field_degree(K_gens)
        deg_K_F = field_degree(K_gens + F_gens)
        
        # K must be a finite extension of F.
        # This means F is a subfield of K, so K(F) == K
        h1_ok = (deg_K_F == deg_K) and (deg_K > 0)
    except Exception:
        h1_ok = False

    # H_2: α is an element of K that is not in F
    try:
        deg_K = field_degree(K_gens)
        deg_F = field_degree(F_gens)
        deg_K_alpha = field_degree(K_gens + [alpha])
        deg_F_alpha = field_degree(F_gens + [alpha])
        
        alpha_in_K = (deg_K_alpha == deg_K)
        alpha_in_F = (deg_F_alpha == deg_F)
        
        h2_ok = alpha_in_K and not alpha_in_F
    except Exception:
        h2_ok = False

    # ¬Q: K is not generated by α over F (K != F(α))
    try:
        deg_K = field_degree(K_gens)
        deg_F_alpha = field_degree(F_gens + [alpha])
        deg_K_F_alpha = field_degree(K_gens + F_gens + [alpha])
        
        # K == F(alpha) iff F(alpha) is a subfield of K and K is a subfield of F(alpha)
        # This is true iff deg(K(F(alpha))) == deg(K) == deg(F(alpha))
        k_equals_f_alpha = (deg_K_F_alpha == deg_K) and (deg_K_F_alpha == deg_F_alpha)
        neg_q_ok = not k_equals_f_alpha
    except Exception:
        neg_q_ok = False

    return [bool(h1_ok), bool(h2_ok), bool(neg_q_ok)]

