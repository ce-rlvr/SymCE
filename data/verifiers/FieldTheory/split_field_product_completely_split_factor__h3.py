import sympy
from sympy import QQ, Poly, roots, Symbol
from sympy import sqrt, I, Rational, Integer, pi, E

# Top-level setup for witness expressions
x = Symbol('x')

def in_field(expr, field):
    """Check if a SymPy expression belongs to the given algebraic field."""
    if field == QQ:
        try:
            QQ.from_sympy(expr)
            return True
        except Exception:
            return False
    else:
        try:
            field.from_sympy(expr)
            return True
        except Exception:
            return False

def is_subfield(gens, field):
    """Check if all generators are in the given field."""
    for g in gens:
        if not in_field(g, field):
            return False
    return True

def safe_algebraic_field(gens):
    """Construct an algebraic field from generators, safely ignoring rationals."""
    valid_gens = []
    for g in gens:
        try:
            # If it can be coerced to QQ, it's rational and not needed as a generator
            QQ.from_sympy(g)
        except Exception:
            valid_gens.append(g)
    if not valid_gens:
        return QQ
    return QQ.algebraic_field(*valid_gens)

def is_poly_in_field(poly_expr, field, x_sym):
    """Check if poly_expr is a polynomial in x_sym with coefficients in field."""
    try:
        p = Poly(poly_expr, x_sym)
        if p.gen != x_sym:
            return False
        for coeff in p.coeffs():
            if not in_field(coeff, field):
                return False
        return True
    except Exception:
        return False

def is_splitting_field(f_expr, g_expr, F_gens, K_gens, x_sym):
    """Check if K is the splitting field of f*g over F."""
    F = safe_algebraic_field(F_gens)
    K = safe_algebraic_field(K_gens)
    
    # 1. K must contain F
    if not is_subfield(F_gens, K):
        return False
        
    # 2. f*g must split completely in K
    fg = f_expr * g_expr
    p = Poly(fg, x_sym)
    rts = roots(p, x_sym)
    
    # If we cannot find all roots in C, we cannot rigorously verify the splitting field
    if sum(rts.values()) != p.degree():
        raise ValueError("Cannot find all roots")
        
    for r in rts.keys():
        if not in_field(r, K):
            return False
            
    # 3. K must be generated by F and the roots of f*g
    L_gens = list(F_gens) + list(rts.keys())
    L = safe_algebraic_field(L_gens)
    
    if not is_subfield(K_gens, L):
        return False
        
    return True

def conditions(witness):
    """
    witness is expected to be a tuple: (F_gens, K_gens, f, g)
    where F_gens and K_gens are lists of algebraic generators (e.g., [sqrt(2)]),
    and f, g are SymPy expressions in x.
    """
    try:
        F_gens, K_gens, f, g = witness
    except Exception:
        return [False, False, False, False]
        
    # H_1: F is a field
    try:
        h1 = isinstance(F_gens, (list, tuple))
        if h1:
            F = safe_algebraic_field(F_gens)
    except Exception:
        h1 = False

    # H_2: f(x) and g(x) are polynomials over F
    try:
        if h1:
            h2 = is_poly_in_field(f, F, x) and is_poly_in_field(g, F, x)
        else:
            h2 = False
    except Exception:
        h2 = False

    # H_3: g(x) splits completely into linear factors over K
    try:
        h3 = False
        if isinstance(K_gens, (list, tuple)):
            K = safe_algebraic_field(K_gens)
            p_g = Poly(g, x)
            rts_g = roots(p_g, x)
            if sum(rts_g.values()) == p_g.degree():
                h3 = True
                for r in rts_g.keys():
                    if not in_field(r, K):
                        h3 = False
                        break
    except Exception:
        h3 = False

    # ¬Q: K is NOT the splitting field of f(x)g(x) over F
    try:
        neg_q = False
        if h1 and isinstance(K_gens, (list, tuple)):
            is_split = is_splitting_field(f, g, F_gens, K_gens, x)
            neg_q = not is_split
    except Exception:
        # If we fail to compute the splitting field (e.g., roots not found),
        # we return False to avoid false positives.
        neg_q = False

    return [h1, h2, h3, neg_q]

