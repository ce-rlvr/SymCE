import sympy as sp
from sympy import Poly, simplify, expand, minpoly
from sympy.abc import x

# Top-level setup
# The witness will provide its own SymPy expressions for the fields and polynomials.
# No special groups or matrices are needed for this field theory conjecture.

CONDITION_LABELS = [
    "H_1: F is a field",
    "H_2: K is the splitting field of f(x) over F",
    "H_3: sigma is a field automorphism of K fixing F",
    "H_4: alpha in K is a root of f(x)",
    "¬Q: sigma(alpha) is NOT a root of f(x)"
]

N_HYP = 4
NEG_Q_INDEX = 4

def conditions(witness):
    f = witness.get('f')
    alpha = witness.get('alpha')
    sigma_map = witness.get('sigma_map', {})
    F_gens = witness.get('F_gens', [])
    K_gens = witness.get('K_gens', [])
    roots = witness.get('roots', [])
    
    # H1: F is a field
    # Any set of complex numbers generates a subfield of C.
    h1 = True
    
    # H2: K is the splitting field of f(x) over F
    try:
        poly_f = Poly(f, x)
        lc = poly_f.LC()
        reconstructed_f = lc
        for r in roots:
            reconstructed_f *= (x - r)
        splits = simplify(expand(f) - expand(reconstructed_f)) == 0
        
        # Ensure K is generated by the roots
        h2_k_gens_in_roots = all(g in roots for g in K_gens)
        h2 = bool(splits and h2_k_gens_in_roots)
    except Exception:
        h2 = False
        
    # H3: sigma is a field automorphism of K fixing F
    try:
        h3_fixes_F = all(simplify(sigma_map.get(g, g) - g) == 0 for g in F_gens)
        h3_valid_auto = True
        for g in K_gens:
            mp = minpoly(g, x)
            img = sigma_map.get(g, g)
            if simplify(mp.subs(x, img)) != 0:
                h3_valid_auto = False
                break
        h3 = bool(h3_fixes_F and h3_valid_auto)
    except Exception:
        h3 = False
        
    # H4: alpha in K is a root of f(x)
    try:
        h4 = bool(simplify(f.subs(x, alpha)) == 0 and (alpha in roots))
    except Exception:
        h4 = False
        
    # Negated Conclusion: sigma(alpha) is NOT a root of f(x)
    try:
        sigma_alpha = alpha.subs(sigma_map)
        neg_q = bool(simplify(f.subs(x, sigma_alpha)) != 0)
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, h4, neg_q]