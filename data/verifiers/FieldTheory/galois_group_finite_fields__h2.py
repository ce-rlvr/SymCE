def is_prime_power(q):
    try:
        q = int(q)
        if q < 2:
            return False
        return len(factorint(q)) == 1
    except Exception:
        return False

def conditions(witness):
    """
    Checks if the witness is a valid counterexample.
    Expected witness format: (q, E_poly)
    where `q` is the order of the finite field F (must be a prime for SymPy Poly domain compatibility),
    and `E_poly` is a polynomial (or list of coefficients) defining the extension E = F[x]/(E_poly).
    """
    try:
        F_obj, E_obj = witness
        if hasattr(F_obj, 'order'):
            q = F_obj.order
        else:
            q = int(F_obj)
    except Exception:
        return [False, False]

    try:
        h1 = is_prime_power(q)
    except Exception:
        h1 = False

    try:
        # E/F is a Galois extension with Gal(E/F) cyclic of order n generated by Frobenius
        # if and only if E is a valid finite field extension of degree n >= 1.
        # This holds iff the defining polynomial E_obj is irreducible over GF(q).
        p = Poly(E_obj, x, domain=GF(q))
        n = p.degree()
        if n < 1:
            is_galois = False
        else:
            is_galois = p.is_irreducible
        
        neg_q = not is_galois
    except Exception:
        # If polynomial construction or irreducibility check fails (e.g., q is not prime),
        # we cannot verify the conclusion, so we return False.
        neg_q = False

    return [h1, neg_q]

