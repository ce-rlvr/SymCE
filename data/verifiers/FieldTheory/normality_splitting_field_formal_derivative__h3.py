def get_extension_degree(roots_list, gen):
    """
    Computes the degree of the field extension generated by the given roots over Q.
    """
    alg_roots = []
    for r in roots_list:
        if not r.is_Rational and r not in alg_roots:
            alg_roots.append(r)
            
    if not alg_roots:
        return 1
        
    p_g = primitive_element(alg_roots, gen)
    return p_g.degree()

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the conjecture.
    """
    try:
        # Determine the generator variable
        if hasattr(witness, "free_symbols") and len(witness.free_symbols) == 1:
            gen = list(witness.free_symbols)[0]
        elif hasattr(witness, "gens") and len(witness.gens) == 1:
            gen = witness.gens[0]
        else:
            gen = x
            
        f = Poly(witness, gen)
        h1 = f.degree() >= 1
    except Exception:
        h1 = False
        gen = x

    # H2 is true by definition for any valid polynomial witness
    h2 = True if h1 else False

    neg_q = False
    try:
        if h1:
            f_expr = f.as_expr()
            f_prime = f.diff(gen)
            
            # Compute roots over C
            r_f_dict = roots(f_expr, gen)
            r_fp_dict = roots(f_prime.as_expr(), gen)
            
            # Proceed only if we can find all roots exactly
            if sum(r_f_dict.values()) == f.degree() and sum(r_fp_dict.values()) == f_prime.degree():
                r_f = list(r_f_dict.keys())
                r_fp = list(r_fp_dict.keys())
                
                # Degree of the splitting field L over Q
                deg_L = get_extension_degree(r_f, gen)
                
                # Check if all roots of f' are in L
                all_in_L = True
                for a in r_fp:
                    if a.is_Rational:
                        continue
                    # If adding 'a' strictly increases the extension degree, 'a' is not in L
                    deg_L_a = get_extension_degree(r_f + [a], gen)
                    if deg_L_a > deg_L:
                        all_in_L = False
                        break
                
                # The conclusion fails if the splitting field of f' is NOT a subfield of L
                neg_q = not all_in_L
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

