def conditions(witness):
    """
    Checks if the given witness is a counterexample to the false conjecture.
    The witness is expected to be a polynomial representing the abstract algebraic extension K = Q[x]/(f).
    """
    try:
        x = sp.Symbol('x')
        if isinstance(witness, str):
            expr = sp.sympify(witness)
        else:
            expr = witness
            
        if hasattr(expr, 'free_symbols'):
            free_syms = expr.free_symbols
            if len(free_syms) == 1:
                gen = list(free_syms)[0]
            else:
                gen = x
        else:
            gen = x
            
        p = Poly(expr, gen, domain='QQ')
        
        # H_1: K/F is an algebraic extension
        # This holds if the polynomial is irreducible over QQ.
        h1 = p.is_irreducible
        
        if not h1:
            return [False, False]
            
        # If the degree is 1, K = F, which is canonically a subfield of \overline{F},
        # so \sigma(K) = K holds and the conclusion is true (not a counterexample).
        if p.degree() <= 1:
            return [bool(h1), False]
            
        # neg_Q: The conclusion fails.
        # Since K = Q[x]/(f) is an abstract extension and not a subfield of \overline{Q},
        # \sigma(K) = K is strictly false (type/set mismatch).
        # Thus, the conclusion (P <-> Q) fails if and only if P (K/F is normal) is TRUE.
        # We check if the extension is normal by verifying if the polynomial splits 
        # completely in the field generated by one of its roots.
        a = sp.RootOf(p, 0)
        factors = sp.factor_list(p, extension=a)
        is_normal = all(Poly(fac, gen).degree() == 1 for fac, mult in factors[1])
        
        neg_q = is_normal
        
        return [bool(h1), bool(neg_q)]
    except Exception:
        return [False, False]