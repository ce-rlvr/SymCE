def conditions(witness):
    """
    Checks the counterexample witness for the false conjecture.
    The witness should be a tuple of two SymPy expressions in `x`: (p_L, g)
    where:
      - p_L is the minimal polynomial of a primitive element `a` for L over K=Q.
      - g is a polynomial such that M = Q(g(a)).
    """
    try:
        if not isinstance(witness, tuple) or len(witness) != 2:
            return [False, False]
            
        p_L_expr, g_expr = witness
        
        p_L = sp.Poly(p_L_expr, x, domain='QQ')
        g = sp.Poly(g_expr, x, domain='QQ')
        
        # H_1: M is an intermediate field between K and L
        # This holds if L is a valid field extension (p_L is irreducible) 
        # and M is generated by an element in L (g is a polynomial).
        h1 = bool(p_L.degree() > 0 and p_L.is_irreducible)
        if not h1:
            return [False, False]
            
        # Let `a` be a primitive element of L over Q
        a = sp.RootOf(p_L_expr, x, 0)
        
        # Find all roots of p_L in L = Q(a) to determine Aut(L/K)
        factors_L = sp.factor_list(p_L_expr, x, extension=a)[1]
        roots_L = []
        for factor, mult in factors_L:
            poly_factor = sp.Poly(factor, x, extension=a)
            if poly_factor.degree() == 1:
                coeffs = poly_factor.all_coeffs()
                r = -coeffs[1] / coeffs[0]
                roots_L.append(r)
                
        aut_L_K_size = len(roots_L)
        
        # Helper to reduce expressions in `a` to standard polynomial form in `y`
        def reduce_mod_pL(expr_in_a):
            expr_in_y = sp.sympify(expr_in_a).subs(a, y)
            rem = sp.rem(expr_in_y, p_L_expr.subs(x, y), y)
            return sp.expand(rem)
            
        # b is the generator of M, b = g(a)
        g_a = reduce_mod_pL(g_expr.subs(x, a))
        
        # Determine Aut(L/M) by checking which automorphisms in Aut(L/K) fix `b`
        aut_L_M_size = 0
        for r in roots_L:
            g_r = reduce_mod_pL(g_expr.subs(x, r))
            if sp.simplify(g_r - g_a) == 0:
                aut_L_M_size += 1
                
        if aut_L_M_size == 0:
            return [True, False]
            
        # Number of left cosets of Aut(L/M) in Aut(L/K)
        cosets_size = aut_L_K_size // aut_L_M_size
        
        # Find the number of distinct K-embeddings of M into L
        # This equals the number of distinct roots of the minimal polynomial of `b` in L
        b = g_expr.subs(x, a)
        p_M_expr = sp.minpoly(b, x)
        
        factors_M = sp.factor_list(p_M_expr, x, extension=a)[1]
        embeddings_size = 0
        for factor, mult in factors_M:
            poly_factor = sp.Poly(factor, x, extension=a)
            if poly_factor.degree() == 1:
                embeddings_size += 1
                
        # ¬Q: The number of embeddings is NOT equal to the number of cosets
        neg_q = (embeddings_size != cosets_size)
        
        return [True, bool(neg_q)]
        
    except Exception:
        return [False, False]