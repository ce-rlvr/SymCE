import sympy
from sympy import Poly, RootOf, factor, Mul, sympify
from sympy.abc import x, y, z, t

# Top-level setup for the witness evaluation namespace
# (Standard symbols are provided; no specific groups are needed for this field theory conjecture)

CONDITION_LABELS = [
    "H_1: K_insep is the maximal purely inseparable subextension of K over F",
    "¬Q: K is not a Galois extension of K_insep"
]

N_HYP = 1
NEG_Q_INDEX = 1

def conditions(witness):
    """
    Checks if the given witness is a valid counterexample to the false conjecture.
    The witness is expected to be a univariate polynomial over Q (representing the field extension K = Q[x]/(f)).
    Since the base field F is Q (characteristic 0), the maximal purely inseparable subextension K_insep is always Q.
    """
    try:
        # Extract the polynomial expression from the witness
        if isinstance(witness, dict):
            expr = witness.get('f', witness.get('K', witness.get('polynomial', witness.get('expr', None))))
            if expr is None and witness:
                expr = list(witness.values())[0]
        else:
            expr = witness
            
        if isinstance(expr, (list, tuple)):
            expr = expr[0]
            
        if isinstance(expr, str):
            expr = sympify(expr)
            
        # Convert to a SymPy Poly object
        if isinstance(expr, Poly):
            f = expr
        else:
            free_symbols = list(expr.free_symbols)
            if len(free_symbols) == 1:
                f = Poly(expr, free_symbols[0])
            elif len(free_symbols) == 0:
                f = Poly(expr, x)
            else:
                f = Poly(expr)
                
        # H1: K_insep is the maximal purely inseparable subextension of K over F.
        # In characteristic 0, this is trivially true (K_insep = F = Q).
        # We just need to verify that f defines a valid field extension over Q (i.e., f is irreducible).
        if f.domain.is_RationalField or f.domain.is_IntegerRing:
            h1 = f.is_irreducible
        else:
            h1 = False
    except Exception:
        h1 = False

    try:
        if not h1:
            neg_q = False
        else:
            # Conclusion: K is a Galois extension of K_insep.
            # Since K_insep = Q, this means K is Galois over Q.
            # K is Galois over Q iff f is a normal polynomial over Q.
            real_roots_count = len(f.real_roots())
            deg = f.degree()
            
            # If an irreducible polynomial over Q has a strict mix of real and non-real roots,
            # its splitting field cannot be generated by a single real root, so it is not normal.
            if 0 < real_roots_count < deg:
                is_galois = False
            else:
                # Fallback: check if f factors completely into linear factors over the field generated by one of its roots.
                alpha = RootOf(f, 0)
                factored = factor(f.as_expr(), extension=alpha)
                
                if isinstance(factored, Mul):
                    is_galois = all(Poly(arg, f.gen).degree() == 1 for arg in factored.args if arg.has(f.gen))
                else:
                    is_galois = Poly(factored, f.gen).degree() == 1
                    
            # neg_Q is True when the conclusion FAILS (i.e., K is NOT Galois over K_insep)
            neg_q = not is_galois
    except Exception:
        neg_q = False

    return [bool(h1), bool(neg_q)]