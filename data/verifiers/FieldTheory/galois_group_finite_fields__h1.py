def conditions(witness):
    try:
        # The witness is expected to be an irreducible polynomial representing 
        # the finite field extension E = F[x]/(P(x)).
        if not isinstance(witness, Poly):
            poly = Poly(witness)
        else:
            poly = witness
            
        domain = poly.domain
        
        # Ensure we are working over a field (e.g., convert ZZ to QQ)
        if not domain.is_Field:
            poly = poly.set_domain(domain.get_field())
            domain = poly.domain
            
        # H_1: E is a finite field extension of F of degree n.
        # This holds if the polynomial is irreducible over its base field.
        h1 = bool(poly.is_irreducible)
        n = poly.degree()
        
        # Check if the base field is a finite field.
        is_finite_field = getattr(domain, 'is_FiniteField', False)
        if not is_finite_field:
            is_finite_field = domain.__class__.__name__ in ('FiniteField', 'GaloisField')
            
        # ¬Q: The extension is not Galois, or its Galois group is not cyclic of order n 
        # generated by the Frobenius automorphism phi(x) = x^q.
        # If the base field is infinite, the only F-automorphism of the form x -> x^q 
        # is the identity (q=1), which generates a group of order 1. 
        # Thus, for any degree n > 1 over an infinite field, the conclusion fails.
        if is_finite_field:
            neg_q = False
        else:
            neg_q = bool(n > 1)
            
    except Exception:
        h1 = False
        neg_q = False
        
    return [h1, neg_q]

