import sympy
from sympy import Symbol
from sympy.abc import x, y, z
from sympy.polys.domains import ZZ, QQ

def conditions(witness):
    """
    Checks whether the given witness is a valid counterexample to the false conjecture.
    The witness should be a dictionary with keys 'F', 'E', 'X', and 'K', representing
    the base domain F, the extension E, the list of generators X, and the algebraic closure K.
    """
    try:
        if not isinstance(witness, dict):
            return [False, False, False]
        F = witness.get('F')
        E = witness.get('E')
        X = witness.get('X')
        K = witness.get('K')
    except Exception:
        return [False, False, False]
        
    # H_1: E is a purely transcendental extension of F generated by algebraically independent elements X
    try:
        if isinstance(X, sympy.Symbol):
            X_list = [X]
        else:
            X_list = list(X)
            
        if len(X_list) == 0 or not all(isinstance(sym, sympy.Symbol) for sym in X_list):
            h1_ok = False
        else:
            # In sympy, the purely transcendental extension F(X) is the fraction field of F[X]
            expected_E = F.frac_field(*X_list)
            h1_ok = (E == expected_E)
    except Exception:
        h1_ok = False
        
    # H_2: K is the algebraic closure of F within E
    try:
        # For an integral domain F, its algebraic closure in the purely transcendental extension F(X)
        # is exactly its field of fractions.
        expected_K = F.get_field()
        h2_ok = (K == expected_K)
    except Exception:
        h2_ok = False
        
    # ¬Q: The field K is NOT equal to F
    try:
        neg_q_ok = (K != F)
    except Exception:
        neg_q_ok = False
        
    return [h1_ok, h2_ok, neg_q_ok]

