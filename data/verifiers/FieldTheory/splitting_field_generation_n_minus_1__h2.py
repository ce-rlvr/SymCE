import sympy
from sympy import Symbol, simplify, expand, Mul, sympify, QQ
from sympy.polys.numberfields import primitive_element

# Top-level setup
x = Symbol('x')

def field_degree(gens):
    """
    Computes the degree of the number field generated by `gens` over Q.
    """
    filtered = []
    seen = set()
    for g in gens:
        g_sym = sympify(g)
        # Filter out rational numbers as they don't extend Q
        if not g_sym.is_Rational and g_sym not in seen:
            filtered.append(g_sym)
            seen.add(g_sym)
    if not filtered:
        return 1
    _, minpoly = primitive_element(filtered, domain=QQ)
    return minpoly.degree()

def conditions(witness):
    """
    Checks the hypotheses and the negated conclusion for the given witness.
    The witness should be a dictionary containing:
      - 'F_gens': list of generators for field F over Q
      - 'E_gens': list of generators for field E over Q
      - 'f': sympy expression for the polynomial f(x)
      - 'roots': list of roots alpha_1, ..., alpha_n
      - 'c': the leading coefficient c
      - 'x': (optional) the variable used in f(x)
    """
    # H1: F is a field
    # Any set of algebraic numbers generates a valid number field over Q.
    try:
        F_gens = witness['F_gens']
        d_F = field_degree(F_gens)
        h1 = True
    except Exception:
        h1 = False

    # H2: E is a splitting field of f(x) over F
    # This means E is generated by F and the roots of f(x).
    try:
        E_gens = witness['E_gens']
        roots = witness['roots']
        
        d_E = field_degree(E_gens)
        d_F_roots = field_degree(F_gens + roots)
        d_E_F_roots = field_degree(E_gens + F_gens + roots)
        
        # E must contain F(roots) and F(roots) must contain E
        h2 = (d_E == d_F_roots) and (d_E == d_E_F_roots)
    except Exception:
        h2 = False

    # H3: \alpha_1, \dots, \alpha_n are the roots of f(x) in E such that 
    # f(x) = c(x-\alpha_1)\cdots(x-\alpha_n) for some c \in F
    try:
        f = witness['f']
        c = witness['c']
        roots = witness['roots']
        
        f_expr = f.as_expr() if hasattr(f, 'as_expr') else f
        
        if 'x' in witness:
            x_sym = witness['x']
        else:
            free_syms = f_expr.free_symbols
            if len(free_syms) == 1:
                x_sym = list(free_syms)[0]
            else:
                x_sym = x
                
        # Check if c is in F
        d_F_c = field_degree(F_gens + [c])
        c_in_F = (d_F == d_F_c)
        
        # Check if f(x) matches the factored form
        expected_f = c * Mul(*[x_sym - a for a in roots])
        f_match = simplify(expand(f_expr - expected_f)) == 0
        
        h3 = c_in_F and f_match and len(roots) >= 1
    except Exception:
        h3 = False

    # Negated Conclusion: E != F(\alpha_1, \dots, \alpha_{n-1})
    # Since F(roots[:-1]) is a subfield of E, they are unequal iff their degrees over Q differ.
    try:
        d_F_roots_minus_1 = field_degree(F_gens + roots[:-1])
        neg_q = (d_E != d_F_roots_minus_1)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

