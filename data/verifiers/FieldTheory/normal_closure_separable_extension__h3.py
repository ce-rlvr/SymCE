def conditions(witness):
    """
    Check if the witness satisfies the hypotheses and falsifies the conclusion.
    The witness is expected to be a polynomial representing the finite field extension E = F[x]/(p).
    """
    # Duck-typing for custom witness objects
    if hasattr(witness, 'is_finite_extension') and callable(witness.is_finite_extension):
        try:
            h1 = bool(witness.is_finite_extension())
            h2 = bool(witness.is_separable())
            neg_q = not bool(witness.normal_closure_is_separable())
            return [h1, h2, neg_q]
        except Exception:
            pass

    try:
        if isinstance(witness, sympy.Poly):
            poly = witness
        else:
            poly = sympy.Poly(witness)
            
        if poly.degree() < 1:
            return [False, False, False]
            
        # H1: Let E/F be a finite field extension
        # This means the polynomial must be irreducible over its base field.
        try:
            h1 = bool(poly.is_irreducible)
        except Exception:
            h1 = False
            
        # H2: The extension E/F is separable
        # A finite extension generated by a root of an irreducible polynomial
        # is separable iff the polynomial is separable (coprime to its formal derivative).
        try:
            p_diff = poly.diff()
            gcd_poly = poly.gcd(p_diff)
            h2 = bool(gcd_poly.degree() == 0)
        except Exception:
            h2 = False
            
        # ¬Q: The extension N/F is not separable
        # The normal closure N is the splitting field of the minimal polynomial.
        # N/F is separable iff the minimal polynomial is separable.
        neg_q = not h2
        
        return [h1, h2, neg_q]
    except Exception:
        return [False, False, False]

