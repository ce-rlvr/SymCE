import sympy
from sympy import Poly, Symbol, GF

# Define symbols that might be used in the witness
x = Symbol('x')

CONDITION_LABELS = [
    "H_1: f(x) is a separable polynomial of degree n over K",
    "H_2: L is the splitting field of f(x) over K",
    "H_3: Delta is the discriminant of the polynomial f(x)",
    "¬Q: Gal(L/K) <= A_n is not equivalent to Delta being a square in K"
]

N_HYP = 3
NEG_Q_INDEX = 3

def conditions(witness):
    try:
        # The witness must be a polynomial
        if not isinstance(witness, Poly):
            return [False, False, False, False]
        
        f = witness
        n = f.degree()
        if n < 1:
            return [False, False, False, False]
            
        # H_1: f(x) is separable iff gcd(f, f') == 1
        df = f.diff()
        gcd_f_df = f.gcd(df)
        h1 = bool(gcd_f_df.degree() == 0)
        
        # H_2 and H_3 are definitions of L and Delta, which are always valid 
        # for any valid polynomial witness.
        h2 = True
        h3 = True
        
        domain = f.domain
        
        # We restrict the evaluation of the Galois group to finite fields.
        # The conjecture fails specifically for fields of characteristic 2.
        # A counterexample over a finite field like GF(2) is sufficient.
        if not domain.is_FiniteField:
            return [h1, h2, h3, False]
            
        # Compute the discriminant Delta
        delta = f.discriminant()
        
        # Check if Delta is a square in the field K
        is_square = False
        if domain.characteristic == 2:
            # In a finite field of characteristic 2, every element is a square
            is_square = True
        else:
            try:
                q = domain.order
            except AttributeError:
                q = domain.size
                
            if delta == 0 or delta == domain.zero:
                is_square = True
            else:
                try:
                    # Euler's criterion for finite fields of odd characteristic
                    is_square = bool(delta**((q-1)//2) == domain.one)
                except Exception:
                    # Fallback if delta is evaluated as a plain integer
                    val = int(delta) % q
                    is_square = bool(pow(val, (q-1)//2, q) == 1)
                    
        # Check if Gal(L/K) is a subgroup of A_n
        # For a finite field, the Galois group is generated by the Frobenius automorphism.
        # The cycle type of the Frobenius permutation on the roots corresponds to the 
        # degrees of the irreducible factors of f(x).
        # The permutation is even (in A_n) iff n - k is even, where k is the number of irreducible factors.
        factors = f.factor_list()
        k = len(factors[1])
        gal_in_An = bool((n - k) % 2 == 0)
        
        # The conclusion states Gal(L/K) <= A_n iff Delta is a square.
        # We want the conclusion to FAIL, meaning the equivalence does not hold.
        neg_q = bool(gal_in_An != is_square)
        
        return [h1, h2, h3, neg_q]
        
    except Exception:
        return [False, False, False, False]