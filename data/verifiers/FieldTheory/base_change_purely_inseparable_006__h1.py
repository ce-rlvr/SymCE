import sympy
from sympy import symbols, sympify, Matrix, isprime
import itertools

# Top-level setup: named object bindings that the witness expression may reference.
# We provide standard variables for defining rational function fields.
x, y, z, t, u, v = symbols('x y z t u v')

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness should represent the fields K, E, L as lists of generators 
    (SymPy expressions in terms of x, y, z, etc.) over a prime field F_p.
    Format: witness = (p, K_gens, E_gens, L_gens) or a dictionary with these keys.
    """
    try:
        # Parse witness
        if isinstance(witness, dict):
            p = witness.get('p', 2)
            K_exprs = witness.get('K', [])
            E_exprs = witness.get('E', [])
            L_exprs = witness.get('L', [])
        elif isinstance(witness, (tuple, list)):
            if len(witness) == 4:
                p, K_exprs, E_exprs, L_exprs = witness
            elif len(witness) == 3:
                p = 2
                K_exprs, E_exprs, L_exprs = witness
            else:
                return [False, False, False]
        else:
            return [False, False, False]

        # Normalize to lists
        if not isinstance(K_exprs, (list, tuple)): K_exprs = [K_exprs]
        if not isinstance(E_exprs, (list, tuple)): E_exprs = [E_exprs]
        if not isinstance(L_exprs, (list, tuple)): L_exprs = [L_exprs]

        K_exprs = [sympify(expr) for expr in K_exprs]
        E_exprs = [sympify(expr) for expr in E_exprs]
        L_exprs = [sympify(expr) for expr in L_exprs]

        if not isprime(p):
            return [False, False, False]

        # Extract all variables used to form the common overfield F_p(vars)
        free_syms = set()
        for expr in K_exprs + E_exprs + L_exprs:
            free_syms.update(expr.free_symbols)
        vars_list = list(free_syms)
        vars_list.sort(key=lambda sym: sym.name)

        # Convert expressions to exponent vectors (representing monomials)
        def to_vectors(exprs):
            vecs = []
            for expr in exprs:
                powers = expr.as_powers_dict()
                vec = []
                for sym in vars_list:
                    p_val = powers.get(sym, 0)
                    if not p_val.is_integer:
                        raise ValueError("Fractional powers not supported in this representation")
                    vec.append(int(p_val))
                vecs.append(tuple(vec))
            return vecs

        K_gens = to_vectors(K_exprs)
        E_gens = to_vectors(E_exprs)
        L_gens = to_vectors(L_exprs)

        # H1: E and L are contained in a common overfield
        # By definition of our representation (rational functions in shared variables), this is True.
        h1 = True

        # Helper to check if a vector is in the Z-span of a list of vectors
        def in_Z_span(vec, gens):
            if not vec:
                return True
            if not gens:
                return all(val == 0 for val in vec)
            M = Matrix(gens).T
            v_col = Matrix(vec)
            try:
                sol, params = M.gauss_jordan_solve(v_col)
                if not params:
                    return all(val.is_integer for val in sol)
                
                # If there are free variables, search a small grid for an integer solution
                search_range = range(-5, 6) if len(params) <= 2 else range(-2, 3)
                if len(params) > 4:
                    search_range = range(-1, 2)
                    
                for vals in itertools.product(search_range, repeat=len(params)):
                    sub_dict = dict(zip(params, vals))
                    sol_sub = sol.subs(sub_dict)
                    if all(val.is_integer for val in sol_sub):
                        return True
                return False
            except Exception:
                return False

        # H2: E is a purely inseparable extension of K
        # 1. K is a subfield of E
        k_in_e = all(in_Z_span(vec, E_gens) for vec in K_gens)
        
        # 2. E is purely inseparable over K
        e_pure_insep_k = True
        for e in E_gens:
            found = False
            for n in range(10):  # Check up to p^9
                pn_e = [val * (p**n) for val in e]
                if in_Z_span(pn_e, K_gens):
                    found = True
                    break
            if not found:
                e_pure_insep_k = False
                break
        h2 = k_in_e and e_pure_insep_k

        # neg_Q: The compositum field EL is NOT a purely inseparable extension of L
        # EL is generated by E_gens U L_gens. L_gens are trivially purely inseparable over L.
        # We check if there is some generator in E_gens that is NOT purely inseparable over L.
        el_not_pure_insep_l = False
        for e in E_gens:
            is_pure_insep = False
            for n in range(10):
                pn_e = [val * (p**n) for val in e]
                if in_Z_span(pn_e, L_gens):
                    is_pure_insep = True
                    break
            if not is_pure_insep:
                el_not_pure_insep_l = True
                break
        neg_q = el_not_pure_insep_l

        return [h1, h2, neg_q]

    except Exception:
        return [False, False, False]

