def conditions(witness):
    """
    Checks if the witness is a counterexample to the false conjecture.
    The witness is expected to be a sympy.Poly object representing f(x).
    """
    # H_1: f(x) is an irreducible polynomial of prime degree p
    try:
        p = witness.degree()
        H1 = bool(isprime(p) and witness.is_irreducible)
    except Exception:
        H1 = False

    # H_2: The Galois group Gal(L/K) is a solvable group
    try:
        if witness.domain.is_QQ:
            G = witness.galois_group()
            H2 = bool(G.is_solvable)
        else:
            # For non-QQ domains (e.g., function fields over finite fields):
            # If the derivative is 0, the polynomial is purely inseparable.
            # The Galois group of a purely inseparable extension is trivial, hence solvable.
            # If it's separable over a finite field, its Galois group is cyclic, hence solvable.
            H2 = True
    except Exception:
        H2 = False

    # ¬Q: The Galois group does NOT act as a subgroup of AGL(1, p) 
    #     OR some non-identity element fixes > 1 root.
    try:
        p = witness.degree()
        diff_poly = witness.diff()
        is_insep = getattr(diff_poly, 'is_zero', diff_poly == 0)
        
        if is_insep:
            # An inseparable irreducible polynomial of degree p has exactly 1 distinct root.
            # The Galois group acts on this 1 root.
            # AGL(1, p) acts on p roots. Since p is prime, p >= 2.
            # An action on 1 root cannot be permutation isomorphic to a subgroup of AGL(1, p).
            # Thus, the conclusion fails.
            neg_Q = True
        else:
            if witness.domain.is_QQ:
                G = witness.galois_group()
                acts_as_AGL = True
                for g in G.elements:
                    if g.is_Identity:
                        continue
                    # Count fixed roots (points) for the permutation
                    fixed = sum(1 for i in range(p) if g(i) == i)
                    if fixed > 1:
                        acts_as_AGL = False
                        break
                neg_Q = not acts_as_AGL
            else:
                # For separable polynomials over finite fields, the Galois group is cyclic of order p,
                # generated by a p-cycle which fixes 0 roots. It acts as a subgroup of AGL(1, p).
                neg_Q = False
    except Exception:
        neg_Q = False

    return [H1, H2, neg_Q]

