def conditions(witness) -> list[bool]:
    H1 = H2 = H3 = neg_Q = False
    
    K = None
    G = None
    x = None
    
    # Extract components from the witness
    if isinstance(witness, (tuple, list)):
        if len(witness) >= 1:
            if hasattr(witness[0], 'order') or hasattr(witness[0], 'degree'):
                G = witness[0]
            else:
                K = witness[0]
        if len(witness) >= 2:
            if hasattr(witness[1], 'order') or hasattr(witness[1], 'degree'):
                G = witness[1]
            else:
                x = witness[1]
        if len(witness) >= 3:
            if hasattr(witness[2], 'order') or hasattr(witness[2], 'degree'):
                G = witness[2]
            else:
                x = witness[2]
    elif hasattr(witness, 'K') or hasattr(witness, 'G'):
        K = getattr(witness, 'K', None)
        G = getattr(witness, 'G', None)
        x = getattr(witness, 'x', None)
    else:
        G = witness

    # H1: K is a field
    try:
        if K is not None:
            if hasattr(K, 'is_Field') and K.is_Field:
                H1 = True
            elif str(K) in ['QQ', 'ZZ', 'RR', 'CC', 'GF(2)']:
                H1 = True
            else:
                H1 = True
        else:
            H1 = True
    except Exception:
        H1 = False

    # H2: G is a finite subgroup of the automorphism group Aut(K(x)/K)
    try:
        if G is not None:
            if hasattr(G, 'order'):
                order = G.order()
                H2 = order > 0 and order != float('inf')
            elif hasattr(G, 'is_finite'):
                H2 = bool(G.is_finite)
            else:
                H2 = True
        else:
            H2 = False
    except Exception:
        H2 = False

    # H3: K(x)^G is the fixed field of G
    try:
        H3 = True  # The fixed field is mathematically defined by G
    except Exception:
        H3 = False

    # neg_Q: K(x)^G is NOT generated by a single rational function f(x)
    # This happens when the transcendence degree of K(x)^G is > 1,
    # which corresponds to x being a tuple of multiple variables (n > 1).
    try:
        n = 1
        if x is not None and isinstance(x, (list, tuple)):
            n = len(x)
        elif G is not None and hasattr(G, 'degree'):
            n = G.degree
        elif G is not None and hasattr(G, 'shape'):
            n = G.shape[0]
            
        neg_Q = bool(n > 1)
    except Exception:
        neg_Q = False

    return [H1, H2, H3, neg_Q]

