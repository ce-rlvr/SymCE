def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "Every field extension is a normal extension."
    
    We interpret the witness as an irreducible polynomial over QQ defining the extension Q(alpha)/Q.
    """
    # H_1: K/F is a field extension
    try:
        p = Poly(witness, x, domain='QQ')
        # A valid field extension Q(alpha)/Q of degree > 1 requires an irreducible polynomial of degree >= 2
        h1 = p.degree() >= 2 and p.is_irreducible
    except Exception:
        h1 = False

    # ¬Q: K/F is NOT a normal extension
    try:
        p = Poly(witness, x, domain='QQ')
        deg = p.degree()
        if deg < 2:
            neg_q = False
        else:
            rr = real_roots(p)
            # If an irreducible polynomial has both real and non-real roots, 
            # its splitting field cannot be generated by a single real root.
            # Thus, the extension Q(alpha)/Q for a real root alpha is not normal.
            if 0 < len(rr) < deg:
                neg_q = True
            else:
                # If all roots are real or all are complex, we check if it splits completely 
                # over the field generated by one of its roots.
                if deg <= 5:
                    r0 = RootOf(p, 0)
                    facs = factor_list(p.as_expr(), extension=r0)
                    neg_q = False
                    for fac, mult in facs[1]:
                        if Poly(fac, x).degree() > 1:
                            neg_q = True
                            break
                else:
                    # Fallback for higher degrees to avoid timeouts
                    neg_q = False
    except Exception:
        neg_q = False

    return [bool(h1), bool(neg_q)]

