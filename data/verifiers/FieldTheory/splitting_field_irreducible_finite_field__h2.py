def conditions(witness):
    try:
        q, f = witness
    except Exception:
        return [False, False]
    
    # H_1: F is a finite field of order q (and f is a valid polynomial over F)
    h1_ok = False
    try:
        if isinstance(q, int) and q >= 2:
            factors_q = factorint(q)
            if len(factors_q) == 1:
                p = list(factors_q.keys())[0]
                
                # Check if f can be interpreted as a polynomial over GF(p)
                f_mod_p = Poly(f, x, modulus=p)
                n = f_mod_p.degree()
                if n >= 1:
                    h1_ok = True
    except Exception:
        h1_ok = False

    # neg_Q: The conclusion fails
    neg_q_ok = False
    try:
        if h1_ok:
            factors_q = factorint(q)
            p = list(factors_q.keys())[0]
            k = factors_q[p]
            
            f_mod_p = Poly(f, x, modulus=p)
            n = f_mod_p.degree()
            
            # Factor f(x) over GF(p)
            _, factor_list_p = factor_list(f, x, modulus=p)
            
            # Degrees of irreducible factors over GF(p)
            D_list = [Poly(fac, x).degree() for fac, mult in factor_list_p]
            
            def lcm(a, b):
                return abs(a * b) // math.gcd(a, b)
            
            # Degree of the splitting field of f over GF(p)
            M = 1
            for D in D_list:
                M = lcm(M, D)
                
            # Degree of the splitting field of f over GF(q)
            m = lcm(M, k) // k
            
            # Degrees of the fields generated by a single root of each irreducible factor over GF(q)
            d_list = [lcm(D, k) // k for D in D_list]
            
            # The conclusion states:
            # 1. The splitting field over GF(q) has order q^n (i.e., degree m == n)
            # 2. It is generated by ANY single root (i.e., every root generates a field of degree m, so all d == m)
            q_holds = (m == n) and all(d == m for d in d_list)
            
            neg_q_ok = not q_holds
    except Exception:
        neg_q_ok = False

    return [h1_ok, neg_q_ok]

