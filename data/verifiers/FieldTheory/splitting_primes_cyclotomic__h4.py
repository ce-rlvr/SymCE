def conditions(witness):
    try:
        p, q = witness
    except Exception:
        return [False, False, False, False]
        
    # H1: p is an odd prime number
    try:
        h1 = bool(sympy.isprime(p) and p % 2 != 0)
    except Exception:
        h1 = False
        
    # H2: q is a prime number
    try:
        h2 = bool(sympy.isprime(q))
    except Exception:
        h2 = False
        
    # H3: q is distinct from p
    try:
        h3 = bool(q != p)
    except Exception:
        h3 = False
        
    # neg_Q: The ideal generated by q in the ring of integers of ℚ(ζ_p) 
    # splits completely into p-1 distinct prime ideals if and only if q ≡ 1 (mod p).
    # We evaluate the negation of this equivalence.
    try:
        # The splitting of q in Z[ζ_p] corresponds to the factorization of the 
        # p-th cyclotomic polynomial modulo q.
        poly = sympy.cyclotomic_poly(p, x)
        factors = sympy.factor_list(poly, modulus=q)[1]
        
        # A: splits completely into p-1 distinct prime ideals
        # This occurs if and only if there are exactly p-1 distinct factors.
        A = (int(len(factors)) == int(p - 1))
        
        # B: q ≡ 1 (mod p)
        B = (int(q % p) == 1)
        
        # The conclusion is A == B. The negated conclusion is A != B.
        neg_q = bool(A != B)
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

