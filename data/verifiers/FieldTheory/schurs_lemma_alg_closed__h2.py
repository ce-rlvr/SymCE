def conditions(witness):
    """
    Checks if the witness satisfies the remaining hypotheses and fails the conclusion.
    witness can be a tuple (K, G_matrices, phi) or a dict with these keys.
    """
    try:
        if isinstance(witness, dict):
            K = witness.get('K', 'C')
            G_matrices = witness.get('G_matrices', [])
            phi = witness.get('phi', eye(1))
        else:
            K, G_matrices, phi = witness
    except Exception:
        return [False, False, False, False]
        
    # H1: K is an algebraically closed field
    try:
        h1 = str(K) in ['C', 'CC', 'Complexes', 'S.Complexes', 'algebraically_closed'] or K == sympy.CC
    except Exception:
        h1 = False
        
    # H2: V is a finite-dimensional irreducible representation of G over K
    try:
        if isinstance(G_matrices, dict):
            G_mats = list(G_matrices.values())
        else:
            G_mats = list(G_matrices)
            
        n = phi.rows
        if n == 0 or phi.cols != n:
            h2 = False
        else:
            valid = all(isinstance(m, Matrix) and m.rows == n and m.cols == n for m in G_mats)
            if not valid:
                h2 = False
            else:
                # Check irreducibility using Burnside's Theorem:
                # The algebra generated by G_mats must be the full matrix algebra M_n(K)
                def to_vec(mat):
                    return list(mat)
                
                basis_vecs = [to_vec(eye(n))]
                basis_mats = [eye(n)]
                head = 0
                
                while head < len(basis_mats) and len(basis_mats) < n * n:
                    b = basis_mats[head]
                    for m in G_mats:
                        new_mat = b * m
                        new_vec = to_vec(new_mat)
                        mat_to_check = Matrix(basis_vecs + [new_vec])
                        if mat_to_check.rank() > len(basis_vecs):
                            basis_vecs.append(new_vec)
                            basis_mats.append(new_mat)
                            if len(basis_mats) == n * n:
                                break
                    head += 1
                    
                h2 = (len(basis_mats) == n * n)
    except Exception:
        h2 = False
        
    # H3: phi is a G-equivariant K-linear map from V to V
    try:
        n = phi.rows
        if phi.cols != n:
            h3 = False
        else:
            h3 = True
            for m in G_mats:
                diff = phi * m - m * phi
                if diff != zeros(n, n):
                    if not all(sympy.simplify(diff[i, j]) == 0 for i in range(n) for j in range(n)):
                        h3 = False
                        break
    except Exception:
        h3 = False
        
    # neg_Q: phi is NOT a scalar multiple of the identity map
    try:
        n = phi.rows
        if n == 0:
            is_scalar = True
        else:
            c = phi[0, 0]
            diff = phi - c * eye(n)
            if diff == zeros(n, n):
                is_scalar = True
            else:
                is_scalar = all(sympy.simplify(diff[i, j]) == 0 for i in range(n) for j in range(n))
        neg_q = not is_scalar
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

