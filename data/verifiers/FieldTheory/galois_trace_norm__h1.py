def in_field(val, gens, X):
    """
    Checks if `val` belongs to the field generated by `gens` over QQ.
    """
    def get_deg(p):
        if hasattr(p, 'degree') and callable(p.degree):
            try:
                return p.degree()
            except Exception:
                pass
        return degree(p, X)

    if not gens:
        mp = minpoly(val, X)
        return get_deg(mp) == 1
        
    gamma, mp_base = primitive_element(gens, X)
    deg_base = get_deg(mp_base)
    
    gamma_val, mp_val = primitive_element(gens + [val], X)
    deg_val = get_deg(mp_val)
    
    return deg_base == deg_val

def conditions(witness):
    """
    witness is expected to be a tuple: (theta, K_gens_X, G_images_X, alpha_X)
    where:
      - theta: a SymPy algebraic number generating L over QQ.
      - K_gens_X: a list of SymPy expressions in X generating K over QQ.
      - G_images_X: a list of SymPy expressions in X representing the images of theta under G.
      - alpha_X: a SymPy expression in X representing the element alpha in L.
    """
    try:
        theta, K_gens_X, G_images_X, alpha_X = witness
    except Exception:
        return [False, False, False]

    # H_1: G is the Galois group of L over K
    h1 = False
    try:
        mp_X = minpoly(theta, X)
        factored = factor(mp_X, extension=theta)
        if factored.is_Mul:
            factors = factored.args
        else:
            factors = [factored]
            
        roots_theta = []
        for f in factors:
            if f.is_Pow:
                f = f.base
            p = f.as_poly(X)
            if p and p.degree() == 1:
                coeffs = p.coeffs()
                root = -coeffs[1] / coeffs[0]
                roots_theta.append(root)
                
        automorphisms_theta = []
        for r_theta in roots_theta:
            fixes_K = True
            for k_X in K_gens_X:
                val = k_X.subs(X, theta)
                img = k_X.subs(X, r_theta)
                if simplify(val - img) != 0:
                    fixes_K = False
                    break
            if fixes_K:
                automorphisms_theta.append(r_theta)
                
        G_images_theta = [img_X.subs(X, theta) for img_X in G_images_X]
        
        if len(G_images_theta) == len(automorphisms_theta) and len(G_images_theta) > 0:
            matched_indices = set()
            is_match = True
            for g in G_images_theta:
                matched = False
                for i, a in enumerate(automorphisms_theta):
                    if i not in matched_indices and simplify(g - a) == 0:
                        matched = True
                        matched_indices.add(i)
                        break
                if not matched:
                    is_match = False
                    break
            h1 = is_match
    except Exception:
        h1 = False

    # H_2: alpha is an element of L
    h2 = False
    try:
        alpha_val = alpha_X.subs(X, theta)
        if not alpha_val.has(sympy.oo, sympy.nan, sympy.zoo):
            h2 = in_field(alpha_val, [theta], X)
    except Exception:
        h2 = False

    # ¬Q: Trace or Norm does not belong to K
    neg_q = False
    try:
        Trace = 0
        Norm = 1
        for img_X in G_images_X:
            sigma_alpha = alpha_X.subs(X, img_X).subs(X, theta)
            Trace += sigma_alpha
            Norm *= sigma_alpha
            
        Trace = simplify(Trace)
        Norm = simplify(Norm)
        
        K_gens_vals = [k_X.subs(X, theta) for k_X in K_gens_X]
        
        trace_in_K = in_field(Trace, K_gens_vals, X)
        norm_in_K = in_field(Norm, K_gens_vals, X)
        
        neg_q = not (trace_in_K and norm_in_K)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]