def get_deg_disc(K):
    """
    Helper function to extract the degree and the absolute value of the discriminant 
    of the number field K.
    """
    if K is None:
        return None, None
    
    x = Symbol('x')
    
    # Handle Q represented as a string or SymPy QQ object
    if isinstance(K, str):
        if K in ["Q", "QQ"]:
            return 1, 1
    if K == sympy.QQ:
        return 1, 1
        
    # Handle SymPy AlgebraicField
    try:
        if hasattr(K, 'ext') and hasattr(K.ext, 'minpoly'):
            p_poly = Poly(K.ext.minpoly, x)
            return p_poly.degree(), abs(discriminant(p_poly))
    except Exception:
        pass
        
    # Handle SymPy NumberField
    try:
        if hasattr(K, 'minpoly'):
            p_poly = Poly(K.minpoly, x)
            return p_poly.degree(), abs(discriminant(p_poly))
    except Exception:
        pass

    # Handle K given directly as a minimal polynomial expression or list of coefficients
    try:
        p_poly = Poly(K, x)
        return p_poly.degree(), abs(discriminant(p_poly))
    except Exception:
        pass
        
    return None, None

def conditions(witness):
    """
    Given a witness, checks if it satisfies the remaining hypotheses and falsifies the conclusion.
    The witness is expected to be a tuple (p, k, K) where K is the field.
    If K is omitted, it is treated as a free variable, meaning the conclusion fails.
    """
    try:
        if isinstance(witness, tuple):
            if len(witness) == 3:
                p, k, K = witness
            elif len(witness) == 2:
                p, k = witness
                K = None
            else:
                return [False, False, False]
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]
        
    # H_1: p is a prime number
    try:
        h1_ok = bool(isprime(p))
    except Exception:
        h1_ok = False
        
    # H_2: k is a positive integer
    try:
        h2_ok = isinstance(k, int) and k > 0
    except Exception:
        h2_ok = False
        
    # neg_Q: The different ideal of K is NOT generated by the given element.
    # The conclusion is true if and only if K is the cyclotomic field Q(zeta_{p^k}).
    # We verify this by checking if the degree and discriminant of K match Q(zeta_{p^k}).
    try:
        deg, disc = get_deg_disc(K)
        if deg is None or disc is None:
            neg_q_ok = True
        else:
            expected_deg = (p**(k - 1)) * (p - 1)
            expected_disc = p**(p**(k - 1) * (p * k - k - 1))
            
            if deg == expected_deg and disc == expected_disc:
                neg_q_ok = False
            else:
                neg_q_ok = True
    except Exception:
        neg_q_ok = True
        
    return [h1_ok, h2_ok, neg_q_ok]

