import sympy as sp
from sympy.abc import x

# Top-level setup
QQ = sp.QQ

def conditions(witness):
    """
    Given a witness, checks if it is a valid counterexample to the false conjecture.
    The witness is expected to be a tuple (p, a) or (F, p, a) where F is implicitly QQ.
    """
    try:
        if isinstance(witness, tuple):
            if len(witness) == 3:
                F, p, a = witness
            elif len(witness) == 2:
                p, a = witness
            else:
                return [False, False, False, False]
        else:
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]

    # H_1: p is prime
    try:
        h1 = bool(sp.isprime(p))
    except Exception:
        h1 = False

    # H_2: a is rational
    try:
        a_rat = sp.Rational(a)
        h2 = True
    except Exception:
        h2 = False

    # H_3: x**p - x - a has no root in Q
    try:
        if h1 and h2:
            poly = x**p - x - a_rat
            rts = sp.roots(poly, x, domain='QQ')
            h3 = (len(rts) == 0)
        else:
            h3 = False
    except Exception:
        h3 = False

    # neg_Q: The splitting field does NOT have degree p OR is NOT generated by a single root
    try:
        if not (h1 and h2 and h3):
            neg_q = False
        else:
            poly = x**p - x - a_rat
            
            # Check if reducible over QQ
            factors = sp.factor_list(poly, x, domain='QQ')[1]
            if len(factors) > 1 or factors[0][1] > 1:
                # Reducible over QQ. Since p is prime, splitting field degree cannot be p.
                neg_q = True
            elif p == 2:
                # Irreducible degree 2 polynomial always has splitting field of degree 2
                # generated by a single root. Conclusion holds.
                neg_q = False
            else:
                # p is odd prime, poly is irreducible
                # Discriminant of x^p - x - a
                disc = ((-1)**(p*(p-1)//2)) * ( (p**p) * (a_rat**(p-1)) - ((p-1)**(p-1)) )
                s = sp.sqrt(disc)
                if not s.is_Rational:
                    # Discriminant not a square -> Galois group not in A_p -> not C_p
                    # Splitting field degree is strictly greater than p.
                    neg_q = True
                elif p == 3:
                    # For p=3, irreducible and disc is square => Galois group is C_3
                    # Splitting field degree is exactly 3. Conclusion holds.
                    neg_q = False
                else:
                    # Fallback for p >= 5 with square discriminant
                    r = sp.RootOf(poly, 0)
                    _, ext_factors = sp.factor_list(poly, extension=r)
                    splits_completely = all(sp.degree(f, x) == 1 for f, _ in ext_factors)
                    
                    from sympy.polys.numberfields import minpoly
                    deg_ext = sp.degree(minpoly(r, x), x)
                    
                    conclusion = splits_completely and (deg_ext == p)
                    neg_q = not conclusion
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

