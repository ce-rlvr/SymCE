NEG_Q_INDEX = 3

def conditions(witness) -> list[bool]:
    """
    Given a witness tuple (E, F, X, S, K), checks if it is a valid counterexample.
    E: The field E
    F: The base field F
    X: List of variables [x_1, ..., x_n]
    S: List of symmetric polynomials [s_1, ..., s_n]
    K: The subfield K
    """
    try:
        E, F, X, S, K = witness
    except Exception:
        return [False, False, False, False]

    n = len(X)

    # H_1: E = F(x_1, ..., x_n) is the field of rational functions in n variables over F
    try:
        h1_ok = hasattr(E, 'is_RationalField') and E.is_RationalField and E.domain == F and list(E.symbols) == list(X)
    except Exception:
        h1_ok = False

    # H_2: s_1, ..., s_n are the elementary symmetric polynomials in the variables x_1, ..., x_n
    try:
        h2_ok = True
        if len(S) != n:
            h2_ok = False
        else:
            t = sympy.Symbol('t')
            poly = sympy.Poly(sympy.prod([t - x for x in X]), t)
            coeffs = poly.all_coeffs()
            expected_S = [(-1)**(i) * coeffs[i] for i in range(1, n + 1)]
            
            for s_val, expected_s in zip(S, expected_S):
                if sympy.simplify(s_val - expected_s) != 0:
                    h2_ok = False
                    break
    except Exception:
        h2_ok = False

    # H_3: K = F(s_1, ..., s_n) is the subfield of E generated by the elementary symmetric polynomials
    try:
        h3_ok = hasattr(K, 'is_RationalField') and K.domain == F and list(K.symbols) == list(S)
    except Exception:
        h3_ok = False

    # ¬Q: E is not a finite Galois extension of K, or Gal(E/K) is not isomorphic to S_n
    try:
        import math
        expected_degree = math.factorial(n)
        is_field = getattr(F, 'is_Field', False)
        
        # The conclusion fails if F is not a field (so E/K is not a standard Galois extension of fields),
        # or if the degree is not n! (e.g., n=0 where S_0 is not S_n in standard terms).
        neg_q = not is_field or (expected_degree == 0)
    except Exception:
        neg_q = False

    return [h1_ok, h2_ok, h3_ok, neg_q]