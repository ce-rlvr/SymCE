import sympy
from sympy import Poly, factor_list
from sympy.ntheory import isprime

# Top-level setup: named object bindings that the witness expression may reference.
x, t = sympy.symbols('x t')

def conditions(witness) -> list[bool]:
    """
    Checks whether the given witness is a valid counterexample to the false conjecture:
    "Every algebraic extension of a field is separable."
    (The dropped hypothesis is that the base field is perfect).
    
    The witness is expected to be a dictionary representing a field extension E = F_p(t)[x]/(poly),
    where F = F_p(t) is the base field.
    Format:
    {
        'poly': <SymPy expression in gen and base_gen>,
        'char': <prime integer p>,
        'gen': <SymPy symbol for the extension generator, e.g., x>,
        'base_gen': <SymPy symbol for the transcendental element in the base field, e.g., t>
    }
    """
    try:
        poly_expr = witness.get('poly')
        p = witness.get('char')
        gen = witness.get('gen')
        base_gen = witness.get('base_gen')
        
        if poly_expr is None or p is None or gen is None or base_gen is None:
            return [False, False, False]
            
        if not isprime(p):
            return [False, False, False]
            
        # Ensure no extra variables are present in the polynomial
        if set(poly_expr.free_symbols) - {gen, base_gen}:
            return [False, False, False]
            
        poly_x = Poly(poly_expr, gen)
        deg = poly_x.degree()
        
        # H1: E is a field extension of F.
        # This requires poly_expr to be irreducible over F_p(base_gen).
        # We check if it is monic in `gen` mod p, and then check irreducibility in F_p[gen, base_gen].
        lc = poly_x.LC()
        try:
            lc_val = int(lc)
            is_monic = (lc_val % p == 1)
        except TypeError:
            is_monic = False
            
        if not is_monic:
            h1 = False
        else:
            facs = factor_list(poly_expr, modulus=p)
            # facs[1] is a list of (factor, multiplicity)
            # It is irreducible if there is exactly one factor and its multiplicity is 1
            h1 = (len(facs[1]) == 1 and facs[1][0][1] == 1)
            
        # H2: The extension E/F is algebraic.
        # Any finite degree extension generated by a root of a polynomial is algebraic.
        h2 = (deg >= 1)
        
        # ¬Q: The extension E/F is NOT separable.
        # An algebraic extension is inseparable iff the minimal polynomial has a zero formal derivative mod p.
        deriv = sympy.diff(poly_expr, gen)
        deriv_poly = Poly(deriv, gen, base_gen)
        coeffs = deriv_poly.coeffs()
        
        if not coeffs:
            neg_q = True
        else:
            try:
                neg_q = all(int(c) % p == 0 for c in coeffs)
            except TypeError:
                neg_q = False
                
        return [bool(h1), bool(h2), bool(neg_q)]
    except Exception:
        return [False, False, False]

