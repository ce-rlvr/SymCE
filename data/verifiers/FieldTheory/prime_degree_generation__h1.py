def conditions(witness):
    # 1. Witness is an integer n, representing K = Q[x]/(x^n) and alpha = x
    try:
        if isinstance(witness, int):
            n = witness
            h1 = sp.isprime(n)
            h2 = n > 1
            neg_q = True
            return [bool(h1), bool(h2), bool(neg_q)]
    except Exception:
        pass

    # 2. Witness is a tuple (n, k) representing K = Q[x]/(x^n) and alpha = x^k
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            if isinstance(witness[0], int) and isinstance(witness[1], int):
                n, k = witness
                h1 = sp.isprime(n)
                h2 = 0 < k < n
                neg_q = True
                return [bool(h1), bool(h2), bool(neg_q)]
    except Exception:
        pass

    # 3. Witness is a tuple of lists (minpoly_coeffs, alpha_coeffs)
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            if isinstance(witness[0], list) and isinstance(witness[1], list):
                x_sym = sp.Symbol('x')
                min_poly = sp.Poly.from_list(witness[0], gens=x_sym)
                alpha_poly = sp.Poly.from_list(witness[1], gens=x_sym)
                
                n = min_poly.degree()
                h1 = sp.isprime(n)
                
                alpha_mod = alpha_poly % min_poly
                h2 = alpha_mod.degree() > 0
                
                is_field = min_poly.is_irreducible
                
                vecs = []
                curr = sp.Poly(1, x_sym)
                for _ in range(n):
                    coeffs = curr.all_coeffs()
                    coeffs = [0]*(n - len(coeffs)) + coeffs
                    vecs.append(coeffs)
                    curr = (curr * alpha_poly) % min_poly
                    
                M = sp.Matrix(vecs)
                dim = M.rank()
                
                neg_q = (not is_field) or (dim < n)
                return [bool(h1), bool(h2), bool(neg_q)]
    except Exception:
        pass

    # 4. Witness is a matrix representing alpha, and F is the base field.
    try:
        if isinstance(witness, sp.Matrix):
            alpha = witness
            n = alpha.shape[0]
            h1 = sp.isprime(n)
            
            I = sp.eye(n)
            is_scalar = False
            if alpha == alpha[0,0] * I:
                is_scalar = True
            h2 = not is_scalar
            
            x_sym = sp.Symbol('x')
            if hasattr(alpha, 'minimal_polynomial'):
                minpoly = alpha.minimal_polynomial(x_sym)
            else:
                minpoly = alpha.charpoly(x_sym).as_expr()
            is_field = sp.Poly(minpoly, x_sym).is_irreducible
            
            vecs = []
            curr = I
            for _ in range(n):
                vecs.append(list(curr))
                curr = curr * alpha
            
            M = sp.Matrix(vecs)
            dim = M.rank()
            
            neg_q = (not is_field) or (dim < n)
            return [bool(h1), bool(h2), bool(neg_q)]
    except Exception:
        pass

    return [False, False, False]