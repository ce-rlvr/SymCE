import sympy
from sympy import Poly, roots, QQ, I, Rational, Integer
from sympy.abc import x, y, z

def is_real_expr(r):
    r = sympy.sympify(r)
    if r.is_real:
        return True
    try:
        return sympy.simplify(sympy.im(r)) == 0
    except Exception:
        return False

def same_field(gens1, gens2):
    try:
        F1 = QQ.algebraic_field(*gens1)
        F2 = QQ.algebraic_field(*gens2)
        if F1 == F2:
            return True
        
        pe1 = F1.ext.orig_ext if hasattr(F1, 'ext') else None
        pe2 = F2.ext.orig_ext if hasattr(F2, 'ext') else None
        
        if pe1 is None and pe2 is None:
            return True
        if pe1 is None or pe2 is None:
            return False
            
        # Check if pe2 is in F1 and pe1 is in F2
        F1.from_expr(pe2)
        F2.from_expr(pe1)
        return True
    except Exception:
        return False

def conditions(witness):
    """
    witness should be a dictionary with:
      - 'f': a sympy expression representing the polynomial f(x)
      - 'K': a list of sympy expressions representing the generators of the splitting field K over Q
    """
    try:
        f = witness['f']
        K_gens = witness['K']
        if not isinstance(K_gens, (list, tuple, set)):
            K_gens = [K_gens]
        else:
            K_gens = list(K_gens)
            
        free_syms = f.free_symbols
        if len(free_syms) == 1:
            var = list(free_syms)[0]
        else:
            var = x
    except Exception:
        return [False, False, False]
    
    # H1: All roots of f(x) in C are real numbers
    h1 = False
    try:
        f_poly = Poly(f, var)
        rts = roots(f_poly)
        # Check if we found all roots (sum of multiplicities equals degree)
        if sum(rts.values()) == f_poly.degree():
            h1 = all(is_real_expr(r) for r in rts.keys())
    except Exception:
        h1 = False

    # H2: K is the splitting field of f(x) over Q viewed as a subfield of C
    h2 = False
    try:
        f_poly = Poly(f, var)
        rts = roots(f_poly)
        if sum(rts.values()) == f_poly.degree():
            # The splitting field over Q is generated by the roots AND the coefficients
            req_elements = list(rts.keys()) + f_poly.coeffs()
            h2 = same_field(req_elements, K_gens)
    except Exception:
        h2 = False

    # neg_Q: K is NOT a subfield of R
    # K is a subfield of R iff all its generators over Q are real numbers
    neg_q = False
    try:
        is_subfield_of_R = all(is_real_expr(g) for g in K_gens)
        neg_q = not is_subfield_of_R
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

