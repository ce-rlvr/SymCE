import sympy
from sympy import QQ, GF

# Top-level setup
# The witness should be a tuple: (n, F, a)
# where n is a positive integer, F is a field (e.g., QQ or GF(p)), and a is a non-zero element.

def conditions(witness) -> list[bool]:
    try:
        n, F, a = witness
    except Exception:
        return [False, False, False, False]
        
    # H1: n is a positive integer
    try:
        n_val = int(n)
        h1 = (n_val == n) and (n_val > 0)
    except Exception:
        h1 = False
        
    char = None
    # H2: F is a field whose characteristic does not divide n
    try:
        if F == QQ:
            char = 0
            h2 = True
        elif hasattr(F, 'characteristic'):
            char = F.characteristic
            h2 = (char != 0) and (n_val % char != 0)
        else:
            try:
                char = int(F)
                if char == 0:
                    h2 = True
                else:
                    from sympy import isprime
                    h2 = isprime(char) and (n_val % char != 0)
            except Exception:
                h2 = False
    except Exception:
        h2 = False
        
    # H3: a is a non-zero element in F
    try:
        if char is None:
            h3 = False
        elif char == 0:
            h3 = (a != 0)
        else:
            val = int(a)
            h3 = (val % char != 0)
    except Exception:
        h3 = False
        
    # neg_Q: The splitting field of x^n - a over F has degree d over F, 
    # where d is a divisor of n, and its Galois group over F is cyclic.
    # We need neg_Q to be True if this conclusion FAILS.
    try:
        if not (h1 and h2 and h3):
            neg_q = False
        else:
            from sympy import Symbol, factor_list, lcm, root, exp, I, pi
            from sympy.polys.numberfields import primitive_element
            x = Symbol('x')
            
            if char > 0:
                # For finite fields, the Galois group is always cyclic.
                # The degree of the splitting field is the LCM of the degrees of the irreducible factors.
                val = int(a)
                factors = factor_list(x**n_val - val, modulus=char)
                d = 1
                for poly, exp_pow in factors[1]:
                    d = lcm(d, poly.degree())
                conclusion_holds = (n_val % d == 0)
            else:
                # For QQ, the splitting field is generated by a**(1/n) and exp(2*I*pi/n).
                exts = [root(a, n_val), exp(2*I*pi/n_val)]
                minpoly, _ = primitive_element(exts, x)
                d = minpoly.degree()
                
                if n_val % d != 0:
                    conclusion_holds = False
                else:
                    # If d divides n, we conservatively assume the conclusion holds (Galois group is cyclic)
                    # to avoid false positives in neg_Q. A valid counterexample should fail the degree check
                    # or use a finite field.
                    conclusion_holds = True
                    
            neg_q = not conclusion_holds
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

