import sympy
from sympy import solve, pi, I
from sympy.abc import x, y, t
import sympy.polys.domains as domains

class AlgebraicClosure:
    """
    A mock class to represent the algebraic closure of a field,
    which is infinite-dimensional over the base field (e.g., QQ).
    """
    def __init__(self, base_field):
        self.base_field = base_field
        self.is_Field = True

    def __eq__(self, other):
        return isinstance(other, AlgebraicClosure) and self.base_field == other.base_field

    def __str__(self):
        return f"AlgebraicClosure({self.base_field})"

def domains_equal(D1, D2):
    if D1 == D2:
        return True
    if D1 == sympy.S.Rationals and D2 == domains.QQ:
        return True
    if D2 == sympy.S.Rationals and D1 == domains.QQ:
        return True
    if D1 == sympy.S.Reals and D2 == domains.RR:
        return True
    if D2 == sympy.S.Reals and D1 == domains.RR:
        return True
    if D1 == sympy.S.Complexes and D2 == domains.CC:
        return True
    if D2 == sympy.S.Complexes and D1 == domains.CC:
        return True
    return False

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "If F is a field and E is a splitting field of f(x) over F, then E is finite-dimensional over F."
    (The dropped hypothesis is that f(x) is a non-zero polynomial, or that f(x) has coefficients in F).
    
    Expected witness format: (F, E, f)
    Example 1: (QQ, QQ.frac_field(pi), x - pi)
    Example 2: (QQ, AlgebraicClosure(QQ), 0)
    """
    try:
        F, E, f = witness
    except Exception:
        return [False, False, False]

    # H1: F is a field
    try:
        h1 = False
        if hasattr(F, 'is_Field') and F.is_Field:
            h1 = True
        elif F in [sympy.S.Reals, sympy.S.Complexes, sympy.S.Rationals]:
            h1 = True
        elif F in [domains.QQ, domains.RR, domains.CC]:
            h1 = True
    except Exception:
        h1 = False

    # H2: E is a splitting field of f(x) over F
    try:
        h2 = False
        if f == 0:
            if isinstance(E, AlgebraicClosure) and domains_equal(E.base_field, F):
                h2 = True
        else:
            syms = f.free_symbols
            if len(syms) == 0:
                if domains_equal(E, F):
                    h2 = True
            else:
                gens_syms = set()
                if hasattr(E, 'gens'):
                    for g in E.gens:
                        if isinstance(g, sympy.Basic):
                            gens_syms.update(g.free_symbols)
                
                # Identify the variable of the polynomial (the symbol not in the field generators)
                possible_vars = [s for s in syms if s not in gens_syms]
                if len(possible_vars) == 1:
                    x_var = possible_vars[0]
                    roots = sympy.solve(f, x_var)
                    
                    if hasattr(E, 'domain') and domains_equal(E.domain, F):
                        if hasattr(E, 'gens'):
                            gens_set = set(E.gens)
                            roots_set = set(roots)
                            
                            # Check if E is generated by the roots
                            if gens_set.issubset(roots_set):
                                all_roots_in_E = True
                                for r in roots:
                                    try:
                                        val = E.from_sympy(r)
                                        if val is None:
                                            all_roots_in_E = False
                                            break
                                    except Exception:
                                        all_roots_in_E = False
                                        break
                                if all_roots_in_E:
                                    h2 = True
    except Exception:
        h2 = False

    # neg_Q: E is NOT finite-dimensional over F
    try:
        neg_q = False
        if isinstance(E, AlgebraicClosure):
            neg_q = True
        elif hasattr(E, 'domain') and domains_equal(E.domain, F):
            # Fraction fields represent transcendental extensions, which are infinite-dimensional
            if isinstance(E, domains.FractionField):
                neg_q = True
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

