# Top-level setup
# No specific named objects are required for this field theory verifier,
# as the witness is expected to provide the ring elements and operations.

def conditions(witness) -> list[bool]:
    """
    witness is expected to be a dictionary with:
      'elements': list of all unique elements in the ring L
      'zero': the additive identity
      'one': the multiplicative identity
      'alpha': the element alpha in L
      'sigma': a function representing the automorphism
      'mul': function(x, y) for multiplication
      'add': function(x, y) for addition
      'eq': function(x, y) for equality
    """
    try:
        elements = witness['elements']
        zero = witness['zero']
        one = witness['one']
        alpha = witness['alpha']
        sigma = witness['sigma']
        mul = witness['mul']
        add = witness['add']
        eq = witness['eq']
    except (TypeError, KeyError):
        return [False, False, False]
        
    # H1: G is generated by an automorphism sigma
    try:
        h1 = True
        # Prevent the trivial ring from being used as a vacuous counterexample
        if eq(zero, one):
            h1 = False
            
        # Check if sigma is an automorphism
        for x in elements:
            for y in elements:
                if not eq(sigma(add(x, y)), add(sigma(x), sigma(y))):
                    h1 = False
                if not eq(sigma(mul(x, y)), mul(sigma(x), sigma(y))):
                    h1 = False
        
        # Check bijection
        img = []
        for x in elements:
            sx = sigma(x)
            if any(eq(sx, i) for i in img):
                h1 = False
            img.append(sx)
            
        # Find order of sigma
        def get_cycle_length(x):
            curr = sigma(x)
            length = 1
            while not eq(curr, x) and length <= len(elements):
                curr = sigma(curr)
                length += 1
            return length

        n = 1
        for x in elements:
            l = get_cycle_length(x)
            if l > len(elements):
                h1 = False
                break
            n = (n * l) // math.gcd(n, l)
            
    except Exception:
        h1 = False

    # H2: alpha is an element of L
    try:
        h2 = any(eq(alpha, x) for x in elements)
    except Exception:
        h2 = False

    # Negated Conclusion
    try:
        if not h1:
            neg_q = False
        else:
            # Compute N(alpha)
            norm = alpha
            curr = alpha
            for _ in range(n - 1):
                curr = sigma(curr)
                norm = mul(norm, curr)
                
            norm_is_one = eq(norm, one)
            
            # Check if exists beta != 0 such that alpha = beta / sigma(beta)
            # This implies sigma(beta) must be invertible.
            exists_beta = False
            for beta in elements:
                if not eq(beta, zero):
                    sb = sigma(beta)
                    # check if sb is invertible
                    is_invertible = any(eq(mul(sb, inv), one) for inv in elements)
                    if is_invertible:
                        if eq(mul(alpha, sb), beta):
                            exists_beta = True
                            break
                            
            neg_q = (norm_is_one != exists_beta)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

