def conditions(witness) -> list[bool]:
    # The witness is expected to be a polynomial expression in x, or a tuple (domain, polynomial)
    if isinstance(witness, tuple):
        if len(witness) >= 2:
            f = witness[1]
        else:
            f = witness[0]
    else:
        f = witness
        
    try:
        f_poly = Poly(f, x, domain='QQ')
    except Exception:
        return [False, False, False, False]
        
    try:
        # H_1: K is a field. 
        # We are working over K = QQ, which is a field.
        h1_ok = True
        
        # H_2: L is the splitting field of f(x) over K.
        # This holds by definition as we construct L as the splitting field.
        h2_ok = True
        
        # Find all roots to construct the splitting field
        rts = sympy.roots(f_poly)
        
        # If we cannot find all roots exactly, we cannot reliably verify
        if sum(rts.values()) != f_poly.degree():
            return [False, False, False, False]
            
        irrational_roots = [r for r in rts if not r.is_rational]
        
        if not irrational_roots:
            D = 1
        else:
            # Compute the primitive element of the splitting field
            prim, min_poly = primitive_element(irrational_roots, x, ex=True)
            D = min_poly.degree()
            
        factors = factor_list(f_poly)[1]
        
        # H_3: The Galois group Gal(L/K) is an abelian group.
        # The order of the Galois group is exactly D = [L:QQ].
        # Any group of order <= 5 is abelian.
        # If D > 5, we check if the splitting field is generated by roots of unity and square roots,
        # which guarantees an abelian Galois group.
        all_abelian = True
        for fac, mult in factors:
            if fac.degree() <= 2:
                continue
            is_cyclo = False
            for n in range(1, 60):
                xn_minus_1 = Poly(x**n - 1, x, domain='QQ')
                if xn_minus_1.rem(fac).is_zero:
                    is_cyclo = True
                    break
            if not is_cyclo:
                all_abelian = False
                break
                
        h3_ok = bool((D <= 5) or all_abelian)
        
        # ¬Q: There exists a root alpha of f(x) such that L != K(alpha).
        # Since [L:K] = D, and [K(alpha):K] is the degree of the irreducible factor of alpha,
        # L != K(alpha) is equivalent to D > deg(irreducible factor).
        # We check if ANY irreducible factor has degree strictly less than D.
        neg_q_ok = bool(any(fac.degree() < D for fac, mult in factors))
        
    except Exception:
        h1_ok = False
        h2_ok = False
        h3_ok = False
        neg_q_ok = False
        
    return [h1_ok, h2_ok, h3_ok, neg_q_ok]

