import sympy
from sympy import Poly, Rational, isprime, sqrt
from sympy.abc import x

# Top-level setup
# The base field is assumed to be Q (rationals).
# Witness is expected to be a tuple (p, a) or (F, p, a) or just a.

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, tuple):
            if len(witness) >= 3:
                p = int(witness[-2])
                a = witness[-1]
            elif len(witness) == 2:
                p = int(witness[0])
                a = witness[1]
            elif len(witness) == 1:
                p = 3
                a = witness[0]
            else:
                return [False, False, False]
        else:
            p = 3
            a = witness
    except Exception:
        return [False, False, False]

    # H_1: p is a prime number
    try:
        h1 = bool(isprime(p))
    except Exception:
        h1 = False

    # H_2: a is an element of F (rational number)
    try:
        a_rat = Rational(a)
        h2 = True
    except Exception:
        h2 = False

    # ¬Q: K = F(alpha) is not a normal extension of F for some root alpha
    neg_q = False
    if h1 and h2:
        try:
            f = Poly(x**p - x - a_rat, x, domain='QQ')
            factors = f.factor_list()[1]
            for g_poly, mult in factors:
                deg = g_poly.degree()
                if deg > 1:
                    real_roots = len(g_poly.real_roots())
                    # If an irreducible polynomial has both real and complex roots,
                    # its splitting field cannot be generated by a real root.
                    if 0 < real_roots < deg:
                        neg_q = True
                        break
                    
                    # For degree 3, if discriminant is not a perfect square, Galois group is S3 (not normal)
                    if deg == 3:
                        disc = g_poly.discriminant()
                        if not sqrt(disc).is_rational:
                            neg_q = True
                            break
                            
                    # For degree 4, check the resolvent cubic. If it has no rational roots,
                    # the Galois group is S4 or A4, neither of which is normal.
                    elif deg == 4:
                        coeffs = g_poly.all_coeffs()
                        b = coeffs[1] / coeffs[0]
                        c = coeffs[2] / coeffs[0]
                        d = coeffs[3] / coeffs[0]
                        e = coeffs[4] / coeffs[0]
                        res_cubic = Poly(x**3 - c*x**2 + (b*d - 4*e)*x - b**2*e + 4*c*e - d**2, x, domain='QQ')
                        has_linear = any(fac.degree() == 1 for fac, _ in res_cubic.factor_list()[1])
                        if not has_linear:
                            neg_q = True
                            break
        except Exception:
            pass

    return [h1, h2, neg_q]

