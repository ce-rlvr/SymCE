import sympy
from sympy.abc import x

# Top-level setup
# We use the rational numbers QQ as our base field K.
# x is provided for constructing polynomials.

def conditions(witness):
    """
    witness should be a tuple (n, E_poly), where:
      - n is an integer (the degree of the extensions)
      - E_poly is a single SymPy polynomial (e.g., x**3 - 2) defining the field E.
        (If a list/tuple of polynomials is provided, we only accept it if it has length 1).
    """
    try:
        if not isinstance(witness, (list, tuple)) or len(witness) < 2:
            return [False, False, False, False]
        n = witness[0]
        E_poly = witness[1] if len(witness) == 2 else witness[1:]
    except Exception:
        return [False, False, False, False]

    # H_1: Let K be a field
    # We implicitly use K = QQ, which is a field.
    h1 = True

    # H_2: Let \overline{K} be a fixed algebraic closure of K
    # We implicitly work within the algebraic numbers.
    h2 = True

    # H_3: Let n be a positive integer
    try:
        h3 = int(n) > 0 and n == int(n)
    except Exception:
        h3 = False

    # neg_Q: The compositum E is NOT a normal extension of K
    try:
        if isinstance(E_poly, (list, tuple)):
            if len(E_poly) == 1:
                E_poly = E_poly[0]
            else:
                # We only support a single extension for simplicity
                return [h1, h2, h3, False]
                
        E_poly = sympy.sympify(E_poly)
        if isinstance(E_poly, sympy.Eq):
            E_poly = E_poly.lhs - E_poly.rhs
            
        syms = list(E_poly.free_symbols)
        if len(syms) != 1:
            neg_q = False
        else:
            sym = syms[0]
            p = sympy.Poly(E_poly, sym, domain='QQ')
            if not p.is_irreducible:
                neg_q = False
            else:
                r_roots = sympy.real_roots(E_poly)
                num_real = len(r_roots)
                deg = p.degree()
                # If an irreducible polynomial has both real and non-real roots,
                # the field generated by one of its real roots cannot be normal,
                # because it cannot contain the non-real roots.
                if num_real > 0 and num_real < deg:
                    neg_q = True
                else:
                    neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

