import sympy
from sympy import S, I, sqrt, Poly, solve
from sympy.abc import x
from sympy.polys.numberfields import primitive_element, field_isomorphism

# Top-level setup
QQ = sympy.QQ
ZZ = sympy.ZZ

def get_prim(gens):
    """
    Computes a primitive element for the field extension generated by `gens` over QQ.
    Returns the primitive element as an algebraic number expression.
    """
    filtered_gens = []
    for g in gens:
        if not getattr(g, 'is_rational', False) and g != S.Zero:
            if g not in filtered_gens:
                filtered_gens.append(g)
                
    if not filtered_gens:
        return S.Zero
    if len(filtered_gens) == 1:
        return filtered_gens[0]
        
    res = primitive_element(filtered_gens, x, ex=True)
    coeffs = res[1]
    return sum(c * g for c, g in zip(coeffs, filtered_gens))

def is_subfield(gens_A, gens_B):
    """
    Checks if the field QQ(gens_A) is a subfield of QQ(gens_B).
    """
    prim_B = get_prim(gens_B)
    if getattr(prim_B, 'is_rational', False) or prim_B == S.Zero:
        for a in gens_A:
            if not (getattr(a, 'is_rational', False) or a == S.Zero):
                return False
        return True

    for a in gens_A:
        if getattr(a, 'is_rational', False) or a == S.Zero:
            continue
        if field_isomorphism(a, prim_B) is None:
            return False
    return True

def conditions(witness):
    """
    Evaluates the hypotheses and the negated conclusion for the given witness.
    The witness is expected to be a dictionary with keys:
      'L_gens': list of generators for L over QQ
      'K1_gens': list of generators for K_1 over QQ
      'K2_gens': list of generators for K_2 over QQ
      'f1': polynomial f_1(x) in QQ[x]
      'f2': polynomial f_2(x) in QQ[x]
    """
    try:
        L_gens = witness['L_gens']
        K1_gens = witness['K1_gens']
        K2_gens = witness['K2_gens']
        f1 = witness['f1']
        f2 = witness['f2']
    except (KeyError, TypeError):
        return [False, False, False, False]

    # H_1: F is a field
    # We implicitly use F = QQ, which is a field.
    h1 = True

    # H_2: L is a field extension of F
    try:
        # Check if L_gens are valid algebraic numbers over QQ
        prim_L = get_prim(L_gens)
        h2 = True
    except Exception:
        h2 = False

    # H_3: K_2 is a subfield of L that is a splitting field of f_2(x) over F
    try:
        k2_in_L = is_subfield(K2_gens, L_gens)
        if not k2_in_L:
            h3 = False
        else:
            poly_f2 = Poly(f2, x)
            f2_in_F = poly_f2.domain.is_RationalField or poly_f2.domain.is_IntegerRing
            if not f2_in_F:
                h3 = False
            else:
                roots2 = solve(f2, x)
                roots_in_K2 = is_subfield(roots2, K2_gens)
                if not roots_in_K2:
                    h3 = False
                else:
                    K2_in_roots = is_subfield(K2_gens, roots2)
                    h3 = K2_in_roots
    except Exception:
        h3 = False

    # ¬Q: K_1 K_2 is NOT a splitting field of f_1(x)f_2(x) over F
    try:
        f12 = f1 * f2
        poly_f12 = Poly(f12, x)
        f12_in_F = poly_f12.domain.is_RationalField or poly_f12.domain.is_IntegerRing
        
        if not f12_in_F:
            is_splitting_field = False
        else:
            K1K2_gens = K1_gens + K2_gens
            roots12 = solve(f12, x)
            
            roots_in_K1K2 = is_subfield(roots12, K1K2_gens)
            if not roots_in_K1K2:
                is_splitting_field = False
            else:
                K1K2_in_roots = is_subfield(K1K2_gens, roots12)
                is_splitting_field = K1K2_in_roots
                
        neg_q = not is_splitting_field
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

