def conditions(witness):
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            domain, expr = witness
            if isinstance(expr, sympy.Poly):
                poly = expr
                expr = poly.as_expr()
            else:
                poly = sympy.Poly(expr)
        elif isinstance(witness, sympy.Poly):
            domain = witness.domain
            poly = witness
            expr = poly.as_expr()
        else:
            expr = witness
            poly = sympy.Poly(expr)
            domain = poly.domain
            
        h1 = False
        if str(domain) in ['CC', 'QQbar', 'C', 'Complexes']:
            h1 = True
        elif domain == sympy.CC:
            h1 = True
        elif hasattr(domain, 'is_AlgebraicField') and domain.is_AlgebraicField:
            h1 = True
    except Exception:
        h1 = False

    try:
        if poly.is_zero:
            neg_q = True
        elif poly.degree() <= 0:
            neg_q = True
        else:
            gens = poly.gens
            if len(gens) != 1:
                neg_q = True
            else:
                gen = gens[0]
                rts = sympy.roots(expr, gen)
                if len(rts) == 1:
                    root, mult = list(rts.items())[0]
                    if mult == poly.degree():
                        neg_q = False
                    else:
                        neg_q = True
                else:
                    neg_q = True
    except Exception:
        neg_q = False

    return [h1, neg_q]

