import sympy
from sympy import isprime

# Top-level setup
# (No named bindings needed for this number theory domain; integers are used directly)

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness should be a tuple (p, q).
    """
    try:
        if not isinstance(witness, (tuple, list)) or len(witness) != 2:
            return [False, False, False, False]
        p, q = witness
    except Exception:
        return [False, False, False, False]
        
    # H_1: p is an odd prime number
    try:
        h1 = bool(isprime(p) and p % 2 != 0)
    except Exception:
        h1 = False
        
    # H_2: q is distinct from p
    try:
        h2 = bool((q != p) and (isinstance(q, int) or (hasattr(q, 'is_integer') and q.is_integer)))
    except Exception:
        h2 = False
        
    # H_3: zeta_p is a primitive p-th root of unity
    # This is a definitional hypothesis establishing the field ℚ(ζ_p).
    # It is always True as long as p is valid.
    h3 = True
    
    # ¬Q: The conclusion FAILS
    # Conclusion: The ideal (q) splits completely into p-1 distinct prime ideals iff q ≡ 1 (mod p).
    try:
        q_int = int(q)
        p_int = int(p)
        
        abs_q = abs(q_int)
        
        # LHS: The ideal (q) splits completely into p-1 distinct prime ideals.
        # In ℚ(ζ_p), a prime p_i splits completely iff p_i ≡ 1 (mod p).
        # For the ideal (q) to split completely into exactly p-1 distinct prime ideals,
        # q must be square-free, and the sum of the number of prime ideals above each 
        # prime factor must be exactly p-1. Since each completely split prime factor 
        # contributes exactly p-1 prime ideals, |q| must be a single prime number 
        # that splits completely.
        lhs = bool(isprime(abs_q) and (abs_q % p_int == 1))
        
        # RHS: q ≡ 1 (mod p)
        rhs = bool(q_int % p_int == 1)
        
        # The conclusion is LHS <==> RHS. We want it to fail (i.e., LHS != RHS).
        neg_q = bool(lhs != rhs)
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

