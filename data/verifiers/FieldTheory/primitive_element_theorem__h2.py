def conditions(witness):
    try:
        L, K = witness
    except Exception:
        return [False, False, False]
    
    # H1: L/K is a field extension
    try:
        h1 = False
        if getattr(L, 'is_Field', False) and getattr(K, 'is_Field', False):
            if L == K:
                h1 = True
            elif hasattr(L, 'domain'):
                if L.domain == K:
                    h1 = True
                elif hasattr(L.domain, 'domain') and L.domain.domain == K:
                    h1 = True
            
            if not h1 and L.__class__.__name__ == 'FractionField' and K.__class__.__name__ == 'FractionField':
                L_ground = getattr(L, 'domain', None)
                if L_ground.__class__.__name__ == 'PolynomialRing':
                    L_ground = L_ground.domain
                K_ground = getattr(K, 'domain', None)
                if K_ground.__class__.__name__ == 'PolynomialRing':
                    K_ground = K_ground.domain
                
                if L_ground == K_ground and L_ground is not None:
                    if hasattr(L, 'gens') and hasattr(K, 'gens'):
                        if set(K.gens).issubset(set(L.gens)):
                            h1 = True
                            
            if not h1 and K == QQ and L.__class__.__name__ == 'AlgebraicField':
                h1 = True
    except Exception:
        h1 = False

    # H2: The extension L/K is separable
    try:
        h2 = False
        if h1:
            char = getattr(K, 'char', None)
            if char is None and hasattr(K, 'characteristic'):
                try:
                    char = K.characteristic()
                except Exception:
                    pass
            if char == 0:
                h2 = True
            elif K == QQ:
                h2 = True
            else:
                K_ground = getattr(K, 'domain', None)
                if K_ground.__class__.__name__ == 'PolynomialRing':
                    K_ground = K_ground.domain
                if K_ground == QQ:
                    h2 = True
    except Exception:
        h2 = False

    # neg_Q: L is NOT generated by a single element over K
    try:
        neg_q = False
        if h1:
            if L.__class__.__name__ == 'FractionField':
                L_ground = getattr(L, 'domain', None)
                if L_ground.__class__.__name__ == 'PolynomialRing':
                    L_ground = L_ground.domain
                
                if L_ground == K:
                    if hasattr(L, 'gens') and len(L.gens) > 1:
                        neg_q = True
                elif K.__class__.__name__ == 'FractionField':
                    K_ground = getattr(K, 'domain', None)
                    if K_ground.__class__.__name__ == 'PolynomialRing':
                        K_ground = K_ground.domain
                    
                    if L_ground == K_ground and L_ground is not None:
                        if hasattr(L, 'gens') and hasattr(K, 'gens'):
                            if set(K.gens).issubset(set(L.gens)):
                                if len(set(L.gens) - set(K.gens)) > 1:
                                    neg_q = True
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

