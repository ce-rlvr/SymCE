def get_basis_and_dim(A):
    """
    Computes a basis for the algebra F(A) generated by the matrix A over its base field,
    and returns the basis (as flattened lists) and its dimension (which equals the degree
    of the minimal polynomial of A).
    """
    n = A.shape[0]
    vecs = []
    basis = []
    for i in range(n + 1):
        mat = A**i
        flat = list(mat)
        vecs.append(flat)
        M = Matrix(vecs)
        if M.rank() == len(vecs):
            basis.append(flat)
        else:
            break
    return basis, len(basis)

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, dict):
            alpha = witness.get('alpha')
            beta = witness.get('beta')
        elif isinstance(witness, (tuple, list)):
            if len(witness) == 2:
                alpha, beta = witness
            elif len(witness) == 3:
                _, alpha, beta = witness
            else:
                return [False, False, False]
        else:
            return [False, False, False]
        
        if isinstance(alpha, list):
            alpha = Matrix(alpha)
        if isinstance(beta, list):
            beta = Matrix(beta)
            
        if alpha is None or beta is None:
            return [False, False, False]
            
    except Exception:
        return [False, False, False]

    # H_1: α and β are algebraic over F
    try:
        if isinstance(alpha, Matrix) and isinstance(beta, Matrix):
            # Square matrices over a field are always algebraic over that field
            if alpha.shape == beta.shape and alpha.shape[0] == alpha.shape[1]:
                h1 = True
            else:
                h1 = False
        elif isinstance(alpha, Expr) and isinstance(beta, Expr):
            h1 = True
        else:
            h1 = False
    except Exception:
        h1 = False

    # H_2: The degree of the minimal polynomial of α over F and the degree of the minimal polynomial of β over F are coprime integers
    try:
        if isinstance(alpha, Matrix) and isinstance(beta, Matrix) and h1:
            basis_a, deg_a = get_basis_and_dim(alpha)
            basis_b, deg_b = get_basis_and_dim(beta)
            h2 = (gcd(int(deg_a), int(deg_b)) == 1)
        elif isinstance(alpha, Expr) and isinstance(beta, Expr) and h1:
            from sympy.polys.polytools import degree
            from sympy import minpoly
            poly_a = minpoly(alpha)
            poly_b = minpoly(beta)
            deg_a = degree(poly_a)
            deg_b = degree(poly_b)
            h2 = (gcd(int(deg_a), int(deg_b)) == 1)
        else:
            h2 = False
    except Exception:
        h2 = False

    # ¬Q: The intersection F(α) ∩ F(β) is not equal to F
    try:
        if isinstance(alpha, Matrix) and isinstance(beta, Matrix) and h1:
            # F is the span of the identity matrix (dimension 1).
            # We find the dimension of the intersection of the two algebras F(α) and F(β).
            # By Grassmann's formula: dim(A ∩ B) = dim(A) + dim(B) - dim(A + B)
            M_sum = Matrix(basis_a + basis_b)
            dim_int = deg_a + deg_b - M_sum.rank()
            
            # If the intersection is strictly larger than F, its dimension is > 1
            neg_q = bool(dim_int > 1)
        elif isinstance(alpha, Expr) and isinstance(beta, Expr) and h1:
            # For actual field extensions, the theorem holds true, so the intersection is exactly F.
            # Thus, the negated conclusion is False.
            neg_q = False
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

