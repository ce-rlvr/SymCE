import sympy as sp

x = sp.Symbol('x')

def conditions(witness):
    try:
        if isinstance(witness, tuple):
            if len(witness) == 3:
                alpha, alpha_bar_wit, m = witness
            elif len(witness) == 2:
                alpha, m = witness
                alpha_bar_wit = sp.conjugate(alpha)
            else:
                return [False, False, False]
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H1: alpha is an algebraic number over Q and m(x) is its minimal polynomial
    try:
        # Check if alpha is algebraic over Q
        sp.minpoly(alpha)
        is_alg = True
    except Exception:
        is_alg = False

    try:
        syms = list(m.free_symbols)
        var = syms[0] if syms else sp.Symbol('x')
        m_poly = sp.Poly(m, var)
        is_monic = m_poly.LC() == 1
        
        val_alpha = m.subs(var, alpha)
        is_root = (sp.simplify(val_alpha) == 0) or (sp.expand(val_alpha) == 0)
        
        # Check irreducibility over the field generated by its coefficients
        if m_poly.degree() == 1:
            is_irred = True
        else:
            factors = sp.factor_list(m)
            is_irred = len(factors[1]) == 1 and factors[1][0][1] == 1
            
        is_minpoly = is_monic and is_root and is_irred and m_poly.degree() >= 1
    except Exception:
        is_minpoly = False

    h1 = bool(is_alg and is_minpoly)

    # H2: alpha_bar is the complex conjugate of alpha
    try:
        diff = alpha_bar_wit - sp.conjugate(alpha)
        h2 = bool(sp.simplify(diff) == 0 or sp.expand(diff) == 0)
    except Exception:
        h2 = False

    # neg_Q: alpha_bar is NOT a root of the minimal polynomial m(x)
    try:
        val_bar = m.subs(var, alpha_bar_wit)
        neg_q = bool(sp.simplify(val_bar) != 0 and sp.expand(val_bar) != 0)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

