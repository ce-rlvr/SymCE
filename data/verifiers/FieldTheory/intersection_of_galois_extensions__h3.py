def is_normal_subgroup(H, G):
    if not H.is_subgroup(G):
        return False
    for g in G.generators:
        g_inv = ~g
        for h in H.generators:
            if not H.contains(g * h * g_inv):
                return False
    return True

def conditions(witness) -> list[bool]:
    """
    Expected witness formats:
    1. Group-theoretic (Galois correspondence):
       witness = (G, H_K, H_L)
       where G is the Galois group of some extension E/F,
       and H_K, H_L are subgroups corresponding to K and L.
    2. Finite fields:
       witness = (p, d_F, d_K, d_L)
       representing F = GF(p^d_F), K = GF(p^d_K), L = GF(p^d_L).
    """
    h1 = h2 = h3 = h4 = neg_q = False
    
    try:
        if isinstance(witness, tuple) and len(witness) == 3:
            G, H_K, H_L = witness
            
            # H1: F is a field
            h1 = True
            
            # H2: K and L are finite field extensions of F
            h2 = H_K.is_subgroup(G) and H_L.is_subgroup(G)
            
            # H3: K/F is a Galois extension
            h3 = is_normal_subgroup(H_K, G)
            
            # H4: L/F is a Galois extension
            h4 = is_normal_subgroup(H_L, G)
            
            # Conclusion: K \cap L is a Galois extension of F
            # K \cap L corresponds to the subgroup generated by H_K and H_L
            H_int = PermutationGroup(list(H_K.generators) + list(H_L.generators))
            q = is_normal_subgroup(H_int, G)
            neg_q = not q
            
        elif isinstance(witness, tuple) and len(witness) == 4:
            p, d_F, d_K, d_L = witness
            p = int(p)
            d_F = int(d_F)
            d_K = int(d_K)
            d_L = int(d_L)
            
            # H1: F is a field
            h1 = isprime(p) and d_F >= 1
            
            # H2: K and L are finite field extensions of F
            h2 = (d_K % d_F == 0) and (d_L % d_F == 0) and d_K >= 1 and d_L >= 1
            
            # H3: K/F is a Galois extension (always true for finite fields)
            h3 = h1 and h2
            
            # H4: L/F is a Galois extension (always true for finite fields)
            h4 = h1 and h2
            
            # Conclusion: K \cap L is a Galois extension of F
            d_int = math.gcd(d_K, d_L)
            is_ext = (d_int % d_F == 0)
            q = is_ext
            neg_q = not q
            
    except Exception:
        pass
        
    return [h1, h2, h3, h4, neg_q]

