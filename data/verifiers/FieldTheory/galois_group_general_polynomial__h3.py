CONDITION_LABELS = [
    "H_1: K is a field",
    "H_2: t_1, ..., t_n are algebraically independent variables over K",
    "H_3: f(x) is a polynomial over E",
    "H_4: L is the splitting field of f(x) over E",
    "¬Q: The Galois group Gal(L/E) is not isomorphic to S_n"
]

def conditions(witness):
    try:
        n = int(witness['n'])
        vars_ = [sp.sympify(v) for v in witness['vars']]
        t = [sp.sympify(ti) for ti in witness['t']]
        roots = [sp.sympify(r) for r in witness['roots']]
    except Exception:
        return [False] * 5

    # H1: K is a field
    # We implicitly use K = Q (the rational numbers), which is a field.
    h1 = True

    # H2: t_1, ..., t_n are algebraically independent variables over K
    # We verify this by checking that the Jacobian determinant of t with respect to vars_ is non-zero.
    try:
        if n >= 1 and len(t) == n and len(vars_) == n and all(isinstance(v, sp.Symbol) for v in vars_):
            J = sp.Matrix(t).jacobian(vars_)
            detJ = J.det()
            h2 = not detJ.equals(0)
        else:
            h2 = False
    except Exception:
        h2 = False

    # H3: f(x) is a polynomial over E
    # E is the field generated by vars_ over Q.
    # We check that each t_i is in E, meaning its free symbols are a subset of vars_.
    try:
        h3 = True
        for ti in t:
            if not ti.free_symbols.issubset(set(vars_)):
                h3 = False
                break
    except Exception:
        h3 = False

    # H4: L is the splitting field of f(x) over E
    # We check that f(x) splits completely into the given roots,
    # and that the roots are in E (so L = E).
    try:
        x = sp.Dummy('x')
        poly_from_roots = sp.Mul(*[x - r for r in roots])
        poly_from_t = x**n
        for i in range(n):
            poly_from_t += (-1)**(i+1) * t[i] * x**(n - 1 - i)
            
        diff = sp.expand(poly_from_roots - poly_from_t)
        h4 = diff.equals(0)
        
        if h4:
            for r in roots:
                if not r.free_symbols.issubset(set(vars_)):
                    h4 = False
                    break
    except Exception:
        h4 = False

    # neg_Q: Gal(L/E) is not isomorphic to S_n
    # Since the roots are in E, L = E, so Gal(L/E) is the trivial group (order 1).
    # S_n has order n!. They are not isomorphic if n! != 1.
    try:
        neg_q = math.factorial(n) != 1
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]