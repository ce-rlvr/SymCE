import sympy
from sympy import Symbol, sqrt, pi, I, Rational
from sympy.abc import x, y, z

# Setup named objects for convenience
QQ = sympy.QQ
ZZ = sympy.ZZ

def conditions(witness) -> list[bool]:
    """
    Given a witness representing the generators of fields K, L, M over QQ,
    checks if it is a valid counterexample.
    The witness should be a tuple of three iterables of SymPy expressions: (K_gens, L_gens, M_gens).
    """
    try:
        if len(witness) != 3:
            return [False, False, False]
        K_gens, L_gens, M_gens = witness
    except Exception:
        return [False, False, False]
        
    def get_non_rat(gens):
        from sympy import sympify
        res = set()
        if not hasattr(gens, '__iter__') or isinstance(gens, str):
            gens = [gens]
        for g in gens:
            try:
                sg = sympify(g)
                # Ignore rational numbers as they don't change the generated field over QQ
                if getattr(sg, 'is_rational', False):
                    continue
                res.add(sg)
            except Exception:
                pass
        return res

    try:
        K_set = get_non_rat(K_gens)
        L_set = get_non_rat(L_gens)
        M_set = get_non_rat(M_gens)
        
        # H_1: K, L, and M are fields such that K \subseteq L \subseteq M
        # We verify this by checking if the generators satisfy the subset relation.
        h1 = K_set.issubset(L_set) and L_set.issubset(M_set)
    except Exception:
        h1 = False

    def is_algebraic_expr(expr, base_symbols, base_exprs):
        """
        Recursively checks if an expression is algebraic over the field generated by base_exprs.
        """
        from sympy import sympify
        try:
            expr = sympify(expr)
        except Exception:
            return False
            
        if expr in base_exprs:
            return True
        if getattr(expr, 'is_rational', False):
            return True
        if getattr(expr, 'is_algebraic', None) is True:
            return True
        if expr.is_Symbol:
            return expr in base_symbols
        if expr.is_Add or expr.is_Mul:
            return all(is_algebraic_expr(arg, base_symbols, base_exprs) for arg in expr.args)
        if expr.is_Pow:
            base, exp = expr.as_base_exp()
            return getattr(exp, 'is_rational', False) and is_algebraic_expr(base, base_symbols, base_exprs)
        return False

    try:
        base_symbols = set()
        for b in K_set:
            base_symbols.update(b.free_symbols)
        base_exprs = K_set
            
        # H_2: The field extension L/K is algebraic
        # True if all generators of L are algebraic over K
        h2 = all(is_algebraic_expr(g, base_symbols, base_exprs) for g in L_set)
    except Exception:
        h2 = False

    try:
        # ¬Q: The field extension M/K is NOT algebraic
        # True if AT LEAST ONE generator of M is transcendental over K
        neg_q = not all(is_algebraic_expr(g, base_symbols, base_exprs) for g in M_set)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

