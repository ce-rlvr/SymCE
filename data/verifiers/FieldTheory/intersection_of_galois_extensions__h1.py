def is_subgroup(H, G):
    """Check if H is a subgroup of G."""
    try:
        return all(h in G for h in H.generators)
    except Exception:
        return False

def is_normal(H, G):
    """Check if H is a normal subgroup of G."""
    try:
        if not is_subgroup(H, G):
            return False
        # For finite groups, checking if g * h * g^-1 is in H 
        # for all generators of G and H is sufficient.
        for h in H.generators:
            for g in G.generators:
                if (g * h * ~g) not in H:
                    return False
        return True
    except Exception:
        return False

def conditions(witness) -> list[bool]:
    """
    Evaluates the hypotheses and the negated conclusion for the conjecture.
    Uses the Fundamental Theorem of Galois Theory to model field extensions as groups.
    Witness is expected to be a tuple (G, H_K, H_L) where:
      - G is the Galois group of a common normal extension E/F.
      - H_K is the subgroup corresponding to the intermediate field K.
      - H_L is the subgroup corresponding to the intermediate field L.
    """
    h1, h2, h3, h4, neg_q = False, False, False, False, False
    
    try:
        if isinstance(witness, (tuple, list)):
            if len(witness) == 3:
                G, H_K, H_L = witness
            elif len(witness) == 2:
                H_K, H_L = witness
                if hasattr(H_K, 'degree'):
                    G = SymmetricGroup(H_K.degree)
                else:
                    return [False] * 5
            else:
                return [False] * 5
        else:
            return [False] * 5
            
        if isinstance(H_K, list):
            H_K = PermutationGroup(*H_K)
        if isinstance(H_L, list):
            H_L = PermutationGroup(*H_L)
            
        if not (isinstance(G, PermutationGroup) and isinstance(H_K, PermutationGroup) and isinstance(H_L, PermutationGroup)):
            return [False] * 5

        # H_1: K and L are finite field extensions of F
        # In Galois correspondence, this means H_K and H_L are subgroups of a finite group G.
        h1 = is_subgroup(H_K, G) and is_subgroup(H_L, G)
        
        # H_2: K and L are contained in a common extension field
        # Being subgroups of the same G implies they are subfields of the same Galois extension E.
        h2 = h1
        
        # H_3: K/F is a Galois extension
        # Corresponds to H_K being a normal subgroup of G.
        h3 = is_normal(H_K, G)
        
        # H_4: L/F is a Galois extension
        # Corresponds to H_L being a normal subgroup of G.
        h4 = is_normal(H_L, G)
        
        # ¬Q: K \cap L is NOT a Galois extension of F
        # K \cap L corresponds to the subgroup generated by H_K and H_L.
        # It is Galois over F iff this generated subgroup is normal in G.
        H_int = PermutationGroup(*(list(H_K.generators) + list(H_L.generators)))
        neg_q = not is_normal(H_int, G)
        
    except Exception:
        pass
        
    return [h1, h2, h3, h4, neg_q]

