import sympy
from sympy import gcd, sympify

# Top-level setup for potential witness expressions
x, y, z = sympy.symbols('x y z')

def conditions(witness) -> list[bool]:
    """
    Checks if the witness is a valid counterexample.
    The witness should be a tuple (a, b) of two integers.
    These integers represent the generators of the principal ideals 
    I = (a) and J = (b) in the ring of integers R = Z.
    """
    try:
        # Witness must be a pair of generators
        if len(witness) != 2:
            return [False, False, False]
            
        a, b = witness
        a = sympify(a)
        b = sympify(b)
        
        # We restrict the ring R to be the integers Z for simplicity.
        # A valid counterexample can easily be found in Z.
        if not (a.is_Integer and b.is_Integer):
            return [False, False, False]
            
        # H_1: I and J are ideals of R
        # Any integer generates a principal ideal in Z, so this is trivially true
        # given the type check above.
        h1 = True
        
        # H_2: I + J = R
        # In Z, the sum of two principal ideals (a) + (b) is generated by gcd(a, b).
        # The ideal (gcd(a, b)) equals Z if and only if gcd(a, b) is a unit (1 or -1).
        g = gcd(a, b)
        h2 = (abs(g) == 1)
            
        # ¬Q: Neither I = R nor J = R
        # I = Z iff 'a' is a unit (1 or -1).
        # J = Z iff 'b' is a unit (1 or -1).
        i_is_r = (abs(a) == 1)
        j_is_r = (abs(b) == 1)
            
        neg_q = not (i_is_r or j_is_r)
        
        return [bool(h1), bool(h2), bool(neg_q)]
    except Exception:
        return [False, False, False]

