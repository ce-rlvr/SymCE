import sympy

CONDITION_LABELS = [
    "H_1: R is an integral domain",
    "¬Q: The equivalence between (a) ∩ (b) = (m) and m being an LCM of a and b fails"
]

N_HYP = 1
NEG_Q_INDEX = 1

def conditions(witness):
    """
    Given a witness, checks if it is a valid counterexample to the false conjecture:
    "In an integral domain, the intersection of the principal ideals (a) and (b) 
    is generated by an element m if and only if m is a least common multiple of a and b."
    
    The witness is expected to be a tuple (R, a, b, m) or an object providing these.
    """
    try:
        # Attempt to unpack witness as a tuple (R, a, b, m)
        if isinstance(witness, tuple) and len(witness) == 4:
            R, a, b, m = witness
        else:
            R = witness.R
            a = witness.a
            b = witness.b
            m = witness.m
    except Exception:
        return [False, False]

    # H_1: R is an integral domain
    try:
        if hasattr(R, 'is_integral_domain'):
            h1 = bool(R.is_integral_domain)
        elif hasattr(R, 'is_domain'):
            h1 = bool(R.is_domain)
        else:
            # Fallback: assume it's an integral domain if it's a sympy domain
            h1 = getattr(R, 'is_commutative', True) and not getattr(R, 'has_zero_divisors', False)
    except Exception:
        h1 = False

    # ¬Q: The equivalence fails
    try:
        # Check if m is an LCM of a and b
        # m is a common multiple
        is_common_multiple = (m in R.ideal(a)) and (m in R.ideal(b)) if hasattr(R, 'ideal') else (m % a == 0 and m % b == 0)
        
        # In a general ring, checking if m is the *least* common multiple might require checking all common multiples,
        # but if R provides an lcm method, we can use it.
        if hasattr(R, 'lcm'):
            actual_lcm = R.lcm(a, b)
            # m is an LCM if it associates with actual_lcm
            if hasattr(R, 'are_associates'):
                is_lcm = R.are_associates(m, actual_lcm)
            else:
                is_lcm = (m == actual_lcm) or (m == -actual_lcm)
        else:
            is_lcm = is_common_multiple # Simplified fallback if no lcm method

        # Check if (a) \cap (b) is generated by m
        if hasattr(R, 'ideal_intersection'):
            intersection = R.ideal_intersection(R.ideal(a), R.ideal(b))
            is_generated_by_m = (intersection == R.ideal(m))
        else:
            # Fallback: assume generated by m if m is the LCM in standard domains
            is_generated_by_m = is_lcm

        # The conjecture states: generated_by_m <==> is_lcm
        # The negation is that this equivalence is False (i.e., they have different truth values)
        neg_q = (bool(is_generated_by_m) != bool(is_lcm))
        
        # If the witness is a custom object that directly provides the truth value of the conjecture
        if hasattr(witness, 'conjecture_holds'):
            neg_q = not witness.conjecture_holds()
            
    except Exception:
        neg_q = False

    return [h1, neg_q]