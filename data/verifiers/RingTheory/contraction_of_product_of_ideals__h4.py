def conditions(witness):
    """
    witness is expected to be a tuple: (n, m, f_map, I_list, J_list)
    representing:
      R = Z/nZ
      S = Z/mZ
      f: R -> S defined by f_map (list or dict)
      I: ideal of S (given as a complete list of elements)
      J: subset of S (given as a list of elements)
    """
    try:
        n, m, f_map, I_list, J_list = witness
        
        if not (isinstance(n, int) and n >= 1 and isinstance(m, int) and m >= 1):
            return [False, False, False, False]
            
        R = list(range(n))
        S = list(range(m))
        
        if isinstance(f_map, dict):
            f = lambda x: f_map.get(x, -1)
        elif callable(f_map):
            f = f_map
        else:
            f = lambda x: f_map[x] if 0 <= x < len(f_map) else -1
            
        # H1: R and S are commutative rings
        # Z/nZ and Z/mZ are commutative rings by definition.
        H1 = True
        
        # H2: f is a ring homomorphism
        H2 = True
        if f(1 % n) != 1 % m:
            H2 = False
        for a in R:
            for b in R:
                if f((a + b) % n) != (f(a) + f(b)) % m:
                    H2 = False
                if f((a * b) % n) != (f(a) * f(b)) % m:
                    H2 = False
                    
        # H3: I is an ideal of S
        I_set = set(I_list)
        H3 = True
        if not I_set.issubset(set(S)):
            H3 = False
        if 0 not in I_set:
            H3 = False
        for i in I_set:
            for j in I_set:
                if (i + j) % m not in I_set:
                    H3 = False
        for i in I_set:
            for s in S:
                if (i * s) % m not in I_set:
                    H3 = False
                    
        # Conclusion: f^{-1}(I)f^{-1}(J) \subseteq f^{-1}(IJ)
        J_set = set(J_list)
        if not J_set.issubset(set(S)):
            return [H1, H2, H3, False]
            
        # IJ is the ideal generated by the pointwise product set of I and J
        pointwise_IJ = set()
        for i in I_set:
            for j in J_set:
                pointwise_IJ.add((i * j) % m)
                
        # Ideal generated by pointwise_IJ in S
        IJ = set(pointwise_IJ)
        IJ.add(0)
        
        # Additive closure
        added = True
        while added:
            added = False
            new_elements = set()
            for a in IJ:
                for b in IJ:
                    s = (a + b) % m
                    if s not in IJ:
                        new_elements.add(s)
            if new_elements:
                IJ.update(new_elements)
                added = True
                
        # f^{-1}(IJ)
        f_inv_IJ = set()
        for r in R:
            if f(r) in IJ:
                f_inv_IJ.add(r)
                
        # f^{-1}(I)
        f_inv_I = set()
        for r in R:
            if f(r) in I_set:
                f_inv_I.add(r)
                
        # f^{-1}(J)
        f_inv_J = set()
        for r in R:
            if f(r) in J_set:
                f_inv_J.add(r)
                
        # Pointwise products of f^{-1}(I) and f^{-1}(J)
        pointwise_products = set()
        for x in f_inv_I:
            for y in f_inv_J:
                pointwise_products.add((x * y) % n)
                
        # The product of f^{-1}(I) and f^{-1}(J) is the ideal generated by their pointwise products.
        LHS = set(pointwise_products)
        LHS.add(0)
        
        added = True
        while added:
            added = False
            new_elements = set()
            for a in LHS:
                for b in LHS:
                    s = (a + b) % n
                    if s not in LHS:
                        new_elements.add(s)
            if new_elements:
                LHS.update(new_elements)
                added = True
                
        is_subset = LHS.issubset(f_inv_IJ)
        neg_Q = not is_subset
        
        return [H1, H2, H3, neg_Q]
    except Exception:
        return [False, False, False, False]

