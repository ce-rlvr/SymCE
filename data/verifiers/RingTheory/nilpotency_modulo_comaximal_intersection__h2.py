import math
import sympy
from sympy import symbols
from sympy.abc import x, y, z
from sympy.ntheory import factorint

# Top-level setup for potential witness expressions
Z = sympy.S.Integers
Q = sympy.S.Rationals

CONDITION_LABELS = [
    "H_1: R is a commutative ring",
    "H_2: x is an element of R",
    "¬Q: x is nilpotent in R/(I \\cap J) is NOT equivalent to (x is nilpotent in R/I and R/J)"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness) -> list[bool]:
    """
    Given a witness, checks if it satisfies the remaining hypotheses and falsifies the conclusion.
    The witness is expected to be a tuple (R, x, I, J).
    For convenience and robustness, we support an integer tuple (n, x, i, j) representing
    the ring Z/nZ, element x, and ideals generated by i and j.
    """
    try:
        if not isinstance(witness, (tuple, list)) or len(witness) != 4:
            return [False, False, False]
            
        # Try to parse the witness as an integer tuple (n, x, i, j) for Z/nZ
        try:
            n, x_val, i, j = [int(w) for w in witness]
            is_int_format = True
        except Exception:
            is_int_format = False
            
        if is_int_format:
            h1 = True  # Z/nZ is always a commutative ring
            h2 = True  # x_val is an integer, representing an element in Z/nZ
            
            # Find the generators for the ideals in Z
            m_I = math.gcd(n, i) if n else abs(i)
            m_J = math.gcd(n, j) if n else abs(j)
            
            # Generator for the intersection ideal I \cap J
            if m_I == 0 or m_J == 0:
                m_IJ = 0
            else:
                m_IJ = abs(m_I * m_J) // math.gcd(m_I, m_J)
                
            def is_nil(val, mod):
                if mod == 0:
                    return val == 0
                if mod == 1 or mod == -1:
                    return True
                mod = abs(mod)
                # In Z/mZ, an element is nilpotent iff every prime factor of m divides it
                for p in factorint(mod):
                    if val % p != 0:
                        return False
                return True
                
            nil_I = is_nil(x_val, m_I)
            nil_J = is_nil(x_val, m_J)
            nil_IJ = is_nil(x_val, m_IJ)
            
            # The conclusion Q is the equivalence of nilpotency
            q = (nil_IJ == (nil_I and nil_J))
            return [h1, h2, not q]
            
        # If the witness is not an integer tuple, try to evaluate it as general sympy objects
        R, x_elem, I, J = witness
        
        h1 = getattr(R, 'is_commutative', False)
        if not h1 and hasattr(R, 'is_Ring'):
            h1 = True
            
        h2 = True  # Assuming x_elem belongs to R if provided in the witness
        
        # The statement "sqrt(I \cap J) = sqrt(I) \cap sqrt(J)" is a mathematical tautology 
        # in any commutative ring. Thus, the conclusion Q is always True, and ¬Q is always False.
        neg_q = False
        
        return [bool(h1), bool(h2), neg_q]
        
    except Exception:
        return [False, False, False]