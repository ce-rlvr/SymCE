import sympy as sp
import itertools

# Top-level setup
x, y, z, w, u, v = sp.symbols('x y z w u v')

def get_powers(m):
    if m == 0:
        return None
    if hasattr(m, 'is_number') and m.is_number:
        return {}
    d = m.as_powers_dict()
    return {k: val for k, val in d.items() if k.is_Symbol}

def is_monomial(m):
    if m == 0:
        return True
    if hasattr(m, 'is_number') and m.is_number:
        return True
    if not hasattr(m, 'as_powers_dict'):
        return False
    d = m.as_powers_dict()
    for k, val in d.items():
        if hasattr(k, 'is_Symbol') and k.is_Symbol:
            if not (isinstance(val, (int, sp.Integer)) and val >= 0):
                return False
        elif hasattr(k, 'is_number') and k.is_number:
            pass
        else:
            return False
    return True

def strip_coeff(m):
    p = get_powers(m)
    if p is None:
        return sp.sympify(0)
    if not p:
        return sp.sympify(1)
    res = sp.sympify(1)
    for k, val in p.items():
        res *= k**val
    return res

def is_divisible(m1, m2):
    p1 = get_powers(m1)
    p2 = get_powers(m2)
    for k, val in p2.items():
        if p1.get(k, 0) < val:
            return False
    return True

def simplify_ideal(gens):
    gens = [g for g in gens if g != 0]
    res = []
    gens.sort(key=lambda expr: sum(get_powers(expr).values()))
    for g in gens:
        if not any(is_divisible(g, r) for r in res):
            res.append(g)
    return res

def ideal_quotient_monomial(K_gens, f):
    res = []
    pf = get_powers(f)
    if pf is None:
        return [sp.sympify(1)]
    for g in K_gens:
        pg = get_powers(g)
        if pg is None:
            continue
        if not pg:
            return [sp.sympify(1)]
        q = sp.sympify(1)
        for k, val in pg.items():
            v_f = pf.get(k, 0)
            if val > v_f:
                q *= k**(val - v_f)
        res.append(q)
    return simplify_ideal(res)

def ideals_equal(gens1, gens2):
    s1 = set(simplify_ideal(gens1))
    s2 = set(simplify_ideal(gens2))
    return s1 == s2

def minimal_primes_of_ideal(K_gens):
    hyperedges = []
    for g in K_gens:
        p = get_powers(g)
        if p is None:
            continue
        if not p:
            return []
        hyperedges.append(set(p.keys()))
    
    if not hyperedges:
        return [set()]
        
    hitting_sets = []
    for prod in itertools.product(*hyperedges):
        hitting_sets.append(set(prod))
        
    minimal = []
    hitting_sets.sort(key=len)
    for hs in hitting_sets:
        if not any(m.issubset(hs) for m in minimal):
            minimal.append(hs)
    return minimal

def height_of_prime_in_R(P_vars, J_gens):
    min_primes_J = minimal_primes_of_ideal(J_gens)
    valid_Qs = [Q for Q in min_primes_J if Q.issubset(P_vars)]
    if not valid_Qs:
        return None
    return len(P_vars) - min(len(Q) for Q in valid_Qs)

def height_of_ideal_in_R(I_gens, J_gens):
    K_gens = J_gens + I_gens
    min_primes_K = minimal_primes_of_ideal(K_gens)
    if not min_primes_K:
        return None
    heights = []
    for Q in min_primes_K:
        h = height_of_prime_in_R(Q, J_gens)
        if h is not None:
            heights.append(h)
    if not heights:
        return None
    return min(heights)

def conditions(witness) -> list[bool]:
    try:
        J_gens_raw = witness.get('J_gens', [])
        I_gens_raw = witness.get('I_gens', [])
        P_gens_raw = witness.get('P_gens', [])
        f_raw = witness.get('f', 1)
        n = witness.get('n', 0)
        
        all_gens = J_gens_raw + I_gens_raw + P_gens_raw + [f_raw]
        if not all(is_monomial(g) for g in all_gens):
            return [False, False, False, False]
            
        J_gens = [strip_coeff(g) for g in J_gens_raw]
        I_gens = [strip_coeff(g) for g in I_gens_raw]
        P_gens = [strip_coeff(g) for g in P_gens_raw]
        f = strip_coeff(f_raw)
        K_gens = J_gens + I_gens
        
        # H1: I is a proper ideal of R
        h1 = True
        for g in K_gens:
            if g == 1:
                h1 = False
                break
                
        # H2: I is generated by exactly n elements
        h2 = len(I_gens_raw) == n
        
        # H3: The height of the ideal I is exactly n
        h_I = height_of_ideal_in_R(I_gens, J_gens)
        h3 = (h_I == n)
        
        # neg_Q: There exists an associated prime ideal of R/I whose height is not exactly n
        is_prime = all(hasattr(g, 'is_Symbol') and g.is_Symbol for g in P_gens)
        quotient_gens = ideal_quotient_monomial(K_gens, f)
        is_assoc = ideals_equal(P_gens, quotient_gens)
        
        P_vars = set(P_gens)
        h_P = height_of_prime_in_R(P_vars, J_gens)
        
        neg_q = is_prime and is_assoc and (h_P is not None) and (h_P != n)
        
        return [h1, h2, h3, neg_q]
    except Exception:
        return [False, False, False, False]

