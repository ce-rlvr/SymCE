import sympy as sp

# Top-level setup: named object bindings that the witness expression may reference.
# We define standard variables for polynomial rings.
x, y, z, t, u, v = sp.symbols('x y z t u v')

def conditions(witness) -> list[bool]:
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness is expected to be a tuple: (gens, vars)
    where `gens` is a list of polynomial generators for the ideal I,
    and `vars` is a list of variables defining the polynomial ring R over QQ.
    """
    try:
        gens, vars = witness
        if not isinstance(gens, (list, tuple)) or not isinstance(vars, (list, tuple)):
            return [False, False]
        if len(gens) == 0 or len(vars) == 0:
            return [False, False]
            
        # Compute the reduced Groebner basis over the rationals
        gb_obj = sp.groebner(gens, *vars, domain='QQ')
        gb = [p.as_expr() for p in gb_obj.polys]
    except Exception:
        return [False, False]

    # H_1: I is a non-zero proper ideal of R
    try:
        is_non_zero = any(sp.expand(g) != 0 for g in gens)
        is_proper = (gb != [sp.S(1)])
        h1_ok = bool(is_non_zero and is_proper)
    except Exception:
        h1_ok = False

    # ¬Q: I is primary iff I = (p^n) for some prime p and n >= 1
    try:
        # Check if I is principal (generated by a single element)
        is_principal = (len(gb) == 1)
        
        # Check if I = (p^n) for some prime p
        is_p_n = False
        if is_principal:
            f = gb[0]
            if f != 0 and f != 1:
                factors = sp.factor_list(f)
                # factors is of the form (constant, [(irreducible_factor, power), ...])
                if len(factors[1]) == 1:
                    is_p_n = True
                    
        # Check if I is primary
        is_primary = False
        if is_principal:
            # In a UFD, a principal ideal (f) is primary iff f = p^n for some prime p
            is_primary = is_p_n
        else:
            # For non-principal ideals, we first check if the radical is maximal.
            # If the radical contains all variables, it is the maximal ideal (x1, ..., xk),
            # and any ideal whose radical is maximal is primary.
            t_dummy = sp.Dummy('t')
            all_in_radical = True
            for var in vars:
                test_gens = list(gens) + [1 - t_dummy * var]
                test_vars = list(vars) + [t_dummy]
                try:
                    test_gb = sp.groebner(test_gens, *test_vars, domain='QQ').polys
                    test_gb_expr = [p.as_expr() for p in test_gb]
                    if test_gb_expr != [sp.S(1)]:
                        all_in_radical = False
                        break
                except Exception:
                    all_in_radical = False
                    break
                    
            if all_in_radical:
                is_primary = True
            else:
                # Fallback: check if it is a monomial ideal
                is_monomial_ideal = True
                for p in gb:
                    poly_p = sp.Poly(p, *vars)
                    if len(poly_p.terms()) != 1:
                        is_monomial_ideal = False
                        break
                        
                if is_monomial_ideal:
                    appearing_vars = set()
                    for p in gb:
                        appearing_vars.update(p.free_symbols.intersection(set(vars)))
                    
                    # A monomial ideal is primary iff for every variable appearing in its generators,
                    # some pure power of that variable is also a generator.
                    is_primary = True
                    for var in appearing_vars:
                        has_pure_power = False
                        for p in gb:
                            if p.free_symbols.intersection(set(vars)) == {var}:
                                has_pure_power = True
                                break
                        if not has_pure_power:
                            is_primary = False
                            break
                else:
                    # If we cannot determine if it's primary, we assume False to safely reject
                    is_primary = is_p_n
                    
        # The conclusion fails if the truth values of "is primary" and "is (p^n)" differ
        neg_q_ok = bool(is_primary != is_p_n)
    except Exception:
        neg_q_ok = False

    return [h1_ok, neg_q_ok]

