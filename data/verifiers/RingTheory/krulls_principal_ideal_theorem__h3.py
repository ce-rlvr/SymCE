import sympy as sp

# Top-level setup: named object bindings that the witness expression may reference.
# We provide standard symbols for constructing polynomial rings.
x, y, z, u, v, w = sp.symbols('x y z u v w')

CONDITION_LABELS = [
    "H_1: R is a commutative Noetherian ring (and P is a prime ideal)",
    "H_2: x is a non-unit element of R",
    "¬Q: The height of the prime ideal P is > 1"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    """
    Checks if the witness is a valid counterexample.
    The witness is expected to be a tuple: (vars, x_elem, P_gens)
    where:
      - vars: a list of sympy Symbols representing the variables of the polynomial ring R = Q[vars].
      - x_elem: a sympy expression representing the element x in R.
      - P_gens: a list of sympy expressions generating the prime ideal P.
    """
    try:
        vars, x_elem, P_gens = witness
    except Exception:
        return [False, False, False]
        
    # H1: R is a commutative Noetherian ring (and P is a prime ideal)
    # R = Q[vars] is always a commutative Noetherian ring.
    # We verify that P is a prime ideal by checking if P_gens are linear polynomials
    # that do not generate the unit ideal (i.e., the linear system is consistent).
    h1 = False
    try:
        if isinstance(vars, (list, tuple)) and all(isinstance(v, sp.Symbol) for v in vars):
            is_prime_ideal = True
            for p in P_gens:
                poly = sp.Poly(p, *vars)
                if poly.total_degree() > 1:
                    is_prime_ideal = False
                    break
            
            if is_prime_ideal:
                if not P_gens:
                    h1 = True
                else:
                    # Check if the linear system P_gens = 0 is consistent
                    A = sp.Matrix([[sp.diff(p, v) for v in vars] for p in P_gens])
                    B = sp.Matrix([-p.subs({v: 0 for v in vars}) for p in P_gens])
                    A_aug = A.row_join(B)
                    if A.rank() == A_aug.rank():
                        h1 = True
    except Exception:
        h1 = False

    # H2: x is a non-unit element of R
    # In Q[vars], the units are exactly the non-zero constants.
    h2 = False
    try:
        poly_x = sp.Poly(x_elem, *vars)
        if poly_x.is_zero:
            h2 = True
        elif poly_x.total_degree() > 0:
            h2 = True
    except Exception:
        h2 = False

    # neg_Q: The height of the prime ideal P is > 1
    # For an ideal generated by linear polynomials in Q[vars], the height is the rank of the Jacobian matrix.
    neg_q = False
    try:
        if h1:
            if not P_gens:
                height = 0
            else:
                A = sp.Matrix([[sp.diff(p, v) for v in vars] for p in P_gens])
                height = A.rank()
            if height > 1:
                neg_q = True
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]