def conditions(witness):
    # H_1: A is an m \times n matrix with entries in R
    try:
        h1_ok = isinstance(witness, MatrixBase)
    except Exception:
        h1_ok = False

    # ¬Q: A does not have a Smith Normal Form
    # If A has a Smith Normal Form D = diag(d_1, ..., d_r, 0, ..., 0) with d_i | d_{i+1},
    # then the k-th determinantal ideal I_k(A) must be equal to I_k(D).
    # Since I_k(D) is generated by the single element d_1 * ... * d_k, 
    # a necessary condition for SNF to exist is that all determinantal ideals of A are principal.
    # We check if any determinantal ideal is non-principal by computing its Groebner basis.
    neg_q_ok = False
    try:
        if h1_ok:
            vars = list(witness.free_symbols)
            if vars:
                m, n = witness.shape
                for k in range(1, min(m, n) + 1):
                    minors = []
                    for rows in itertools.combinations(range(m), k):
                        for cols in itertools.combinations(range(n), k):
                            sub_A = witness.extract(rows, cols)
                            minors.append(sub_A.det())
                    
                    minors = [m_val for m_val in minors if m_val != 0]
                    if not minors:
                        continue
                        
                    try:
                        # Check if all coefficients are integers to use ZZ domain
                        is_zz = True
                        for m_val in minors:
                            p = Poly(m_val, *vars)
                            if not all(c.is_integer for c in p.coeffs()):
                                is_zz = False
                                break
                        
                        if is_zz:
                            gb = groebner(minors, *vars, domain='ZZ')
                        else:
                            gb = groebner(minors, *vars)
                    except Exception:
                        try:
                            # Fallback if domain detection or ZZ computation fails
                            gb = groebner(minors, *vars)
                        except Exception:
                            continue
                            
                    # In polynomial rings over a field or ZZ, a principal ideal 
                    # has a reduced Groebner basis of exactly length 1.
                    if len(gb) > 1:
                        neg_q_ok = True
                        break
    except Exception:
        neg_q_ok = False

    return [h1_ok, neg_q_ok]

