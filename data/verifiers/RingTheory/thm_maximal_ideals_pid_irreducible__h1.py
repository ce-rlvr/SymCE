import sympy
from sympy.abc import x, y
from sympy.ntheory import isprime

# Top-level setup
# The witness is expected to be a tuple (R_str, p) where R_str is a string like "ZZ[x]"
# and p is a sympy expression. If witness is just an expression, R_str defaults to "ZZ[x]".

def is_irreducible(R_str, p):
    if R_str == "ZZ":
        return isprime(abs(int(p)))
    elif R_str == "QQ":
        return False
    elif R_str == "ZZ[x]":
        p_poly = sympy.Poly(p, x, domain='ZZ')
        if p_poly.degree() <= 0:
            if p_poly.is_zero:
                return False
            return isprime(abs(int(p_poly.nth(0))))
        else:
            u, factors = sympy.factor_list(p, domain='ZZ')
            if len(factors) == 1 and factors[0][1] == 1 and abs(u) == 1:
                return True
            return False
    elif R_str == "QQ[x]":
        p_poly = sympy.Poly(p, x, domain='QQ')
        if p_poly.degree() <= 0:
            return False
        u, factors = sympy.factor_list(p, domain='QQ')
        if len(factors) == 1 and factors[0][1] == 1:
            return True
        return False
    elif R_str == "ZZ[x,y]":
        p_poly = sympy.Poly(p, x, y, domain='ZZ')
        if p_poly.degree() <= 0:
            if p_poly.is_zero:
                return False
            return isprime(abs(int(p_poly.nth(0, 0))))
        else:
            u, factors = sympy.factor_list(p, domain='ZZ')
            if len(factors) == 1 and factors[0][1] == 1 and abs(u) == 1:
                return True
            return False
    return False

def is_maximal(R_str, p):
    if R_str == "ZZ":
        return isprime(abs(int(p)))
    elif R_str == "QQ":
        return False
    elif R_str == "ZZ[x]":
        return False
    elif R_str == "QQ[x]":
        p_poly = sympy.Poly(p, x, domain='QQ')
        if p_poly.degree() <= 0:
            return False
        u, factors = sympy.factor_list(p, domain='QQ')
        if len(factors) == 1 and factors[0][1] == 1:
            return True
        return False
    elif R_str == "ZZ[x,y]":
        return False
    return False

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            R_str, p = witness
        else:
            R_str = "ZZ[x]"
            p = witness
            
        # H1: p is a non-zero element of R
        try:
            if R_str == "ZZ":
                if isinstance(p, float) or (hasattr(p, 'is_Float') and p.is_Float):
                    h1 = False
                else:
                    h1 = (int(p) != 0)
            elif R_str == "QQ":
                h1 = (float(p) != 0)
            else:
                if R_str in ["ZZ[x]", "QQ[x]"]:
                    h1 = not sympy.Poly(p, x).is_zero
                elif R_str == "ZZ[x,y]":
                    h1 = not sympy.Poly(p, x, y).is_zero
                else:
                    h1 = False
        except Exception:
            h1 = False

        # Conclusion: (p) is maximal iff p is irreducible
        try:
            irr = is_irreducible(R_str, p)
            maxi = is_maximal(R_str, p)
            neg_q = (irr != maxi)
        except Exception:
            neg_q = False

        return [h1, neg_q]
    except Exception:
        return [False, False]

