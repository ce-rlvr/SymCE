import math
import sympy

# Top-level setup
# The witness is expected to be a tuple (n, I_gen, S) representing:
# - n: an integer >= 2, the modulus for the ring R = Z/nZ
# - I_gen: an integer, the generator for the ideal I in Z/nZ
# - S: an iterable of integers, representing the subset S of Z/nZ

def conditions(witness) -> list[bool]:
    try:
        n, I_gen, S = witness
        n = int(n)
        I_gen = int(I_gen)
        S = list(S)
    except Exception:
        return [False, False, False, False]

    # H_1: R is a commutative ring with identity
    try:
        h1 = (n >= 2)
    except Exception:
        h1 = False

    # H_2: I is an ideal of R such that the intersection of I and S is empty
    try:
        h2 = False
        if h1:
            I_set = set((I_gen * x) % n for x in range(n))
            S_set = set(s % n for s in S)
            h2 = I_set.isdisjoint(S_set)
    except Exception:
        h2 = False

    # H_3: For any ideal J of R strictly containing I, the intersection of J and S is non-empty
    try:
        h3 = False
        if h1:
            I_set = set((I_gen * x) % n for x in range(n))
            S_set = set(s % n for s in S)
            
            # In Z/nZ, all ideals are principal and generated by divisors of n.
            divisors = [d for d in range(1, n + 1) if n % d == 0]
            all_intersect = True
            
            for d in divisors:
                J_set = set((d * x) % n for x in range(n))
                if I_set < J_set:  # J strictly contains I
                    if J_set.isdisjoint(S_set):
                        all_intersect = False
                        break
            h3 = all_intersect
    except Exception:
        h3 = False

    # neg_Q: I is not a prime ideal of R
    try:
        neg_q = False
        if h1:
            # In Z/nZ, an ideal <k> is prime iff the quotient ring Z/nZ / <k> is an integral domain.
            # The quotient ring is isomorphic to Z/gcd(k, n)Z.
            # Z/mZ is an integral domain iff m is a prime number.
            is_prime_ideal = sympy.isprime(math.gcd(I_gen, n))
            neg_q = not is_prime_ideal
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

