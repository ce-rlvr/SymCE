# Top-level setup
t = sp.Symbol('t')

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "If R is an integral domain, then R[x] is integrally closed in its field of fractions."
    
    A valid counterexample is an integral domain R that is NOT integrally closed.
    We support witnesses provided as a list of polynomials in a single variable (e.g., [t**2, t**3]),
    which generate a subring of k[t].
    """
    try:
        # Handle string witnesses for common known counterexamples
        if isinstance(witness, str):
            w = witness.replace(" ", "").lower()
            if w in ["z[sqrt(5)]", "z[sqrt(-3)]", "z[i*sqrt(3)]", "k[t^2,t^3]", "q[t^2,t^3]", "z[t^2,t^3]"]:
                return [True, True]
                
        if not isinstance(witness, (list, tuple, set)):
            return [False, False]
            
        witness = list(witness)
        if len(witness) == 0:
            return [False, False]
            
        if not all(isinstance(expr, sp.Expr) for expr in witness):
            return [False, False]
            
        symbols = set()
        for expr in witness:
            symbols.update(expr.free_symbols)
            
        # We only support subrings of k[t] generated by polynomials in 1 variable
        if len(symbols) != 1:
            return [False, False]
            
        t_sym = list(symbols)[0]
        
        if not all(expr.is_polynomial(t_sym) for expr in witness):
            return [False, False]
            
        # H_1: R is an integral domain
        # Any subring of k[t] is an integral domain.
        h1 = True
        
        # ¬Q: R[x] is NOT integrally closed in its field of fractions
        # R[x] is integrally closed iff R is integrally closed.
        # By Luroth's theorem, the fraction field k(f_1, ..., f_n) is equal to k(g) for some polynomial g.
        # The integral closure of k[f_1, ..., f_n] is exactly k[g].
        # We can find g(X) - g(Y) as the GCD of f_i(X) - f_i(Y).
        X = sp.Symbol('X')
        Y = sp.Symbol('Y')
        gcd_poly = None
        for expr in witness:
            poly_X = expr.subs(t_sym, X)
            poly_Y = expr.subs(t_sym, Y)
            diff = sp.expand(poly_X - poly_Y)
            if gcd_poly is None:
                gcd_poly = diff
            else:
                gcd_poly = sp.gcd(gcd_poly, diff)
                
        if gcd_poly == 0 or gcd_poly.is_number:
            # The ring is just constants (a field), which is integrally closed.
            return [h1, False]
            
        # Extract the generator g(t) of the integral closure
        g_X = gcd_poly.subs(Y, 0)
        g_t = g_X.subs(X, t_sym)
        
        # Check if g_t is in the subring k[f_1, ..., f_n] using Groebner bases
        y_vars = sp.symbols(f'y0:{len(witness)}')
        
        polys = []
        for i, expr in enumerate(witness):
            polys.append(y_vars[i] - expr)
            
        # Compute Groebner basis with lexicographic order t > y_i
        gb = sp.groebner(polys, t_sym, *y_vars, order='lex')
        
        # Reduce g_t modulo the Groebner basis
        res = sp.reduced(g_t, gb, (t_sym, *y_vars), order='lex')
        reduced_g_t = res[1] if isinstance(res, tuple) and len(res) == 2 else res
        
        # If the normal form contains t, then g_t is NOT in the ring, so it's not integrally closed.
        is_integrally_closed = not reduced_g_t.has(t_sym)
        neg_q = not is_integrally_closed
        
        return [h1, neg_q]
        
    except Exception:
        return [False, False]

