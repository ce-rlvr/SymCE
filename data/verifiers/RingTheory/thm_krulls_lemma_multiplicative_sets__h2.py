# Expected witness format:
# witness = (n, I, S)
# where:
#   n is an integer >= 2, representing the commutative ring Z/nZ
#   I is an integer (generator) or an iterable of integers (elements of the ideal)
#   S is an integer (single element) or an iterable of integers (elements of the subset S)

def conditions(witness) -> list[bool]:
    try:
        if len(witness) != 3:
            return [False, False, False]
            
        n, I_input, S_input = witness
        n = int(n)
        if n < 2 or n > 1000:
            return [False, False, False]
            
        if isinstance(I_input, (int, sympy.Integer)):
            I = set((k * int(I_input)) % n for k in range(n))
        else:
            I = set(int(x) % n for x in I_input)
            
        if isinstance(S_input, (int, sympy.Integer)):
            S = {int(S_input) % n}
        else:
            S = set(int(x) % n for x in S_input)
            
        # H_1: R is a commutative ring
        # Z/nZ is always a commutative ring for n >= 2
        h1 = True
        
        # H_2: I is an ideal of R that is maximal with respect to the property of being disjoint from S
        is_ideal = True
        if not I or 0 not in I:
            is_ideal = False
        else:
            # Check closure under addition
            for a in I:
                for b in I:
                    if (a + b) % n not in I:
                        is_ideal = False
                        break
                if not is_ideal:
                    break
            # Check closure under scalar multiplication
            if is_ideal:
                for a in I:
                    for r in range(n):
                        if (a * r) % n not in I:
                            is_ideal = False
                            break
                    if not is_ideal:
                        break
                        
        is_disjoint = I.isdisjoint(S)
        
        is_maximal = True
        if is_ideal and is_disjoint:
            # In Z/nZ, every ideal is principal and generated by a divisor of n
            for d in range(1, n + 1):
                if n % d == 0:
                    J = set((k * d) % n for k in range(n // d))
                    if I.issubset(J) and I != J:
                        if J.isdisjoint(S):
                            is_maximal = False
                            break
                            
        h2 = is_ideal and is_disjoint and is_maximal
        
        # ¬Q: I is not a prime ideal of R
        is_prime = True
        if len(I) == n:
            is_prime = False
        else:
            for a in range(n):
                for b in range(n):
                    if (a * b) % n in I:
                        if a not in I and b not in I:
                            is_prime = False
                            break
                if not is_prime:
                    break
                    
        neg_q = not is_prime
        
        return [h1, h2, neg_q]
    except Exception:
        return [False, False, False]

