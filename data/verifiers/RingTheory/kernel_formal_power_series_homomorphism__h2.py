def conditions(witness) -> list[bool]:
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The conjecture claims that the kernel of the induced formal power series 
    ring homomorphism f_x is the ideal ker(f)_x.
    
    This is false in general because if ker(f) is not finitely generated, 
    the ideal generated by ker(f) in R_x is strictly smaller than the set 
    of all formal power series with coefficients in ker(f). Alternatively, 
    if f is not a ring homomorphism, ker(f)_x is not an ideal.
    """
    h1, h2, neg_q = False, False, False

    # 1. Witness as a dictionary
    if isinstance(witness, dict):
        try:
            h1 = bool(witness.get('R_is_commutative', False) and witness.get('S_is_commutative', False))
            h2 = bool(witness.get('f_x_is_induced_homomorphism', False))
            
            not_fg = not bool(witness.get('ker_is_finitely_generated', True))
            not_hom = not bool(witness.get('f_is_ring_homomorphism', True))
            neg_q = not_fg or not_hom
            return [h1, h2, neg_q]
        except Exception:
            pass

    # 2. Witness as an object with R and S attributes
    try:
        if hasattr(witness, 'R') and hasattr(witness, 'S'):
            h1 = bool(getattr(witness.R, 'is_commutative', False) and getattr(witness.S, 'is_commutative', False))
            h2 = bool(getattr(witness, 'f_x_is_induced_homomorphism', True))
            
            not_fg = False
            if hasattr(witness, 'ker'):
                not_fg = not bool(getattr(witness.ker, 'is_finitely_generated', True))
            elif hasattr(witness, 'ker_is_finitely_generated'):
                not_fg = not bool(witness.ker_is_finitely_generated)
                
            not_hom = not bool(getattr(witness, 'is_ring_homomorphism', True))
            
            neg_q = not_fg or not_hom
            return [h1, h2, neg_q]
    except Exception:
        pass

    # 3. Witness as a tuple (R, S, f)
    if isinstance(witness, tuple) and len(witness) == 3:
        try:
            R, S, f = witness
            h1 = bool(getattr(R, 'is_commutative', True) and getattr(S, 'is_commutative', True))
            h2 = True
            
            not_fg = False
            if hasattr(f, 'ker'):
                not_fg = not bool(getattr(f.ker, 'is_finitely_generated', True))
            elif hasattr(f, 'ker_is_finitely_generated'):
                not_fg = not bool(f.ker_is_finitely_generated)
                
            not_hom = not bool(getattr(f, 'is_ring_homomorphism', True))
            
            neg_q = not_fg or not_hom
            return [h1, h2, neg_q]
        except Exception:
            pass

    # 4. Witness as an object with flat attributes
    try:
        h1 = bool(getattr(witness, 'R_is_commutative', False) and getattr(witness, 'S_is_commutative', False))
        h2 = bool(getattr(witness, 'f_x_is_induced_homomorphism', False))
        
        not_fg = not bool(getattr(witness, 'ker_is_finitely_generated', True))
        not_hom = not bool(getattr(witness, 'f_is_ring_homomorphism', True))
        neg_q = not_fg or not_hom
        
        if h1 or h2 or neg_q:
            return [h1, h2, neg_q]
    except Exception:
        pass

    # 5. Witness as a SymPy Ideal (representing ker(f))
    try:
        if hasattr(witness, 'is_finitely_generated') and hasattr(witness, 'ring'):
            h1 = bool(getattr(witness.ring, 'is_commutative', True))
            h2 = True
            neg_q = not bool(witness.is_finitely_generated)
            return [h1, h2, neg_q]
    except Exception:
        pass

    return [False, False, False]

