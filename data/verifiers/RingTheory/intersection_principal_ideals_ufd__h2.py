CONDITION_LABELS = [
    "H_1: R is a unique factorization domain",
    "¬Q: The intersection (a) \\cap (b) is not equal to the principal ideal (lcm(a, b))"
]

N_HYP = 1
NEG_Q_INDEX = 1

def conditions(witness):
    try:
        if isinstance(witness, (tuple, list)):
            if len(witness) == 3:
                R, a, b = witness
            elif len(witness) == 2:
                a, b = witness
                a_sym = sympy.sympify(a)
                if a_sym.is_Integer:
                    R = sympy.ZZ
                elif a_sym.is_Rational:
                    R = sympy.QQ
                elif hasattr(a, 'ring'):
                    R = a.ring
                elif hasattr(a, 'domain'):
                    R = a.domain
                else:
                    return [False, False]
            else:
                return [False, False]
        else:
            return [False, False]
    except Exception:
        return [False, False]

    # H_1: R is a UFD
    try:
        h1 = bool(R.is_UFD)
    except Exception:
        h1 = False

    # neg_Q: (a) \cap (b) != (lcm(a, b))
    try:
        if hasattr(R, 'lcm'):
            l = R.lcm(a, b)
        else:
            l = sympy.lcm(a, b)
            
        try:
            I_a = R.ideal(a)
            I_b = R.ideal(b)
            I_lcm = R.ideal(l)
            conclusion_holds = (I_a.intersect(I_b) == I_lcm)
        except Exception:
            # If ideal intersection cannot be computed directly (e.g. in ZZ), 
            # we assume it holds because in any domain, if the LCM exists, 
            # the intersection of principal ideals is generated by their LCM.
            conclusion_holds = True
            
        neg_q = not conclusion_holds
    except Exception:
        # If LCM fails to compute or raises an error, the principal ideal (lcm(a, b)) 
        # does not exist, meaning the conclusion fails.
        neg_q = True

    return [h1, neg_q]