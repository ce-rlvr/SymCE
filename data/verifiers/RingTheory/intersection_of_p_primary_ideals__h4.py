# Top-level setup for potential witness expressions
Z = sympy.S.Integers
Q = sympy.S.Rationals

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "If R is a commutative ring with identity, P is a prime ideal, and q_1, ..., q_k 
    are primary ideals, then their intersection is a primary ideal and its radical is P."
    
    The witness is expected to be ideals in Z, represented by their integer generators.
    Format can be a dict like {'P': 2, 'qs': [4, 9]} or a tuple like (2, [4, 9]).
    """
    try:
        if isinstance(witness, dict):
            P_gen = abs(int(witness.get('P', witness.get('P_gen', 0))))
            qs_raw = witness.get('qs', witness.get('q', witness.get('q_i', [])))
            if not isinstance(qs_raw, (list, tuple, set)):
                qs_raw = [qs_raw]
            qs = []
            for q in qs_raw:
                qs.append(abs(int(q)))
        else:
            ints = []
            def flatten(obj):
                if isinstance(obj, (int, sympy.Integer)):
                    ints.append(int(obj))
                elif isinstance(obj, (list, tuple, set)):
                    for item in obj:
                        flatten(item)
                else:
                    try:
                        val = int(obj)
                        ints.append(val)
                    except Exception:
                        pass
            flatten(witness)
            if len(ints) < 2:
                return [False, False, False, False]
            P_gen = abs(ints[0])
            qs = [abs(q) for q in ints[1:]]
            
        if not qs:
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]

    # H1: R is a commutative ring with identity
    # We evaluate in Z, which is a commutative ring with identity.
    h1 = True

    # H2: P is a prime ideal of R
    # In Z, an ideal (n) is prime iff n is prime or n = 0.
    try:
        if P_gen == 0:
            h2 = True
        else:
            h2 = sympy.isprime(P_gen)
    except Exception:
        h2 = False

    # H3: q_1, ..., q_k are primary ideals of R
    # In Z, an ideal (n) is primary iff n = p^k for some prime p (k>=1) or n = 0.
    try:
        h3 = True
        for q in qs:
            if q == 0:
                continue
            if q == 1:
                h3 = False
                break
            factors = sympy.factorint(q)
            if len(factors) != 1:
                h3 = False
                break
    except Exception:
        h3 = False

    # neg_Q: The intersection is NOT a primary ideal OR its radical is NOT P
    # The intersection of (q_1), ..., (q_k) in Z is generated by their LCM.
    try:
        L = qs[0]
        for q in qs[1:]:
            L = sympy.lcm(L, q)
            
        is_L_primary = False
        if L == 0:
            is_L_primary = True
        elif L > 1:
            factors_L = sympy.factorint(L)
            if len(factors_L) == 1:
                is_L_primary = True
                
        if L == 0:
            rad_L = 0
        elif L == 1:
            rad_L = 1
        else:
            rad_L = 1
            for p in sympy.factorint(L):
                rad_L *= p
                
        is_rad_P = (rad_L == P_gen)
        
        conclusion = is_L_primary and is_rad_P
        neg_q = not conclusion
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

