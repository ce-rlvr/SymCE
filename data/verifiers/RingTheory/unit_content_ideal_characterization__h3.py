import sympy
from sympy import Poly
from sympy.abc import x, y, z

def conditions(witness):
    """
    Evaluates the hypotheses and the negated conclusion for the given witness.
    
    The conjecture is:
    "The content ideal c(f) is the unit ideal R if and only if for every maximal ideal m of R, f not in mR[x]"
    
    Remaining hypotheses:
      - R is a commutative ring with identity
      - f is a polynomial in R[x]
    """
    try:
        h1_ok = False
        h2_ok = False
        neg_q_ok = False
        
        # Fallback for custom witness objects
        if hasattr(witness, 'c_f_is_R') and hasattr(witness, 'forall_m'):
            h1_ok = getattr(witness, 'is_commutative_ring_with_identity', True)
            h2_ok = getattr(witness, 'is_polynomial', True)
            neg_q_ok = (witness.c_f_is_R != witness.forall_m)
            return [bool(h1_ok), bool(h2_ok), bool(neg_q_ok)]
            
        if isinstance(witness, Poly):
            domain = witness.domain
            h1_ok = domain.is_CommutativeRing
            if not h1_ok:
                h1_ok = True # Assume true if SymPy domain
            h2_ok = True
            
            coeffs = witness.coeffs()
            if not coeffs:
                return [h1_ok, h2_ok, False]
                
            # Compute GCD of coefficients
            c_f = coeffs[0]
            for c in coeffs[1:]:
                if hasattr(domain, 'gcd'):
                    c_f = domain.gcd(c_f, c)
                else:
                    c_f = sympy.gcd(c_f, c)
                    
            try:
                c_f_is_R = domain.is_unit(c_f)
            except Exception:
                c_f_is_R = (c_f == domain.one or c_f == -domain.one or c_f == 1 or c_f == -1)
                
            # Compute if ideal generated by coeffs is R
            expr_coeffs = [getattr(c, 'as_expr', lambda: c)() for c in coeffs]
            free_vars = set()
            for c in expr_coeffs:
                if hasattr(c, 'free_symbols'):
                    free_vars.update(c.free_symbols)
            
            if free_vars:
                try:
                    gb_domain = domain
                    if hasattr(domain, 'dom'):
                        gb_domain = domain.dom
                    gb = sympy.groebner(expr_coeffs, *free_vars, domain=gb_domain)
                    forall_m = (len(gb) == 1 and gb[0] == 1)
                except Exception:
                    forall_m = c_f_is_R
            else:
                # For integers or rationals, GCD generates the ideal
                forall_m = c_f_is_R
                
            neg_q_ok = (c_f_is_R != forall_m)
            return [h1_ok, h2_ok, neg_q_ok]
            
        # Support tuple witness: ("ZZ[y]", [2, y])
        if isinstance(witness, tuple) and len(witness) == 2:
            ring_str, coeffs = witness
            if isinstance(ring_str, str) and isinstance(coeffs, list):
                h1_ok = True
                h2_ok = True
                parsed_coeffs = [sympy.sympify(c) for c in coeffs]
                
                if not parsed_coeffs:
                    return [h1_ok, h2_ok, False]
                    
                c_f = parsed_coeffs[0]
                for c in parsed_coeffs[1:]:
                    c_f = sympy.gcd(c_f, c)
                    
                c_f_is_R = (c_f == 1 or c_f == -1)
                
                free_vars = set()
                for c in parsed_coeffs:
                    if hasattr(c, 'free_symbols'):
                        free_vars.update(c.free_symbols)
                        
                if free_vars:
                    try:
                        domain_kwarg = {}
                        if "QQ" in ring_str:
                            domain_kwarg['domain'] = 'QQ'
                        elif "ZZ" in ring_str:
                            domain_kwarg['domain'] = 'ZZ'
                            
                        gb = sympy.groebner(parsed_coeffs, *free_vars, **domain_kwarg)
                        forall_m = (len(gb) == 1 and gb[0] == 1)
                    except Exception:
                        forall_m = c_f_is_R
                else:
                    # If no free vars, check if coprime
                    from sympy import gcd
                    from functools import reduce
                    g = reduce(gcd, parsed_coeffs)
                    forall_m = (g == 1 or g == -1)
                    
                neg_q_ok = (c_f_is_R != forall_m)
                return [h1_ok, h2_ok, neg_q_ok]
                
        return [False, False, False]
    except Exception:
        return [False, False, False]

