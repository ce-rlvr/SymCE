def conditions(witness) -> list[bool]:
    """
    Checks if the witness is a valid counterexample to the conjecture.
    The intended counterexample is a ring with zero divisors, such as R = Z/mZ,
    where the annihilator of rx is not generated by a / gcd(a, r).
    
    The witness can be provided as a tuple (m, a, r) representing the modulo m,
    and the elements a and r in Z/mZ.
    """
    try:
        # Parse witness
        m, a, r = None, None, None
        if hasattr(witness, 'm') and hasattr(witness, 'a') and hasattr(witness, 'r'):
            m, a, r = witness.m, witness.a, witness.r
        elif isinstance(witness, dict) and 'a' in witness and 'r' in witness:
            m = witness.get('m', 0)
            a = witness['a']
            r = witness['r']
        elif isinstance(witness, (tuple, list)):
            if len(witness) == 3:
                m, a, r = witness
            elif len(witness) == 2:
                m = 0
                a, r = witness
            elif len(witness) == 4:
                _, _, a, r = witness
                m = 0
                
        if m is None or a is None or r is None:
            return [False, False, False, False]
            
        m = abs(int(m))
        a = int(a)
        r = int(r)
        
        # H_1: M is an R-module
        # We can always construct M = (Z/mZ) / (a) and x = 1, so this is trivially satisfiable.
        h1 = True
        
        # H_2: x in M has annihilator generated by a non-zero element a in R
        if m > 0:
            h2 = (a % m) != 0
        else:
            h2 = a != 0
            
        # H_3: r is a non-zero element of R
        if m > 0:
            h3 = (r % m) != 0
        else:
            h3 = r != 0
            
        # ¬Q: The annihilator of rx is NOT generated by a / gcd(a, r)
        if m > 0:
            g = math.gcd(a, r)
            if g == 0:
                neg_q = False
            else:
                # The element proposed by the conclusion
                d = a // g
                
                # The actual annihilator of rx in Z/mZ is the ideal of s such that s*r is a multiple of a.
                # s*r = k*a mod m  =>  s*r is a multiple of gcd(a, m)
                A = math.gcd(a, m)
                
                # s * r = c * A  =>  s * (r / gcd(r, A)) = c * (A / gcd(r, A))
                # So s must be a multiple of A / gcd(r, A)
                gen_actual = A // math.gcd(r, A)
                
                # Two elements generate the same ideal in Z/mZ iff their gcd with m are equal
                neg_q = math.gcd(d, m) != math.gcd(gen_actual, m)
        else:
            # In Z (a PID), the conclusion always holds, so neg_Q is False
            neg_q = False
            
        return [h1, h2, h3, neg_q]
    except Exception:
        return [False, False, False, False]

