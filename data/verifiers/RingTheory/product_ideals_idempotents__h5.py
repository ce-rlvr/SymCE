import sympy
from sympy import ZZ, QQ
import math
import functools

# Top-level setup
# ZZ and QQ are provided as standard commutative rings for the witness.

def ideal_eq(R, gens1, gens2):
    """Helper to check if two sets of generators produce the same ideal in R."""
    if R == sympy.ZZ:
        g1 = functools.reduce(math.gcd, [int(x) for x in gens1], 0)
        g2 = functools.reduce(math.gcd, [int(x) for x in gens2], 0)
        return abs(g1) == abs(g2)
    elif R == sympy.QQ:
        g1 = 1 if any(x != 0 for x in gens1) else 0
        g2 = 1 if any(x != 0 for x in gens2) else 0
        return g1 == g2
    
    try:
        if hasattr(R, 'ideal'):
            return R.ideal(*gens1) == R.ideal(*gens2)
    except Exception:
        pass

    return False

def conditions(witness):
    try:
        if isinstance(witness, dict):
            R = witness.get('R')
            e = witness.get('e')
            f = witness.get('f')
            I = witness.get('I')
            J = witness.get('J')
        else:
            R, e, f, I, J = witness
            
        # Normalize common SymPy sets to their Ring equivalents
        if R == sympy.S.Integers:
            R = sympy.ZZ
        elif R == sympy.S.Rationals:
            R = sympy.QQ
    except Exception:
        return [False, False, False, False, False]
    
    # H1: R is a commutative ring
    try:
        h1 = bool(hasattr(R, 'is_commutative') and R.is_commutative and hasattr(R, 'is_Ring') and R.is_Ring)
    except Exception:
        h1 = False

    # H2: e is an idempotent element of R
    try:
        h2 = bool((e in R) and (e * e == e))
    except Exception:
        h2 = False

    # H3: f is an idempotent element of R
    try:
        h3 = bool((f in R) and (f * f == f))
    except Exception:
        h3 = False

    # H4: I is the principal ideal generated by e
    try:
        if hasattr(I, 'gens'):
            I_gens = list(I.gens)
        elif hasattr(I, '__iter__') and not isinstance(I, str):
            I_gens = list(I)
        else:
            I_gens = [I]
        h4 = bool(ideal_eq(R, I_gens, [e]))
    except Exception:
        h4 = False

    # neg_Q: The product ideal IJ is NOT the principal ideal generated by ef
    try:
        if hasattr(J, 'gens'):
            J_gens = list(J.gens)
        elif hasattr(J, '__iter__') and not isinstance(J, str):
            J_gens = list(J)
        else:
            J_gens = [J]
            
        IJ_gens = [x * y for x in I_gens for y in J_gens]
        neg_q = not ideal_eq(R, IJ_gens, [e * f])
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]

