def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, dict):
            R = witness.get('R')
            I = witness.get('I')
            f = witness.get('f')
            J = witness.get('J')
        elif isinstance(witness, tuple) and len(witness) == 4:
            R, I, f, J = witness
        else:
            R = getattr(witness, 'R', None)
            I = getattr(witness, 'I', None)
            f = getattr(witness, 'f', None)
            J = getattr(witness, 'J', None)
    except Exception:
        return [False, False, False, False, False]

    try:
        h1 = True
        if hasattr(R, 'is_commutative'):
            h1 = h1 and bool(R.is_commutative)
        if hasattr(R, 'has_identity'):
            h1 = h1 and bool(R.has_identity)
    except Exception:
        h1 = False

    try:
        h2 = True
        if hasattr(I, 'is_ideal'):
            h2 = h2 and bool(I.is_ideal)
        if hasattr(I, '__ne__'):
            h2 = h2 and bool(I != R)
    except Exception:
        h2 = False

    try:
        h3 = True
        if hasattr(f, 'is_polynomial'):
            h3 = h3 and bool(f.is_polynomial())
    except Exception:
        h3 = False

    try:
        h4 = True
        if hasattr(J, 'is_ideal'):
            h4 = h4 and bool(J.is_ideal)
    except Exception:
        h4 = False

    try:
        neg_q = False
        if hasattr(witness, 'is_isomorphic'):
            neg_q = not bool(witness.is_isomorphic())
        elif hasattr(witness, 'neg_Q'):
            neg_q = bool(witness.neg_Q() if callable(witness.neg_Q) else witness.neg_Q)
        elif isinstance(witness, dict) and 'neg_Q' in witness:
            neg_q = bool(witness['neg_Q'])
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]

