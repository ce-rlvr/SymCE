class QuadraticInteger:
    """
    Represents an element u + v*sqrt(D) in the quadratic integer ring Z[sqrt(D)].
    Assumes D is a square-free integer. For simplicity in finding divisors, 
    we primarily support D < 0.
    """
    def __init__(self, u, v, D):
        self.u = u
        self.v = v
        self.D = D

    def __eq__(self, other):
        if isinstance(other, QuadraticInteger):
            return self.u == other.u and self.v == other.v and self.D == other.D
        return False

    def __add__(self, other):
        return QuadraticInteger(self.u + other.u, self.v + other.v, self.D)

    def __sub__(self, other):
        return QuadraticInteger(self.u - other.u, self.v - other.v, self.D)

    def __mul__(self, other):
        return QuadraticInteger(
            self.u * other.u + self.v * other.v * self.D,
            self.u * other.v + self.v * other.u,
            self.D
        )

    def norm(self):
        return self.u**2 - self.D * self.v**2

    def is_zero(self):
        return self.u == 0 and self.v == 0

    def divides(self, other):
        n = self.norm()
        if n == 0:
            return other.is_zero()
        det_x = other.u * self.u - other.v * self.v * self.D
        det_y = self.u * other.v - self.v * other.u
        return det_x % n == 0 and det_y % n == 0

    def divided_by(self, other):
        n = other.norm()
        det_x = self.u * other.u - self.v * other.v * self.D
        det_y = self.v * other.u - self.u * other.v
        return QuadraticInteger(det_x // n, det_y // n, self.D)

def get_divisors(a):
    if a.is_zero():
        return []
    n = abs(a.norm())
    D = a.D
    if D >= 0:
        return []
    
    divisors = []
    for k in range(1, n + 1):
        if n % k == 0:
            abs_D = -D
            max_v = int((k / abs_D)**0.5) + 1
            for v in range(-max_v, max_v + 1):
                rem = k - abs_D * v**2
                if rem >= 0:
                    u = int(rem**0.5)
                    if u**2 == rem:
                        d1 = QuadraticInteger(u, v, D)
                        if d1.divides(a):
                            divisors.append(d1)
                        if u != 0:
                            d2 = QuadraticInteger(-u, v, D)
                            if d2.divides(a):
                                divisors.append(d2)
    return divisors

def get_gcd(a, b):
    divs_a = get_divisors(a)
    common = []
    for da in divs_a:
        if da.divides(b):
            common.append(da)
            
    gcds = []
    for g in common:
        is_gcd = True
        for c in common:
            if not c.divides(g):
                is_gcd = False
                break
        if is_gcd:
            gcds.append(g)
            
    return gcds

def check_conclusion(a, b):
    gcds = get_gcd(a, b)
    if not gcds:
        # If no GCD exists, the expression a / gcd(a,b) is undefined, so the conclusion fails.
        return True
    
    g = gcds[0]
    q = a.divided_by(g)
    
    # Check if (q) is a subset of ((a) : (b))
    if not a.divides(q * b):
        return True
        
    # Check if ((a) : (b)) is a subset of (q) by searching for a counterexample
    for u in range(-20, 21):
        for v in range(-20, 21):
            x = QuadraticInteger(u, v, a.D)
            if a.divides(x * b):
                if not q.divides(x):
                    return True
                    
    return False

def parse_sympy_to_quad(expr):
    expr = sp.sympify(expr)
    expr = sp.expand(expr)
    if expr.is_Integer:
        return QuadraticInteger(int(expr), 0, -5)
    
    sqrts = [a for a in expr.atoms(sp.Pow) if a.exp == sp.Rational(1, 2)]
    if len(sqrts) == 1:
        s = sqrts[0]
        if s.base.is_Integer:
            D = int(s.base)
            u = expr.subs(s, 0)
            v = sp.simplify((expr - u) / s)
            if u.is_Integer and v.is_Integer:
                return QuadraticInteger(int(u), int(v), D)
    return None

