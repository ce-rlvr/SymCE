def conditions(witness):
    try:
        if isinstance(witness, tuple):
            # Case 1: Witness is a tuple (n, a, b) representing elements a, b in Z/nZ
            if len(witness) == 3 and all(isinstance(x, int) for x in witness):
                n, a, b = witness
                h1 = (a % n != 0) and (b % n != 0) and (n > 1)
                
                # In Z/nZ, the ideal generated by a and b is generated by gcd(a, b, n)
                d = math.gcd(a, math.gcd(b, n))
                q = a // d
                
                ideal_q = set((k * q) % n for k in range(n))
                ideal_a = set((k * a) % n for k in range(n))
                ideal_quot = set(x for x in range(n) if (x * b) % n in ideal_a)
                
                neg_q = (ideal_q != ideal_quot)
                return [h1, neg_q]
                
            # Case 2: Witness is a tuple (a, b) representing elements in a quadratic integer ring
            if len(witness) == 2:
                a, b = witness
                
                if isinstance(a, QuadraticInteger) and isinstance(b, QuadraticInteger):
                    h1 = (not a.is_zero()) and (not b.is_zero())
                    neg_q = check_conclusion(a, b)
                    return [h1, neg_q]
                
                qa = parse_sympy_to_quad(a)
                qb = parse_sympy_to_quad(b)
                if qa is not None and qb is not None:
                    if qa.D != qb.D:
                        if qa.v == 0: qa.D = qb.D
                        elif qb.v == 0: qb.D = qa.D
                    
                    if qa.D == qb.D and qa.D < 0:
                        h1 = (not qa.is_zero()) and (not qb.is_zero())
                        neg_q = check_conclusion(qa, qb)
                        return [h1, neg_q]
    except Exception:
        pass
    
    return [False, False]