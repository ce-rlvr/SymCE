import math
import sympy
from sympy import Rational, Integer
from sympy.abc import x, y, z

def conditions(witness):
    """
    Checks the hypotheses and the negated conclusion for the false conjecture:
    Hypotheses:
      1. R is a commutative ring
      2. S and T are subsets of R
      3. J is the ideal generated by T
    Conclusion:
      The product ideal IJ is generated by the set {st | s \in S, t \in T}.
      
    The witness is expected to be a tuple (S, T, I, J) or (R, S, T, I, J),
    or a dictionary with keys 'S', 'T', 'I', 'J'.
    We evaluate the conditions in the ring of integers Z.
    Ideals I and J can be given as integer generators or lists of generators.
    """
    try:
        if isinstance(witness, dict):
            S = witness.get('S', [])
            T = witness.get('T', [])
            I = witness.get('I', 0)
            J = witness.get('J', 0)
        elif isinstance(witness, (tuple, list)):
            if len(witness) == 4:
                S, T, I, J = witness
            elif len(witness) == 5:
                _, S, T, I, J = witness
            else:
                return [False, False, False, False]
        else:
            return [False, False, False, False]
            
        S = list(S)
        T = list(T)
    except Exception:
        return [False, False, False, False]

    def list_gcd(lst):
        if not lst: 
            return 0
        g = int(lst[0])
        for val in lst[1:]:
            g = math.gcd(g, int(val))
        return g

    def get_ideal_gen(ideal_rep):
        if isinstance(ideal_rep, (int, sympy.Integer)):
            return int(ideal_rep)
        elif isinstance(ideal_rep, (list, tuple, set)):
            return list_gcd(list(ideal_rep))
        else:
            return int(ideal_rep)

    # H_1: R is a commutative ring
    # We implicitly evaluate the witness in Z, which is a commutative ring.
    try:
        h1 = True
    except Exception:
        h1 = False

    # H_2: S and T are subsets of R
    try:
        h2 = all(isinstance(val, (int, sympy.Integer)) for val in S) and \
             all(isinstance(val, (int, sympy.Integer)) for val in T)
    except Exception:
        h2 = False

    # H_3: J is the ideal generated by T
    try:
        J_gen = get_ideal_gen(J)
        h3 = abs(J_gen) == abs(list_gcd(T))
    except Exception:
        h3 = False

    # ¬Q: The product ideal IJ is NOT generated by the set {st | s in S, t in T}
    try:
        I_gen = get_ideal_gen(I)
        J_gen = get_ideal_gen(J)
        st_list = [int(s) * int(t) for s in S for t in T]
        gen_st = list_gcd(st_list)
        
        # The product ideal IJ is generated by I_gen * J_gen
        # We check if it differs from the ideal generated by {st | s in S, t in T}
        neg_q = abs(I_gen * J_gen) != abs(gen_st)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

