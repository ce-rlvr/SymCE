import sympy
from sympy.ntheory import factorint

# Top-level setup
# We evaluate the conjecture in the ring of integers Z, which is a commutative ring.
# The witness is expected to provide the generators for the ideals Q, I, and J.
Z = sympy.S.Integers

def conditions(witness):
    """
    Check the hypotheses and the negated conclusion for the conjecture.
    The witness should represent the ideals Q, I, J in Z by their integer generators.
    """
    try:
        if isinstance(witness, dict):
            q = witness.get('q', witness.get('Q', 0))
            i = witness.get('i', witness.get('I', 0))
            j = witness.get('j', witness.get('J', 0))
        else:
            q, i, j = witness
            
        # Extract generator if provided as a collection (e.g., list or tuple of generators)
        if isinstance(q, (list, tuple, set)): q = next(iter(q))
        if isinstance(i, (list, tuple, set)): i = next(iter(i))
        if isinstance(j, (list, tuple, set)): j = next(iter(j))
        
        q = int(q)
        i = int(i)
        j = int(j)
    except Exception:
        return [False, False, False, False]
        
    # H_1: R is a commutative ring
    # Z is a commutative ring, so this is trivially True for valid integer witnesses.
    h1_ok = True
    
    # H_2: Q is a primary ideal of R
    # In Z, an ideal (q) is primary iff q = 0 or |q| = p^n for some prime p and n >= 1.
    try:
        abs_q = abs(q)
        if abs_q == 0:
            h2_ok = True
        elif abs_q == 1:
            h2_ok = False
        else:
            factors = factorint(abs_q)
            h2_ok = (len(factors) == 1)
    except Exception:
        h2_ok = False
        
    # H_3: I \not\subseteq Q
    # In Z, (i) is a subset of (q) iff q divides i.
    try:
        if q == 0:
            h3_ok = (i != 0)
        else:
            h3_ok = (i % q != 0)
    except Exception:
        h3_ok = False
        
    # neg_Q: J \not\subseteq \sqrt{Q}
    # In Z, \sqrt{(q)} is generated by the product of distinct prime factors of q.
    try:
        abs_q = abs(q)
        if abs_q == 0:
            rad = 0
        elif abs_q == 1:
            rad = 1
        else:
            factors = factorint(abs_q)
            rad = 1
            for p in factors:
                rad *= p
        
        if rad == 0:
            neg_q_ok = (j != 0)
        else:
            neg_q_ok = (j % rad != 0)
    except Exception:
        neg_q_ok = False
        
    return [h1_ok, h2_ok, h3_ok, neg_q_ok]

