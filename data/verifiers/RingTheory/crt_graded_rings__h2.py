import sympy
from sympy import symbols, groebner, Poly, sympify
from sympy.abc import x, y, z, a, b, c

CONDITION_LABELS = [
    "H_1: R is a graded ring",
    "H_2: I and J are comaximal",
    "¬Q: The canonical map is not an isomorphism of graded rings"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    try:
        if not isinstance(witness, tuple) or len(witness) != 2:
            return [False, False, False]
        
        I_gens_raw, J_gens_raw = witness
        if not isinstance(I_gens_raw, list) or not isinstance(J_gens_raw, list):
            return [False, False, False]
            
        I_gens = [sympify(g) for g in I_gens_raw]
        J_gens = [sympify(g) for g in J_gens_raw]
        
        syms = set()
        for g in I_gens + J_gens:
            syms.update(g.free_symbols)
        syms = sorted(list(syms), key=lambda s: s.name)
        
        # H1: R is a graded ring
        # We assume R is the polynomial ring over QQ generated by the symbols in the witness.
        # A standard polynomial ring is always a graded ring.
        h1 = True
        
        # H2: I and J are comaximal
        try:
            combined = I_gens + J_gens
            if not combined:
                h2 = False
            elif all(g == 0 for g in combined):
                h2 = False
            elif not syms:
                h2 = any(g != 0 for g in combined)
            else:
                gb = groebner(combined, *syms, domain='QQ')
                h2 = len(gb) == 1 and gb[0].as_expr().is_number and gb[0].as_expr() != 0
        except Exception:
            h2 = False
            
        # neg_Q: The canonical map is not an isomorphism of graded rings
        # This happens if either I or J is not a homogeneous ideal.
        try:
            def is_homog(gens):
                if not gens: return True
                if all(g == 0 for g in gens): return True
                if not syms: return True
                gb = groebner(gens, *syms, order='grevlex', domain='QQ')
                for p in gb:
                    expr = p.as_expr()
                    if expr == 0: continue
                    poly = expr.as_poly(*syms)
                    if poly is None: return False
                    if not poly.is_homogeneous:
                        return False
                return True
                
            neg_q = not (is_homog(I_gens) and is_homog(J_gens))
        except Exception:
            neg_q = False
            
        return [h1, h2, neg_q]
    except Exception:
        return [False, False, False]