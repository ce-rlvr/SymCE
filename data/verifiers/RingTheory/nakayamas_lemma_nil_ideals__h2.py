import sympy
from sympy import ZZ, QQ
from sympy.abc import x, y, z

# Top-level setup
# The witness expression may reference ZZ, QQ, x, y, z.

def conditions(witness) -> list[bool]:
    """
    Expects witness to be a tuple (I_gens, M_gens) or (R, I_gens, M_gens)
    representing the generators of an ideal I and a module M over the ring R = ZZ.
    Generators can be integers or lists of integers.
    For example, witness = (1, 1) represents I = ZZ and M = ZZ.
    """
    try:
        if isinstance(witness, tuple):
            if len(witness) == 3:
                R, I_gens, M_gens = witness
            elif len(witness) == 2:
                I_gens, M_gens = witness
            else:
                return [False, False, False, False]
        else:
            return [False, False, False, False]
            
        def get_gen(gens):
            if isinstance(gens, (int, sympy.Integer)):
                return gens
            elif isinstance(gens, (list, tuple, set)):
                if len(gens) == 0:
                    return 0
                int_gens = [g for g in gens if isinstance(g, (int, sympy.Integer))]
                if int_gens:
                    return sympy.gcd_list(int_gens)
                else:
                    return None
            else:
                return None

        I_val = get_gen(I_gens)
        M_val = get_gen(M_gens)
        
        if I_val is None or M_val is None:
            return [False, False, False, False]
            
        # H_1: R is a commutative ring
        # We evaluate this in R = ZZ, which is commutative.
        h1 = True
        
        # H_2: M is a finitely generated R-module
        # A principal ideal in ZZ is finitely generated.
        h2 = True
        
        # H_3: The submodule IM is equal to M
        # In ZZ, IM is generated by I_val * M_val.
        h3 = (abs(I_val * M_val) == abs(M_val))
        
        # ¬Q: M is not the zero module
        neg_q = (M_val != 0)
        
        return [h1, h2, h3, neg_q]
    except Exception:
        return [False, False, False, False]

