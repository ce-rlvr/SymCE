import sympy

class Ring:
    def is_local(self):
        return False

class Ideal:
    def is_maximal(self):
        return False
    def contract(self, subring):
        raise NotImplementedError

class Z_localized(Ring):
    """
    Represents the localization of the integers Z at a prime ideal (p).
    This is a local ring with maximal ideal pZ_{(p)}.
    """
    def __init__(self, p):
        self.p = p

    def is_local(self):
        return sympy.isprime(self.p)

    def __eq__(self, other):
        return isinstance(other, Z_localized) and self.p == other.p

    def __str__(self):
        return f"Z_({self.p})"

class Field(Ring):
    """
    Represents a field (e.g., the field of rational numbers QQ).
    A field is trivially a local ring with maximal ideal {0}.
    """
    def __init__(self, name="F"):
        self.name = name

    def is_local(self):
        return True

    def is_field(self):
        return True

    def __eq__(self, other):
        return isinstance(other, Field) and self.name == other.name

QQ = Field("QQ")

class PrincipalIdeal(Ideal):
    """
    Represents a principal ideal generated by 'gen' in 'ring'.
    """
    def __init__(self, ring, gen):
        self.ring = ring
        self.gen = gen

    def is_maximal(self):
        if isinstance(self.ring, Z_localized):
            return sympy.isprime(self.ring.p) and self.gen == self.ring.p
        return False

    def __eq__(self, other):
        return isinstance(other, PrincipalIdeal) and self.ring == other.ring and self.gen == other.gen

class ZeroIdeal(Ideal):
    """
    Represents the zero ideal {0} in a ring.
    """
    def __init__(self, ring):
        self.ring = ring

    def is_maximal(self):
        return hasattr(self.ring, 'is_field') and self.ring.is_field()

    def contract(self, subring):
        """
        The contraction of the zero ideal to a subring is the zero ideal of the subring.
        """
        return ZeroIdeal(subring)

    def __eq__(self, other):
        return isinstance(other, ZeroIdeal) and self.ring == other.ring


def conditions(witness) -> list[bool]:
    try:
        R, m, S, n = witness
    except Exception:
        return [False, False, False]
    
    # H_1: R is a local ring with maximal ideal m
    try:
        h1 = (isinstance(R, Ring) and R.is_local() and 
              isinstance(m, Ideal) and m.ring == R and m.is_maximal())
    except Exception:
        h1 = False
        
    # H_2: n is a maximal ideal of S
    try:
        h2 = (isinstance(S, Ring) and 
              isinstance(n, Ideal) and n.ring == S and n.is_maximal())
    except Exception:
        h2 = False
        
    # ¬Q: The contraction of the ideal n to R is not exactly m
    try:
        contraction = n.contract(R)
        neg_q = not (contraction == m)
    except Exception:
        neg_q = False
        
    return [bool(h1), bool(h2), bool(neg_q)]


