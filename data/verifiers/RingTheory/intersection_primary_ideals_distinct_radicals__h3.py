import sympy
import sympy.abc
import math

# Top-level setup for potential witness expressions
x, y, z = sympy.abc.x, sympy.abc.y, sympy.abc.z
Z = sympy.S.Integers
Q = sympy.S.Rationals

def conditions(witness) -> list[bool]:
    """
    Checks the hypotheses and the negated conclusion for the false conjecture:
    Hypotheses:
      - R is a commutative ring
      - Q_1 is a P_1-primary ideal in R
      - P_1 is not contained in P_2
      - P_2 is not contained in P_1
    Conclusion:
      - The intersection Q_1 \cap Q_2 is not a primary ideal.
      
    We evaluate this in the ring of integers Z, where ideals are principal 
    and can be represented by their non-negative generators.
    """
    try:
        # Extract ideals (represented by their generators in Z)
        if isinstance(witness, dict):
            q1 = witness.get('Q_1', witness.get('q1'))
            q2 = witness.get('Q_2', witness.get('q2'))
            p1 = witness.get('P_1', witness.get('p1'))
            p2 = witness.get('P_2', witness.get('p2'))
        elif isinstance(witness, (list, tuple)):
            if len(witness) == 5:
                _, q1, q2, p1, p2 = witness
            elif len(witness) == 4:
                q1, q2, p1, p2 = witness
            else:
                return [False] * 5
        else:
            return [False] * 5
            
        def extract_gen(ideal):
            if hasattr(ideal, 'gens') and len(ideal.gens) == 1:
                return ideal.gens[0]
            return ideal

        q1 = abs(int(extract_gen(q1)))
        q2 = abs(int(extract_gen(q2)))
        p1 = abs(int(extract_gen(p1)))
        p2 = abs(int(extract_gen(p2)))
    except Exception:
        return [False] * 5

    def is_primary(q):
        if q == 1:
            return False
        if q == 0:
            return True
        factors = sympy.factorint(q)
        return len(factors) == 1

    def radical(q):
        if q == 0:
            return 0
        if q == 1:
            return 1
        factors = sympy.factorint(q)
        rad = 1
        for p in factors:
            rad *= p
        return rad

    def contains(a, b):
        # Ideal (a) contains ideal (b) iff a divides b
        if a == 0:
            return b == 0
        return b % a == 0

    # H_1: R is a commutative ring
    # Implicitly true as we are working with ideals in Z
    try:
        h1 = True
    except Exception:
        h1 = False

    # H_2: Q_1 is a P_1-primary ideal in R
    try:
        h2 = is_primary(q1) and radical(q1) == p1
    except Exception:
        h2 = False

    # H_3: P_1 is not contained in P_2
    try:
        h3 = not contains(p2, p1)
    except Exception:
        h3 = False

    # H_4: P_2 is not contained in P_1
    try:
        h4 = not contains(p1, p2)
    except Exception:
        h4 = False

    # ¬Q: The intersection Q_1 \cap Q_2 is a primary ideal
    # In Z, the intersection of ideals (a) and (b) is generated by lcm(a, b)
    try:
        q_int = math.lcm(q1, q2)
        neg_q = is_primary(q_int)
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]

