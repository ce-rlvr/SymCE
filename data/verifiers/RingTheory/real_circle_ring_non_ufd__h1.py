import sympy
from sympy import symbols, Poly
from sympy.polys.domains import CC, RR, QQ, ZZ, GF, Domain

# Top-level setup
x, y = symbols('x y')

def get_K(witness):
    if hasattr(witness, 'domain') and hasattr(witness, 'gens'):
        return witness.domain
    if isinstance(witness, Domain):
        return witness
    if witness == sympy.S.Complexes:
        return CC
    if witness == sympy.S.Reals:
        return RR
    if witness == sympy.S.Rationals:
        return QQ
    if witness == sympy.S.Integers:
        return ZZ
    return None

def conditions(witness) -> list[bool]:
    try:
        K = get_K(witness)
        if K is None:
            h1 = False
        else:
            h1 = isinstance(K, Domain)
    except Exception:
        h1 = False

    try:
        K = get_K(witness)
        if K is None:
            neg_q = False
        else:
            # Check if R/I is an integral domain
            if K in (CC, RR, QQ, ZZ):
                is_id = True
            elif hasattr(K, 'char') and K.char == 2:
                is_id = False
            elif hasattr(K, 'is_Field') and K.is_Field:
                is_id = True
            elif isinstance(K, Domain):
                is_id = True
            else:
                is_id = False
                
            # Check if R/I is a UFD
            # R/I is a UFD iff K is a UFD and -1 is a square in K
            if K == CC:
                is_ufd = True
            elif K in (RR, QQ, ZZ):
                is_ufd = False
            else:
                try:
                    t = sympy.Symbol('t')
                    poly = sympy.Poly(t**2 + 1, domain=K)
                    is_ufd = not poly.is_irreducible
                except Exception:
                    if hasattr(K, 'char') and K.char > 0:
                        is_ufd = (K.char % 4 == 1)
                    else:
                        is_ufd = False
                        
            # Conclusion Q: R/I is an integral domain but is not a UFD
            q = is_id and (not is_ufd)
            neg_q = not q
            
    except Exception:
        neg_q = False

    return [h1, neg_q]

