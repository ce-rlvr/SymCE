class RingIdeal:
    """Base class for ring ideals in this verification context."""
    def is_proper_ideal(self):
        return False
    def intersection_powers_is_zero(self):
        return True

class PuiseuxPolynomialPositiveDegreeIdeal(RingIdeal):
    """
    The ideal I generated by {x^q | q > 0} in the Puiseux polynomial ring R = Q[x^q | q >= 0].
    R is an integral domain.
    I is a proper ideal because 1 is not in I.
    Since x^q = (x^{q/2})^2, we have I = I^2 = I^3 = ...
    Therefore, the intersection of I^n is I, which is not the zero ideal.
    """
    def is_proper_ideal(self):
        return True
    def intersection_powers_is_zero(self):
        return False

class SmoothFunctionsPointIdeal(RingIdeal):
    """
    The ideal I of smooth functions f: R -> R such that f(0) = 0.
    I is a proper ideal.
    The intersection of I^n is the ideal of flat functions at 0,
    which contains non-zero functions like e^{-1/x^2} (extended by 0 at 0).
    Thus, the intersection is not the zero ideal.
    """
    def is_proper_ideal(self):
        return True
    def intersection_powers_is_zero(self):
        return False

# Named object bindings for the witness expression to reference
Puiseux_ideal = PuiseuxPolynomialPositiveDegreeIdeal()
C_infty_ideal = SmoothFunctionsPointIdeal()

def conditions(witness) -> list[bool]:
    """
    Evaluates the remaining hypotheses and the negated conclusion at the witness.
    Returns [H_1_ok, neg_Q_ok].
    """
    try:
        h1 = bool(witness.is_proper_ideal())
    except Exception:
        h1 = False

    try:
        # The conclusion is that the intersection is the zero ideal.
        # We want the NEGATED conclusion, so we check if it is NOT the zero ideal.
        neg_q = not bool(witness.intersection_powers_is_zero())
    except Exception:
        neg_q = False

    return [h1, neg_q]

