def conditions(witness):
    """
    Checks if the witness is a valid counterexample.
    Expected witness format: a tuple (n, k) or (n, [generators]) representing
    the ring Z/nZ and the ideal generated by k (or the list of generators).
    """
    n = None
    k = None
    
    try:
        # Handle dictionary formats
        if isinstance(witness, dict):
            if 'R' in witness and 'P' in witness:
                witness = (witness['R'], witness['P'])
            elif 'n' in witness and 'k' in witness:
                witness = (witness['n'], witness['k'])
                
        # Handle tuple format (R, P)
        if isinstance(witness, tuple) and len(witness) == 2:
            r, p = witness
            if isinstance(r, int) and r >= 2:
                n = r
                if isinstance(p, int):
                    k = p
                elif isinstance(p, (list, tuple, set)):
                    g = n
                    for x in p:
                        if isinstance(x, int):
                            g = gcd(g, x)
                    k = g
    except Exception:
        pass

    h1 = False
    neg_q = False
    
    if n is not None and k is not None:
        h1 = True
        
        # In Z/nZ, an ideal generated by k is maximal if and only if 
        # the quotient ring (which is isomorphic to Z/gZ where g = gcd(k, n))
        # is a field. Z/gZ is a field iff g is a prime number.
        g = gcd(k, n)
        
        # The conclusion Q is "P is a maximal ideal".
        # We want neg_Q to be True when P is NOT a maximal ideal.
        neg_q = not isprime(g)
        
    return [h1, neg_q]