def is_pid(A):
    """
    Checks if the matrix entries belong to a known Principal Ideal Domain (PID).
    Recognized PIDs here: ZZ, QQ, RR, CC, and k(x) or k[x] (one variable over a field).
    """
    if not isinstance(A, sp.MatrixBase):
        return False
    symbols = A.free_symbols
    if len(symbols) > 1:
        return False  # Polynomials in >1 variables are not PIDs
    for e in A:
        # Reject fractional powers (e.g., algebraic extensions like Z[\sqrt{-5}] which are not PIDs)
        if e.has(sp.RootOf, sp.root, sp.Pow):
            for arg in e.atoms(sp.Pow):
                if not arg.exp.is_Integer:
                    return False
        # Must be a rational function (covers integers, rationals, and polynomials/rational functions in 1 var)
        if not e.is_rational_function():
            return False
    return True

def conditions(witness) -> list[bool]:
    # H_1: Let R be a principal ideal domain
    try:
        h1 = is_pid(witness)
    except Exception:
        h1 = False

    # H_2: Let A be an n x n matrix with entries in R
    try:
        h2 = isinstance(witness, sp.MatrixBase) and witness.rows == witness.cols
    except Exception:
        h2 = False

    # H_3: Assume A^2 = A
    try:
        if h2:
            h3 = bool(witness**2 == witness)
        else:
            h3 = False
    except Exception:
        h3 = False

    # ¬Q: A is NOT similar over R to a diagonal matrix whose diagonal entries are exclusively 1s and 0s
    try:
        if not h2:
            neg_q = False
        else:
            n = witness.rows
            trace = witness.trace()
            
            # The trace of an idempotent matrix must be an integer (the rank of its image)
            if not trace.is_Integer:
                neg_q = True
            else:
                k = int(trace)
                if k < 0 or k > n:
                    neg_q = True
                elif n > 5:
                    # Prevent timeout for excessively large matrices in minor computation
                    neg_q = False
                else:
                    def get_k_minors(M, k_size):
                        minors = []
                        for row_indices in itertools.combinations(range(n), k_size):
                            for col_indices in itertools.combinations(range(n), k_size):
                                submatrix = M[row_indices, col_indices]
                                minors.append(submatrix.det())
                        return minors

                    def is_unit(g, A_mat):
                        g = sp.simplify(g)
                        if g == 0:
                            return False
                        if g == 1 or g == -1:
                            return True
                        syms = A_mat.free_symbols
                        if not syms:
                            # Over ZZ, units are only 1 and -1
                            if all(e.is_Integer for e in A_mat):
                                return False
                            # Over a field (QQ, RR, CC), any non-zero constant is a unit
                            else:
                                return True
                        else:
                            # Over k[x] or k(x), units are non-zero constants
                            return g.is_constant()

                    neg_q = False
                    try:
                        # A is similar to a diagonal matrix of 1s and 0s over a PID iff 
                        # its image and kernel are free modules. This is true iff the Fitting ideals 
                        # (generated by the k x k minors) are the unit ideal.
                        if k > 0:
                            minors_A = get_k_minors(witness, k)
                            g = minors_A[0]
                            for m in minors_A[1:]:
                                g = sp.gcd(g, m)
                            if not is_unit(g, witness):
                                neg_q = True
                                
                        if not neg_q and n - k > 0:
                            I_minus_A = sp.eye(n) - witness
                            minors_I_A = get_k_minors(I_minus_A, n - k)
                            g2 = minors_I_A[0]
                            for m in minors_I_A[1:]:
                                g2 = sp.gcd(g2, m)
                            if not is_unit(g2, witness):
                                neg_q = True
                    except Exception:
                        neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

