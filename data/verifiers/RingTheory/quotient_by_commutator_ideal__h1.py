def get_R(witness):
    if isinstance(witness, tuple): return witness[0]
    if isinstance(witness, dict): return witness["R"]
    return witness.R

def get_add(witness):
    if isinstance(witness, tuple): return witness[1]
    if isinstance(witness, dict): return witness["add"]
    return witness.add

def get_mul(witness):
    if isinstance(witness, tuple): return witness[2]
    if isinstance(witness, dict): return witness["mul"]
    return witness.mul

def get_C(witness):
    if isinstance(witness, tuple): return witness[3]
    if isinstance(witness, dict): return witness["C"]
    return witness.C

def find_zero(R, add):
    for z in R:
        if all(add(z, x) == x and add(x, z) == x for x in R):
            return z
    return None

def get_neg(R, add, zero):
    neg_map = {}
    for x in R:
        for y in R:
            if add(x, y) == zero and add(y, x) == zero:
                neg_map[x] = y
                break
        if x not in neg_map:
            return None
    return neg_map

def unique_add(lst, item):
    if item not in lst:
        lst.append(item)

def conditions(witness):
    try:
        R = get_R(witness)
        add = get_add(witness)
        mul = get_mul(witness)
        C = get_C(witness)
    except Exception:
        return [False, False]
        
    # H1: C is the two-sided ideal of R generated by all elements of the form xy - yx
    try:
        zero = find_zero(R, add)
        if zero is None:
            h1 = False
        else:
            neg_map = get_neg(R, add, zero)
            if neg_map is None:
                h1 = False
            else:
                commutators = []
                unique_add(commutators, zero)
                
                valid_closure = True
                for x in R:
                    for y in R:
                        xy = mul(x, y)
                        if xy not in R: valid_closure = False
                        yx = mul(y, x)
                        if yx not in R: valid_closure = False
                        if not valid_closure: break
                        neg_yx = neg_map[yx]
                        com = add(xy, neg_yx)
                        if com not in R: valid_closure = False
                        if not valid_closure: break
                        unique_add(commutators, com)
                    if not valid_closure: break
                
                if not valid_closure:
                    h1 = False
                else:
                    I = list(commutators)
                    while True:
                        size_before = len(I)
                        new_I = list(I)
                        for x in I:
                            for y in I:
                                res = add(x, y)
                                if res not in R: valid_closure = False
                                unique_add(new_I, res)
                            res_neg = neg_map[x]
                            if res_neg not in R: valid_closure = False
                            unique_add(new_I, res_neg)
                            for r in R:
                                res_mul1 = mul(x, r)
                                if res_mul1 not in R: valid_closure = False
                                unique_add(new_I, res_mul1)
                                res_mul2 = mul(r, x)
                                if res_mul2 not in R: valid_closure = False
                                unique_add(new_I, res_mul2)
                        if not valid_closure:
                            break
                        I = new_I
                        if len(I) == size_before:
                            break
                    
                    if not valid_closure:
                        h1 = False
                    else:
                        h1 = True
                        for c in C:
                            if c not in I: h1 = False
                        for i in I:
                            if i not in C: h1 = False
    except Exception:
        h1 = False

    # neg_Q: The quotient ring R/C is NOT a commutative ring
    try:
        zero = find_zero(R, add)
        if zero is None:
            neg_q = True
        else:
            neg_map = get_neg(R, add, zero)
            if neg_map is None:
                neg_q = True
            else:
                classes = []
                for x in R:
                    found = False
                    for cls in classes:
                        rep = cls[0]
                        if add(x, neg_map[rep]) in C:
                            cls.append(x)
                            found = True
                            break
                    if not found:
                        classes.append([x])
                
                def get_class(x):
                    for i, cls in enumerate(classes):
                        if x in cls: return i
                    return -1
                
                is_comm_ring = True
                add_table = {}
                for i, cls_i in enumerate(classes):
                    for j, cls_j in enumerate(classes):
                        target = None
                        for x in cls_i:
                            for y in cls_j:
                                res = get_class(add(x, y))
                                if res == -1:
                                    is_comm_ring = False
                                if target is None:
                                    target = res
                                elif target != res:
                                    is_comm_ring = False
                        add_table[(i, j)] = target
                
                mul_table = {}
                for i, cls_i in enumerate(classes):
                    for j, cls_j in enumerate(classes):
                        target = None
                        for x in cls_i:
                            for y in cls_j:
                                res = get_class(mul(x, y))
                                if res == -1:
                                    is_comm_ring = False
                                if target is None:
                                    target = res
                                elif target != res:
                                    is_comm_ring = False
                        mul_table[(i, j)] = target
                
                if not is_comm_ring:
                    neg_q = True
                else:
                    n = len(classes)
                    # 1. Addition commutative
                    for i in range(n):
                        for j in range(n):
                            if add_table[(i, j)] != add_table[(j, i)]:
                                is_comm_ring = False
                    # 2. Addition associative
                    for i in range(n):
                        for j in range(n):
                            for k in range(n):
                                if add_table[(add_table[(i, j)], k)] != add_table[(i, add_table[(j, k)])]:
                                    is_comm_ring = False
                    # 3. Additive identity
                    zero_cls = None
                    for i in range(n):
                        if all(add_table[(i, j)] == j and add_table[(j, i)] == j for j in range(n)):
                            zero_cls = i
                            break
                    if zero_cls is None:
                        is_comm_ring = False
                    # 4. Additive inverses
                    if is_comm_ring:
                        for i in range(n):
                            has_inv = False
                            for j in range(n):
                                if add_table[(i, j)] == zero_cls and add_table[(j, i)] == zero_cls:
                                    has_inv = True
                                    break
                            if not has_inv:
                                is_comm_ring = False
                    # 5. Multiplication associative
                    for i in range(n):
                        for j in range(n):
                            for k in range(n):
                                if mul_table[(mul_table[(i, j)], k)] != mul_table[(i, mul_table[(j, k)])]:
                                    is_comm_ring = False
                    # 6. Multiplication commutative
                    for i in range(n):
                        for j in range(n):
                            if mul_table[(i, j)] != mul_table[(j, i)]:
                                is_comm_ring = False
                    # 7. Multiplicative identity
                    one_cls = None
                    for i in range(n):
                        if all(mul_table[(i, j)] == j and mul_table[(j, i)] == j for j in range(n)):
                            one_cls = i
                            break
                    if one_cls is None:
                        is_comm_ring = False
                    # 8. Distributive laws
                    for i in range(n):
                        for j in range(n):
                            for k in range(n):
                                left = mul_table[(i, add_table[(j, k)])]
                                right = add_table[(mul_table[(i, j)], mul_table[(i, k)])]
                                if left != right:
                                    is_comm_ring = False
                                left2 = mul_table[(add_table[(i, j)], k)]
                                right2 = add_table[(mul_table[(i, k)], mul_table[(j, k)])]
                                if left2 != right2:
                                    is_comm_ring = False
                    
                    neg_q = not is_comm_ring
    except Exception:
        neg_q = False

    return [h1, neg_q]

