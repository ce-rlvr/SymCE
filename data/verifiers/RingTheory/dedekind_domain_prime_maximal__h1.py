import sympy as sp
from sympy.abc import x, y, z

# Top-level setup for witness expressions
ZZ = sp.ZZ
QQ = sp.QQ
RR = sp.RR
CC = sp.CC

def evaluate_properties(witness):
    """
    Evaluates the properties of the given witness.
    Expected witness format: (domain, variables, generators)
    Example: (ZZ, [x], [x]) represents the ideal (x) in ZZ[x].
    Returns: (is_valid, is_nonzero, is_prime, is_maximal)
    """
    try:
        if not isinstance(witness, (tuple, list)) or len(witness) != 3:
            return False, False, False, False
            
        domain, vars_list, gens_list = witness
        
        if not isinstance(vars_list, (tuple, list)):
            vars_list = [vars_list]
        if not isinstance(gens_list, (tuple, list)):
            gens_list = [gens_list]
            
        # Check if it's the zero ideal
        is_zero = all(sp.expand(g) == 0 for g in gens_list)
        if is_zero:
            return True, False, False, False
            
        current_gens = list(gens_list)
        current_vars = list(vars_list)
        
        # Eliminate variables using linear generators
        changed = True
        while changed:
            changed = False
            for g in current_gens:
                if g == 0: continue
                for v in current_vars:
                    try:
                        poly = sp.Poly(g, v)
                        if poly.degree() == 1:
                            sol = sp.solve(g, v)
                            if sol and len(sol) == 1:
                                val = sol[0]
                                lc = poly.LC()
                                # Only substitute if the leading coefficient is a unit in the domain
                                if not getattr(lc, 'is_number', False) and not isinstance(lc, (int, float)):
                                    continue
                                if domain == sp.ZZ and lc not in [1, -1]:
                                    continue
                                
                                current_gens = [sp.expand(cg.subs(v, val)) for cg in current_gens]
                                current_vars.remove(v)
                                changed = True
                                break
                    except Exception:
                        pass
                if changed:
                    break
                    
        current_gens = [g for g in current_gens if g != 0]
        
        # Case 1: Ideal is generated by linear terms that eliminate some/all variables
        if not current_gens:
            if len(current_vars) > 0:
                # Quotient is a polynomial ring over the domain (domain, not field)
                is_prime = True
                is_maximal = False
            else:
                # Quotient is exactly the domain
                is_prime = True
                is_maximal = getattr(domain, 'is_Field', domain != sp.ZZ)
            return True, True, is_prime, is_maximal
            
        # Case 2: Ideal is generated by constants
        if all(getattr(g, 'is_number', False) or isinstance(g, (int, float)) for g in current_gens):
            if domain == sp.ZZ:
                g_val = sp.gcd_list(current_gens)
                if g_val == 1:
                    return True, True, False, False
                elif sp.isprime(g_val):
                    if len(current_vars) == 0:
                        return True, True, True, True
                    else:
                        return True, True, True, False
                else:
                    return True, True, False, False
            else:
                # Over a field, any non-zero constant generates the whole ring
                return True, True, False, False

        # Case 3: Ideal is generated by a single polynomial in one remaining variable
        if len(current_gens) == 1 and len(current_vars) == 1:
            g = current_gens[0]
            v = current_vars[0]
            poly = sp.Poly(g, v, domain=domain)
            if poly.is_irreducible:
                if getattr(domain, 'is_Field', domain != sp.ZZ):
                    return True, True, True, True
                else:
                    return True, True, True, False
            else:
                return True, True, False, False

        # Fallback for complex ideals not easily evaluated
        return False, False, False, False
    except Exception:
        return False, False, False, False

def conditions(witness):
    is_valid, is_nonzero, is_prime, is_maximal = evaluate_properties(witness)
    
    if not is_valid:
        return [False, False]
        
    h1 = is_nonzero and is_prime
    neg_q = not is_maximal
    
    return [h1, neg_q]

