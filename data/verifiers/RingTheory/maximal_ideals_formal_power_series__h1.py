def conditions(witness) -> list[bool]:
    h1 = False
    h2 = False
    neg_q = False
    
    try:
        if isinstance(witness, str):
            h1 = True
            h2 = True
            s = witness.lower()
            if "2z" in s or "even" in s or "without identity" in s or "no identity" in s or "twoz" in s:
                neg_q = True
            return [h1, h2, neg_q]
            
        if isinstance(witness, tuple):
            for item in witness:
                if isinstance(item, Ideal):
                    witness = item
                    break
            else:
                if all(isinstance(x, str) for x in witness):
                    s = " ".join(witness).lower()
                    h1 = True
                    h2 = True
                    if "2z" in s or "even" in s or "without identity" in s or "no identity" in s or "twoz" in s:
                        neg_q = True
                    return [h1, h2, neg_q]
                    
        if isinstance(witness, Ring):
            h1 = True
            h2 = True
            if not witness.has_identity:
                neg_q = True
            return [h1, h2, neg_q]
            
        if isinstance(witness, Ideal):
            h1 = isinstance(witness.ring, FormalPowerSeriesRing)
            h2 = True
            base_ring = witness.ring.base_ring
            
            claimed_neg_q = (witness.is_maximal != witness.is_generated_by_m_and_x)
            
            if hasattr(base_ring, "has_identity"):
                has_id = base_ring.has_identity
            else:
                has_id = True
                
            if claimed_neg_q and not has_id:
                neg_q = True
            elif not claimed_neg_q:
                neg_q = False
            else:
                neg_q = False
                
        elif hasattr(witness, "is_maximal") and hasattr(witness, "ring"):
            h1 = type(witness.ring).__name__ == "FormalPowerSeriesRing"
            h2 = True
            base_ring = getattr(witness.ring, "base_ring", None)
            has_id = getattr(base_ring, "has_identity", True)
            
            claimed_neg_q = (getattr(witness, "is_maximal", False) != getattr(witness, "is_generated_by_m_and_x", False))
            if claimed_neg_q and not has_id:
                neg_q = True
                
    except Exception:
        pass
        
    return [h1, h2, neg_q]

