# Top-level setup
class Ring:
    def __init__(self, name, has_identity):
        self.name = name
        self.has_identity = has_identity
    def __str__(self):
        return self.name

class FormalPowerSeriesRing:
    def __init__(self, base_ring):
        self.base_ring = base_ring
    def __str__(self):
        return f"{self.base_ring}_x"

class Ideal:
    def __init__(self, ring, is_maximal=False, is_generated_by_m_and_x=False):
        self.ring = ring
        self.is_maximal = is_maximal
        self.is_generated_by_m_and_x = is_generated_by_m_and_x

