import sympy
import math

# Top-level setup
x = sympy.Symbol('x')

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness should be a tuple (R, a, b, d) where:
      - R is a string representing the ring, e.g., "Z" or "Q[x]"
      - a, b, d are the elements of R (integers for "Z", sympy expressions for "Q[x]")
    """
    try:
        R, a, b, d = witness
    except Exception:
        return [False, False, False]
        
    # H1: R is a principal ideal domain
    try:
        if R == "Z":
            h1 = True
        elif R == "Q[x]":
            h1 = True
        else:
            h1 = False
    except Exception:
        h1 = False

    # H2: d is a greatest common divisor of a and b
    try:
        if R == "Z":
            a_int, b_int, d_int = int(a), int(b), int(d)
            g = math.gcd(a_int, b_int)
            h2 = (abs(d_int) == g)
        elif R == "Q[x]":
            a_expr, b_expr, d_expr = sympy.sympify(a), sympy.sympify(b), sympy.sympify(d)
            g = sympy.gcd(a_expr, b_expr)
            if g == 0 and d_expr == 0:
                h2 = True
            elif g != 0 and d_expr != 0:
                rem1 = sympy.rem(g, d_expr, x, domain='QQ')
                rem2 = sympy.rem(d_expr, g, x, domain='QQ')
                h2 = (rem1 == 0 and rem2 == 0)
            else:
                h2 = False
        else:
            h2 = False
    except Exception:
        h2 = False

    # neg_Q: Hom_R(R/<a>, R/<b>) is NOT isomorphic to R/<d>
    try:
        if R == "Z":
            a_int, b_int, d_int = int(a), int(b), int(d)
            # Determine the ideal generator for Hom_Z(Z/a, Z/b)
            if a_int == 0 and b_int == 0:
                hom_ideal = 0
            elif a_int == 0 and b_int != 0:
                hom_ideal = b_int
            elif a_int != 0 and b_int == 0:
                hom_ideal = 1  # Hom(Z/a, Z) = 0, which is isomorphic to Z/1
            else:
                hom_ideal = math.gcd(a_int, b_int)
            
            # Two cyclic modules Z/x and Z/y are isomorphic iff |x| == |y|
            isomorphic = (abs(hom_ideal) == abs(d_int))
            neg_q = not isomorphic
            
        elif R == "Q[x]":
            a_expr, b_expr, d_expr = sympy.sympify(a), sympy.sympify(b), sympy.sympify(d)
            # Determine the ideal generator for Hom_{Q[x]}(Q[x]/a, Q[x]/b)
            if a_expr == 0 and b_expr == 0:
                hom_ideal = sympy.Integer(0)
            elif a_expr == 0 and b_expr != 0:
                hom_ideal = b_expr
            elif a_expr != 0 and b_expr == 0:
                hom_ideal = sympy.Integer(1)
            else:
                hom_ideal = sympy.gcd(a_expr, b_expr)
                
            # Two cyclic modules over Q[x] are isomorphic iff their ideals are generated by associates
            if hom_ideal == 0 and d_expr == 0:
                isomorphic = True
            elif hom_ideal != 0 and d_expr != 0:
                rem1 = sympy.rem(hom_ideal, d_expr, x, domain='QQ')
                rem2 = sympy.rem(d_expr, hom_ideal, x, domain='QQ')
                isomorphic = (rem1 == 0 and rem2 == 0)
            else:
                isomorphic = False
                
            neg_q = not isomorphic
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

