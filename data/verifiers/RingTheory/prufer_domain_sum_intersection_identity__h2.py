import sympy

# Top-level setup
QQ_x = 'QQ[x]'
ZZ = sympy.ZZ
QQ = sympy.QQ

def conditions(witness) -> list[bool]:
    """
    Evaluates the conjecture at the given witness.
    The witness is expected to be a tuple (R, I, J) where:
      - R is the ring (e.g., 'QQ[x]', sympy.ZZ, 'ZZ', sympy.QQ, 'QQ')
      - I is a subset of R
      - J is an ideal of R
      
    For R = 'QQ[x]', subsets are represented by a set of non-negative integers 
    corresponding to the degrees of the monomials spanning the subspace (up to MAX_DEG).
    For R = ZZ or QQ, subsets are represented by finite sets of elements.
    """
    try:
        R, I, J = witness
    except Exception:
        return [False, False, False]
        
    # H1: R is a Prüfer domain
    # We support QQ[x] (a PID), ZZ (a PID), and QQ (a field), all of which are Prüfer domains.
    try:
        h1 = bool(R in ['QQ[x]', sympy.ZZ, 'ZZ', sympy.QQ, 'QQ'])
    except Exception:
        h1 = False
        
    MAX_DEG = 20
    
    # H2: J is an ideal of R
    try:
        if R == 'QQ[x]':
            if not isinstance(J, (set, frozenset, list, tuple)):
                h2 = False
            else:
                J_set = set(J)
                if not J_set:
                    h2 = True
                else:
                    # An ideal in QQ[x] generated by x^k contains all degrees >= k
                    min_deg = min(J_set)
                    expected = set(range(min_deg, MAX_DEG + 1))
                    h2 = bool(J_set == expected)
        elif R in [sympy.ZZ, 'ZZ', sympy.QQ, 'QQ']:
            if not isinstance(J, (set, frozenset, list, tuple)):
                h2 = False
            else:
                J_set = set(J)
                # For finite set representations in ZZ or QQ, only the zero ideal {0} is supported
                h2 = bool(J_set == {0})
        else:
            h2 = False
    except Exception:
        h2 = False
        
    # Conclusion: (I+J)(I \cap J) == IJ
    # We want to return True if the conclusion FAILS (i.e., they are not equal).
    try:
        if not isinstance(I, (set, frozenset, list, tuple)) or not isinstance(J, (set, frozenset, list, tuple)):
            neg_q = False
        else:
            I_set = set(I)
            J_set = set(J)
            
            if R == 'QQ[x]':
                # Subspace addition is the union of basis degrees
                I_plus_J = I_set | J_set
                # Subspace intersection is the intersection of basis degrees
                I_cap_J = I_set & J_set
                
                def mul_degs(A, B):
                    return {a + b for a in A for b in B if a + b <= MAX_DEG}
                    
                lhs = mul_degs(I_plus_J, I_cap_J)
                rhs = mul_degs(I_set, J_set)
                neg_q = bool(lhs != rhs)
                
            elif R in [sympy.ZZ, 'ZZ', sympy.QQ, 'QQ']:
                # Minkowski sum for subsets
                I_plus_J = {i + j for i in I_set for j in J_set}
                # Set intersection
                I_cap_J = I_set & J_set
                
                def mul_elements(A, B):
                    return {a * b for a in A for b in B}
                    
                lhs = mul_elements(I_plus_J, I_cap_J)
                rhs = mul_elements(I_set, J_set)
                neg_q = bool(lhs != rhs)
            else:
                neg_q = False
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

