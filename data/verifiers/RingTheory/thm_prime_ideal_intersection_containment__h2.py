def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, dict):
            i = witness.get('I', witness.get('i'))
            j = witness.get('J', witness.get('j'))
            p = witness.get('P', witness.get('p'))
        else:
            i, j, p = witness
            
        # Try to treat as integers first (principal ideals in Z)
        try:
            i_val = int(i)
            j_val = int(j)
            p_val = int(p)
            is_int = True
        except (TypeError, ValueError):
            is_int = False
            
        # H_1: R is a commutative ring
        # We evaluate this in the ring of integers Z or a polynomial ring, which are commutative.
        h1 = True
        
        # H_2: I and J are ideals of R
        # In Z or a polynomial ring, any single element generates a principal ideal.
        h2 = True
        
        if is_int:
            i_val = abs(i_val)
            j_val = abs(j_val)
            p_val = abs(p_val)
            
            if i_val == 0 or j_val == 0:
                lcm_ij = 0
            else:
                lcm_ij = (i_val * j_val) // math.gcd(i_val, j_val)
                
            # H_3: The intersection I \cap J is contained in P
            # In Z, I \cap J is generated by lcm(i, j). Containment in P means p divides lcm(i, j).
            if p_val == 0:
                h3 = (lcm_ij == 0)
                i_in_p = (i_val == 0)
                j_in_p = (j_val == 0)
            else:
                h3 = (lcm_ij % p_val == 0)
                i_in_p = (i_val % p_val == 0)
                j_in_p = (j_val % p_val == 0)
        else:
            # Treat as sympy expressions (principal ideals in a polynomial ring)
            i_expr = sympy.sympify(i)
            j_expr = sympy.sympify(j)
            p_expr = sympy.sympify(p)
            
            lcm_ij = sympy.lcm(i_expr, j_expr)
            
            def divides(a, b):
                if a == 0:
                    return b == 0
                res = sympy.cancel(b / a)
                return res.as_numer_denom()[1] == 1
                
            h3 = bool(divides(p_expr, lcm_ij))
            i_in_p = bool(divides(p_expr, i_expr))
            j_in_p = bool(divides(p_expr, j_expr))
            
        # ¬Q: I is not contained in P and J is not contained in P
        neg_q = not (i_in_p or j_in_p)
        
        return [h1, h2, h3, neg_q]
    except Exception:
        return [False, False, False, False]

