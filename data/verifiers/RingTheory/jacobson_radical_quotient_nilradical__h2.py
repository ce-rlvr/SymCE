import sympy
from sympy import ZZ, QQ
from sympy.ntheory import factorint

# Top-level setup for potential witness evaluation
# We define standard commutative rings that might be used as witnesses.
Z = ZZ
Q = QQ

def conditions(witness):
    """
    Given a witness, checks if it satisfies the remaining hypotheses
    and if it falsifies the conclusion of the conjecture.
    
    The witness is expected to provide:
      - R: a commutative ring
      - J: the Jacobson radical of R
      - N: an ideal of R (the dropped hypothesis was that N is the nilradical)
    """
    R = J = N = None
    
    # Extract R, J, N from the witness
    if isinstance(witness, dict):
        R = witness.get('R', witness.get('r'))
        J = witness.get('J', witness.get('j'))
        N = witness.get('N', witness.get('n'))
    elif isinstance(witness, (tuple, list)):
        if len(witness) == 3:
            R, J, N = witness
        elif len(witness) == 2:
            R, N = witness
            if R == ZZ or str(R) == 'ZZ':
                J = 0
    elif hasattr(witness, 'R') and hasattr(witness, 'J') and hasattr(witness, 'N'):
        R = witness.R
        J = witness.J
        N = witness.N
    else:
        # If the witness is just an integer, assume it represents the ideal N in ZZ
        try:
            N_int = int(witness)
            R = ZZ
            J = 0
            N = N_int
        except Exception:
            pass

    # H_1: R is a commutative ring
    h1 = False
    try:
        if R == ZZ or str(R) == 'ZZ':
            h1 = True
        elif R == QQ or str(R) == 'QQ':
            h1 = True
        elif hasattr(R, 'is_commutative') and R.is_commutative:
            h1 = True
        elif hasattr(R, 'is_Commutative') and R.is_Commutative:
            h1 = True
        elif hasattr(R, 'gens') and hasattr(R, 'domain'):
            # Polynomial rings over commutative domains are commutative
            h1 = True
    except Exception:
        pass

    # H_2: J is the Jacobson radical of R
    h2 = False
    try:
        if (R == ZZ or str(R) == 'ZZ') and (J == 0 or str(J) == '0'):
            h2 = True
        elif (R == QQ or str(R) == 'QQ') and (J == 0 or str(J) == '0'):
            h2 = True
        elif hasattr(R, 'gens') and hasattr(R, 'domain') and (J == 0 or str(J) == '0'):
            # The Jacobson radical of a polynomial ring over a field/Z is 0
            h2 = True
    except Exception:
        pass

    # ¬Q: The Jacobson radical of the quotient ring R/N is NOT equal to J/N
    neg_q = False
    try:
        if R == ZZ or str(R) == 'ZZ':
            n_val = None
            try:
                n_val = abs(int(N))
            except Exception:
                if isinstance(N, (list, tuple)) and len(N) == 1:
                    n_val = abs(int(N[0]))
                elif hasattr(N, 'gen'):
                    n_val = abs(int(N.gen))
            
            if n_val is not None and n_val > 1:
                # In Z, J = 0. So J/N = 0.
                # The Jacobson radical of Z/nZ is generated by the radical of n (product of distinct prime factors).
                # They are NOT equal if rad(n) != n (i.e., n is not square-free).
                factors = factorint(n_val)
                rad = 1
                for p in factors:
                    rad *= p
                if rad != n_val:
                    neg_q = True
                    
        elif hasattr(R, 'gens') and hasattr(R, 'domain'):
            # In k[x], J = 0. So J/N = 0.
            # The Jacobson radical of k[x]/(N) is non-zero iff N is not square-free.
            if N != 0 and str(N) != '0':
                poly_N = sympy.Poly(N, R.gens)
                if not poly_N.is_squarefree:
                    neg_q = True
    except Exception:
        pass

    return [h1, h2, neg_q]

