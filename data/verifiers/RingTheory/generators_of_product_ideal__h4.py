# Top-level setup
# We implicitly work in a commutative ring like Z or Q[x] where ideals are principal.
# The witness can use integers or sympy expressions (like x, y, z).

def get_gen(val):
    """
    Returns the single generator (gcd) for a list/set of elements, 
    or the element itself if it's a single value.
    """
    if isinstance(val, (list, set, tuple)):
        if not val:
            return sympify(0)
        g = sympify(0)
        for e in val:
            g = gcd(g, sympify(e))
        return g
    else:
        return sympify(val)

def same_ideal(g1, g2):
    """
    Checks if two elements generate the same ideal in Z or Q[x].
    """
    g1 = sympify(g1)
    g2 = sympify(g2)
    
    # In Z, generators must be equal in absolute value
    if g1.is_Integer and g2.is_Integer:
        return abs(g1) == abs(g2)
        
    if g1 == g2 or g1 == -g2:
        return True
        
    # In Q[x], generators can differ by a non-zero constant unit
    try:
        q1 = cancel(g1 / g2)
        q2 = cancel(g2 / g1)
        if q1.is_number and q2.is_number:
            return True
    except Exception:
        pass
    return False

def conditions(witness):
    """
    Evaluates the hypotheses and the negated conclusion for the given witness.
    The witness should provide S, T, I, and J.
    """
    try:
        if isinstance(witness, dict):
            S = witness.get('S')
            T = witness.get('T')
            I = witness.get('I')
            J = witness.get('J')
        elif isinstance(witness, (tuple, list)):
            if len(witness) == 4:
                S, T, I, J = witness
            elif len(witness) == 5:
                _, S, T, I, J = witness
            else:
                raise ValueError("Tuple witness must have length 4 or 5")
        else:
            raise ValueError("Witness must be a dict or tuple")
            
        if S is None or T is None or I is None or J is None:
            raise ValueError("Missing required witness components")
    except Exception:
        return [False, False, False, False]

    # H_1: R is a commutative ring
    try:
        # We implicitly work in a commutative ring (Z or Q[x]) 
        # as long as the elements can be sympified and processed.
        h1 = True
    except Exception:
        h1 = False

    # H_2: S and T are subsets of R
    try:
        h2 = isinstance(S, (list, set, tuple)) and isinstance(T, (list, set, tuple))
    except Exception:
        h2 = False

    # H_3: I is the ideal generated by S
    try:
        gen_S = get_gen(S)
        gen_I = get_gen(I)
        h3 = same_ideal(gen_I, gen_S)
    except Exception:
        h3 = False

    # ¬Q: The product ideal IJ is NOT generated by {st | s in S, t in T}
    try:
        gen_J = get_gen(J)
        # In a PID, the product ideal IJ is generated by the product of their generators
        gen_IJ = gen_I * gen_J
        
        # The ideal generated by the set {st | s in S, t in T}
        ST = [sympify(s_elem) * sympify(t_elem) for s_elem in S for t_elem in T]
        gen_ST = get_gen(ST)
        
        neg_q = not same_ideal(gen_IJ, gen_ST)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

