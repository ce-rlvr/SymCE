import sympy
from sympy import symbols, Rational

def conditions(witness) -> list[bool]:
    """
    Check if the witness is a counterexample to the false conjecture.
    The witness should be a tuple (R_id, ideals) where:
      - R_id is a string identifying the ring (e.g., "Z" for integers)
      - ideals is a list of ideals (each represented as a list of generators)
    """
    try:
        R_id, ideals = witness
    except Exception:
        return [False, False, False]

    # H1: R is a commutative ring with identity.
    # We will only accept Z (integers) as the ring for simplicity,
    # which is a commutative ring with identity.
    try:
        h1 = (R_id == "Z")
    except Exception:
        h1 = False

    # H2: For all indices i and j such that i \neq j, I_i + I_j = R.
    try:
        h2 = True
        n = len(ideals)
        for i in range(n):
            for j in range(n):
                if i != j:
                    # In Z, the sum of two ideals generated by a and b is generated by gcd(a, b).
                    # For the sum to be R (which is Z), the gcd must be 1.
                    # We assume each ideal is principal and given by a single generator.
                    gen_i = abs(ideals[i][0])
                    gen_j = abs(ideals[j][0])
                    if sympy.gcd(gen_i, gen_j) != 1:
                        h2 = False
                        break
            if not h2:
                break
    except Exception:
        h2 = False

    # ¬Q: The product ideal I_1 I_2 \cdots I_n is NOT equal to the intersection ideal I_1 \cap I_2 \cap \cdots \cap I_n.
    try:
        if n == 0:
            neg_q = False
        else:
            # Calculate the product ideal generator
            prod_gen = 1
            for ideal in ideals:
                prod_gen *= ideal[0]
            prod_gen = abs(prod_gen)

            # Calculate the intersection ideal generator (lcm of all generators)
            lcm_gen = abs(ideals[0][0])
            for ideal in ideals[1:]:
                lcm_gen = sympy.lcm(lcm_gen, abs(ideal[0]))

            # The conclusion FAILS if the product ideal is NOT equal to the intersection ideal.
            # In Z, two ideals are equal iff their positive generators are equal.
            neg_q = (prod_gen != lcm_gen)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

