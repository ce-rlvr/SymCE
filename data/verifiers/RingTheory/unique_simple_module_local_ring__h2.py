import sympy
from sympy.ntheory import factorint

# Top-level setup
# Witnesses for this conjecture are expected to be of the form (R, M)
# where R is an integer n representing the ring Z/nZ,
# and M is an integer or list of integers representing the invariant factors
# of the module M (e.g., M = [2, 2] for Z/2Z x Z/2Z).
# Alternatively, R can be a field like sympy.QQ, and M its dimension.

def conditions(witness):
    try:
        if not (isinstance(witness, tuple) and len(witness) == 2):
            return [False, False]
            
        R, M = witness
        
        # Handle the case where R is a field (which is a local ring with maximal ideal {0})
        if R in (sympy.QQ, sympy.S.Reals, sympy.S.Complexes):
            h1 = True
            try:
                dim = int(M)
                if dim < 0:
                    return [False, False]
                # For a field R, R/m is isomorphic to R (dimension 1)
                neg_q = (dim != 1)
                return [h1, neg_q]
            except Exception:
                return [False, False]
                
        # Handle the case where R is Z/nZ represented by an integer n
        try:
            n = int(R)
        except Exception:
            return [False, False]
            
        if n < 2:
            return [False, False]
            
        if isinstance(M, (int, sympy.Integer)):
            M_factors = [int(M)]
        elif isinstance(M, (list, tuple)):
            M_factors = [int(x) for x in M]
        else:
            return [False, False]
            
        # H_1: R is a local ring
        # For Z/nZ, it is a local ring iff n is a prime power p^k.
        factors = factorint(n)
        h1 = (len(factors) == 1)
        
        if h1:
            p = list(factors.keys())[0]
            M_clean = sorted([abs(d) for d in M_factors if abs(d) > 1])
            
            # Verify that M is actually a valid R-module.
            # For Z/nZ, this means n must annihilate M, so each invariant factor must divide n.
            is_module = all(n % d == 0 for d in M_clean)
            if not is_module:
                return [False, False]
                
            # ¬Q: M is NOT isomorphic to R/m as an R-module
            # The unique maximal ideal m of Z/p^k Z is generated by p.
            # R/m is isomorphic to Z/pZ, which has a single invariant factor [p].
            neg_q = (M_clean != [p])
        else:
            neg_q = False
            
        return [h1, neg_q]
    except Exception:
        return [False, False]

