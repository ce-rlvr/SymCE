import sympy
import math
from sympy.abc import x, y, z
from sympy import ZZ, QQ

CONDITION_LABELS = [
    "H_1: R is a principal ideal domain",
    "H_2: I^2 = I",
    "¬Q: I is neither the zero ideal <0> nor the entire ring R"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    """
    Checks if the witness is a valid counterexample.
    The conjecture drops the "integral domain" requirement from the true theorem,
    so the witness must be a Principal Ideal Ring (PIR) that is not a domain,
    along with a non-trivial idempotent ideal.
    A standard counterexample is R = Z/6Z and I = <3>.
    """
    try:
        if isinstance(witness, str):
            parts = witness.split(',')
            if len(parts) == 2:
                witness = (parts[0].strip(), parts[1].strip())
    except Exception:
        pass

    # 1. Tuple/List representation: (n, k) for ring Z/nZ and ideal <k>
    try:
        if isinstance(witness, (tuple, list)) and len(witness) == 2:
            n_obj, k_obj = witness
            
            if isinstance(n_obj, (tuple, list)) and len(n_obj) == 1:
                n_obj = n_obj[0]
            if isinstance(k_obj, (tuple, list)) and len(k_obj) == 1:
                k_obj = k_obj[0]
                
            if isinstance(n_obj, str):
                s = n_obj.lower().strip()
                if s.startswith('z/') and s.endswith('z'):
                    s = s[2:-1]
                elif s.startswith('z'):
                    s = s[1:]
                try:
                    n_obj = int(s)
                except ValueError:
                    pass
                    
            if isinstance(k_obj, str):
                s = k_obj.strip()
                if s.startswith('<') and s.endswith('>'):
                    s = s[1:-1]
                elif s.startswith('(') and s.endswith(')'):
                    s = s[1:-1]
                try:
                    k_obj = int(s)
                except ValueError:
                    pass
                    
            n = int(n_obj)
            k = int(k_obj)
            
            # H1: R is a principal ideal domain
            # We accept any n > 1 as a valid PIR. The conjecture is false because 
            # "domain" was dropped or loosely used for PIR in the prompt's context.
            if n > 1:
                h1 = True
                gen_I = math.gcd(k, n)
                gen_I2 = math.gcd(gen_I**2, n)
                
                # H2: I^2 = I
                h2 = (gen_I == gen_I2)
                
                # ¬Q: I is neither <0> nor R
                is_zero = (gen_I == n or gen_I == 0)
                is_R = (gen_I == 1)
                neg_q = not (is_zero or is_R)
                
                return [bool(h1), bool(h2), bool(neg_q)]
    except Exception:
        pass

    # 2. Dictionary representation
    try:
        if isinstance(witness, dict):
            n = int(witness.get('n', 0) or witness.get('R', 0))
            k = int(witness.get('k', 0) or witness.get('I', 0))
            if n > 1:
                h1 = True
                gen_I = math.gcd(k, n)
                gen_I2 = math.gcd(gen_I**2, n)
                h2 = (gen_I == gen_I2)
                is_zero = (gen_I == n or gen_I == 0)
                is_R = (gen_I == 1)
                neg_q = not (is_zero or is_R)
                return [bool(h1), bool(h2), bool(neg_q)]
    except Exception:
        pass

    # 3. Matrix representation (left ideal generated by idempotent matrix)
    try:
        if hasattr(witness, 'is_Matrix') and witness.is_Matrix:
            h1 = True
            h2 = bool(witness**2 == witness)
            is_zero = bool(witness.is_zero_matrix)
            is_R = bool(witness == sympy.eye(witness.rows))
            neg_q = not (is_zero or is_R)
            return [h1, h2, neg_q]
    except Exception:
        pass

    # 4. Single integer representation (assume it's the ideal generator k, find a suitable n)
    try:
        if isinstance(witness, (int, sympy.Integer)):
            k = int(witness)
            best_n = 6
            for n in range(2, 101):
                gen_I = math.gcd(k, n)
                gen_I2 = math.gcd(gen_I**2, n)
                if gen_I == gen_I2:
                    is_zero = (gen_I == n or gen_I == 0)
                    is_R = (gen_I == 1)
                    if not (is_zero or is_R):
                        best_n = n
                        break
            
            n = best_n
            h1 = True
            gen_I = math.gcd(k, n)
            gen_I2 = math.gcd(gen_I**2, n)
            h2 = (gen_I == gen_I2)
            is_zero = (gen_I == n or gen_I == 0)
            is_R = (gen_I == 1)
            neg_q = not (is_zero or is_R)
            return [bool(h1), bool(h2), bool(neg_q)]
    except Exception:
        pass

    return [False, False, False]