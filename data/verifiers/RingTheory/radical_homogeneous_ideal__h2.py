import sympy
from sympy.abc import x, y, z, t, u, v, w

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "Let R be an N-graded commutative ring. The radical of I is a homogeneous ideal."
    
    The dropped hypothesis was that I itself must be a homogeneous ideal.
    A valid witness is an ideal I (represented as a list of polynomial generators)
    whose radical is NOT homogeneous.
    """
    # Normalize witness to a list of generators
    if not isinstance(witness, (list, tuple, set)):
        witness = [witness]
        
    h1 = False
    neg_q = False
    
    # H_1: R is an N-graded commutative ring and I is an ideal.
    # We evaluate this in the polynomial ring QQ[x, y, z, ...], which is N-graded.
    # We just need to verify that the witness is a valid list of polynomial expressions.
    try:
        polys = [sympy.sympify(p) for p in witness]
        if all(isinstance(p, sympy.Expr) for p in polys):
            h1 = True
    except Exception:
        h1 = False

    if not h1:
        return [False, False]

    # ¬Q: The radical of I is NOT a homogeneous ideal.
    try:
        if len(polys) == 1:
            # Principal ideal: radical is generated by the square-free part.
            f = polys[0]
            f_red = sympy.sqf_part(f)
            if f_red.is_number:
                is_hom = True
            else:
                is_hom = sympy.Poly(f_red).is_homogeneous
            neg_q = not is_hom
            
        else:
            vars_list = [p.free_symbols for p in polys]
            # Case A: Generators are univariate in distinct variables.
            # The radical is generated by the square-free parts of the generators.
            if all(len(v) <= 1 for v in vars_list) and len(set().union(*vars_list)) == sum(len(v) for v in vars_list):
                is_hom = True
                for p in polys:
                    p_red = sympy.sqf_part(p)
                    if not p_red.is_number:
                        if not sympy.Poly(p_red).is_homogeneous:
                            is_hom = False
                            break
                neg_q = not is_hom
                
            # Case B: All generators are linear (degree <= 1).
            # The ideal is already radical. We can check homogeneity via its reduced Groebner basis.
            else:
                all_linear = True
                for p in polys:
                    if p.is_number:
                        continue
                    poly_p = sympy.Poly(p)
                    if poly_p.total_degree() > 1:
                        all_linear = False
                        break
                        
                if all_linear:
                    all_vars = list(set().union(*vars_list))
                    if not all_vars:
                        is_hom = True
                    else:
                        gb = sympy.groebner(polys, *all_vars)
                        is_hom = True
                        for p in gb:
                            if p.is_number:
                                continue
                            if not sympy.Poly(p).is_homogeneous:
                                is_hom = False
                                break
                    neg_q = not is_hom
    except Exception:
        pass

    return [h1, neg_q]

