import sympy
from sympy import abc
from math import gcd
from functools import reduce

def is_square_free(n):
    n = abs(n)
    if n == 0:
        return False
    for i in range(2, int(n**0.5) + 1):
        if n % (i**2) == 0:
            return False
    return True

class MonomialSubring:
    """
    Represents a subring of QQ[x] generated by a set of monomials x^d.
    """
    def __init__(self, *degrees):
        self.degrees = list(degrees)
        if not all(isinstance(d, int) and d > 0 for d in self.degrees):
            raise ValueError("Degrees must be positive integers")
        self.g = reduce(gcd, self.degrees) if self.degrees else 1

    def fraction_field(self):
        return RationalFunctionField(self.g)

    def is_integrally_closed_in(self, field):
        if not isinstance(field, RationalFunctionField):
            return False
        if field.g != self.g:
            return False
        return self.g in self.degrees

class RationalFunctionField:
    """
    Represents a subfield of QQ(x) generated by x^g.
    """
    def __init__(self, g):
        self.g = g

    def __eq__(self, other):
        return isinstance(other, RationalFunctionField) and self.g == other.g

class QuadraticRing:
    """
    Represents the ring ZZ[sqrt(d)].
    """
    def __init__(self, d):
        if not isinstance(d, int):
            raise ValueError("d must be an integer")
        self.d = d

    def fraction_field(self):
        return QuadraticField(self.d)

    def is_integrally_closed_in(self, field):
        if not isinstance(field, QuadraticField) or field.d != self.d:
            return False
        if not is_square_free(self.d):
            return False
        # ZZ[sqrt(d)] is integrally closed iff d != 1 mod 4
        return self.d % 4 != 1

class QuadraticField:
    """
    Represents the field QQ(sqrt(d)).
    """
    def __init__(self, d):
        self.d = d

    def __eq__(self, other):
        return isinstance(other, QuadraticField) and self.d == other.d

