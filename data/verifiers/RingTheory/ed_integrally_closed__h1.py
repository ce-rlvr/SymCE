def conditions(witness) -> list[bool]:
    try:
        if not isinstance(witness, (list, tuple)) or len(witness) != 2:
            return [False, False]
        R, K = witness
    except Exception:
        return [False, False]
        
    try:
        if hasattr(R, 'fraction_field'):
            h1 = (K == R.fraction_field())
        elif hasattr(R, 'get_field'):
            h1 = (K == R.get_field())
        else:
            h1 = False
    except Exception:
        h1 = False
        
    try:
        if hasattr(R, 'is_integrally_closed_in'):
            q = R.is_integrally_closed_in(K)
        elif R == sympy.ZZ and K == sympy.QQ:
            q = True
        else:
            # Default to True so it fails to be a counterexample if we can't verify
            q = True
        neg_q = not q
    except Exception:
        neg_q = False
        
    return [h1, neg_q]

