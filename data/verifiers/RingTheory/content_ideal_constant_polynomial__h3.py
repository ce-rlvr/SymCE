CONDITION_LABELS = [
    "H_1: R is a commutative ring with identity",
    "H_2: a is an element of R",
    "¬Q: The content ideal c(f) is not equal to the principal ideal (a)"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    """
    Given a witness, checks if it is a valid counterexample to the false conjecture.
    The witness should be a tuple (a, f) or (R, a, f) where:
      - R is a SymPy domain (optional, inferred from f if omitted)
      - a is an element of R
      - f is a polynomial in R[x]
    """
    try:
        if len(witness) == 3:
            R, a, f = witness
            if not isinstance(f, sympy.Poly):
                f = sympy.Poly(f, domain=R)
            domain = f.domain
        elif len(witness) == 2:
            a, f = witness
            if not isinstance(f, sympy.Poly):
                f = sympy.Poly(f)
            domain = f.domain
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H1: R is a commutative ring with identity
    try:
        # All SymPy polynomial domains represent commutative rings with identity
        h1 = True
    except Exception:
        h1 = False

    # H2: a is an element of R
    try:
        # Check if 'a' can be converted to an element of the polynomial's domain
        a_dom = domain.convert(a)
        h2 = True
    except Exception:
        h2 = False

    # neg_Q: The content ideal c(f) is not equal to the principal ideal (a)
    try:
        coeffs = [domain.to_sympy(c) for c in f.coeffs()]
        if not coeffs:
            coeffs = [sympy.S.Zero]
        
        # In a PID, the content ideal c(f) is generated by the GCD of its coefficients.
        g = coeffs[0]
        for c in coeffs[1:]:
            g = sympy.gcd(g, c)
        
        def divides(divisor, dividend):
            if dividend == 0:
                return True
            if divisor == 0:
                return False
            try:
                # Exact division in the domain
                domain.exquo(domain.convert(dividend), domain.convert(divisor))
                return True
            except Exception:
                return False

        # Two principal ideals (g) and (a) are equal iff g divides a and a divides g.
        # Since g is the GCD of the coefficients, a divides g iff a divides all coefficients.
        g_divides_a = divides(g, a)
        a_divides_coeffs = all(divides(a, c) for c in coeffs)
        
        ideals_equal = g_divides_a and a_divides_coeffs
        
        # The conclusion FAILS if the ideals are NOT equal
        neg_q = not ideals_equal
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]