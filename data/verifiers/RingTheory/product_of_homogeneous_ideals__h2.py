import sympy
from sympy import groebner, Poly
from sympy.abc import x, y, z, t, u, v, w

def conditions(witness) -> list[bool]:
    """
    Given a witness, checks if it is a valid counterexample to the false conjecture:
    "If R is a graded ring, then the product ideal IJ is a homogeneous ideal of R."
    
    The witness should be a tuple (I, J) where I and J are lists of polynomials 
    (generators for the ideals) in a polynomial ring (which is naturally graded).
    """
    try:
        I, J = witness
    except Exception:
        return [False, False]
    
    # H_1: R is a graded ring
    # We verify that I and J are collections of sympy expressions.
    # Polynomial rings are graded rings, so any valid polynomial generators satisfy this.
    try:
        h1 = True
        for gens in (I, J):
            if not isinstance(gens, (list, tuple, set)):
                h1 = False
                break
            for g in gens:
                if not isinstance(g, sympy.Expr):
                    h1 = False
                    break
    except Exception:
        h1 = False

    # ¬Q: The product ideal IJ is NOT a homogeneous ideal of R
    try:
        # Generate the product ideal IJ
        IJ = []
        for i in I:
            for j in J:
                IJ.append(i * j)
        
        # Extract all free symbols to define the polynomial ring
        syms = set()
        for g in IJ:
            syms.update(g.free_symbols)
        syms = list(syms)
        
        if not syms:
            # If there are no symbols, the ideal is generated by constants.
            # Constant ideals in a polynomial ring are either (0) or (1), both homogeneous.
            neg_q = False
        else:
            # An ideal is homogeneous iff its reduced Groebner basis consists of homogeneous polynomials.
            gb = groebner(IJ, *syms)
            is_hom = True
            for p in gb:
                poly = Poly(p, *syms)
                if not poly.is_homogeneous:
                    is_hom = False
                    break
            neg_q = not is_hom
    except Exception:
        neg_q = False

    return [h1, neg_q]

