import sympy
from sympy import Poly, Expr, Symbol
from sympy.abc import x, y, z, t, u, v

def conditions(witness):
    try:
        degrees, S_gens = witness
    except Exception:
        return [False, False, False]
        
    # H1: R is a graded commutative ring
    # We verify this by checking that degrees defines a valid grading on a polynomial ring,
    # and S_gens are valid polynomials in this ring.
    try:
        h1 = isinstance(degrees, dict) and all(isinstance(k, Symbol) and isinstance(v, int) for k, v in degrees.items())
        h1 = h1 and isinstance(S_gens, list) and all(isinstance(g, (Expr, int)) for g in S_gens)
        if h1:
            for g in S_gens:
                g_sym = sympy.sympify(g)
                fs = list(g_sym.free_symbols)
                if fs:
                    # This will raise PolynomialError if g_sym is not a polynomial
                    Poly(g_sym, *fs)
    except Exception:
        h1 = False
        
    # H2: S is a multiplicatively closed subset of R
    # S is generated by S_gens. It is multiplicatively closed if S_gens are valid non-zero elements.
    try:
        h2 = isinstance(S_gens, list) and len(S_gens) > 0 and all(g != 0 for g in S_gens)
    except Exception:
        h2 = False
        
    # Neg_Q: The localized ring S^{-1}R does NOT admit a natural grading making the canonical map graded.
    # This occurs when S contains non-homogeneous elements (which cannot be inverted in a graded sense
    # without forcing non-trivial relations like nilpotency, which don't exist in our free polynomial ring).
    try:
        def is_homogeneous(expr, degrees):
            expr = sympy.sympify(expr)
            if expr == 0:
                return True
            expr = sympy.expand(expr)
            if expr.is_Number:
                return True
            free_symbols = list(expr.free_symbols)
            if not free_symbols:
                return True
            poly = Poly(expr, *free_symbols)
            deg_set = set()
            for monom in poly.monoms():
                d = sum(exp * degrees.get(sym, 0) for exp, sym in zip(monom, free_symbols))
                deg_set.add(d)
            return len(deg_set) <= 1

        neg_q = not all(is_homogeneous(g, degrees) for g in S_gens)
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

