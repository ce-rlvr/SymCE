def get_attr(w, name):
    if isinstance(w, dict):
        return w.get(name)
    return getattr(w, name, None)

def conditions(witness) -> list[bool]:
    R = get_attr(witness, 'R')
    I = get_attr(witness, 'I')
    S_set = get_attr(witness, 'S')
    J = get_attr(witness, 'J')
    T = get_attr(witness, 'T')

    try:
        if hasattr(S_set, '__iter__') and not hasattr(S_set, '__len__') and not hasattr(S_set, 'is_finite'):
            S_set = list(S_set)
    except Exception:
        pass

    # H1: R is a commutative ring
    h1 = False
    try:
        if R in (sympy.S.Integers, sympy.ZZ):
            h1 = True
        elif hasattr(R, 'is_commutative') and R.is_commutative and hasattr(R, 'is_Ring') and R.is_Ring:
            h1 = True
        elif R in (sympy.QQ, sympy.RR, sympy.CC):
            h1 = True
    except Exception:
        pass

    # H2: I is an ideal of R generated by a finite set S
    h2 = False
    try:
        S_is_finite = False
        if isinstance(S_set, (set, list, tuple)):
            S_is_finite = True
        elif hasattr(S_set, 'is_finite') and S_set.is_finite:
            S_is_finite = True
        
        if S_is_finite:
            if R in (sympy.S.Integers, sympy.ZZ):
                g = 0
                for s in S_set:
                    g = math.gcd(g, int(s))
                if isinstance(I, (int, sympy.Integer)):
                    if abs(int(I)) == g:
                        h2 = True
                elif I in (sympy.S.Integers, sympy.ZZ) and g == 1:
                    h2 = True
            else:
                h2 = True
    except Exception:
        pass

    # neg_Q: The product ideal IJ is NOT finitely generated by the set of all products st where s \in S and t \in T.
    neg_q = False
    try:
        T_is_infinite = False
        if T in (sympy.S.Integers, sympy.S.Naturals, sympy.S.Naturals0, sympy.ZZ):
            T_is_infinite = True
        elif hasattr(T, 'is_finite') and T.is_finite is False:
            T_is_infinite = True
        elif isinstance(T, (set, list, tuple)):
            T_is_infinite = False
        elif hasattr(T, '__iter__') and not hasattr(T, '__len__'):
            T_is_infinite = True
            
        if T_is_infinite:
            # If T is infinite, the set of products is infinite unless S_set only contains 0
            if any(s != 0 for s in S_set):
                neg_q = True
        else:
            # If T is finite, P is finite. Check if P generates IJ.
            P = set()
            for s in S_set:
                for t in T:
                    P.add(s * t)
            
            if R in (sympy.S.Integers, sympy.ZZ):
                p_gen = 0
                for p in P:
                    p_gen = math.gcd(p_gen, int(p))
                
                if isinstance(I, (int, sympy.Integer)) and isinstance(J, (int, sympy.Integer)):
                    ij_gen = abs(int(I) * int(J))
                elif I in (sympy.S.Integers, sympy.ZZ) and J in (sympy.S.Integers, sympy.ZZ):
                    ij_gen = 1
                elif isinstance(I, (int, sympy.Integer)) and J in (sympy.S.Integers, sympy.ZZ):
                    ij_gen = abs(int(I))
                elif I in (sympy.S.Integers, sympy.ZZ) and isinstance(J, (int, sympy.Integer)):
                    ij_gen = abs(int(J))
                else:
                    ij_gen = None
                
                if ij_gen is not None and p_gen != ij_gen:
                    neg_q = True
    except Exception:
        pass

    return [h1, h2, neg_q]

