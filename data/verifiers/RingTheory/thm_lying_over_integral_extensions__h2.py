import sympy

# Top-level setup
# Witness is expected to be a tuple of integers (n, m, p) representing:
# R = Z/nZ
# S = Z/mZ
# P = pZ/nZ (where p is a prime dividing n)
# No special named objects are required for this witness format.

def divides(a, b):
    if a == 0:
        return b == 0
    return b % a == 0

def conditions(witness):
    try:
        if isinstance(witness, dict):
            n = int(witness['n'])
            m = int(witness['m'])
            p = int(witness['p'])
        else:
            n, m, p = witness
            n = int(n)
            m = int(m)
            p = int(p)
    except Exception:
        return [False, False, False, False]

    # H_1: R and S are commutative rings with identity
    try:
        # Z/nZ and Z/mZ are commutative rings with identity for n, m >= 0
        h1 = (n >= 0) and (m >= 0)
    except Exception:
        h1 = False

    # H_2: S is an integral extension of R
    try:
        # The natural map Z/nZ -> Z/mZ is a well-defined ring homomorphism if m divides n.
        # Since this map is surjective, S is generated by 1 over R, making it an integral extension.
        # (Note: The false conjecture drops the requirement that R is a subring of S, i.e., injectivity).
        h2 = divides(m, n)
    except Exception:
        h2 = False

    # H_3: P is a prime ideal of R
    try:
        # In Z/nZ, the ideal generated by p is prime iff p is a prime number and divides n.
        h3 = sympy.isprime(p) and divides(p, n)
    except Exception:
        h3 = False

    # ¬Q: There is no prime ideal Q of S such that Q \cap R = P
    try:
        # Prime ideals of S = Z/mZ correspond to prime divisors of m.
        # The preimage (contraction) of qZ/mZ in Z/nZ is qZ/nZ.
        # For this to equal P = pZ/nZ, we must have q = p.
        # Thus, such a prime ideal Q exists iff p divides m.
        # The conclusion fails (neg_q is True) iff p does NOT divide m.
        neg_q = not divides(p, m)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

