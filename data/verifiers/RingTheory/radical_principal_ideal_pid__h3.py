import sympy
from sympy import factor_list
from sympy.ntheory import primefactors
import math
from sympy.abc import x, y, z

# Top-level setup
# (No specific named objects required for this ring theory theorem, 
# but we define some standard ones just in case)
# x, y, z are already imported from sympy.abc

def conditions(witness) -> list[bool]:
    try:
        # Flexible witness parsing to handle (a,), (a, p_list), (R, a, p_list), etc.
        if isinstance(witness, tuple) and len(witness) > 0 and isinstance(witness[0], str):
            if len(witness) == 2:
                witness = witness[1]
            else:
                witness = witness[1:]

        if isinstance(witness, tuple):
            if len(witness) == 2 and isinstance(witness[1], (list, tuple)):
                a, p_list = witness
            elif len(witness) >= 2 and isinstance(witness[1], (int, sympy.Integer, sympy.Expr)):
                a = witness[0]
                p_list = witness[1:]
            elif len(witness) == 3 and isinstance(witness[2], (list, tuple)):
                _, a, p_list = witness
            else:
                a = witness[0]
                p_list = []
        else:
            a = witness
            p_list = []
            
        a = sympy.sympify(a)
        p_list = [sympy.sympify(p) for p in p_list]
    except Exception:
        return [False, False, False]

    # H1: R is a principal ideal domain
    # We evaluate in Z or Q[x], which are PIDs.
    h1 = True

    # H2: a is a non-zero non-unit element of R
    try:
        if a == 0:
            h2 = False
        elif a.is_Integer:
            h2 = abs(a) != 1
        else:
            h2 = not sympy.cancel(a).is_constant()
    except Exception:
        h2 = False

    # NegQ: The radical of <a> is NOT the principal ideal generated by the product p_1...p_m
    try:
        # Compute the generator of the radical of <a>
        if a == 0:
            rad_a = sympy.Integer(0)
        elif a.is_Integer:
            rad_a = sympy.Integer(math.prod(primefactors(int(a))))
        else:
            factors = factor_list(a)
            rad_a = factors[0]
            for f, _ in factors[1]:
                rad_a *= f
                
        # Compute the product p_1...p_m
        if not p_list:
            # If p_list is not provided, assume p_1...p_m are the prime factors of a
            # whose product is exactly a (since the "distinct" hypothesis was dropped).
            prod_p = a
        else:
            prod_p = p_list[0]
            for p in p_list[1:]:
                prod_p *= p
                
        # Check if rad_a and prod_p generate the same ideal
        if rad_a == 0 and prod_p == 0:
            ideals_equal = True
        elif rad_a == 0 or prod_p == 0:
            ideals_equal = False
        elif rad_a.is_Integer and prod_p.is_Integer:
            ideals_equal = abs(rad_a) == abs(prod_p)
        else:
            ratio = sympy.cancel(rad_a / prod_p)
            ideals_equal = ratio.is_constant()
            
        neg_q = not ideals_equal
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

