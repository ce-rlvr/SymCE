import sympy
from sympy import symbols, groebner

# Top-level setup: named object bindings that the witness expression may reference.
x, y, z = symbols('x y z')

CONDITION_LABELS = [
    "H_1: M is a finitely generated R-module",
    "¬Q: M is not isomorphic to a direct sum of a free R-module and finitely many cyclic modules of the form R/(p^k)"
]

N_HYP = 1
NEG_Q_INDEX = 1

def conditions(witness):
    """
    Expects witness to be a tuple representing an ideal in a polynomial ring:
      witness = (variables, generators)
    or
      witness = (variables, generators, domain_str)
      
    Example: ((x, y), [x, y]) for the ideal (x, y) in QQ[x, y].
    """
    try:
        if isinstance(witness, tuple):
            if len(witness) == 2:
                vars_tuple, gens = witness
                domain_str = 'QQ'
            elif len(witness) == 3:
                vars_tuple, gens, domain_str = witness
            else:
                return [False, False]
        else:
            return [False, False]
            
        if not isinstance(vars_tuple, tuple):
            vars_tuple = (vars_tuple,)
            
        if not isinstance(gens, list) or len(gens) == 0:
            return [False, False]
            
        # H_1: M is a finitely generated R-module
        # The witness represents an ideal in a polynomial ring generated by `gens`.
        # Since `gens` is a finite list, the ideal is finitely generated.
        h1_ok = True
        
        # ¬Q: M is not isomorphic to a direct sum of a free R-module and cyclic modules R/(p^k)
        # For an ideal in an integral domain, it is torsion-free.
        # Thus, any such direct sum must have no torsion part, meaning M must be free.
        # Since M is an ideal, its rank as a free module is at most 1.
        # Therefore, M is free iff it is a principal ideal.
        # An ideal in a polynomial ring over a field (or ZZ) is principal 
        # iff its reduced Groebner basis has length <= 1.
        gb = groebner(gens, *vars_tuple, domain=domain_str)
        gb_polys = list(gb)
        
        neg_q_ok = len(gb_polys) > 1
        
        return [h1_ok, neg_q_ok]
    except Exception:
        return [False, False]