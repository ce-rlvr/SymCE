def conditions(witness) -> list[bool]:
    h1, h2, h3, h4, neg_q = False, False, False, False, False
    try:
        if isinstance(witness, dict):
            h1 = bool(witness.get('h1', False))
            h2 = bool(witness.get('h2', False))
            h3 = bool(witness.get('h3', False))
            h4 = bool(witness.get('h4', False))
            neg_q = bool(witness.get('neg_q', False))
        elif hasattr(witness, 'h1'):
            h1 = bool(witness.h1())
            h2 = bool(witness.h2())
            h3 = bool(witness.h3())
            h4 = bool(witness.h4())
            neg_q = bool(witness.neg_q())
    except Exception:
        pass
    return [h1, h2, h3, h4, neg_q]

