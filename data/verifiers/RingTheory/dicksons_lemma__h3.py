import sympy as sp

x, y, z, t = sp.symbols('x y z t')
x1, x2, x3, x4 = sp.symbols('x1 x2 x3 x4')

def conditions(witness):
    try:
        h1 = False
        if isinstance(witness, (list, tuple, set)) and len(witness) > 0:
            h1 = True
    except Exception:
        h1 = False

    try:
        h2 = False
        if isinstance(witness, (list, tuple, set)) and len(witness) > 0:
            all_poly = True
            for w in witness:
                p = sp.sympify(w)
                if not p.is_polynomial():
                    all_poly = False
                    break
            h2 = all_poly
    except Exception:
        h2 = False

    try:
        neg_q = False
        if h2:
            gens = set()
            for w in witness:
                gens.update(sp.sympify(w).free_symbols)
            gens = list(gens)
            if not gens:
                neg_q = False
            else:
                try:
                    G = sp.groebner(witness, *gens, domain='QQ')
                except Exception:
                    G = sp.groebner(witness, *gens)
                for p in G:
                    poly = sp.Poly(p, *gens)
                    if len(poly.terms()) > 1:
                        neg_q = True
                        break
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

