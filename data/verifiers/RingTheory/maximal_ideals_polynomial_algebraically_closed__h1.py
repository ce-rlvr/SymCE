import sympy
from sympy import Poly
from sympy.abc import x

def _get_poly(witness):
    if isinstance(witness, (list, tuple)):
        if len(witness) != 1:
            return None
        w = witness[0]
    else:
        w = witness
        
    if not isinstance(w, sympy.Poly):
        free_symbols = getattr(w, "free_symbols", set())
        if len(free_symbols) == 1:
            gen = list(free_symbols)[0]
            p = sympy.Poly(w, gen)
        else:
            p = sympy.Poly(w, x)
    else:
        p = w
        
    if not p.is_univariate:
        return None
        
    if not p.domain.is_Field:
        p = p.set_domain(p.domain.get_field())
        
    return p

def conditions(witness) -> list[bool]:
    try:
        p = _get_poly(witness)
        if p is None:
            h1 = False
        else:
            h1 = bool(p.degree() >= 1 and p.is_irreducible)
    except Exception:
        h1 = False

    try:
        p = _get_poly(witness)
        if p is None:
            neg_q = False
        else:
            neg_q = bool(p.degree() != 1)
    except Exception:
        neg_q = False

    return [h1, neg_q]

