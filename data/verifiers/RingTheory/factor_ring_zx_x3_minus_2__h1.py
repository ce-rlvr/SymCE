import sympy
from sympy.abc import x

def conditions(witness):
    try:
        H_1 = bool(witness == x**3 - 2)
    except Exception:
        H_1 = False

    try:
        # In Z[x], the ideal <P> is prime iff P is irreducible over Z.
        # Thus, Z[x]/<P> is an integral domain iff P is irreducible over Z.
        is_domain = sympy.polys.polytools.is_irreducible(witness, domain='ZZ')
        
        # Z[x]/<P> is never a field for any polynomial P because Z is not a field
        # (the ideal <P> is never maximal in Z[x]).
        is_field = False
        
        conclusion = is_domain and not is_field
        neg_Q = not conclusion
    except Exception:
        neg_Q = False

    return [H_1, neg_Q]

