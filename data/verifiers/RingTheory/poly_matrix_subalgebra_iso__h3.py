def conditions(witness) -> list[bool]:
    try:
        if not isinstance(witness, sympy.MatrixBase):
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H_1: F is a field
    # Any sympy matrix can be considered as a matrix over the field of fractions of its entries.
    h1 = True

    # H_2: A is an n x n matrix over F
    try:
        h2 = bool(witness.is_square)
    except Exception:
        h2 = False

    # ¬Q: The factor ring F[x]/(m_A(x)) is NOT isomorphic to the F-subalgebra generated by A.
    # Assuming m_A(x) refers to the characteristic polynomial, the conclusion fails
    # if and only if the minimal polynomial has degree strictly less than n.
    # This happens if and only if the matrices I, A, A^2, ..., A^{n-1} are linearly dependent.
    try:
        if not h2:
            neg_q = False
        else:
            n = witness.rows
            if n == 0:
                neg_q = False
            else:
                vecs = []
                A_k = sympy.eye(n)
                for k in range(n):
                    flat = [A_k[i, j] for i in range(n) for j in range(n)]
                    vecs.append(flat)
                    A_k = A_k * witness
                M = sympy.Matrix(vecs)
                rank = M.rank()
                neg_q = bool(rank < n)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

