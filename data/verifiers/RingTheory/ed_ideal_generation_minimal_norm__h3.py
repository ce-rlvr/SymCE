import sympy
from functools import reduce

# Top-level setup for potential witness expressions
x, y, z = sympy.symbols('x y z')

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness should be a tuple: (I_gens, a)
    where I_gens is a list of generators for the ideal I, and a is an element.
    """
    try:
        I_gens, a = witness
        if not isinstance(I_gens, (list, tuple, set)):
            I_gens = [I_gens]
            
        # H1: R is a Euclidean domain
        # We accept integers (Z) or univariate polynomials over a field (Q[x])
        is_Z = all(isinstance(val, (int, sympy.Integer)) for val in I_gens) and isinstance(a, (int, sympy.Integer))
        
        is_poly = False
        if not is_Z:
            try:
                symbols = set()
                for val in list(I_gens) + [a]:
                    if hasattr(val, 'free_symbols'):
                        symbols.update(val.free_symbols)
                # Univariate polynomials over a field form a Euclidean domain
                if len(symbols) <= 1:
                    syms = list(symbols)
                    for val in list(I_gens) + [a]:
                        # This will raise an exception if val is not a polynomial
                        sympy.Poly(val, *syms)
                    is_poly = True
            except Exception:
                pass
                
        h1 = is_Z or is_poly
        
        # H2: I is a non-zero ideal of R
        h2 = False
        try:
            if any(sympy.simplify(val) != 0 for val in I_gens):
                h2 = True
        except Exception:
            pass
            
        # ¬Q: The ideal I is NOT generated by a
        neg_q = False
        try:
            if not I_gens:
                g = 0
            else:
                g = reduce(sympy.gcd, I_gens)
                
            if is_Z:
                neg_q = abs(int(g)) != abs(int(a))
            elif is_poly:
                g_simp = sympy.simplify(g)
                a_simp = sympy.simplify(a)
                if g_simp == 0 and a_simp == 0:
                    neg_q = False
                elif g_simp == 0 or a_simp == 0:
                    neg_q = True
                else:
                    # In Q[x], two elements generate the same ideal iff they are associates
                    # (i.e., their ratio is a non-zero constant)
                    ratio = sympy.simplify(g_simp / a_simp)
                    if ratio.free_symbols:
                        neg_q = True
                    else:
                        neg_q = False
        except Exception:
            pass
            
        return [bool(h1), bool(h2), bool(neg_q)]
    except Exception:
        return [False, False, False]

