def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, dict):
            n = witness.get('n')
            J = witness.get('J', None)
            x = witness.get('x')
        elif isinstance(witness, (tuple, list)):
            if len(witness) == 3:
                n, J, x = witness
            elif len(witness) == 2:
                n, x = witness
                J = None
            else:
                return [False, False, False]
        else:
            return [False, False, False]

        if not isinstance(n, int) or n < 2:
            return [False, False, False]

        # H_1: R is a right Artinian ring
        # Z_n is a finite ring, which is always Artinian.
        h1 = True

        # H_2: J is the Jacobson radical of R
        # In Z_n, the Jacobson radical is the ideal generated by the product of its distinct prime factors.
        rad_n = 1
        for p in factorint(n).keys():
            rad_n *= p
        expected_J = set((k * rad_n) % n for k in range(n))

        if J is not None:
            try:
                J_set = set(int(y) % n for y in J)
            except TypeError:
                J_set = set()
            h2 = (J_set == expected_J)
        else:
            J_set = expected_J
            h2 = True

        x_mod = int(x) % n

        # neg_Q: There does NOT exist an idempotent e in R such that e - x in J
        idempotents = [e for e in range(n) if (e * e) % n == e]

        exists_e = False
        for e in idempotents:
            if (e - x_mod) % n in J_set:
                exists_e = True
                break

        neg_q = not exists_e

        return [h1, h2, neg_q]
    except Exception:
        return [False, False, False]

