def conditions(witness):
    h1, h2, neg_q = False, False, False

    def check_prop(prop):
        if isinstance(witness, dict):
            if prop in witness:
                return bool(witness[prop])
        else:
            if hasattr(witness, prop):
                val = getattr(witness, prop)
                if callable(val):
                    try:
                        return bool(val())
                    except Exception:
                        return False
                return bool(val)
        return None

    try:
        # H1: I is an ideal in the polynomial ring
        is_ideal = check_prop('is_ideal')
        in_poly = check_prop('in_polynomial_ring')
        
        if is_ideal is not None and in_poly is not None:
            h1 = is_ideal and in_poly
        else:
            h1_direct = check_prop('is_ideal_in_polynomial_ring')
            if h1_direct is not None:
                h1 = h1_direct
            else:
                # Fallback: check if it has a ring attribute (e.g., SymPy Ideal)
                if hasattr(witness, 'ring'):
                    ring = witness.ring
                    ring_is_poly = False
                    if hasattr(ring, 'is_polynomial_ring'):
                        val = ring.is_polynomial_ring
                        ring_is_poly = bool(val() if callable(val) else val)
                    elif 'polynomial' in str(type(ring)).lower():
                        ring_is_poly = True
                    
                    if is_ideal is not None:
                        h1 = is_ideal and ring_is_poly
                    elif 'ideal' in str(type(witness)).lower():
                        h1 = ring_is_poly
    except Exception:
        pass

    try:
        # H2: I is generated by a subset of monomials
        is_monomial = check_prop('is_monomial_ideal')
        gen_mono = check_prop('generated_by_monomials')
        
        if is_monomial is not None:
            h2 = is_monomial
        elif gen_mono is not None:
            h2 = gen_mono
        else:
            # Fallback: Check if it's an ideal with explicit monomial generators
            if hasattr(witness, 'gens'):
                gens = witness.gens
                if callable(gens):
                    gens = gens()
                all_mono = True
                has_gens = False
                for g in gens:
                    has_gens = True
                    try:
                        if hasattr(g, 'as_poly'):
                            p = g.as_poly()
                            if p is not None:
                                if len(p.terms()) != 1:
                                    all_mono = False
                                    break
                            else:
                                all_mono = False
                                break
                        elif hasattr(g, 'is_monomial'):
                            if not g.is_monomial:
                                all_mono = False
                                break
                        else:
                            all_mono = False
                            break
                    except Exception:
                        all_mono = False
                        break
                if has_gens and all_mono:
                    h2 = True
    except Exception:
        pass

    try:
        # neg_Q: I is not generated by a finite set of monomials
        is_fin_gen = check_prop('is_finitely_generated')
        fin_gen = check_prop('finitely_generated')
        
        if is_fin_gen is not None:
            neg_q = not is_fin_gen
        elif fin_gen is not None:
            neg_q = not fin_gen
        else:
            # If it's a standard SymPy ideal, it has a finite list of generators
            if hasattr(witness, 'gens'):
                neg_q = False
    except Exception:
        pass

    return [h1, h2, neg_q]

