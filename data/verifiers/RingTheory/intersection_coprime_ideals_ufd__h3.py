import sympy
from sympy import ZZ, QQ
from sympy.abc import x, y, z

Z = ZZ
Q = QQ

CONDITION_LABELS = [
    "H_1: R is a unique factorization domain",
    "H_2: a and b are non-zero elements of R",
    "¬Q: The intersection of the principal ideals (a) and (b) is not the principal ideal (ab)"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    try:
        if isinstance(witness, tuple):
            if len(witness) == 3:
                R, a, b = witness
            elif len(witness) == 2:
                R = ZZ
                a, b = witness
            else:
                return [False, False, False]
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H_1: R is a unique factorization domain
    try:
        h1 = bool(R.is_UFD)
    except Exception:
        h1 = False

    # H_2: a and b are non-zero elements of R
    try:
        a_dom = R.convert(a)
        b_dom = R.convert(b)
        a_nonzero = (a_dom != R.zero)
        b_nonzero = (b_dom != R.zero)
        h2 = bool(a_nonzero and b_nonzero)
    except Exception:
        h2 = False

    # ¬Q: The intersection of the principal ideals (a) and (b) is not the principal ideal (ab)
    try:
        a_dom = R.convert(a)
        b_dom = R.convert(b)
        
        # In a UFD, the intersection of principal ideals (a) and (b) is generated by lcm(a, b).
        # Thus, (a) ∩ (b) = (ab) if and only if lcm(a, b) and ab generate the same ideal.
        ab = R.mul(a_dom, b_dom)
        lcm_ab = R.lcm(a_dom, b_dom)
        
        def divides(divisor, dividend, dom):
            if divisor == dom.zero:
                return dividend == dom.zero
            try:
                dom.exquo(dividend, divisor)
                return True
            except Exception:
                return False
                
        ab_divides_lcm = divides(ab, lcm_ab, R)
        lcm_divides_ab = divides(lcm_ab, ab, R)
        
        ideals_equal = ab_divides_lcm and lcm_divides_ab
        neg_q = not ideals_equal
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]