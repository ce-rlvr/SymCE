def is_in_field(val, F):
    try:
        if val in F:
            return True
    except Exception:
        pass
    try:
        if hasattr(F, 'contains') and F.contains(val):
            return True
    except Exception:
        pass
    if F == QQ:
        if hasattr(val, 'is_rational') and val.is_rational:
            return True
        if isinstance(val, (int, Integer, Rational)):
            return True
    return False

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            A, F = witness
        else:
            A = witness
            F = QQ
    except Exception:
        return [False, False, False]

    try:
        h1_ok = False
        if hasattr(F, 'is_Field') and F.is_Field:
            h1_ok = True
        elif F == QQ:
            h1_ok = True
    except Exception:
        h1_ok = False

    try:
        m_A = sympy.minpoly(A, x)
        poly = m_A.as_poly(x)
        if poly is None:
            h2_ok = False
        else:
            coeffs = poly.coeffs()
            h2_ok = True
            for c in coeffs:
                if not is_in_field(c, F):
                    h2_ok = False
                    break
    except Exception:
        h2_ok = False

    try:
        if not isinstance(A, Matrix):
            neg_q = True
        elif A.rows != A.cols:
            neg_q = True
        else:
            entries_in_F = True
            for e in A:
                if not is_in_field(e, F):
                    entries_in_F = False
                    break
            neg_q = not entries_in_F
    except Exception:
        neg_q = True

    return [h1_ok, h2_ok, neg_q]

