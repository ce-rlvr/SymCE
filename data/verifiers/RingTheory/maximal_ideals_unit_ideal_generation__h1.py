def extract_callable_or_value(obj, key, *args):
    if isinstance(obj, dict):
        if key not in obj:
            raise KeyError(f"Key '{key}' not found in witness dictionary.")
        val = obj[key]
    else:
        if not hasattr(obj, key):
            raise AttributeError(f"Attribute '{key}' not found in witness object.")
        val = getattr(obj, key)
        
    if callable(val):
        return val(*args)
    elif isinstance(val, dict) and len(args) == 1:
        return val[args[0]]
    return val

def conditions(witness) -> list[bool]:
    try:
        h1_ok = bool(extract_callable_or_value(witness, 'is_proper_ideal'))
    except Exception:
        h1_ok = False
        
    try:
        is_max = bool(extract_callable_or_value(witness, 'is_maximal_ideal'))
        r_minus_m = extract_callable_or_value(witness, 'R_minus_M')
        
        all_eq_R = True
        for x in r_minus_m:
            eq_R = bool(extract_callable_or_value(witness, 'ideal_generated_by_M_and_x_eq_R', x))
            if not eq_R:
                all_eq_R = False
                break
                
        q = (is_max == all_eq_R)
        neg_q = not q
    except Exception:
        neg_q = False
        
    return [h1_ok, neg_q]

