def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    Hypotheses:
      - R is a commutative ring
      - I is an ideal of R
    Conclusion:
      Ann_R(IJ) = (Ann_R(I) : J)
    """
    try:
        # Extract R, I, J and operations from the witness
        if isinstance(witness, tuple) and len(witness) == 3:
            R, I, J = witness
            add = lambda a, b: a + b
            mul = lambda a, b: a * b
        else:
            R = witness.R
            I = witness.I
            J = witness.J
            add = witness.add if hasattr(witness, 'add') else lambda a, b: a + b
            mul = witness.mul if hasattr(witness, 'mul') else lambda a, b: a * b
            
        R = list(R)
        I = list(I)
        J = list(J)
        
        # Find the zero element of R
        zero_R = None
        for z in R:
            if all(add(z, a) == a for a in R):
                zero_R = z
                break
        if zero_R is None:
            return [False, False, False]
            
        # Find the zero element of J (J might be an external R-module)
        zero_J = None
        for z in J:
            if all(add(z, a) == a for a in J):
                zero_J = z
                break
        if zero_J is None:
            if not J:
                zero_J = zero_R
            else:
                return [False, False, False]
                
        # H1: R is a commutative ring
        is_comm_ring = True
        for a in R:
            if not is_comm_ring: break
            for b in R:
                if not is_comm_ring: break
                if add(a, b) != add(b, a): is_comm_ring = False
                if mul(a, b) != mul(b, a): is_comm_ring = False
                if add(a, b) not in R: is_comm_ring = False
                if mul(a, b) not in R: is_comm_ring = False
                for c in R:
                    if add(add(a, b), c) != add(a, add(b, c)): is_comm_ring = False
                    if mul(mul(a, b), c) != mul(a, mul(b, c)): is_comm_ring = False
                    if mul(a, add(b, c)) != add(mul(a, b), mul(a, c)): is_comm_ring = False
        
        for a in R:
            has_inv = False
            for b in R:
                if add(a, b) == zero_R:
                    has_inv = True
                    break
            if not has_inv:
                is_comm_ring = False
                break
                
        # H2: I is an ideal of R
        is_ideal_I = True
        if zero_R not in I:
            is_ideal_I = False
        for i in I:
            if not is_ideal_I: break
            for j in I:
                if add(i, j) not in I:
                    is_ideal_I = False
                    break
        for r in R:
            if not is_ideal_I: break
            for i in I:
                if mul(r, i) not in I:
                    is_ideal_I = False
                    break
                    
        # Compute the product ideal/submodule IJ
        # IJ is generated by {i*j | i in I, j in J}
        IJ_gens = [mul(i, j) for i in I for j in J]
        IJ = []
        for x in IJ_gens:
            if x not in IJ:
                IJ.append(x)
        
        # Close IJ under addition
        added = True
        while added:
            added = False
            for a in IJ:
                for b in IJ:
                    c = add(a, b)
                    if c not in IJ:
                        IJ.append(c)
                        added = True
                        
        # Compute Ann_R(IJ) = {r in R | r*x = 0_J for all x in IJ}
        Ann_IJ = []
        for r in R:
            if all(mul(r, x) == zero_J for x in IJ):
                Ann_IJ.append(r)
                
        # Compute Ann_R(I) = {r in R | r*x = 0_R for all x in I}
        Ann_I = []
        for r in R:
            if all(mul(r, x) == zero_R for x in I):
                Ann_I.append(r)
                
        # Compute (Ann_R(I) : J) = {r in R | r*j in Ann_R(I) for all j in J}
        Ann_I_colon_J = []
        for r in R:
            if all(mul(r, j) in Ann_I for j in J):
                Ann_I_colon_J.append(r)
                
        # Check if Ann_R(IJ) == (Ann_R(I) : J)
        def subset(A, B):
            return all(a in B for a in A)
            
        neg_Q = not (subset(Ann_IJ, Ann_I_colon_J) and subset(Ann_I_colon_J, Ann_IJ))
        
        return [is_comm_ring, is_ideal_I, neg_Q]
    except Exception:
        return [False, False, False]

