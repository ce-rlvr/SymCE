import sympy as sp
import math
from sympy.ntheory import factorint

x, y, z, w = sp.symbols('x y z w')

def conditions(witness) -> list[bool]:
    try:
        if len(witness) == 2:
            f, g = witness
            K = []
        elif len(witness) == 3:
            K, f, g = witness
        else:
            return [False, False, False, False]
            
        h1 = True
        h2 = True
        h3 = True
        
        neg_q = False
        
        if isinstance(K, int):
            n = K
            if n <= 0:
                return [False, False, False, False]
            
            f_vals = [int(a) % n for a in f]
            g_vals = [int(b) % n for b in g]
            
            fg_vals = [0] * (len(f_vals) + len(g_vals) - 1)
            for i, a in enumerate(f_vals):
                for j, b in enumerate(g_vals):
                    fg_vals[i+j] = (fg_vals[i+j] + a * b) % n
                    
            def gcd_list(lst):
                res = 0
                for val in lst:
                    res = math.gcd(res, val)
                return res
                
            c_fg = math.gcd(n, gcd_list(fg_vals))
            c_f = math.gcd(n, gcd_list(f_vals))
            c_g = math.gcd(n, gcd_list(g_vals))
            c_f_c_g = math.gcd(n, c_f * c_g)
            
            def radical(ideal, mod):
                if ideal == 1:
                    return 1
                if ideal == 0:
                    ideal = mod
                factors = factorint(ideal)
                rad = 1
                for p in factors:
                    rad *= p
                return math.gcd(rad, mod)
                
            rad_c_fg = radical(c_fg, n)
            rad_c_f_c_g = radical(c_f_c_g, n)
            
            neg_q = (rad_c_fg != rad_c_f_c_g)
            
        else:
            K_expr = [sp.sympify(k) for k in K]
            f_expr = [sp.sympify(a) for a in f]
            g_expr = [sp.sympify(b) for b in g]
            
            fg = [0] * (len(f_expr) + len(g_expr) - 1)
            for i, a in enumerate(f_expr):
                for j, b in enumerate(g_expr):
                    fg[i+j] = fg[i+j] + a * b
                    
            A = K_expr + fg
            B = K_expr[:]
            for a in f_expr:
                for b in g_expr:
                    B.append(a * b)
                    
            vars_set = set()
            for expr in A + B:
                if hasattr(expr, 'free_symbols'):
                    vars_set.update(expr.free_symbols)
            vars_list = list(vars_set)
            
            t_var = sp.Symbol('t_rabinowitsch')
            vars_with_t = vars_list + [t_var]
            
            rad_eq = True
            for b in B:
                if b == 0: continue
                ideal_gens = A + [1 - t_var * b]
                gb = sp.groebner(ideal_gens, *vars_with_t, domain='QQ')
                if list(gb) != [1]:
                    rad_eq = False
                    break
                    
            if rad_eq:
                for a in A:
                    if a == 0: continue
                    ideal_gens = B + [1 - t_var * a]
                    gb = sp.groebner(ideal_gens, *vars_with_t, domain='QQ')
                    if list(gb) != [1]:
                        rad_eq = False
                        break
                        
            neg_q = not rad_eq
            
        return [h1, h2, h3, neg_q]
    except Exception:
        return [False, False, False, False]

