import sympy
from sympy import S
import math
import functools

# Top-level setup: named object bindings
ZZ = S.Integers
QQ = S.Rationals
RR = S.Reals
CC = S.Complexes

def conditions(witness) -> list[bool]:
    h1 = False
    neg_q = False
    
    try:
        # The witness is expected to be either a tuple (R, I) or just the ideal I (with R implicitly ZZ).
        if isinstance(witness, tuple) and len(witness) == 2:
            R, I = witness
        else:
            R = ZZ
            I = witness

        # Check H1: R is a commutative ring with unity
        if R in (ZZ, QQ, RR, CC):
            h1 = True
        elif str(R) == 'ZZ':
            h1 = True
        elif hasattr(R, 'is_commutative') and getattr(R, 'is_commutative', False):
            h1 = True
        elif hasattr(R, 'domain'):
            h1 = True

        # Check neg_Q: There does not exist a maximal ideal M of R such that I is a subset of M.
        # By Krull's Theorem, an ideal is contained in a maximal ideal if and only if it is a proper ideal.
        # Thus, neg_Q is True if and only if I is NOT a proper ideal (i.e., I = R, or I is generated by units).
        if R == ZZ or str(R) == 'ZZ':
            if I == ZZ or str(I) == 'ZZ':
                neg_q = True
            elif isinstance(I, (int, sympy.Integer)):
                if abs(int(I)) == 1:
                    neg_q = True
            elif isinstance(I, (list, set, tuple)):
                g = functools.reduce(math.gcd, [int(x) for x in I])
                if abs(g) == 1:
                    neg_q = True
        else:
            if I == R:
                neg_q = True
            elif I == 1:
                neg_q = True
            elif hasattr(I, 'is_one') and getattr(I, 'is_one', False):
                neg_q = True
            elif isinstance(I, (list, set, tuple)) and 1 in I:
                neg_q = True
            elif R in (QQ, RR, CC):
                # In a field, any non-zero ideal is the entire ring
                if isinstance(I, (int, float, sympy.Expr, sympy.Rational)) and I != 0:
                    neg_q = True
                elif isinstance(I, (list, set, tuple)) and any(x != 0 for x in I):
                    neg_q = True
    except Exception:
        pass

    return [h1, neg_q]

