import math
import itertools
import functools
import sympy
from sympy import S, Rational, Integer
from sympy.abc import x, y, z

# Top-level setup
Z = S.Integers
Q = S.Rationals

def conditions(witness):
    """
    Checks whether the given witness is a valid counterexample to the false conjecture:
    "For any ideals I, J of a commutative ring R, and positive integers m, n, I^m + J^n = R."
    
    The witness can be of the form (R, I, J, m, n) or simply (I, J, m, n) where R is implicitly Z.
    Ideals in Z are represented by their integer generators (or a list of generators).
    """
    try:
        if len(witness) == 5:
            R, I, J, m, n = witness
        elif len(witness) == 4:
            I, J, m, n = witness
            R = "Z"
        else:
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]

    # H_1: R is a commutative ring
    try:
        # We support Z as the commutative ring for counterexamples.
        h1 = str(R) in ("Z", "ZZ", "Integers", "Ring of Integers") or R == S.Integers
    except Exception:
        h1 = False

    # H_2: I and J are ideals of R
    try:
        if isinstance(I, (list, tuple, set)):
            I_val = functools.reduce(math.gcd, [int(arg) for arg in I], 0)
        else:
            I_val = int(I)
            
        if isinstance(J, (list, tuple, set)):
            J_val = functools.reduce(math.gcd, [int(arg) for arg in J], 0)
        else:
            J_val = int(J)
        h2 = True
    except Exception:
        h2 = False

    # H_3: m and n are positive integers
    try:
        m_val = int(m)
        n_val = int(n)
        h3 = (m_val > 0) and (n_val > 0) and (m == m_val) and (n == n_val) and not isinstance(m, float) and not isinstance(n, float)
    except Exception:
        h3 = False

    # ¬Q: I^m + J^n != R
    try:
        if h1 and h2 and h3:
            # In Z, the ideal I^m + J^n is generated by gcd(I_val^m, J_val^n).
            # It equals R iff the gcd is 1.
            if m_val > 1000 or n_val > 1000:
                # Prevent DoS from huge exponentiation; I^m + J^n = R iff I + J = R
                neg_q = (math.gcd(abs(I_val), abs(J_val)) != 1)
            else:
                gen_I_m = abs(I_val) ** m_val
                gen_J_n = abs(J_val) ** n_val
                ideal_sum_gen = math.gcd(gen_I_m, gen_J_n)
                neg_q = (ideal_sum_gen != 1)
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

