import math
from sympy import isprime

# Top-level setup
# The witness is expected to be a tuple (n, p) representing the ring Z/nZ 
# and the element p in Z/nZ.

def conditions(witness):
    try:
        if isinstance(witness, dict):
            n = int(witness.get('n', 0))
            p = int(witness.get('p', 0))
        elif isinstance(witness, (tuple, list)):
            if len(witness) != 2:
                return [False, False, False]
            n = int(witness[0])
            p = int(witness[1])
        else:
            return [False, False, False]
            
        if n <= 1:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H_1: p is a non-zero element of R
    try:
        h1 = (p % n) != 0
    except Exception:
        h1 = False

    # H_2: The ideal <p> generated by p is a maximal ideal in R
    try:
        # In Z/nZ, the ideal <p> is maximal iff gcd(p, n) is prime.
        g = math.gcd(p, n)
        h2 = isprime(g)
    except Exception:
        h2 = False

    # neg_Q: p is NOT an irreducible element of R
    try:
        # An element p is irreducible if it is non-zero, not a unit, 
        # and whenever p = ab, then a is a unit or b is a unit.
        # So p is NOT irreducible if it is a unit, OR 
        # there exist a, b such that p = ab and neither a nor b is a unit.
        
        is_unit = math.gcd(p, n) == 1
        
        has_non_trivial_factorization = False
        for a in range(n):
            if math.gcd(a, n) != 1:
                for b in range(n):
                    if math.gcd(b, n) != 1:
                        if (a * b) % n == p % n:
                            has_non_trivial_factorization = True
                            break
            if has_non_trivial_factorization:
                break
                
        neg_q = is_unit or has_non_trivial_factorization
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

