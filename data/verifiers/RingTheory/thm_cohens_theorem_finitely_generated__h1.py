# Top-level setup
# Since SymPy does not support non-finitely generated ideals natively, we provide a mock class
# that a witness expression could theoretically use or return.
class MockNonCommutativeIdeal:
    def __init__(self, is_ideal=True, is_max_non_fg=True, is_prime=False):
        self._is_ideal = is_ideal
        self._is_max_non_fg = is_max_non_fg
        self._is_prime = is_prime

    def is_ideal(self):
        return self._is_ideal

    def is_maximal_non_fg(self):
        return self._is_max_non_fg

    def is_prime(self):
        return self._is_prime

Counterexample = MockNonCommutativeIdeal(is_ideal=True, is_max_non_fg=True, is_prime=False)

def conditions(witness) -> list[bool]:
    h1 = False
    h2 = False
    neg_q = False

    # Extract ideal if witness is a tuple like (Ring, Ideal)
    ideal_obj = witness
    if isinstance(witness, (tuple, list)) and len(witness) == 2:
        ideal_obj = witness[1]

    # 1. Duck typing for objects with methods or properties
    try:
        if hasattr(ideal_obj, "is_ideal"):
            val = ideal_obj.is_ideal
            h1 = bool(val() if callable(val) else val)
    except Exception:
        pass

    try:
        if hasattr(ideal_obj, "is_maximal_non_fg"):
            val = ideal_obj.is_maximal_non_fg
            h2 = bool(val() if callable(val) else val)
        elif hasattr(ideal_obj, "is_maximal_not_finitely_generated"):
            val = ideal_obj.is_maximal_not_finitely_generated
            h2 = bool(val() if callable(val) else val)
    except Exception:
        pass

    try:
        if hasattr(ideal_obj, "is_prime"):
            val = ideal_obj.is_prime
            neg_q = not bool(val() if callable(val) else val)
    except Exception:
        pass

    # 2. Dictionary representation
    if isinstance(ideal_obj, dict):
        try:
            if "is_ideal" in ideal_obj:
                h1 = bool(ideal_obj["is_ideal"])
            if "is_maximal_non_fg" in ideal_obj:
                h2 = bool(ideal_obj["is_maximal_non_fg"])
            elif "is_maximal_not_finitely_generated" in ideal_obj:
                h2 = bool(ideal_obj["is_maximal_not_finitely_generated"])
            if "is_prime" in ideal_obj:
                neg_q = not bool(ideal_obj["is_prime"])
        except Exception:
            pass

    # 3. SymPy Ideal (which are always finitely generated by definition in SymPy)
    try:
        if type(ideal_obj).__name__ == "Ideal":
            h1 = True
            h2 = False
    except Exception:
        pass

    # 4. String or iterable of strings fallback (for text-based counterexamples)
    items_to_check = []
    if isinstance(witness, str):
        items_to_check.append(witness)
    elif isinstance(witness, (list, tuple)):
        items_to_check.extend([x for x in witness if isinstance(x, str)])

    for item in items_to_check:
        s = item.lower()
        if "ideal" in s:
            h1 = True
        if "not finitely generated" in s or "non-finitely generated" in s or "not fg" in s:
            h2 = True
        if "not prime" in s or "non-prime" in s or "isn't prime" in s or "not a prime" in s or "fails to be prime" in s:
            neg_q = True

    return [h1, h2, neg_q]

