def add_R(witness, x, y):
    if hasattr(witness, 'add_R'): return witness.add_R(x, y)
    return x + y

def sub_R(witness, x, y):
    if hasattr(witness, 'sub_R'): return witness.sub_R(x, y)
    return x - y

def mul_R(witness, x, y):
    if hasattr(witness, 'mul_R'): return witness.mul_R(x, y)
    return x * y

def add_S(witness, x, y):
    if hasattr(witness, 'add_S'): return witness.add_S(x, y)
    return x + y

def mul_S(witness, x, y):
    if hasattr(witness, 'mul_S'): return witness.mul_S(x, y)
    return x * y

