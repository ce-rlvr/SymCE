import sympy
from sympy import symbols, Poly

x, y = symbols('x y')

def conditions(witness):
    try:
        explicit_F = False
        if isinstance(witness, tuple) and len(witness) == 2:
            if hasattr(witness[0], 'is_Field'):
                F, I = witness
                explicit_F = True
        
        if not explicit_F:
            I = witness

        if not isinstance(I, (list, tuple)):
            I = [I]

        if not I:
            if explicit_F:
                h1 = bool(F.is_Field)
            else:
                h1 = True
            return [h1, True]

        polys = [Poly(p, x, y) for p in I]

        if explicit_F:
            domain = F
        else:
            domain = polys[0].domain
            for p in polys[1:]:
                domain = domain.unify(p.domain)
            if hasattr(domain, 'get_field'):
                domain = domain.get_field()

        h1 = bool(domain.is_Field)
    except Exception:
        h1 = False

    try:
        if not h1:
            neg_q = False
        else:
            polys_y = []
            for p in polys:
                py = Poly(p.as_expr().subs(x, 0), y, domain=domain)
                polys_y.append(py)
            
            g_poly = polys_y[0]
            for p in polys_y[1:]:
                g_poly = g_poly.gcd(p)

            if g_poly.is_zero:
                neg_q = True
            elif g_poly.degree() == 0:
                neg_q = False
            else:
                neg_q = bool(g_poly.is_irreducible)
                
    except Exception:
        neg_q = False

    return [h1, neg_q]

