import sympy
from sympy.abc import x, y, z
from sympy.polys.domains import ZZ, QQ, RR, CC, GF, Domain
from sympy.polys.rings import ring, PolyRing

# Top-level setup for witness expressions
# Provides standard symbols and domains for constructing rings.

def conditions(witness):
    """
    Given a witness tuple (p, R), checks if it satisfies the remaining hypotheses
    and falsifies the conclusion of the conjecture.
    """
    try:
        p, R = witness
    except Exception:
        return [False, False, False, False]
        
    # H1: Let p be a prime number.
    try:
        h1 = bool(sympy.isprime(p))
    except Exception:
        h1 = False
        
    # H2: Let \mathbb{F}_p be the finite field with p elements.
    # This is a definitional hypothesis; we just require p > 1 for the notation to make sense.
    try:
        h2 = bool(sympy.isprime(p) or p > 1)
    except Exception:
        h2 = False
        
    # H3: Let I = (x^p - x) be the principal ideal generated by x^p - x in R.
    # This implies R is a ring containing the generator x.
    try:
        is_valid_ring = isinstance(R, (Domain, PolyRing))
        h3 = bool(is_valid_ring and hasattr(R, 'gens') and len(R.gens) >= 1)
    except Exception:
        h3 = False
        
    # neg_Q: The factor ring R/I is NOT isomorphic to the direct product of p copies of \mathbb{F}_p.
    # R/(x^p - x) is isomorphic to F_p^p if and only if R is the polynomial ring F_p[x].
    try:
        if not sympy.isprime(p):
            neg_q = True
        elif hasattr(R, 'domain') and hasattr(R, 'gens'):
            is_isomorphic = (R.domain == GF(p)) and (len(R.gens) == 1)
            neg_q = not is_isomorphic
        else:
            neg_q = True
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

