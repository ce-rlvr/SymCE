def conditions(witness) -> list[bool]:
    """
    Given a witness object, checks if it is a valid counterexample to the conjecture.
    Returns [H_1_ok, H_2_ok, neg_Q_ok].
    """
    def get_prop(obj, prop_names, *args):
        for name in prop_names:
            if hasattr(obj, name):
                attr = getattr(obj, name)
                if callable(attr):
                    return attr(*args)
                else:
                    return attr
        raise AttributeError(f"None of {prop_names} found on {obj}")

    # Unpack witness
    try:
        if isinstance(witness, tuple):
            if len(witness) == 2:
                R, N = witness
            else:
                R = witness[0]
                N = get_prop(R, ['nilradical', 'nil_radical'])
        elif isinstance(witness, dict):
            R = witness['R']
            N = witness.get('N', get_prop(R, ['nilradical', 'nil_radical']))
        else:
            R = witness
            N = get_prop(R, ['nilradical', 'nil_radical'])
    except Exception:
        return [False, False, False]

    # H_1: R is a commutative ring
    try:
        h1 = bool(get_prop(R, ['is_commutative']))
    except Exception:
        h1 = False

    # H_2: N is the nilradical of R
    try:
        nil_R = get_prop(R, ['nilradical', 'nil_radical'])
        h2 = bool(N == nil_R)
    except Exception:
        h2 = False

    # ¬Q: The Jacobson radical of R[x] is NOT equal to the ideal N[x]
    try:
        Rx = get_prop(R, ['polynomial_ring', 'poly_ring'])
        J_Rx = get_prop(Rx, ['jacobson_radical', 'jacobson'])
        
        try:
            Nx = get_prop(N, ['polynomial_ring', 'poly_ring', 'polynomial_ideal'])
        except AttributeError:
            try:
                Nx = get_prop(Rx, ['ideal', 'generate_ideal'], N)
            except AttributeError:
                Nx = get_prop(N, ['extend'], Rx)
                
        neg_q = bool(J_Rx != Nx)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

