import sympy
from sympy.abc import x, y, z, t, u, v, w, a, b, c, d, A, B, C, D, X, Y, Z
from itertools import combinations_with_replacement

def conditions(witness) -> list[bool]:
    try:
        if not isinstance(witness, tuple) or len(witness) != 2:
            return [False]*4 + [False]
        f_coeffs, n_val = witness
    except Exception:
        return [False]*4 + [False]

    try:
        vars_set = set()
        for coeff in f_coeffs:
            c_expr = sympy.sympify(coeff)
            if hasattr(c_expr, 'free_symbols'):
                vars_set.update(c_expr.free_symbols)
        vars_list = sorted(list(vars_set), key=lambda var: var.name)
    except Exception:
        return [False]*4 + [False]

    try:
        h1 = True
        for coeff in f_coeffs:
            c_expr = sympy.sympify(coeff)
            if vars_list:
                if not c_expr.is_polynomial(*vars_list):
                    h1 = False
                    break
                poly_c = sympy.Poly(c_expr, *vars_list)
                if not (poly_c.domain.is_QQ or poly_c.domain.is_ZZ):
                    h1 = False
                    break
            else:
                if not c_expr.is_Rational:
                    h1 = False
                    break
    except Exception:
        h1 = False

    try:
        h2 = isinstance(f_coeffs, (list, tuple)) and len(f_coeffs) > 0
    except Exception:
        h2 = False

    h3 = True

    try:
        h4 = isinstance(n_val, int) and n_val > 0
    except Exception:
        h4 = False

    try:
        if not (h1 and h2 and h4):
            neg_q = False
        else:
            t_var = sympy.Symbol('t_dummy_var')
            f = sum(sympy.sympify(coeff) * t_var**i for i, coeff in enumerate(f_coeffs))
            f_n = sympy.expand(f**n_val)
            
            f_n_poly = sympy.Poly(f_n, t_var)
            c_f_n = f_n_poly.coeffs()
            
            c_f_pow_n = []
            for combo in combinations_with_replacement(f_coeffs, n_val):
                prod = 1
                for elem in combo:
                    prod *= sympy.sympify(elem)
                c_f_pow_n.append(sympy.expand(prod))
                
            c_f_n_nonzero = [sympy.expand(c_val) for c_val in c_f_n]
            c_f_n_nonzero = [c_val for c_val in c_f_n_nonzero if c_val != 0]
            
            c_f_pow_n_nonzero = [sympy.expand(c_val) for c_val in c_f_pow_n]
            c_f_pow_n_nonzero = [c_val for c_val in c_f_pow_n_nonzero if c_val != 0]
            
            if not vars_list:
                ideal1_zero = len(c_f_n_nonzero) == 0
                ideal2_zero = len(c_f_pow_n_nonzero) == 0
                neg_q = (ideal1_zero != ideal2_zero)
            else:
                if len(c_f_n_nonzero) == 0 and len(c_f_pow_n_nonzero) == 0:
                    neg_q = False
                elif len(c_f_n_nonzero) == 0 or len(c_f_pow_n_nonzero) == 0:
                    neg_q = True
                else:
                    gb1 = sympy.groebner(c_f_n_nonzero, *vars_list, domain='QQ')
                    gb2 = sympy.groebner(c_f_pow_n_nonzero, *vars_list, domain='QQ')
                    
                    def in_ideal(p, gb):
                        if p == 0: 
                            return True
                        _, rem = sympy.reduced(p, gb, *vars_list, domain='QQ')
                        return sympy.expand(rem) == 0
                    
                    subset1 = all(in_ideal(p, gb2) for p in c_f_n_nonzero)
                    subset2 = all(in_ideal(p, gb1) for p in c_f_pow_n_nonzero)
                    
                    ideals_equal = subset1 and subset2
                    neg_q = not ideals_equal
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]

