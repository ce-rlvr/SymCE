import math
from sympy import S, ZZ

# Top-level setup: named object bindings that the witness expression may reference.
class CommutativeRing:
    pass

class Z_Ring(CommutativeRing):
    def __str__(self): return "Z"
    def __repr__(self): return "Z"

# Z represents the ring of integers
Z = Z_Ring()

class Ideal:
    def __init__(self, ring, gens):
        self.ring = ring
        if isinstance(gens, (int, float)):
            self.gens = [gens]
        else:
            self.gens = list(gens)

def conditions(witness) -> list[bool]:
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness should specify a commutative ring R, and two ideals I and J.
    For simplicity, we support R = Z (the ring of integers).
    """
    try:
        # Parse witness
        if isinstance(witness, tuple) and len(witness) == 3:
            R, I, J = witness
        elif isinstance(witness, dict):
            R = witness.get('R') or witness.get('ring')
            I = witness.get('I')
            J = witness.get('J')
        else:
            return [False] * 5

        # H1: R is a commutative ring
        # We restrict to the ring of integers for this verifier
        is_Z = (isinstance(R, Z_Ring) or R == S.Integers or R == ZZ or R == 'Z')
        h1 = is_Z
        
        def get_gens(ideal, expected_ring):
            if isinstance(ideal, Ideal):
                return ideal.gens, ideal.ring == expected_ring
            elif isinstance(ideal, (list, tuple, set)):
                return list(ideal), True
            elif isinstance(ideal, int) or (hasattr(ideal, 'is_Integer') and ideal.is_Integer):
                return [int(ideal)], True
            elif hasattr(ideal, 'gens'):
                return list(ideal.gens), True
            return None, False

        I_gens, I_ring_match = get_gens(I, R)
        J_gens, J_ring_match = get_gens(J, R)

        # H2: I is an ideal of R
        h2 = I_gens is not None and I_ring_match
        
        # H3: J is an ideal of R
        h3 = J_gens is not None and J_ring_match

        if not (h1 and h2 and h3):
            return [h1, h2, h3, False, False]

        if is_Z:
            # In Z (an integral domain), regular elements are exactly the non-zero elements.
            # J contains a regular element iff it is not the zero ideal.
            h4 = any(g != 0 for g in J_gens)
            
            # The product ideal IJ is generated by the pairwise products of the generators of I and J.
            ij_gens = [x * y for x in I_gens for y in J_gens]
            
            # IJ contains a regular element iff it is not the zero ideal.
            ij_has_regular = any(g != 0 for g in ij_gens)
            
            # neg_Q: The product ideal IJ does NOT contain at least one regular element.
            neg_q = not ij_has_regular
            
            return [h1, h2, h3, h4, neg_q]
            
        return [h1, h2, h3, False, False]
    except Exception:
        return [False] * 5

