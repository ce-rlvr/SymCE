import sympy
import itertools
from sympy.abc import x, y, z, u, v, w

def get_gens_vars(witness):
    """
    Helper to extract generators and variables from the witness.
    Accepts either a tuple (gens, vars) or just gens.
    """
    if isinstance(witness, tuple) and len(witness) == 2:
        gens, vars = witness
        if isinstance(vars, (tuple, list)) and all(hasattr(v, 'name') for v in vars):
            return list(gens), tuple(vars)
    
    if not isinstance(witness, (list, tuple)):
        gens = [witness]
    else:
        gens = list(witness)
        
    free_vars = set()
    for g in gens:
        if hasattr(g, 'free_symbols'):
            free_vars.update(g.free_symbols)
            
    vars = tuple(sorted(free_vars, key=lambda var: var.name))
    return gens, vars

def conditions(witness) -> list[bool]:
    def is_ufd(w):
        """
        Check if R is a Unique Factorization Domain.
        We interpret the ring as QQ[vars], which is always a UFD.
        We just need to verify the generators are valid polynomials over QQ.
        """
        try:
            gens, vars = get_gens_vars(w)
            if len(vars) == 0:
                return False
            for g in gens:
                sympy.Poly(g, *vars, domain='QQ')
            return True
        except Exception:
            return False

    def height_is_one(w):
        """
        Check if the Krull height of the ideal P is exactly 1.
        In QQ[vars], height(P) = n - dim(P).
        We compute dim(P) using the initial ideal from a Groebner basis.
        """
        try:
            gens, vars = get_gens_vars(w)
            if not gens or len(vars) == 0:
                return False
            
            gb = sympy.groebner(gens, *vars, domain='QQ', order='lex')
            lms = []
            for g in gb:
                p = sympy.Poly(g, *vars, domain='QQ', order='lex')
                if p.is_zero:
                    continue
                lm = p.monoms()[0]
                if all(e == 0 for e in lm):
                    return False # Ideal is the whole ring (height is 0 or n, not 1)
                lms.append(lm)
            
            n = len(vars)
            max_dim = -1
            # A subset of variables is independent if no leading monomial is formed entirely by them
            for k in range(n + 1):
                for subset in itertools.combinations(range(n), k):
                    independent = True
                    for lm in lms:
                        if all(i in subset for i, exp in enumerate(lm) if exp > 0):
                            independent = False
                            break
                    if independent:
                        max_dim = max(max_dim, k)
            
            height = n - max_dim
            return height == 1
        except Exception:
            return False

    def neg_q(w):
        """
        Check if the conclusion FAILS.
        Conclusion: P is a principal ideal generated by a prime element.
        Negation: P is NOT principal OR P is NOT generated by a prime element.
        """
        try:
            gens, vars = get_gens_vars(w)
            if not gens or len(vars) == 0:
                return False
            
            gb = sympy.groebner(gens, *vars, domain='QQ', order='lex')
            gb_polys = [sympy.Poly(g, *vars, domain='QQ', order='lex') for g in gb if g != 0]
            
            # In QQ[vars], an ideal is principal iff its reduced Groebner basis has exactly 1 element
            if len(gb_polys) != 1:
                return True # Not principal, so conclusion fails
            
            f = gb_polys[0].as_expr()
            const, factors = sympy.factor_list(f, domain='QQ')
            
            # A principal ideal is generated by a prime element iff its generator is irreducible
            if len(factors) == 1 and factors[0][1] == 1:
                return False # It IS generated by a prime element, conclusion holds
            
            return True # Not generated by a prime element, conclusion fails
        except Exception:
            return False

    return [is_ufd(witness), height_is_one(witness), neg_q(witness)]

