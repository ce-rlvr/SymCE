import sympy
from sympy import ZZ, QQ, Poly, Symbol
from sympy.abc import x, y, z

def conditions(witness):
    """
    Checks if the witness is a counterexample to the false conjecture:
    "In a principal ideal domain R, every non-zero ideal I can be uniquely 
    factored into a product of prime ideals."
    
    The dropped hypothesis is that I must be a PROPER ideal. 
    The unit ideal I = R cannot be factored into a product of prime ideals 
    (since prime ideals are proper by definition, and their product is proper).
    """
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            R, I = witness
            
            # Check H1: R is a PID
            h1 = False
            if hasattr(R, 'is_PID') and R.is_PID:
                h1 = True
            elif getattr(R, '__class__', None).__name__ == 'IntegerRing':
                h1 = True
            elif hasattr(R, 'is_Field') and R.is_Field:
                h1 = True
                
            # Check H2: I is a non-zero ideal
            h2 = False
            if I != 0 and I != getattr(R, 'zero', 0):
                h2 = True
                
            # Check neg_Q: I cannot be factored into prime ideals
            # This happens when I is the unit ideal (i.e., I = R or I is generated by a unit)
            neg_q = False
            try:
                if hasattr(R, 'is_unit') and R.is_unit(I):
                    neg_q = True
                elif hasattr(I, 'is_unit') and I.is_unit:
                    neg_q = True
                elif getattr(R, '__class__', None).__name__ == 'IntegerRing':
                    if abs(int(I)) == 1:
                        neg_q = True
                elif I == 1 or I == getattr(R, 'one', 1) or I == R:
                    neg_q = True
            except Exception:
                if I == 1 or I == R:
                    neg_q = True
                    
            return [bool(h1), bool(h2), bool(neg_q)]
        else:
            # Assume witness is the generator of an ideal in a PID (like ZZ or QQ[x])
            try:
                n = int(witness)
                h1 = True
                h2 = (n != 0)
                neg_q = (abs(n) == 1)
                return [h1, h2, neg_q]
            except (TypeError, ValueError):
                if isinstance(witness, sympy.Expr):
                    h1 = True
                    h2 = (witness != 0)
                    if witness.is_constant():
                        neg_q = True
                    else:
                        neg_q = False
                    return [h1, h2, neg_q]
                return [False, False, False]
    except Exception:
        return [False, False, False]

