import sympy
import math

# Top-level setup
# We define ZZ for convenience if the witness references it.
ZZ = sympy.S.Integers

def extract_int(v):
    """Attempt to extract an integer from various common representations of principal ideals."""
    if isinstance(v, (int, sympy.Integer)):
        return int(v)
    if hasattr(v, 'gens') and len(v.gens) == 1:
        elem = v.gens[0]
        if isinstance(elem, (int, sympy.Integer)):
            return int(elem)
    if isinstance(v, (list, tuple, set)) and len(v) == 1:
        elem = list(v)[0]
        if isinstance(elem, (int, sympy.Integer)):
            return int(elem)
    return None

def conditions(witness) -> list[bool]:
    h1 = False
    h2 = False
    neg_q = False
    
    try:
        q_raw, p_raw, x_raw = None, None, None
        
        # Parse witness
        if isinstance(witness, tuple):
            if len(witness) == 4:
                _, q_raw, p_raw, x_raw = witness
            elif len(witness) == 3:
                # Distinguish between (R, Q, x) and (Q, P, x)
                if str(witness[0]) in ['ZZ', 'Z', 'Integers'] or hasattr(witness[0], 'is_commutative'):
                    _, q_raw, x_raw = witness
                else:
                    q_raw, p_raw, x_raw = witness
            elif len(witness) == 2:
                q_raw, x_raw = witness
        elif isinstance(witness, dict):
            q_raw = witness.get('Q', witness.get('q'))
            p_raw = witness.get('P', witness.get('p'))
            x_raw = witness.get('x')
            
        q = extract_int(q_raw)
        x = extract_int(x_raw)
        p = extract_int(p_raw)
        
        if q is not None and x is not None:
            # If P was not explicitly provided, deduce it from Q (valid in Z)
            if p is None:
                if q == 0:
                    p = 0
                elif q != 0:
                    factors = sympy.factorint(abs(q))
                    if len(factors) == 1:
                        p = list(factors.keys())[0]
            
            if p is not None:
                # H1: R is a commutative ring with identity
                # Since we successfully extracted integers, we are working in Z,
                # which is a commutative ring with identity.
                h1 = True
                
                # H2: Q is a P-primary ideal of R
                q_abs = abs(q)
                p_abs = abs(p)
                if q_abs == 0:
                    h2 = (p_abs == 0)
                elif q_abs == 1:
                    h2 = False
                else:
                    if sympy.isprime(p_abs):
                        n = q_abs
                        while n % p_abs == 0:
                            n = n // p_abs
                        h2 = (n == 1)
                    else:
                        h2 = False
                
                # Negated Conclusion: The ideal quotient (Q : x) is NOT equal to Q
                if q == 0:
                    # In Z, (0 : x) = Z if x == 0, else (0)
                    # Q is (0), so (0 : x) != (0) iff x == 0
                    neg_q = (x == 0)
                else:
                    # In Z, (q : x) is generated by q / gcd(q, x)
                    # It equals (q) iff gcd(q, x) == 1
                    g = math.gcd(q, x)
                    neg_q = (g != 1)
    except Exception:
        pass
        
    return [h1, h2, neg_q]

