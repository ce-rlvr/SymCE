import sympy
from sympy import symbols, S

# Top-level setup for Ring/Field domain
x, y, z = symbols('x y z')
Z = S.Integers
Q = S.Rationals

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness is expected to be a tuple (k, i, j) representing the generators
    of the ideals K, I, and J in a Principal Ideal Domain (PID) such as the integers Z.
    """
    try:
        if isinstance(witness, dict):
            k = witness.get('k', witness.get('K'))
            i = witness.get('i', witness.get('I'))
            j = witness.get('j', witness.get('J'))
        else:
            k, i, j = witness
            
        k = sympy.sympify(k)
        i = sympy.sympify(i)
        j = sympy.sympify(j)
    except Exception:
        return [False, False, False]

    try:
        # H1: R is a ring.
        # We assume the witness provides elements of a PID (like Z or F[x]), which is a ring.
        h1 = True
    except Exception:
        h1 = False

    try:
        # H2: K is a proper ideal of R.
        # In a PID, an ideal (k) is proper iff k is not a unit.
        # This is equivalent to saying that the ideal generated by k is not the whole ring,
        # so gcd(k, 0) != 1.
        h2 = bool(sympy.gcd(k, 0) != 1)
    except Exception:
        h2 = False

    try:
        # Conclusion: I and J are comaximal in R iff I/K and J/K are comaximal in R/K.
        # In a PID, I=(i) and J=(j) are comaximal iff I + J = R iff gcd(i, j) == 1.
        comaximal_R = (sympy.gcd(i, j) == 1)
        
        # I/K and J/K are comaximal in R/K iff I + J + K = R iff gcd(i, j, k) == 1.
        comaximal_RK = (sympy.gcd(sympy.gcd(i, j), k) == 1)
        
        # The conclusion states they are equivalent. 
        # The negated conclusion (neg_Q) is True when they are NOT equivalent.
        neg_q = bool(comaximal_R != comaximal_RK)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

