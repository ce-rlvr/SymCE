def conditions(witness):
    h1 = False
    h2 = False
    neg_q = False
    
    try:
        # Fallback for when witness is just a matrix (implicitly R=M_n(Q), I={0})
        if isinstance(witness, sympy.MatrixBase) and witness.shape[0] == witness.shape[1]:
            x = witness
            h1 = True  
            h2 = True  
            is_unit = (x.det() != 0)
            is_ideal_R = not x.is_zero_matrix
            conclusion = (is_unit == is_ideal_R)
            neg_q = not conclusion
            return [h1, h2, neg_q]
            
        if isinstance(witness, tuple) and len(witness) == 3:
            R, I, x = witness
            
            n = None
            field = None
            if isinstance(R, MatrixRing):
                n = R.n
                field = R.field
            elif isinstance(R, str):
                if '2' in R: n = 2
                elif '3' in R: n = 3
                if 'Z' in R: field = 'Z'
                else: field = 'Q'
                
            if n is not None:
                is_zero_I = False
                is_whole_I = False
                
                if isinstance(I, ZeroIdeal) or (isinstance(I, int) and I == 0) or str(I) in ['0', '{0}']:
                    is_zero_I = True
                elif hasattr(I, 'is_zero_matrix') and I.is_zero_matrix:
                    is_zero_I = True
                elif I == R or str(I) == str(R):
                    is_whole_I = True
                    
                if is_zero_I or is_whole_I:
                    h1 = True
                    
                if isinstance(x, sympy.MatrixBase) and x.shape == (n, n):
                    h2 = True
                    
                if h1 and h2:
                    if is_zero_I:
                        if field == 'Z':
                            is_unit = (abs(x.det()) == 1)
                            g = 0
                            for val in x:
                                g = math.gcd(g, int(val))
                            is_ideal_R = (g == 1)
                        else:
                            is_unit = (x.det() != 0)
                            is_ideal_R = not x.is_zero_matrix
                    elif is_whole_I:
                        is_unit = True
                        is_ideal_R = True
                        
                    conclusion = (is_unit == is_ideal_R)
                    neg_q = not conclusion
                    return [h1, h2, neg_q]
                    
            elif R in ['Z', 'ZZ', sympy.ZZ]:
                try:
                    I_val = int(I)
                    h1 = True
                except Exception:
                    pass
                try:
                    x_val = int(x)
                    h2 = True
                except Exception:
                    pass
                if h1 and h2:
                    is_unit = (math.gcd(x_val, I_val) == 1)
                    is_ideal_R = (math.gcd(x_val, I_val) == 1)
                    conclusion = (is_unit == is_ideal_R)
                    neg_q = not conclusion
                    return [h1, h2, neg_q]
                    
    except Exception:
        pass
        
    return [h1, h2, neg_q]

