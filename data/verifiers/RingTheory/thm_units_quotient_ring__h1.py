import sympy
from sympy import Matrix, eye, zeros
import math

class MatrixRing:
    def __init__(self, n, field='Q'):
        self.n = n
        self.field = field
        
    def __str__(self):
        return f"M_{self.n}({self.field})"
        
    def __repr__(self):
        return self.__str__()
        
    def __eq__(self, other):
        return isinstance(other, MatrixRing) and self.n == other.n and self.field == other.field

class ZeroIdeal:
    def __str__(self):
        return "{0}"
        
    def __repr__(self):
        return self.__str__()
        
    def __eq__(self, other):
        return isinstance(other, ZeroIdeal)

