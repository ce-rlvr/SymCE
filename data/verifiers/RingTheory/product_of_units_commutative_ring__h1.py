import sympy

class ShiftOperator:
    """
    Element of the Toeplitz algebra (algebra generated by left and right shifts).
    L shifts left: L(x_0, x_1, ...) = (x_1, x_2, ...)
    R shifts right: R(x_0, x_1, ...) = (0, x_0, x_1, ...)
    L * R = I
    R * L != I
    """
    def __init__(self, coeffs):
        if isinstance(coeffs, dict):
            self.coeffs = {k: v for k, v in coeffs.items() if v != 0}
        else:
            self.coeffs = {}

    def __add__(self, other):
        if not isinstance(other, ShiftOperator):
            return NotImplemented
        res = dict(self.coeffs)
        for k, v in other.coeffs.items():
            res[k] = res.get(k, 0) + v
        return ShiftOperator(res)

    def __sub__(self, other):
        if not isinstance(other, ShiftOperator):
            return NotImplemented
        res = dict(self.coeffs)
        for k, v in other.coeffs.items():
            res[k] = res.get(k, 0) - v
        return ShiftOperator(res)

    def __mul__(self, other):
        if not isinstance(other, ShiftOperator):
            return NotImplemented
        res = {}
        for (i1, j1), v1 in self.coeffs.items():
            for (i2, j2), v2 in other.coeffs.items():
                m = min(j1, i2)
                k = (i1 + i2 - m, j1 + j2 - m)
                res[k] = res.get(k, 0) + v1 * v2
        return ShiftOperator(res)

    def __eq__(self, other):
        if not isinstance(other, ShiftOperator):
            return False
        return self.coeffs == other.coeffs

    def is_unit(self):
        if not self.coeffs:
            return False
        if len(self.coeffs) == 1:
            (i, j), v = list(self.coeffs.items())[0]
            if i == 0 and j == 0:
                return True
        return False

L = ShiftOperator({(0, 1): 1})
R = ShiftOperator({(1, 0): 1})
I = ShiftOperator({(0, 0): 1})

def conditions(witness) -> list[bool]:
    try:
        a, b = witness
    except Exception:
        return [False, False, False]
    
    try:
        ab = a * b
        h1 = hasattr(a, 'is_unit') and hasattr(b, 'is_unit')
    except Exception:
        h1 = False
        
    try:
        h2 = bool(ab.is_unit())
    except Exception:
        h2 = False
        
    try:
        a_unit = bool(a.is_unit())
        b_unit = bool(b.is_unit())
        neg_q = not (a_unit and b_unit)
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

