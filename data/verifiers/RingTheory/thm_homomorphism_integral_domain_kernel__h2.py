def conditions(witness) -> list[bool]:
    try:
        # Parse the witness into domain modulus n and codomain modulus m
        if isinstance(witness, NaturalProjection):
            n, m = witness.n, witness.m
        elif isinstance(witness, tuple):
            if len(witness) == 2:
                n, m = witness
            elif len(witness) == 3:
                R, S, f = witness
                n = R.n if hasattr(R, 'n') else int(R)
                m = S.n if hasattr(S, 'n') else int(S)
            else:
                return [False, False, False, False]
        else:
            return [False, False, False, False]
            
        n = int(n)
        m = int(m)
        
        # H_1: R and S are commutative rings with identity
        # Z/nZ and Z/mZ are always commutative rings with identity.
        h1 = True
        
        # H_2: f: R -> S is a ring homomorphism
        # For f(x mod n) = x mod m to be well-defined, m must divide n.
        if m == 0:
            h2 = (n == 0)
        else:
            h2 = (n % m == 0)
            
        # H_3: f(1_R) = 1_S
        # The natural projection maps 1 to 1.
        h3 = True
        
        # ¬Q: The kernel of f is not a prime ideal of R
        # The kernel is the ideal generated by m in Z/nZ.
        # It is a prime ideal if and only if m is a prime number or m == 0.
        is_prime_ideal = sympy.isprime(abs(m)) or m == 0
        neg_q = not is_prime_ideal
        
        return [h1, h2, h3, neg_q]
    except Exception:
        return [False, False, False, False]

