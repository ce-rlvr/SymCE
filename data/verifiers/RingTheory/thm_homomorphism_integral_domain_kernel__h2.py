import sympy

class NaturalProjection:
    """
    Represents the natural ring homomorphism f: Z/nZ -> Z/mZ, 
    defined by f(x mod n) = x mod m.
    n=0 represents the ring of integers Z.
    Example: NaturalProjection(0, 6) is the projection Z -> Z/6Z.
    """
    def __init__(self, n, m):
        self.n = n
        self.m = m

class Z_mod:
    """
    Represents the ring Z/nZ. n=0 represents Z.
    """
    def __init__(self, n):
        self.n = n

