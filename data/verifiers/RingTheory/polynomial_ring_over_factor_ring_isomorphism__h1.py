def conditions(witness) -> list[bool]:
    h1 = False
    h2 = False
    neg_q = False
    
    try:
        h1 = True
        h2 = True
        
        is_comm = True
        if hasattr(witness, 'is_commutative'):
            if witness.is_commutative is False:
                is_comm = False
        elif isinstance(witness, tuple) and len(witness) == 2:
            R, I = witness
            if hasattr(R, 'is_commutative'):
                if R.is_commutative is False:
                    is_comm = False
            elif isinstance(R, sympy.combinatorics.PermutationGroup) and not R.is_abelian:
                is_comm = False
        elif isinstance(witness, sympy.combinatorics.PermutationGroup) and not witness.is_abelian:
            is_comm = False
        elif hasattr(witness, 'is_Matrix') and witness.is_Matrix:
            is_comm = False
            
        neg_q = not is_comm
            
    except Exception:
        pass
        
    return [h1, h2, neg_q]

