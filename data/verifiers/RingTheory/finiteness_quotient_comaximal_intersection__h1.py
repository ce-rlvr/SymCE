import itertools

def conditions(witness):
    """
    Checks if the witness is a valid counterexample.
    The witness should be a tuple (n, add_table, mul_table, I, J) representing a finite ring R
    of size n, with elements 0 to n-1, and two subsets I and J representing the ideals.
    """
    try:
        n, add, mul, I, J = witness
        R = set(range(n))
        I = set(I)
        J = set(J)
    except Exception:
        return [False, False, False]
        
    # H1: I and J are comaximal ideals of R
    try:
        def is_ideal(S):
            if not S: return False
            # Additive closure
            for x in S:
                for y in S:
                    if add[x][y] not in S: return False
            # Find additive identity
            zeros = [e for e in range(n) if all(add[e][x] == x for x in range(n))]
            if not zeros: return False
            zero = zeros[0]
            if zero not in S: return False
            # Additive inverses
            for x in S:
                inv_x = [y for y in range(n) if add[x][y] == zero]
                if not inv_x or not any(y in S for y in inv_x): return False
            # Multiplicative absorption
            for s in S:
                for r in range(n):
                    if mul[r][s] not in S: return False
                    if mul[s][r] not in S: return False
            return True
            
        h1 = is_ideal(I) and is_ideal(J)
        
        # Comaximal: I + J = R
        I_plus_J = set(add[i][j] for i in I for j in J)
        if I_plus_J != R:
            h1 = False
    except Exception:
        h1 = False
        
    # H2: R/I and R/J are finite
    try:
        # Since R is a finite ring, its quotients are inherently finite.
        h2 = True
    except Exception:
        h2 = False
        
    # neg_Q: The quotient ring R/(I \cap J) is NOT finite, OR its cardinality is NOT |R/I| * |R/J|
    # Note: For finite rings, |R/(I \cap J)| == |R/I| * |R/J| is a mathematical tautology if I+J=R.
    # The true theorem likely stated R/IJ instead of R/(I \cap J). We check both to be robust 
    # against the dropped hypothesis (e.g. R having an identity) and the likely typo in the prompt.
    try:
        if len(I) == 0 or len(J) == 0:
            neg_q = False
        else:
            I_cap_J = I.intersection(J)
            size_R_I = n / len(I)
            size_R_J = n / len(J)
            
            if len(I_cap_J) == 0:
                neg_q = True
            else:
                size_R_I_cap_J = n / len(I_cap_J)
                
                # Compute IJ (ideal generated by products i*j)
                products = set(mul[i][j] for i in I for j in J)
                IJ = set(products)
                changed = True
                while changed:
                    changed = False
                    new_elements = set()
                    for x in IJ:
                        for y in IJ:
                            s = add[x][y]
                            if s not in IJ: new_elements.add(s)
                    for x in IJ:
                        for r in range(n):
                            p1 = mul[r][x]
                            p2 = mul[x][r]
                            if p1 not in IJ: new_elements.add(p1)
                            if p2 not in IJ: new_elements.add(p2)
                    if new_elements:
                        IJ.update(new_elements)
                        changed = True
                        
                size_R_IJ = n / len(IJ) if len(IJ) > 0 else float('inf')
                
                # The conclusion fails if the cardinality of R/(I \cap J) OR R/IJ is not the product
                neg_q = (size_R_I_cap_J != size_R_I * size_R_J) or (size_R_IJ != size_R_I * size_R_J)
    except Exception:
        neg_q = False
        
    return [bool(h1), bool(h2), bool(neg_q)]

