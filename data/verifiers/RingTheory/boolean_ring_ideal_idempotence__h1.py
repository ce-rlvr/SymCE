def multi_gcd(lst):
    lst = list(lst)
    if not lst:
        return 0
    return functools.reduce(math.gcd, lst)

def conditions(witness) -> list[bool]:
    try:
        # 1. Try SymPy ideal
        if hasattr(witness, 'ring') and hasattr(witness, 'gens'):
            I = witness
            h1 = True
            gens = I.gens
            I2_gens = [g1 * g2 for g1 in gens for g2 in gens]
            I2 = I.ring.ideal(*I2_gens)
            neg_q = bool(I != I2)
            return [h1, neg_q]
    except Exception:
        pass

    try:
        # 2. Try tuple (domain, generator/elements)
        if isinstance(witness, tuple) and len(witness) == 2:
            domain, I = witness
            
            # Domain is ZZ or represented by 0
            if domain == ZZ or domain == 0:
                if isinstance(I, int):
                    k = I
                elif isinstance(I, (list, tuple, set)) and len(I) == 1:
                    k = list(I)[0]
                else:
                    k = None
                
                if k is not None:
                    h1 = True
                    neg_q = abs(k) != abs(k**2)
                    return [h1, neg_q]
            
            # Domain is Z/nZ
            elif isinstance(domain, int) and domain > 0:
                n = domain
                if isinstance(I, int):
                    k = I
                    h1 = True
                    neg_q = math.gcd(k, n) != math.gcd(k**2, n)
                    return [h1, neg_q]
                elif isinstance(I, (list, tuple, set)):
                    if len(I) == 1:
                        k = list(I)[0]
                        h1 = True
                        neg_q = math.gcd(k, n) != math.gcd(k**2, n)
                        return [h1, neg_q]
                    else:
                        h1 = True
                        I2 = set((a * b) % n for a in I for b in I)
                        gen_I = math.gcd(multi_gcd(I), n)
                        gen_I2 = math.gcd(multi_gcd(I2), n)
                        neg_q = gen_I != gen_I2
                        return [h1, neg_q]
            
            # Domain is a SymPy ring
            elif hasattr(domain, 'ideal'):
                if isinstance(I, (list, tuple, set)):
                    ideal_I = domain.ideal(*I)
                else:
                    ideal_I = domain.ideal(I)
                h1 = True
                gens = ideal_I.gens
                I2_gens = [g1 * g2 for g1 in gens for g2 in gens]
                ideal_I2 = domain.ideal(*I2_gens)
                neg_q = bool(ideal_I != ideal_I2)
                return [h1, neg_q]
            
            # Domain is a list of elements (assume Z/nZ operations)
            elif isinstance(domain, (list, set, tuple)) and isinstance(I, (list, set, tuple)):
                R = domain
                n = len(R)
                if set(R) == set(range(n)):
                    h1 = True
                    I2 = set((a * b) % n for a in I for b in I)
                    gen_I = math.gcd(multi_gcd(I), n)
                    gen_I2 = math.gcd(multi_gcd(I2), n)
                    neg_q = gen_I != gen_I2
                    return [h1, neg_q]
    except Exception:
        pass

    try:
        # 3. Try integer (assume ZZ, ideal generated by witness)
        if isinstance(witness, int):
            k = witness
            h1 = True
            neg_q = abs(k) != abs(k**2)
            return [h1, neg_q]
    except Exception:
        pass

    return [False, False]

