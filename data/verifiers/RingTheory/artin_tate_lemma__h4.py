import sympy
import sympy.polys.polytools
from sympy.abc import x, y, z

# Top-level setup
# (No specific named objects needed for this algebraic counterexample,
# but we provide standard symbols for convenience)

def conditions(witness):
    try:
        vars = tuple(witness.vars)
    except Exception:
        return [False, False, False, False]

    def check_in_subalgebra(p, gens):
        p = sympy.expand(p)
        if not gens:
            return not any(p.has(v) for v in vars)
        Y = sympy.symbols(f'_Y_subalg_0:{len(gens)}')
        ideal_gens = [Y[i] - sympy.expand(gens[i]) for i in range(len(gens))]
        try:
            G = sympy.groebner(ideal_gens, *(vars + Y), order='lex')
            rem = sympy.polys.polytools.reduced(p, G, *(vars + Y), order='lex')[1]
            return not any(rem.has(v) for v in vars)
        except Exception:
            return False

    # H1: R <= S <= T
    try:
        h1 = True
        if not witness.R_elements or not witness.S_elements or not witness.T_elements:
            h1 = False
        for p in witness.R_elements:
            if not witness.S_contains(p):
                h1 = False
        for p in witness.S_elements:
            if not witness.T_contains(p):
                h1 = False
    except Exception:
        h1 = False

    # H2: R is a Noetherian ring
    try:
        h2 = True
        if not witness.R_contains(sympy.Integer(1)):
            h2 = False
        if len(vars) >= 2:
            if witness.R_contains(vars[0]) or witness.R_contains(vars[1]):
                h2 = False
        for p in witness.T_elements:
            is_const = not any(p.has(v) for v in vars)
            if is_const and not witness.R_contains(p):
                h2 = False
            if not is_const and witness.R_contains(p):
                h2 = False
    except Exception:
        h2 = False

    # H3: T is finitely generated as an algebra over R
    try:
        h3 = True
        if not witness.T_gens or len(witness.T_elements) < 2:
            h3 = False
        for g in witness.T_gens:
            if not witness.T_contains(g):
                h3 = False
        for p in witness.T_elements:
            if not check_in_subalgebra(p, witness.T_gens):
                h3 = False
                
        if len(vars) >= 2:
            v1, v2 = vars[0], vars[1]
            for poly in [sympy.Integer(1), v1, v2, v1*v2, v1**2, v2**2]:
                if not witness.T_contains(poly):
                    h3 = False
                    break
    except Exception:
        h3 = False

    # neg_Q: S is not finitely generated as an algebra over R
    try:
        neg_q = True
        if len(witness.S_elements) < 3:
            neg_q = False
        
        # Verify that the witness can produce an element in S not generated by any given prefix of S_elements
        for i in range(1, len(witness.S_elements) + 1):
            gens = witness.S_elements[:i]
            p = sympy.expand(witness.S_counter_element(gens))
            if not witness.S_contains(p):
                neg_q = False
                break
            if check_in_subalgebra(p, gens):
                neg_q = False
                break
                
        # Verify that S_contains matches the known counterexample behavior (e.g., S = k + x*k[x,y])
        if len(vars) >= 2:
            v1, v2 = vars[0], vars[1]
            test_cases = {
                sympy.Integer(1): True,
                v1: True,
                v2: False,
                v1*v2: True,
                v1**2: True,
                v2**2: False,
                v1 + v2: False,
                v1*v2 + v2**2: False,
                v1**2 * v2: True,
                v1 * v2**2: True
            }
            for poly, expected in test_cases.items():
                if bool(witness.S_contains(poly)) != expected:
                    neg_q = False
                    break
        else:
            neg_q = False
            
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

