def conditions(witness) -> list[bool]:
    """
    Expected witness format:
    A tuple or dict of three integers (n, i, m) representing:
    R = Z/nZ
    I = iZ/nZ
    m = mZ/nZ
    """
    try:
        if isinstance(witness, dict):
            n = abs(int(witness['n']))
            i = abs(int(witness['i']))
            m = abs(int(witness['m']))
        else:
            n, i, m = witness
            n = abs(int(n))
            i = abs(int(i))
            m = abs(int(m))
            
        if i == 0:
            return [False, False]
            
        # H1: I is a proper ideal of R
        # In R = Z/nZ, the ideal I = iZ/nZ is proper iff i > 1 and i divides n.
        h1 = (n > 1) and (n % i == 0) and (i > 1)
        
        # Q: R/I is a local ring with unique maximal ideal m/I
        # R/I is isomorphic to Z/iZ.
        # Z/iZ is a local ring iff i has exactly one prime factor.
        factors = factorint(i)
        if len(factors) == 1:
            p = list(factors.keys())[0]
            # The unique maximal ideal of Z/iZ is generated by p.
            # The ideal m/I in Z/iZ is generated by gcd(m, i).
            q = (math.gcd(m, i) == p)
        else:
            q = False
            
        neg_q = not q
        
        return [bool(h1), bool(neg_q)]
    except Exception:
        return [False, False]

