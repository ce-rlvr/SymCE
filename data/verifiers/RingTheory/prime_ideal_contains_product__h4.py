# Top-level setup: named object bindings that the witness expression may reference.
# We support the ring of integers Z, where ideals and subsets can be specified by their generators.
Z = "Z"

def get_val(witness, key):
    if isinstance(witness, dict):
        return witness.get(key)
    return getattr(witness, key, None)

def conditions(witness) -> list[bool]:
    try:
        ring = get_val(witness, 'ring')
        P = get_val(witness, 'P')
        I = get_val(witness, 'I')
        J = get_val(witness, 'J')
        
        # This verifier evaluates counterexamples in the ring of integers Z.
        if ring != "Z":
            return [False] * 4 + [False]
            
        def get_gens(X):
            if isinstance(X, (int, sympy.Integer, sympy.Rational, float)):
                return [sympy.Rational(X)]
            try:
                gens = []
                for i, x in enumerate(X):
                    if i > 100:  # Prevent infinite loops for infinite iterables
                        break
                    gens.append(sympy.Rational(x))
                return gens
            except TypeError:
                return [sympy.Rational(X)]

        P_gens = get_gens(P)
        I_gens = get_gens(I)
        J_gens = get_gens(J)
        
        # H_1: R is a commutative ring
        h1 = True  # Z is a commutative ring
        
        # H_2: P is a prime ideal of R
        # In Z, prime ideals are generated by prime numbers or 0.
        if not P_gens or not all(g.is_integer for g in P_gens):
            h2 = False
            P_gen = sympy.Integer(1)
        else:
            P_gen = sympy.gcd_list([sympy.Integer(p) for p in P_gens])
            h2 = sympy.isprime(P_gen) or P_gen == 0
            
        # H_3: I is an ideal of R
        # In Z, any set of integers generates an ideal.
        if not I_gens:
            h3 = True
        else:
            h3 = all(g.is_integer for g in I_gens)
            
        # Helper to check if a set of generators defines a subset of P
        def is_subset_of_P(gens, p_gen):
            if p_gen == 0:
                return all(g == 0 for g in gens)
            return all(sympy.Rational(g, p_gen).is_integer for g in gens)
            
        # H_4: The product ideal IJ is a subset of P
        # IJ is generated by the pairwise products of the generators of I and J.
        IJ_gens = [i * j for i in I_gens for j in J_gens]
        h4 = is_subset_of_P(IJ_gens, P_gen)
        
        # ¬Q: The conclusion must FAIL at the witness.
        # Conclusion: Either I is a subset of P, or J is a subset of P.
        # Negation: I is NOT a subset of P AND J is NOT a subset of P.
        I_sub_P = is_subset_of_P(I_gens, P_gen)
        J_sub_P = is_subset_of_P(J_gens, P_gen)
        neg_q = (not I_sub_P) and (not J_sub_P)
        
        return [h1, h2, h3, h4, neg_q]
    except Exception:
        return [False] * 5

