import sympy
import math

# Top-level setup for potential witness expressions
x, y, z = sympy.symbols('x y z', commutative=False)

def mod_k(expr, k):
    """
    Reduces the integer coefficients of a SymPy expression modulo k.
    If k == 0, it just expands the expression (representing the ring of integers).
    """
    if k == 0:
        return sympy.expand(expr)
    
    expr = sympy.expand(expr)
    
    def walk(e):
        if e.is_Number:
            return sympy.Integer(int(e) % k)
        elif e.is_Add:
            return sympy.Add(*[walk(arg) for arg in e.args])
        elif e.is_Mul:
            coeff = 1
            rest = []
            for a in e.args:
                if a.is_Number:
                    coeff = (coeff * int(a)) % k
                else:
                    rest.append(walk(a))
            if coeff == 0:
                return sympy.Integer(0)
            return sympy.Mul(sympy.Integer(coeff), *rest)
        elif e.is_Pow:
            base, exp = e.args
            return sympy.Pow(walk(base), exp)
        else:
            return e

    return sympy.expand(walk(expr))

def conditions(witness):
    """
    Checks the hypotheses and the negated conclusion for the conjecture.
    The witness is expected to be a dictionary with:
      - 'k': an integer >= 0 representing the ring Z/kZ (0 means Z)
      - 'X': a list/set of SymPy symbols
      - 'u': a SymPy expression representing the element u
      - 'v': (optional) a SymPy expression representing the inverse of u
    """
    # H_1: X is a set of variables
    try:
        X = witness.get('X', [])
        h1 = isinstance(X, (list, set, tuple)) and all(isinstance(sym, sympy.Symbol) for sym in X)
    except Exception:
        h1 = False

    # H_2: k<X> is the free associative algebra over k generated by X
    # We verify that k is a valid ring identifier (integer >= 0)
    try:
        k = witness.get('k')
        h2 = isinstance(k, int) and k >= 0
    except Exception:
        h2 = False

    # H_3: u \in k<X>
    try:
        u = witness.get('u')
        X_set = set(witness.get('X', []))
        if u is None:
            h3 = False
        else:
            u_expr = sympy.sympify(u)
            h3 = u_expr.free_symbols.issubset(X_set)
            # Ensure all numeric coefficients are integers (since the base ring is Z or Z/kZ)
            if h3:
                for a in u_expr.atoms(sympy.Number):
                    if not a.is_Integer:
                        h3 = False
                        break
    except Exception:
        h3 = False

    # ¬Q: u is a unit iff u is a non-zero scalar in k (fails)
    try:
        k = witness.get('k')
        X_set = set(witness.get('X', []))
        u = witness.get('u')
        v = witness.get('v')
        
        u_expr = sympy.sympify(u)
        v_expr = sympy.sympify(v) if v is not None else None
        
        u_mod = mod_k(u_expr, k)
        
        # Check if u is a non-zero scalar
        if u_mod == 0:
            is_nonzero_scalar = False
        else:
            is_nonzero_scalar = u_mod.free_symbols.isdisjoint(X_set)
            
        # Check if u is a unit
        if v_expr is not None:
            # Validate that the provided inverse v is actually in k<X>
            v_valid = v_expr.free_symbols.issubset(X_set)
            for a in v_expr.atoms(sympy.Number):
                if not a.is_Integer:
                    v_valid = False
                    break
            
            if v_valid:
                v_mod = mod_k(v_expr, k)
                prod1 = mod_k(u_mod * v_mod, k)
                prod2 = mod_k(v_mod * u_mod, k)
                is_unit = (prod1 == 1) and (prod2 == 1)
            else:
                v_expr = None  # Fallback to scalar check if invalid v is provided
                
        if v_expr is None:
            # If no valid inverse is provided, we can only definitively check scalar units
            if is_nonzero_scalar:
                val = int(u_mod)
                if k == 0:
                    is_unit = (val in [1, -1])
                else:
                    is_unit = (math.gcd(val, k) == 1)
            else:
                # Without a witness inverse for a non-scalar, we assume it's not a unit
                is_unit = False
                
        # The conclusion is an equivalence. The negated conclusion means the equivalence fails.
        neg_q = (is_unit != is_nonzero_scalar)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

