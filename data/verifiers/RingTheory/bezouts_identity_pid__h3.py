import sympy
from sympy import ZZ, QQ
from sympy.abc import x, y, z

N_HYP = 2
NEG_Q_INDEX = 2

CONDITION_LABELS = [
    "H_1: R is a principal ideal domain",
    "H_2: a and b are non-zero elements of R",
    "¬Q: There do not exist x, y in R such that d = ax + by"
]

def conditions(witness):
    """
    Given a witness tuple (R, a, b, d), checks if it is a valid counterexample.
    R must be a SymPy domain (e.g., ZZ, QQ[x]).
    """
    try:
        if len(witness) != 4:
            return [False, False, False]
        R, a, b, d = witness
    except Exception:
        return [False, False, False]

    # H_1: R is a principal ideal domain
    try:
        h1 = bool(getattr(R, 'is_PID', False))
    except Exception:
        h1 = False

    # H_2: a and b are non-zero elements of R
    try:
        zero = getattr(R, 'zero', 0)
        h2 = bool(a in R and b in R and a != zero and b != zero)
    except Exception:
        h2 = False

    # ¬Q: There do not exist x, y in R such that d = ax + by
    # In a PID, the ideal (a, b) is generated by gcd(a, b).
    # Thus, d = ax + by has a solution in R iff gcd(a, b) divides d in R.
    try:
        if d not in R:
            neg_q = True
        else:
            g = R.gcd(a, b)
            zero = getattr(R, 'zero', 0)
            try:
                # Check if d is a multiple of g using remainder
                rem = R.rem(d, g)
                neg_q = bool(rem != zero)
            except Exception:
                # Fallback if rem is not available: try exact quotient
                try:
                    q = R.exquo(d, g)
                    neg_q = False  # Exact quotient exists, so d is a multiple
                except Exception:
                    neg_q = True   # Exact quotient failed, so d is not a multiple
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]