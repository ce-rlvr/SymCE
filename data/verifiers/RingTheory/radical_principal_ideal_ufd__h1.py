import sympy
from sympy import Mul, Pow

def conditions(witness) -> list[bool]:
    """
    Checks whether the witness is a valid counterexample to the false conjecture.
    
    The witness is expected to be a tuple: (R, a, p_list, k_list)
    where R is a ring object (or a wrapper) that provides the necessary algebraic operations,
    a is the element, p_list is the list of primes, and k_list is the list of exponents.
    
    If R is not provided, it falls back to assuming the witness is (a, p_list, k_list)
    and attempts to use standard sympy operations.
    """
    try:
        if len(witness) == 4:
            R, a, p_list, k_list = witness
        else:
            a, p_list, k_list = witness
            R = None
    except Exception:
        return [False, False, False]

    # H1: a is a non-zero non-unit element of R
    try:
        if R is not None:
            h1_ok = not R.is_zero(a) and not R.is_unit(a)
        else:
            # Fallback for standard sympy expressions/integers
            h1_ok = (a != 0) and (abs(a) != 1)
    except Exception:
        h1_ok = False

    # H2: a = p_1^{k_1} ... p_n^{k_n} where p_i are pairwise non-associate primes and k_i > 0
    try:
        h2_ok = True
        
        # Check k_i are positive integers
        if not all(isinstance(k, int) and k > 0 for k in k_list):
            h2_ok = False
            
        # Check product equals a
        if h2_ok:
            if R is not None:
                prod = R.one() if hasattr(R, 'one') else 1
                for p, k in zip(p_list, k_list):
                    prod = R.mul(prod, R.pow(p, k))
                if not R.eq(a, prod):
                    h2_ok = False
            else:
                prod = Mul(*[Pow(p, k) for p, k in zip(p_list, k_list)])
                if sympy.simplify(a - prod) != 0:
                    h2_ok = False

        # Check p_i are primes
        if h2_ok:
            if R is not None:
                if not all(R.is_prime(p) for p in p_list):
                    h2_ok = False
            else:
                if not all(sympy.isprime(p) for p in p_list):
                    h2_ok = False

        # Check pairwise non-associate
        if h2_ok:
            n_p = len(p_list)
            for i in range(n_p):
                for j in range(i + 1, n_p):
                    if R is not None:
                        if R.are_associate(p_list[i], p_list[j]):
                            h2_ok = False
                    else:
                        if p_list[i] == p_list[j] or p_list[i] == -p_list[j]:
                            h2_ok = False
    except Exception:
        h2_ok = False

    # NegQ: The radical of the principal ideal (a) is NOT the principal ideal generated by p_1 ... p_n
    try:
        if R is not None:
            prod_p = R.one() if hasattr(R, 'one') else 1
            for p in p_list:
                prod_p = R.mul(prod_p, p)
            # Check if rad(a) != (p_1 ... p_n)
            neg_q_ok = not R.ideal_eq(R.rad_ideal(a), R.ideal(prod_p))
        else:
            # Fallback for Z: rad(a) is always generated by the product of distinct primes
            prod_p = Mul(*p_list)
            # In Z, the radical of (a) is generated by the square-free part of a.
            # Since the conjecture is true in Z, neg_q_ok will be False.
            # We compute the square-free part to compare.
            sq_free = 1
            for p in sympy.factorint(a).keys():
                sq_free *= p
            neg_q_ok = abs(sq_free) != abs(prod_p)
    except Exception:
        neg_q_ok = False

    return [bool(h1_ok), bool(h2_ok), bool(neg_q_ok)]

