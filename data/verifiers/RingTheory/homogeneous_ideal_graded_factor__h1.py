def conditions(witness):
    try:
        if isinstance(witness, dict):
            n = witness.get('n', 0)
            I_gens = witness.get('I_gens', [])
            vars = witness.get('vars', [])
            is_comm = witness.get('R_is_commutative', True)
        else:
            R = witness[0]
            n = witness[1]
            if len(witness) == 4:
                vars = witness[2]
                I_gens = witness[3]
            else:
                I_gens = witness[2]
                vars = []
                
            if hasattr(R, 'is_commutative') and R.is_commutative is not None:
                is_comm = R.is_commutative
            elif type(R).__name__ in ['Matrix', 'MutableDenseMatrix', 'ImmutableDenseMatrix', 'MatrixSymbol']:
                is_comm = False
            elif isinstance(R, str) and any(kw in R.lower() for kw in ['matrix', 'non-commutative', 'noncommutative', 'm_']):
                is_comm = False
            else:
                is_comm = True
                
        if not vars:
            v_set = set()
            for gen in I_gens:
                if hasattr(gen, 'free_symbols'):
                    v_set.update([s for s in gen.free_symbols if getattr(s, 'is_commutative', True)])
            vars = list(v_set)
            
    except Exception:
        return [False, False, False, False]

    try:
        h1 = isinstance(n, int) and n > 0
    except Exception:
        h1 = False

    try:
        h2 = isinstance(I_gens, (list, tuple, set)) and len(vars) <= n
        if h2:
            for gen in I_gens:
                if hasattr(gen, 'as_expr'):
                    expr = gen.as_expr()
                else:
                    expr = gen
                if vars and hasattr(expr, 'is_polynomial') and not expr.is_polynomial(*vars):
                    h2 = False
                    break
    except Exception:
        h2 = False

    try:
        h3 = True
        for gen in I_gens:
            if hasattr(gen, 'as_expr'):
                expr = gen.as_expr()
            else:
                expr = gen
                
            if hasattr(expr, 'expand'):
                expr = expr.expand()
                
            if expr == 0:
                continue
                
            if hasattr(expr, 'is_Add') and expr.is_Add:
                terms = expr.args
            else:
                terms = [expr]
            
            degrees = set()
            for term in terms:
                deg = 0
                if hasattr(term, 'is_Mul') and term.is_Mul:
                    factors = term.args
                else:
                    factors = [term]
                for factor in factors:
                    if factor in vars:
                        deg += 1
                    elif hasattr(factor, 'is_Pow') and factor.is_Pow and factor.base in vars:
                        if hasattr(factor.exp, 'is_Integer') and factor.exp.is_Integer:
                            deg += int(factor.exp)
                        elif isinstance(factor.exp, int):
                            deg += factor.exp
                degrees.add(deg)
            if len(degrees) > 1:
                h3 = False
                break
    except Exception:
        h3 = False

    try:
        neg_Q = not is_comm
    except Exception:
        neg_Q = False

    return [h1, h2, h3, neg_Q]

