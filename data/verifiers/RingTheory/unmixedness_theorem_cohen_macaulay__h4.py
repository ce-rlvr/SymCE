import sympy
from sympy import groebner, Dummy, reduced, expand, cancel, fraction
from sympy.abc import x, y, z

# Top-level setup for the verifier
# The witness is expected to be a tuple: (vars, I_gens, n, P_gens, c)
# where:
#   vars: tuple of SymPy symbols representing the variables of the polynomial ring R = QQ[vars]
#   I_gens: tuple of polynomials generating the ideal I
#   n: integer, the number of generators of I
#   P_gens: tuple of variables (subset of vars) generating an associated prime ideal P
#   c: a polynomial such that P = (I : c)

def ideal_quotient(I_gens, c, vars):
    """Computes the generators of the ideal quotient (I : c) in QQ[vars]."""
    t_dummy = Dummy('t')
    # J = t*I + (1-t)*(c)
    J_gens = [expand(t_dummy * g) for g in I_gens] + [expand((1 - t_dummy) * c)]
    # Eliminate t_dummy using lexicographic order
    G = groebner(J_gens, t_dummy, *vars, order='lex')
    intersect_gens = [g for g in G if t_dummy not in g.free_symbols]
    
    quotient_gens = []
    for g in intersect_gens:
        q = cancel(g / c)
        num, den = fraction(q)
        # If the denominator is a constant (free of variables), it's a valid polynomial generator
        if not any(v in den.free_symbols for v in vars):
            quotient_gens.append(num)
    return quotient_gens

def ideals_equal(A_gens, B_gens, vars):
    """Checks if two ideals generated by A_gens and B_gens are equal."""
    A_gens = [a for a in A_gens if a != 0]
    B_gens = [b for b in B_gens if b != 0]
    
    if not A_gens and not B_gens:
        return True
    if not A_gens or not B_gens:
        return False
        
    GA = groebner(A_gens, *vars)
    GB = groebner(B_gens, *vars)
    
    for a in A_gens:
        if reduced(a, GB, *vars)[1] != 0:
            return False
    for b in B_gens:
        if reduced(b, GA, *vars)[1] != 0:
            return False
    return True

def conditions(witness):
    try:
        vars_tuple, I_gens, n, P_gens, c = witness
    except Exception:
        return [False, False, False, False]
        
    # H_1: R is a Cohen-Macaulay commutative Noetherian ring
    # A polynomial ring over a field is always a Cohen-Macaulay commutative Noetherian ring.
    try:
        h1 = (isinstance(vars_tuple, (list, tuple)) and 
              len(vars_tuple) > 0 and 
              all(isinstance(v, sympy.Symbol) for v in vars_tuple))
    except Exception:
        h1 = False
        
    # H_2: I is a proper ideal of R
    try:
        I_gens_clean = [g for g in I_gens if g != 0]
        if not I_gens_clean:
            h2 = True
        else:
            G_I = groebner(I_gens_clean, *vars_tuple)
            h2 = True
            for g in G_I:
                # If the Groebner basis contains a non-zero constant, the ideal is the whole ring (not proper)
                if not g.free_symbols and g != 0:
                    h2 = False
                    break
    except Exception:
        h2 = False
        
    # H_3: I is generated by exactly n elements
    try:
        h3 = (len(I_gens) == n)
    except Exception:
        h3 = False
        
    # ¬Q: There exists an associated prime ideal of R/I with height != n
    try:
        # To easily verify P is prime and determine its height, we require P_gens to be a subset of vars
        if not all(p in vars_tuple for p in P_gens):
            neg_q = False
        elif len(set(P_gens)) != len(P_gens):
            neg_q = False
        else:
            height_P = len(P_gens)
            if height_P == n:
                neg_q = False
            else:
                # Verify that P is indeed an associated prime of I, i.e., P = (I : c)
                quotient_gens = ideal_quotient(I_gens, c, vars_tuple)
                neg_q = ideals_equal(P_gens, quotient_gens, vars_tuple)
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

