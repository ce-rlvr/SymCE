import sympy
from sympy import QQ, ZZ, RR, CC
from sympy.abc import x, y

# Top-level setup for potential witness expressions
# We define standard domains and symbols that might be used to construct a ring.

CONDITION_LABELS = [
    "H_1: R is an integral domain",
    "¬Q: G is not a cyclic group"
]

N_HYP = 1
NEG_Q_INDEX = 1

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "If R is an integral domain, then its multiplicative group G is cyclic."
    
    The witness can be a ring R (implying G is the full multiplicative group of R),
    or a tuple (R, G) where G is a list of generators for a subgroup.
    """
    if isinstance(witness, tuple):
        if len(witness) == 2:
            R, G = witness
        else:
            R = witness[0]
            G = None
    else:
        R = witness
        G = None

    # H_1: R is an integral domain
    try:
        if R in (QQ, ZZ, RR, CC):
            h1 = True
        elif getattr(R, 'is_Field', False):
            h1 = True
        elif getattr(R, 'is_PID', False):
            h1 = True
        elif getattr(R, 'is_domain', False):
            h1 = True
        else:
            h1 = False
    except Exception:
        h1 = False

    # ¬Q: G is not a cyclic group
    try:
        if G is None:
            # If G is not explicitly provided, we assume G is the full unit group of R.
            if R in (QQ, RR, CC):
                neg_q = True
            elif R == ZZ:
                # Units of ZZ are {1, -1}, which is cyclic.
                neg_q = False
            elif getattr(R, 'is_FiniteField', False):
                # The multiplicative group of any finite field is cyclic.
                neg_q = False
            elif hasattr(R, 'domain'):
                # For polynomial rings, the units are the units of the base ring.
                base = R.domain
                if base in (QQ, RR, CC):
                    neg_q = True
                elif base == ZZ:
                    neg_q = False
                else:
                    neg_q = True
            else:
                # Infinite fields generally have non-cyclic multiplicative groups.
                if getattr(R, 'is_Field', False) and not getattr(R, 'is_FiniteField', False):
                    neg_q = True
                else:
                    neg_q = False
        else:
            # If G is provided as a list of generators
            if isinstance(G, list):
                roots_of_unity = {1, -1}
                if all(g in roots_of_unity for g in G):
                    # Subgroup generated by roots of unity in a domain is finite, hence cyclic.
                    neg_q = False
                else:
                    # If there are multiple generators and they are not just roots of unity,
                    # they typically generate a non-cyclic free abelian group (e.g., <2, 3> in QQ).
                    neg_q = len(G) > 1
            else:
                neg_q = False
    except Exception:
        neg_q = False

    return [h1, neg_q]