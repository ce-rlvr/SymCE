CONDITION_LABELS = [
    "H_1: R is not a field",
    "¬Q: The intersection of all non-zero ideals of R is not the zero ideal"
]

N_HYP = 1
NEG_Q_INDEX = 1

def conditions(witness):
    try:
        # If the witness is an integer n, we interpret it as the ring Z/nZ
        if isinstance(witness, (int, sympy.Integer)):
            n = int(witness)
            if n < 2:
                return [False, False]
            
            # H_1: Z/nZ is not a field iff n is not prime
            h1 = not sympy.isprime(n)
            
            # ¬Q: The intersection of all non-zero ideals is not the zero ideal.
            # In Z/nZ, non-zero ideals correspond to proper divisors of n.
            # The intersection of these ideals corresponds to the ideal generated by their LCM.
            # If the LCM is less than n, the intersection is not the zero ideal.
            proper_divisors = [int(d) for d in sympy.divisors(n) if d < n]
            if not proper_divisors:
                lcm_val = 1
            else:
                lcm_val = functools.reduce(lambda a, b: a * b // math.gcd(a, b), proper_divisors)
            
            neg_q = (lcm_val < n)
            return [h1, neg_q]
            
        # If the witness is a sympy domain (like ZZ, QQ, etc.)
        elif hasattr(witness, 'is_Field'):
            h1 = not witness.is_Field
            
            # For standard infinite domains in sympy (like ZZ, QQ[x]), the intersection 
            # of all non-zero ideals is the zero ideal.
            # If it is a field, the only non-zero ideal is the ring itself, so the intersection is not zero.
            if witness.is_Field:
                neg_q = True
            else:
                neg_q = False
                
            return [bool(h1), bool(neg_q)]
            
        else:
            return [False, False]
            
    except Exception:
        return [False, False]