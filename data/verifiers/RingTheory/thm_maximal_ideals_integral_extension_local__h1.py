import sympy
from sympy import Poly, Symbol, isprime, GF

x = Symbol('x')

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness should be a dictionary specifying:
      - 'S_poly': a monic polynomial in x (defines S = Z[x]/(S_poly), an integral extension of Z)
      - 'n_p': a prime integer (part of the generator for the maximal ideal n in S)
      - 'n_g': a polynomial in x (the other part of the generator for n)
      - 'm_gen': an integer (generator for the ideal m in Z)
    """
    # H1: S is a commutative ring that is an integral extension of R
    # We use R = Z. S = Z[x]/(S_poly) is an integral extension iff S_poly is monic.
    try:
        S_poly = Poly(witness['S_poly'], x)
        h1 = S_poly.is_monic
    except Exception:
        h1 = False

    # H2: n is a maximal ideal of S
    # n is generated by (n_p, n_g) in Z[x]/(S_poly)
    try:
        n_p = int(witness['n_p'])
        n_g = Poly(witness['n_g'], x)
        
        if not isprime(n_p):
            h2 = False
        else:
            # n_g must be irreducible mod n_p
            n_g_mod = Poly(n_g.as_expr(), x, domain=GF(n_p))
            if not n_g_mod.is_irreducible:
                h2 = False
            else:
                # S_poly must be in the ideal (n_p, n_g) in Z[x]
                # i.e., S_poly mod n_p is divisible by n_g mod n_p
                S_poly_mod = Poly(S_poly.as_expr(), x, domain=GF(n_p))
                rem = S_poly_mod % n_g_mod
                h2 = rem.is_zero
    except Exception:
        h2 = False

    # Negated Conclusion: The contraction of the ideal n to R is NOT exactly m
    try:
        m_gen = int(witness['m_gen'])
        n_p = int(witness['n_p'])
        # The contraction of n = (n_p, n_g) to Z is exactly the ideal (n_p).
        # The ideal m is (m_gen).
        # They are equal iff abs(n_p) == abs(m_gen).
        # The conclusion fails if they are not equal.
        neg_q = (abs(n_p) != abs(m_gen))
    except Exception:
        neg_q = False

    return [bool(h1), bool(h2), bool(neg_q)]

