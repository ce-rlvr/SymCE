import sympy
from sympy import ZZ, QQ
from sympy.abc import x, y, z

# Top-level setup
# We provide standard integral domains from SymPy for the witness to use.
# The witness is expected to be a tuple: (R, I, J)
# where R is a domain (e.g., ZZ), and I, J are lists of generators for the ideals.

def conditions(witness):
    try:
        R, I, J = witness
    except Exception:
        return [False, False, False]

    # H_1: R is an integral domain
    try:
        from sympy.polys.domains import Domain
        from sympy import S, ZZ as sympy_ZZ
        if isinstance(R, Domain):
            h1_ok = True
        elif R == S.Integers:
            h1_ok = True
            R = sympy_ZZ  # normalize to Domain for later use
        elif hasattr(R, 'is_integral_domain') and R.is_integral_domain:
            h1_ok = True
        else:
            h1_ok = False
    except Exception:
        h1_ok = False

    # H_2: I is a non-zero ideal of R
    try:
        h2_ok = False
        if isinstance(I, (list, tuple, set)):
            for gen in I:
                zero_elem = R.zero if hasattr(R, 'zero') else 0
                if gen != zero_elem and gen != 0:
                    h2_ok = True
                    break
    except Exception:
        h2_ok = False

    # ¬Q: The product ideal IJ is zero
    # The product ideal is generated by {a * b | a in I, b in J}.
    # It is zero if and only if all such products are zero.
    try:
        neg_q_ok = True
        if not isinstance(J, (list, tuple, set)):
            neg_q_ok = False
        else:
            for a in I:
                for b in J:
                    try:
                        if hasattr(R, 'mul'):
                            prod = R.mul(a, b)
                        else:
                            prod = a * b
                    except Exception:
                        prod = a * b
                    
                    zero_elem = R.zero if hasattr(R, 'zero') else 0
                    if prod != zero_elem and prod != 0:
                        neg_q_ok = False
                        break
                if not neg_q_ok:
                    break
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, neg_q_ok]

