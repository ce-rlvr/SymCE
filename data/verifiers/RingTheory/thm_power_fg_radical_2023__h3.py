class InfinitePolynomialRing:
    """
    Represents the polynomial ring k[x_1, x_2, ...] with infinitely many variables.
    """
    @property
    def is_commutative(self):
        return True

class MonomialIdeal:
    """
    Represents an ideal generated by { x_i^{gen_degrees(i)} | i >= 1 }.
    """
    def __init__(self, gen_degrees):
        self.gen_degrees = gen_degrees

    def contains(self, monomial):
        """
        monomial: dict {var_index: power}
        """
        for i, p in monomial.items():
            if callable(self.gen_degrees):
                deg = self.gen_degrees(i)
            else:
                deg = self.gen_degrees.get(i, float('inf'))
            if p >= deg:
                return True
        return False

    def in_radical_power(self, monomial, n):
        """
        Checks if the monomial is in (\sqrt{I})^n.
        """
        return sum(monomial.values()) >= n

def conditions(witness):
    """
    Checks if the witness is a valid counterexample.
    The witness is expected to be a tuple: (ring, ideal, get_ce)
    where get_ce(n) returns a monomial (as a dict) that is in (\sqrt{I})^n but not in I.
    """
    try:
        if not isinstance(witness, (tuple, list)) or len(witness) != 3:
            return [False, False, False]
        ring, ideal, get_ce = witness
    except Exception:
        return [False, False, False]

    # H_1: R is a commutative ring
    try:
        h1 = bool(ring.is_commutative)
    except Exception:
        h1 = False

    # H_2: I is an ideal in R
    try:
        h2 = hasattr(ideal, 'contains') and hasattr(ideal, 'in_radical_power')
    except Exception:
        h2 = False

    # ¬Q: For all n >= 1, (\sqrt{I})^n is not contained in I
    try:
        neg_q = True
        for n in [1, 2, 3, 5, 10, 20, 50, 100, 500, 1000]:
            ce = get_ce(n)
            if not isinstance(ce, dict):
                neg_q = False
                break
            if not ideal.in_radical_power(ce, n):
                neg_q = False
                break
            if ideal.contains(ce):
                neg_q = False
                break
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

