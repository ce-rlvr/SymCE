def conditions(witness):
    try:
        if len(witness) == 3:
            R, c, S_set = witness
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    h1 = False
    try:
        if isinstance(R, MatrixSet):
            if hasattr(c, 'shape') and c.shape == R.shape:
                base_set = R.set
                if hasattr(base_set, 'contains'):
                    h1 = all(base_set.contains(elem) for elem in c)
                else:
                    h1 = all(elem in base_set for elem in c)
        elif hasattr(R, 'contains'):
            h1 = R.contains(c)
        elif hasattr(R, '__contains__'):
            h1 = c in R
    except Exception:
        pass

    h2 = False
    try:
        if isinstance(S_set, (list, tuple, set)):
            has_c = any(c == x for x in S_set)
            has_c2 = any((c**2) == x for x in S_set)
            h2 = has_c and has_c2
        elif hasattr(S_set, '__next__'):
            first_few = list(itertools.islice(S_set, 10))
            has_c = any(c == x for x in first_few)
            has_c2 = any((c**2) == x for x in first_few)
            h2 = has_c and has_c2
        elif callable(S_set) and not isinstance(S_set, Lambda):
            h2 = (S_set(1) == c) and (S_set(2) == c**2)
        elif isinstance(S_set, Lambda):
            h2 = (S_set(1) == c) and (S_set(2) == c**2)
        elif hasattr(S_set, 'contains'):
            h2 = S_set.contains(c) and S_set.contains(c**2)
    except Exception:
        pass

    neg_q = False
    try:
        if isinstance(R, MatrixSet):
            n = R.shape[0]
            m = R.shape[1]
            base_set = R.set
            if n != m:
                neg_q = True
            else:
                has_1 = False
                has_0 = False
                if hasattr(base_set, 'contains'):
                    has_1 = base_set.contains(1)
                    has_0 = base_set.contains(0)
                elif hasattr(base_set, '__contains__'):
                    has_1 = 1 in base_set
                    has_0 = 0 in base_set
                
                if not has_1 or not has_0:
                    neg_q = True
                elif n >= 2:
                    is_central = False
                    if c.is_diagonal():
                        diag = [c[i,i] for i in range(n)]
                        if all(d == diag[0] for d in diag):
                            is_central = True
                    if not is_central:
                        neg_q = True
        else:
            lacks_identity = False
            if hasattr(R, 'contains'):
                if not R.contains(1):
                    lacks_identity = True
            elif hasattr(R, '__contains__'):
                if 1 not in R:
                    lacks_identity = True
            
            if lacks_identity:
                neg_q = True
            elif hasattr(R, 'is_commutative') and R.is_commutative is False:
                neg_q = True
    except Exception:
        pass

    return [bool(h1), bool(h2), bool(neg_q)]

