import sympy
from sympy import Rational, Integer
from sympy.abc import x, y, z

# Top-level setup
# The witness is expected to represent ideals in the commutative ring R = ZZ.
# It can be provided as a tuple (p, q, s) or (R, p, q, s), or a dictionary, where:
# - p is the generator of the prime ideal P = pZZ
# - q is the generator of the P-primary ideal Q = qZZ
# - s is the generator (or a list of generators) of the multiplicatively closed subset S

def conditions(witness) -> list[bool]:
    try:
        # Extract p, q, s from the witness
        if isinstance(witness, dict):
            p = witness.get('p', witness.get('P'))
            q = witness.get('q', witness.get('Q'))
            s = witness.get('s', witness.get('S'))
            if p is None or q is None or s is None:
                return [False] * 5
        elif isinstance(witness, (list, tuple)):
            if len(witness) == 3:
                p, q, s = witness
            elif len(witness) == 4:
                _, p, q, s = witness
            else:
                return [False] * 5
        else:
            return [False] * 5
            
        # Normalize sympy.Integer to int for easier type checking and arithmetic
        if isinstance(p, sympy.Integer): p = int(p)
        if isinstance(q, sympy.Integer): q = int(q)
        
        if isinstance(s, (list, tuple, set)):
            s = [int(val) if isinstance(val, sympy.Integer) else val for val in s]
        elif isinstance(s, sympy.Integer):
            s = int(s)
            
    except Exception:
        return [False] * 5

    # H_1: R is a commutative ring
    # We are working in ZZ, which is a commutative ring. We just verify the types of generators.
    try:
        if isinstance(s, (list, tuple, set)):
            s_ok = all(isinstance(val, int) for val in s)
        else:
            s_ok = isinstance(s, int)
        h1 = isinstance(p, int) and isinstance(q, int) and s_ok
    except Exception:
        h1 = False

    # H_2: P is a prime ideal of R
    # In ZZ, an ideal pZZ is prime iff p is a prime number or p == 0.
    try:
        h2 = sympy.isprime(p) or p == 0
    except Exception:
        h2 = False

    # H_3: Q is a P-primary ideal of R
    # In ZZ, qZZ is pZZ-primary iff q = p^k for some k >= 1 (if p > 0), or q = 0 (if p = 0).
    try:
        if p == 0:
            h3 = (q == 0)
        else:
            h3 = False
            if q > 1:
                temp = q
                while temp % p == 0:
                    temp //= p
                if temp == 1:
                    h3 = True
    except Exception:
        h3 = False

    # H_4: S is a multiplicatively closed subset of R
    # Any set generated by powers of s (or products of elements in s) is multiplicatively closed.
    try:
        h4 = True
    except Exception:
        h4 = False

    # ¬Q: S^{-1}Q is not an S^{-1}P-primary ideal in S^{-1}R
    # S^{-1}Q is primary iff S \cap P = empty.
    # If S \cap P != empty, S^{-1}Q becomes the whole ring, which is not a proper ideal, hence not primary.
    # S \cap P != empty iff p divides at least one generator in s (or 0 is in S).
    try:
        if p == 0:
            if isinstance(s, (list, tuple, set)):
                neg_q = (0 in s)
            else:
                neg_q = (s == 0)
        else:
            if isinstance(s, (list, tuple, set)):
                neg_q = any(val % p == 0 for val in s)
            else:
                neg_q = (s % p == 0)
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]

