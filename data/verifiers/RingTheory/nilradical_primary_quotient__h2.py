# Top-level setup: named object bindings
ZZ = S.Integers
QQ = S.Rationals

def rad(n):
    """Compute the radical of an integer (product of its distinct prime factors)."""
    if n == 0:
        return 0
    n = abs(int(n))
    if n == 1:
        return 1
    res = 1
    for prime in factorint(n).keys():
        res *= prime
    return res

def conditions(witness) -> list[bool]:
    h1 = False
    q = None
    p = None
    
    # Parse the witness. We expect ideals Q and P in the ring R = Z, 
    # represented by their integer generators q and p.
    try:
        if isinstance(witness, (tuple, list)):
            if len(witness) == 2:
                q, p = witness
                h1 = True
            elif len(witness) >= 3:
                R, q, p = witness[:3]
                h1 = True
        elif isinstance(witness, dict):
            q = witness.get('Q', witness.get('q'))
            p = witness.get('P', witness.get('p'))
            if q is not None and p is not None:
                h1 = True
                
        if not h1:
            return [False, False]
            
        # Ensure they can be interpreted as integers
        q = int(q)
        p = int(p)
    except Exception:
        return [False, False]
        
    # Evaluate the negated conclusion
    try:
        # In R = Z, the nilradical of Z/qZ is generated by rad(q).
        # The ideal P/Q corresponds to the ideal (P + Q)/Q, generated by gcd(p, q).
        # The nilradical of R/Q is equal to P/Q iff rad(q) == gcd(p, q).
        r = rad(q)
        g = math.gcd(p, q)
        
        # neg_Q is True when the conclusion FAILS (they are not equal)
        neg_q = (r != g)
    except Exception:
        neg_q = False
        
    return [h1, neg_q]

