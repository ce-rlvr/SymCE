import sympy
from sympy import symbols, Poly

# Top-level setup: symbols that the witness expression may reference
x, y, z, w, u, v = symbols('x y z w u v')

def get_monom(p, syms):
    """Extract the exponent tuple from a monomial expression."""
    try:
        if p == 0:
            return "ZERO"
        poly = Poly(p, *syms)
        terms = poly.terms()
        if len(terms) != 1:
            return None
        return terms[0][0]
    except Exception:
        return None

def minimize(I_gens, num_vars):
    """Remove redundant generators (multiples of other generators)."""
    I_gens = list(set(I_gens))
    res = []
    for g in I_gens:
        is_divisible = False
        for r in I_gens:
            if r != g and all(r[j] <= g[j] for j in range(num_vars)):
                is_divisible = True
                break
        if not is_divisible:
            res.append(g)
    return res

def decompose(I_gens, num_vars):
    """Recursively find an irreducible decomposition of a monomial ideal."""
    I_gens = minimize(I_gens, num_vars)
    if not I_gens:
        return [tuple(0 for _ in range(num_vars))]
    if tuple(0 for _ in range(num_vars)) in I_gens:
        return []
        
    for i, gen in enumerate(I_gens):
        vars_in_gen = [j for j, exp in enumerate(gen) if exp > 0]
        if len(vars_in_gen) > 1:
            v = vars_in_gen[0]
            exp = gen[v]
            
            gen1 = tuple(exp if j == v else 0 for j in range(num_vars))
            I1 = I_gens[:i] + I_gens[i+1:] + [gen1]
            
            gen2 = tuple(gen[j] if j != v else 0 for j in range(num_vars))
            I2 = I_gens[:i] + I_gens[i+1:] + [gen2]
            
            return decompose(I1, num_vars) + decompose(I2, num_vars)
            
    q = [0] * num_vars
    for gen in I_gens:
        for j in range(num_vars):
            if gen[j] > 0:
                if q[j] == 0 or gen[j] < q[j]:
                    q[j] = gen[j]
    return [tuple(q)]

def is_contained(QA, QB, num_vars):
    """Check if irreducible ideal QA is a subset of irreducible ideal QB."""
    for j in range(num_vars):
        if QA[j] > 0:
            if QB[j] == 0 or QB[j] > QA[j]:
                return False
    return True

def irredundant_components(components, num_vars):
    """Filter out redundant irreducible components from the intersection."""
    res = []
    for i, qi in enumerate(components):
        is_redundant = False
        for j, qj in enumerate(components):
            if i != j and is_contained(qj, qi, num_vars):
                if j < i or not is_contained(qi, qj, num_vars):
                    is_redundant = True
                    break
        if not is_redundant:
            res.append(qi)
    return res

def conditions(witness) -> list[bool]:
    """
    Check the hypotheses and negated conclusion for the Unmixedness Theorem.
    The witness is expected to be a tuple: (gens, n)
    where gens is a list of monomial expressions in a polynomial ring over a field,
    and n is the expected height of the ideal.
    """
    try:
        gens, n = witness
        if not isinstance(gens, (list, tuple)):
            return [False, False, False, False]
        if not isinstance(n, int):
            return [False, False, False, False]
            
        syms = set()
        for g in gens:
            if hasattr(g, 'free_symbols'):
                syms.update(g.free_symbols)
        syms = sorted(list(syms), key=lambda s: s.name)
        num_vars = len(syms)
        
        if num_vars == 0:
            if not gens:
                num_vars = 1
                
        I_gens = []
        is_monomial_ideal = True
        for g in gens:
            m = get_monom(g, syms)
            if m == "ZERO":
                continue
            if m is None:
                is_monomial_ideal = False
                break
            I_gens.append(m)
            
        if not is_monomial_ideal:
            return [False, False, False, False]
            
        # H_1: R is a Cohen-Macaulay commutative Noetherian ring
        # A polynomial ring over a field is regular, hence Cohen-Macaulay and Noetherian.
        h1 = True
        
        # H_2: I is a proper ideal of R
        min_gens = minimize(I_gens, num_vars)
        zero_tuple = tuple(0 for _ in range(num_vars))
        if not min_gens:
            h2 = True
        elif zero_tuple in min_gens:
            h2 = False
        else:
            h2 = True
            
        # Compute the primary decomposition to find associated primes
        comps = decompose(I_gens, num_vars)
        irred_comps = irredundant_components(comps, num_vars)
        
        assoc_primes = set()
        for comp in irred_comps:
            # The radical of an irreducible monomial ideal is generated by the variables present
            rad = tuple(1 if exp > 0 else 0 for exp in comp)
            assoc_primes.add(rad)
            
        # The height of a prime monomial ideal is the number of variables it contains
        assoc_heights = [sum(rad) for rad in assoc_primes]
        
        if not assoc_heights:
            ideal_height = 0
        else:
            ideal_height = min(assoc_heights)
            
        # H_3: The height of the ideal I is exactly n
        h3 = (ideal_height == n)
        
        # ¬Q: Not every associated prime ideal of R/I has height exactly n
        neg_q = any(h != n for h in assoc_heights)
        
        return [h1, h2, h3, neg_q]
        
    except Exception:
        return [False, False, False, False]

