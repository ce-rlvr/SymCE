import sympy
from sympy.ntheory import factorint
from sympy.abc import x

# Top-level setup: named object bindings for witness expressions
class ZnRing:
    is_Zn = True
    def __init__(self, n):
        self.n = n

class Field:
    is_Field = True
    def __init__(self, name):
        self.name = name

class FormalPowerSeriesRing:
    is_FormalPowerSeries = True
    def __init__(self, base, var):
        self.base = base
        self.var = var

class QuotientPolyRing:
    is_QuotientPoly = True
    def __init__(self, base_ring, poly_degree, is_irreducible):
        self.base_ring = base_ring
        self.poly_degree = poly_degree
        self.is_irreducible = is_irreducible

