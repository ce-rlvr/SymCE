def conditions(witness) -> list[bool]:
    h1 = False
    h2 = False
    neg_q = False
    
    try:
        if getattr(witness, 'is_Zn', False):
            n = witness.n
            if n > 1:
                factors = factorint(n)
                # A finite ring Z/nZ is local iff n is a prime power
                h1 = (len(factors) == 1)
                # In Z/nZ, every ideal is principal
                h2 = True
                # Z/nZ is either a field (if n is prime) or not a domain (if n is composite).
                # A DVR must be a PID with exactly one non-zero maximal ideal (hence a domain but not a field).
                neg_q = True
                
        elif isinstance(witness, int) or getattr(witness, 'is_Integer', False):
            n = int(witness)
            if n > 1:
                factors = factorint(n)
                h1 = (len(factors) == 1)
                h2 = True
                neg_q = True
                
        elif getattr(witness, 'is_Field', False) or witness in (sympy.S.Reals, sympy.S.Complexes, sympy.S.Rationals):
            # Fields are local (maximal ideal (0)) and Noetherian
            h1 = True
            # The maximal ideal (0) is principal
            h2 = True
            # Fields have dimension 0, so they are not DVRs
            neg_q = True
            
        elif getattr(witness, 'is_FormalPowerSeries', False):
            h1 = True
            h2 = True
            neg_q = False # k[[x]] is a valid DVR
            
        elif getattr(witness, 'is_QuotientPoly', False):
            # e.g., k[x]/(x^2)
            h1 = True
            h2 = True
            neg_q = True # Not a domain, so not a DVR
            
        elif witness == sympy.S.Integers:
            # Z is Noetherian but not local
            h1 = False
            h2 = True
            neg_q = True
            
    except Exception:
        pass
        
    return [bool(h1), bool(h2), bool(neg_q)]

