import sympy
from sympy import Poly, gcd, groebner, reduced, Mul
import itertools

x, y, z = sympy.symbols('x y z')

def conditions(witness):
    try:
        if isinstance(witness, dict):
            f = witness.get('f')
            x_var = witness.get('x', sympy.Symbol('x'))
            n = witness.get('n')
        elif isinstance(witness, tuple):
            if len(witness) == 3:
                f, x_var, n = witness
            elif len(witness) == 4:
                _, f, x_var, n = witness
            else:
                return [False] * 5
        else:
            return [False] * 5
    except Exception:
        return [False] * 5

    try:
        h1 = isinstance(f, sympy.Expr)
    except Exception:
        h1 = False

    try:
        p = Poly(f, x_var)
        h2 = True
    except Exception:
        h2 = False

    h3 = True

    try:
        if not h2:
            h4 = False
        else:
            coeffs = p.coeffs()
            vars_R = list(f.free_symbols - {x_var})
            if not vars_R:
                h4 = any(c != 0 for c in coeffs)
            else:
                g = coeffs[0]
                for c in coeffs[1:]:
                    g = gcd(g, c)
                if g == 0:
                    h4 = False
                else:
                    reduced_coeffs = [sympy.simplify(c / g) for c in coeffs]
                    gb = groebner(reduced_coeffs, *vars_R)
                    h4 = (len(gb) == 1 and gb[0] == 1)
    except Exception:
        h4 = False

    try:
        if not h2 or not isinstance(n, (int, sympy.Integer)) or n < 1:
            neg_q = False
        else:
            vars_R = list(f.free_symbols - {x_var})
            fn = sympy.expand(f**n)
            pn = Poly(fn, x_var)
            coeffs_fn = pn.coeffs()
            
            coeffs_f = p.coeffs()
            ideal_cf_n = [Mul(*p_comb) for p_comb in itertools.combinations_with_replacement(coeffs_f, n)]
            
            if not vars_R:
                g1 = coeffs_fn[0]
                for c in coeffs_fn[1:]: 
                    g1 = gcd(g1, c)
                g2 = ideal_cf_n[0]
                for c in ideal_cf_n[1:]: 
                    g2 = gcd(g2, c)
                q = (abs(g1) == abs(g2))
            else:
                gb1 = groebner(coeffs_fn, *vars_R)
                gb2 = groebner(ideal_cf_n, *vars_R)
                q = True
                for c in coeffs_fn:
                    if reduced(c, gb2, *vars_R)[1] != 0:
                        q = False
                        break
                if q:
                    for c in ideal_cf_n:
                        if reduced(c, gb1, *vars_R)[1] != 0:
                            q = False
                            break
            neg_q = not q
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]

