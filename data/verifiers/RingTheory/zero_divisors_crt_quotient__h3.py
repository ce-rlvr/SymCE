import math
import sympy
from sympy.abc import x, y, z, t

def conditions(witness):
    """
    Checks if the given witness is a counterexample to the conjecture.
    The witness is expected to be a tuple (m_list, x) or (R, m_list, x),
    where m_list is a list of generators for the ideals I_k in Z or K[t],
    and x is an element of the ring.
    """
    try:
        if len(witness) == 2:
            m_list, val_x = witness
        elif len(witness) == 3:
            _, m_list, val_x = witness
        else:
            return [False] * 4
            
        if not isinstance(m_list, (list, tuple)) or len(m_list) == 0:
            return [False] * 4
            
        # H_1: R is a commutative ring
        # We interpret the witness as elements of Z or K[t], which are commutative rings.
        h1 = True
    except Exception:
        return [False] * 4

    try:
        # H_2: I_1, ..., I_n are pairwise comaximal ideals of R
        h2 = True
        for i in range(len(m_list)):
            for j in range(i + 1, len(m_list)):
                m1, m2 = m_list[i], m_list[j]
                if (hasattr(m1, 'free_symbols') and m1.free_symbols) or \
                   (hasattr(m2, 'free_symbols') and m2.free_symbols):
                    g = sympy.gcd(m1, m2)
                    if g == 0:
                        h2 = False
                        break
                    try:
                        if sympy.degree(g) != 0:
                            h2 = False
                            break
                    except Exception:
                        h2 = False
                        break
                else:
                    if math.gcd(int(m1), int(m2)) != 1:
                        h2 = False
                        break
            if not h2:
                break
    except Exception:
        h2 = False

    try:
        # H_3: x in R
        h3 = True
    except Exception:
        h3 = False

    try:
        def is_zd_or_zero(val, mod):
            if hasattr(mod, 'free_symbols') and mod.free_symbols:
                mod = sympy.sympify(mod)
                val = sympy.sympify(val)
                if mod == 0:
                    return val == 0
                try:
                    deg = sympy.degree(mod)
                except Exception:
                    deg = 0
                if deg == 0:
                    return True
                g = sympy.gcd(val, mod)
                try:
                    return sympy.degree(g) > 0
                except Exception:
                    return False
            else:
                mod = abs(int(mod))
                val = int(val)
                if mod == 1:
                    return True
                elif mod == 0:
                    return val == 0
                else:
                    return math.gcd(val, mod) > 1

        # I is the intersection of I_k. Since they are pairwise comaximal,
        # the intersection is generated by their product.
        M = 1
        for m in m_list:
            M = M * m
            
        lhs = is_zd_or_zero(val_x, M)
        rhs = any(is_zd_or_zero(val_x, m) for m in m_list)
        
        # ¬Q: The conclusion fails
        neg_q = (lhs != rhs)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

