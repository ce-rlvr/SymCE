class BooleanRingOfSubsetsOfN:
    """
    Represents the Boolean ring of all subsets of the natural numbers.
    Addition is symmetric difference, multiplication is intersection.
    The identity element is the set of all natural numbers.
    """
    is_commutative_ring = True
    has_identity = True

class IdealOfFiniteSubsets:
    """
    Represents the ideal of all finite subsets of the natural numbers
    in the Boolean ring of subsets of N.
    """
    is_ideal = True
    is_idempotent_ideal = True
    is_generated_by_idempotent = False

def get_prop(obj, prop):
    """Helper to extract properties from dictionaries or objects."""
    if isinstance(obj, dict) and prop in obj:
        val = obj[prop]
    else:
        val = getattr(obj, prop)
    if callable(val):
        return val()
    return val

def conditions(witness) -> list[bool]:
    """
    Checks if the witness is a valid counterexample to the conjecture.
    The witness is expected to be a tuple (R, I) representing the ring and the ideal.
    """
    try:
        if len(witness) != 2:
            return [False, False, False]
        R, I = witness
    except Exception:
        return [False, False, False]

    # H_1: R is a commutative ring with identity
    try:
        h1 = bool(get_prop(R, 'is_commutative_ring') and get_prop(R, 'has_identity'))
    except Exception:
        h1 = False

    # H_2: I is an ideal such that I^2 = I
    try:
        h2 = bool(get_prop(I, 'is_ideal') and get_prop(I, 'is_idempotent_ideal'))
    except Exception:
        h2 = False

    # ¬Q: I is not generated by an idempotent element
    try:
        neg_q = not bool(get_prop(I, 'is_generated_by_idempotent'))
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

