def is_in_ideal(P, ideal, vars):
    """
    Checks if polynomial P is in the ideal generated by `ideal` over `vars`.
    It does this by checking if adding P to the ideal generators changes the reduced Groebner basis.
    """
    P = expand(P)
    if P == 0:
        return True
    if not ideal:
        return False
    try:
        gb1 = groebner(ideal, *vars)
        gb2 = groebner(ideal + [P], *vars)
        return list(gb1) == list(gb2)
    except Exception:
        return False

def conditions(witness):
    try:
        vec = list(witness['v'])
        coefs = list(witness['coefs'])
        ideal = list(witness['ideal'])
        vars = list(witness['vars'])
    except (KeyError, TypeError):
        return [False, False]
        
    # H_1: v is a unimodular row vector of length n over R
    try:
        if len(vec) == 0 or len(vec) != len(coefs):
            h1 = False
        else:
            # Unimodular means there exist coefficients such that the dot product is 1 in the ring R.
            # This is equivalent to sum(vec[i]*coefs[i]) - 1 being in the ideal defining R.
            poly = sum(vec[i]*coefs[i] for i in range(len(vec))) - 1
            h1 = is_in_ideal(poly, ideal, vars)
    except Exception:
        h1 = False
        
    # neg_Q: There DOES NOT exist an invertible n by n matrix over R whose first row is v.
    try:
        n = len(vec)
        # By Adams' theorem on vector fields on spheres, the tangent bundle of S^{n-1} 
        # is trivial (parallelizable) iff n in [1, 2, 4, 8].
        # For other n, the syzygy module of the unimodular row [x_1, ..., x_n] over 
        # R[x_1, ..., x_n]/(x_1^2 + ... + x_n^2 - 1) is not free, so it cannot be extended.
        if n not in [1, 2, 4, 8]:
            sphere_poly = sum(vi**2 for vi in vec) - 1
            sphere_poly = expand(sphere_poly)
            
            if sphere_poly == 0:
                neg_q = False
            elif not ideal:
                neg_q = False
            else:
                # Check if the ring is exactly the coordinate ring of the sphere
                if is_in_ideal(sphere_poly, ideal, vars):
                    all_in = True
                    for g in ideal:
                        if not is_in_ideal(g, [sphere_poly], vars):
                            all_in = False
                            break
                    neg_q = all_in
                else:
                    neg_q = False
        else:
            neg_q = False
    except Exception:
        neg_q = False
        
    return [h1, neg_q]

