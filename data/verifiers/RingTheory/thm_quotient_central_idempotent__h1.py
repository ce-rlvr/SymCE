def in_list(val, lst):
    for x in lst:
        if x == val:
            return True
    return False

def conditions(witness):
    try:
        if isinstance(witness, tuple):
            R_raw, e, I_raw = witness[0], witness[1], witness[2]
        elif isinstance(witness, dict):
            R_raw, e, I_raw = witness['R'], witness['e'], witness['I']
        else:
            R_raw, e, I_raw = witness.R, witness.e, witness.I
            
        R = []
        for i, x in enumerate(R_raw):
            if i > 500:
                return [False, False, False]
            R.append(x)
            
        I = []
        for i, x in enumerate(I_raw):
            if i > 500:
                return [False, False, False]
            I.append(x)
    except Exception:
        return [False, False, False]

    # H1: e is a central idempotent element of R
    try:
        h1 = in_list(e, R) and (e * e == e)
        if h1:
            for x in R:
                if e * x != x * e:
                    h1 = False
                    break
    except Exception:
        h1 = False

    # H2: I is the principal two-sided ideal generated by e
    try:
        gen_I = []
        def add_val(v):
            for x in gen_I:
                if x == v:
                    return False
            gen_I.append(v)
            return True
            
        add_val(e)
        changed = True
        while changed:
            changed = False
            curr = list(gen_I)
            for x in curr:
                for y in curr:
                    if add_val(x + y): changed = True
                    if add_val(x - y): changed = True
                for r in R:
                    if add_val(r * x): changed = True
                    if add_val(x * r): changed = True
                    
        h2 = True
        for x in I:
            if not in_list(x, gen_I):
                h2 = False
                break
        if h2:
            for x in gen_I:
                if not in_list(x, I):
                    h2 = False
                    break
    except Exception:
        h2 = False

    # neg_Q: The quotient ring R/I is NOT isomorphic to the ring R(1-e)
    try:
        identity = None
        for id_cand in R:
            is_id = True
            for x in R:
                if id_cand * x != x or x * id_cand != x:
                    is_id = False
                    break
            if is_id:
                identity = id_cand
                break
                
        if identity is None:
            # If R has no identity, R(1-e) is undefined, so the conclusion fails.
            neg_q = True
        else:
            one_minus_e = identity - e
            
            S = []
            for r in R:
                val = r * one_minus_e
                if not in_list(val, S):
                    S.append(val)
                    
            cosets = []
            for r in R:
                coset = []
                for i in I:
                    val = r + i
                    if not in_list(val, coset):
                        coset.append(val)
                is_new = True
                for c in cosets:
                    if len(c) == len(coset):
                        all_in = True
                        for x in coset:
                            if not in_list(x, c):
                                all_in = False
                                break
                        if all_in:
                            is_new = False
                            break
                if is_new:
                    cosets.append(coset)
                    
            if len(cosets) != len(S):
                neg_q = True
            else:
                is_iso = True
                for c in cosets:
                    mapped_vals = []
                    for r in c:
                        val = r * one_minus_e
                        if not in_list(val, mapped_vals):
                            mapped_vals.append(val)
                    if len(mapped_vals) > 1:
                        is_iso = False
                        break
                        
                if is_iso:
                    for c1 in cosets:
                        for c2 in cosets:
                            r1 = c1[0]
                            r2 = c2[0]
                            
                            sum_r = r1 + r2
                            sum_c = None
                            for c in cosets:
                                if in_list(sum_r, c):
                                    sum_c = c
                                    break
                            
                            mul_r = r1 * r2
                            mul_c = None
                            for c in cosets:
                                if in_list(mul_r, c):
                                    mul_c = c
                                    break
                                    
                            val1 = r1 * one_minus_e
                            val2 = r2 * one_minus_e
                            val_sum = sum_c[0] * one_minus_e
                            val_mul = mul_c[0] * one_minus_e
                            
                            if val1 + val2 != val_sum:
                                is_iso = False
                                break
                            if val1 * val2 != val_mul:
                                is_iso = False
                                break
                        if not is_iso:
                            break
                neg_q = not is_iso
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

