import sympy as sp
import itertools

x = sp.Symbol('x')

def conditions(witness):
    """
    witness: tuple (f, gens)
      - f: SymPy expression, a monic irreducible polynomial in Z[x] defining the ring R = Z[x]/(f)
      - gens: list of SymPy expressions, generators of the ideal P in R
    """
    try:
        if not isinstance(witness, (tuple, list)) or len(witness) != 2:
            return [False, False, False]
        
        f_expr, gens_expr = witness
        f = sp.Poly(f_expr, x, domain='ZZ')
        
        if f.degree() < 2 or f.LC() != 1 or not f.is_irreducible:
            return [False, False, False]
            
        gens = [sp.Poly(g, x, domain='ZZ') for g in gens_expr]
        
        # Compute the norm of the ideal P by sampling elements and taking the GCD of their norms
        res = 0
        samples = []
        basis = [1, x]
        if f.degree() > 2:
            basis += [x**i for i in range(2, f.degree())]
            
        for g in gens:
            for b in basis:
                samples.append(g * b)
                
        n_gens = len(samples)
        for i in range(n_gens):
            for j in range(i + 1, n_gens):
                samples.append(samples[i] + samples[j])
                samples.append(samples[i] - samples[j])
                
        for g in samples:
            if g.is_zero:
                continue
            r = sp.resultant(f, g)
            res = sp.gcd(res, r)
            if res == 1:
                break
                
        ideal_norm = abs(int(res))
        
        if ideal_norm <= 1:
            h1 = False
        else:
            factors = sp.factorint(ideal_norm)
            if len(factors) == 1:
                p_val = list(factors.keys())[0]
            else:
                p_val = ideal_norm
                
            if not sp.isprime(p_val):
                h1 = False
            else:
                # Check if P mod p is a prime ideal in F_p[x]/(f)
                f_mod = sp.Poly(f_expr, x, domain=sp.GF(p_val))
                gens_mod = [sp.Poly(g.as_expr(), x, domain=sp.GF(p_val)) for g in gens]
                
                ideal_gen = f_mod
                for g_mod in gens_mod:
                    ideal_gen = sp.gcd(ideal_gen, g_mod)
                    
                if not ideal_gen.is_irreducible:
                    h1 = False
                else:
                    # Check if the ideal norm matches the expected norm of the prime component
                    expected_norm = p_val ** ideal_gen.degree()
                    if ideal_norm != expected_norm:
                        h1 = False
                    else:
                        h1 = True
    except Exception:
        h1 = False

    try:
        # R is a 1-dimensional domain, so any non-zero prime ideal has height 1
        h2 = h1 and (ideal_norm > 1)
    except Exception:
        h2 = False

    try:
        if not h1:
            neg_q = False
        else:
            if f.degree() == 2:
                coeffs = f.all_coeffs()
                b_val = int(coeffs[1])
                c_val = int(coeffs[2])
                
                disc = b_val**2 - 4*c_val
                is_principal = False
                
                if disc < 0:
                    # For imaginary quadratic fields, P is principal iff there is an element of norm N(P)
                    max_B = int((ideal_norm / (c_val - b_val**2 / 4.0))**0.5) + 1
                    for B in range(-max_B, max_B + 1):
                        rem = (b_val * B)**2 - 4 * (c_val * B**2 - ideal_norm)
                        if rem >= 0:
                            root = int(rem**0.5)
                            if root**2 == rem:
                                if (b_val * B + root) % 2 == 0 or (b_val * B - root) % 2 == 0:
                                    is_principal = True
                                    break
                else:
                    # Fallback for real quadratic fields to avoid false positives
                    neg_q = False
                    return [h1, h2, neg_q]
                
                neg_q = not is_principal
            else:
                # Fallback for higher degree fields
                neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

