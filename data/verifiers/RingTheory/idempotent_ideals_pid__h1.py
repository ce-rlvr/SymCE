def conditions(witness):
    try:
        # We expect the witness to represent the ring Z/nZ and an ideal generated by k.
        # It can be provided as a dictionary or a tuple (n, k).
        if isinstance(witness, dict):
            n = witness.get('n', witness.get('R', witness.get('ring', 0)))
            k = witness.get('k', witness.get('I', witness.get('ideal', 0)))
        elif isinstance(witness, (tuple, list)) and len(witness) == 2:
            n, k = witness
        else:
            return [False, False, False]
            
        # Parse n (the modulus of the ring Z/nZ)
        if isinstance(n, str):
            n_str = n.upper().replace('Z', '').replace('/', ' ').replace('_', '').strip()
            parts = n_str.split()
            if parts:
                n = int(parts[-1])
            else:
                n = 0
        elif hasattr(n, 'order') and callable(n.order):
            n = n.order()
        else:
            n = int(n)
            
        if n < 2:
            return [False, False, False]
            
        # Parse k (the generator of the ideal)
        if hasattr(k, 'order') and callable(k.order):
            m = k.order()
            if m > 0 and n % m == 0:
                k = n // m
            else:
                k = int(k)
        elif isinstance(k, (list, set, tuple)):
            gen = n
            for x in k:
                if isinstance(x, str):
                    x_str = x.upper().replace('Z', '').replace('/', ' ').replace('_', '').strip('<>()[]{} ')
                    x_parts = x_str.split()
                    val = int(x_parts[0]) if x_parts else 1
                else:
                    val = int(x)
                gen = math.gcd(gen, val)
            k = gen
        elif isinstance(k, str):
            k_str = k.upper().replace('Z', '').replace('/', ' ').replace('_', '').strip('<>()[]{} ')
            parts = k_str.split()
            if parts:
                k = int(parts[0])
            else:
                k = 1
        else:
            k = int(k)
            
        # H_1: I is an ideal of R
        # In Z/nZ, any integer k defines a principal ideal (k).
        h1 = True
        
        # H_2: I^2 = I
        # The ideal I is generated by gcd(k, n).
        # I^2 is generated by gcd(k^2, n).
        g1 = math.gcd(k, n)
        g2 = math.gcd(k**2, n)
        h2 = (g1 == g2)
        
        # ¬Q: I is neither the zero ideal nor the entire ring
        # The zero ideal is generated by n (i.e., 0 mod n).
        # The entire ring is generated by 1.
        neg_q = (g1 != n) and (g1 != 1)
        
        return [h1, h2, neg_q]
    except Exception:
        return [False, False, False]