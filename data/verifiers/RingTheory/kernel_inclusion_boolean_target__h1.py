def get_attr(witness, attr):
    if isinstance(witness, dict):
        return witness.get(attr)
    if isinstance(witness, tuple) and len(witness) == 5:
        keys = ['R_add', 'R_mul', 'B_add', 'B_mul', 'f']
        if attr in keys:
            return witness[keys.index(attr)]
    return getattr(witness, attr, None)

def is_abelian_group(add):
    n = len(add)
    for row in add:
        if any(x < 0 or x >= n for x in row): return False
    for i in range(n):
        for j in range(n):
            if add[i][j] != add[j][i]: return False
    for i in range(n):
        for j in range(n):
            for k in range(n):
                if add[add[i][j]][k] != add[i][add[j][k]]: return False
    id_elem = -1
    for i in range(n):
        if all(add[i][j] == j for j in range(n)):
            id_elem = i
            break
    if id_elem == -1: return False
    for i in range(n):
        if not any(add[i][j] == id_elem for j in range(n)): return False
    return True

def is_ring(add, mul):
    if not is_abelian_group(add): return False
    n = len(add)
    for row in mul:
        if any(x < 0 or x >= n for x in row): return False
    for i in range(n):
        for j in range(n):
            for k in range(n):
                if mul[mul[i][j]][k] != mul[i][mul[j][k]]: return False
    for i in range(n):
        for j in range(n):
            for k in range(n):
                if mul[i][add[j][k]] != add[mul[i][j]][mul[i][k]]: return False
                if mul[add[i][j]][k] != add[mul[i][k]][mul[j][k]]: return False
    return True

def is_boolean_ring(add, mul):
    if not is_ring(add, mul): return False
    n = len(add)
    for i in range(n):
        if mul[i][i] != i: return False
    return True

def get_zero(add):
    n = len(add)
    for i in range(n):
        if all(add[i][j] == j for j in range(n)):
            return i
    return -1

def get_neg(add, zero):
    n = len(add)
    neg = [-1] * n
    for i in range(n):
        for j in range(n):
            if add[i][j] == zero:
                neg[i] = j
                break
    return neg

