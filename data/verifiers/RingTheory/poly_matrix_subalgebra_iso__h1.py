O3 = sp.zeros(3, 3)

def conditions(witness) -> list[bool]:
    try:
        n, A, m_A = witness
        n = int(n)
    except Exception:
        return [False, False, False]

    try:
        h1 = (n >= 2 and isinstance(A, sp.Matrix) and A.rows == A.cols and A.rows > 0 and all(val.is_integer == True for val in A))
        if h1:
            m_A_poly = sp.Poly(m_A, x, domain='ZZ')
            if not m_A_poly.is_Poly:
                h1 = False
    except Exception:
        h1 = False

    try:
        if not h1:
            h2 = False
        else:
            coeffs = m_A_poly.all_coeffs()
            d = m_A_poly.degree()
            
            if len(coeffs) == 0 or coeffs[0] % n != 1 or d < 1:
                h2 = False
            else:
                powers = [sp.eye(A.rows)]
                for _ in range(d):
                    powers.append((powers[-1] * A) % n)
                
                def eval_with_powers(test_coeffs):
                    res = sp.zeros(A.rows, A.cols)
                    for i, c in enumerate(reversed(test_coeffs)):
                        if c % n != 0:
                            res = (res + c * powers[i]) % n
                    return res

                if not all(val % n == 0 for val in eval_with_powers(coeffs)):
                    h2 = False
                else:
                    h2 = True
                    for deg in range(1, d):
                        for lower_coeffs in itertools.product(range(n), repeat=deg):
                            test_coeffs = [1] + list(lower_coeffs)
                            if all(val % n == 0 for val in eval_with_powers(test_coeffs)):
                                h2 = False
                                break
                        if not h2:
                            break
    except Exception:
        h2 = False

    try:
        if not h1:
            neg_q = False
        else:
            d = m_A_poly.degree()
            if d < 1:
                neg_q = False
            else:
                powers_basis = [sp.eye(A.rows)]
                for _ in range(d - 1):
                    powers_basis.append((powers_basis[-1] * A) % n)
                
                flat_powers = [tuple(p) for p in powers_basis]
                rows, cols = A.rows, A.cols
                
                generated_matrices = set()
                for c_tuple in itertools.product(range(n), repeat=d):
                    mat = [0] * (rows * cols)
                    for i, c in enumerate(c_tuple):
                        if c == 0: 
                            continue
                        fp = flat_powers[i]
                        for j in range(rows * cols):
                            mat[j] = (mat[j] + c * fp[j]) % n
                    generated_matrices.add(tuple(mat))
                
                neg_q = len(generated_matrices) != (n ** d)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

