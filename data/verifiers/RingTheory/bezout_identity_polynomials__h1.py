import sympy
from sympy import Poly, groebner
from sympy.abc import x, y, z

def conditions(witness):
    try:
        f, g = witness
    except Exception:
        return [False, False, False]
        
    # H1: f(x) and g(x) are polynomials in F[x]
    try:
        h1 = (isinstance(f, Poly) and isinstance(g, Poly) and 
              f.is_univariate and g.is_univariate and 
              f.gen == g.gen and f.domain == g.domain)
    except Exception:
        h1 = False
        
    # H2: f(x) and g(x) are relatively prime (their greatest common divisor is a non-zero constant)
    try:
        gcd_fg = f.gcd(g)
        h2 = gcd_fg.degree() == 0 and not gcd_fg.is_zero
    except Exception:
        h2 = False
        
    # neg_Q: There do NOT exist polynomials a(x), b(x) in F[x] such that a(x)f(x) + b(x)g(x) = 1
    try:
        # We check if 1 is in the ideal generated by f and g over their domain F.
        # If 1 is in the ideal, the Groebner basis will contain a unit of degree 0.
        # Over fields, SymPy normalizes this to 1. Over ZZ, it will be 1 or -1.
        gb = groebner([f, g], f.gen, domain=f.domain)
        is_one_in_ideal = False
        for p in gb:
            if p.degree() == 0 and (p.LC() == 1 or p.LC() == -1):
                is_one_in_ideal = True
                break
        neg_q = not is_one_in_ideal
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

