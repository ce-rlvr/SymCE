def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "If R is a Dedekind domain and P is a non-zero ideal, then P is a maximal ideal."
    
    We interpret the witness as a generator of a principal ideal in either Z or Q[x].
    Both Z and Q[x] are Principal Ideal Domains, and therefore Dedekind domains.
    """
    
    # H1: R is a Dedekind domain
    try:
        if isinstance(witness, (int, Integer)):
            h1 = True
        else:
            p = Poly(witness, domain='QQ')
            # Q[x] is a Dedekind domain, but Q[x, y, ...] is not (Krull dimension > 1)
            h1 = not p.is_multivariate
    except Exception:
        h1 = False

    # H2: P is not the zero ideal
    try:
        if isinstance(witness, (int, Integer)):
            h2 = (witness != 0)
        else:
            p = Poly(witness, domain='QQ')
            h2 = not p.is_zero
    except Exception:
        h2 = False

    # neg_Q: P is not a maximal ideal of R
    try:
        if isinstance(witness, (int, Integer)):
            val = abs(int(witness))
            # In Z, maximal ideals are generated by prime numbers.
            # 1 generates the whole ring, which is not a proper ideal, hence not maximal.
            neg_q = (val == 1) or not sympy.isprime(val)
        else:
            p = Poly(witness, domain='QQ')
            # In Q[x], maximal ideals are generated by irreducible polynomials.
            # Polynomials of degree <= 0 are units (or zero), generating the whole ring (or zero ideal).
            neg_q = (p.degree() <= 0) or not p.is_irreducible
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

