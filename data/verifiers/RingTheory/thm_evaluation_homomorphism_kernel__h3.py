CONDITION_LABELS = [
    "H_1: R is a commutative ring with identity",
    "H_2: a is an element of R",
    "¬Q: The kernel of ev_a is NOT the principal ideal generated by the polynomial x - a"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness) -> list[bool]:
    # Unpack witness
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            R, a = witness
        else:
            R = witness
            a = None
    except Exception:
        return [False, False, False]

    # H_1: R is a commutative ring with identity
    try:
        # Check if R is a sympy domain/ring
        is_ring = hasattr(R, 'ring') or hasattr(R, 'get_ring') or hasattr(R, 'is_commutative')
        # In sympy, standard domains (ZZ, QQ, etc.) are commutative rings with identity
        h1_ok = bool(is_ring and getattr(R, 'is_commutative', True))
    except Exception:
        h1_ok = False

    # H_2: a is an element of R
    try:
        if a is None:
            h2_ok = False
        else:
            # Check if a belongs to the domain R
            h2_ok = a in R or R.of_type(a)
    except Exception:
        h2_ok = False

    # ¬Q: The kernel of ev_a is NOT the principal ideal generated by the polynomial x - a
    # Mathematically, for any commutative ring with identity R and any a in R, 
    # the division algorithm f(x) = q(x)(x-a) + f(a) holds as a formal identity in R[x].
    # Thus, f(a) = 0 if and only if f(x) = q(x)(x-a), meaning the kernel of the evaluation 
    # homomorphism ev_a: R[x] -> R is ALWAYS exactly the principal ideal <x - a>.
    # Since the conclusion is a universal theorem, it never fails at any valid witness.
    neg_q_ok = False

    return [h1_ok, h2_ok, neg_q_ok]