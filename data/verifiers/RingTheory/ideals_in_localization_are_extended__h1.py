def get_attr(obj, attr):
    if isinstance(obj, dict):
        return obj[attr]
    return getattr(obj, attr)

def conditions(witness) -> list[bool]:
    # H_1: S is a multiplicatively closed subset of R
    try:
        S = get_attr(witness, 'S')
        R = get_attr(witness, 'R')
        mul_R = get_attr(witness, 'mul_R')
        
        h1_ok = True
        for a in S:
            for b in S:
                if mul_R(a, b) not in S:
                    h1_ok = False
                    break
            if not h1_ok:
                break
        if not all(x in R for x in S):
            h1_ok = False
    except Exception:
        h1_ok = False

    # H_2: J is an ideal of the localization S^{-1}R
    try:
        J = get_attr(witness, 'J')
        S_inv_R = get_attr(witness, 'S_inv_R')
        add_loc = get_attr(witness, 'add_loc')
        mul_loc = get_attr(witness, 'mul_loc')
        zero_loc = get_attr(witness, 'zero_loc')
        
        h2_ok = True
        if zero_loc not in J:
            h2_ok = False
        if not all(x in S_inv_R for x in J):
            h2_ok = False
            
        if h2_ok:
            for a in J:
                for b in J:
                    if add_loc(a, b) not in J:
                        h2_ok = False
                for r in S_inv_R:
                    if mul_loc(a, r) not in J:
                        h2_ok = False
                    if mul_loc(r, a) not in J:
                        h2_ok = False
                has_inv = False
                for b in J:
                    if add_loc(a, b) == zero_loc and add_loc(b, a) == zero_loc:
                        has_inv = True
                        break
                if not has_inv:
                    h2_ok = False
    except Exception:
        h2_ok = False

    # ¬Q: There does NOT exist an ideal I of R such that J = S^{-1}I
    try:
        R = get_attr(witness, 'R')
        J = get_attr(witness, 'J')
        S_inv_R = get_attr(witness, 'S_inv_R')
        add_loc = get_attr(witness, 'add_loc')
        mul_loc = get_attr(witness, 'mul_loc')
        zero_loc = get_attr(witness, 'zero_loc')
        loc_map = get_attr(witness, 'loc_map')
        
        # The only candidate ideal I of R that could extend to J is its contraction
        I = [r for r in R if loc_map(r) in J]
        
        # Extension of I in S_inv_R (ideal generated by loc_map(I))
        generators = [loc_map(r) for r in I]
        
        current = []
        for g in generators:
            if g not in current:
                current.append(g)
        if zero_loc not in current:
            current.append(zero_loc)
            
        max_size = len(S_inv_R)
        while True:
            added = False
            n = len(current)
            for i in range(n):
                a = current[i]
                for j in range(n):
                    b = current[j]
                    val = add_loc(a, b)
                    if val not in current:
                        current.append(val)
                        added = True
                for r in S_inv_R:
                    val1 = mul_loc(a, r)
                    if val1 not in current:
                        current.append(val1)
                        added = True
                    val2 = mul_loc(r, a)
                    if val2 not in current:
                        current.append(val2)
                        added = True
            for i in range(n):
                a = current[i]
                for b in S_inv_R:
                    if add_loc(a, b) == zero_loc:
                        if b not in current:
                            current.append(b)
                            added = True
            if not added:
                break
            if len(current) > max_size:
                raise ValueError("Generated ideal exceeds S_inv_R size")
                
        # J is extended from I iff the generated ideal `current` equals `J`
        is_equal = all(x in J for x in current) and all(x in current for x in J)
        neg_q_ok = not is_equal
        
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, neg_q_ok]

