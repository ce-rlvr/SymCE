import sympy
from sympy import Rational, Integer

# Top-level setup
# We define standard symbols that might be used in the witness.
x, y, z = sympy.symbols('x y z')

def conditions(witness) -> list[bool]:
    """
    Checks whether the witness is a valid counterexample to the false conjecture.
    
    Remaining hypotheses:
      1. R is a Unique Factorization Domain (UFD).
      2. a and b are non-zero elements in R.
      
    Conclusion (must FAIL at the witness):
      a divides b in R if and only if v_p(a) <= v_p(b) for all prime elements p in R.
      
    The witness is expected to be a tuple: (R, a, b)
    where R is a sympy domain (e.g., sympy.ZZ, sympy.QQ), and a, b are elements of R.
    """
    try:
        R, a, b = witness
    except Exception:
        return [False, False, False]

    # H_1: R is a Unique Factorization Domain
    try:
        # In sympy, domains have properties. We check if R is a UFD.
        h1_ok = bool(R.is_UFD)
    except Exception:
        h1_ok = False

    # H_2: a and b are non-zero elements in R
    try:
        # Check if a and b belong to R and are non-zero
        in_R = (a in R) and (b in R)
        non_zero = (a != R.zero) and (b != R.zero)
        h2_ok = bool(in_R and non_zero)
    except Exception:
        h2_ok = False

    # ¬Q: The conclusion fails at the witness.
    # The conclusion is: a divides b in R iff v_p(a) <= v_p(b) for all prime elements p in R.
    # We evaluate both sides of the iff.
    try:
        # Check if a divides b in R
        # In a domain, a divides b if b is in the ideal generated by a, or b/a is in R.
        if R.is_Field:
            a_divides_b = True
        else:
            # For domains like ZZ or polynomials
            q, r = R.div(b, a)
            a_divides_b = (r == R.zero)
            
        # Check if v_p(a) <= v_p(b) for all prime elements p in R.
        # Since we cannot iterate over all primes, we check the prime factors of a and b.
        # If R is a field, there are no prime elements, so the condition is vacuously true.
        if R.is_Field:
            vp_condition = True
        else:
            # Factorize a and b in R
            factors_a = R.factor(a)
            factors_b = R.factor(b)
            
            # factors_a is typically a dictionary of {prime_element: exponent} or similar,
            # but sympy's domain factor returns (unit, {factor: exponent})
            if isinstance(factors_a, tuple) and len(factors_a) == 2:
                dict_a = factors_a[1]
            elif isinstance(factors_a, dict):
                dict_a = factors_a
            else:
                dict_a = factors_a.copy()
                
            if isinstance(factors_b, tuple) and len(factors_b) == 2:
                dict_b = factors_b[1]
            elif isinstance(factors_b, dict):
                dict_b = factors_b
            else:
                dict_b = factors_b.copy()
                
            vp_condition = True
            # We need to check all primes. The only primes where v_p(a) > 0 are in dict_a.
            # For any prime p in dict_a, we must have v_p(a) <= v_p(b).
            # Note: sympy factors might not be unique up to associates in the exact keys,
            # but for standard domains like ZZ or QQ[x] they are normalized.
            for p, exp_a in dict_a.items():
                exp_b = dict_b.get(p, 0)
                if exp_a > exp_b:
                    vp_condition = False
                    break
                    
        # The conclusion is (a_divides_b == vp_condition)
        # We want the conclusion to FAIL, so we negate it.
        neg_q_ok = bool(a_divides_b != vp_condition)
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, neg_q_ok]

