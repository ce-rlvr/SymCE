import sympy
from sympy import S

# Top-level setup: named object bindings that the witness expression may reference.
Z = sympy.S.Integers
ZZ = sympy.ZZ
QQ = sympy.QQ

def conditions(witness) -> list[bool]:
    """
    Checks whether the given witness is a valid counterexample to the false conjecture.
    The witness should be a tuple: (R, I, P_list, e_list) or (I, P_list, e_list) assuming R=Z.
    """
    try:
        if len(witness) == 4:
            R, I, P_list, e_list = witness
        elif len(witness) == 3:
            I, P_list, e_list = witness
            R = sympy.ZZ
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]
        
    # H_1: R is a Dedekind domain
    # We support the ring of integers Z as the primary Dedekind domain for witnesses.
    try:
        h1 = R in (sympy.S.Integers, sympy.ZZ, "ZZ", "Z", Z, ZZ)
    except Exception:
        h1 = False
        
    # H_2: I = P_1^{e_1} ... P_k^{e_k} is the unique prime factorization of I, 
    # where P_i are distinct prime ideals and e_i >= 1
    try:
        if len(P_list) != len(e_list):
            h2 = False
        else:
            prod = 1
            for p, e in zip(P_list, e_list):
                prod *= (int(p) ** int(e))
            
            # In Z, ideals are generated by their absolute value
            is_prod = (abs(int(I)) == abs(prod))
            
            # Check that the prime ideals are distinct
            distinct = (len(set(abs(int(p)) for p in P_list)) == len(P_list))
            
            # Check that each P_i is a prime ideal. In Z, (0) is a prime ideal.
            def is_prime_ideal(p):
                p = abs(int(p))
                if p == 0:
                    return True
                return sympy.isprime(p)
                
            primes_ok = all(is_prime_ideal(p) for p in P_list)
            
            # Check exponents
            e_ok = all(int(e) >= 1 for e in e_list)
            
            h2 = is_prod and distinct and primes_ok and e_ok
    except Exception:
        h2 = False
        
    # ¬Q: R/I is NOT isomorphic to the direct product of R/P_i^{e_i}
    try:
        # We determine isomorphism of finitely generated abelian groups (which uniquely 
        # determines the ring structure for quotients of Z) by comparing their invariant factors.
        def get_invariants(n_list):
            rank = 0
            primary = {}
            for n in n_list:
                n = abs(int(n))
                if n == 0:
                    rank += 1
                elif n == 1:
                    continue
                else:
                    f = sympy.factorint(n)
                    for p, e in f.items():
                        primary[p] = primary.get(p, []) + [e]
            for p in primary:
                primary[p].sort()
            return rank, primary

        rank1, prim1 = get_invariants([I])
        n_list = [int(p)**int(e) for p, e in zip(P_list, e_list)]
        rank2, prim2 = get_invariants(n_list)
        
        isomorphic = (rank1 == rank2 and prim1 == prim2)
        neg_q = not isomorphic
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

