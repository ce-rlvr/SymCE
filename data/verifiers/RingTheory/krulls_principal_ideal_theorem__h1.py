import sympy
from sympy import symbols
from sympy.abc import x, y, z

class ValuationRingRank2:
    """
    Represents a valuation ring V with value group Z x Z (lexicographic order).
    Elements are represented by their valuation (a, b).
    'infty' represents the zero element.
    This ring serves as a standard counterexample to Krull's Principal Ideal Theorem
    when the Noetherian hypothesis is dropped.
    """
    def __init__(self):
        self.primes = ['P0', 'P1', 'P2']
        
    def is_element(self, elem):
        if elem == 'infty': 
            return True
        if isinstance(elem, tuple) and len(elem) == 2:
            a, b = elem
            if isinstance(a, int) and isinstance(b, int):
                return a > 0 or (a == 0 and b >= 0)
        return False

    def is_unit(self, elem):
        return elem == (0, 0)

    def is_prime_ideal(self, P):
        return P in self.primes

    def minimal_primes_over_principal(self, elem):
        if not self.is_element(elem):
            return []
        if elem == 'infty':
            return ['P0']
        
        a, b = elem
        containing_primes = []
        
        # P1 contains elements with a > 0
        if a > 0:
            containing_primes.append('P1')
            
        # P2 contains elements with a > 0 or (a == 0 and b > 0)
        if a > 0 or (a == 0 and b > 0):
            containing_primes.append('P2')
            
        if 'P1' in containing_primes:
            return ['P1']
        elif 'P2' in containing_primes:
            return ['P2']
        else:
            return []

    def height(self, P):
        if P == 'P0': return 0
        if P == 'P1': return 1
        if P == 'P2': return 2
        return -1

# Top-level setup
V = ValuationRingRank2()

def conditions(witness):
    """
    Checks whether the witness is a valid counterexample.
    Expected witness format: (R, x, P) or (x, P) assuming R = V.
    """
    try:
        if isinstance(witness, (tuple, list)):
            if len(witness) == 3:
                R, elem, P = witness
            elif len(witness) == 2:
                R = V
                elem, P = witness
            else:
                return [False, False, False]
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H_1: x is a non-unit element of R
    try:
        h1 = R.is_element(elem) and not R.is_unit(elem)
    except Exception:
        h1 = False

    # H_2: P is a minimal prime ideal over the principal ideal generated by x
    try:
        h2 = R.is_prime_ideal(P) and P in R.minimal_primes_over_principal(elem)
    except Exception:
        h2 = False

    # ¬Q: The height of the prime ideal P is strictly greater than 1
    try:
        neg_q = R.height(P) > 1
    except Exception:
        neg_q = False

    return [bool(h1), bool(h2), bool(neg_q)]

