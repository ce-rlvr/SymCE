import sympy as sp

# Top-level setup for named objects
x, y, z, t = sp.symbols('x y z t')
ZZ = sp.ZZ
QQ = sp.QQ

CONDITION_LABELS = [
    "H_1: R is a Unique Factorization Domain",
    "H_2: a in R is a non-zero element",
    "not Q: The content of the monomial a*x^n is NOT associate to a in R"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness) -> list[bool]:
    # Parse the witness. It can be a single element `a` or a tuple/list `(a, n)`.
    try:
        if isinstance(witness, (tuple, list)):
            if len(witness) >= 2:
                a, n = witness[0], witness[1]
            elif len(witness) == 1:
                a = witness[0]
                n = 1
            else:
                return [False, False, False]
        else:
            a = witness
            n = 1
    except Exception:
        return [False, False, False]
        
    try:
        a = sp.sympify(a)
        n = sp.sympify(n)
    except Exception:
        return [False, False, False]
        
    # H_1: R is a Unique Factorization Domain
    # We consider the base ring R to be the polynomial ring over QQ generated by the free symbols of `a`.
    # Polynomial rings over fields are always UFDs. We just need `a` to be a valid algebraic expression.
    try:
        if not isinstance(a, sp.Expr):
            h1 = False
        else:
            h1 = True
    except Exception:
        h1 = False
        
    # H_2: a in R is a non-zero element
    try:
        h2 = bool(sp.simplify(a) != 0)
    except Exception:
        h2 = False
        
    # not Q: The content of the monomial a*x^n is NOT associate to a in R
    try:
        expr = a * x**n
        
        # Compute the content of the polynomial with respect to x
        p = sp.Poly(expr, x)
        c = p.content()
        
        # Check if the content `c` is associate to `a` in R.
        # In the polynomial ring QQ[symbols], the units are exactly the non-zero constants (elements of QQ).
        # Thus, `c` and `a` are associate if and only if their ratio is a non-zero constant.
        ratio = sp.cancel(c / a)
        
        if ratio.free_symbols:
            # The ratio depends on some variables, so it is not a unit.
            is_associate = False
        else:
            # The ratio is a constant. It is a unit as long as it is non-zero.
            is_associate = (ratio != 0)
            
        neg_q = not is_associate
    except Exception:
        # If Poly fails (e.g., if n < 0, making it a Laurent monomial rather than a polynomial),
        # the content is undefined in R[x], meaning the conclusion fails to hold.
        neg_q = True
        
    return [h1, h2, neg_q]