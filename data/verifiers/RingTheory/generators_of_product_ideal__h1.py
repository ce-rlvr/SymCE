def get_ideal_gen(matrix_list):
    """
    Computes the generator of the ideal in the base ring C 
    corresponding to the two-sided ideal generated by matrix_list in M_n(C).
    """
    g = 0
    for M in matrix_list:
        for val in M:
            g = gcd(g, val)
    return g

def same_ideal(g1, g2, all_integers):
    """
    Checks if two base ring elements generate the same ideal.
    """
    if g1 == 0 and g2 == 0:
        return True
    if g1 == 0 or g2 == 0:
        return False
    try:
        r1 = cancel(g1 / g2)
        r2 = cancel(g2 / g1)
        if all_integers:
            # In Z, they must divide each other to generate the same ideal
            return r1.is_integer and r2.is_integer
        else:
            # In a field, any non-zero elements generate the same ideal.
            # In a polynomial ring over a field, they must differ by a unit (constant).
            if r1.is_number and r2.is_number:
                return True
            return r1.as_numer_denom()[1] == 1 and r2.as_numer_denom()[1] == 1
    except Exception:
        return False

def conditions(witness):
    # Extract S, T, I, J from the witness
    if isinstance(witness, dict):
        S = witness.get('S', [])
        T = witness.get('T', [])
        I = witness.get('I', S)
        J = witness.get('J', T)
    elif isinstance(witness, tuple) and len(witness) >= 2:
        S = witness[0]
        T = witness[1]
        I = witness[2] if len(witness) > 2 else S
        J = witness[3] if len(witness) > 3 else T
    else:
        return [False, False, False, False]

    # H_1: S and T are subsets of R
    # We assume R is a matrix ring M_n(C) to allow for non-commutative counterexamples
    try:
        def is_valid_subset(subset):
            if not isinstance(subset, (list, tuple, set)):
                return False
            for M in subset:
                if not hasattr(M, 'rows') or not hasattr(M, 'cols'):
                    return False
                if M.rows != M.cols:
                    return False
            return True

        h1 = is_valid_subset(S) and is_valid_subset(T) and is_valid_subset(I) and is_valid_subset(J)
        
        # Ensure all matrices belong to the same ring (same dimensions)
        sizes = set()
        for subset in (S, T, I, J):
            if subset:
                for M in subset:
                    sizes.add(M.rows)
        if len(sizes) > 1:
            h1 = False
            
    except Exception:
        h1 = False

    # Determine the base ring characteristics
    try:
        all_matrices = list(S) + list(T) + list(I) + list(J)
        all_integers = True
        for M in all_matrices:
            for val in M:
                if not val.is_integer:
                    all_integers = False
                    break
    except Exception:
        all_integers = False

    # H_2: I is the ideal generated by S
    try:
        gen_S = get_ideal_gen(S)
        gen_I = get_ideal_gen(I)
        h2 = same_ideal(gen_S, gen_I, all_integers)
    except Exception:
        h2 = False

    # H_3: J is the ideal generated by T
    try:
        gen_T = get_ideal_gen(T)
        gen_J = get_ideal_gen(J)
        h3 = same_ideal(gen_T, gen_J, all_integers)
    except Exception:
        h3 = False

    # ¬Q: The product ideal IJ is NOT generated by the set {st | s in S, t in T}
    try:
        # The product ideal IJ in M_n(C) corresponds to the product of their base ring ideals
        gen_IJ = gen_I * gen_J
        
        # Compute the ideal generated by the set ST = {s*t | s in S, t in T}
        ST = []
        for s in S:
            for t in T:
                ST.append(s * t)
        
        gen_ST = get_ideal_gen(ST)
        
        # The conclusion fails if IJ and <ST> do not generate the same ideal
        neg_q = not same_ideal(gen_IJ, gen_ST, all_integers)
    except Exception:
        neg_q = False

    return [bool(h1), bool(h2), bool(h3), bool(neg_q)]

