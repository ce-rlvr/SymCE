import sympy
from sympy import symbols, factor_list

# Top-level setup: named object bindings that the witness expression may reference.
x, y, z, t = symbols('x y z t')

CONDITION_LABELS = [
    "H_1: P is a prime ideal of R",
    "H_2: P is not the zero ideal",
    "¬Q: P is not a maximal ideal of R"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness) -> list[bool]:
    try:
        # Extract ideal generators and ring generators from the witness.
        # The witness can be a tuple (I_gens, R_gens) or a SymPy Ideal object.
        if hasattr(witness, 'ring') and hasattr(witness, 'gens'):
            I_gens = witness.gens
            R_gens = witness.ring.gens
        else:
            I_gens, R_domain = witness
            if hasattr(R_domain, 'gens'):
                R_gens = R_domain.gens
            else:
                R_gens = R_domain
                
        if not isinstance(I_gens, (list, tuple)):
            I_gens = [I_gens]
        if not isinstance(R_gens, (list, tuple)):
            R_gens = [R_gens]
            
        I_gens = list(I_gens)
        R_gens = list(R_gens)
    except Exception:
        return [False, False, False]

    # H_1: P is a prime ideal of R
    try:
        h1 = False
        if all(g == 0 for g in I_gens):
            h1 = True
        elif all(g in R_gens for g in I_gens):
            h1 = True
        elif len(I_gens) == 1:
            f = I_gens[0]
            try:
                factors = factor_list(f)
                # A principal ideal (f) is prime if f is irreducible
                if len(factors[1]) == 1 and factors[1][0][1] == 1:
                    h1 = True
            except Exception:
                pass
    except Exception:
        h1 = False

    # H_2: P is not the zero ideal
    try:
        h2 = not all(g == 0 for g in I_gens)
    except Exception:
        h2 = False

    # ¬Q: P is not a maximal ideal of R
    try:
        is_max = False
        if all(g in R_gens for g in I_gens):
            # An ideal generated by variables is maximal iff it contains all variables
            is_max = len(set(I_gens)) == len(set(R_gens))
        elif len(I_gens) == 1:
            # A principal prime ideal is maximal iff the ring has dimension 1 (1 variable)
            if len(R_gens) == 1:
                is_max = True
            else:
                is_max = False
        else:
            is_max = False
            
        neg_q = not is_max
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]