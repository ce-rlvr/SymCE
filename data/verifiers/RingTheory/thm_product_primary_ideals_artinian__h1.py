import sympy as sp
import itertools
from math import gcd
from functools import reduce

# Top-level setup: named object bindings that the witness expression may reference.
x, y, z, w, u, v = sp.symbols('x y z w u v')

def conditions(witness):
    try:
        # Extract generators from the witness
        if hasattr(witness, 'gens'):
            exprs = witness.gens
        elif isinstance(witness, (list, tuple, set)):
            exprs = list(witness)
        else:
            return [False, False]
            
        exprs = [sp.sympify(g) for g in exprs]
        
        # Find all variables used in the expressions
        vars_in_exprs = set()
        for expr in exprs:
            vars_in_exprs.update(expr.free_symbols)
        vars_in_exprs = sorted(list(vars_in_exprs), key=lambda var: var.name)
        
        # Handle pure integer ideals (no variables)
        if not vars_in_exprs:
            try:
                nums = [abs(int(e)) for e in exprs]
                g = reduce(gcd, nums) if nums else 0
                h1 = (g != 1)
                # In Z, every proper ideal is a product of primary ideals
                return [h1, False]
            except Exception:
                return [False, False]
                
        # Compute the Groebner basis over Z to find minimal generators
        gb = sp.groebner(exprs, *vars_in_exprs, domain='ZZ')
        gb_exprs = list(gb)
        
        # H1: I is a proper ideal of R
        # The ideal is proper if the Groebner basis is not [1] or [-1]
        h1 = not (len(gb_exprs) == 1 and abs(gb_exprs[0]) == 1)
        if not h1:
            return [False, False]
            
        # Check if the ideal is generated by monomials
        is_monomial = True
        for g in gb_exprs:
            if g == 0:
                continue
            poly = g.as_poly(*vars_in_exprs, domain='ZZ')
            if poly is None or not poly.is_monomial:
                is_monomial = False
                break
                
        # neg_Q: I cannot be written as a finite product of primary ideals
        neg_q = False
        if is_monomial:
            # 2-generator monomial ideals
            if len(gb_exprs) == 2:
                m1, m2 = gb_exprs
                v1 = m1.free_symbols
                v2 = m2.free_symbols
                # If the generators have disjoint variables, and one has >= 1 variable 
                # while the other has >= 2 variables, it is not a product of primary ideals.
                if v1.is_disjoint(v2):
                    eff_len1 = len(v1) if len(v1) > 0 else 1
                    eff_len2 = len(v2) if len(v2) > 0 else 1
                    if (eff_len1 >= 1 and eff_len2 >= 2) or (eff_len1 >= 2 and eff_len2 >= 1):
                        neg_q = True
                        
            # >= 3-generator monomial ideals
            elif len(gb_exprs) >= 3:
                # Check for the specific (xy, xz, yz) pattern
                if len(gb_exprs) == 3:
                    vars_all = set()
                    for g in gb_exprs:
                        vars_all.update(g.free_symbols)
                    if len(vars_all) == 3:
                        degrees = [sum(g.as_poly(*vars_in_exprs, domain='ZZ').degree_list()) for g in gb_exprs]
                        if all(d == 2 for d in degrees):
                            if all(len(g.free_symbols) == 2 for g in gb_exprs):
                                neg_q = True
                
                # General disjoint check for any number of generators >= 3
                if not neg_q:
                    for i in range(len(gb_exprs)):
                        v1 = gb_exprs[i].free_symbols
                        other_gens = gb_exprs[:i] + gb_exprs[i+1:]
                        v_other = set()
                        for g in other_gens:
                            v_other.update(g.free_symbols)
                        
                        # If one generator is disjoint from all others, and either it has >= 2 variables
                        # or one of the other generators has >= 2 variables, it's a counterexample.
                        if v1.is_disjoint(v_other):
                            eff_len1 = len(v1) if len(v1) > 0 else 1
                            if eff_len1 >= 2 or any(len(g.free_symbols) >= 2 for g in other_gens):
                                neg_q = True
                                break
                                
        return [h1, neg_q]
    except Exception:
        return [False, False]

