import sympy
from sympy.abc import x, y, z

def conditions(witness) -> list[bool]:
    # H1: R is an integral domain
    # We restrict the witness to be an element of Z or Z[x, y, z],
    # which are well-known integral domains.
    try:
        if isinstance(witness, (int, sympy.Integer)):
            h1 = True
        elif isinstance(witness, sympy.Expr):
            p = sympy.poly(witness)
            h1 = (p.domain == sympy.ZZ)
        else:
            h1 = False
    except Exception:
        h1 = False

    # H2: p is a non-zero, non-unit element of R
    # In Z and Z[x, y, z], the only units are 1 and -1.
    try:
        if isinstance(witness, (int, sympy.Integer)):
            h2 = witness != 0 and abs(witness) != 1
        elif isinstance(witness, sympy.Expr):
            h2 = witness != 0 and witness != 1 and witness != -1
        else:
            h2 = False
    except Exception:
        h2 = False

    # neg_Q: The principal ideal generated by p is NOT a prime ideal of R
    # In a UFD like Z or Z[x, y, z], a principal ideal (p) is prime iff p is prime (irreducible).
    # Thus, the ideal is NOT prime if the element factors into multiple non-units.
    try:
        if isinstance(witness, (int, sympy.Integer)):
            neg_q = not sympy.isprime(abs(int(witness)))
        elif isinstance(witness, sympy.Expr):
            factors = sympy.factor_list(witness)
            num_factors = 0
            
            # Check the constant content factor
            c = abs(factors[0])
            if c > 1:
                if not sympy.isprime(c):
                    num_factors += 2  # Composite content contributes at least 2 prime factors
                else:
                    num_factors += 1  # Prime content contributes 1 prime factor
                    
            # Check the polynomial factors
            for f, mult in factors[1]:
                num_factors += mult
                
            neg_q = num_factors > 1
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

