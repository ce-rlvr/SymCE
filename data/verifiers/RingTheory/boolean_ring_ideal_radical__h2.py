def extract_witness(witness):
    if isinstance(witness, tuple):
        if len(witness) == 5:
            return witness
        elif len(witness) == 2:
            R, I = witness
            if hasattr(R, 'elements') and hasattr(R, 'add') and hasattr(R, 'mul') and hasattr(R, 'zero'):
                return R.elements, R.add, R.mul, R.zero, I
            elif isinstance(R, dict):
                return R['elements'], R['add'], R['mul'], R['zero'], I
    elif isinstance(witness, dict):
        return witness['elements'], witness['add'], witness['mul'], witness['zero'], witness['I']
    elif hasattr(witness, 'elements') and hasattr(witness, 'add') and hasattr(witness, 'mul') and hasattr(witness, 'zero') and hasattr(witness, 'I'):
        return witness.elements, witness.add, witness.mul, witness.zero, witness.I
    raise ValueError("Unrecognized witness format")

def is_boolean_ring(elements, add, mul, zero):
    try:
        elements_set = set(elements)
    except TypeError:
        return False
    
    if len(elements_set) == 0: return False
    if zero not in elements_set: return False
    
    for x in elements_set:
        if add(x, zero) != x or add(zero, x) != x:
            return False
        if mul(x, x) != x:
            return False
            
    for x in elements_set:
        has_inverse = False
        for y in elements_set:
            if add(x, y) == zero and add(y, x) == zero:
                has_inverse = True
                break
        if not has_inverse:
            return False
            
    for x in elements_set:
        for y in elements_set:
            s = add(x, y)
            p = mul(x, y)
            if s not in elements_set: return False
            if p not in elements_set: return False
            if s != add(y, x): return False
            
            for z in elements_set:
                if add(s, z) != add(x, add(y, z)): return False
                if mul(p, z) != mul(x, mul(y, z)): return False
                if mul(x, add(y, z)) != add(mul(x, y), mul(x, z)): return False
                if mul(add(x, y), z) != add(mul(x, z), mul(y, z)): return False
                
    return True

def conditions(witness) -> list[bool]:
    try:
        elements, add, mul, zero, I = extract_witness(witness)
    except Exception:
        return [False, False]
        
    try:
        h1 = is_boolean_ring(elements, add, mul, zero)
    except Exception:
        h1 = False
        
    try:
        if not set(I).issubset(set(elements)):
            neg_q = False
        else:
            # Compute the ideal generated by I
            ideal = set(I)
            ideal.add(zero)
            changed = True
            while changed:
                changed = False
                new_elements = set()
                for x in ideal:
                    for y in ideal:
                        s = add(x, y)
                        if s not in ideal and s not in new_elements:
                            new_elements.add(s)
                    for r in elements:
                        p1 = mul(r, x)
                        if p1 not in ideal and p1 not in new_elements:
                            new_elements.add(p1)
                        p2 = mul(x, r)
                        if p2 not in ideal and p2 not in new_elements:
                            new_elements.add(p2)
                if new_elements:
                    ideal.update(new_elements)
                    changed = True
                    
            # Compute the radical of the generated ideal
            rad = set()
            for x in elements:
                curr = x
                in_ideal = False
                for _ in range(1, len(elements) + 2):
                    if curr in ideal:
                        in_ideal = True
                        break
                    curr = mul(curr, x)
                if in_ideal:
                    rad.add(x)
                    
            # The conclusion fails if the radical of I is not equal to I
            neg_q = (set(I) != rad)
    except Exception:
        neg_q = False
        
    return [h1, neg_q]

