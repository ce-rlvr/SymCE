# Top-level setup: Named finite rings that might be used in witnesses
class Z2Ring:
    elements = [0, 1]
    zero = 0
    @staticmethod
    def add(x, y): return (x + y) % 2
    @staticmethod
    def mul(x, y): return (x * y) % 2

