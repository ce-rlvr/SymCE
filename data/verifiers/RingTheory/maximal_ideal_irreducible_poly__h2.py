import sympy
from sympy.combinatorics import SymmetricGroup, CyclicGroup
from sympy.matrices import eye
from sympy import Poly, QQ, ZZ
from sympy.abc import x, y, z

# Top-level setup
S3 = SymmetricGroup(3)
Z2 = CyclicGroup(2)
I2 = eye(2)

def conditions(witness) -> list[bool]:
    """
    Check if the witness is a valid counterexample to the false conjecture.
    The witness is expected to be a tuple (F, f) where F is a SymPy domain 
    (e.g., QQ, ZZ) and f is a polynomial expression.
    """
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            F, f = witness
        else:
            F = QQ
            f = witness
    except Exception:
        return [False, False, False]
        
    try:
        expr = f.as_expr() if hasattr(f, 'as_expr') else f
    except Exception:
        expr = f

    # H1: Let F be a field.
    try:
        h1 = bool(F.is_Field)
    except Exception:
        h1 = False
        
    # H2: Let f(x) be an irreducible polynomial over F.
    try:
        symbols = list(expr.free_symbols) if hasattr(expr, 'free_symbols') else []
        if not symbols:
            p = Poly(expr, x, domain=F)
        else:
            symbols = sorted(symbols, key=lambda s: s.name)
            p = Poly(expr, *symbols, domain=F)
        h2 = bool(p.is_irreducible)
    except Exception:
        h2 = False
        
    # neg_Q: The principal ideal (f(x)) is NOT a maximal ideal in F[x].
    # In F[vars], an ideal generated by an irreducible polynomial is maximal iff there is exactly 1 variable.
    try:
        symbols = list(expr.free_symbols) if hasattr(expr, 'free_symbols') else []
        if not symbols:
            is_maximal = False
        else:
            symbols = sorted(symbols, key=lambda s: s.name)
            p = Poly(expr, *symbols, domain=F)
            is_maximal = bool(F.is_Field and p.is_irreducible and len(symbols) == 1)
        neg_q = not is_maximal
    except Exception:
        neg_q = True
        
    return [h1, h2, neg_q]

