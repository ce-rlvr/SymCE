import sympy
from sympy import Poly
from sympy.abc import x

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, Poly):
            f = witness
        else:
            witness_expr = sympy.sympify(witness)
            free = list(witness_expr.free_symbols)
            if not free:
                f = Poly(witness_expr, x)
            else:
                free.sort(key=lambda s: s.name)
                f = Poly(witness_expr, free[0])
    except Exception:
        return [False, False]
        
    try:
        h1 = bool(not f.is_zero)
    except Exception:
        h1 = False
        
    try:
        coeffs = f.coeffs()
        dom = f.domain
        
        has_generator = False
        for c in coeffs:
            c_divides_all = True
            for d in coeffs:
                try:
                    q = dom.exquo(d, c)
                    if dom.mul(q, c) != d:
                        c_divides_all = False
                        break
                except Exception:
                    c_divides_all = False
                    break
            
            if c_divides_all:
                has_generator = True
                break
                
        neg_q = bool(not has_generator)
    except Exception:
        neg_q = False
        
    return [h1, neg_q]

