import sympy as sp
from sympy.abc import x, y
from sympy.ntheory import factorint

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "If x_1, ..., x_d is an M-regular sequence of length d (where d is the Krull dimension of R),
    then the ideal generated by the sequence is an M-primary ideal."
    
    The conjecture is false because it drops the hypothesis that R is a local ring.
    
    Expected witness formats:
    1. An integer `n` (interpreted as R=Z, d=1, seq=[n])
    2. A list of integers (interpreted as R=Z, d=len(seq), seq=seq)
    3. A dictionary specifying the ring, d, and seq. Supported rings: 'Z', 'Q[x]', 'Q[x,y]'.
       Example: {'ring': 'Z', 'd': 1, 'seq': [6]}
       Example: {'ring': 'Q[x,y]', 'd': 2, 'seq': [x*(x-1), y]}
    """
    try:
        if isinstance(witness, dict):
            ring = witness.get('ring', 'Z')
            d = witness.get('d', 1)
            seq = witness.get('seq', [])
            M = witness.get('M', ring)
        elif isinstance(witness, list):
            ring = 'Z'
            d = len(witness)
            seq = witness
            M = 'Z'
        elif isinstance(witness, int):
            ring = 'Z'
            d = 1
            seq = [witness]
            M = 'Z'
        else:
            return [False, False, False]

        # We only support the case where the module M is the ring R itself
        if M != ring:
            return [False, False, False]

        if ring == 'Z':
            # H1: d is the Krull dimension of R (dim Z = 1)
            h1 = (d == 1)
            
            if len(seq) != d:
                h2 = False
                neg_q = False
            else:
                if d == 1:
                    try:
                        n = int(seq[0])
                    except (ValueError, TypeError):
                        return [False, False, False]
                        
                    # H2: seq is a regular sequence of length 1 in Z
                    # This means n is not a zero divisor (n != 0) and generates a proper ideal (abs(n) != 1)
                    h2 = (n != 0 and abs(n) != 1)
                    
                    # neg_Q: The ideal (n) is NOT primary
                    # In Z, (n) is primary iff n=0 or abs(n) is a prime power
                    n_abs = abs(n)
                    if n_abs == 1:
                        is_primary = False
                    elif n_abs == 0:
                        is_primary = True
                    else:
                        factors = factorint(n_abs)
                        is_primary = (len(factors) == 1)
                    neg_q = not is_primary
                else:
                    h2 = False
                    neg_q = False
                
            return [h1, h2, neg_q]
            
        elif ring == 'Q[x]':
            # H1: d is the Krull dimension of R (dim Q[x] = 1)
            h1 = (d == 1)
            
            if len(seq) != d:
                return [h1, False, False]
                
            f = sp.sympify(seq[0])
            if not f.free_symbols.issubset({x}):
                return [False, False, False]
            
            # H2: regular sequence of length 1 (non-zero, proper ideal)
            if f == 0:
                h2 = False
            else:
                h2 = not f.is_number
                
            # neg_Q: ideal is NOT primary
            # In Q[x], (f) is primary iff f is a power of an irreducible polynomial
            if f.is_number:
                is_primary = False
            elif f == 0:
                is_primary = True
            else:
                factors = sp.factor_list(f)[1]
                is_primary = (len(factors) == 1)
                
            neg_q = not is_primary
            return [h1, h2, neg_q]
            
        elif ring == 'Q[x,y]':
            # H1: d is the Krull dimension of R (dim Q[x,y] = 2)
            h1 = (d == 2)
            
            if len(seq) != d:
                return [h1, False, False]
                
            f, g = sp.sympify(seq[0]), sp.sympify(seq[1])
            if not (f.free_symbols | g.free_symbols).issubset({x, y}):
                return [False, False, False]
            
            # H2: regular sequence of length 2
            if f == 0:
                h2 = False
            else:
                gcd_fg = sp.gcd(f, g)
                if not gcd_fg.is_number:
                    h2 = False
                else:
                    gb = sp.groebner([f, g], x, y, domain='QQ')
                    h2 = (list(gb) != [1])
                    
            # neg_Q: ideal is NOT primary
            # For a 0-dimensional ideal in Q[x,y], if all roots are rational, 
            # it is primary iff there is exactly 1 root.
            sols = sp.solve([f, g], (x, y), dict=True)
            all_rational = True
            for sol in sols:
                for var, val in sol.items():
                    if not val.is_rational:
                        all_rational = False
                        
            if all_rational:
                is_primary = (len(sols) == 1)
            else:
                # Conservative fallback to avoid false positives on irrational roots
                is_primary = True
                
            neg_q = not is_primary
            return [h1, h2, neg_q]
            
        else:
            return [False, False, False]
            
    except Exception:
        return [False, False, False]

