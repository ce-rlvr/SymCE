def extract_witness(witness):
    if isinstance(witness, dict):
        return witness.get('add'), witness.get('mul'), witness.get('I')
    elif isinstance(witness, (list, tuple)) and len(witness) == 3:
        return witness[0], witness[1], witness[2]
    else:
        return getattr(witness, 'add', None), getattr(witness, 'mul', None), getattr(witness, 'I', None)

def is_boolean_ring(add, mul):
    try:
        add = list(add)
        mul = list(mul)
        n = len(add)
        if n == 0: return False
        if len(mul) != n: return False
        for row in add + mul:
            if len(row) != n: return False
            for x in row:
                if type(x) is not int or not (0 <= x < n): return False
                
        # Find zero
        zero = -1
        for i in range(n):
            if all(add[i][j] == j for j in range(n)) and all(add[j][i] == j for j in range(n)):
                zero = i
                break
        if zero == -1: return False
        
        for i in range(n):
            # inverse
            if not any(add[i][j] == zero for j in range(n)): return False
            for j in range(n):
                if add[i][j] != add[j][i]: return False
                for k in range(n):
                    if add[add[i][j]][k] != add[i][add[j][k]]: return False
                    if mul[mul[i][j]][k] != mul[i][mul[j][k]]: return False
                    if mul[i][add[j][k]] != add[mul[i][j]][mul[i][k]]: return False
                    if mul[add[i][j]][k] != add[mul[i][k]][mul[j][k]]: return False
                    
        # Boolean property
        for i in range(n):
            if mul[i][i] != i: return False
            
        return True
    except Exception:
        return False

def conditions(witness) -> list[bool]:
    H1 = False
    neg_Q = False
    
    try:
        add, mul, I = extract_witness(witness)
        if add is not None and mul is not None and I is not None:
            H1 = is_boolean_ring(add, mul)
            
            if H1:
                n = len(add)
                I_set = set(I)
                
                if not all(type(x) is int and 0 <= x < n for x in I_set):
                    return [H1, False]
                
                # Find zero
                zero = -1
                for i in range(n):
                    if all(add[i][j] == j for j in range(n)):
                        zero = i
                        break
                        
                # I^2 generators
                generators = set()
                for x in I_set:
                    for y in I_set:
                        generators.add(mul[x][y])
                        
                # Ideal generated by generators
                ideal = set(generators)
                if zero != -1:
                    ideal.add(zero)
                    
                changed = True
                while changed:
                    changed = False
                    new_elements = set()
                    for x in ideal:
                        for r in range(n):
                            new_elements.add(mul[r][x])
                            new_elements.add(mul[x][r])
                    for x in ideal:
                        for y in ideal:
                            new_elements.add(add[x][y])
                    if not new_elements.issubset(ideal):
                        ideal.update(new_elements)
                        changed = True
                        
                neg_Q = (I_set != ideal)
    except Exception:
        pass
        
    return [H1, neg_Q]

