import sympy
from sympy import Symbol
from sympy.polys.domains import ZZ, QQ
from sympy.polys.domains.domain import Domain

# Top-level setup: named object bindings that the witness expression may reference.
x = Symbol('x')
y = Symbol('y')
z = Symbol('z')

# Common rings that might be used as witnesses
Z_x = ZZ[x]
Q_x = QQ[x]
Q_x_y = QQ[x, y]
Z_x_y = ZZ[x, y]

def conditions(witness) -> list[bool]:
    # H_1: R is an integral domain
    try:
        if isinstance(witness, Domain):
            # In SymPy, most Domain objects are integral domains.
            # The main exception that could have zero divisors is IntegerModRing for composite moduli.
            if witness.__class__.__name__ == 'IntegerModRing':
                from sympy import isprime
                h1_ok = bool(isprime(witness.mod))
            else:
                h1_ok = True
        else:
            h1_ok = False
    except Exception:
        h1_ok = False

    # ¬Q: Every ideal in R is NOT generated by a single element (i.e., R is NOT a PID)
    try:
        if hasattr(witness, 'is_PID'):
            # We specifically check for False to ensure it's known not to be a PID
            neg_q_ok = (witness.is_PID is False)
        else:
            neg_q_ok = False
    except Exception:
        neg_q_ok = False

    return [h1_ok, neg_q_ok]

