def get_vars(S, f):
    vars_set = set()
    for p in S:
        vars_set.update(sympy.sympify(p).free_symbols)
    vars_set.update(sympy.sympify(f).free_symbols)
    if not vars_set:
        vars_set.add(sympy.Symbol('x'))
    return sorted(list(vars_set), key=lambda var: var.name)

def conditions(witness):
    try:
        S, f = witness
    except Exception:
        return [False, False, False]
        
    try:
        S = [sympy.sympify(p) for p in S]
        f = sympy.sympify(f)
        vars = get_vars(S, f)
    except Exception:
        return [False, False, False]
        
    # H1: k is a field
    # We assume the domain of the provided polynomials is over a field (e.g., QQ),
    # which sympy's groebner basis algorithm will use by default.
    h1_ok = True
    
    # H2: I is an ideal generated by a set of monomials
    # An ideal is a monomial ideal iff its reduced Groebner basis consists of monomials.
    try:
        if not S:
            h2_ok = True
        else:
            GB = sympy.groebner(S, *vars)
            h2_ok = True
            for g in GB:
                poly = sympy.Poly(g, vars)
                if len(poly.terms()) > 1:
                    h2_ok = False
                    break
    except Exception:
        h2_ok = False
        
    # neg_Q: The conclusion fails
    # Conclusion: f in I iff every monomial term of f is a multiple of at least one of the monomials generating I.
    try:
        if not S:
            f_in_I = sympy.Poly(f, vars).is_zero
        else:
            GB = sympy.groebner(S, *vars)
            rem = sympy.reduced(f, list(GB), *vars)[1]
            f_in_I = sympy.Poly(rem, vars).is_zero
            
        # Extract the monomials from the given generating set S
        M_monoms = []
        for m in S:
            poly_m = sympy.Poly(m, vars)
            if len(poly_m.terms()) == 1:
                M_monoms.append(poly_m.monoms()[0])
                
        # Extract the terms of f
        poly_f = sympy.Poly(f, vars)
        f_terms = poly_f.monoms()
        
        # Check if every term of f is a multiple of at least one monomial in S
        if poly_f.is_zero:
            rhs = True
        else:
            rhs = True
            for t_exp in f_terms:
                is_mult = False
                for m_exp in M_monoms:
                    if all(t_e >= m_e for t_e, m_e in zip(t_exp, m_exp)):
                        is_mult = True
                        break
                if not is_mult:
                    rhs = False
                    break
                
        conclusion = (f_in_I == rhs)
        neg_q = not conclusion
    except Exception:
        neg_q = False
        
    return [h1_ok, h2_ok, neg_q]

