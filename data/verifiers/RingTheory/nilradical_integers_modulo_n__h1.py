def extract_n(witness):
    """Helper to extract the integer n from various possible witness formats."""
    if isinstance(witness, dict):
        if 'n' in witness:
            return int(witness['n'])
    elif isinstance(witness, (tuple, list)):
        if len(witness) > 0:
            return int(witness[0])
    return int(witness)

def conditions(witness) -> list[bool]:
    try:
        n = extract_n(witness)
    except Exception:
        return [False, False, False]
        
    # H_1: R is the quotient ring Z/nZ
    # This hypothesis sets the context. As long as n is a valid integer, it holds.
    h1 = True
    
    # H_2: p_1, p_2, ..., p_k are the distinct prime divisors of n
    # This is a declarative hypothesis setting up the variables for the conclusion.
    # We evaluate it as True for any valid integer witness.
    h2 = True
    
    try:
        # The theorem states that the nilradical of Z/nZ is generated by the product 
        # of its distinct prime factors. This is mathematically TRUE for all n != 0.
        # However, for n = 0, Z/0Z is isomorphic to Z. The nilradical of Z is {0}.
        # The prime divisors of 0 are all primes (an infinite set), so the finite product 
        # p_1 * p_2 * ... * p_k is undefined, and the conclusion fails.
        if n == 0:
            neg_q = True
        else:
            neg_q = False
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

