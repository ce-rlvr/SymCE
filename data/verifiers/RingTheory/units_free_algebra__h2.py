import sympy
from sympy import QQ, ZZ, RR, CC, Symbol, symbols
from sympy.polys.rings import PolyRing

def conditions(witness):
    try:
        if isinstance(witness, dict):
            k = witness.get('k')
            X = witness.get('X')
            kX = witness.get('kX')
            u = witness.get('u')
            v = witness.get('v')
        else:
            u = witness
            v = None
            kX = getattr(u, 'ring', None)
            k = getattr(kX, 'domain', None)
            X = getattr(kX, 'symbols', None)
    except Exception:
        return [False, False, False, False]

    # H1: k is a field
    try:
        h1 = bool(k.is_Field)
    except Exception:
        h1 = False

    # H2: k<X> is the free associative algebra over k generated by X
    try:
        if not isinstance(X, (list, tuple, set)):
            X_set = {X}
        else:
            X_set = set(X)
            
        if hasattr(kX, 'symbols'):
            X_names = {str(x) for x in X_set}
            kX_names = {str(x) for x in kX.symbols}
        else:
            X_names = set()
            kX_names = set()
            
        if isinstance(kX, PolyRing):
            h2 = (kX.domain == k) and (X_names == kX_names)
        else:
            h2 = False
    except Exception:
        h2 = False

    # H3: u \in k<X>
    try:
        if u in kX or (hasattr(kX, 'dtype') and isinstance(u, kX.dtype)):
            h3 = True
        else:
            try:
                u = kX(u)
                h3 = True
            except Exception:
                h3 = False
    except Exception:
        h3 = False

    # neg_Q: not (u is a unit in k<X> iff u is a non-zero scalar in k)
    try:
        def check_scalar(u_val):
            if u_val == kX.zero:
                return False
            if hasattr(u_val, 'terms'):
                for monom, coeff in u_val.terms():
                    if sum(monom) > 0:
                        return False
                return True
            if hasattr(u_val, 'is_ground'):
                return u_val.is_ground
            if u_val in k:
                return True
            return False

        u_is_nonzero_scalar = check_scalar(u)

        u_is_unit = False
        if v is not None and v in kX:
            if (u * v == kX.one) and (v * u == kX.one):
                u_is_unit = True
        else:
            try:
                inv = kX.revert(u)
                u_is_unit = True
            except Exception:
                try:
                    inv = ~u
                    u_is_unit = True
                except Exception:
                    try:
                        inv = kX.one / u
                        if inv in kX:
                            u_is_unit = True
                    except Exception:
                        u_is_unit = u_is_nonzero_scalar

        neg_q = not (u_is_unit == u_is_nonzero_scalar)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

