import sympy
from sympy import symbols

# Top-level setup
x, y, z = symbols('x y z')
x1, x2, x3, x4 = symbols('x1 x2 x3 x4')

def conditions(witness) -> list[bool]:
    # H1: R is a commutative ring
    # We assume the coefficients of the sympy expressions belong to a commutative ring.
    try:
        h1 = True
    except Exception:
        h1 = False

    # H2: I is an ideal of the polynomial ring
    # A list of polynomials naturally generates an ideal.
    try:
        h2 = isinstance(witness, list)
        gens = set()
        if h2:
            for p in witness:
                try:
                    if hasattr(p, 'free_symbols'):
                        gens.update(p.free_symbols)
                except Exception:
                    pass
        gens = sorted(list(gens), key=lambda s: s.name)
        if not gens:
            gens = [x]
            
        if h2:
            for p in witness:
                if p != 0:
                    # This will raise an exception if p is not a valid polynomial
                    _ = sympy.poly(p, *gens)
    except Exception:
        h2 = False

    # H3: I is generated by a set of homogeneous polynomials
    try:
        h3 = True
        if h2:
            for p in witness:
                if p != 0:
                    poly_p = sympy.poly(p, *gens)
                    if not poly_p.is_homogeneous:
                        h3 = False
                        break
        else:
            h3 = False
    except Exception:
        h3 = False

    # ¬Q: The factor ring R/I does NOT naturally inherit the structure of a graded R-algebra.
    # A graded R-algebra S requires S_0 = R (or at least an injective structure map R -> S).
    # If the ideal contains a non-zero constant, I_0 != 0, so S_0 = R/I_0 != R, breaking the R-algebra structure.
    # Also, if the ideal is not homogeneous, it doesn't inherit a grading at all.
    try:
        neg_q = False
        if h2:
            is_homog_ideal = True
            has_nonzero_const = False
            for p in witness:
                if p != 0:
                    poly_p = sympy.poly(p, *gens)
                    if not poly_p.is_homogeneous:
                        is_homog_ideal = False
                    if poly_p.is_constant():
                        has_nonzero_const = True
            
            if not is_homog_ideal or has_nonzero_const:
                neg_q = True
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

