def _make_ideal(R, gens):
    if not gens:
        try:
            return R.ideal()
        except Exception:
            return R.ideal(R.zero)
    return R.ideal(*gens)

def conditions(witness):
    """
    Checks the hypotheses and the negated conclusion for the conjecture.
    The witness is expected to contain (R, I, J, S, T) where:
      - R is a commutative ring
      - I, J are ideals of R
      - S, T are sets (or lists) of generators for I and J respectively
    """
    # Extract R, I, J, S, T
    if isinstance(witness, dict):
        R = witness.get('R')
        I = witness.get('I')
        J = witness.get('J')
        S = witness.get('S')
        T = witness.get('T')
    elif hasattr(witness, 'R') and hasattr(witness, 'I'):
        R = witness.R
        I = witness.I
        J = witness.J
        S = witness.S
        T = witness.T
    else:
        try:
            R, I, J, S, T = witness
        except Exception:
            return [False, False, False, False]

    # H1: R is a commutative ring
    try:
        if hasattr(R, 'is_commutative'):
            h1 = bool(R.is_commutative)
        else:
            # Fallback: assume it's a commutative ring if it supports ideal creation
            h1 = hasattr(R, 'ideal')
    except Exception:
        h1 = False

    # H2: I is the ideal generated by S
    try:
        ideal_S = _make_ideal(R, S)
        h2 = bool(I == ideal_S)
    except Exception:
        h2 = False

    # H3: J is the ideal generated by T
    try:
        ideal_T = _make_ideal(R, T)
        h3 = bool(J == ideal_T)
    except Exception:
        h3 = False

    # neg_Q: The product ideal IJ is NOT generated by the set {st | s in S, t in T}
    try:
        ST = [s * t for s in S for t in T]
        ideal_ST = _make_ideal(R, ST)
        
        try:
            # Try to use the overloaded multiplication if available
            IJ = I * J
            # Verify it's actually an ideal by checking if it can be compared
            _ = (IJ == ideal_ST)
        except Exception:
            # Fallback: manually compute the product ideal from generators
            if not (hasattr(I, 'gens') or hasattr(I, 'generators')):
                raise ValueError("I has no generators")
            if not (hasattr(J, 'gens') or hasattr(J, 'generators')):
                raise ValueError("J has no generators")
            gens_I = getattr(I, 'gens', getattr(I, 'generators', []))
            gens_J = getattr(J, 'gens', getattr(J, 'generators', []))
            IJ_gens = [i * j for i in gens_I for j in gens_J]
            IJ = _make_ideal(R, IJ_gens)
            
        neg_q = bool(IJ != ideal_ST)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

