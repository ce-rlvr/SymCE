import math
from sympy import ZZ

# Top-level setup
# For this ring theory conjecture, ZZ (the ring of integers) is the standard Dedekind domain.
# No other special bindings are strictly necessary.

CONDITION_LABELS = [
    "H_1: R is a Dedekind domain",
    "H_2: I is a non-zero proper ideal of R",
    "¬Q: R/I is not isomorphic to the direct product of R/P_i^{e_i}"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness) -> list[bool]:
    """
    Evaluates the hypotheses and the negated conclusion for the given witness.
    The witness is expected to provide the ring R, the ideal I, and the sequence of prime ideals and exponents.
    Format examples:
      witness = {'R': 'ZZ', 'I': 4, 'P_e_list': [(2, 1), (2, 1)]}
      witness = ('ZZ', 4, [(2, 1), (2, 1)])
    """
    try:
        R_name = 'ZZ'
        I_val = None
        P_e_list = []
        
        # Parse witness
        if isinstance(witness, dict):
            R_name = witness.get('R', 'ZZ')
            I_val = witness.get('I')
            P_e_list = witness.get('P_e_list', witness.get('factorization', witness.get('factors', [])))
        elif isinstance(witness, tuple):
            if len(witness) == 3:
                R_name, I_val, P_e_list = witness
            elif len(witness) == 2:
                I_val, P_e_list = witness
            elif len(witness) == 1:
                I_val = witness[0]
        else:
            I_val = witness
            
        # Extract generator if a sympy ideal object was passed
        if hasattr(I_val, 'gen'):
            I_val = I_val.gen
        elif hasattr(I_val, 'gens') and len(I_val.gens) == 1:
            I_val = I_val.gens[0]
            
        # H_1: R is a Dedekind domain
        # We support ZZ (integers) as the primary Dedekind domain for counterexamples
        h1 = False
        try:
            if R_name in ['ZZ', 'Z', int, ZZ] or str(R_name) in ['ZZ', 'Z', 'Integers']:
                h1 = True
        except Exception:
            pass
            
        # H_2: I is a non-zero proper ideal of R
        # In ZZ, a proper non-zero ideal is generated by an integer with absolute value > 1
        h2 = False
        try:
            I_abs = abs(int(I_val))
            if I_abs > 1:
                h2 = True
        except Exception:
            pass
            
        # ¬Q: R/I is NOT isomorphic to the direct product of R/P_i^{e_i}
        neg_q = False
        try:
            m_list = []
            for item in P_e_list:
                if isinstance(item, (tuple, list)) and len(item) == 2:
                    p, e = item
                    if hasattr(p, 'gen'): p = p.gen
                    elif hasattr(p, 'gens') and len(p.gens) == 1: p = p.gens[0]
                    m_list.append(abs(int(p))**int(e))
                else:
                    p = item
                    if hasattr(p, 'gen'): p = p.gen
                    elif hasattr(p, 'gens') and len(p.gens) == 1: p = p.gens[0]
                    m_list.append(abs(int(p)))
            
            prod = 1
            for m in m_list:
                prod *= m
            
            # For ZZ, Z/nZ is isomorphic to prod Z/m_iZ iff n == prod m_i and m_i are pairwise coprime
            if I_abs != prod:
                neg_q = True
            else:
                isomorphic = True
                for i in range(len(m_list)):
                    for j in range(i + 1, len(m_list)):
                        if math.gcd(m_list[i], m_list[j]) > 1:
                            isomorphic = False
                            break
                    if not isomorphic:
                        break
                neg_q = not isomorphic
        except Exception:
            neg_q = False
            
        return [h1, h2, neg_q]
    except Exception:
        return [False, False, False]