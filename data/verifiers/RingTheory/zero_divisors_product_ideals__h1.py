# Top-level setup
# Witnesses for this conjecture are expected to be finite rings provided via their Cayley tables.
# A witness can be a tuple: (n, add_table, mul_table, I, J)
# where n is the size of the ring, add_table and mul_table are n x n lists of lists,
# and I, J are lists of integers representing the ideals.

def conditions(witness) -> list[bool]:
    try:
        # Extract ring data from witness
        if isinstance(witness, tuple) and len(witness) == 5:
            n, add_table, mul_table, I, J = witness
        elif hasattr(witness, 'n') and hasattr(witness, 'add_table'):
            n = witness.n
            add_table = witness.add_table
            mul_table = witness.mul_table
            I = witness.I
            J = witness.J
        else:
            return [False] * 5
            
        if not isinstance(n, int) or n < 2:
            return [False] * 5
            
        # Find the additive identity (zero)
        zero = None
        for i in range(n):
            if all(add_table[i][x] == x for x in range(n)):
                zero = i
                break
        if zero is None:
            return [False] * 5
            
        # Helper to check if a subset is a two-sided ideal
        def is_ideal(S):
            if not S: return False
            S_set = set(S)
            if zero not in S_set: return False
            # Closed under addition
            for a in S_set:
                for b in S_set:
                    if add_table[a][b] not in S_set:
                        return False
            # Absorbing under left and right multiplication
            for s in S_set:
                for r in range(n):
                    if mul_table[s][r] not in S_set:
                        return False
                    if mul_table[r][s] not in S_set:
                        return False
            return True
            
        h1 = is_ideal(I)
        h2 = is_ideal(J)
        
        # Check if the product ideal IJ is the zero ideal
        # IJ is generated by {i*j | i in I, j in J}. It is the zero ideal iff all i*j == zero.
        h3 = True
        for i in I:
            for j in J:
                if mul_table[i][j] != zero:
                    h3 = False
                    break
            if not h3: break
            
        # Check if I is not the zero ideal
        h4 = any(i != zero for i in I)
        
        # Helper to check if an element is a two-sided zero-divisor
        # (In non-commutative rings, an element might be a right zero-divisor but not a left one)
        def is_zero_divisor(x):
            left_zd = False
            right_zd = False
            for y in range(n):
                if y != zero:
                    if mul_table[x][y] == zero:
                        left_zd = True
                    if mul_table[y][x] == zero:
                        right_zd = True
            return left_zd and right_zd
            
        # Check negated conclusion: There exists an element in J that is NOT a zero-divisor
        neg_q = False
        for j in J:
            if not is_zero_divisor(j):
                neg_q = True
                break
                
        return [bool(h1), bool(h2), bool(h3), bool(h4), bool(neg_q)]
    except Exception:
        return [False] * 5

