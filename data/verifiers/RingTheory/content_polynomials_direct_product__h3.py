def get_gcd(lst):
    if not lst:
        return 0
    return abs(reduce(math.gcd, [int(x) for x in lst]))

def conditions(witness) -> list[bool]:
    h1 = False
    h2 = False
    neg_q = False
    
    try:
        # Handle abstract dictionary witness
        if isinstance(witness, dict):
            h1 = witness.get('R1_R2_comm_rings_with_id', False)
            h2 = witness.get('R_is_direct_product', False)
            neg_q = witness.get('neg_Q', False)
            if not neg_q and 'c_f_eq_direct_product' in witness:
                neg_q = not witness['c_f_eq_direct_product']
            return [h1, h2, neg_q]
            
        # Handle concrete witness represented as tuples of coefficient lists
        # e.g., witness = (coeffs_f, coeffs_f1, coeffs_f2)
        # where coeffs_f is a list of pairs (a, b) representing coefficients in Z x Z
        coeffs_f, coeffs_f1, coeffs_f2 = None, None, None
        
        if isinstance(witness, tuple):
            if len(witness) == 3:
                coeffs_f, coeffs_f1, coeffs_f2 = witness
            elif len(witness) == 5:
                _, _, coeffs_f, coeffs_f1, coeffs_f2 = witness
                
        if isinstance(coeffs_f, list) and isinstance(coeffs_f1, list) and isinstance(coeffs_f2, list):
            if all(isinstance(c, tuple) and len(c) == 2 for c in coeffs_f):
                # If we are working with Z x Z, it is a direct product of commutative rings with identity
                h1 = True
                h2 = True
                
                # The content ideal in Z is generated by the GCD of the coefficients.
                # In Z x Z, the ideal is I1 x I2 where I1 and I2 are the respective GCDs.
                gcd_f_1 = get_gcd([c[0] for c in coeffs_f])
                gcd_f_2 = get_gcd([c[1] for c in coeffs_f])
                
                gcd_f1 = get_gcd(coeffs_f1)
                gcd_f2 = get_gcd(coeffs_f2)
                
                # The conclusion fails if the content ideal of f is NOT the direct product
                # of the content ideals of f1 and f2.
                neg_q = (gcd_f_1 != gcd_f1) or (gcd_f_2 != gcd_f2)
                
    except Exception:
        pass

    return [h1, h2, neg_q]

