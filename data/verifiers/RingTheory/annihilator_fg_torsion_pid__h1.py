import sympy
from sympy import symbols, Rational, Integer, Matrix, Expr
from sympy.abc import x, y, z, t, u, v, w

# Top-level setup
# The witness is expected to be a list of polynomials generating an ideal I in a polynomial ring R.
# The module is M = R/I, which is finitely generated (cyclic).
# The annihilator of M is Ann(M) = I.

def conditions(witness) -> list[bool]:
    # Parse the witness into a list of SymPy expressions representing the generators of Ann(M)
    try:
        if isinstance(witness, str):
            witness = sympy.sympify(witness)
            
        if isinstance(witness, Expr):
            exprs = [witness]
        elif hasattr(witness, 'args') and type(witness).__name__ in ('Ideal', 'Tuple'):
            exprs = list(witness.args)
        elif isinstance(witness, (list, tuple, set)):
            exprs = [sympy.sympify(w) for w in witness]
        else:
            try:
                exprs = [sympy.sympify(w) for w in witness]
            except TypeError:
                exprs = [sympy.sympify(witness)]
            
        if not exprs:
            return [False, False, False]
            
        # H_1: M is a finitely generated module over R
        # M = R/I is generated by 1 element, so it is always finitely generated.
        h1 = True
    except Exception:
        return [False, False, False]
        
    # H_2: M is a torsion module
    # M = R/I is a torsion module iff I contains a regular element.
    # In an integral domain (like QQ[vars] or ZZ[vars]), this is true iff I is not the zero ideal.
    try:
        h2 = any(e != 0 for e in exprs)
    except Exception:
        h2 = False
        
    # neg_Q: Ann(M) is not a non-zero principal ideal
    # Ann(M) = I. We check if I is a non-zero principal ideal.
    try:
        free_syms = set()
        for e in exprs:
            free_syms.update(e.free_symbols)
        free_syms = list(free_syms)
        
        if not free_syms:
            # If there are no free symbols, it's an ideal in a field or ZZ.
            # All ideals in a field or ZZ are principal.
            non_zero = [e for e in exprs if e != 0]
            if not non_zero:
                # The zero ideal is not a NON-ZERO principal ideal.
                neg_q = True
            else:
                neg_q = False
        else:
            # Compute the Groebner basis to determine if the ideal is principal.
            # A principal ideal has a reduced Groebner basis of exactly 1 element.
            try:
                # Try over ZZ first to support counterexamples in ZZ[x]
                gb = sympy.groebner(exprs, *free_syms, domain='ZZ')
            except Exception:
                # Fall back to default domain (usually QQ)
                gb = sympy.groebner(exprs, *free_syms)
                
            non_zero_gb = [g for g in gb if g != 0]
            neg_q = len(non_zero_gb) != 1
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

