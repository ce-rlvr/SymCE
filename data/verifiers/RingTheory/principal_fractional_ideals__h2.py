import sympy
from sympy import S

Z = S.Integers
Q = S.Rationals

def conditions(witness) -> list[bool]:
    h1 = False
    h2 = False
    neg_q = False
    
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            R, M = witness
        else:
            R = Z
            M = witness
            
        # Check H1: R is a PID
        is_field = False
        if R == Z or str(R) in ['Z', 'ZZ', 'Integers', 'sympy.S.Integers']:
            h1 = True
        elif R == Q or str(R) in ['Q', 'QQ', 'Rationals', 'sympy.S.Rationals']:
            h1 = True
            is_field = True
        elif hasattr(R, 'is_Field') and R.is_Field:
            h1 = True
            is_field = True
        elif hasattr(R, 'is_PID') and R.is_PID:
            h1 = True
        elif hasattr(R, 'domain') and hasattr(R, 'gens'):
            if getattr(R.domain, 'is_Field', False) and len(R.gens) == 1:
                h1 = True
                
        # Check H2 and neg_Q
        if M == R or str(M) == str(R):
            h2 = True
            neg_q = False
        elif is_field:
            # Over a field, every non-zero fractional ideal is the field itself, generated by 1.
            pass
        else:
            if M == Q:
                h2 = True
                neg_q = True
            elif isinstance(M, sympy.Rational) and M != 0:
                h2 = True
                neg_q = False
            else:
                M_str = str(M).lower().strip()
                non_principal_ideals = {
                    'q', 'rationals', 'qq', 'field of fractions',
                    'z[1/2]', 'dyadic rationals', 'z[1/p]'
                }
                if M_str in non_principal_ideals:
                    h2 = True
                    neg_q = True
                elif hasattr(R, 'frac_field') and M == R.frac_field:
                    h2 = True
                    neg_q = True
                elif hasattr(M, 'is_fractional_ideal') and hasattr(M, 'is_principal'):
                    if M.is_fractional_ideal:
                        h2 = True
                    if not M.is_principal:
                        neg_q = True
                        
    except Exception:
        pass
        
    return [h1, h2, neg_q]

