import sympy
import math

# Top-level setup
ZZ = sympy.ZZ
QQ = sympy.QQ

def conditions(witness):
    n = None
    p_list = None
    R = None
    
    # Attempt to extract n, p_list, and R from the witness
    if isinstance(witness, dict):
        n = witness.get('n', None)
        p_list = witness.get('p_list', witness.get('p', None))
        R = witness.get('R', None)
    elif isinstance(witness, tuple):
        if len(witness) == 3:
            n, p_list, R = witness
        elif len(witness) == 2:
            if isinstance(witness[1], (list, set, tuple)):
                n, p_list = witness
            else:
                n, R = witness
    else:
        try:
            n = getattr(witness, 'n', None)
            p_list = getattr(witness, 'p_list', getattr(witness, 'p', None))
            R = getattr(witness, 'R', None)
        except Exception:
            pass
            
    if n is None:
        n = witness

    # H_1: n > 1 is an integer
    try:
        if hasattr(n, 'is_integer') and n.is_integer:
            n = int(n)
        elif isinstance(n, float) and n.is_integer():
            n = int(n)
        h1 = isinstance(n, int) and n > 1
    except Exception:
        h1 = False

    # H_2: p_1, p_2, ..., p_k are the distinct prime divisors of n
    try:
        if not h1:
            h2 = False
        else:
            actual_primes = sympy.primefactors(n)
            if p_list is None:
                h2 = True
                p_list = actual_primes
            else:
                p_list_ints = [int(p) for p in p_list]
                h2 = sorted(p_list_ints) == sorted(actual_primes)
    except Exception:
        h2 = False

    # neg_Q: The nilradical of R is NOT the principal ideal generated by the congruence class of the product p_1 p_2 ... p_k
    try:
        if not h1 or not h2:
            neg_q = False
        else:
            actual_primes = sympy.primefactors(n)
            if p_list is None:
                p_list_ints = actual_primes
            else:
                p_list_ints = [int(p) for p in p_list]
            product_p = math.prod(p_list_ints)
            
            # Parse string representations of rings
            if isinstance(R, str):
                s = R.replace(' ', '').replace('mathbb{Z}', 'Z').replace('_', '')
                if s.startswith('Z/') and s.endswith('Z'):
                    try:
                        R = int(s[2:-1])
                    except ValueError:
                        pass
                elif s in ("Z", "ZZ"):
                    R = sympy.ZZ
                elif s in ("Q", "QQ"):
                    R = sympy.QQ

            # Convert float/sympy integers to int for R
            if isinstance(R, float) and R.is_integer():
                R = int(R)
            elif hasattr(R, 'is_integer') and R.is_integer:
                try:
                    R = int(R)
                except Exception:
                    pass

            if R is None:
                # If R is not provided, we assume the intended ring was Z/nZ, where the conclusion holds.
                neg_q = False
            elif R == sympy.ZZ or R == sympy.S.Integers:
                # In ZZ, the nilradical is {0}. The ideal generated by product_p is product_p * ZZ.
                # Since product_p >= 2, they are not equal.
                neg_q = (product_p != 0)
            elif R == sympy.QQ or R == sympy.S.Rationals:
                # In QQ, the nilradical is {0}. The ideal generated by product_p is QQ.
                neg_q = True
            elif isinstance(R, int) and R > 0:
                # R represents the ring Z/RZ
                nil_gen = math.prod(sympy.primefactors(R))
                ideal_gen = math.gcd(product_p, R)
                # The ideals are equal iff their generators are equal modulo R
                neg_q = (ideal_gen != nil_gen)
            else:
                # For any other ring, if it's not explicitly Z/nZ, the conclusion generally fails.
                if R == n:
                    neg_q = False
                else:
                    neg_q = True
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

