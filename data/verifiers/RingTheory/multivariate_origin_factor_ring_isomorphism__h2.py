import sympy
from sympy import ZZ, QQ, RR, CC, Symbol
from sympy.abc import x, y, z

def conditions(witness) -> list[bool]:
    h1 = False
    h2 = False
    neg_q = False
    
    try:
        if isinstance(witness, tuple) and len(witness) >= 2:
            R = witness[0]
            if isinstance(witness[1], (list, tuple)):
                X = witness[1]
            else:
                X = list(witness[1:])
        else:
            R = witness
            X = []
            
        try:
            if R in [ZZ, QQ, RR, CC]:
                h1 = True
            elif hasattr(R, 'is_commutative') and R.is_commutative:
                h1 = True
            elif hasattr(R, 'is_CommutativeRing') and R.is_CommutativeRing:
                h1 = True
        except Exception:
            pass
            
        try:
            if isinstance(X, (list, tuple)) and len(X) > 0:
                h2 = True
        except Exception:
            pass
            
        try:
            if h1 and h2:
                is_trivial = False
                try:
                    if hasattr(R, 'zero') and hasattr(R, 'one'):
                        if R.zero == R.one:
                            is_trivial = True
                except Exception:
                    pass
                
                if is_trivial:
                    neg_q = False
                else:
                    is_zero_ideal = True
                    has_symbol = False
                    for var in X:
                        if isinstance(var, Symbol) or (hasattr(var, 'is_Symbol') and var.is_Symbol):
                            has_symbol = True
                            break
                        try:
                            if var != 0:
                                is_zero_ideal = False
                        except Exception:
                            is_zero_ideal = False
                    
                    if has_symbol:
                        neg_q = False
                    elif not is_zero_ideal:
                        neg_q = True
                    else:
                        neg_q = False
        except Exception:
            pass
            
    except Exception:
        pass
        
    return [h1, h2, neg_q]

