import sympy
from sympy.ntheory import factorint

# Top-level setup for potential witness expressions
# (No special named bindings are strictly required for this domain, 
# but we provide standard ones just in case)
Z2 = 2
Z3 = 3
Z4 = 4
Z6 = 6
Z8 = 8

CONDITION_LABELS = [
    "H_1: R is a commutative ring",
    "H_2: R is a valuation ring",
    "¬Q: The localized ring R_P is not a valuation ring"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    """
    Checks if the witness is a valid counterexample.
    The witness can be:
      1. An object with methods `is_commutative_ring()`, `is_valuation_ring()`, 
         and `localized_ring_is_valuation_ring()`.
      2. A tuple/list `(n, d)` or dict `{'n': n, 'd': d}` representing the finite 
         ring R = Z/nZ and the ideal P = (d).
    """
    # 1. Try object with methods
    if hasattr(witness, 'is_commutative_ring'):
        try:
            h1 = witness.is_commutative_ring()
            h2 = witness.is_valuation_ring()
            q = witness.localized_ring_is_valuation_ring()
            return [bool(h1), bool(h2), not bool(q)]
        except Exception:
            pass

    # 2. Try dict or tuple for Z/nZ and ideal (d)
    try:
        if isinstance(witness, dict) and 'n' in witness and 'd' in witness:
            n = int(witness['n'])
            d = int(witness['d'])
        elif isinstance(witness, (tuple, list)) and len(witness) == 2:
            n = int(witness[0])
            d = int(witness[1])
        else:
            return [False, False, False]

        # Restrict n to a reasonable size for fast evaluation
        if n < 2 or n > 2000:
            return [False, False, False]

        # H1: R is a commutative ring
        # Z/nZ is always a commutative ring for n >= 2
        h1 = True

        # H2: R is a valuation ring
        # A finite commutative ring Z/nZ is a valuation ring (chained ring) 
        # if and only if its ideals are totally ordered, which happens iff n is a prime power.
        factors = factorint(n)
        h2 = (len(factors) == 1)

        # Conclusion: The localized ring R_P is a valuation ring.
        # P is the ideal generated by d.
        P_set = set((k * d) % n for k in range(n))
        
        # S is the complement of P in R.
        S_set = set(range(n)) - P_set

        # Compute the multiplicative closure M of S
        M = set(S_set)
        M.add(1) # The empty product is 1

        while True:
            new_M = set(M)
            for val in M:
                for s in S_set:
                    new_M.add((val * s) % n)
            if len(new_M) == len(M):
                break
            M = new_M

        # R_P is the localization of R at the multiplicative set M.
        if 0 in M:
            # If 0 is in the multiplicative closure, R_P is the zero ring.
            # The zero ring is not considered a valuation ring (it lacks 1 != 0).
            q = False
        else:
            # If 0 is not in M, R_P is isomorphic to R/I for some proper ideal I.
            # Since R is a chained ring, any proper quotient of R is also a chained ring.
            # Thus, R_P is a valuation ring.
            q = True

        return [h1, h2, not q]

    except Exception:
        return [False, False, False]