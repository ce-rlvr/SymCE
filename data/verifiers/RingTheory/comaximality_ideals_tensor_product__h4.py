import math
import sympy

# Top-level setup: named object bindings that the witness expression may reference
ZZ = sympy.ZZ
QQ = sympy.QQ

def parse_ideal(I):
    if hasattr(I, 'gens'):
        I = I.gens
    if isinstance(I, (tuple, list, set)):
        if len(I) == 0:
            return 0
        elif len(I) == 1:
            I = list(I)[0]
        else:
            for x in I:
                if not isinstance(x, (int, sympy.Integer)):
                    raise ValueError("Not an integer")
            return math.gcd(*[int(x) for x in I])
    if not isinstance(I, (int, sympy.Integer)):
        raise ValueError("Not an integer")
    return int(I)

def conditions(witness):
    """
    Checks whether the witness is a valid counterexample to the false conjecture.
    Returns a list of booleans: [H_1, H_2, H_3, neg_Q]
    """
    try:
        if isinstance(witness, dict):
            R = witness.get('R', witness.get('r'))
            A = witness.get('A', witness.get('a'))
            B = witness.get('B', witness.get('b'))
            I = witness.get('I', witness.get('i'))
            J = witness.get('J', witness.get('j'))
        else:
            R, A, B, I, J = witness
    except Exception:
        return [False, False, False, False]

    # Normalize SymPy sets to domains if used
    try:
        if R == sympy.S.Integers: R = sympy.ZZ
        if A == sympy.S.Integers: A = sympy.ZZ
        if B == sympy.S.Integers: B = sympy.ZZ
        if R == sympy.S.Rationals: R = sympy.QQ
        if A == sympy.S.Rationals: A = sympy.QQ
        if B == sympy.S.Rationals: B = sympy.QQ
    except Exception:
        pass

    # Normalize string representations to domains if used
    try:
        if isinstance(R, str):
            if R.upper() in ["Z", "ZZ"]: R = sympy.ZZ
            elif R.upper() in ["Q", "QQ"]: R = sympy.QQ
        if isinstance(A, str):
            if A.upper() in ["Z", "ZZ"]: A = sympy.ZZ
            elif A.upper() in ["Q", "QQ"]: A = sympy.QQ
        if isinstance(B, str):
            if B.upper() in ["Z", "ZZ"]: B = sympy.ZZ
            elif B.upper() in ["Q", "QQ"]: B = sympy.QQ
    except Exception:
        pass

    # Parse ideals into integer generators
    try:
        I = parse_ideal(I)
        J = parse_ideal(J)
    except Exception:
        pass

    # H_1: R is a commutative ring
    try:
        h1 = (R in [sympy.ZZ, sympy.QQ])
    except Exception:
        h1 = False

    # H_2: A and B are commutative R-algebras
    try:
        h2 = False
        if R == sympy.ZZ and A in [sympy.ZZ, sympy.QQ] and B in [sympy.ZZ, sympy.QQ]:
            h2 = True
        elif R == sympy.QQ and A == sympy.QQ and B == sympy.QQ:
            h2 = True
    except Exception:
        h2 = False

    # H_3: I and J are ideals of A
    try:
        h3 = False
        if A == sympy.ZZ:
            h3 = isinstance(I, int) and isinstance(J, int)
        elif A == sympy.QQ:
            h3 = isinstance(I, int) and isinstance(J, int)
            if h3:
                # In a field, any non-zero ideal is the whole ring (generated by 1)
                I = 1 if I != 0 else 0
                J = 1 if J != 0 else 0
    except Exception:
        h3 = False

    # neg_Q: I \otimes_R B and J \otimes_R B are NOT comaximal in A \otimes_R B
    try:
        neg_q = False
        if A == sympy.ZZ and B == sympy.ZZ:
            # A \otimes B = ZZ. Extended ideals are generated by I and J.
            # Comaximal iff gcd(I, J) == 1
            neg_q = math.gcd(I, J) != 1
        elif A == sympy.ZZ and B == sympy.QQ:
            # A \otimes B = QQ. Extended ideals are QQ if non-zero, else 0.
            I_ext = 1 if I != 0 else 0
            J_ext = 1 if J != 0 else 0
            neg_q = not (I_ext == 1 or J_ext == 1)
        elif A == sympy.QQ and B == sympy.ZZ:
            # A \otimes B = QQ.
            neg_q = not (I == 1 or J == 1)
        elif A == sympy.QQ and B == sympy.QQ:
            # A \otimes B = QQ.
            neg_q = not (I == 1 or J == 1)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

