def contains(lst, item):
    return any(x == item for x in lst)

def extract(witness):
    if isinstance(witness, dict):
        R = witness.get('R')
        x = witness.get('x')
        y = witness.get('y')
        I = witness.get('I')
        add = witness.get('add')
        mul = witness.get('mul')
    elif isinstance(witness, tuple):
        if len(witness) == 6:
            R, add, mul, x, y, I = witness
        elif len(witness) == 4:
            R, x, y, I = witness
            add = None
            mul = None
        else:
            return None, None, None, None, None, None
    else:
        try:
            R = witness.R
            x = witness.x
            y = witness.y
            I = witness.I
            add = getattr(witness, 'add', None)
            mul = getattr(witness, 'mul', None)
        except AttributeError:
            return None, None, None, None, None, None

    if R is None:
        return None, None, None, None, None, None

    R_list = []
    for i, r in enumerate(R):
        if i > 1000:
            return None, None, None, None, None, None
        R_list.append(r)
    R = R_list

    if add is None or mul is None:
        if R and isinstance(R[0], (int, set, frozenset)):
            add = lambda a, b: a ^ b
            mul = lambda a, b: a & b
        else:
            import operator
            add = operator.add
            mul = operator.mul

    return R, add, mul, x, y, I

def check_boolean_ring(R, add, mul):
    if not R: return False
    
    # check closure
    for a in R:
        for b in R:
            if not contains(R, add(a, b)): return False
            if not contains(R, mul(a, b)): return False
            
    # check boolean condition a*a = a
    for a in R:
        if mul(a, a) != a: return False
        
    # check add commutativity
    for a in R:
        for b in R:
            if add(a, b) != add(b, a): return False
            
    # check add associativity
    for a in R:
        for b in R:
            ab = add(a, b)
            for c in R:
                if add(ab, c) != add(a, add(b, c)): return False
                
    # check mul associativity
    for a in R:
        for b in R:
            ab = mul(a, b)
            for c in R:
                if mul(ab, c) != mul(a, mul(b, c)): return False
                
    # check distributivity
    for a in R:
        for b in R:
            ab_add = add(a, b)
            for c in R:
                if mul(a, add(b, c)) != add(mul(a, b), mul(a, c)): return False
                if mul(ab_add, c) != add(mul(a, c), mul(b, c)): return False
                
    # check zero
    zeros_list = [z for z in R if all(add(a, z) == a for a in R)]
    if len(zeros_list) != 1: return False
    zero = zeros_list[0]
    
    # check additive inverse
    for a in R:
        if not any(add(a, b) == zero for b in R): return False
        
    return True

def conditions(witness):
    try:
        R, add, mul, x, y, I = extract(witness)
        if R is None:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H1: R is a Boolean ring
    try:
        h1 = check_boolean_ring(R, add, mul)
    except Exception:
        h1 = False

    # H2: x and y are elements of R
    try:
        h2 = contains(R, x) and contains(R, y)
    except Exception:
        h2 = False

    # neg_Q: I is NOT the principal ideal generated by x + y + xy
    try:
        g = add(add(x, y), mul(x, y))
        
        # Principal ideal generated by g in R is {r * g | r in R}
        P = []
        for r in R:
            p = mul(r, g)
            if not contains(P, p):
                P.append(p)
                
        I_list = []
        for i, item in enumerate(I):
            if i > 2000:
                break
            I_list.append(item)
            
        p_in_I = all(contains(I_list, p) for p in P)
        i_in_P = all(contains(P, i) for i in I_list)
        
        neg_q = not (p_in_I and i_in_P)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]