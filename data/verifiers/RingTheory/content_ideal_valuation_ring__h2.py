def conditions(witness) -> list[bool]:
    h1 = False
    neg_q = False
    
    # Check if witness is a tuple (R, f)
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            R, f = witness
            
            # Check H_1 on R
            if isinstance(R, dict):
                h1 = bool(R.get('is_valuation_ring', False))
            else:
                h1 = bool(getattr(R, 'is_valuation_ring', False))
                
            # Check neg_Q on f
            if isinstance(f, dict):
                if 'content_ideal_generated_by_coeff' in f:
                    q = bool(f['content_ideal_generated_by_coeff'])
                else:
                    q = bool(f.get('is_principal', True)) and bool(f.get('generated_by_coeff', True))
            else:
                if hasattr(f, 'content_ideal_generated_by_coeff'):
                    q = bool(f.content_ideal_generated_by_coeff)
                else:
                    q = bool(getattr(f, 'is_principal', True)) and bool(getattr(f, 'generated_by_coeff', True))
            neg_q = not q
            return [h1, neg_q]
    except Exception:
        pass

    # Fallback to single object witness
    try:
        if isinstance(witness, dict):
            h1 = bool(witness.get('is_valuation_ring', False))
        else:
            h1 = bool(getattr(witness, 'is_valuation_ring', False))
    except Exception:
        h1 = False

    try:
        if isinstance(witness, dict):
            if 'content_ideal_generated_by_coeff' in witness:
                q = bool(witness['content_ideal_generated_by_coeff'])
            else:
                is_princ = witness.get('is_principal', True)
                gen_by_coeff = witness.get('generated_by_coeff', True)
                q = bool(is_princ and gen_by_coeff)
        else:
            if hasattr(witness, 'content_ideal_generated_by_coeff'):
                q = bool(witness.content_ideal_generated_by_coeff)
            else:
                is_princ = getattr(witness, 'is_principal', True)
                gen_by_coeff = getattr(witness, 'generated_by_coeff', True)
                q = bool(is_princ and gen_by_coeff)
        neg_q = not q
    except Exception:
        neg_q = False

    return [h1, neg_q]

