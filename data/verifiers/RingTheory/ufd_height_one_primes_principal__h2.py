import sympy
from sympy import groebner, Poly
from itertools import combinations
from sympy.abc import x, y, z, t, u, v, w

# Top-level setup
# The witness is expected to be a tuple: (vars, F)
# where `vars` is a tuple of sympy Symbols and `F` is a list of polynomials in those variables.
# This implicitly defines the ring R as QQ[vars], which is always a Unique Factorization Domain.

def ideal_dimension(F, vars):
    """
    Computes the Krull dimension of the ideal generated by F in QQ[vars].
    Uses the fact that the dimension of an ideal is equal to the dimension 
    of the monomial ideal generated by the leading terms of its Groebner basis.
    """
    if not F:
        return len(vars)
    
    gb = groebner(F, *vars, domain='QQ')
    gb_list = list(gb)
    
    if len(gb_list) == 1 and gb_list[0] == 1:
        return -1
    if len(gb_list) == 1 and gb_list[0] == 0:
        return len(vars)
    if not gb_list:
        return len(vars)
    
    # Extract leading monomials (exponent tuples)
    lms = [Poly(p, *vars, domain='QQ').LM() for p in gb_list]
    
    # Find the maximum size of an independent set of variables
    for d in range(len(vars), -1, -1):
        for S_indices in combinations(range(len(vars)), d):
            independent = True
            for lm in lms:
                # Check if the leading monomial lm belongs to k[S]
                # It belongs to k[S] if all variables NOT in S have exponent 0
                if all(lm[i] == 0 for i in range(len(vars)) if i not in S_indices):
                    independent = False
                    break
            if independent:
                return d
    return -1

def conditions(witness):
    try:
        vars_tuple, F = witness
        if not isinstance(vars_tuple, (list, tuple)) or not isinstance(F, (list, tuple)):
            return [False, False, False]
        
        if not all(isinstance(v, sympy.Symbol) for v in vars_tuple):
            return [False, False, False]
            
        # H_1: R is a Unique Factorization Domain
        # By restricting the witness to polynomials over QQ, R = QQ[vars] is guaranteed to be a UFD.
        # We just need to verify that F contains valid polynomials.
        for f in F:
            Poly(f, *vars_tuple, domain='QQ')
            
        h1 = True
    except Exception:
        return [False, False, False]

    try:
        # H_2: The height of P is exactly 1
        # In a polynomial ring over a field, height(I) = number of variables - dim(I)
        dim = ideal_dimension(F, vars_tuple)
        height = len(vars_tuple) - dim
        h2 = (height == 1)
    except Exception:
        h2 = False

    try:
        # ¬Q: P is not a principal ideal
        # In QQ[vars], an ideal is principal if and only if its reduced Groebner basis has length <= 1
        if not F:
            neg_q = False
        else:
            gb = groebner(F, *vars_tuple, domain='QQ')
            gb_list = list(gb)
            neg_q = len(gb_list) > 1
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

