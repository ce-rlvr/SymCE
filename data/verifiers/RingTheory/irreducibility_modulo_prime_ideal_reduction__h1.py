import math
import sympy
from sympy import Poly
from sympy.abc import x

# Top-level setup
# The witness is expected to be a tuple: (m, p, f_coeffs, g_coeffs, h_coeffs)
# representing a counterexample in the ring R = Z_m.
# m: modulus of the ring Z_m (integer >= 2)
# p: prime generating the ideal P = <p> in Z_m
# f_coeffs: coefficients of f(x) in Z_m[x], from lowest to highest degree
# g_coeffs, h_coeffs: coefficients of factors g(x) and h(x) such that f = g * h in Z_m[x]

def strip_zeros(coeffs, m):
    if not coeffs:
        return [0]
    m_int = int(m)
    c = [int(val) % m_int for val in coeffs]
    while len(c) > 1 and c[-1] == 0:
        c.pop()
    return c

def is_unit(coeffs, m):
    m_int = int(m)
    c = strip_zeros(coeffs, m_int)
    if math.gcd(c[0], m_int) != 1:
        return False
    rad = 1
    for q in sympy.primefactors(m_int):
        rad *= q
    for val in c[1:]:
        if val % rad != 0:
            return False
    return True

def poly_mul(A, B, m):
    if not A or not B:
        return [0]
    m_int = int(m)
    res = [0] * (len(A) + len(B) - 1)
    for i, a in enumerate(A):
        for j, b in enumerate(B):
            res[i+j] = (res[i+j] + int(a) * int(b)) % m_int
    return res

def conditions(witness):
    h1 = h2 = h3 = h4 = neg_q = False
    
    try:
        if isinstance(witness, dict):
            m = int(witness['m'])
            p = int(witness['p'])
            f_coeffs = witness['f']
            g_coeffs = witness['g']
            h_coeffs = witness['h']
        else:
            m, p, f_coeffs, g_coeffs, h_coeffs = witness
            m = int(m)
            p = int(p)
            
        if m < 2:
            return [False, False, False, False, False]
    except Exception:
        return [False, False, False, False, False]
        
    # H1: P is a prime ideal of R
    # In Z_m, <p> is a prime ideal iff p is prime and p divides m
    try:
        h1 = sympy.isprime(p) and (m % p == 0)
    except Exception:
        pass
        
    # H2: f(x) is a primitive polynomial
    # In Z_m, primitive means the ideal generated by coefficients is the whole ring
    try:
        f_c = strip_zeros(f_coeffs, m)
        gcd_all = m
        for c in f_c:
            gcd_all = math.gcd(gcd_all, c)
        h2 = (gcd_all == 1)
    except Exception:
        pass
        
    # H3: a_n \notin P
    try:
        f_c = strip_zeros(f_coeffs, m)
        a_n = f_c[-1]
        h3 = (a_n % p != 0)
    except Exception:
        pass
        
    # H4: The reduction of f(x) modulo P is irreducible over R/P
    try:
        if sympy.isprime(p):
            f_c = strip_zeros(f_coeffs, m)
            f_p = strip_zeros(f_c, p)
            if len(f_p) > 1:
                poly_p = Poly(list(reversed(f_p)), x, domain=sympy.GF(p))
                h4 = sympy.is_irreducible(poly_p)
    except Exception:
        pass
        
    # ¬Q: f(x) is reducible over R
    # This means f = g * h where neither g nor h is a unit in Z_m[x]
    try:
        f_c = strip_zeros(f_coeffs, m)
        g_c = strip_zeros(g_coeffs, m)
        h_c = strip_zeros(h_coeffs, m)
        
        is_g_unit = is_unit(g_c, m)
        is_h_unit = is_unit(h_c, m)
        
        prod = poly_mul(g_c, h_c, m)
        prod_c = strip_zeros(prod, m)
        
        is_factorization_valid = (f_c == prod_c)
        
        neg_q = is_factorization_valid and not is_g_unit and not is_h_unit
    except Exception:
        pass
        
    return [bool(h1), bool(h2), bool(h3), bool(h4), bool(neg_q)]

