import sympy

# Top-level setup for witness expressions
x, y, z, t = sympy.symbols('x y z t')
QQ = sympy.QQ
ZZ = sympy.ZZ

def conditions(witness):
    try:
        domain, variables, generators = witness
    except Exception:
        return [False, False]
        
    # H_1: I is a maximal ideal
    try:
        if not getattr(domain, 'is_Field', False):
            h1 = False
        else:
            G = sympy.groebner(generators, *variables, domain=domain, order='lex')
            G_polys = list(G)
            
            lms = []
            for p in G_polys:
                poly_p = sympy.Poly(p, *variables, domain=domain)
                lms.append(poly_p.LM())
                
            if len(G_polys) == len(variables):
                is_max = True
                pure_powers = {}
                for i, lm in enumerate(lms):
                    non_zeros = [j for j, exp in enumerate(lm) if exp > 0]
                    if len(non_zeros) != 1:
                        is_max = False
                        break
                    var_idx = non_zeros[0]
                    degree = lm[var_idx]
                    pure_powers[var_idx] = (degree, G_polys[i])
                    
                if is_max and len(pure_powers) == len(variables):
                    degrees = [pure_powers[j][0] for j in range(len(variables))]
                    gt_1 = [j for j, d in enumerate(degrees) if d > 1]
                    if len(gt_1) == 0:
                        h1 = True
                    elif len(gt_1) == 1:
                        var_idx = gt_1[0]
                        poly = pure_powers[var_idx][1]
                        free_vars = poly.free_symbols.intersection(set(variables))
                        if len(free_vars) == 1:
                            factors = sympy.factor_list(poly, domain=domain)
                            if len(factors[1]) == 1 and factors[1][0][1] == 1:
                                h1 = True
                            else:
                                h1 = False
                        else:
                            h1 = False
                    else:
                        h1 = False
                else:
                    h1 = False
            else:
                h1 = False
    except Exception:
        h1 = False
        
    # neg_Q: I is NOT of the form <x_1 - a_1, ..., x_n - a_n>
    try:
        G = sympy.groebner(generators, *variables, domain=domain, order='lex')
        G_polys = list(G)
        is_point = True
        if len(G_polys) == len(variables):
            for p in G_polys:
                poly_p = sympy.Poly(p, *variables, domain=domain)
                lm = poly_p.LM()
                if sum(lm) != 1:
                    is_point = False
                    break
        else:
            is_point = False
            
        neg_q = not is_point
    except Exception:
        neg_q = False
        
    return [h1, neg_q]

