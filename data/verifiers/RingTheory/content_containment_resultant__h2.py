import sympy as sp
import itertools
from sympy.abc import x, y, z, a, b, c, d, e, t, u, v, w

# Top-level setup for witness expressions
Z = sp.S.Integers
Q = sp.S.Rationals

def conditions(witness):
    """
    Checks whether the given witness is a valid counterexample to the false conjecture.
    The witness should be a tuple: (f, g, var, n, m)
    where f and g are SymPy expressions representing polynomials in `var`,
    and n, m are their respective degrees.
    """
    try:
        f, g, var, n, m = witness
    except Exception:
        return [False, False, False, False]

    # H_1: R is a commutative ring
    # SymPy expressions inherently belong to commutative rings.
    try:
        h1 = isinstance(f, sp.Expr) and isinstance(g, sp.Expr)
    except Exception:
        h1 = False

    # H_2: n is the degree of f and m is the degree of g
    try:
        f_poly = sp.Poly(f, var)
        g_poly = sp.Poly(g, var)
        h2 = (f_poly.degree() == n) and (g_poly.degree() == m)
    except Exception:
        h2 = False

    # H_3: n >= 1 and m >= 1
    try:
        h3 = (n >= 1) and (m >= 1)
    except Exception:
        h3 = False

    # neg_Q: The resultant Res(f,g) is NOT an element of the ideal c(f)^m c(g)^n
    try:
        res = sp.resultant(f, g, var)
        
        if res == 0:
            # 0 is always in any ideal
            in_ideal = True
        else:
            coeffs_f = f_poly.coeffs()
            coeffs_g = g_poly.coeffs()
            
            # Generate the ideal c(f)^m c(g)^n
            # c(f)^m is generated by all products of m coefficients of f
            gen_f = [sp.prod(p) for p in itertools.combinations_with_replacement(coeffs_f, m)]
            # c(g)^n is generated by all products of n coefficients of g
            gen_g = [sp.prod(p) for p in itertools.combinations_with_replacement(coeffs_g, n)]
            
            # The product ideal is generated by the pairwise products of their generators
            generators = [gf * gg for gf in gen_f for gg in gen_g]
            
            variables = list(set().union(*(gen.free_symbols for gen in generators)) | res.free_symbols)
            
            if not variables:
                # Integer ideal
                ideal_gcd = generators[0]
                for gen in generators[1:]:
                    ideal_gcd = sp.gcd(ideal_gcd, gen)
                
                if ideal_gcd == 0:
                    in_ideal = (res == 0)
                else:
                    in_ideal = (sp.simplify(res % ideal_gcd) == 0)
            else:
                # Polynomial ideal over a field/ring
                gb = sp.groebner(generators, *variables)
                reduced = sp.reduced(res, gb, *variables)[1]
                in_ideal = (sp.simplify(reduced) == 0)
                
        neg_q = not in_ideal
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

