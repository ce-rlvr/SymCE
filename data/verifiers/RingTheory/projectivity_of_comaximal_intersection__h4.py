CONDITION_LABELS = [
    "H_1: R is a commutative ring",
    "H_2: I and J are ideals of R",
    "H_3: I and J are comaximal, meaning I + J = R",
    "¬Q: I \\cap J is not a projective R-module"
]

N_HYP = 3
NEG_Q_INDEX = 3

def conditions(witness):
    """
    Expects witness to be a tuple (n, a, b) representing:
    - R = Z/nZ
    - I = (a)
    - J = (b)
    """
    try:
        if isinstance(witness, dict):
            n = int(witness.get("n", 0))
            a = int(witness.get("a", 0))
            b = int(witness.get("b", 0))
        else:
            n, a, b = witness
            n = int(n)
            a = int(a)
            b = int(b)
    except Exception:
        return [False, False, False, False]
    
    try:
        # H_1: R is a commutative ring
        # Z/nZ is a commutative ring for n >= 2
        h1 = (n >= 2)
    except Exception:
        h1 = False

    try:
        # H_2: I and J are ideals of R
        # In Z/nZ, any integer defines a principal ideal.
        h2 = True
    except Exception:
        h2 = False

    try:
        # H_3: I and J are comaximal
        # I = (a), J = (b). I + J = (gcd(a, b, n)).
        # Comaximal means I + J = R = (1), so gcd(a, b, n) == 1.
        h3 = (math.gcd(a, math.gcd(b, n)) == 1)
    except Exception:
        h3 = False

    try:
        # ¬Q: I \cap J is not a projective R-module
        # I \cap J is generated by c = lcm(gcd(a, n), gcd(b, n)) % n
        # Since gcd(a, b, n) == 1, this simplifies to c = (gcd(a, n) * gcd(b, n)) % n
        ga = math.gcd(a, n)
        gb = math.gcd(b, n)
        c = (ga * gb) % n
        
        # In Z/nZ, an ideal (c) is projective iff it is generated by an idempotent.
        # This is true iff gcd(c, n // gcd(c, n)) == 1.
        gc = math.gcd(c, n)
        if gc == 0:
            is_projective = True
        else:
            is_projective = (math.gcd(gc, n // gc) == 1)
            
        neg_q = not is_projective
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]