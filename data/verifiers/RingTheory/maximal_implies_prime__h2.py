import sympy
import math
from sympy.abc import x, y, z

# Top-level setup
# Witnesses for this conjecture are typically integers m (representing the ideal mZ in R = Z)
# or tuples (n, m) representing the ideal mZ/nZ in R = Z/nZ.
# No special named objects are strictly required for this domain.

def conditions(witness) -> list[bool]:
    """
    Checks if the witness is a valid counterexample to "Maximal ideals are prime"
    where the "maximal" hypothesis was dropped.
    """
    try:
        if isinstance(witness, (int, sympy.Integer)):
            n = 0
            m = int(witness)
        elif isinstance(witness, (tuple, list)) and len(witness) == 2:
            n = int(witness[0])
            m = int(witness[1])
        else:
            return [False, False]
    except Exception:
        return [False, False]

    # H_1: R is a commutative ring with unity
    # We interpret the witness as defining R = Z/nZ (or Z if n=0), 
    # which is always a commutative ring with unity.
    h1_ok = True

    # neg_Q: M is not a prime ideal of R
    # M is the ideal generated by m in Z/nZ.
    try:
        k = math.gcd(n, m)
        if n == 0:
            # In Z, an ideal (k) is prime iff k is prime or k == 0
            is_prime = (k == 0) or sympy.isprime(k)
        else:
            # In Z/nZ, an ideal (m) is prime iff Z/gcd(n,m)Z is an integral domain,
            # which is true iff gcd(n,m) is a prime number.
            is_prime = sympy.isprime(k)
            
        neg_q_ok = not is_prime
    except Exception:
        neg_q_ok = False

    return [h1_ok, neg_q_ok]

