import sympy

def conditions(witness):
    try:
        if isinstance(witness, int):
            witness = [witness]
        if not isinstance(witness, (list, tuple)):
            return [False, False, False]
        if len(witness) < 1:
            return [False, False, False]
            
        try:
            exponents = [int(x) for x in witness]
        except (TypeError, ValueError):
            return [False, False, False]
            
        h1 = True
        h2 = all(x >= 0 for x in exponents)
        is_primary = all(x >= 1 for x in exponents)
        neg_q = not is_primary
        
        return [h1, h2, neg_q]
    except Exception:
        return [False, False, False]

