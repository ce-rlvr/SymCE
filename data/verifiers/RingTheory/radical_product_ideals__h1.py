def conditions(witness) -> list[bool]:
    """
    Given a witness object, checks whether it is a valid counterexample to the false conjecture:
    "The radical of the product ideal IJ is equal to \\sqrt{I} \\cap \\sqrt{J}."
    """
    try:
        # Unpack the witness
        if isinstance(witness, dict):
            R = witness.get('R', None)
            I = witness.get('I', None)
            J = witness.get('J', None)
            if I is None or J is None:
                return [False, False, False]
        elif isinstance(witness, tuple):
            if len(witness) == 3:
                R, I, J = witness
            elif len(witness) == 2:
                R = None
                I, J = witness
            else:
                return [False, False, False]
        else:
            R = getattr(witness, 'R', None)
            I = getattr(witness, 'I', None)
            J = getattr(witness, 'J', None)
            if I is None or J is None:
                return [False, False, False]

        # H_1: I is an ideal of R
        h1 = False
        try:
            if hasattr(I, 'is_ideal'):
                if callable(I.is_ideal):
                    h1 = bool(I.is_ideal(R) if R is not None else I.is_ideal())
                else:
                    h1 = bool(I.is_ideal)
            else:
                h1 = True  # Fallback if the witness doesn't explicitly provide this check
        except Exception:
            h1 = False

        # H_2: J is an ideal of R
        h2 = False
        try:
            if hasattr(J, 'is_ideal'):
                if callable(J.is_ideal):
                    h2 = bool(J.is_ideal(R) if R is not None else J.is_ideal())
                else:
                    h2 = bool(J.is_ideal)
            else:
                h2 = True  # Fallback if the witness doesn't explicitly provide this check
        except Exception:
            h2 = False

        # ¬Q: The radical of the product ideal IJ is NOT equal to \sqrt{I} \cap \sqrt{J}
        neg_q = False
        try:
            # Compute the product ideal IJ
            IJ = I * J
            
            # Compute radicals
            rad_IJ = IJ.radical() if callable(getattr(IJ, 'radical', None)) else IJ.radical
            rad_I = I.radical() if callable(getattr(I, 'radical', None)) else I.radical
            rad_J = J.radical() if callable(getattr(J, 'radical', None)) else J.radical
            
            # Compute intersection \sqrt{I} \cap \sqrt{J}
            if hasattr(rad_I, 'intersect'):
                rhs = rad_I.intersect(rad_J)
            elif hasattr(rad_I, 'intersection'):
                rhs = rad_I.intersection(rad_J)
            else:
                rhs = rad_I & rad_J
                
            neg_q = bool(rad_IJ != rhs)
        except Exception:
            # Fallback for integer ideals if provided as plain integers
            if isinstance(I, (int, sympy.Integer)) and isinstance(J, (int, sympy.Integer)):
                from sympy.ntheory import rad
                from sympy import lcm
                rad_IJ = rad(I * J)
                rad_I = rad(I)
                rad_J = rad(J)
                # Intersection of ideals (a) and (b) in Z is generated by lcm(a, b)
                rhs = lcm(rad_I, rad_J)
                neg_q = bool(rad_IJ != rhs)
            else:
                neg_q = False

        return [h1, h2, neg_q]

    except Exception:
        return [False, False, False]

