import sympy
from sympy import sympify, factor_list
from sympy.ntheory import isprime, factorint
from sympy.abc import x, y, z

# Top-level setup
ZZ = sympy.S.Integers
QQ = sympy.S.Rationals

def get_gen(gens):
    """Helper to extract a single generator from a list/tuple of generators using GCD."""
    if not isinstance(gens, (list, tuple)):
        return sympify(gens)
    if len(gens) == 0:
        return sympify(0)
    g = sympify(gens[0])
    for i in range(1, len(gens)):
        g = sympy.gcd(g, sympify(gens[i]))
    return g

def conditions(witness) -> list[bool]:
    q, p = None, None
    try:
        # The witness can be provided as (q, p) or (R, Q, P)
        # where Q and P are ideals represented by their generators.
        if isinstance(witness, (tuple, list)):
            if len(witness) == 2:
                q = get_gen(witness[0])
                p = get_gen(witness[1])
            elif len(witness) == 3:
                R, Q, P = witness
                q = get_gen(Q)
                p = get_gen(P)
    except Exception:
        pass

    if q is None or p is None:
        return [False, False, False, False]

    # H_1: R is a commutative ring
    # We assume the ring generated by the witness elements is commutative (e.g., ZZ or a polynomial ring).
    h1 = True

    # H_2: Q is an ideal in R
    # Any element generates a principal ideal.
    h2 = True

    # H_3: P is a prime ideal in R
    h3 = False
    try:
        p_sym = sympify(p)
        if p_sym == 0:
            h3 = True
        elif p_sym.is_Integer:
            h3 = isprime(abs(int(p_sym)))
        else:
            fac = factor_list(p_sym)
            # A principal ideal (p) is prime iff p is irreducible
            h3 = (len(fac[1]) == 1 and fac[1][0][1] == 1)
    except Exception:
        h3 = False

    # ¬Q: Q_ext is not a P_ext-primary ideal
    neg_q = False
    try:
        q_sym = sympify(q)
        p_sym = sympify(p)
        
        is_primary = False
        if p_sym == 0:
            is_primary = (q_sym == 0)
        elif q_sym == 0:
            is_primary = False
        elif q_sym.is_Integer and p_sym.is_Integer:
            q_fac = factorint(abs(int(q_sym)))
            p_fac = factorint(abs(int(p_sym)))
            # In ZZ, (q) is (p)-primary iff q = p^n for some n >= 1
            if len(p_fac) == 1 and len(q_fac) == 1:
                p_prime = list(p_fac.keys())[0]
                q_prime = list(q_fac.keys())[0]
                is_primary = (p_prime == q_prime)
        elif q_sym.is_Integer or p_sym.is_Integer:
            # One is integer, one is polynomial -> cannot be primary to each other (unless 0, handled above)
            is_primary = False
        else:
            q_fac = factor_list(q_sym)
            p_fac = factor_list(p_sym)
            # In a polynomial ring, (q) is (p)-primary iff rad(q) = (p)
            if len(q_fac[1]) == 1 and len(p_fac[1]) == 1:
                q_base = q_fac[1][0][0]
                p_base = p_fac[1][0][0]
                ratio = sympy.simplify(q_base / p_base)
                is_primary = ratio.is_constant()
                
        neg_q = not is_primary
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

