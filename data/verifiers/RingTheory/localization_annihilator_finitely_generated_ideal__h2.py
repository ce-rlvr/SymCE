def get_attr(witness, attr):
    if isinstance(witness, dict):
        return witness[attr]
    return getattr(witness, attr)

def check_commutative_ring(witness):
    elements = get_attr(witness, 'ring_elements')
    add = get_attr(witness, 'add')
    mul = get_attr(witness, 'mul')
    zero = get_attr(witness, 'zero')
    one = get_attr(witness, 'one')
    
    if zero not in elements or one not in elements:
        return False
        
    for a in elements:
        if add(a, zero) != a or add(zero, a) != a: return False
        if mul(a, one) != a or mul(one, a) != a: return False
        
        has_inv = False
        for b in elements:
            if add(a, b) == zero and add(b, a) == zero:
                has_inv = True
                break
        if not has_inv: return False
        
        for b in elements:
            ab_add = add(a, b)
            ab_mul = mul(a, b)
            if ab_add not in elements: return False
            if ab_mul not in elements: return False
            if ab_add != add(b, a): return False
            if ab_mul != mul(b, a): return False
            
            for c in elements:
                if add(ab_add, c) != add(a, add(b, c)): return False
                if mul(ab_mul, c) != mul(a, mul(b, c)): return False
                if mul(a, add(b, c)) != add(ab_mul, mul(a, c)): return False
                
    return True

def check_finitely_generated_ideal(witness):
    elements = get_attr(witness, 'ring_elements')
    I_gens = get_attr(witness, 'I_gens')
    if not isinstance(I_gens, (list, tuple, set)): return False
    for g in I_gens:
        if g not in elements: return False
    return True

def check_neg_q(witness):
    elements = get_attr(witness, 'ring_elements')
    add = get_attr(witness, 'add')
    mul = get_attr(witness, 'mul')
    zero = get_attr(witness, 'zero')
    one = get_attr(witness, 'one')
    I_gens = get_attr(witness, 'I_gens')
    S_gens = get_attr(witness, 'S')
    
    # 1. Compute multiplicative closure of S
    S = set([one])
    for s in S_gens:
        S.add(s)
    added = True
    while added:
        added = False
        new_s = set()
        for a in S:
            for b in S:
                c = mul(a, b)
                if c not in S:
                    new_s.add(c)
        if new_s:
            S.update(new_s)
            added = True
            
    # 2. Compute ideal I generated by I_gens
    I = set([zero])
    for g in I_gens:
        I.add(g)
    added = True
    while added:
        added = False
        new_i = set()
        for a in I:
            for r in elements:
                c = mul(a, r)
                if c not in I:
                    new_i.add(c)
            for b in I:
                c = add(a, b)
                if c not in I:
                    new_i.add(c)
        if new_i:
            I.update(new_i)
            added = True
            
    # 3. Compute Ann(I) in R
    Ann_I = set()
    for r in elements:
        is_ann = True
        for x in I:
            if mul(r, x) != zero:
                is_ann = False
                break
        if is_ann:
            Ann_I.add(r)
            
    def sub(a, b):
        for x in elements:
            if add(b, x) == zero:
                return add(a, x)
        return None

    # 4. Check if (r, s) is in S^{-1}Ann(I)
    def in_S_inv_Ann_I(r, s):
        for a in Ann_I:
            for t in S:
                diff = sub(mul(r, t), mul(a, s))
                for u in S:
                    if mul(u, diff) == zero:
                        return True
        return False

    # 5. Check if (r, s) is in Ann_{S^{-1}R}(S^{-1}I)
    def in_Ann_S_inv_I(r, s):
        for x in I:
            found_u = False
            for u in S:
                if mul(u, mul(r, x)) == zero:
                    found_u = True
                    break
            if not found_u:
                return False
        return True

    # 6. Compare the two sets
    for r in elements:
        for s in S:
            if in_S_inv_Ann_I(r, s) != in_Ann_S_inv_I(r, s):
                return True # They are not equal, so conclusion fails (neg_Q is True)
                
    return False # They are equal, conclusion holds (neg_Q is False)

def conditions(witness):
    h1, h2, neg_q = False, False, False
    
    # H1: R is a commutative ring
    if hasattr(witness, 'is_commutative_ring'):
        try:
            h1 = bool(witness.is_commutative_ring())
        except Exception:
            pass
    else:
        try:
            h1 = check_commutative_ring(witness)
        except Exception:
            pass

    # H2: I is a finitely generated ideal of R
    if hasattr(witness, 'is_finitely_generated_ideal'):
        try:
            h2 = bool(witness.is_finitely_generated_ideal())
        except Exception:
            pass
    else:
        try:
            h2 = check_finitely_generated_ideal(witness)
        except Exception:
            pass

    # neg_Q: S^{-1}(Ann(I)) != Ann_{S^{-1}R}(S^{-1}I)
    if hasattr(witness, 'localization_annihilator_commutes'):
        try:
            neg_q = not bool(witness.localization_annihilator_commutes())
        except Exception:
            pass
    else:
        try:
            neg_q = check_neg_q(witness)
        except Exception:
            pass

    # Fallback for SymPy-like tuples (R, I_gens, S_gens)
    if not (h1 and h2) and isinstance(witness, tuple) and len(witness) == 3:
        try:
            R, I_gens, S_gens = witness
            if hasattr(R, 'is_commutative'):
                h1 = bool(R.is_commutative)
            if isinstance(I_gens, (list, tuple, set)):
                h2 = True
            # For valid commutative rings and finitely generated ideals, the theorem holds.
            neg_q = False
        except Exception:
            pass

    return [bool(h1), bool(h2), bool(neg_q)]