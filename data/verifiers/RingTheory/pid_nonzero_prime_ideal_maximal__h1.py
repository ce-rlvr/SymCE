import sympy
from sympy import symbols, groebner, factor_list, Expr, Poly
from sympy.abc import x, y, z

# Top-level setup
QQ = sympy.QQ
ZZ = sympy.ZZ

CONDITION_LABELS = [
    "H_1: P is a non-zero prime ideal of R",
    "¬Q: P is not a maximal ideal in R"
]

N_HYP = 1
NEG_Q_INDEX = 1

def conditions(witness):
    h1_ok = False
    neg_q = False
    
    try:
        gens = []
        if isinstance(witness, Expr):
            gens = [witness]
        elif isinstance(witness, (list, tuple, set)):
            wit_list = list(witness)
            try:
                # Ensure deterministic order if witness was an unordered collection
                wit_list = sorted(wit_list, key=str)
            except Exception:
                pass
                
            for item in wit_list:
                if isinstance(item, (list, tuple)) and len(item) > 0 and all(isinstance(e, Expr) for e in item):
                    gens = list(item)
                    break
            if not gens:
                gens = [e for e in wit_list if isinstance(e, Expr)]
                
        if not gens:
            return [False, False]
            
        # Determine variables: always include at least x and y to ensure 
        # we evaluate the ideal in a ring of Krull dimension >= 2 (like QQ[x,y]).
        # This guarantees that principal prime ideals are correctly identified as non-maximal.
        syms = set([x, y])
        for g in gens:
            syms.update(g.free_symbols)
        syms = sorted(list(syms), key=lambda s: s.name)
        
        # Compute Groebner basis over QQ
        GB_obj = groebner(gens, *syms, domain='QQ')
        GB = list(GB_obj)
        
        # Check H1: P is a non-zero prime ideal
        if len(GB) == 1:
            f = GB[0]
            if f != 0:
                facs = factor_list(f, domain='QQ')
                # A principal ideal is prime iff its generator is irreducible
                if len(facs[1]) == 1 and facs[1][0][1] == 1:
                    h1_ok = True
        elif all(Poly(g, *syms).total_degree() == 1 for g in GB):
            # An ideal generated by linearly independent linear polynomials is prime
            h1_ok = True
            
        # Check neg_Q: P is NOT maximal
        # In QQ[syms], an ideal is maximal iff it is zero-dimensional (and prime).
        # If it is not zero-dimensional, it is strictly contained in a maximal ideal.
        if not GB_obj.is_zero_dimensional:
            neg_q = True
            
    except Exception:
        pass
        
    return [h1_ok, neg_q]