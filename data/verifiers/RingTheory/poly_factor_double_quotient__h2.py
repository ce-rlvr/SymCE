import sympy
from sympy import Symbol, gcd, degree, sympify

# Top-level setup: named object bindings that the witness expression may reference
x = Symbol('x')
ZZ = sympy.ZZ
QQ = sympy.QQ
RR = sympy.RR
CC = sympy.CC

def conditions(witness):
    """
    Checks the hypotheses and the negated conclusion for the Double Quotient Polynomial Ring Isomorphism conjecture.
    The witness is expected to be a tuple: (R, I, f) or just (I, f) assuming R = QQ.
    """
    try:
        if isinstance(witness, (list, tuple)) and len(witness) == 3:
            R_val, I_val, f_val = witness
        elif isinstance(witness, (list, tuple)) and len(witness) == 2:
            I_val, f_val = witness
        else:
            return [False] * 5
    except Exception:
        return [False] * 5
        
    # H_1: R is a commutative ring with identity
    h1 = True
    
    # H_2: f is a polynomial over R
    try:
        f_expr = sympify(f_val)
        h2 = f_expr.is_polynomial(x) or f_expr.is_number
    except Exception:
        h2 = False
        
    # H_3: J is the ideal generated by I and f
    try:
        if isinstance(I_val, (list, tuple, set)):
            I_exprs = [sympify(i) for i in I_val]
        else:
            I_exprs = [sympify(I_val)]
        h3 = all(i.is_polynomial(x) or i.is_number for i in I_exprs)
    except Exception:
        h3 = False
        
    # H_4: f_bar is the image of f under the natural projection
    h4 = h2 and h3
    
    # ¬Q: The factor rings are not isomorphic
    try:
        neg_q = False
        if h2 and h3:
            if not I_exprs:
                g_I = sympify(0)
            else:
                g_I = I_exprs[0]
                for i in I_exprs[1:]:
                    g_I = gcd(g_I, i)
                
            deg_I = degree(g_I, x) if g_I != 0 else float('inf')
            deg_f = degree(f_expr, x) if f_expr != 0 else float('inf')
            
            g_J = f_expr
            for i in I_exprs:
                g_J = gcd(g_J, i)
                
            deg_J = degree(g_J, x) if g_J != 0 else float('inf')
            
            if g_I == 0:
                neg_q = False
            elif f_expr == 0:
                if deg_I == 0:
                    neg_q = False
                else:
                    neg_q = True
            else:
                # Compare dimensions over the base field
                if deg_J != deg_I * deg_f:
                    neg_q = True
    except Exception:
        neg_q = False
        
    return [bool(h1), bool(h2), bool(h3), bool(h4), bool(neg_q)]

