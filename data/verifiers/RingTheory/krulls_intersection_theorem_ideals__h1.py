class Zn_Ideal:
    """
    Represents the ring Z/nZ and the principal ideal generated by k.
    """
    def __init__(self, n, k):
        self.n = int(n)
        self.k = int(k) % self.n if self.n != 0 else int(k)
        
    def is_proper_ideal(self):
        if self.n == 0:
            return abs(self.k) != 1
        return math.gcd(self.k, self.n) > 1 or (self.k == 0 and self.n > 1)
        
    def intersection_of_powers_is_zero(self):
        if self.n == 0:
            return True
        val = self.k
        for _ in range(self.n):
            if val == 0:
                return True
            val = (val * self.k) % self.n
        return False

def extract_n_k(witness):
    try:
        if hasattr(witness, 'n') and hasattr(witness, 'k'):
            return int(witness.n), int(witness.k)
    except Exception:
        pass

    if isinstance(witness, dict) and 'n' in witness and 'k' in witness:
        try:
            return int(witness['n']), int(witness['k'])
        except Exception:
            pass

    if isinstance(witness, (tuple, list)) and len(witness) == 2:
        n, k = witness
        if hasattr(n, 'order'):
            try:
                n = int(n.order())
            except Exception:
                pass
        try:
            return int(n), int(k)
        except Exception:
            pass

    return None, None

def conditions(witness) -> list[bool]:
    h1 = False
    neg_q = False
    
    try:
        if hasattr(witness, 'is_proper_ideal'):
            h1 = bool(witness.is_proper_ideal())
        else:
            n, k = extract_n_k(witness)
            if n is not None and k is not None:
                if n == 0:
                    h1 = abs(k) != 1
                else:
                    h1 = math.gcd(k, n) > 1 or (k % n == 0 and n > 1)
    except Exception:
        pass

    try:
        if hasattr(witness, 'intersection_of_powers_is_zero'):
            neg_q = not bool(witness.intersection_of_powers_is_zero())
        else:
            n, k = extract_n_k(witness)
            if n is not None and k is not None:
                if n == 0:
                    neg_q = False
                else:
                    val = k % n
                    nilpotent = False
                    for _ in range(n):
                        if val == 0:
                            nilpotent = True
                            break
                        val = (val * k) % n
                    neg_q = not nilpotent
    except Exception:
        pass

    return [h1, neg_q]

