def conditions(witness):
    try:
        if isinstance(witness, dict):
            elements = list(witness['elements'])
            add = witness['add']
            mul = witness['mul']
            zero = witness['zero']
            c = witness['c']
            S = list(witness['S'])
        elif isinstance(witness, tuple) and len(witness) == 6:
            elements, add, mul, zero, c, S = witness
            elements = list(elements)
            S = list(S)
        else:
            elements = list(witness.elements)
            add = witness.add
            mul = witness.mul
            zero = witness.zero
            c = witness.c
            S = list(witness.S)
    except Exception:
        return [False, False, False]
        
    h1 = True
    try:
        if zero not in elements:
            h1 = False
            
        for x in elements:
            if add(x, zero) != x or add(zero, x) != x:
                h1 = False
            has_neg = False
            for y in elements:
                if add(x, y) == zero and add(y, x) == zero:
                    has_neg = True
                    break
            if not has_neg:
                h1 = False
                
            for y in elements:
                if add(x, y) not in elements: h1 = False
                if mul(x, y) not in elements: h1 = False
                if add(x, y) != add(y, x): h1 = False
                if mul(x, y) != mul(y, x): h1 = False
                for z in elements:
                    if add(add(x, y), z) != add(x, add(y, z)): h1 = False
                    if mul(mul(x, y), z) != mul(x, mul(y, z)): h1 = False
                    if mul(x, add(y, z)) != add(mul(x, y), mul(x, z)): h1 = False
    except Exception:
        h1 = False

    h2 = True
    try:
        if c not in elements:
            h2 = False
        else:
            powers = []
            curr = c
            for _ in range(len(elements) + 1):
                if curr not in powers:
                    powers.append(curr)
                curr = mul(curr, c)
                
            S_set = set(S)
            powers_set = set(powers)
            
            identity = None
            for e in elements:
                if all(mul(e, x) == x for x in elements) and all(mul(x, e) == x for x in elements):
                    identity = e
                    break
                    
            valid_S = [powers_set]
            if identity is not None:
                valid_S.append(powers_set.union({identity}))
                
            if S_set not in valid_S:
                h2 = False
    except Exception:
        h2 = False

    neg_q = False
    try:
        identity = None
        for e in elements:
            if all(mul(e, x) == x for x in elements) and all(mul(x, e) == x for x in elements):
                identity = e
                break
        
        if identity is None:
            neg_q = True
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

