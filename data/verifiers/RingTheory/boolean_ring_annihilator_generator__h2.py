# Top-level setup
class FiniteRing:
    def __init__(self, elements, add_func, mul_func, zero, one):
        self.elements = list(elements)
        self.add_func = add_func
        self.mul_func = mul_func
        self.zero = zero
        self.one = one

    def add(self, a, b):
        return self.add_func(a, b)

    def mul(self, a, b):
        return self.mul_func(a, b)

