def is_boolean_ring_with_identity(R):
    if not hasattr(R, 'elements'):
        return False
    elements = R.elements
    if len(elements) > 100:
        return False
    zero = R.zero
    one = R.one
    add = R.add
    mul = R.mul
    
    # Check zero
    for a in elements:
        if add(a, zero) != a or add(zero, a) != a:
            return False
            
    # Check one
    for a in elements:
        if mul(a, one) != a or mul(one, a) != a:
            return False
            
    # Check Boolean (idempotent)
    for a in elements:
        if mul(a, a) != a:
            return False
            
    # Check ring axioms
    for a in elements:
        for b in elements:
            if add(a, b) != add(b, a):
                return False
            for c in elements:
                if add(add(a, b), c) != add(a, add(b, c)):
                    return False
                if mul(mul(a, b), c) != mul(a, mul(b, c)):
                    return False
                if mul(a, add(b, c)) != add(mul(a, b), mul(a, c)):
                    return False
                if mul(add(a, b), c) != add(mul(a, c), mul(b, c)):
                    return False
                    
    # Check additive inverses
    for a in elements:
        has_inv = False
        for b in elements:
            if add(a, b) == zero and add(b, a) == zero:
                has_inv = True
                break
        if not has_inv:
            return False
            
    return True

def conditions(witness):
    try:
        if isinstance(witness, (tuple, list)) and len(witness) == 2 and hasattr(witness[0], 'elements'):
            R, x = witness
            check_all_x = False
        else:
            R = witness
            check_all_x = True
            
        h1 = is_boolean_ring_with_identity(R)
    except Exception:
        h1 = False

    try:
        if not h1:
            neg_q = False
        else:
            def check_x(x):
                if x not in R.elements:
                    return False
                
                # Ann(x)
                ann_x = set()
                for y in R.elements:
                    if R.mul(x, y) == R.zero and R.mul(y, x) == R.zero:
                        ann_x.add(y)
                
                # Find -x
                neg_x = None
                for y in R.elements:
                    if R.add(x, y) == R.zero and R.add(y, x) == R.zero:
                        neg_x = y
                        break
                if neg_x is None:
                    return False
                
                # 1 - x
                comp_x = R.add(R.one, neg_x)
                
                # Principal ideal <1 - x>
                ideal = set()
                for r in R.elements:
                    ideal.add(R.mul(r, comp_x))
                    
                return ann_x != ideal

            if check_all_x:
                neg_q = any(check_x(x) for x in R.elements)
            else:
                neg_q = check_x(x)
    except Exception:
        neg_q = False

    return [h1, neg_q]

