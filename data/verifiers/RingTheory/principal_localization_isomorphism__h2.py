def conditions(witness):
    h1, h2, neg_q = False, False, False
    
    try:
        if hasattr(witness, 'is_commutative_ring'):
            h1 = witness.is_commutative_ring()
            h2 = witness.is_S_generated_by_f()
            neg_q = not witness.is_isomorphic()
            return [bool(h1), bool(h2), bool(neg_q)]
    except Exception:
        pass

    try:
        if isinstance(witness, tuple) and len(witness) == 5:
            if isinstance(witness[0], int):
                n, add_table, mul_table, f_index, S_indices = witness
                elements = list(range(n))
                add_func = lambda a, b: add_table[a][b]
                mul_func = lambda a, b: mul_table[a][b]
                f = f_index
                S = S_indices
            else:
                elements, add_func, mul_func, f, S = witness
                elements = list(elements)
                
            # H1: R is a commutative ring
            h1 = True
            for a in elements:
                for b in elements:
                    if add_func(a, b) != add_func(b, a): h1 = False
                    if mul_func(a, b) != mul_func(b, a): h1 = False
                    for c in elements:
                        if add_func(add_func(a, b), c) != add_func(a, add_func(b, c)): h1 = False
                        if mul_func(mul_func(a, b), c) != mul_func(a, mul_func(b, c)): h1 = False
                        if mul_func(a, add_func(b, c)) != add_func(mul_func(a, b), mul_func(a, c)): h1 = False
            
            has_zero = False
            for z_idx in elements:
                if all(add_func(z_idx, i) == i for i in elements):
                    has_zero = True
                    for i in elements:
                        if not any(add_func(i, j) == z_idx for j in elements):
                            has_zero = False
                    if has_zero:
                        break
            if not has_zero: h1 = False
            
            # H2: S is the multiplicatively closed subset generated by f
            gen_S = set()
            curr = f
            for _ in range(len(elements) + 1):
                gen_S.add(curr)
                curr = mul_func(curr, f)
                
            identity = None
            for e in elements:
                if all(mul_func(e, i) == i for i in elements):
                    identity = e
                    break
                    
            gen_S_with_1 = set(gen_S)
            if identity is not None:
                gen_S_with_1.add(identity)
                
            S_set = set(S)
            if S_set != gen_S and S_set != gen_S_with_1:
                h2 = False
            else:
                h2 = True
                for a in S_set:
                    for b in S_set:
                        if mul_func(a, b) not in S_set:
                            h2 = False
                            
            # neg_Q: The localized ring S^{-1}R is NOT isomorphic to R[x]/(xf - 1)
            # This is true if R lacks an identity.
            neg_q = (identity is None)
            
    except Exception:
        pass

    try:
        if isinstance(witness, tuple) and len(witness) == 3:
            elements, f, S = witness
            elements = list(elements)
            add_func = lambda a, b: a + b
            mul_func = lambda a, b: a * b
            
            # H1: R is a commutative ring
            h1 = True
            for a in elements:
                for b in elements:
                    if add_func(a, b) not in elements: h1 = False
                    if mul_func(a, b) not in elements: h1 = False
                    if add_func(a, b) != add_func(b, a): h1 = False
                    if mul_func(a, b) != mul_func(b, a): h1 = False
                    for c in elements:
                        if add_func(add_func(a, b), c) != add_func(a, add_func(b, c)): h1 = False
                        if mul_func(mul_func(a, b), c) != mul_func(a, mul_func(b, c)): h1 = False
                        if mul_func(a, add_func(b, c)) != add_func(mul_func(a, b), mul_func(a, c)): h1 = False
            
            has_zero = False
            for z_idx in elements:
                if all(add_func(z_idx, i) == i for i in elements):
                    has_zero = True
                    for i in elements:
                        if not any(add_func(i, j) == z_idx for j in elements):
                            has_zero = False
                    if has_zero:
                        break
            if not has_zero: h1 = False
            
            # H2: S is the multiplicatively closed subset generated by f
            gen_S = set()
            curr = f
            for _ in range(len(elements) + 1):
                gen_S.add(curr)
                curr = mul_func(curr, f)
                
            identity = None
            for e in elements:
                if all(mul_func(e, i) == i for i in elements):
                    identity = e
                    break
                    
            gen_S_with_1 = set(gen_S)
            if identity is not None:
                gen_S_with_1.add(identity)
                
            S_set = set(S)
            if S_set != gen_S and S_set != gen_S_with_1:
                h2 = False
            else:
                h2 = True
                for a in S_set:
                    for b in S_set:
                        if mul_func(a, b) not in S_set:
                            h2 = False
                            
            # neg_Q: The localized ring S^{-1}R is NOT isomorphic to R[x]/(xf - 1)
            neg_q = (identity is None)
            
    except Exception:
        pass

    return [bool(h1), bool(h2), bool(neg_q)]

