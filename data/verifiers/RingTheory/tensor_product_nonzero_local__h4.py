def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness should be a tuple (R, A, B) where:
      - R is the ring (either an integer n >= 2 representing Z/nZ, or a sympy field like QQ)
      - A is the presentation matrix for M (or an integer representing the dimension if R is a field)
      - B is the presentation matrix for N (or an integer representing the dimension if R is a field)
    """
    res = [False, False, False, False]
    try:
        R, A, B = witness
        
        # Handle string representations like "Z4"
        if isinstance(R, str) and R.startswith('Z') and R[1:].isdigit():
            R = int(R[1:])
            
        # If A or B are given as integers, treat them as dimensions of free modules (presentation matrix is 0 x dim)
        if isinstance(A, (int, Integer)):
            A = zeros(0, int(A))
        else:
            A = Matrix(A)
            
        if isinstance(B, (int, Integer)):
            B = zeros(0, int(B))
        else:
            B = Matrix(B)
            
        is_local = False
        p = None
        
        # Check if R is a local ring
        # Z/nZ is a local ring iff n is a prime power p^k
        if isinstance(R, (int, Integer)) and R >= 2:
            factors = factorint(int(R))
            if len(factors) == 1:
                is_local = True
                p = list(factors.keys())[0]
        # Fields are also local rings
        elif R in [QQ, RR, CC, S.Reals, S.Complexes, S.Rationals]:
            is_local = True
            p = 0
            
        res[0] = is_local
        
        # M and N are finitely generated because they are presented by finite matrices
        res[1] = True
        
        if is_local:
            m = A.shape[1]
            k = B.shape[1]
            
            # By Nakayama's lemma, a finitely generated module over a local ring with maximal ideal m
            # is zero iff M/mM is zero. For Z/p^k Z, the maximal ideal is generated by p.
            # Thus, M is zero iff the rank of its presentation matrix modulo p is equal to the number of generators.
            if p > 0:
                A_eval = Matrix(A.shape[0], A.shape[1], lambda i, j: int(A[i, j]) % p)
                B_eval = Matrix(B.shape[0], B.shape[1], lambda i, j: int(B[i, j]) % p)
            else:
                A_eval = A
                B_eval = B
                
            rank_A = A_eval.rank() if m > 0 else 0
            rank_B = B_eval.rank() if k > 0 else 0
            
            M_zero = (rank_A == m)
            N_zero = (rank_B == k)
            
            # H_3: M is not the zero module
            res[2] = not M_zero
            
            # ¬Q: M \otimes_R N is the zero module
            # Over a local ring, M \otimes N = 0 iff M = 0 or N = 0
            res[3] = M_zero or N_zero
            
    except Exception:
        pass
        
    return res

