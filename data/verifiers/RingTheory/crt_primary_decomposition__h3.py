def get_vars(witness):
    symbols_set = set()
    I_gens = witness.get('I', [])
    Q_gens_list = witness.get('Q', [])
    
    for g in I_gens:
        if hasattr(g, 'free_symbols'):
            symbols_set.update(g.free_symbols)
    for q in Q_gens_list:
        for g in q:
            if hasattr(g, 'free_symbols'):
                symbols_set.update(g.free_symbols)
                
    vars_list = sorted(list(symbols_set), key=lambda s: s.name)
    if not vars_list:
        vars_list = [sympy.Symbol('x')]
    return vars_list

def intersect_ideals(I1_gens, I2_gens, vars_list):
    t = sympy.Symbol('t_intersect_12345')
    gens = [t * g for g in I1_gens] + [(1 - t) * g for g in I2_gens]
    gb = sympy.groebner(gens, *([t] + list(vars_list)), order='lex')
    intersect_gens = []
    for p in gb:
        expr = p.as_expr() if hasattr(p, 'as_expr') else p
        if t not in expr.free_symbols:
            intersect_gens.append(expr)
    return intersect_gens

def intersect_multiple_ideals(ideals_gens, vars_list):
    if not ideals_gens:
        return [0]
    res = ideals_gens[0]
    for i in range(1, len(ideals_gens)):
        res = intersect_ideals(res, ideals_gens[i], vars_list)
    return res

def ideals_equal(I1_gens, I2_gens, vars_list):
    I1 = I1_gens if I1_gens else [0]
    I2 = I2_gens if I2_gens else [0]
    
    try:
        gb1 = sympy.groebner(I1, *vars_list)
        gb2 = sympy.groebner(I2, *vars_list)
        
        for g in I1:
            if sympy.reduced(g, gb2, *vars_list)[1] != 0:
                return False
        for g in I2:
            if sympy.reduced(g, gb1, *vars_list)[1] != 0:
                return False
        return True
    except Exception:
        return False

def is_primary(Q_gens, vars_list):
    if not Q_gens:
        return False
    Q_gens = [g for g in Q_gens if g != 0]
    if not Q_gens:
        return False
        
    try:
        gb = sympy.groebner(Q_gens, *vars_list)
        if len(gb) == 1:
            expr = gb[0].as_expr() if hasattr(gb[0], 'as_expr') else gb[0]
            if expr.is_number and expr != 0:
                return False # Not a proper ideal
    except Exception:
        return False

    # 1. Prime ideal generated by a single irreducible polynomial
    if len(Q_gens) == 1:
        f = Q_gens[0]
        try:
            if sympy.polys.polytools.is_irreducible(f):
                return True
        except Exception:
            pass
            
    # 2. Ideal generated by a subset of variables (prime)
    if all(g in vars_list for g in Q_gens):
        return True
        
    # 3. Zero-dimensional in its own variables (radical is maximal)
    try:
        used_vars = set()
        for g in Q_gens:
            if hasattr(g, 'free_symbols'):
                used_vars.update(g.free_symbols)
        used_vars = [v for v in vars_list if v in used_vars]
        
        if used_vars:
            all_used_nilpotent = True
            for v in used_vars:
                is_nilpotent = False
                for k in range(1, 15):
                    if sympy.reduced(v**k, gb, *vars_list)[1] == 0:
                        is_nilpotent = True
                        break
                if not is_nilpotent:
                    all_used_nilpotent = False
                    break
            if all_used_nilpotent:
                return True
    except Exception:
        pass
        
    return False

def check_H2(I_gens, Q_gens_list, vars_list):
    if not Q_gens_list:
        return False
    
    intersect_gens = intersect_multiple_ideals(Q_gens_list, vars_list)
    if not ideals_equal(I_gens, intersect_gens, vars_list):
        return False
        
    for Q_gens in Q_gens_list:
        if not is_primary(Q_gens, vars_list):
            return False
            
    return True

def check_neg_Q(I_gens, Q_gens_list, vars_list):
    n = len(Q_gens_list)
    if n < 2:
        return False
        
    for i in range(n):
        for j in range(i + 1, n):
            gens = list(Q_gens_list[i]) + list(Q_gens_list[j])
            gb = sympy.groebner(gens, *vars_list)
            is_comaximal = False
            if len(gb) == 1:
                expr = gb[0].as_expr() if hasattr(gb[0], 'as_expr') else gb[0]
                if expr.is_number and expr != 0:
                    is_comaximal = True
            if not is_comaximal:
                return True
                
    return False

def conditions(witness):
    try:
        if not isinstance(witness, dict):
            return [False, False, False]
            
        I_gens = witness.get('I', [])
        Q_gens_list = witness.get('Q', [])
        
        if not isinstance(I_gens, list) or not isinstance(Q_gens_list, list):
            return [False, False, False]
            
        for q in Q_gens_list:
            if not isinstance(q, list):
                return [False, False, False]
                
        vars_list = get_vars(witness)
        
        # H1: R is a commutative ring (Polynomial rings over QQ are commutative)
        h1_ok = True
        
        # H2: I admits a primary decomposition I = Q_1 \cap \dots \cap Q_n
        try:
            h2_ok = check_H2(I_gens, Q_gens_list, vars_list)
        except Exception:
            h2_ok = False
            
        # neg_Q: R/I is not isomorphic to \prod R/Q_i
        try:
            neg_q_ok = check_neg_Q(I_gens, Q_gens_list, vars_list)
        except Exception:
            neg_q_ok = False
            
        return [h1_ok, h2_ok, neg_q_ok]
    except Exception:
        return [False, False, False]