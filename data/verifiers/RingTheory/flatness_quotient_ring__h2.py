class AbstractRingIdeal:
    """
    Mock object to represent rings and ideals that cannot be constructed in SymPy
    (e.g., non-Noetherian rings like infinite direct products).
    """
    def __init__(self, is_commutative, is_flat_quotient, is_generated_by_idempotent):
        self.is_commutative = is_commutative
        self.is_flat_quotient = is_flat_quotient
        self.is_generated_by_idempotent = is_generated_by_idempotent

# Standard counterexample: R is the Boolean ring of subsets of N, I is the ideal of finite subsets.
# R is commutative. R/I is flat (all modules over Boolean rings are flat).
# I is not generated by an idempotent (it is not principal).
Counterexample = AbstractRingIdeal(True, True, False)
BooleanRingCounterexample = Counterexample

def conditions(witness):
    h1 = False
    neg_q = False
    
    try:
        if isinstance(witness, AbstractRingIdeal):
            h1 = bool(witness.is_commutative)
            q = (bool(witness.is_flat_quotient) == bool(witness.is_generated_by_idempotent))
            neg_q = not q
            
        elif isinstance(witness, dict):
            h1 = bool(witness.get("is_commutative", witness.get("is_commutative_ring", False)))
            
            flat = witness.get("is_flat_quotient", 
                   witness.get("is_flat", 
                   witness.get("quotient_is_flat", False)))
            
            idem = witness.get("is_generated_by_idempotent", 
                   witness.get("is_idempotent_generated", 
                   witness.get("ideal_generated_by_idempotent", 
                   witness.get("generated_by_idempotent", False))))
                   
            q = (bool(flat) == bool(idem))
            neg_q = not q
            
        elif isinstance(witness, str):
            s = witness.lower()
            if ("boolean" in s or "power set" in s or "product" in s or "z2" in s or "z_2" in s) and \
               ("finite" in s or "direct sum" in s or "ideal" in s or "infinite" in s or "non-principal" in s):
                h1 = True
                neg_q = True
                
        elif isinstance(witness, tuple) or isinstance(witness, list):
            s = str(witness).lower()
            if ("boolean" in s or "power set" in s or "product" in s or "z2" in s or "z_2" in s) and \
               ("finite" in s or "direct sum" in s or "ideal" in s or "infinite" in s or "non-principal" in s):
                h1 = True
                neg_q = True
                
    except Exception:
        pass
        
    return [h1, neg_q]

