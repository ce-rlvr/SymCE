import sympy
from sympy import symbols

# Top-level setup
# Since SymPy does not natively support computing Cohen-Macaulayness, ideal heights, 
# or associated primes for general rings, we provide mock classes that a witness 
# expression can instantiate to represent a counterexample.
class MockRing:
    """Mock class for a commutative ring to be used as a witness."""
    def __init__(self, is_Cohen_Macaulay=True, is_commutative=True, is_Noetherian=True):
        self.is_Cohen_Macaulay = is_Cohen_Macaulay
        self.is_commutative = is_commutative
        self.is_Noetherian = is_Noetherian

class MockIdeal:
    """Mock class for an ideal to be used as a witness."""
    def __init__(self, ring, generators_count, height, associated_primes_heights):
        self.ring = ring
        self.generators_count = generators_count
        self.height = height
        self.associated_primes_heights = associated_primes_heights

def conditions(witness) -> list[bool]:
    try:
        # Witness can be a dictionary with all properties
        if isinstance(witness, dict):
            h1 = bool(witness.get("is_Cohen_Macaulay", False) and 
                      witness.get("is_commutative", False) and 
                      witness.get("is_Noetherian", False))
            h2 = bool(witness.get("generators_count", -1) == witness.get("n", -2))
            h3 = bool(witness.get("height", -1) == witness.get("n", -2))
            assoc_heights = witness.get("associated_primes_heights", [])
            n = witness.get("n", -2)
            
            if assoc_heights is None:
                assoc_heights = []
            elif isinstance(assoc_heights, int):
                assoc_heights = [assoc_heights]
                
            # neg_Q: there is an associated prime whose height is not n
            neg_q = not all(h == n for h in assoc_heights)
            if not assoc_heights:
                neg_q = False
                
            return [h1, h2, h3, neg_q]
        
        # Witness can be a tuple (R, I, n)
        R, I, n = witness
        
        if isinstance(R, dict):
            h1 = bool(R.get("is_Cohen_Macaulay", False) and 
                      R.get("is_commutative", False) and 
                      R.get("is_Noetherian", False))
        else:
            h1 = bool(getattr(R, 'is_Cohen_Macaulay', False) and 
                      getattr(R, 'is_commutative', False) and 
                      getattr(R, 'is_Noetherian', False))
            
        if isinstance(I, dict):
            h2 = bool(I.get("generators_count", -1) == n)
            h3 = bool(I.get("height", -1) == n)
            assoc_heights = I.get("associated_primes_heights", [])
        else:
            h2 = bool(getattr(I, 'generators_count', -1) == n)
            h3 = bool(getattr(I, 'height', -1) == n)
            assoc_heights = getattr(I, 'associated_primes_heights', [])
            
        if assoc_heights is None:
            assoc_heights = []
        elif isinstance(assoc_heights, int):
            assoc_heights = [assoc_heights]
            
        neg_q = not all(h == n for h in assoc_heights)
        if not assoc_heights:
            neg_q = False
            
        return [h1, h2, h3, neg_q]
    except Exception:
        return [False, False, False, False]

