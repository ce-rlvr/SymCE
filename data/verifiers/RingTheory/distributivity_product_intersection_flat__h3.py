import math
from functools import reduce
from sympy import ZZ, QQ, S
from sympy.abc import x, y

def multi_gcd(*args):
    if not args:
        return 0
    return reduce(math.gcd, args)

class Z_Ideal:
    """
    A helper class to represent ideals in the ring of integers (ZZ).
    Since ZZ is a Principal Ideal Domain, every ideal is generated by a single integer.
    All ideals in ZZ are torsion-free, hence flat as ZZ-modules.
    """
    def __init__(self, *gens):
        if not gens:
            self.gen = 0
        else:
            self.gen = multi_gcd(*[abs(g) for g in gens])
            
    def __contains__(self, item):
        if self.gen == 0:
            return item == 0
        return item % self.gen == 0
        
    def intersect(self, other):
        if isinstance(other, Z_Ideal):
            if self.gen == 0 or other.gen == 0:
                return Z_Ideal(0)
            return Z_Ideal(abs(self.gen * other.gen) // math.gcd(self.gen, other.gen))
        if isinstance(other, (set, list, tuple)):
            return type(other)(x for x in other if x in self)
        raise TypeError
        
    def __mul__(self, other):
        if isinstance(other, Z_Ideal):
            return Z_Ideal(self.gen * other.gen)
        if isinstance(other, (set, list, tuple)):
            return Z_Ideal(*[self.gen * x for x in other])
        raise TypeError
        
    def __rmul__(self, other):
        return self.__mul__(other)
        
    def __eq__(self, other):
        return isinstance(other, Z_Ideal) and self.gen == other.gen
        
    def __str__(self):
        return f"Z_Ideal({self.gen})"
        
    def __repr__(self):
        return self.__str__()

def is_ZZ(R):
    return R is ZZ or R == S.Integers

def contains(ideal, element):
    if hasattr(ideal, 'contains'):
        return ideal.contains(element)
    return element in ideal

def intersect(A, B):
    if isinstance(A, Z_Ideal) and isinstance(B, Z_Ideal):
        return A.intersect(B)
    if hasattr(A, 'intersect') and hasattr(B, 'intersect') and not isinstance(A, (set, list, tuple)) and not isinstance(B, (set, list, tuple)):
        return A.intersect(B)
    if isinstance(A, (set, list, tuple)):
        return type(A)(x for x in A if contains(B, x))
    if isinstance(B, (set, list, tuple)):
        return type(B)(x for x in B if contains(A, x))
    raise TypeError

def multiply(A, B, R):
    if isinstance(A, Z_Ideal):
        return A * B
    if isinstance(B, Z_Ideal):
        return B * A
    if hasattr(A, '__mul__') and hasattr(B, '__mul__') and not isinstance(A, (set, list, tuple)) and not isinstance(B, (set, list, tuple)):
        return A * B
    if hasattr(A, 'gens') and isinstance(B, (set, list, tuple)):
        gens = [i * j for i in A.gens for j in B]
        return R.ideal(*gens) if gens else R.ideal(0)
    if hasattr(B, 'gens') and isinstance(A, (set, list, tuple)):
        gens = [i * j for i in B.gens for j in A]
        return R.ideal(*gens) if gens else R.ideal(0)
    raise TypeError

def ideals_equal(A, B):
    if isinstance(A, Z_Ideal) and isinstance(B, Z_Ideal):
        return A == B
    if hasattr(A, 'gens') and hasattr(B, 'gens'):
        A_in_B = all(contains(B, g) for g in A.gens)
        B_in_A = all(contains(A, g) for g in B.gens)
        return A_in_B and B_in_A
    return A == B

def conditions(witness):
    """
    Given a witness tuple (R, I, J, K), checks if it is a valid counterexample.
    J is the object for which the "J is an ideal" hypothesis was dropped (e.g., a mere subset).
    """
    try:
        R, I, J, K = witness
    except Exception:
        return [False, False, False, False]

    # H_1: R is a commutative ring
    try:
        h1 = False
        if is_ZZ(R) or getattr(R, 'is_commutative', False):
            h1 = True
    except Exception:
        h1 = False

    # H_2: I is an ideal of R that is flat as an R-module
    try:
        h2 = False
        if is_ZZ(R) and isinstance(I, Z_Ideal):
            h2 = True
        elif hasattr(R, 'ideal') and hasattr(I, 'gens'):
            # In domains, principal ideals are free, hence flat.
            if len(I.gens) <= 1:
                h2 = True
    except Exception:
        h2 = False

    # H_3: K is an ideal of R
    try:
        h3 = False
        if is_ZZ(R) and isinstance(K, Z_Ideal):
            h3 = True
        elif hasattr(R, 'ideal') and hasattr(K, 'gens'):
            h3 = True
    except Exception:
        h3 = False

    # ¬Q: The ideal I(J \cap K) is NOT equal to the intersection of the ideals IJ and IK.
    try:
        neg_q = False
        J_cap_K = intersect(J, K)
        I_J_cap_K = multiply(I, J_cap_K, R)
        IJ = multiply(I, J, R)
        IK = multiply(I, K, R)
        IJ_cap_IK = intersect(IJ, IK)
        
        if not ideals_equal(I_J_cap_K, IJ_cap_IK):
            neg_q = True
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

