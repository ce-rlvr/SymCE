import sympy
from sympy.abc import x, y, z
import math
from functools import reduce

# Top-level setup for potential witness expressions
I2 = sympy.eye(2)
I3 = sympy.eye(3)
O2 = sympy.zeros(2, 2)
O3 = sympy.zeros(3, 3)

CONDITION_LABELS = [
    "H_1: x and y are elements of R",
    "H_2: x + y + xy = 1",
    "¬Q: The principal ideals (x) and (y) are not comaximal in R"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    try:
        # Witness can be (x, y) for an implicit ring or (n, x, y) for Z_n
        if isinstance(witness, tuple):
            if len(witness) == 2:
                x_val, y_val = witness
                n = None
            elif len(witness) == 3:
                n, x_val, y_val = witness
            else:
                return [False, False, False]
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H_1: x and y are elements of R (check if operations are valid)
    try:
        if n is not None:
            _ = (x_val + y_val + x_val * y_val) % n
        else:
            _ = x_val + y_val + x_val * y_val
        h1_ok = True
    except Exception:
        h1_ok = False

    # H_2: x + y + xy = 1
    try:
        if n is not None and isinstance(n, int):
            h2_ok = ((x_val + y_val + x_val * y_val) % n) == (1 % n)
        else:
            val = x_val + y_val + x_val * y_val
            if val == 1:
                h2_ok = True
            else:
                if hasattr(x_val, 'shape') and hasattr(y_val, 'shape') and x_val.shape == y_val.shape:
                    I = sympy.eye(x_val.shape[0])
                    h2_ok = (val == I)
                else:
                    h2_ok = (sympy.simplify(val - 1) == 0)
    except Exception:
        h2_ok = False

    # ¬Q: The principal ideals (x) and (y) are NOT comaximal in R
    try:
        comaximal = False
        if n is not None and isinstance(n, int):
            # In Z_n, (x) and (y) are comaximal iff gcd(x, y, n) == 1
            comaximal = math.gcd(math.gcd(int(x_val), int(y_val)), n) == 1
        else:
            if isinstance(x_val, int) and isinstance(y_val, int):
                comaximal = math.gcd(x_val, y_val) == 1
            elif hasattr(x_val, 'shape') and hasattr(y_val, 'shape'):
                # For matrices, check the ideal generated by their entries
                def matrix_gcd(M):
                    entries = list(M)
                    if not entries:
                        return 0
                    if all(isinstance(e, (int, sympy.Integer)) for e in entries):
                        return reduce(math.gcd, [int(e) for e in entries])
                    else:
                        for e in entries:
                            if e != 0:
                                return 1
                        return 0
                gx = matrix_gcd(x_val)
                gy = matrix_gcd(y_val)
                if isinstance(gx, int) and isinstance(gy, int):
                    comaximal = math.gcd(gx, gy) == 1
                else:
                    comaximal = (gx != 0) or (gy != 0)
            else:
                # For polynomials or other sympy expressions
                g = sympy.gcd(x_val, y_val)
                if isinstance(g, (int, sympy.Integer)):
                    comaximal = (abs(g) == 1)
                elif hasattr(g, 'is_number') and g.is_number and g != 0:
                    comaximal = True
                else:
                    comaximal = False
    except Exception:
        # Default to True on evaluation failure so that neg_q_ok becomes False
        comaximal = True

    neg_q_ok = not comaximal

    return [h1_ok, h2_ok, neg_q_ok]