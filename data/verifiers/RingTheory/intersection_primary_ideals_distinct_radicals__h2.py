import sympy

# Top-level setup
# We evaluate the conjecture in the ring of integers Z.
# Ideals in Z are principal and can be represented by their non-negative generator.
# A witness is expected to be a tuple of 4 integers: (q1, q2, p1, p2)
# representing the ideals (q1), (q2), (p1), (p2) in Z.
Z = "Z"

def is_ideal_contained(a, b):
    # In Z, ideal (a) is contained in ideal (b) iff b divides a
    if b == 0:
        return a == 0
    return a % b == 0

def is_primary_ideal(q, p):
    # In Z, (q) is (p)-primary iff q = p^n for some n >= 1 and p is prime,
    # or if q == 0 and p == 0 (since (0) is a prime ideal, hence primary).
    if q == 0 and p == 0:
        return True
    if q == 0 or p == 0:
        return False
    q, p = abs(q), abs(p)
    if q == 1:
        return False
    if not sympy.isprime(p):
        return False
    n = q
    while n % p == 0:
        n //= p
    return n == 1

def is_primary(q):
    # In Z, (q) is primary iff q = p^n for some prime p and n >= 1, or q == 0.
    if q == 0:
        return True
    q = abs(q)
    if q == 1:
        return False
    factors = sympy.factorint(q)
    return len(factors) == 1

def conditions(witness):
    try:
        if isinstance(witness, dict):
            q1 = witness.get('Q1', witness.get('q1'))
            q2 = witness.get('Q2', witness.get('q2'))
            p1 = witness.get('P1', witness.get('p1'))
            p2 = witness.get('P2', witness.get('p2'))
        elif len(witness) == 5:
            _, q1, q2, p1, p2 = witness
        else:
            q1, q2, p1, p2 = witness
            
        q1 = int(q1)
        q2 = int(q2)
        p1 = int(p1)
        p2 = int(p2)
    except Exception:
        return [False] * 5

    # H_1: R is a commutative ring
    # We are working in Z, which is a commutative ring.
    h1 = True

    # H_2: Q_2 is a P_2-primary ideal in R
    try:
        h2 = is_primary_ideal(q2, p2)
    except Exception:
        h2 = False

    # H_3: P_1 is not contained in P_2
    try:
        h3 = not is_ideal_contained(p1, p2)
    except Exception:
        h3 = False

    # H_4: P_2 is not contained in P_1
    try:
        h4 = not is_ideal_contained(p2, p1)
    except Exception:
        h4 = False

    # neg_Q: Q_1 \cap Q_2 is a primary ideal
    # In Z, the intersection of (q1) and (q2) is generated by lcm(q1, q2)
    try:
        intersection_gen = sympy.lcm(q1, q2)
        neg_q = is_primary(intersection_gen)
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]

