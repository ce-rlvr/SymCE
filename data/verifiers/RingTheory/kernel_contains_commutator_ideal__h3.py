def check_ring(els, add, mul, zero):
    if zero not in els: return False
    for a in els:
        if add(a, zero) != a or add(zero, a) != a: return False
        has_inv = False
        for b in els:
            if add(a, b) == zero and add(b, a) == zero:
                has_inv = True
                break
        if not has_inv: return False
        for b in els:
            if add(a, b) not in els: return False
            if mul(a, b) not in els: return False
            if add(a, b) != add(b, a): return False
            for c in els:
                if add(add(a, b), c) != add(a, add(b, c)): return False
                if mul(mul(a, b), c) != mul(a, mul(b, c)): return False
                if mul(a, add(b, c)) != add(mul(a, b), mul(a, c)): return False
                if mul(add(a, b), c) != add(mul(a, c), mul(b, c)): return False
    return True

def check_comm_ring(els, add, mul, zero):
    if not check_ring(els, add, mul, zero): return False
    for a in els:
        for b in els:
            if mul(a, b) != mul(b, a): return False
    return True

def conditions(witness):
    try:
        if isinstance(witness, dict):
            R_els = list(witness['R'])
            R_add = witness['add_R']
            R_mul = witness['mul_R']
            R_zero = witness['zero_R']
            S_els = list(witness['S'])
            S_add = witness['add_S']
            S_mul = witness['mul_S']
            S_zero = witness['zero_S']
            f = witness['f']
        elif isinstance(witness, tuple) and len(witness) == 3:
            R_obj, S_obj, f = witness
            R_els = list(R_obj.elements)
            R_add = R_obj.add
            R_mul = R_obj.mul
            R_zero = R_obj.zero
            S_els = list(S_obj.elements)
            S_add = S_obj.add
            S_mul = S_obj.mul
            S_zero = S_obj.zero
        elif isinstance(witness, tuple) and len(witness) == 9:
            R_els, R_add, R_mul, R_zero, S_els, S_add, S_mul, S_zero, f = witness
            R_els = list(R_els)
            S_els = list(S_els)
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    if isinstance(f, dict):
        f_func = lambda x: f[x]
    else:
        f_func = f

    h1 = False
    try:
        h1 = check_ring(R_els, R_add, R_mul, R_zero)
    except Exception:
        pass

    h2 = False
    try:
        h2 = check_comm_ring(S_els, S_add, S_mul, S_zero)
    except Exception:
        pass

    neg_q = False
    try:
        for x in R_els:
            fx = f_func(x)
            if fx not in S_els:
                raise ValueError("f(x) not in S")
        
        neg_R = {}
        for a in R_els:
            for b in R_els:
                if R_add(a, b) == R_zero:
                    neg_R[a] = b
                    break
            if a not in neg_R:
                raise ValueError("No additive inverse")
        
        commutators = []
        for a in R_els:
            for b in R_els:
                ab = R_mul(a, b)
                ba = R_mul(b, a)
                if ab not in R_els or ba not in R_els:
                    raise ValueError("Not closed")
                minus_ba = neg_R[ba]
                comm = R_add(ab, minus_ba)
                if comm not in R_els:
                    raise ValueError("Not closed")
                if comm not in commutators:
                    commutators.append(comm)
        
        ideal = []
        for c in commutators:
            if c not in ideal:
                ideal.append(c)
        
        changed = True
        while changed:
            changed = False
            new_elements = []
            for x in ideal:
                for y in ideal:
                    s = R_add(x, y)
                    if s not in R_els: raise ValueError("Not closed")
                    if s not in ideal and s not in new_elements:
                        new_elements.append(s)
                for r in R_els:
                    rx = R_mul(r, x)
                    if rx not in R_els: raise ValueError("Not closed")
                    if rx not in ideal and rx not in new_elements:
                        new_elements.append(rx)
                    xr = R_mul(x, r)
                    if xr not in R_els: raise ValueError("Not closed")
                    if xr not in ideal and xr not in new_elements:
                        new_elements.append(xr)
                nx = neg_R[x]
                if nx not in ideal and nx not in new_elements:
                    new_elements.append(nx)
            if new_elements:
                ideal.extend(new_elements)
                changed = True
        
        for x in ideal:
            if f_func(x) != S_zero:
                neg_q = True
                break
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]