import itertools

class FiniteRing:
    def __init__(self, elements, add, mul, zero):
        self.elements = list(elements)
        self.add = add
        self.mul = mul
        self.zero = zero

def make_Zn(n):
    return FiniteRing(
        elements=list(range(n)),
        add=lambda a, b: (a + b) % n,
        mul=lambda a, b: (a * b) % n,
        zero=0
    )

Z2 = make_Zn(2)
Z3 = make_Zn(3)
Z4 = make_Zn(4)
Z6 = make_Zn(6)

def make_M2_Z2():
    elements = list(itertools.product(range(2), repeat=4))
    def add(A, B):
        return tuple((a+b)%2 for a, b in zip(A, B))
    def mul(A, B):
        return (
            (A[0]*B[0] + A[1]*B[2])%2,
            (A[0]*B[1] + A[1]*B[3])%2,
            (A[2]*B[0] + A[3]*B[2])%2,
            (A[2]*B[1] + A[3]*B[3])%2
        )
    return FiniteRing(elements, add, mul, (0,0,0,0))

