import itertools

class FiniteRing:
    def __init__(self, elements, add_func, mul_func):
        self.elements = list(elements)
        self.add = add_func
        self.mul = mul_func
        self.zero = self.elements[0]

    def is_ideal(self, I):
        I_set = set(I)
        if not I_set.issubset(set(self.elements)): 
            return False
        if self.zero not in I_set: 
            return False
        for x in I_set:
            for y in I_set:
                if self.add(x, y) not in I_set: 
                    return False
        for x in I_set:
            for r in self.elements:
                if self.mul(r, x) not in I_set: 
                    return False
                if self.mul(x, r) not in I_set: 
                    return False
        return True

    def is_proper_ideal(self, I):
        return self.is_ideal(I) and set(I) != set(self.elements)

    def ideal_generated_by(self, e):
        gen = {e}
        queue = [e]
        while queue:
            x = queue.pop(0)
            
            for r in self.elements:
                mx = self.mul(r, x)
                if mx not in gen:
                    gen.add(mx)
                    queue.append(mx)
                xm = self.mul(x, r)
                if xm not in gen:
                    gen.add(xm)
                    queue.append(xm)
                    
            current_gen = list(gen)
            for y in current_gen:
                s = self.add(x, y)
                if s not in gen:
                    gen.add(s)
                    queue.append(s)
                    
        return frozenset(gen)

    def is_generated_by_idempotent(self, I):
        I_set = set(I)
        for e in self.elements:
            if self.mul(e, e) == e:
                if self.ideal_generated_by(e) == I_set:
                    return True
        return False

    def is_left_flat(self, I):
        for x in I:
            if not any(x == self.mul(x, y) for y in I):
                return False
        return True

    def is_right_flat(self, I):
        for x in I:
            if not any(x == self.mul(y, x) for y in I):
                return False
        return True

def UpperTriangularMatrixRingOverF2(n):
    elements = []
    indices = [(i, j) for i in range(n) for j in range(i, n)]
    for vals in itertools.product([0, 1], repeat=len(indices)):
        mat = [0] * (n * n)
        for (i, j), val in zip(indices, vals):
            mat[i * n + j] = val
        elements.append(tuple(mat))
    
    def add(A, B):
        return tuple((a + b) % 2 for a, b in zip(A, B))
        
    def mul(A, B):
        C = [0] * (n * n)
        for i in range(n):
            for j in range(i, n):
                s = 0
                for k in range(i, j + 1):
                    s += A[i * n + k] * B[k * n + j]
                C[i * n + j] = s % 2
        return tuple(C)
        
    return FiniteRing(elements, add, mul)

def MatrixRingOverF2(n):
    elements = []
    for vals in itertools.product([0, 1], repeat=n*n):
        elements.append(tuple(vals))
    
    def add(A, B):
        return tuple((a + b) % 2 for a, b in zip(A, B))
        
    def mul(A, B):
        C = [0] * (n * n)
        for i in range(n):
            for j in range(n):
                s = 0
                for k in range(n):
                    s += A[i * n + k] * B[k * n + j]
                C[i * n + j] = s % 2
        return tuple(C)
        
    return FiniteRing(elements, add, mul)

