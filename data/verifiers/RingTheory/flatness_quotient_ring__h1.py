def conditions(witness) -> list[bool]:
    try:
        R, I = witness
    except Exception:
        return [False, False]
        
    try:
        h1 = R.is_proper_ideal(I)
    except Exception:
        h1 = False

    try:
        is_idemp_gen = R.is_generated_by_idempotent(I)
        is_left_flat = R.is_left_flat(I)
        is_right_flat = R.is_right_flat(I)
        
        is_flat = is_left_flat or is_right_flat
        
        neg_q = (is_flat != is_idemp_gen)
    except Exception:
        neg_q = False

    return [h1, neg_q]

