# Top-level setup
# No specific named bindings are required for this domain beyond standard sympy objects.

def conditions(witness) -> list[bool]:
    """
    Checks whether the witness is a valid counterexample to the false conjecture.
    The witness should be a tuple: (k, X, kX, u, is_unit_in_kX, is_nonzero_scalar_in_k)
    where:
      - k is the field
      - X is the set of variables
      - kX is the free associative algebra over k generated by X
      - u is the element in question
      - is_unit_in_kX is a boolean function or value indicating if u is a unit in kX
      - is_nonzero_scalar_in_k is a boolean function or value indicating if u is a non-zero scalar in k
    """
    try:
        k, X, kX, u, is_unit_in_kX, is_nonzero_scalar_in_k = witness
    except Exception:
        return [False, False, False, False]

    # H1: k is a field
    try:
        # Check if k has a property is_Field or if it's a known sympy Field
        h1_ok = getattr(k, 'is_Field', False) or isinstance(k, sympy.polys.domains.Field)
    except Exception:
        h1_ok = False

    # H2: X is a set of variables
    try:
        h2_ok = isinstance(X, (set, list, tuple))
    except Exception:
        h2_ok = False

    # H3: k<X> is the free associative algebra over k generated by X
    try:
        # We assume the witness provides a valid representation of the free algebra
        # and we just check if it's not None as a basic sanity check.
        h3_ok = kX is not None
    except Exception:
        h3_ok = False

    # ¬Q: The conclusion must FAIL at the witness.
    # Conclusion: u is a unit in k<X> if and only if u is a non-zero scalar in k
    # Negation: (u is a unit in k<X>) != (u is a non-zero scalar in k)
    try:
        unit_val = bool(is_unit_in_kX(u) if callable(is_unit_in_kX) else is_unit_in_kX)
        scalar_val = bool(is_nonzero_scalar_in_k(u) if callable(is_nonzero_scalar_in_k) else is_nonzero_scalar_in_k)
        neg_q_ok = (unit_val != scalar_val)
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, h3_ok, neg_q_ok]

