def is_ideal(val):
    """In Z, any integer generates an ideal."""
    return isinstance(val, (int, Integer))

def is_primary(n):
    """Check if the ideal (n) is primary in Z.
    In Z, (n) is primary iff n = 0 or n = p^k for some prime p and k >= 1.
    """
    n = abs(int(n))
    if n == 0:
        return True
    if n == 1:
        return False
    factors = factorint(n)
    return len(factors) == 1

def radical(n):
    """Compute the generator of the radical of the ideal (n) in Z."""
    n = abs(int(n))
    if n == 0:
        return 0
    if n == 1:
        return 1
    factors = factorint(n)
    res = 1
    for p in factors:
        res *= p
    return res

def lcm_list(lst):
    """Compute the LCM of a list of integers, which corresponds to ideal intersection in Z."""
    if not lst:
        return 1
    lst = [abs(int(x)) for x in lst]
    if 0 in lst:
        return 0
    res = lst[0]
    for x in lst[1:]:
        res = (res * x) // math.gcd(res, x)
    return res

def is_irredundant_primary_decomp(n, vals):
    """
    Check if the set of ideals generated by `vals` forms an irredundant 
    primary decomposition of the ideal (n) in Z.
    """
    n = abs(int(n))
    vals = [abs(int(v)) for v in vals]
    
    # 1. The intersection of the ideals must be (n)
    if lcm_list(vals) != n:
        return False
        
    # 2. Each ideal must be primary
    for v in vals:
        if not is_primary(v):
            return False
            
    # 3. The decomposition must be irredundant (no ideal can be removed)
    for i in range(len(vals)):
        others = vals[:i] + vals[i+1:]
        if lcm_list(others) == n:
            return False
            
    # 4. The associated primes (radicals) must be distinct
    rads = [radical(v) for v in vals]
    if len(set(rads)) != len(rads):
        return False
        
    return True

def conditions(witness):
    """
    Expects witness in the form: (I_val, J_val, Q_vals, P_vals)
    where I_val and J_val are integers generating ideals I and J in Z,
    and Q_vals and P_vals are lists/tuples of integers generating the primary components.
    """
    try:
        I_val, J_val, Q_vals, P_vals = witness
    except Exception:
        return [False, False, False, False]
        
    try:
        h1 = is_ideal(I_val) and is_ideal(J_val)
    except Exception:
        h1 = False
        
    try:
        h2 = is_irredundant_primary_decomp(I_val, Q_vals)
    except Exception:
        h2 = False
        
    try:
        h3 = is_irredundant_primary_decomp(J_val, P_vals)
    except Exception:
        h3 = False
        
    try:
        # The intersection I \cap J in Z is generated by the LCM of I_val and J_val
        I_cap_J = lcm_list([I_val, J_val])
        
        # The combined set of primary ideals from both decompositions
        combined_vals = list(Q_vals) + list(P_vals)
        
        # The conclusion claims that this combined set IS a primary decomposition of I \cap J.
        # The conclusion FAILS (neg_q is True) if it is NOT a valid irredundant primary decomposition.
        neg_q = not is_irredundant_primary_decomp(I_cap_J, combined_vals)
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

