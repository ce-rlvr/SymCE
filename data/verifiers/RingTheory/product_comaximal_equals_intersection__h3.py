import sympy
from sympy import ZZ, QQ
from sympy.abc import x, y, z
import functools

# Top-level setup
# We provide standard commutative rings and symbols for the witness to use.
# A typical witness would be (ZZ, [2], [4]) or (QQ[x], [x], [x]).

def conditions(witness):
    try:
        R, I, J = witness
    except Exception:
        return [False, False, False]

    # H1: R is a commutative ring
    h1 = False
    try:
        if R == ZZ or R == QQ:
            h1 = True
        elif hasattr(R, 'is_commutative') and R.is_commutative:
            h1 = True
        elif hasattr(R, 'domain') and hasattr(R, 'symbols'):
            h1 = True
    except Exception:
        pass

    # H2: I and J are ideals of R
    h2 = False
    try:
        if not isinstance(I, (list, tuple, set)):
            I_list = [I]
        else:
            I_list = list(I)
            
        if not isinstance(J, (list, tuple, set)):
            J_list = [J]
        else:
            J_list = list(J)
            
        if len(I_list) > 0 and len(J_list) > 0:
            h2 = True
    except Exception:
        pass

    # neg_Q: IJ != I \cap J
    neg_q = False
    try:
        def get_gen(ideal_list):
            if len(ideal_list) == 1:
                return ideal_list[0]
            return functools.reduce(sympy.gcd, ideal_list)
            
        gen_I = get_gen(I_list)
        gen_J = get_gen(J_list)
        
        # In a PID, the product ideal is generated by the product of generators
        gen_IJ = gen_I * gen_J
        
        # In a PID, the intersection ideal is generated by the LCM of generators
        gen_I_cap_J = sympy.lcm(gen_I, gen_J)
        
        def divides(a, b):
            if a == 0:
                return b == 0
            if isinstance(a, (int, sympy.Integer)) and isinstance(b, (int, sympy.Integer)):
                return b % a == 0
            try:
                q, r = sympy.div(b, a)
                return r == 0
            except Exception:
                return False
                
        def same_ideal(g1, g2):
            return divides(g1, g2) and divides(g2, g1)
            
        neg_q = not same_ideal(gen_IJ, gen_I_cap_J)
    except Exception:
        pass

    return [h1, h2, neg_q]

