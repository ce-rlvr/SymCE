import sympy
from sympy import symbols

X, Y, Z, W = symbols('X Y Z W')
x, y, z, w = symbols('x y z w')

def conditions(witness):
    try:
        if isinstance(witness, dict):
            R_gens = witness.get('R', witness.get('R_gens', []))
            S_gens = witness.get('S', witness.get('S_gens', []))
            Q1_gens = witness.get('Q1', witness.get('Q1_gens', []))
            Q2_gens = witness.get('Q2', witness.get('Q2_gens', []))
        else:
            R_gens, S_gens, Q1_gens, Q2_gens = witness
            
        def extract_gens(obj):
            if isinstance(obj, (list, tuple, set)):
                raw_gens = list(obj)
            elif hasattr(obj, 'gens'):
                raw_gens = list(obj.gens)
            else:
                raw_gens = []
                
            for g in raw_gens:
                if not isinstance(g, (sympy.Symbol, str)):
                    raise ValueError("Invalid generator: must be a Symbol or string")
                if isinstance(g, str) and not g.isidentifier():
                    raise ValueError("String generator must be a valid identifier")
                    
            return set(str(g) for g in raw_gens)

        R_gens = extract_gens(R_gens)
        S_gens = extract_gens(S_gens)
        Q1_gens = extract_gens(Q1_gens)
        Q2_gens = extract_gens(Q2_gens)
            
    except Exception:
        return [False] * 6

    # H1: R and S are commutative rings with identity
    try:
        # Represented as polynomial rings over a base field generated by the given variables
        h1 = True
    except Exception:
        h1 = False

    # H2: R is a subring of S
    try:
        h2 = R_gens.issubset(S_gens)
    except Exception:
        h2 = False

    # H3: Q_1 and Q_2 are prime ideals of S
    try:
        # An ideal generated by a subset of variables in a polynomial ring is prime
        h3 = Q1_gens.issubset(S_gens) and Q2_gens.issubset(S_gens)
    except Exception:
        h3 = False

    # H4: Q_1 is a subset of Q_2
    try:
        h4 = Q1_gens.issubset(Q2_gens)
    except Exception:
        h4 = False

    # H5: Q_1 \cap R = Q_2 \cap R
    try:
        h5 = Q1_gens.intersection(R_gens) == Q2_gens.intersection(R_gens)
    except Exception:
        h5 = False

    # neg_Q: Q_1 != Q_2
    try:
        neg_q = Q1_gens != Q2_gens
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, h5, neg_q]

