import sympy
import math

# Top-level setup for potential witness evaluation
Z = sympy.S.Integers

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "Let R be a PID, M an R-module, r a non-zero element of R. 
    Then the annihilator of rx is generated by a / gcd(a, r)."
    
    The dropped hypothesis was that the annihilator of x is generated by a.
    Without it, 'a' does not necessarily generate Ann(x), so the conclusion fails.
    
    Expected witness format: a tuple (r, a, x_order) or a dict with these keys,
    where x_order is the generator of the annihilator of x.
    """
    try:
        # Unpack witness
        if isinstance(witness, dict):
            r = witness.get('r')
            a = witness.get('a')
            x_order = witness.get('x_order', witness.get('x', 0))
        elif hasattr(witness, 'r') and hasattr(witness, 'a'):
            r = witness.r
            a = witness.a
            x_order = getattr(witness, 'x_order', getattr(witness, 'x', 0))
        elif isinstance(witness, (tuple, list)):
            if len(witness) >= 3:
                # Assume the last three elements are r, a, x_order
                r = witness[-3]
                a = witness[-2]
                x_order = witness[-1]
            else:
                return [False, False, False, False]
        else:
            return [False, False, False, False]

        # H1: R is a principal ideal domain (We assume R=Z or F[x], which are PIDs)
        h1 = True
        
        # H2: M is an R-module (We assume M is a valid module like Z/x_order Z)
        h2 = True
        
        # H3: r is a non-zero element of R
        if hasattr(r, 'is_zero') and r.is_zero is not None:
            h3 = not r.is_zero
        else:
            h3 = (r != 0)
            
        # Convert to sympy objects for safe algebraic manipulation
        r_sym = sympy.sympify(r)
        a_sym = sympy.sympify(a)
        x_sym = sympy.sympify(x_order)
        
        # Calculate the actual generator of Ann(rx)
        # Ann(rx) is generated by x_order / gcd(x_order, r)
        actual_gcd = sympy.gcd(x_sym, r_sym)
        if actual_gcd == 0:
            actual_gen = sympy.S.Zero
        else:
            actual_gen = sympy.cancel(x_sym / actual_gcd)
            
        # Calculate the proposed generator of Ann(rx)
        # The conjecture claims it is a / gcd(a, r)
        proposed_gcd = sympy.gcd(a_sym, r_sym)
        if proposed_gcd == 0:
            proposed_gen = sympy.S.Zero
        else:
            proposed_gen = sympy.cancel(a_sym / proposed_gcd)
            
        # Check if the actual generator and proposed generator generate the same ideal.
        # In a PID, they generate the same ideal iff they are associates (differ by a unit).
        if actual_gen == 0 and proposed_gen == 0:
            neg_q = False
        elif actual_gen == 0 or proposed_gen == 0:
            neg_q = True
        else:
            div1 = sympy.cancel(actual_gen / proposed_gen)
            div2 = sympy.cancel(proposed_gen / actual_gen)
            
            if r_sym.is_integer and a_sym.is_integer and x_sym.is_integer:
                # In Z, the only units are 1 and -1
                neg_q = not (abs(div1) == 1 and abs(div2) == 1)
            else:
                # In F[x], any non-zero constant is a unit
                neg_q = not (div1.is_number and div2.is_number)

        return [bool(h1), bool(h2), bool(h3), bool(neg_q)]
    except Exception:
        return [False, False, False, False]

