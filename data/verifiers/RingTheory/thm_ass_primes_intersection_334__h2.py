import math
import sympy
from sympy.ntheory import primefactors

# Top-level setup for the witness namespace
Z = sympy.S.Integers
QQ = sympy.S.Rationals

def conditions(witness) -> list[bool]:
    """
    Given a witness (R, I, J), checks if it is a valid counterexample to the conjecture.
    For this verifier, we model the Noetherian ring R as the ring of integers Z.
    I is a subset of Z (represented as a list/set/tuple of integers).
    J is an ideal in Z (represented by its integer generator).
    """
    try:
        R, I, J = witness
    except Exception:
        return [False, False, False]
        
    # H_1: R is a Noetherian ring
    try:
        # Z is a principal ideal domain, hence Noetherian.
        h1_ok = bool(R == 'Z' or R == sympy.S.Integers)
    except Exception:
        h1_ok = False
        
    # H_2: J is an ideal in R
    try:
        # In Z, any integer generates an ideal.
        h2_ok = isinstance(J, int)
    except Exception:
        h2_ok = False
        
    # ¬Q: Ass(R/(I \cap J)) is NOT a subset of Ass(R/I) \cup Ass(R/J)
    try:
        if not isinstance(I, (list, set, tuple)):
            neg_q_ok = False
        else:
            # I is a subset of Z.
            # J is an ideal of Z, so it contains all multiples of its generator J.
            if J == 0:
                I_cap_J = [x for x in I if x == 0]
            else:
                I_cap_J = [x for x in I if x % J == 0]
                
            def get_gcd(lst):
                if not lst:
                    return 0
                g = lst[0]
                for x in lst[1:]:
                    g = math.gcd(g, x)
                return g
                
            def Ass(n):
                """Returns the associated primes of Z/nZ."""
                n = abs(n)
                if n == 0:
                    return {0}
                elif n == 1:
                    return set()
                else:
                    return set(primefactors(n))
                    
            # The quotient R/S for a subset S implicitly means R/<S> where <S> is the ideal generated by S.
            gen_I = get_gcd(list(I))
            gen_I_cap_J = get_gcd(I_cap_J)
            gen_J = J
            
            ass_I_cap_J = Ass(gen_I_cap_J)
            ass_I = Ass(gen_I)
            ass_J = Ass(gen_J)
            
            # The conclusion fails if Ass(R/<I \cap J>) is NOT a subset of Ass(R/<I>) \cup Ass(R/J)
            neg_q_ok = not ass_I_cap_J.issubset(ass_I.union(ass_J))
    except Exception:
        neg_q_ok = False
        
    return [h1_ok, h2_ok, neg_q_ok]

