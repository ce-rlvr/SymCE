import sympy
from sympy.abc import x, y, z, w

# Top-level setup
# Symbols x, y, z, w are provided for constructing polynomial ring witnesses.

def conditions(witness) -> list[bool]:
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "In any ring R, if a|c and b|c, then lcm(a, b)|c."
    
    Expected witness formats:
      1. dict: {'gens': (x, y, ...), 'I': [poly1, ...], 'a': expr, 'b': expr, 'c': expr, 'domain': 'QQ'}
      2. tuple: (gens, I, a, b, c)
      3. tuple: (a, b, c)  # For simple rings without a quotient ideal
    """
    h1 = False
    h2 = False
    h3 = False
    neg_q = False
    
    try:
        if isinstance(witness, dict):
            gens = witness.get('gens', [])
            I = witness.get('I', [])
            a = witness['a']
            b = witness['b']
            c = witness['c']
            domain = witness.get('domain', 'QQ')
        elif len(witness) == 5:
            gens, I, a, b, c = witness
            domain = 'QQ'
        elif len(witness) == 3:
            a, b, c = witness
            gens = []
            I = []
            domain = 'QQ'
        else:
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]

    # H1: a, b, c are elements of R
    try:
        h1 = True
    except Exception:
        h1 = False

    if not gens and not I:
        # Simple divisibility (e.g., integers or free polynomial rings)
        # H2: a divides c
        try:
            try:
                h2 = bool(sympy.rem(c, a) == 0)
            except Exception:
                h2 = bool(c % a == 0)
        except Exception:
            h2 = False
            
        # H3: b divides c
        try:
            try:
                h3 = bool(sympy.rem(c, b) == 0)
            except Exception:
                h3 = bool(c % b == 0)
        except Exception:
            h3 = False
            
        # neg_Q: lcm(a, b) does not divide c
        try:
            m = sympy.lcm(a, b)
            try:
                q = bool(sympy.rem(c, m) == 0)
            except Exception:
                q = bool(c % m == 0)
            neg_q = not q
        except Exception:
            neg_q = False
            
    else:
        # Divisibility in a quotient ring R = K[gens] / I
        def divides(u, v):
            # u divides v modulo I iff v is in the ideal generated by I and u.
            # We check this by computing the Groebner basis of I + (u) and reducing v.
            GB = sympy.groebner(list(I) + [u], *gens, domain=domain)
            rem = sympy.reduced(v, list(GB), *gens, domain=domain)[1]
            return rem == 0

        # H2: a divides c
        try:
            h2 = bool(divides(a, c))
        except Exception:
            h2 = False
            
        # H3: b divides c
        try:
            h3 = bool(divides(b, c))
        except Exception:
            h3 = False
            
        # neg_Q: lcm(a, b) does not divide c
        try:
            # Compute the formal LCM in the free polynomial ring
            m = sympy.lcm(a, b)
            q = bool(divides(m, c))
            neg_q = not q
        except Exception:
            neg_q = False

    return [h1, h2, h3, neg_q]

