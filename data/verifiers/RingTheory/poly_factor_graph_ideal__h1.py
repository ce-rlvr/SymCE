import sympy
from sympy import Matrix, symbols, eye, zeros

x, y = symbols('x y')
A, B = symbols('A B', commutative=False)
I2 = eye(2)
O2 = zeros(2, 2)

def conditions(witness):
    try:
        if isinstance(witness, tuple):
            if len(witness) == 2:
                R_gens, f = witness
            elif len(witness) >= 3:
                R_gens, f = witness[0], witness[1]
            else:
                R_gens = witness[0]
                f = x
        else:
            R_gens = witness
            f = x
    except Exception:
        return [False, False, False]

    try:
        if not isinstance(R_gens, (list, tuple)):
            R_gens = [R_gens]
        h1 = len(R_gens) > 0
    except Exception:
        h1 = False

    try:
        h2 = False
        if hasattr(f, 'free_symbols'):
            h2 = y not in f.free_symbols
        elif isinstance(f, (int, float, complex)):
            h2 = True
        elif isinstance(f, sympy.MatrixBase):
            h2 = y not in f.free_symbols
    except Exception:
        h2 = False

    try:
        neg_q = False
        if h1 and h2:
            for r in R_gens:
                diff = f * r - r * f
                if hasattr(diff, 'expand'):
                    diff = diff.expand()
                is_zero = False
                if isinstance(diff, sympy.MatrixBase):
                    diff = sympy.simplify(diff)
                    if diff.is_zero_matrix:
                        is_zero = True
                    elif all(hasattr(e, 'is_zero') and e.is_zero for e in diff):
                        is_zero = True
                    elif all(e == 0 for e in diff):
                        is_zero = True
                else:
                    if hasattr(diff, 'simplify'):
                        diff = diff.simplify()
                    if hasattr(diff, 'is_zero') and diff.is_zero:
                        is_zero = True
                    elif diff == 0:
                        is_zero = True
                if not is_zero:
                    neg_q = True
                    break
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

