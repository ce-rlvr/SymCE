import sympy
import sympy.polys

def conditions(witness):
    """
    Checks if the witness satisfies the remaining hypotheses and fails the conclusion.
    
    Remaining hypotheses:
      H1: k is an algebraically closed field
      H2: M is an ideal in the polynomial ring over k
      
    Conclusion to fail (neg_Q):
      M is a maximal ideal if and only if there exist elements a_1, ..., a_n in k 
      such that M is generated by the polynomials x_1 - a_1, ..., x_n - a_n.
    """
    h1 = False
    h2 = False
    neg_q = False
    
    try:
        # Parse the witness into an ideal and its underlying ring/field
        if hasattr(witness, 'ring') and hasattr(witness, 'groebner_basis'):
            M = witness
            ring = M.ring
            k = ring.domain
            gens = ring.gens
            gb = list(M.groebner_basis())
        elif isinstance(witness, (list, tuple)) and len(witness) > 0:
            polys = [sympy.sympify(p) for p in witness]
            gens = list(set().union(*[p.free_symbols for p in polys]))
            gens.sort(key=lambda x: x.name)
            if not gens:
                return [False, False, False]
            gb_obj = sympy.groebner(polys, *gens)
            gb = gb_obj.polys
            k = gb_obj.domain
        else:
            return [False, False, False]
            
        # H1: k is an algebraically closed field
        if k.is_Field:
            name = getattr(k, 'name', str(k))
            if 'CC' in name or 'Complex' in name or 'QQbar' in name or 'Algebraic' in name:
                h1 = True
            elif hasattr(k, 'is_algebraically_closed') and k.is_algebraically_closed:
                h1 = True
            else:
                h1 = False
                
        # H2: M is an ideal in the polynomial ring over k
        # If we successfully extracted generators and a field domain, it is a valid ideal.
        h2 = True
        
        # neg_Q: M is maximal XOR M is generated by x_1 - a_1, ..., x_n - a_n
        n = len(gens)
        
        # Check if M is generated by x_1 - a_1, ..., x_n - a_n
        is_generated_by_linear = False
        if len(gb) == n:
            lts = set()
            is_linear = True
            for g in gb:
                if not isinstance(g, sympy.Poly):
                    g_poly = sympy.Poly(g, *gens)
                else:
                    g_poly = g
                
                if g_poly.total_degree() != 1:
                    is_linear = False
                    break
                
                vars_deg1 = [gen for gen in gens if g_poly.degree(gen) == 1]
                if len(vars_deg1) != 1:
                    is_linear = False
                    break
                
                lts.add(vars_deg1[0])
                
            if is_linear and lts == set(gens):
                is_generated_by_linear = True
                
        # Check if M is a maximal ideal
        is_maximal = False
        if is_generated_by_linear:
            # If it is generated by x_1 - a_1, ..., x_n - a_n, the quotient is k, which is a field.
            is_maximal = True
        else:
            # If it's not linear, we can definitively check maximality for n = 1
            if n == 1:
                if len(gb) == 1:
                    p = gb[0]
                    if not isinstance(p, sympy.Poly):
                        p_poly = sympy.Poly(p, *gens)
                    else:
                        p_poly = p
                        
                    if p_poly.degree() > 0 and p_poly.is_irreducible:
                        is_maximal = True
                        
        # The conclusion is an iff statement. It fails if the two sides have different truth values.
        neg_q = (is_maximal != is_generated_by_linear)
        
    except Exception:
        pass
        
    return [h1, h2, neg_q]

