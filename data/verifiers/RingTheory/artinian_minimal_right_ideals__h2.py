CONDITION_LABELS = [
    "H_1: R is a right Artinian ring",
    "¬Q: The ideal I does not contain a minimal non-zero right ideal of R"
]

N_HYP = 1
NEG_Q_INDEX = 1

def conditions(witness):
    try:
        if isinstance(witness, dict):
            R = witness.get('R')
            I = witness.get('I')
        else:
            R, I = witness
    except Exception:
        return [False, False]
    
    # H_1: R is a right Artinian ring
    # We represent the ring R = Z/nZ by an integer n >= 2.
    # Finite rings are always right Artinian.
    try:
        if isinstance(R, int) and R >= 2:
            h1_ok = True
        else:
            h1_ok = False
    except Exception:
        h1_ok = False
        
    # ¬Q: The ideal I does not contain a minimal non-zero right ideal of R
    try:
        if isinstance(R, int) and R >= 2:
            n = R
            try:
                I_set = set(e % n for e in I)
            except TypeError:
                I_set = set()
                
            # First, verify that I is actually an ideal in Z/nZ
            is_ideal = True
            if not I_set:
                is_ideal = False
            else:
                for a in I_set:
                    for b in I_set:
                        if (a + b) % n not in I_set:
                            is_ideal = False
                    for r in range(n):
                        if (a * r) % n not in I_set:
                            is_ideal = False
                            
            if not is_ideal:
                neg_q_ok = False
            else:
                # Find all minimal non-zero ideals of Z/nZ.
                # In Z/nZ, minimal non-zero ideals are generated by n/p for prime factors p of n.
                primes = primefactors(n)
                contains_min = False
                for p in primes:
                    gen = n // p
                    M_p = set((gen * x) % n for x in range(n))
                    if M_p.issubset(I_set):
                        contains_min = True
                        break
                neg_q_ok = not contains_min
        else:
            neg_q_ok = False
    except Exception:
        neg_q_ok = False
        
    return [h1_ok, neg_q_ok]