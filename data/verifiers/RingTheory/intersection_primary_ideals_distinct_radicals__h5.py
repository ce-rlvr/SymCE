import math

class Z_Ideal:
    """
    Represents an ideal in the commutative ring of integers Z.
    Ideals in Z are generated by a single non-negative integer.
    """
    def __init__(self, gen):
        self.gen = abs(gen)
        
    def intersection(self, other):
        if self.gen == 0 or other.gen == 0:
            return Z_Ideal(0)
        return Z_Ideal(abs(self.gen * other.gen) // math.gcd(self.gen, other.gen))
        
    def is_subset(self, other):
        # self is a subset of other iff other.gen divides self.gen
        if other.gen == 0:
            return self.gen == 0
        return self.gen % other.gen == 0

    def radical(self):
        if self.gen == 0:
            return Z_Ideal(0)
        if self.gen == 1:
            return Z_Ideal(1)
        n = self.gen
        rad = 1
        d = 2
        while d * d <= n:
            if n % d == 0:
                rad *= d
                while n % d == 0:
                    n //= d
            d += 1
        if n > 1:
            rad *= n
        return Z_Ideal(rad)

    def is_prime(self):
        if self.gen == 0:
            return True
        if self.gen == 1:
            return False
        n = self.gen
        for d in range(2, int(math.isqrt(n)) + 1):
            if n % d == 0:
                return False
        return True

    def is_primary(self):
        if self.gen == 0:
            return True
        if self.gen == 1:
            return False
        rad = self.radical()
        return rad.is_prime()

def conditions(witness) -> list[bool]:
    """
    Evaluates the hypotheses and the negated conclusion for the given witness.
    
    Expected witness formats:
      - A tuple or list of 4 integers (q1, q2, p1, p2) representing the generators 
        of the ideals Q_1, Q_2, P_1, P_2 in the ring of integers Z.
      - A dictionary with keys 'q1', 'q2', 'p1', 'p2' mapping to integers.
      - A custom object implementing the required ring and ideal methods.
    """
    try:
        if isinstance(witness, dict):
            Q1 = Z_Ideal(witness["q1"])
            Q2 = Z_Ideal(witness["q2"])
            P1 = Z_Ideal(witness["p1"])
            P2 = Z_Ideal(witness["p2"])
        elif isinstance(witness, (tuple, list)) and len(witness) == 4:
            q1, q2, p1, p2 = witness
            if isinstance(q1, int):
                Q1, Q2, P1, P2 = map(Z_Ideal, witness)
            else:
                Q1, Q2, P1, P2 = witness
        else:
            # Fallback for custom witness objects
            h1 = bool(witness.is_commutative_ring())
            h2 = bool(witness.is_primary_ideal(witness.Q1, witness.P1))
            h3 = bool(witness.is_primary_ideal(witness.Q2, witness.P2))
            h4 = not bool(witness.is_subset(witness.P1, witness.P2))
            
            # Negated conclusion: Q_1 \cap Q_2 IS a primary ideal
            neg_q = bool(witness.is_primary_ideal(witness.intersect(witness.Q1, witness.Q2)))
            return [h1, h2, h3, h4, neg_q]

        # H_1: R is a commutative ring (Z is always a commutative ring)
        h1 = True
        
        # H_2: Q_1 is a P_1-primary ideal in R
        h2 = Q1.is_primary() and Q1.radical().gen == P1.gen
        
        # H_3: Q_2 is a P_2-primary ideal in R
        h3 = Q2.is_primary() and Q2.radical().gen == P2.gen
        
        # H_4: P_1 is not contained in P_2
        h4 = not P1.is_subset(P2)
        
        # ¬Q: The intersection Q_1 \cap Q_2 IS a primary ideal
        neg_q = Q1.intersection(Q2).is_primary()
        
        return [h1, h2, h3, h4, neg_q]
    except Exception:
        return [False, False, False, False, False]

