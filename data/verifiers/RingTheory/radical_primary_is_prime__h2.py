import sympy
from sympy import S, ZZ, QQ

# Top-level setup for potential witness expressions
# We define standard rings that might be used in the witness.
Z = ZZ
Q = QQ

CONDITION_LABELS = [
    "H_1: R is a commutative ring",
    "¬Q: The radical of Q is not a prime ideal"
]

N_HYP = 1
NEG_Q_INDEX = 1

def conditions(witness):
    try:
        # Parse witness
        # The witness can be an integer n (representing the ideal nZ in ZZ),
        # a list of integers (generators in ZZ), a tuple (R, Q), or a dict.
        if isinstance(witness, (int, sympy.Integer)):
            R = ZZ
            Q_gens = [int(witness)]
        elif isinstance(witness, list):
            R = ZZ
            Q_gens = list(witness)
        elif isinstance(witness, tuple) and len(witness) == 2:
            R, Q_ideal = witness
            if isinstance(Q_ideal, (int, sympy.Integer)):
                Q_gens = [int(Q_ideal)]
            elif isinstance(Q_ideal, (list, tuple)):
                Q_gens = list(Q_ideal)
            else:
                return [False, False]
        elif isinstance(witness, dict):
            R = witness.get('R', ZZ)
            Q_ideal = witness.get('Q', 0)
            if isinstance(Q_ideal, (int, sympy.Integer)):
                Q_gens = [int(Q_ideal)]
            elif isinstance(Q_ideal, (list, tuple)):
                Q_gens = list(Q_ideal)
            else:
                return [False, False]
        else:
            return [False, False]

        if not Q_gens:
            Q_gens = [0]

        # H_1: R is a commutative ring
        h1 = False
        if R in (ZZ, S.Integers, QQ, S.Rationals, sympy.RR, S.Reals, sympy.CC, S.Complexes):
            h1 = True
        elif hasattr(R, 'is_commutative'):
            h1 = bool(R.is_commutative)
        elif hasattr(R, 'domain') and hasattr(R.domain, 'is_commutative'):
            h1 = bool(R.domain.is_commutative)

        # ¬Q: The radical of Q is NOT a prime ideal
        neg_q = False
        if R in (ZZ, S.Integers):
            # Calculate the generator of the ideal Q in ZZ
            g = Q_gens[0]
            for val in Q_gens[1:]:
                g = sympy.gcd(g, val)
            n = abs(int(g))
            
            # Calculate the generator of the radical of Q
            # The radical of (n) is generated by the product of its distinct prime factors.
            if n == 0:
                rad_gen = 0
            elif n == 1:
                rad_gen = 1
            else:
                factors = sympy.factorint(n)
                rad_gen = 1
                for p in factors:
                    rad_gen *= p
            
            # Check if the radical is a prime ideal
            # In ZZ, an ideal (m) is prime iff m is a prime number or m == 0
            is_prime_ideal = (rad_gen == 0) or sympy.isprime(rad_gen)
            neg_q = not is_prime_ideal
        else:
            # For rings other than ZZ, computing the radical and checking primality 
            # is non-trivial in sympy. We return False to indicate we couldn't verify it.
            neg_q = False

        return [h1, neg_q]
    except Exception:
        return [False, False]