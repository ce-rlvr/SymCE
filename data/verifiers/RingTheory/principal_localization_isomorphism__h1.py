def conditions(witness) -> list[bool]:
    h1 = False
    h2 = False
    neg_q = False

    if hasattr(witness, 'f_in_R') and hasattr(witness, 'S_generated_by_f'):
        try: 
            h1 = bool(witness.f_in_R())
        except Exception: 
            pass
        try: 
            h2 = bool(witness.S_generated_by_f())
        except Exception: 
            pass
        try: 
            if hasattr(witness, 'is_isomorphic'):
                neg_q = not bool(witness.is_isomorphic())
            elif hasattr(witness, 'conclusion'):
                neg_q = not bool(witness.conclusion())
        except Exception: 
            pass
        return [h1, h2, neg_q]

    R, f, S = None, None, None
    if isinstance(witness, tuple) and len(witness) == 3:
        R, f, S = witness
    elif isinstance(witness, dict):
        R = witness.get('R')
        f = witness.get('f')
        S = witness.get('S')
    elif isinstance(witness, sympy.MatrixBase):
        f = witness
        R = "MatrixRing"
        S = "Powers"
    else:
        f = witness
        R = "Ring"
        S = "Powers"

    try:
        if R == "MatrixRing":
            h1 = bool(f.is_square)
        elif R == "Ring":
            h1 = True
        elif hasattr(R, 'contains'):
            h1 = bool(R.contains(f))
        elif hasattr(R, '__contains__'):
            h1 = bool(f in R)
        else:
            h1 = True
    except Exception:
        h1 = False

    try:
        if S in ("Powers", "Generated"):
            h2 = True
        elif hasattr(S, 'is_generated_by'):
            h2 = bool(S.is_generated_by(f))
        elif hasattr(S, 'generator'):
            h2 = bool(S.generator == f)
        else:
            h2 = True
    except Exception:
        h2 = False

    try:
        if isinstance(f, sympy.MatrixBase):
            is_non_zero_divisor = (f.det() != 0)
            is_central = (f == f[0, 0] * sympy.eye(f.rows))
            neg_q = is_non_zero_divisor and not is_central
        elif hasattr(f, 'is_commutative'):
            if f.is_commutative is False:
                neg_q = True
            else:
                neg_q = False
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

