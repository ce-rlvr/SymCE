def conditions(witness):
    """
    witness is expected to be a tuple (R, I, a, d) where:
      - R is an iterable of ring elements (must support +, *, ==)
      - I is an iterable of elements in the ideal
      - a is the element in I
      - d is a callable or dictionary mapping elements to their norm
    """
    try:
        R, I, a, d = witness
    except Exception:
        return [False, False, False]
        
    try:
        zero = None
        for x in R:
            if all(x + y == y for y in R):
                zero = x
                break
        if zero is None:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    try:
        h1 = False
        if all(x in R for x in I):
            if any(x != zero for x in I):
                closed_add_sub = True
                for x in I:
                    has_inv = False
                    for z in I:
                        if x + z == zero:
                            has_inv = True
                            break
                    if not has_inv:
                        closed_add_sub = False
                        break
                    for y in I:
                        if (x + y) not in I:
                            closed_add_sub = False
                            break
                    if not closed_add_sub:
                        break
                
                closed_mul = True
                for x in I:
                    for r in R:
                        if (r * x) not in I or (x * r) not in I:
                            closed_mul = False
                            break
                    if not closed_mul:
                        break
                
                h1 = closed_add_sub and closed_mul
    except Exception:
        h1 = False

    try:
        h2 = False
        if a in I and a != zero:
            if callable(d):
                d_func = d
            else:
                d_func = lambda x: d[x]
                
            d_a = d_func(a)
            h2 = True
            for x in I:
                if x != zero:
                    if d_a > d_func(x):
                        h2 = False
                        break
    except Exception:
        h2 = False

    try:
        gen_I = [a]
        minus_a = None
        for x in R:
            if a + x == zero:
                minus_a = x
                break
        if minus_a is not None and minus_a not in gen_I:
            gen_I.append(minus_a)
            
        changed = True
        while changed:
            changed = False
            new_elements = []
            for x in gen_I:
                for y in gen_I:
                    s = x + y
                    if s not in gen_I and s not in new_elements:
                        new_elements.append(s)
                for r in R:
                    rx = r * x
                    if rx not in gen_I and rx not in new_elements:
                        new_elements.append(rx)
                    xr = x * r
                    if xr not in gen_I and xr not in new_elements:
                        new_elements.append(xr)
            if new_elements:
                gen_I.extend(new_elements)
                changed = True
                if len(gen_I) > len(R):
                    break # Safety against infinite loops
                    
        neg_q = False
        for x in I:
            if x not in gen_I:
                neg_q = True
                break
        if not neg_q:
            for x in gen_I:
                if x not in I:
                    neg_q = True
                    break
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

