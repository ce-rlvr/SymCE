import math
from sympy.ntheory import factorint

# Top-level setup
# (No specific named bindings required for this domain; witnesses are integers or tuples of integers)

def rad(q):
    """Returns the radical of an integer q (product of its distinct prime factors)."""
    q = abs(q)
    if q == 0:
        return 0
    if q == 1:
        return 1
    r = 1
    for p in factorint(q):
        r *= p
    return r

def conditions(witness):
    """
    Checks the hypotheses and negated conclusion for the given witness.
    The witness represents an ideal Q in a commutative ring R.
    - If witness is an int `q`, R = Z and Q = qZ.
    - If witness is a tuple `(n, q)`, R = Z/nZ and Q is the ideal generated by q.
    """
    try:
        if isinstance(witness, tuple):
            n, q = witness
        else:
            n = 0
            q = witness
            
        n = abs(int(n))
        q = abs(int(q))
        
        # In Z/nZ, the ideal generated by q is the same as the ideal generated by gcd(q, n)
        if n > 0:
            q = math.gcd(q, n)
            
        # H_1: R is a commutative ring
        # Z and Z/nZ are always commutative rings.
        h1_ok = True
        
        # H_2: For any two ideals I and J of R, if I J \subseteq Q and I \not\subseteq Q, then J \subseteq \sqrt{Q}
        h2_ok = True
        if n == 0:
            # In Z, this condition holds iff q is 0, 1, or a prime power.
            if q > 1:
                factors = factorint(q)
                if len(factors) > 1:
                    h2_ok = False
        else:
            # In Z/nZ, ideals are generated by divisors of n.
            divs = [i for i in range(1, n + 1) if n % i == 0]
            rq = math.gcd(rad(q), n)
            for a in divs:
                for b in divs:
                    ab = math.gcd(a * b, n)
                    ij_sub_q = (ab % q == 0)
                    i_sub_q = (a % q == 0)
                    j_sub_rq = (b % rq == 0)
                    
                    if ij_sub_q and not i_sub_q:
                        if not j_sub_rq:
                            h2_ok = False
                            break
                if not h2_ok:
                    break
                    
        # Conclusion: Q is a primary ideal
        # A primary ideal must be proper (q != 1) and satisfy the element-wise condition.
        is_proper = (q != 1)
        is_primary = is_proper
        
        if is_primary:
            if n == 0:
                if q > 1:
                    factors = factorint(q)
                    if len(factors) > 1:
                        is_primary = False
            else:
                rq = math.gcd(rad(q), n)
                for x in range(n):
                    for y in range(n):
                        if (x * y) % q == 0 and x % q != 0:
                            if y % rq != 0:
                                is_primary = False
                                break
                    if not is_primary:
                        break
                        
        neg_q_ok = not is_primary
        
        return [h1_ok, h2_ok, neg_q_ok]
    except Exception:
        return [False, False, False]

