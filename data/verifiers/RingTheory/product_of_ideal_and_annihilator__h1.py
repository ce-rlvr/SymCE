def is_subset(sub, sup):
    for item in sub:
        if item not in sup:
            return False
    return True

def is_ring(R):
    if not R: 
        return False
        
    # Check closure and commutativity of addition
    for a in R:
        for b in R:
            if (a + b) not in R: return False
            if (a - b) not in R: return False
            if (a * b) not in R: return False
            if a + b != b + a: return False
            
    # Check associativity and distributivity
    for a in R:
        for b in R:
            ab = a * b
            apb = a + b
            for c in R:
                if apb + c != a + (b + c): return False
                if ab * c != a * (b * c): return False
                if a * (b + c) != ab + (a * c): return False
                if apb * c != (a * c) + (b * c): return False
                
    # Find additive identity (zero)
    zeros_list = [z_elem for z_elem in R if all((z_elem + a) == a for a in R)]
    if not zeros_list: 
        return False
    zero = zeros_list[0]
    
    # Check additive inverses
    for a in R:
        if not any((a + b) == zero for b in R): 
            return False
            
    return True

def is_ideal(R, I):
    if not I: 
        return False
    if not is_subset(I, R): 
        return False
    
    # Check subgroup under addition (closure under subtraction is sufficient)
    for a in I:
        for b in I:
            if (a - b) not in I: 
                return False
            
    # Check absorbing property (two-sided ideal)
    for r in R:
        for i in I:
            if (r * i) not in I: return False
            if (i * r) not in I: return False
            
    return True

def is_annihilator(R, I, AnnI):
    zeros_list = [z_elem for z_elem in R if all((z_elem + a) == a for a in R)]
    if not zeros_list: 
        return False
    zero = zeros_list[0]
    
    # Calculate left, right, and two-sided annihilators
    left_ann = [x_elem for x_elem in R if all((x_elem * i) == zero for i in I)]
    right_ann = [x_elem for x_elem in R if all((i * x_elem) == zero for i in I)]
    two_sided_ann = [x_elem for x_elem in R if all((x_elem * i) == zero and (i * x_elem) == zero for i in I)]
    
    def same_set(A, B):
        return is_subset(A, B) and is_subset(B, A)
        
    # The witness must provide one of the valid annihilator ideals
    return same_set(AnnI, left_ann) or same_set(AnnI, right_ann) or same_set(AnnI, two_sided_ann)

def conditions(witness):
    try:
        R_iter, I_iter, AnnI_iter = witness
        R = list(R_iter)
        I = list(I_iter)
        AnnI = list(AnnI_iter)
    except Exception:
        return [False, False, False]
        
    # Safeguard against infinite or excessively large rings
    if len(R) > 100 or len(R) == 0:
        return [False, False, False]
        
    # H_1: I is an ideal of R
    try:
        h1_ok = is_ring(R) and is_ideal(R, I)
    except Exception:
        h1_ok = False
        
    # H_2: Ann(I) is the annihilator ideal of I in R
    try:
        h2_ok = is_ideal(R, AnnI) and is_annihilator(R, I, AnnI)
    except Exception:
        h2_ok = False
        
    # ¬Q: I * Ann(I) != {0}
    try:
        zeros_list = [z_elem for z_elem in R if all((z_elem + a) == a for a in R)]
        if not zeros_list:
            neg_q_ok = False
        else:
            zero = zeros_list[0]
            # The ideal I * Ann(I) is generated by elements of the form i * x.
            # It is non-zero if and only if at least one such product is non-zero.
            neg_q_ok = any((i * x_elem) != zero for i in I for x_elem in AnnI)
    except Exception:
        neg_q_ok = False
        
    return [bool(h1_ok), bool(h2_ok), bool(neg_q_ok)]

