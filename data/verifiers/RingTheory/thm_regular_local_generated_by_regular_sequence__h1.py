# Top-level setup: Named rings and ideals for the witness to reference.
# The theorem requires a ring R and a maximal ideal m.
class CommutativeRing:
    def __init__(self, name, is_local, is_regular_local):
        self.name = name
        self.is_local = is_local
        self.is_regular_local = is_regular_local

class Ideal:
    def __init__(self, ring, is_maximal, is_generated_by_regular_sequence):
        self.ring = ring
        self.is_maximal = is_maximal
        self.is_generated_by_regular_sequence = is_generated_by_regular_sequence

# Z is not a local ring, so it is not a regular local ring.
# However, its maximal ideals (e.g., (2)) are generated by a regular sequence (the prime itself).
Z = CommutativeRing("Z", is_local=False, is_regular_local=False)
I_2 = Ideal(Z, is_maximal=True, is_generated_by_regular_sequence=True)
I_3 = Ideal(Z, is_maximal=True, is_generated_by_regular_sequence=True)

# Q[x] is not local, but its maximal ideals are generated by regular sequences.
Qx = CommutativeRing("Q[x]", is_local=False, is_regular_local=False)
I_x = Ideal(Qx, is_maximal=True, is_generated_by_regular_sequence=True)

# Z/4Z is a local ring but not regular. Its maximal ideal (2) is not generated by a regular sequence.
Z4 = CommutativeRing("Z/4Z", is_local=True, is_regular_local=False)
I_Z4_2 = Ideal(Z4, is_maximal=True, is_generated_by_regular_sequence=False)

# Q[x]_(x) is a regular local ring. Its maximal ideal is generated by a regular sequence.
Qx_loc = CommutativeRing("Q[x]_(x)", is_local=True, is_regular_local=True)
I_Qx_loc_x = Ideal(Qx_loc, is_maximal=True, is_generated_by_regular_sequence=True)


def conditions(witness) -> list[bool]:
    try:
        R, m = witness
        
        # Validate the ring and ideal properties to prevent trivial cheating
        if R.name == "Z":
            if R.is_local is not False or R.is_regular_local is not False: 
                return [False]
            if m.is_maximal and not m.is_generated_by_regular_sequence: 
                return [False]
        elif R.name == "Q[x]":
            if R.is_local is not False or R.is_regular_local is not False: 
                return [False]
            if m.is_maximal and not m.is_generated_by_regular_sequence: 
                return [False]
        elif R.name == "Z/4Z":
            if R.is_local is not True or R.is_regular_local is not False: 
                return [False]
            if m.is_maximal and m.is_generated_by_regular_sequence: 
                return [False]
        elif R.name == "Q[x]_(x)":
            if R.is_local is not True or R.is_regular_local is not True: 
                return [False]
            if m.is_maximal and not m.is_generated_by_regular_sequence: 
                return [False]
        else:
            return [False]
            
        # Implicit hypotheses: m must be a maximal ideal of R
        if m.ring != R:
            return [False]
        if not m.is_maximal:
            return [False]
            
        # Evaluate the conclusion: R is a regular local ring iff m is generated by a regular sequence
        lhs = R.is_regular_local
        rhs = m.is_generated_by_regular_sequence
        
        # The conclusion fails if the equivalence does not hold
        neg_q = (lhs != rhs)
        
        return [neg_q]
    except Exception:
        return [False]

