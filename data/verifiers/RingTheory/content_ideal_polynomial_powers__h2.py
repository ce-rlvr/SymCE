import sympy as sp
import itertools

def conditions(witness):
    try:
        # Parse witness
        if len(witness) == 3:
            f, x, n = witness
            x = sp.sympify(x)
        elif len(witness) == 2:
            f, n = witness
            f_sym = sp.sympify(f)
            free = f_sym.free_symbols
            if len(free) == 1:
                x = list(free)[0]
            else:
                x = sp.Symbol('x')
        else:
            return [False] * 4 + [False]
            
        f = sp.sympify(f)
        
        try:
            n = int(n)
        except Exception:
            return [False] * 4 + [False]
            
        # H_1: R is an integral domain
        # We evaluate polynomials over Z or Q (or their polynomial extensions),
        # which are always integral domains.
        H1 = True
        
        # H_2: c(f) is the fractional ideal generated by the coefficients of f
        # This is a definitional hypothesis.
        H2 = True
        
        # H_4: n is a positive integer
        H4 = (n > 0)
        
        # Extract coefficients of f with respect to the main variable x
        try:
            f_poly = sp.Poly(f, x)
            coeffs = f_poly.coeffs()
            gens = list(f.free_symbols - {x})
        except Exception:
            return [False] * 4 + [False]
            
        # H_3: c(f) is an invertible fractional ideal
        # In polynomial rings over Z or Q, an ideal is invertible iff it is principal.
        # The zero ideal is not invertible.
        if all(c == 0 for c in coeffs):
            H3 = False
        elif not gens:
            H3 = True
        else:
            try:
                gb = sp.groebner(coeffs, *gens)
                H3 = (len(gb) == 1)
            except Exception:
                H3 = False
                
        # ¬Q: c(f^n) != c(f)^n
        try:
            fn = sp.expand(f**n)
            fn_poly = sp.Poly(fn, x)
            coeffs_fn = fn_poly.coeffs()
            
            # Generate generators for c(f)^n
            cf_n_gens = []
            for combo in itertools.combinations_with_replacement(coeffs, n):
                prod = 1
                for c in combo:
                    prod *= c
                cf_n_gens.append(prod)
                
            if not gens:
                gcd_fn = coeffs_fn[0] if coeffs_fn else 0
                for c in coeffs_fn[1:]:
                    gcd_fn = sp.gcd(gcd_fn, c)
                
                gcd_cf_n = cf_n_gens[0] if cf_n_gens else 0
                for c in cf_n_gens[1:]:
                    gcd_cf_n = sp.gcd(gcd_cf_n, c)
                
                neg_Q = (abs(gcd_fn) != abs(gcd_cf_n))
            else:
                gb_fn = sp.groebner(coeffs_fn, *gens)
                gb_cf_n = sp.groebner(cf_n_gens, *gens)
                
                # Check mutual inclusion to determine ideal equality
                equal = True
                for a in coeffs_fn:
                    _, rem = sp.reduced(a, gb_cf_n, *gens)
                    if rem != 0:
                        equal = False
                        break
                if equal:
                    for b in cf_n_gens:
                        _, rem = sp.reduced(b, gb_fn, *gens)
                        if rem != 0:
                            equal = False
                            break
                neg_Q = not equal
        except Exception:
            neg_Q = False
            
        return [H1, H2, H3, H4, neg_Q]
    except Exception:
        return [False] * 4 + [False]

