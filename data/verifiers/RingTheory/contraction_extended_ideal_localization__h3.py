# Top-level setup
# The witness is expected to be a dictionary or tuple representing a finite ring Z/nZ,
# a multiplicatively closed subset S, and a subset I.
# Format: {'n': int, 'S': list[int], 'I': list[int]} or (n, S, I)

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, dict):
            n = witness['n']
            S = set(witness['S'])
            I = set(witness['I'])
        else:
            n, S, I = witness
            S = set(S)
            I = set(I)
    except Exception:
        return [False, False, False, False]

    # H_1: R is a commutative ring
    # We use R = Z/nZ for n >= 2.
    try:
        h1 = isinstance(n, int) and not isinstance(n, bool) and n >= 2
        if h1:
            if not all(isinstance(x, int) and not isinstance(x, bool) and 0 <= x < n for x in S):
                h1 = False
            if not all(isinstance(x, int) and not isinstance(x, bool) and 0 <= x < n for x in I):
                h1 = False
    except Exception:
        h1 = False

    # H_2: S is a multiplicatively closed subset of R
    try:
        if h1 and len(S) > 0:
            h2 = True
            for a in S:
                for b in S:
                    if (a * b) % n not in S:
                        h2 = False
                        break
                if not h2:
                    break
        else:
            h2 = False
    except Exception:
        h2 = False

    # H_3: \phi is the canonical localization map from R to S^{-1}R
    # This is a definitional hypothesis that holds by construction in our evaluation.
    h3 = True

    # ¬Q: The contraction of the extended ideal \phi^{-1}(S^{-1}I) is not equal to {x \in R | \exists s \in S such that sx \in I}
    try:
        if h1 and h2:
            # First, compute the ideal J generated by I in Z/nZ
            if not I:
                J = {0}
            else:
                g = n
                for val in I:
                    g = math.gcd(g, val)
                J = set((k * g) % n for k in range(n))
            
            # The contraction of the extended ideal S^{-1}I is {r \in R | \exists s \in S such that s*r \in J}
            contraction = set()
            for r in range(n):
                for s in S:
                    if (s * r) % n in J:
                        contraction.add(r)
                        break
            
            # The set K described in the conclusion is {x \in R | \exists s \in S such that s*x \in I}
            K = set()
            for val in range(n):
                for s in S:
                    if (s * val) % n in I:
                        K.add(val)
                        break
            
            neg_q = (contraction != K)
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

