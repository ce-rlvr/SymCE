def conditions(witness) -> list[bool]:
    h1 = False
    h2 = False
    neg_q = False
    
    try:
        # Unpack witness
        if isinstance(witness, tuple):
            if len(witness) == 3:
                R, a, b = witness
            elif len(witness) == 2:
                a, b = witness
                R = None
            else:
                return [False, False, False]
        else:
            R = getattr(witness, 'R', witness)
            a = getattr(witness, 'a', None)
            b = getattr(witness, 'b', None)
            
        # H1: R is an integral domain
        if R is not None:
            if hasattr(R, 'is_integral_domain'):
                val = R.is_integral_domain
                h1 = bool(val() if callable(val) else val)
            elif hasattr(R, 'is_domain'):
                val = R.is_domain
                h1 = bool(val() if callable(val) else val)
            else:
                h1 = True
        else:
            h1 = True
            
        # H2: The principal ideal generated by a is equal to the principal ideal generated by b
        if R is not None and hasattr(R, 'ideal'):
            val_a = R.ideal(a)
            val_b = R.ideal(b)
            h2 = bool(val_a == val_b)
        elif R is not None and hasattr(R, 'principal_ideal'):
            val_a = R.principal_ideal(a)
            val_b = R.principal_ideal(b)
            h2 = bool(val_a == val_b)
        elif R is not None and hasattr(R, 'generates_same_ideal'):
            val = R.generates_same_ideal
            h2 = bool(val(a, b) if callable(val) else val)
        elif R is not None and hasattr(R, 'exquo'):
            if a == b:
                h2 = True
            else:
                try:
                    q1 = R.exquo(a, b)
                    q2 = R.exquo(b, a)
                    h2 = True
                except Exception:
                    h2 = False
        else:
            if a == b or a == -b:
                h2 = True
            else:
                h2 = False
                
        # neg_Q: There does not exist a unit u in R such that a = ub
        if R is not None and hasattr(R, 'units'):
            units = R.units() if callable(R.units) else R.units
            neg_q = not any(a == u * b for u in units)
        elif R is not None and hasattr(R, 'is_unit'):
            if a == 0 and b == 0:
                neg_q = False
            elif hasattr(R, 'exquo'):
                try:
                    q = R.exquo(a, b)
                    val = R.is_unit(q)
                    neg_q = not bool(val() if callable(val) else val)
                except Exception:
                    neg_q = True
            else:
                try:
                    if a == b and R.is_unit(1):
                        neg_q = False
                    elif a == -b and R.is_unit(-1):
                        neg_q = False
                    else:
                        neg_q = True
                except Exception:
                    neg_q = True
        else:
            # If R has no units defined, or R is None, assume no units exist
            # (e.g., in 2Z, there are no units, so a = u*b is false)
            neg_q = True
            
    except Exception:
        pass
        
    return [h1, h2, neg_q]

