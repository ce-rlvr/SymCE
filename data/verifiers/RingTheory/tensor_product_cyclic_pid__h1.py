import sympy as sp
from sympy.polys.polytools import groebner, reduced

x, y, z = sp.symbols('x y z')

CONDITION_LABELS = [
    "H_1: a and b are non-zero elements of R",
    "H_2: d is a greatest common divisor of a and b",
    "¬Q: R/<a> ⊗_R R/<b> is not isomorphic to R/<d> as R-modules"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    """
    Checks the hypotheses and negated conclusion for the conjecture.
    The witness can be a tuple (domain_str, a, b, d) or just (a, b, d)
    where domain_str is a sympy domain string like 'QQ' or 'ZZ',
    and a, b, d are sympy expressions representing elements of the polynomial ring
    over the specified domain generated by their free symbols.
    If domain_str is omitted, it defaults to 'QQ'.
    """
    if isinstance(witness, tuple) and len(witness) == 4 and isinstance(witness[0], str):
        domain_str, a, b, d = witness
    elif isinstance(witness, tuple) and len(witness) == 3:
        domain_str = 'QQ'
        a, b, d = witness
    else:
        return [False, False, False]
        
    try:
        a = sp.sympify(a)
        b = sp.sympify(b)
        d = sp.sympify(d)
    except Exception:
        return [False, False, False]
        
    # H_1: a and b are non-zero elements of R
    try:
        h1 = (a != 0) and (b != 0)
    except Exception:
        h1 = False
        
    # H_2: d is a greatest common divisor of a and b
    try:
        gens = list(a.free_symbols | b.free_symbols | d.free_symbols)
        gens.sort(key=lambda s: s.name)
        if not gens:
            gens = [sp.Symbol('x')]
            
        poly_a = sp.Poly(a, *gens, domain=domain_str)
        poly_b = sp.Poly(b, *gens, domain=domain_str)
        poly_d = sp.Poly(d, *gens, domain=domain_str)
        
        # Check if d divides both a and b
        try:
            poly_a.exquo(poly_d)
            poly_b.exquo(poly_d)
            divides_ab = True
        except Exception:
            divides_ab = False
            
        # Check if the canonical gcd divides d (meaning d is an associate of the gcd)
        gcd_poly = poly_a.gcd(poly_b)
        try:
            poly_d.exquo(gcd_poly)
            gcd_divides_d = True
        except Exception:
            gcd_divides_d = False
            
        h2 = divides_ab and gcd_divides_d
    except Exception:
        h2 = False
        
    # ¬Q: R/<a> ⊗_R R/<b> is not isomorphic to R/<d>
    # In commutative rings, R/<a> ⊗ R/<b> ≅ R/<a, b>.
    # R/<a, b> ≅ R/<d> if and only if the ideals <a, b> and <d> are equal.
    # Since d is a common divisor, <a, b> ⊆ <d>.
    # Thus, they are equal if and only if d ∈ <a, b>.
    # We check ideal membership using Gröbner bases.
    try:
        G = groebner([a, b], *gens, domain=domain_str)
        rem = reduced(d, G, *gens, domain=domain_str)[1]
        neg_q = (rem != 0)
    except Exception:
        neg_q = False
        
    return [bool(h1), bool(h2), bool(neg_q)]