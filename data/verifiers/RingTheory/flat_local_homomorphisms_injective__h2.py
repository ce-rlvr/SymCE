import sympy as sp

# Top-level setup: define symbols that the witness expression may reference.
# The witness is expected to be a dictionary representing a counterexample
# constructed from the local ring R = Q[x, y]_{(x, y)} / I and its localization S = R_P.
x, y = sp.symbols('x y')

def conditions(witness):
    try:
        if not isinstance(witness, dict):
            return [False, False, False]
            
        I_gens = witness.get('I_gens', [])
        P_gens = witness.get('P_gens', [])
        f = witness.get('f', 0)
        g = witness.get('g', 0)
        
        def is_homogeneous(poly):
            try:
                poly = sp.sympify(poly)
                if poly == 0:
                    return True
                if not poly.free_symbols.issubset({x, y}):
                    return False
                p = sp.Poly(poly, x, y)
                terms = p.terms()
                if not terms:
                    return True
                degree = sum(terms[0][0])
                return all(sum(power) == degree for power, _ in terms)
            except Exception:
                return False

        # H_1: R and S are commutative local rings
        # R = Q[x, y]_{(x, y)} / I is a local ring if I is generated by homogeneous polynomials.
        # S = R_P is a local ring if P is a prime ideal containing I.
        h1_ok = True
        
        if not isinstance(I_gens, list):
            h1_ok = False
        else:
            for gen in I_gens:
                if not is_homogeneous(gen):
                    h1_ok = False
                    break
                    
        if not isinstance(P_gens, list) or len(P_gens) == 0:
            h1_ok = False
        else:
            for gen in P_gens:
                if gen not in [x, y]:
                    h1_ok = False
                    break
                    
        if h1_ok:
            subs_dict = {v: 0 for v in P_gens}
            for gen in I_gens:
                if sp.sympify(gen).subs(subs_dict) != 0:
                    h1_ok = False
                    break
                    
        if not is_homogeneous(f) or not is_homogeneous(g):
            h1_ok = False

        # H_2: S is a flat R-module via the homomorphism \phi
        # S is defined as the localization R_P. Localization is always an exact functor,
        # hence S is unconditionally a flat R-module in this construction.
        h2_ok = h1_ok

        # ¬Q: The homomorphism \phi is not injective
        # \phi: R -> R_P is not injective iff there exists g \neq 0 in R and f \notin P/I
        # such that f * g = 0 in R.
        neg_q_ok = False
        if h1_ok:
            try:
                f_sym = sp.sympify(f)
                g_sym = sp.sympify(g)
                
                if not I_gens:
                    g_in_I = (g_sym == 0)
                    fg_in_I = (f_sym * g_sym == 0)
                else:
                    gb = sp.groebner(I_gens, x, y, domain='QQ')
                    g_in_I = sp.reduced(g_sym, gb, x, y)[1] == 0
                    fg_in_I = sp.reduced(f_sym * g_sym, gb, x, y)[1] == 0
                    
                f_in_P = (f_sym.subs(subs_dict) == 0)
                
                if (not g_in_I) and (not f_in_P) and fg_in_I:
                    neg_q_ok = True
            except Exception:
                neg_q_ok = False

        return [h1_ok, h2_ok, neg_q_ok]
    except Exception:
        return [False, False, False]

