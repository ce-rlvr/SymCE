def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, dict):
            a = witness.get('a')
            b = witness.get('b')
            c = witness.get('c')
            if a is None or b is None or c is None:
                return [False, False]
        elif isinstance(witness, (tuple, list)):
            if len(witness) == 3:
                a, b, c = witness
            elif len(witness) == 4:
                _, a, b, c = witness
            else:
                return [False, False]
        else:
            return [False, False]
            
        a = sympy.sympify(a)
        b = sympy.sympify(b)
        c = sympy.sympify(c)
        
        bac = sympy.expand(b + a * c)
        
        # H1: R is a UFD. We assume the implicit ring generated by a, b, bac is a UFD.
        # We check if sympy.gcd can successfully compute the GCDs.
        g1 = sympy.gcd(a, b)
        g2 = sympy.gcd(a, bac)
        h1_ok = True
    except Exception:
        h1_ok = False

    try:
        if not h1_ok:
            neg_q = False
        else:
            if g1 == 0 and g2 == 0:
                neg_q = False
            elif g1 == 0 or g2 == 0:
                neg_q = True
            else:
                ratio = sympy.cancel(g1 / g2)
                if not ratio.is_constant():
                    neg_q = True
                else:
                    def is_int_poly(expr):
                        if expr.is_Integer:
                            return True
                        if expr.is_Rational and not expr.is_Integer:
                            return False
                        if expr.free_symbols:
                            try:
                                poly = sympy.poly(expr)
                                if poly is not None:
                                    return all(coeff.is_Integer for coeff in poly.coeffs())
                            except Exception:
                                return False
                        return False

                    # If all elements belong to Z or Z[x], the only units are 1 and -1.
                    if is_int_poly(a) and is_int_poly(b) and is_int_poly(bac):
                        neg_q = (abs(ratio) != 1)
                    else:
                        # In a field or over Q[x], R[x], etc., any non-zero constant is a unit.
                        neg_q = (ratio == 0)
    except Exception:
        neg_q = False

    return [h1_ok, neg_q]