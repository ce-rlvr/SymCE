def conditions(witness) -> list[bool]:
    try:
        if not isinstance(witness, (tuple, list)) or len(witness) != 3:
            return [False, False, False, False, False]
            
        R, I_gens, J_gens = witness
        
        if isinstance(I_gens, (int, sympy.Integer)): I_gens = [I_gens]
        if isinstance(J_gens, (int, sympy.Integer)): J_gens = [J_gens]
        if isinstance(I_gens, (set, tuple)): I_gens = list(I_gens)
        if isinstance(J_gens, (set, tuple)): J_gens = list(J_gens)
        
        if R == sympy.ZZ or R == 'ZZ':
            h1 = True
            h2 = True
            h3 = True
            
            i_val = 0
            for g in I_gens: 
                i_val = math.gcd(i_val, int(g))
                
            j_val = 0
            for g in J_gens: 
                j_val = math.gcd(j_val, int(g))
            
            h4 = (i_val * j_val == 0)
            
            # In ZZ, the only zero-divisor is 0.
            # J contains an element that is not a zero-divisor iff J != {0}.
            # J != {0} iff j_val != 0.
            neg_q = (j_val != 0)
            
            return [h1, h2, h3, h4, neg_q]
            
        elif isinstance(R, (int, sympy.Integer)) and R >= 2:
            n = int(R)
            h1 = True
            h2 = True
            h3 = True
            
            i_val = n
            for g in I_gens: 
                i_val = math.gcd(i_val, int(g))
                
            j_val = n
            for g in J_gens: 
                j_val = math.gcd(j_val, int(g))
                
            h4 = ((i_val * j_val) % n == 0)
            
            # In Z/nZ, an element y is not a zero-divisor iff gcd(y, n) == 1.
            # J is the ideal generated by j_val.
            # J contains an element coprime to n iff gcd(j_val, n) == 1.
            neg_q = (math.gcd(j_val, n) == 1)
            
            return [h1, h2, h3, h4, neg_q]
            
        else:
            return [False, False, False, False, False]
            
    except Exception:
        return [False, False, False, False, False]

