class PowerSetRing:
    """
    Represents the Boolean ring of all subsets of a set X.
    Addition is symmetric difference, multiplication is intersection.
    """
    def __init__(self, is_infinite=True):
        self.is_infinite = is_infinite

    def is_boolean_ring(self):
        return True

class FiniteSubsetsIdeal:
    """
    Represents the ideal of all finite subsets in a PowerSetRing.
    """
    def __init__(self, ring):
        self.ring = ring

    def is_principal(self):
        if getattr(self.ring, 'is_infinite', False):
            return False
        return True

class PolynomialRingGF2:
    """
    Represents the Boolean ring of polynomials over GF(2) modulo x^2=x for all variables.
    """
    def __init__(self, num_variables=float('inf')):
        self.num_variables = num_variables
        self.is_infinite = (num_variables == float('inf'))

    def is_boolean_ring(self):
        return True

class IdealGeneratedByAllVariables:
    """
    Represents the ideal generated by all variables in PolynomialRingGF2.
    """
    def __init__(self, ring):
        self.ring = ring

    def is_principal(self):
        if getattr(self.ring, 'is_infinite', False):
            return False
        return True

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            ring, ideal = witness
        else:
            ideal = witness
            ring = ideal.ring
    except Exception:
        return [False, False]

    try:
        h1 = bool(ring.is_boolean_ring())
    except Exception:
        h1 = False

    try:
        neg_q = not bool(ideal.is_principal())
    except Exception:
        neg_q = False

    return [h1, neg_q]

