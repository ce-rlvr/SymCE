import sympy
from sympy import Symbol, Poly
from sympy.polys.polytools import groebner, resultant

# Top-level setup
x = Symbol('x')

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness should be an ideal in Z[x], represented as a list of polynomials.
    """
    h1_ok = False
    polys = []
    try:
        # Ensure witness is a collection of generators
        if not isinstance(witness, (list, tuple, set)):
            witness = [witness]
        
        # Check if all elements can be interpreted as polynomials in Z[x]
        for w in witness:
            polys.append(Poly(w, x, domain='ZZ'))
        
        h1_ok = True
    except Exception:
        h1_ok = False

    neg_q_ok = False
    try:
        if h1_ok:
            is_iso = False
            
            if len(polys) > 0:
                # Compute the GCD of all generators in Z[x]
                g = polys[0]
                for p in polys[1:]:
                    g = g.gcd(p)
                
                # For Z[x]/I to be isomorphic to Z[1/2], the ideal must be generated by 
                # a single primitive polynomial of the form b*x - a, where b is a power of 2 (b > 1)
                # and a is odd.
                if g.degree() == 1:
                    coeffs = g.all_coeffs()
                    b = coeffs[0]
                    a = -coeffs[1]
                    
                    cont, prim = g.primitive()
                    if abs(cont) == 1:
                        b_abs = abs(b)
                        # Check if b is a power of 2 strictly greater than 1
                        if b_abs > 1 and (b_abs & (b_abs - 1)) == 0:
                            # Check if a is odd
                            if a % 2 != 0:
                                # Now check if the ideal generated by the witness is EXACTLY <g>
                                # This is true iff 1 is in the ideal generated by the quotients p_i / g
                                r_list = [p.exquo(g) for p in polys]
                                
                                one_in_ideal = False
                                for r in r_list:
                                    if r.is_one or r == 1 or r == -1:
                                        one_in_ideal = True
                                        break
                                
                                # Fallback 1: Resultant of two polynomials
                                if not one_in_ideal and len(r_list) == 2:
                                    try:
                                        res = resultant(r_list[0], r_list[1], x)
                                        if res == 1 or res == -1:
                                            one_in_ideal = True
                                    except Exception:
                                        pass
                                        
                                # Fallback 2: Groebner basis over ZZ
                                if not one_in_ideal:
                                    try:
                                        gb = groebner(r_list, x, domain='ZZ')
                                        if len(gb) == 1 and (gb[0] == 1 or gb[0] == -1 or getattr(gb[0], 'is_one', False)):
                                            one_in_ideal = True
                                    except Exception:
                                        pass
                                        
                                if one_in_ideal:
                                    is_iso = True
            
            # The conclusion is that R/I IS isomorphic to Z[1/2].
            # We want the negation of the conclusion to be True.
            neg_q_ok = not is_iso
    except Exception:
        neg_q_ok = False

    return [h1_ok, neg_q_ok]

