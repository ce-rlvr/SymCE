import math
import sympy

# Top-level setup for potential witness expressions
x, y, z = sympy.symbols('x y z')

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "If R is a commutative ring with identity and P is a prime ideal, 
    then the localization S^{-1}R is a local ring with unique maximal ideal S^{-1}P."
    
    The witness is expected to be a tuple: (n, p, S_gens)
    representing:
      - R = Z/nZ (or Z if n=0)
      - P = (p), the ideal generated by p
      - S, the multiplicatively closed set generated by the elements in S_gens
    """
    try:
        n, p, S_gens = witness
    except Exception:
        return [False, False, False]
        
    # H_1: R is a commutative ring with identity
    try:
        h1 = isinstance(n, int) and n >= 0 and isinstance(p, int) and isinstance(S_gens, list)
        if not h1:
            return [False, False, False]
        for s in S_gens:
            if not isinstance(s, int):
                h1 = False
    except Exception:
        h1 = False

    # H_2: P is a prime ideal of R
    try:
        if n == 0:
            g = abs(p)
        else:
            g = math.gcd(p, n)
        
        if g == 0:
            # In Z, (0) is a prime ideal. In Z/nZ (n>0), g=0 implies n=0, which is handled.
            h2 = (n == 0)
        else:
            # In Z/nZ, the ideal (g) is prime iff g is a prime number.
            h2 = sympy.isprime(g)
    except Exception:
        h2 = False

    # ¬Q: S^{-1}R is NOT a local ring with unique maximal ideal S^{-1}P
    try:
        if n == 0:
            # For R = Z, S^{-1}R is a local ring iff S is the complement of a prime ideal.
            # Since S is generated by a finite set S_gens, S cannot be the complement of a prime ideal
            # (the complement of (q) contains infinitely many primes, so it cannot be finitely generated).
            # Thus S^{-1}Z is never a local ring for any finite S_gens.
            neg_q = True
        else:
            # For R = Z/nZ
            prime_factors_n = set(sympy.primefactors(n))
            
            # M is the set of prime ideals of R that do not intersect S.
            # A prime ideal (q) intersects S iff q divides some element in S_gens.
            M = set()
            for q in prime_factors_n:
                divides_some = False
                for s in S_gens:
                    if s % q == 0:
                        divides_some = True
                        break
                if not divides_some:
                    M.add(q)
            
            # S^{-1}R is a local ring with unique maximal ideal S^{-1}P
            # iff M contains exactly one prime, and that prime corresponds to the generator of P.
            is_local_with_unique_max = (len(M) == 1 and list(M)[0] == g)
            
            neg_q = not is_local_with_unique_max
            
    except Exception:
        neg_q = False

    return [bool(h1), bool(h2), bool(neg_q)]

