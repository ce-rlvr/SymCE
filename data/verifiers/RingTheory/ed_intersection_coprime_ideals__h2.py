import sympy
from sympy import symbols, Poly, sympify, div, lcm, gcd, S

# Top-level setup
x, y, z = symbols('x y z')

def conditions(witness) -> list[bool]:
    """
    Given a witness (a, b), checks if it is a counterexample to the conjecture:
    "In a Euclidean domain, if a and b are coprime, then (a) \cap (b) = (ab)."
    """
    try:
        a, b = witness
    except Exception:
        return [False, False, False]
        
    h1 = False
    h2 = False
    neg_q = False
    
    try:
        # If the witness elements come from a sympy.polys.rings ring
        if hasattr(a, 'ring'):
            R = a.ring
            # Euclidean domains are PIDs
            h1 = getattr(R, 'is_PID', True)
            # Coprime means they generate the unit ideal
            h2 = R.ideal(a, b).is_whole_ring()
            
            I_a = R.ideal(a)
            I_b = R.ideal(b)
            I_ab = R.ideal(a * b)
            neg_q = (I_a.intersect(I_b) != I_ab)
            
        else:
            # Fallback for standard SymPy expressions (integers, polynomials)
            a_sym = sympify(a)
            b_sym = sympify(b)
            
            # H1: R is a Euclidean domain
            if a_sym.is_Integer and b_sym.is_Integer:
                h1 = True
            else:
                poly_a = Poly(a_sym)
                poly_b = Poly(b_sym)
                gens = set(poly_a.gens) | set(poly_b.gens)
                if len(gens) == 0:
                    h1 = True
                elif len(gens) == 1:
                    # K[x] is a Euclidean domain iff K is a field
                    h1 = poly_a.domain.is_Field and poly_b.domain.is_Field
                else:
                    h1 = False
                    
            # H2: a and b are coprime
            h2 = (gcd(a_sym, b_sym) == 1)
            
            # neg_Q: (a) \cap (b) != (ab)
            # In a PID, (a) \cap (b) is generated by lcm(a, b).
            # We check if lcm(a, b) and a*b generate the same ideal (i.e., are associates).
            lcm_ab = lcm(a_sym, b_sym)
            prod_ab = a_sym * b_sym
            
            if a_sym.is_Integer and b_sym.is_Integer:
                if prod_ab == 0:
                    neg_q = (lcm_ab != 0)
                else:
                    neg_q = (abs(lcm_ab) != abs(prod_ab))
            else:
                if prod_ab == 0:
                    neg_q = (lcm_ab != 0)
                else:
                    q1, r1 = div(lcm_ab, prod_ab)
                    q2, r2 = div(prod_ab, lcm_ab)
                    neg_q = not (r1 == 0 and r2 == 0)
                    
    except Exception:
        pass
        
    return [bool(h1), bool(h2), bool(neg_q)]

