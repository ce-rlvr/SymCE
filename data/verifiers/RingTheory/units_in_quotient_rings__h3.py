def conditions(witness) -> list[bool]:
    """
    Evaluates the hypotheses and negated conclusion for the conjecture:
    "If R is a ring with identity and I is a proper two-sided ideal of R, 
    then the coset u + I is a unit in the quotient ring R/I."
    
    The witness is expected to represent a ring R = Z/nZ, an ideal I = mZ/nZ, 
    and an element u. It can be provided as:
      - A tuple (m, u) for R = Z (i.e., n = 0)
      - A tuple (n, m, u) for R = Z/nZ
      - A dictionary or object with attributes 'n', 'm', 'u'
    """
    try:
        if isinstance(witness, dict):
            n = int(witness.get('n', 0))
            m = int(witness['m'])
            u = int(witness['u'])
        elif isinstance(witness, (tuple, list)):
            if len(witness) == 2:
                n = 0
                m = int(witness[0])
                u = int(witness[1])
            elif len(witness) == 3:
                n = int(witness[0])
                m = int(witness[1])
                u = int(witness[2])
            else:
                return [False, False, False]
        else:
            n = int(getattr(witness, 'n', 0))
            m = int(getattr(witness, 'm'))
            u = int(getattr(witness, 'u'))
            
        n = abs(n)
        
        # H_1: R is a ring with identity
        # Z/nZ is always a ring with identity for any n >= 0.
        h1_ok = True
        
        # H_2: I is a proper two-sided ideal of R
        # In Z/nZ, the ideal generated by m is proper iff gcd(m, n) != 1.
        # For Z (n=0), it is proper iff abs(m) != 1.
        if n == 0:
            h2_ok = (abs(m) != 1)
        else:
            h2_ok = (math.gcd(m, n) != 1)
            
        # Conclusion: u + I is a unit in R/I
        # R/I is isomorphic to Z/kZ where k = gcd(n, m) if n > 0 else abs(m)
        if n == 0:
            k = abs(m)
        else:
            k = math.gcd(n, m)
            
        if k == 0:
            # R/I = Z, units are 1 and -1
            is_unit = (abs(u) == 1)
        elif k == 1:
            # R/I = zero ring, 0 is the identity and is a unit
            is_unit = True
        else:
            # R/I = Z/kZ, units are elements coprime to k
            is_unit = (math.gcd(u, k) == 1)
            
        neg_q_ok = not is_unit
        
        return [h1_ok, h2_ok, neg_q_ok]
    except Exception:
        return [False, False, False]

