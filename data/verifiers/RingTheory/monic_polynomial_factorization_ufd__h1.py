import sympy as sp

x, y = sp.symbols('x y')

class Witness:
    """
    Witness for the conjecture.
    To avoid undecidable Z-algebra membership tests, we use a Q-algebra counterexample.
    Let y be a transcendental variable.
    R is the subring of Q[y] generated by R_gens (a list of polynomials in y).
    K is the field of fractions of R. We require K = Q(y),
    which is proven by providing y_num, y_den in R such that y = y_num / y_den.
    f is a monic polynomial in x with coefficients in R.
    g, h are monic polynomials in x with coefficients in K = Q(y).
    """
    def __init__(self, R_gens, y_num, y_den, f, g, h):
        self.R_gens = R_gens
        self.y_num = y_num
        self.y_den = y_den
        self.f = f
        self.g = g
        self.h = h

def is_QQ_poly(expr):
    expr = sp.cancel(sp.sympify(expr))
    if expr.free_symbols - {y}:
        return False
    if not expr.is_polynomial(y):
        return False
    poly = sp.Poly(expr, y)
    for c in poly.coeffs():
        if not (isinstance(c, (sp.Rational, int)) or c.is_Rational):
            return False
    return True

def is_QQ_rat_func(expr):
    expr = sp.cancel(sp.sympify(expr))
    if expr.free_symbols - {y}:
        return False
    num, den = expr.as_numer_denom()
    return is_QQ_poly(num) and is_QQ_poly(den)

def in_R(expr, R_gens):
    if not is_QQ_poly(expr):
        return False
    if not R_gens:
        return sp.cancel(sp.sympify(expr)).is_Rational
    
    expr = sp.cancel(sp.sympify(expr))
    Z = sp.symbols(f'z0:{len(R_gens)}')
    F = [Z[i] - R_gens[i] for i in range(len(R_gens))]
    
    G = sp.groebner(F, y, *Z, order='lex')
    rem = sp.reduced(expr, G, [y] + list(Z), order='lex')[1]
    return not rem.has(y)

def check_H1(witness):
    if not hasattr(witness, 'R_gens') or not hasattr(witness, 'y_num') or not hasattr(witness, 'y_den'):
        return False
    if not isinstance(witness.R_gens, (list, tuple)):
        return False
        
    for g in witness.R_gens:
        if not is_QQ_poly(g):
            return False
            
    if not in_R(witness.y_num, witness.R_gens):
        return False
    if not in_R(witness.y_den, witness.R_gens):
        return False
        
    if sp.simplify(witness.y_den) == 0:
        return False
        
    if sp.simplify(witness.y_num / witness.y_den - y) != 0:
        return False
        
    return True

def check_H2(witness):
    if not hasattr(witness, 'f'):
        return False
    f = sp.sympify(witness.f)
    if f.free_symbols - {x, y}:
        return False
    if not f.is_polynomial(x):
        return False
    poly_f = sp.Poly(f, x)
    if poly_f.LC() != 1:
        return False
    for c in poly_f.coeffs():
        if not in_R(c, witness.R_gens):
            return False
    return True

def check_H3(witness):
    if not hasattr(witness, 'g') or not hasattr(witness, 'h'):
        return False
    g = sp.sympify(witness.g)
    h = sp.sympify(witness.h)
    
    for p in [g, h]:
        if p.free_symbols - {x, y}:
            return False
        try:
            poly_p = sp.Poly(p, x)
        except Exception:
            return False
            
        if poly_p.LC() != 1:
            return False
        for c in poly_p.coeffs():
            if not is_QQ_rat_func(c):
                return False
    return True

def check_H4(witness):
    if not hasattr(witness, 'f') or not hasattr(witness, 'g') or not hasattr(witness, 'h'):
        return False
    f = sp.sympify(witness.f)
    g = sp.sympify(witness.g)
    h = sp.sympify(witness.h)
    return sp.simplify(f - g * h) == 0

def check_neg_Q(witness):
    if not hasattr(witness, 'g') or not hasattr(witness, 'h'):
        return False
    g = sp.sympify(witness.g)
    h = sp.sympify(witness.h)
    
    try:
        poly_g = sp.Poly(g, x)
        poly_h = sp.Poly(h, x)
    except Exception:
        return False
        
    g_in_R = all(in_R(c, witness.R_gens) for c in poly_g.coeffs())
    h_in_R = all(in_R(c, witness.R_gens) for c in poly_h.coeffs())
    
    return not (g_in_R and h_in_R)

CONDITION_LABELS = [
    "H_1: K is the field of fractions of R",
    "H_2: f is a monic polynomial with coefficients in R",
    "H_3: g and h are monic polynomials with coefficients in K",
    "H_4: f = g * h",
    "¬Q: g and h do not both have coefficients in R"
]

N_HYP = 4
NEG_Q_INDEX = 4

def conditions(witness):
    try:
        h1 = check_H1(witness)
    except Exception:
        h1 = False

    try:
        h2 = check_H2(witness)
    except Exception:
        h2 = False

    try:
        h3 = check_H3(witness)
    except Exception:
        h3 = False

    try:
        h4 = check_H4(witness)
    except Exception:
        h4 = False

    try:
        neg_q = check_neg_Q(witness)
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]