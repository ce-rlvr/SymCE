import sympy
from sympy import symbols, groebner, reduced, Poly

# Top-level setup for standard variables
x, y, z, w = symbols('x y z w')

def in_ideal(f, I_gens, vars):
    if not I_gens:
        return f == 0
    GB = groebner(I_gens, *vars, domain='QQ')
    return reduced(f, GB, *vars, domain='QQ')[1] == 0

def is_subset(I1_gens, I2_gens, vars):
    if not I2_gens:
        return all(f == 0 for f in I1_gens)
    GB = groebner(I2_gens, *vars, domain='QQ')
    for g in I1_gens:
        if reduced(g, GB, *vars, domain='QQ')[1] != 0:
            return False
    return True

def is_equal(I1_gens, I2_gens, vars):
    return is_subset(I1_gens, I2_gens, vars) and is_subset(I2_gens, I1_gens, vars)

def is_prime_ideal(M_gens, vars):
    if not M_gens:
        return True
    GB = groebner(M_gens, *vars, domain='QQ')
    if list(GB) == [1]:
        return False
    for g in GB:
        p = Poly(g, *vars)
        if p.degree() != 1:
            return False
    return True

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "If R is a commutative Noetherian ring, and Q_1, Q_2 are M-primary ideals, 
    then Q_1 Q_2 is an M-primary ideal."
    
    The witness should be a dictionary containing:
      - 'vars': list of variables (e.g., [x, y, z])
      - 'I': generators for the ideal I such that R = k[vars]/I
      - 'M': generators for the prime ideal M (must be generated by linear polynomials in R)
      - 'Q1': generators for Q1 (we check if Q1 == M)
      - 'Q2': generators for Q2 (we check if Q2 == M)
      - 'a', 'b': elements in R proving Q1*Q2 is not primary (a*b in Q1*Q2, a not in Q1*Q2, b not in M)
    """
    try:
        vars_raw = witness['vars']
        vars_syms = []
        for v in vars_raw:
            if isinstance(v, str):
                vars_syms.append(sympy.Symbol(v))
            else:
                vars_syms.append(v)
        ring_vars = tuple(vars_syms)
        
        def sympify_list(lst):
            res = []
            for expr in lst:
                if isinstance(expr, str):
                    res.append(sympy.sympify(expr))
                else:
                    res.append(expr)
            return res
        
        I = sympify_list(witness.get('I', []))
        M = sympify_list(witness['M'])
        Q1 = sympify_list(witness['Q1'])
        Q2 = sympify_list(witness['Q2'])
        
        a = sympy.sympify(witness['a']) if isinstance(witness['a'], str) else witness['a']
        b = sympy.sympify(witness['b']) if isinstance(witness['b'], str) else witness['b']
    except KeyError:
        return [False, False, False]

    # H_1: R is a commutative Noetherian ring
    # R is represented as k[vars]/I, which is always a commutative Noetherian ring.
    h1_ok = True

    # H_2: Q_1 and Q_2 are M-primary ideals of R
    try:
        M_R = M + I
        Q1_R = Q1 + I
        Q2_R = Q2 + I

        # We verify M is prime and Q1 == M, Q2 == M in R/I.
        # If Q == M and M is prime, then Q is M-primary.
        m_prime = is_prime_ideal(M_R, ring_vars)
        q1_eq_m = is_equal(Q1_R, M_R, ring_vars)
        q2_eq_m = is_equal(Q2_R, M_R, ring_vars)

        h2_ok = bool(m_prime and q1_eq_m and q2_eq_m)
    except Exception:
        h2_ok = False

    # ¬Q: The product ideal Q_1 Q_2 is not an M-primary ideal of R
    try:
        Q1_Q2 = []
        for g1 in Q1:
            for g2 in Q2:
                Q1_Q2.append(g1 * g2)
        
        Q1_Q2_R = Q1_Q2 + I

        # To prove Q1*Q2 is not primary, the witness provides a, b such that:
        # a * b \in Q1*Q2
        # a \notin Q1*Q2
        # b \notin M (which is the radical of Q1*Q2)
        ab_in = in_ideal(a * b, Q1_Q2_R, ring_vars)
        a_notin = not in_ideal(a, Q1_Q2_R, ring_vars)
        b_notin = not in_ideal(b, M_R, ring_vars)

        neg_q_ok = bool(ab_in and a_notin and b_notin)
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, neg_q_ok]

