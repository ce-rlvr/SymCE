import math
from sympy.ntheory import isprime, factorint
from sympy import symbols, Rational, Integer

# No specific named bindings are required for this ring theory conjecture,
# as witnesses are typically provided as tuples, lists, or dicts representing 
# rings of the form Z/nZ or Z_{(p)}.

def conditions(witness):
    try:
        h1 = False
        h2 = False
        neg_q = False
        
        # Check for Z_localized dictionary format
        if isinstance(witness, dict) and witness.get('domain') in ('Z_localized', 'localized'):
            p = witness.get('p')
            m_gen = witness.get('m_gen')
            S_type = witness.get('S_type')
            n_gen = witness.get('n_gen')
            
            if p is not None and isprime(p) and m_gen == p:
                h1 = True
            if S_type in ('same', 'R', 'Z_localized', witness.get('domain')):
                h2 = True
            if n_gen is not None and m_gen is not None and n_gen != m_gen:
                neg_q = True
            return [h1, h2, neg_q]

        # Try to extract integers for Z/nZ format
        R_mod, m_gen, S_mod, n_gen = None, None, None, None
        
        if isinstance(witness, (tuple, list)) and len(witness) == 4:
            R_mod, m_gen, S_mod, n_gen = witness
        elif isinstance(witness, dict):
            if 'R_mod' in witness:
                R_mod = witness.get('R_mod')
                m_gen = witness.get('m_gen')
                S_mod = witness.get('S_mod')
                n_gen = witness.get('n_gen')
            elif 'R' in witness:
                R_mod = witness.get('R')
                m_gen = witness.get('m')
                S_mod = witness.get('S')
                n_gen = witness.get('n')
        else:
            if hasattr(witness, 'R_mod'):
                R_mod = getattr(witness, 'R_mod', None)
                m_gen = getattr(witness, 'm_gen', None)
                S_mod = getattr(witness, 'S_mod', None)
                n_gen = getattr(witness, 'n_gen', None)
            elif hasattr(witness, 'R'):
                R_mod = getattr(witness, 'R', None)
                m_gen = getattr(witness, 'm', None)
                S_mod = getattr(witness, 'S', None)
                n_gen = getattr(witness, 'n', None)
                
        if R_mod is not None and m_gen is not None and S_mod is not None and n_gen is not None:
            try:
                R_mod = int(R_mod)
                m_gen = int(m_gen)
                S_mod = int(S_mod)
                n_gen = int(n_gen)
                
                # H1: R is a local ring with maximal ideal m
                # Z/nZ is a local ring iff n is a prime power p^k. 
                # Its unique maximal ideal is generated by p.
                if R_mod > 1:
                    factors = factorint(R_mod)
                    if len(factors) == 1:
                        p = list(factors.keys())[0]
                        if math.gcd(m_gen, R_mod) == p:
                            h1 = True
                
                # H2: S is a commutative ring that is an integral extension of R
                # We accept S = R as a valid integral extension
                if S_mod == R_mod:
                    h2 = True
                    
                # ¬Q: The contraction of the ideal n to R is not exactly m
                # For S = R, the contraction of n is just n itself.
                n_ideal = math.gcd(n_gen, R_mod)
                m_ideal = math.gcd(m_gen, R_mod)
                if n_ideal != m_ideal:
                    neg_q = True
            except (ValueError, TypeError):
                pass
                
        return [h1, h2, neg_q]
    except Exception:
        return [False, False, False]

