x = sympy.Symbol('x')

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, tuple):
            domain, expr = witness
            f = sympy.Poly(expr, x, domain=domain)
        else:
            f = sympy.Poly(witness, x)
            domain = f.domain
    except Exception:
        return [False, False, False]

    try:
        h1 = bool(f.degree() > 0)
    except Exception:
        h1 = False

    try:
        h2 = bool(f.is_irreducible)
    except Exception:
        h2 = False

    try:
        # The ideal (f(x)) is maximal in R[x] for irreducible f(x) iff R is a field.
        # If the domain is not a field, the conclusion fails (ideal is not maximal).
        neg_q = not bool(domain.is_Field)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

