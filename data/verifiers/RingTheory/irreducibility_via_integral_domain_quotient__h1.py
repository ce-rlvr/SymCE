import sympy
from sympy import Poly, GF
from sympy.abc import x
from sympy.ntheory import factorint
import math
from itertools import product

# Top-level setup
x_sym = x

def conditions(witness):
    try:
        n = None
        coeffs = None
        
        # Parse witness: expect a tuple (n, coeffs) representing F = Z_n and f(x) in Z_n[x]
        if isinstance(witness, tuple) and len(witness) == 2:
            n, coeffs = witness
            if hasattr(coeffs, 'all_coeffs'):
                coeffs = coeffs.all_coeffs()[::-1]
            elif not isinstance(coeffs, list):
                coeffs = list(coeffs)
        elif hasattr(witness, 'domain'):
            domain = witness.domain
            if hasattr(domain, 'mod'):
                n = domain.mod
            else:
                n = 0
            coeffs = witness.all_coeffs()[::-1]
        
        # We only consider finite rings Z_n for n >= 2 since integral domains don't yield counterexamples
        if n is None or coeffs is None or not isinstance(n, int) or n < 2:
            return [False, False, False]
            
        # H_1: f(x) is a non-zero polynomial in Z_n[x]
        h1 = any(c % n != 0 for c in coeffs)
        
        # H_2: F[x]/<f(x)> is an integral domain
        # This is true iff <f(x)> is a prime ideal in Z_n[x].
        # By CRT, Z_n[x] is a product of Z_{p^k}[x]. The ideal is prime iff it is prime in exactly one 
        # component and is the whole ring (i.e., generated by a unit) in all other components.
        def is_unit_mod_pk(C, p, k):
            if C[0] % p == 0:
                return False
            for c in C[1:]:
                if c % p != 0:
                    return False
            return True

        def is_prime_ideal_mod_pk(C, p, k):
            if k == 1:
                if all(c % p == 0 for c in C):
                    return True  # <0> is a prime ideal in Z_p[x]
                f_poly = Poly(list(reversed(C)), x_sym, domain=GF(p))
                if f_poly.degree() <= 0:
                    return False
                return f_poly.is_irreducible
            else:
                # In Z_{p^k}[x] for k > 1, prime ideals are exactly <p>
                if C[0] % p != 0 or C[0] % (p**2) == 0:
                    return False
                for c in C[1:]:
                    if c % (p**2) != 0:
                        return False
                return True

        factors = factorint(n)
        prime_ideal_count = 0
        h2_ok = True
        for p, k in factors.items():
            if is_prime_ideal_mod_pk(coeffs, p, k):
                prime_ideal_count += 1
            elif is_unit_mod_pk(coeffs, p, k):
                pass
            else:
                h2_ok = False
                break
        
        h2 = h2_ok and (prime_ideal_count == 1)
        
        # ¬Q: f(x) is NOT an irreducible polynomial over F
        # We check if f(x) can be factored into two non-units in Z_n[x].
        if n > 50:
            return [bool(h1), bool(h2), False] # Prevent timeout for excessively large rings
            
        def poly_mul(A, B):
            res = [0] * (len(A) + len(B) - 1)
            for i, a in enumerate(A):
                for j, b in enumerate(B):
                    res[i+j] = (res[i+j] + a * b) % n
            while len(res) > 1 and res[-1] == 0:
                res.pop()
            return res

        def is_unit_poly(A):
            if math.gcd(A[0], n) != 1:
                return False
            primes = list(factors.keys())
            for a in A[1:]:
                for p in primes:
                    if a % p != 0:
                        return False
            return True

        deg_f = len(coeffs) - 1
        while deg_f > 0 and coeffs[deg_f] % n == 0:
            deg_f -= 1
            
        max_deg = max(1, deg_f + 1)
        polys = []
        for d in range(max_deg + 1):
            for c in product(range(n), repeat=d+1):
                if c[-1] != 0 or d == 0:
                    polys.append(list(c))
                if len(polys) > 1000:
                    break
            if len(polys) > 1000:
                break
                    
        f_norm = [c % n for c in coeffs]
        while len(f_norm) > 1 and f_norm[-1] == 0:
            f_norm.pop()

        neg_q = False
        if is_unit_poly(f_norm):
            neg_q = True  # Units are not irreducible
        else:
            for g in polys:
                for h in polys:
                    if poly_mul(g, h) == f_norm:
                        if not is_unit_poly(g) and not is_unit_poly(h):
                            neg_q = True
                            break
                if neg_q:
                    break
                    
        return [bool(h1), bool(h2), bool(neg_q)]
    except Exception:
        return [False, False, False]

