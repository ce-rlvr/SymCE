def analyze_ring(R):
    """
    Analyzes the ring R to determine if it is an integral domain and if it is a prime ring.
    Returns a tuple: (is_integral_domain, is_prime_ring)
    """
    if isinstance(R, dict):
        if 'is_integral_domain' in R or 'is_prime_ring' in R or 'is_prime_ideal' in R:
            is_id = R.get('is_integral_domain', True)
            is_pr = R.get('is_prime_ring', True)
            if 'is_prime_ideal' in R:
                is_pr = R['is_prime_ideal']
            return bool(is_id), bool(is_pr)
        if 'ring' in R:
            return analyze_ring(R['ring'])
        if 'R' in R:
            return analyze_ring(R['R'])

    if hasattr(R, 'is_integral_domain') and hasattr(R, 'is_prime_ring'):
        return bool(R.is_integral_domain), bool(R.is_prime_ring)

    if isinstance(R, int) or (hasattr(R, 'is_Integer') and R.is_Integer):
        n = int(R)
        if n >= 2:
            # nZ for n >= 2 is a prime ring but lacks identity, so not an integral domain
            return False, True
        elif n == 0:
            return False, False
        else:
            return True, True

    R_str = str(R).replace(" ", "")
    
    # Check for nZ representations
    for i in range(2, 100):
        if R_str == f"{i}Z" or R_str == f"{i}*Z" or R_str == f"{i}ZZ" or R_str == f"{i}*ZZ":
            return False, True
            
    if ("Lambda" in R_str and "Integers" in R_str) or ("2*S.Integers" in R_str) or ("2*Integers" in R_str):
        return False, True

    # Check for Matrix rings (prime rings but not domains, unless over a non-domain)
    if "MatrixSpace" in R_str or "M_" in R_str or "M2" in R_str or "M3" in R_str:
        if "Z4" in R_str or "Z6" in R_str or "Mod" in R_str or "CyclicGroup" in R_str:
            return False, False
        return False, True
        
    # Check for non-commutative domains
    if "Quaternion" in R_str or "FreeAlgebra" in R_str or "<x,y>" in R_str:
        return False, True

    if hasattr(R, 'shape') and hasattr(R, 'set'):
        return False, True

    # Default fallback for standard commutative rings with identity
    return True, True

def get_ring_properties(witness):
    if isinstance(witness, tuple) or isinstance(witness, list):
        for item in witness:
            is_id, is_pr = analyze_ring(item)
            # If we find a valid counterexample component, use it
            if not is_id and is_pr:
                return is_id, is_pr
        if len(witness) > 0:
            return analyze_ring(witness[-1])
    return analyze_ring(witness)

def conditions(witness) -> list[bool]:
    try:
        # H_1: I is the principal ideal generated by x in the polynomial ring
        # This is the context setting. Any valid witness object can be interpreted in this context.
        h1_ok = witness is not None
    except Exception:
        h1_ok = False

    try:
        is_id, is_pr = get_ring_properties(witness)
        
        # Conclusion Q: I is a prime ideal iff R is an integral domain
        # I is a prime ideal <==> R is a prime ring (is_pr)
        # R is an integral domain <==> is_id
        # The conclusion fails (neg_Q is True) if these two truth values differ.
        neg_q = (is_pr != is_id)
    except Exception:
        neg_q = False

    return [h1_ok, neg_q]

