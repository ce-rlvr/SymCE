import sympy
from sympy import symbols
import itertools

# Top-level setup for witness expressions
x, y, z, t, u, v, w = symbols('x y z t u v w')

def conditions(witness) -> list[bool]:
    """
    The witness is expected to represent a polynomial ring R = Z_n[vars] 
    and two ideals I, J generated by lists of polynomials.
    Format: dict with keys 'n', 'vars', 'I', 'J'
    or a tuple (n, vars, I, J).
    """
    try:
        if isinstance(witness, dict):
            n = witness.get('n')
            vs = witness.get('vars')
            I_gens = witness.get('I')
            J_gens = witness.get('J')
        elif isinstance(witness, tuple) and len(witness) == 4:
            n, vs, I_gens, J_gens = witness
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]
        
    # H_1: R is a commutative ring
    # R = Z_n[vars] is a commutative ring for any integer n >= 2.
    try:
        h1 = isinstance(n, (int, sympy.Integer)) and int(n) >= 2 and isinstance(vs, list)
        if h1:
            for var in vs:
                if not isinstance(var, sympy.Symbol):
                    h1 = False
    except Exception:
        h1 = False
        
    # H_2: I and J are ideals of R
    # Any set of polynomials generates an ideal.
    try:
        h2 = isinstance(I_gens, list) and isinstance(J_gens, list)
        if h2:
            for f in I_gens + J_gens:
                sympy.sympify(f)
    except Exception:
        h2 = False
        
    # ¬Q: V(IJ) != V(I) \cup V(J)
    try:
        I_exprs = [sympy.sympify(f) for f in I_gens]
        J_exprs = [sympy.sympify(f) for f in J_gens]
        
        m = len(vs)
        # Limit the search space to ensure the verifier is fast
        if int(n)**m > 10000:
            neg_q = False
        else:
            points = list(itertools.product(range(int(n)), repeat=m))
            
            def vanishes(gens, pt):
                subs_dict = dict(zip(vs, pt))
                for f in gens:
                    val = f.subs(subs_dict)
                    if int(val) % int(n) != 0:
                        return False
                return True
                
            V_I = set()
            for pt in points:
                if vanishes(I_exprs, pt):
                    V_I.add(pt)
                    
            V_J = set()
            for pt in points:
                if vanishes(J_exprs, pt):
                    V_J.add(pt)
                    
            # The product ideal IJ is generated by all pairwise products
            IJ_exprs = [f * g for f in I_exprs for g in J_exprs]
            
            V_IJ = set()
            for pt in points:
                if vanishes(IJ_exprs, pt):
                    V_IJ.add(pt)
                    
            V_I_cup_V_J = V_I.union(V_J)
            
            neg_q = (V_IJ != V_I_cup_V_J)
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

