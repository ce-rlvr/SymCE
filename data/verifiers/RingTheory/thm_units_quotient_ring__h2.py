import sympy
import math
from functools import reduce

# Top-level setup
ZZ = sympy.ZZ
QQ = sympy.QQ

def conditions(witness) -> list[bool]:
    """
    Given a witness, checks if it is a valid counterexample to the false conjecture.
    The dropped hypothesis is that "I is an ideal of R". If I is not an ideal, 
    the quotient ring R/I is undefined (or not a quotient ring), making the LHS false,
    while the RHS (the ideal generated by x and I is R) can still be true.
    """
    try:
        # Extract R, x, I from the witness
        if isinstance(witness, dict):
            R_obj = witness.get('R', 0)
            x_obj = witness.get('x', 0)
            I_obj = witness.get('I', [])
        elif isinstance(witness, tuple) and len(witness) == 3:
            R_obj, x_obj, I_obj = witness
        else:
            R_obj = getattr(witness, 'R', 0)
            x_obj = getattr(witness, 'x', 0)
            I_obj = getattr(witness, 'I', [])
    except Exception:
        return [False, False, False]

    # H_1: R is a commutative ring with identity
    try:
        # We support Z (represented by 0 or 'Z') and Z_n (represented by n or 'Z_n')
        if R_obj == 0 or str(R_obj) in ['ZZ', 'Z', 'Integers']:
            n = 0
            h1 = True
        else:
            if isinstance(R_obj, str) and R_obj.startswith('Z_'):
                n = int(R_obj[2:])
            else:
                n = int(R_obj)
            h1 = (n >= 0)
    except Exception:
        h1 = False
        n = -1

    # H_2: x is an element of R
    try:
        x = int(x_obj)
        if n == 0:
            h2 = True
        elif n > 0:
            h2 = True
            x = x % n
        else:
            h2 = False
    except Exception:
        h2 = False

    # ¬Q: The conclusion fails at the witness
    try:
        if n < 0:
            neg_q = False
        else:
            # Parse I into a list of integers
            if isinstance(I_obj, str):
                I_obj = I_obj.strip()
                if I_obj.startswith('[') and I_obj.endswith(']'):
                    I_str = I_obj[1:-1].split(',')
                    I = [int(i.strip()) for i in I_str if i.strip()]
                else:
                    I = [int(I_obj)]
            elif isinstance(I_obj, (int, sympy.Integer)):
                I = [int(I_obj)]
            else:
                try:
                    iter(I_obj)
                    I = [int(i) for i in I_obj]
                except TypeError:
                    I = [int(I_obj)]
                
            if n > 0:
                I = [i % n for i in I]
                
            # Check if I is an ideal in R
            is_id = False
            if not I:
                is_id = False
            else:
                I_set = set(I)
                if n == 0:
                    # In Z, the only finite ideal is {0}
                    is_id = (I_set == {0})
                else:
                    # In Z_n, check closure under addition and multiplication
                    if 0 in I_set:
                        is_id = True
                        for a in I_set:
                            for b in I_set:
                                if (a + b) % n not in I_set:
                                    is_id = False
                                    break
                            if not is_id: break
                            for r in range(n):
                                if (r * a) % n not in I_set:
                                    is_id = False
                                    break
                            if not is_id: break
                    else:
                        is_id = False
                        
            # Evaluate LHS: x + I is a unit in the quotient ring R/I
            if not is_id:
                # If I is not an ideal, R/I is not a quotient ring
                lhs = False
            else:
                if n == 0:
                    lhs = (x in (1, -1))
                else:
                    lhs = False
                    for y in range(n):
                        if (x * y - 1) % n in I_set:
                            lhs = True
                            break
                            
            # Evaluate RHS: the ideal generated by x and I is the entire ring R
            elements = [x] + I
            if n > 0:
                elements.append(n)
            g = reduce(math.gcd, elements)
            g = abs(g)
            rhs = (g == 1)
            
            # The conclusion is LHS <==> RHS. We want it to fail.
            neg_q = (lhs != rhs)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

