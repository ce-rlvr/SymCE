def to_int(x, depth=0):
    """Robustly extract an integer representation from various object types."""
    if depth > 5: return None
    if isinstance(x, int): return x
    if x is sympy.ZZ: return 0
    if isinstance(x, sympy.Integer): return int(x)
    if callable(x): return None
    if isinstance(x, (set, list, tuple)):
        g = 0
        for item in x:
            val = to_int(item, depth+1)
            if val is not None:
                g = math.gcd(g, val)
        return g
    s = str(x)
    if len(s) > 1000:
        s = s[:1000]
    digits = ""
    for char in s:
        if char.isdigit():
            digits += char
        elif digits:
            break
    if digits:
        return int(digits)
    if 'Z' in s or 'z' in s: return 0
    return None

def parse_witness(witness):
    """
    Extract R_n, S_n, and M_gen from the witness.
    R_n and S_n represent Z/R_n Z and Z/S_n Z respectively (0 means Z).
    M_gen is the generator of the ideal M in S.
    """
    if isinstance(witness, dict):
        if 'R' in witness or 'R_n' in witness:
            R = witness.get('R', witness.get('R_n', 0))
            S = witness.get('S', witness.get('S_n', 0))
            M = witness.get('M', witness.get('M_gen', 0))
            return to_int(R), to_int(S), to_int(M)
        else:
            vals = list(witness.values())
            ints = []
            for x in vals:
                val = to_int(x)
                if val is not None:
                    ints.append(val)
            if len(ints) >= 3:
                return ints[0], ints[1], ints[2]
            elif len(ints) == 2:
                return ints[0], ints[1], 0
            return None, None, None
    
    if isinstance(witness, (tuple, list)):
        if len(witness) == 4:
            # Likely format: (R, S, f, M)
            R = to_int(witness[0])
            S = to_int(witness[1])
            M = to_int(witness[3])
            if R is not None and S is not None and M is not None:
                return R, S, M
        
        ints = []
        for x in witness:
            val = to_int(x)
            if val is not None:
                ints.append(val)
        if len(ints) >= 3:
            return ints[0], ints[1], ints[2]
        elif len(ints) == 2:
            return ints[0], ints[1], 0
            
    return None, None, None

def conditions(witness) -> list[bool]:
    try:
        R_n, S_n, M_gen = parse_witness(witness)
        if R_n is None or S_n is None or M_gen is None:
            return [False, False, False]
            
        # H_1: R and S are commutative rings with identity
        # Z/nZ is a commutative ring with identity for all n >= 0.
        # We exclude n=1 (the zero ring) to avoid degenerate cases where 1=0.
        h1 = (R_n >= 0) and (S_n >= 0) and (R_n != 1) and (S_n != 1)
        
        # H_2: f: R -> S is a surjective ring homomorphism
        # The natural map Z/R_n Z -> Z/S_n Z is a well-defined surjective homomorphism iff S_n divides R_n.
        if S_n == 0:
            h2 = (R_n == 0)
        else:
            h2 = (R_n % S_n == 0)
            
        # ¬Q: The preimage f^{-1}(M) is NOT a maximal ideal of R
        # M is generated by M_gen in Z/S_n Z.
        # The preimage f^{-1}(M) in Z/R_n Z is generated by g = gcd(M_gen, S_n).
        # In Z/R_n Z, the ideal <g> is maximal if and only if g is a prime number.
        if S_n > 0:
            g = math.gcd(M_gen, S_n)
        else:
            g = abs(M_gen)
            
        neg_q = not isprime(g)
        
        return [bool(h1), bool(h2), bool(neg_q)]
    except Exception:
        return [False, False, False]

