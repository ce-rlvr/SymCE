def conditions(witness) -> list[bool]:
    try:
        coeffs, n = witness
    except Exception:
        return [False, False, False, False, False]

    try:
        if not isinstance(coeffs, list) or not coeffs:
            h1 = False
        else:
            is_matrix = all(hasattr(C, 'is_Matrix') and C.is_Matrix and C.rows == C.cols and C.rows == coeffs[0].rows for C in coeffs)
            if is_matrix:
                h1 = all(all(getattr(e, 'is_integer', False) == True or isinstance(e, int) for e in C) for C in coeffs)
            else:
                h1 = all(getattr(c, 'is_integer', False) == True or isinstance(c, int) for c in coeffs)
    except Exception:
        h1 = False

    h2 = True

    try:
        entries = []
        for C in coeffs:
            if hasattr(C, 'is_Matrix') and C.is_Matrix:
                entries.extend(list(C))
            else:
                entries.append(C)
                
        d1 = entries[0]
        for e in entries[1:]:
            d1 = sympy.gcd(d1, e)
            
        h3 = (d1 != 0)
    except Exception:
        h3 = False

    try:
        h4 = isinstance(n, int) and n > 0
    except Exception:
        h4 = False

    try:
        def poly_mul(A, B):
            degA = len(A) - 1
            degB = len(B) - 1
            if hasattr(A[0], 'is_Matrix') and A[0].is_Matrix:
                res = [A[0].zeros(A[0].rows, A[0].cols) for _ in range(degA + degB + 1)]
            else:
                res = [0 for _ in range(degA + degB + 1)]
                
            for i in range(degA + 1):
                for j in range(degB + 1):
                    res[i+j] += A[i] * B[j]
            return res
        
        fn_coeffs = coeffs
        for _ in range(n - 1):
            fn_coeffs = poly_mul(fn_coeffs, coeffs)
            
        entries_n = []
        for C in fn_coeffs:
            if hasattr(C, 'is_Matrix') and C.is_Matrix:
                entries_n.extend(list(C))
            else:
                entries_n.append(C)
                
        dn = entries_n[0]
        for e in entries_n[1:]:
            dn = sympy.gcd(dn, e)
            
        neg_q = (dn != d1**n)
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]

