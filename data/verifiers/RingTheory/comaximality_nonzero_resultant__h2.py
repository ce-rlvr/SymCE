import sympy
from sympy.abc import x, y, z

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "Let k be a field. Assume the Sylvester resultant of f and g is non-zero. 
    Then the principal ideals (f) and (g) are comaximal in k[x]."
    """
    try:
        # Parse witness
        if isinstance(witness, (tuple, list)):
            if len(witness) == 3:
                f, g, x_var = witness
            elif len(witness) == 2:
                f, g = witness
                free = list(sympy.sympify(f).free_symbols | sympy.sympify(g).free_symbols)
                x_var = free[0] if free else sympy.Symbol('x')
            else:
                return [False, False, False]
        else:
            return [False, False, False]
            
        f = sympy.sympify(f)
        g = sympy.sympify(g)
        x_var = sympy.sympify(x_var)
        
        # Determine the variables (generators) of the polynomial ring
        gens = list(f.free_symbols | g.free_symbols)
        if not gens:
            gens = [x_var]
        elif x_var not in gens:
            gens.append(x_var)
            
        poly_f = f.as_poly(*gens)
        poly_g = g.as_poly(*gens)
        
        # H_1: Let k be a field
        # We ensure f and g are valid polynomials. The field condition is enforced 
        # by evaluating comaximality over a field (field=True in groebner).
        h1 = (poly_f is not None) and (poly_g is not None)
        
        # H_2: Assume the Sylvester resultant of f and g is non-zero
        # The resultant is taken with respect to the specified variable (x_var)
        res = sympy.resultant(f, g, x_var)
        h2 = bool(sympy.expand(res) != 0)
        
        # ¬Q: The principal ideals (f) and (g) are NOT comaximal
        # We check if 1 is in the ideal generated by f and g in the full polynomial ring.
        # field=True ensures the coefficient domain is treated as a field (e.g., QQ).
        gb = sympy.groebner([f, g], *gens, field=True)
        is_comaximal = (len(gb) == 1 and gb[0] == 1)
        
        neg_q = not is_comaximal
        
        return [h1, h2, neg_q]
    except Exception:
        return [False, False, False]

