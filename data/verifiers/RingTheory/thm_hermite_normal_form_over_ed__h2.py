CONDITION_LABELS = [
    "H_1: R is an integral domain",
    "H_2: A is an m x n matrix with entries in R",
    "¬Q: There does NOT exist an invertible m x m matrix U over R such that UA is in Hermite normal form"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    """
    Checks if the given witness is a valid counterexample.
    The witness should be a tuple (R, A) where R is a SymPy domain (e.g., ZZ[x])
    and A is a SymPy Matrix.
    """
    try:
        if not isinstance(witness, tuple) or len(witness) != 2:
            return [False, False, False]
        R, A = witness
    except Exception:
        return [False, False, False]
        
    # H_1: R is an integral domain
    try:
        # In SymPy, standard domains (like ZZ, QQ, ZZ[x]) inherit from Domain
        # and are integral domains.
        h1 = isinstance(R, Domain)
    except Exception:
        h1 = False
        
    # H_2: A is an m x n matrix with entries in R
    try:
        h2 = False
        if isinstance(A, Matrix):
            all_in_R = True
            for e in A:
                try:
                    # If the element cannot be coerced into the ring R, this raises an exception
                    R.from_sympy(e)
                except Exception:
                    all_in_R = False
                    break
            h2 = all_in_R
    except Exception:
        h2 = False
        
    # ¬Q: There does NOT exist an invertible m x m matrix U over R such that UA is in HNF
    try:
        neg_q = False
        if h1 and h2:
            # If R is a PID (like ZZ or QQ), HNF always exists, so it's not a counterexample.
            # We only proceed if R has generators (like ZZ[x] or QQ[x, y]).
            if hasattr(R, 'gens') and R.gens:
                col = None
                # Find the first non-zero column of A
                for j in range(A.cols):
                    c = A[:, j]
                    if not all(e == 0 for e in c):
                        col = c
                        break
                
                # For UA to be in HNF, its first non-zero column must be of the form [d, 0, ..., 0]^T.
                # This requires the ideal generated by the elements of `col` to be principal.
                if col is not None and A.rows >= 2:
                    exprs = [sympy.sympify(e) for e in col]
                    
                    # Compute the GCD of the column elements
                    d = exprs[0]
                    for e in exprs[1:]:
                        d = sympy.gcd(d, e)
                        
                    if d != 0:
                        # Divide elements by their GCD
                        reduced = [sympy.simplify(e / d) for e in exprs]
                        
                        gens = R.gens
                        ground = R.domain
                        
                        # Check if the reduced elements generate the unit ideal
                        gb = sympy.groebner(reduced, *gens, domain=ground)
                        is_unit_ideal = (len(gb) == 1 and gb[0] in [1, -1])
                        
                        # If they do NOT generate the unit ideal, the original ideal is not principal,
                        # meaning no such invertible matrix U exists.
                        neg_q = not is_unit_ideal
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]