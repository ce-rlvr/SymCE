import sympy

# Top-level setup: named object bindings that the witness expression may reference.
x, y = sympy.symbols('x y')

def conditions(witness) -> list[bool]:
    """
    Evaluates the remaining hypotheses and the negated conclusion at the given witness.
    """
    # H_1: Context hypothesis. We simply verify the witness is a valid mathematical expression in x and y.
    try:
        w = sympy.sympify(witness)
        if not w.free_symbols.issubset({x, y}):
            h1_ok = False
        else:
            h1_ok = True
    except Exception:
        h1_ok = False

    # ¬Q: The principal ideal generated by the image of the witness IS a prime ideal.
    # In the factor ring R = F[x,y]/(y^2 - x^3), the normalization is F[t] with x = t^2, y = t^3.
    # The ideal generated by w(x,y) in R is prime if and only if W(t) = w(t^2, t^3) is either 0
    # or an irreducible polynomial in F[t]. We assume F = QQ for the purpose of verification.
    try:
        w = sympy.sympify(witness)
        if not w.free_symbols.issubset({x, y}):
            neg_q_ok = False
        else:
            t = sympy.Symbol('t')
            # Substitute x = t^2, y = t^3
            W = w.subs({x: t**2, y: t**3})
            W = sympy.nsimplify(W)
            W = sympy.simplify(W)
            
            if W == 0:
                neg_q_ok = True
            else:
                poly_W = sympy.Poly(W, t, domain='QQ')
                neg_q_ok = poly_W.is_irreducible
    except Exception:
        neg_q_ok = False

    return [h1_ok, neg_q_ok]

