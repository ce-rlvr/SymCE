import sympy
from sympy import ZZ, QQ, Symbol

# Top-level setup for witness expressions
x = Symbol('x')

def conditions(witness):
    """
    Checks the remaining hypotheses and the negated conclusion.
    The witness is expected to be a tuple (R, d) where R is a polynomial ring and d is an integer.
    """
    try:
        R, d = witness
    except Exception:
        return [False, False, False]
        
    # H_1: d is a square-free integer such that d = 2 or 3 mod 4
    try:
        h1 = isinstance(d, (int, sympy.Integer)) and sympy.is_squarefree(abs(d)) and (d % 4 in [2, 3])
    except Exception:
        h1 = False
        
    # H_2: I = (x^2 - d) is the principal ideal generated by x^2 - d in R
    # This implies x^2 - d is an element of R. We check if R is a polynomial ring containing x.
    try:
        h2 = hasattr(R, 'gens') and any(str(g) == 'x' for g in R.gens)
    except Exception:
        h2 = False
        
    # ¬Q: The factor ring R/I is NOT isomorphic to the ring of algebraic integers of Q(sqrt(d))
    # For d = 2, 3 mod 4, the ring of algebraic integers is exactly ZZ[sqrt(d)].
    # R/(x^2 - d) is isomorphic to ZZ[sqrt(d)] if and only if R is isomorphic to ZZ[x].
    # If R is, for example, QQ[x], then R/I is a field (QQ(sqrt(d))), which is not isomorphic to ZZ[sqrt(d)].
    try:
        is_isomorphic = hasattr(R, 'domain') and (R.domain == sympy.ZZ) and (len(R.gens) == 1) and (str(R.gens[0]) == 'x')
        neg_q = not is_isomorphic
    except Exception:
        neg_q = True
        
    return [h1, h2, neg_q]

