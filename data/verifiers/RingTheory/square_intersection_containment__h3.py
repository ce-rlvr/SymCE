# Top-level setup
# The witness should be a tuple (R, add, mul, I, J) or a dictionary with these keys.
# R: list of elements in the ring
# add: callable f(a, b) for addition
# mul: callable f(a, b) for multiplication
# I: list of elements in the ideal I
# J: list of elements in the subset J

CONDITION_LABELS = [
    "H_1: R is a commutative ring",
    "H_2: I is an ideal of R",
    "¬Q: (I \\cap J)^2 \\not\\subseteq IJ"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    try:
        if isinstance(witness, dict):
            R = witness['R']
            add = witness['add']
            mul = witness['mul']
            I = witness['I']
            J = witness['J']
        else:
            R, add, mul, I, J = witness
    except Exception:
        return [False, False, False]

    # H_1: R is a commutative ring
    def check_h1():
        if not isinstance(R, list) or not R: return False
        if len(R) > 100: return False # Prevent timeouts
        
        # Check closure
        for a in R:
            for b in R:
                if add(a, b) not in R: return False
                if mul(a, b) not in R: return False
                
        # Check commutativity
        for a in R:
            for b in R:
                if add(a, b) != add(b, a): return False
                if mul(a, b) != mul(b, a): return False
                
        # Check associativity and distributivity
        for a in R:
            for b in R:
                for c in R:
                    if add(add(a, b), c) != add(a, add(b, c)): return False
                    if mul(mul(a, b), c) != mul(a, mul(b, c)): return False
                    if mul(a, add(b, c)) != add(mul(a, b), mul(a, c)): return False
                    
        # Check additive identity
        zero = None
        for z_elem in R:
            if all(add(a, z_elem) == a for a in R):
                zero = z_elem
                break
        if zero is None: return False
        
        # Check additive inverses
        for a in R:
            if not any(add(a, b) == zero for b in R): return False
            
        return True

    try:
        h1 = check_h1()
    except Exception:
        h1 = False

    # H_2: I is an ideal of R
    def check_h2():
        if not isinstance(I, list) or not I: return False
        if not all(elem in R for elem in I): return False
        
        zero = None
        for z_elem in R:
            if all(add(a, z_elem) == a for a in R):
                zero = z_elem
                break
        if zero not in I: return False
        
        # Closed under addition
        for a in I:
            for b in I:
                if add(a, b) not in I: return False
                
        # Closed under additive inverse
        for a in I:
            has_inv = False
            for b in I:
                if add(a, b) == zero:
                    has_inv = True
                    break
            if not has_inv: return False
            
        # Closed under scalar multiplication
        for r in R:
            for i in I:
                if mul(r, i) not in I: return False
                
        return True

    try:
        h2 = check_h2()
    except Exception:
        h2 = False

    # neg_Q: (I \cap J)^2 \not\subseteq IJ
    def check_neg_q():
        if not isinstance(J, list) or not all(elem in R for elem in J): return False
        
        InJ = [elem for elem in I if elem in J]
        
        # IJ is the ideal generated by products i * j
        IJ_prods = []
        for i in I:
            for j in J:
                p = mul(i, j)
                if p not in IJ_prods:
                    IJ_prods.append(p)
                    
        # Additive closure of IJ_prods
        closure_IJ = list(IJ_prods)
        changed = True
        while changed:
            changed = False
            new_elements = []
            for a in closure_IJ:
                for b in closure_IJ:
                    s = add(a, b)
                    if s not in closure_IJ and s not in new_elements:
                        new_elements.append(s)
            if new_elements:
                closure_IJ.extend(new_elements)
                changed = True
                
        # (I \cap J)^2 is the ideal generated by products x * y for x, y in I \cap J
        InJ_prods = []
        for x_elem in InJ:
            for y_elem in InJ:
                p = mul(x_elem, y_elem)
                for r in R:
                    rp = mul(r, p)
                    if rp not in InJ_prods:
                        InJ_prods.append(rp)
                        
        # Additive closure of InJ_prods
        closure_InJ2 = list(InJ_prods)
        changed = True
        while changed:
            changed = False
            new_elements = []
            for a in closure_InJ2:
                for b in closure_InJ2:
                    s = add(a, b)
                    if s not in closure_InJ2 and s not in new_elements:
                        new_elements.append(s)
            if new_elements:
                closure_InJ2.extend(new_elements)
                changed = True
                
        # Check if closure_InJ2 is a subset of closure_IJ
        is_subset = all(elem in closure_IJ for elem in closure_InJ2)
        return not is_subset

    try:
        neg_q = check_neg_q()
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]