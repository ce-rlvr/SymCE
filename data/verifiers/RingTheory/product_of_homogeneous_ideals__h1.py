import sympy
from sympy import symbols, Poly, groebner

# Top-level setup: named object bindings that the witness expression may reference.
x, y, z, w, t = symbols('x y z w t')

def conditions(witness):
    """
    Checks whether the witness is a valid counterexample to the conjecture.
    The witness should be a tuple (I_gens, J_gens) where I_gens and J_gens 
    are lists of generators (SymPy expressions) for the ideals I and J.
    """
    try:
        I_gens = [sympy.sympify(g) for g in witness[0]]
        J_gens = [sympy.sympify(g) for g in witness[1]]
    except Exception:
        return [False, False, False]
    
    syms = set()
    try:
        for g in I_gens + J_gens:
            syms.update(g.free_symbols)
        # Sort symbols by name to ensure deterministic behavior
        syms = sorted(list(syms), key=lambda s: s.name)
    except Exception:
        return [False, False, False]
        
    def is_homog(gens):
        if not gens:
            return True
        if not syms:
            return True
        try:
            # An ideal is homogeneous iff its reduced Groebner basis 
            # consists entirely of homogeneous polynomials.
            gb = groebner(gens, *syms)
            for p in gb:
                if not Poly(p, *syms).is_homogeneous:
                    return False
            return True
        except Exception:
            return False

    try:
        h1 = is_homog(I_gens)
    except Exception:
        h1 = False
        
    try:
        h2 = is_homog(J_gens)
    except Exception:
        h2 = False
        
    try:
        # The product ideal IJ is generated by the pairwise products of the generators of I and J
        IJ_gens = [p * q for p in I_gens for q in J_gens]
        q_cond = is_homog(IJ_gens)
        neg_q = not q_cond
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

