def all_zero(c):
    """Recursively check if an element, matrix, or list of elements is entirely zero."""
    if hasattr(c, 'is_zero_matrix'):
        return c.is_zero_matrix
    if hasattr(c, 'is_zero') and c.is_zero is not None:
        return c.is_zero
    if hasattr(c, '__iter__') and not isinstance(c, (str, dict)):
        return all(all_zero(x) for x in c)
    try:
        return bool(c == 0)
    except Exception:
        pass
    return False

def conditions(witness):
    try:
        f, g = witness
        
        # Extract coefficients if the witness provides sympy.Poly objects
        if hasattr(f, 'all_coeffs'):
            f = f.all_coeffs()
        if hasattr(g, 'all_coeffs'):
            g = g.all_coeffs()
            
        # The witness should be represented as lists/tuples of coefficients
        if not isinstance(f, (list, tuple)) or not isinstance(g, (list, tuple)):
            return [False, False, False, False]
        
        # H_1: f and g are polynomials over R (must have coefficients)
        h1 = len(f) > 0 and len(g) > 0
        
        # H_2 and H_3 are definitions, so they trivially hold
        h2 = True
        h3 = True
        
        # Compute the coefficients of the product polynomial fg
        fg = [None] * (len(f) + len(g) - 1)
        for i, a in enumerate(f):
            for j, b in enumerate(g):
                if fg[i+j] is None:
                    fg[i+j] = a * b
                else:
                    fg[i+j] = fg[i+j] + a * b
                    
        # Check if the product polynomial fg is identically zero
        fg_zero = all(all_zero(c) for c in fg)
        
        # Check if the product of the contents c(f)c(g) is zero
        # c(f)c(g) is generated by all products a * b for a in f, b in g
        cfg_zero = True
        for a in f:
            for b in g:
                if not all_zero(a * b):
                    cfg_zero = False
                    break
            if not cfg_zero:
                break
                
        # The conclusion is \sqrt{c(fg)} = \sqrt{c(f)c(g)}.
        # For standard counterexamples over non-commutative rings (like matrix rings),
        # fg = 0 (so \sqrt{c(fg)} = 0) but c(f)c(g) != 0 (so \sqrt{c(f)c(g)} != 0).
        # Thus, if fg is zero but c(f)c(g) is not, the conclusion fails.
        neg_q = fg_zero and not cfg_zero
        
        return [h1, h2, h3, neg_q]
    except Exception:
        return [False, False, False, False]

