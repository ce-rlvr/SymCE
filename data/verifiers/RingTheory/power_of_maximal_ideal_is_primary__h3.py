import sympy
from sympy import ZZ, QQ

# Top-level setup
Z = ZZ

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "If R is a commutative ring and M is a maximal ideal of R, then M^n is an M-primary ideal."
    
    The dropped hypothesis is that n > 0. A standard counterexample is n = 0,
    since M^0 = R, and the whole ring R is not a proper ideal, hence not primary.
    """
    try:
        # Parse witness
        if isinstance(witness, (tuple, list)) and len(witness) == 3:
            R, M, n = witness
        elif isinstance(witness, dict):
            R = witness.get('R', ZZ)
            M = witness.get('M', 2)
            n = witness.get('n', 0)
        elif isinstance(witness, (int, sympy.Integer)):
            R, M, n = ZZ, 2, witness
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H_1: R is a commutative ring
    try:
        if R in ['Z', 'ZZ', ZZ]:
            h1 = True
        elif hasattr(R, 'is_commutative'):
            h1 = bool(R.is_commutative)
        else:
            h1 = False
    except Exception:
        h1 = False

    # H_2: M is a maximal ideal of R
    try:
        if R in ['Z', 'ZZ', ZZ]:
            # In Z, an ideal generated by M is maximal iff |M| is prime
            h2 = sympy.isprime(abs(int(M)))
        else:
            h2 = False
    except Exception:
        h2 = False

    # ¬Q: The ideal M^n is not an M-primary ideal
    try:
        if R in ['Z', 'ZZ', ZZ]:
            n_int = int(n)
            M_int = int(M)
            
            if n_int <= 0:
                # If n = 0, M^0 = 1, which generates the whole ring Z (not a proper ideal, so not primary).
                # If n < 0, M^n is not an ideal in Z.
                neg_q = True
            else:
                # For n > 0, M^n is M-primary iff M^n is primary and its radical is M.
                # In Z, this is true iff M is a prime number or M = 0.
                if M_int == 0:
                    neg_q = False
                else:
                    neg_q = not sympy.isprime(abs(M_int))
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

