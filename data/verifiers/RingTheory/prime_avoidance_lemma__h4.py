import sympy

# Top-level setup
# For this Ring Theory conjecture, we evaluate witnesses in the ring of integers Z.
# Ideals in Z are principal and can be represented by their integer generators.
# A witness should be a tuple (P_list, I) where P_list is a list of integers 
# representing the ideals P_i, and I is an integer representing the ideal I.

def is_int(x):
    try:
        return int(x) == x and not isinstance(x, float)
    except Exception:
        return False

def is_prime_ideal(p):
    try:
        p_val = int(p)
        if p_val == 0:
            return True
        return sympy.isprime(abs(p_val))
    except Exception:
        return False

def is_subset(i, p):
    try:
        i_val = int(i)
        p_val = int(p)
        if p_val == 0:
            return i_val == 0
        return i_val % p_val == 0
    except Exception:
        return False

def conditions(witness):
    try:
        if isinstance(witness, dict):
            P_list = witness.get('P_list', witness.get('P'))
            I = witness['I']
        elif isinstance(witness, (list, tuple)):
            if len(witness) == 2:
                P_list, I = witness
            elif len(witness) == 3:
                _, P_list, I = witness
            else:
                return [False, False, False, False]
        else:
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]

    # H_1: R is a commutative ring
    # We interpret the witness as ideals in Z, generated by the given integers.
    try:
        h1 = isinstance(P_list, (list, tuple, set)) and len(P_list) >= 1 and all(is_int(p) for p in P_list) and is_int(I)
    except Exception:
        h1 = False

    # H_2: P_1, ..., P_n are ideals of R such that at most two of them are not prime ideals
    try:
        if not h1:
            h2 = False
        else:
            non_primes = sum(1 for p in P_list if not is_prime_ideal(p))
            h2 = non_primes <= 2
    except Exception:
        h2 = False

    # H_3: I is an ideal of R
    # In Z, any integer generates an ideal.
    try:
        h3 = h1
    except Exception:
        h3 = False

    # ¬Q: I is not a subset of any P_i
    try:
        if not h1:
            neg_q = False
        else:
            neg_q = True
            for p in P_list:
                if is_subset(I, p):
                    neg_q = False
                    break
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

