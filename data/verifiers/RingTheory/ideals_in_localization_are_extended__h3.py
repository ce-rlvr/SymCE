# Expected witness format:
# witness = (n, S, J)
# where:
#   n (int): modulus for the ring R = Z/nZ (2 <= n <= 50)
#   S (list of int): multiplicatively closed subset of R
#   J (list of tuples): subset of S^{-1}R, where each element is a fraction r/s represented as (r, s)

def conditions(witness) -> list[bool]:
    try:
        if not isinstance(witness, (list, tuple)) or len(witness) != 3:
            return [False, False, False]
        n, S, J = witness
    except Exception:
        return [False, False, False]
        
    # H1: R is a commutative ring with identity
    try:
        h1 = isinstance(n, int) and 2 <= n <= 50
    except Exception:
        h1 = False
        
    # H2: S is a multiplicatively closed subset of R
    try:
        h2 = False
        if isinstance(S, (list, set, tuple)) and len(S) > 0:
            S_set = set(S)
            valid = True
            for a in S_set:
                if not isinstance(a, int) or a < 0 or a >= n:
                    valid = False
                    break
            if valid:
                closed = True
                for a in S_set:
                    for b in S_set:
                        if (a * b) % n not in S_set:
                            closed = False
                            break
                    if not closed:
                        break
                h2 = closed
    except Exception:
        h2 = False
        
    # neg_Q: J is not of the form S^{-1}I for any ideal I of R
    try:
        neg_q = False
        if h1 and h2 and isinstance(J, (list, set, tuple)):
            S_set = set(S)
            
            # Precompute elements annihilated by S
            annihilated_by_S = set()
            for d in range(n):
                for u in S_set:
                    if (u * d) % n == 0:
                        annihilated_by_S.add(d)
                        break
                        
            pairs = [(r, s) for r in range(n) for s in S_set]
            parent = {p: p for p in pairs}
            
            def find(i):
                root = i
                while parent[root] != root:
                    root = parent[root]
                curr = i
                while curr != root:
                    nxt = parent[curr]
                    parent[curr] = root
                    curr = nxt
                return root
                
            def union(i, j):
                root_i = find(i)
                root_j = find(j)
                if root_i != root_j:
                    if root_i < root_j:
                        parent[root_j] = root_i
                    else:
                        parent[root_i] = root_j

            # Build equivalence classes for S^{-1}R
            for i in range(len(pairs)):
                r1, s1 = pairs[i]
                for j in range(i + 1, len(pairs)):
                    r2, s2 = pairs[j]
                    d = (r1 * s2 - r2 * s1) % n
                    if d in annihilated_by_S:
                        union(pairs[i], pairs[j])
                        
            reps = {}
            for p in pairs:
                reps[p] = find(p)
                
            J_canon = set()
            valid_J = True
            for item in J:
                if not isinstance(item, (list, tuple)) or len(item) != 2:
                    valid_J = False
                    break
                r, s = item
                if not isinstance(r, int) or not isinstance(s, int):
                    valid_J = False
                    break
                if r < 0 or r >= n or s not in S_set:
                    valid_J = False
                    break
                J_canon.add(reps[(r, s)])
                
            if valid_J:
                # Get all ideals of Z/nZ (generated by divisors of n)
                ideals = []
                for d in range(1, n + 1):
                    if n % d == 0:
                        ideal = set((k * d) % n for k in range(n // d))
                        ideals.append(ideal)
                
                is_extended = False
                for I in ideals:
                    S_inv_I = set()
                    for x in I:
                        for s in S_set:
                            S_inv_I.add(reps[(x, s)])
                    if J_canon == S_inv_I:
                        is_extended = True
                        break
                
                neg_q = not is_extended
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

