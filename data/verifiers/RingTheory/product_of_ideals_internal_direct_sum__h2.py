def get_attr(witness, name):
    if isinstance(witness, dict):
        return witness[name]
    return getattr(witness, name)

def conditions(witness) -> list[bool]:
    try:
        elements = list(get_attr(witness, 'elements'))
        zero = get_attr(witness, 'zero')
        add = get_attr(witness, 'add')
        mul = get_attr(witness, 'mul')
        I = list(get_attr(witness, 'I'))
        J = list(get_attr(witness, 'J'))
        action = get_attr(witness, 'action')
    except Exception:
        return [False, False, False]

    # H_1: R is a commutative ring
    h1 = True
    try:
        if zero not in elements:
            h1 = False
            
        for a in elements:
            if add(a, zero) != a or add(zero, a) != a:
                h1 = False
                
            has_inv = False
            for b in elements:
                if add(a, b) == zero and add(b, a) == zero:
                    has_inv = True
                    break
            if not has_inv:
                h1 = False
                
            for b in elements:
                if add(a, b) not in elements: h1 = False
                if mul(a, b) not in elements: h1 = False
                if add(a, b) != add(b, a): h1 = False
                if mul(a, b) != mul(b, a): h1 = False
                for c in elements:
                    if add(add(a, b), c) != add(a, add(b, c)): h1 = False
                    if mul(mul(a, b), c) != mul(a, mul(b, c)): h1 = False
                    if mul(a, add(b, c)) != add(mul(a, b), mul(a, c)): h1 = False
    except Exception:
        h1 = False

    # H_2: R is the internal direct sum of I and J as R-modules
    h2 = True
    try:
        if not all(x in elements for x in I): h2 = False
        if not all(x in elements for x in J): h2 = False
        if zero not in I or zero not in J: h2 = False
        
        # I and J are closed under addition
        for i1 in I:
            for i2 in I:
                if add(i1, i2) not in I: h2 = False
        for j1 in J:
            for j2 in J:
                if add(j1, j2) not in J: h2 = False
                
        # I and J are closed under R-module action
        for r in elements:
            for i in I:
                if action(r, i) not in I: h2 = False
            for j in J:
                if action(r, j) not in J: h2 = False

        # R-module axioms
        for r in elements:
            for s in elements:
                for x in elements:
                    for y in elements:
                        if action(r, add(x, y)) != add(action(r, x), action(r, y)): h2 = False
                        if action(add(r, s), x) != add(action(r, x), action(s, x)): h2 = False
                        if action(mul(r, s), x) != action(r, action(s, x)): h2 = False

        # Unital action if R has an identity
        identity = None
        for e in elements:
            if all(mul(e, x) == x for x in elements):
                identity = e
                break
        if identity is not None:
            for x in elements:
                if action(identity, x) != x: h2 = False

        # Internal direct sum: I \cap J = {0}
        for x in I:
            if x in J and x != zero: h2 = False
            
        # Internal direct sum: I + J = R
        sums = []
        for i in I:
            for j in J:
                s_val = add(i, j)
                if s_val not in sums:
                    sums.append(s_val)
        for x in elements:
            if x not in sums: h2 = False
    except Exception:
        h2 = False

    # ¬Q: The product ideal IJ is not the zero ideal
    neg_q = False
    try:
        # IJ is the ideal generated by {i*j | i \in I, j \in J}
        # If any i*j != 0, the ideal is not the zero ideal.
        for i in I:
            for j in J:
                if mul(i, j) != zero:
                    neg_q = True
    except Exception:
        neg_q = False

    return [bool(h1), bool(h2), bool(neg_q)]

