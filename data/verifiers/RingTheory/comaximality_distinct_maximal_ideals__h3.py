import sympy
from sympy import isprime, gcd, Symbol, S
from sympy.polys.domains import ZZ, QQ
import functools

# Top-level setup for witness expressions
x = Symbol('x')
y = Symbol('y')
Z = ZZ
Q = QQ

def Ideal(*args):
    """
    Helper to allow the LLM to write Ideal(2) or Ideal(x).
    In a PID, an ideal generated by multiple elements is generated by their gcd.
    """
    if not args:
        return 0
    return functools.reduce(gcd, args)

CONDITION_LABELS = [
    "H_1: R is a commutative ring with identity",
    "H_2: M_1 and M_2 are maximal ideals of R",
    "¬Q: M_1 + M_2 != R"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness) -> list[bool]:
    # Extract R, M1, M2 from the witness
    try:
        if isinstance(witness, tuple):
            if len(witness) == 3:
                R, M1, M2 = witness
            elif len(witness) == 2:
                R = ZZ
                M1, M2 = witness
            else:
                return [False, False, False]
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H_1: R is a commutative ring with identity
    try:
        # We accept any non-None R as a valid ring representation for the sake of the counterexample,
        # since the core logic is evaluated on the ideal generators in a PID (ZZ or QQ[x]).
        h1 = R is not None
    except Exception:
        h1 = False

    # H_2: M_1 and M_2 are maximal ideals of R
    try:
        def is_max(M):
            # In ZZ, an ideal is maximal iff its generator is prime
            if isinstance(M, (int, sympy.Integer)):
                return sympy.isprime(abs(int(M)))
            # In QQ[x], an ideal is maximal iff its generator is irreducible
            try:
                poly = sympy.Poly(M)
                return poly.is_irreducible
            except Exception:
                return False
                
        h2 = bool(is_max(M1) and is_max(M2))
    except Exception:
        h2 = False

    # ¬Q: M_1 + M_2 != R
    try:
        # In a PID, M_1 + M_2 is generated by gcd(M_1, M_2).
        # The sum is the whole ring R iff the gcd is a unit.
        g = sympy.gcd(M1, M2)
        if isinstance(g, (int, sympy.Integer)):
            # In ZZ, the only units are 1 and -1
            neg_q = bool(abs(int(g)) != 1)
        else:
            # For polynomials, the units are the non-zero constants
            g_expr = sympy.sympify(g)
            if hasattr(g_expr, 'is_constant'):
                neg_q = not bool(g_expr.is_constant())
            else:
                neg_q = True
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]