import sympy
from sympy import Poly, Basic, Symbol
from sympy.abc import x, y, z, a, b, c, u, v, w

def conditions(witness) -> list[bool]:
    # H_1: R is a commutative ring (witness is a polynomial over a commutative ring)
    try:
        if not isinstance(witness, Basic):
            h1 = False
        else:
            vars = list(witness.free_symbols)
            if not vars:
                # If there are no free symbols, check if it's a valid constant polynomial
                Poly(witness, Symbol('__dummy__'))
                h1 = True
            else:
                # Check if it's a valid polynomial in its variables
                Poly(witness, *vars)
                h1 = True
    except Exception:
        h1 = False

    # ¬Q: There does not exist a unique polynomial g such that f = g(e_1, ..., e_n)
    # This conclusion fails (i.e., ¬Q is True) if and only if f is NOT a symmetric polynomial.
    try:
        if not h1:
            neg_q = False
        else:
            vars = sorted(list(witness.free_symbols), key=lambda s: s.name)
            if len(vars) <= 1:
                # Polynomials in 0 or 1 variable are trivially symmetric
                neg_q = False
            else:
                is_sym = True
                f_exp = witness.expand()
                # The symmetric group S_n is generated by adjacent transpositions.
                # We only need to check invariance under swapping vars[i] and vars[i+1].
                for i in range(len(vars) - 1):
                    swap_dict = {vars[i]: vars[i+1], vars[i+1]: vars[i]}
                    if f_exp.subs(swap_dict, simultaneous=True).expand() != f_exp:
                        is_sym = False
                        break
                neg_q = not is_sym
    except Exception:
        neg_q = False

    return [h1, neg_q]

