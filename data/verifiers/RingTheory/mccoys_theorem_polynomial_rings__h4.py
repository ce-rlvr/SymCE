def parse_witness(witness):
    """
    Parses the witness into a modulus n and a list of integer coefficients.
    n = 0 represents Z, n = -1 represents a field (like Q), n >= 2 represents Z/nZ.
    """
    if isinstance(witness, tuple) and len(witness) == 2:
        a, b = witness
        
        n = None
        if isinstance(a, int):
            n = a
        elif hasattr(a, 'is_Ring') or hasattr(a, 'is_Field'):
            if getattr(a, 'is_ZZ', False):
                n = 0
            elif getattr(a, 'is_Field', False):
                n = -1
            else:
                n = 0
                
        if n is not None:
            if isinstance(b, (list, tuple)):
                return n, [int(c) for c in b]
            else:
                p = sympy.Poly(b, x)
                return n, [int(c) for c in p.all_coeffs()]
                
    if isinstance(witness, sympy.Poly):
        domain = witness.domain
        n = 0 if domain.is_ZZ else (-1 if domain.is_Field else 0)
        return n, [int(c) for c in witness.all_coeffs()]
        
    if isinstance(witness, (sympy.Expr, int)):
        p = sympy.Poly(witness, x)
        return 0, [int(c) for c in p.all_coeffs()]
        
    if isinstance(witness, (list, tuple)):
        return 0, [int(c) for c in witness]
        
    raise ValueError("Cannot parse witness")

def conditions(witness) -> list[bool]:
    try:
        n, coeffs = parse_witness(witness)
    except Exception:
        return [False, False, False, False]
        
    # H_1: R is a commutative ring with identity
    try:
        h1 = (isinstance(n, int) and (n == -1 or n == 0 or n >= 2))
    except Exception:
        h1 = False
        
    # H_2: f is a polynomial over R
    try:
        h2 = isinstance(coeffs, list) and len(coeffs) > 0 and all(isinstance(c, int) for c in coeffs)
    except Exception:
        h2 = False
        
    # H_3: c(f) denotes the ideal generated by the coefficients of f
    try:
        h3 = h1 and h2
    except Exception:
        h3 = False
        
    # ¬Q: There does not exist a non-zero element r in R such that r c(f) = {0}
    try:
        if n == 0 or n == -1:
            has_annihilator = all(c == 0 for c in coeffs)
        elif n >= 2:
            g = reduce(math.gcd, coeffs, n)
            has_annihilator = (g > 1)
        else:
            has_annihilator = True
            
        neg_q = not has_annihilator
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

