def conditions(witness) -> list[bool]:
    # Parse the witness into a polynomial
    try:
        if isinstance(witness, Poly):
            f = witness
            x = f.gens[0]
        else:
            f_expr = sympify(witness)
            free = f_expr.free_symbols
            if not free:
                x = Symbol('x')
            else:
                x = Symbol('x') if Symbol('x') in free else list(free)[0]
            f = Poly(f_expr, x)
    except Exception:
        return [False, False, False]

    # H_1: f \in R[x] is a non-constant polynomial
    try:
        h1 = f.degree() > 0
    except Exception:
        h1 = False

    # H_2: The formal derivative f' is non-zero
    try:
        f_prime = f.diff()
        h2 = not f_prime.is_zero
    except Exception:
        h2 = False

    # neg_Q: The content c(f) does NOT divide the content c(f') in R
    try:
        c_f = f.content()
        c_f_prime = f_prime.content()
        domain = f.domain
        
        divides_gcd = False
        if c_f == domain.zero:
            divides_gcd = (c_f_prime == domain.zero)
        elif domain.is_Field:
            divides_gcd = True
        else:
            try:
                q, r = domain.div(c_f_prime, c_f)
                divides_gcd = (r == domain.zero)
            except Exception:
                c_f_expr = sympify(c_f)
                c_f_prime_expr = sympify(c_f_prime)
                ratio = cancel(c_f_prime_expr / c_f_expr)
                divides_gcd = ratio.as_numer_denom()[1] == 1
                
        if not divides_gcd:
            neg_q = True
        else:
            # Check ideal divisibility for rings that are not Principal Ideal Domains (like Z[y, z])
            # In such rings, content is the ideal generated by the coefficients.
            # If the ideal is not principal, c(f) generally does not divide c(f').
            coeffs = f.all_coeffs()
            coeffs = [c for c in coeffs if c != 0]
            
            if not coeffs:
                neg_q = False
            else:
                g = coeffs[0]
                for c in coeffs[1:]:
                    g = gcd(g, c)
                
                A_prime = [cancel(c / g) for c in coeffs]
                
                free_vars = set()
                for a in A_prime:
                    free_vars.update(sympify(a).free_symbols)
                free_vars = list(free_vars)
                
                is_princ = False
                if not free_vars:
                    num_gcd = A_prime[0]
                    for a in A_prime[1:]:
                        num_gcd = gcd(num_gcd, a)
                    is_princ = (num_gcd == 1 or num_gcd == -1)
                else:
                    try:
                        gb = groebner(A_prime, *free_vars)
                        if len(gb) == 1 and gb[0] == 1:
                            is_princ = True
                    except Exception:
                        is_princ = True
                
                neg_q = not is_princ
    except Exception:
        neg_q = False

    return [bool(h1), bool(h2), bool(neg_q)]

