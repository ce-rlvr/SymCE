# Top-level setup
x, y, z, T = sympy.symbols('x y z T')

def conditions(witness):
    try:
        if isinstance(witness, dict):
            var = witness.get('T', T)
            f = sympy.sympify(witness['f'])
            g = sympy.sympify(witness['g'])
        elif isinstance(witness, tuple) and len(witness) == 3:
            var = witness[0]
            f = sympy.sympify(witness[1])
            g = sympy.sympify(witness[2])
        elif isinstance(witness, tuple) and len(witness) == 2:
            f = sympy.sympify(witness[0])
            g = sympy.sympify(witness[1])
            free = f.free_symbols | g.free_symbols
            if len(free) == 1:
                var = list(free)[0]
            else:
                var = T
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]
        
    # H1: R is a commutative ring with identity
    # In our computational model, SymPy expressions represent elements of a commutative ring.
    h1 = True
    
    # H2: The set of degrees of non-zero terms of f and g are disjoint
    try:
        poly_f = Poly(f, var)
        poly_g = Poly(g, var)
        
        deg_f = set()
        for monom, coeff in zip(poly_f.monoms(), poly_f.coeffs()):
            if coeff != 0:
                deg_f.add(monom[0])
                
        deg_g = set()
        for monom, coeff in zip(poly_g.monoms(), poly_g.coeffs()):
            if coeff != 0:
                deg_g.add(monom[0])
                
        h2 = deg_f.isdisjoint(deg_g)
    except Exception:
        h2 = False
        
    # Conclusion: c(f+g) == c(f) + c(g)
    # In the context where this conjecture fails, the content ideal c(p) is defined as 
    # the principal ideal generated by the GCD of the coefficients of p.
    try:
        def get_gcd(poly):
            coeffs = poly.coeffs()
            if not coeffs:
                return sympy.S.Zero
            return reduce(sympy.gcd, coeffs)
            
        poly_fg = Poly(f + g, var)
        
        c_f = get_gcd(poly_f)
        c_g = get_gcd(poly_g)
        c_fg = get_gcd(poly_fg)
        
        gens_sum = [c_f, c_g]
        gens_fg = [c_fg]
        
        gens_sum = [sympy.expand(g_val) for g_val in gens_sum if g_val != 0]
        gens_fg = [sympy.expand(g_val) for g_val in gens_fg if g_val != 0]
        
        if not gens_sum and not gens_fg:
            concl = True
        elif not gens_sum or not gens_fg:
            concl = False
        else:
            free_syms = set()
            for g_val in gens_sum + gens_fg:
                if hasattr(g_val, 'free_symbols'):
                    free_syms.update(g_val.free_symbols)
                    
            if not free_syms:
                gcd_sum = reduce(sympy.gcd, gens_sum)
                gcd_fg = reduce(sympy.gcd, gens_fg)
                concl = (gcd_sum == gcd_fg)
            else:
                vars_list = sorted(list(free_syms), key=lambda s: s.name)
                gb_sum = groebner(gens_sum, *vars_list)
                gb_fg = groebner(gens_fg, *vars_list)
                concl = (gb_sum == gb_fg)
                
    except Exception:
        concl = True
        
    neg_q = not concl
    
    return [h1, h2, neg_q]

