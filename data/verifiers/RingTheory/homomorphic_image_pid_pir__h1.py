import sympy
from sympy.polys.domains import ZZ, QQ
from sympy.polys.rings import ring
from sympy.abc import x, y, z

CONDITION_LABELS = [
    "H_1: I is an ideal of R",
    "¬Q: The quotient ring R/I is not a principal ideal ring"
]

N_HYP = 1
NEG_Q_INDEX = 1

def conditions(witness):
    try:
        R, I = witness
    except Exception:
        return [False, False]
        
    # H_1: I is an ideal of R
    # We verify that R is a ring-like object and I is a valid collection of elements in R.
    try:
        if not hasattr(R, 'zero'):
            h1 = False
        elif not isinstance(I, (list, tuple, set)):
            h1 = False
        else:
            h1 = True
            for f in I:
                if f == 0 or f == R.zero:
                    continue
                if f not in R:
                    h1 = False
                    break
    except Exception:
        h1 = False
        
    # ¬Q: R/I is not a principal ideal ring
    # We check for standard non-PIRs: ZZ[x1, ..., xn] (n >= 1) and K[x1, ..., xn] (n >= 2).
    # If I is generated by a subset of variables, we evaluate the remaining variables.
    try:
        neg_q = False
        if hasattr(R, 'domain') and hasattr(R, 'gens'):
            gens_in_I = []
            other_in_I = False
            for f in I:
                if f == 0 or (hasattr(R, 'zero') and f == R.zero):
                    continue
                if f in R.gens:
                    gens_in_I.append(f)
                else:
                    other_in_I = True
            
            if not other_in_I:
                remaining_gens = len(R.gens) - len(set(gens_in_I))
                if R.domain == ZZ and remaining_gens >= 1:
                    neg_q = True
                elif getattr(R.domain, 'is_Field', False) and remaining_gens >= 2:
                    neg_q = True
    except Exception:
        neg_q = False
        
    return [h1, neg_q]