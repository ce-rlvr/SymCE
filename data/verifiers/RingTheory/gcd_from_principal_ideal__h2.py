def check_kZ(k, a, b, d):
    """
    Checks the conditions for the ring R = kZ (multiples of k).
    For k > 0, kZ is a commutative ring without identity (if k >= 2) and has no zero divisors,
    so it is an integral domain (under the definition that doesn't require an identity).
    """
    if k <= 0:
        return False, False, False
    
    in_R = lambda v: v % k == 0
    
    # H1: R is an integral domain
    h1 = True
    
    if not (in_R(a) and in_R(b) and in_R(d)):
        return h1, False, False
        
    # H2: The ideal generated by a and b in R is a principal ideal, generated by d.
    # In kZ, the ideal generated by any subset is exactly the Z-ideal generated by it.
    # So (a, b) == (d) in kZ if and only if gcd(a, b) == |d|.
    if abs(d) != math.gcd(a, b):
        return h1, False, False
    h2 = True
    
    def divides_in_R(u, v):
        if u == 0:
            return v == 0
        if v % u != 0:
            return False
        return in_R(v // u)
        
    d_divides_a = divides_in_R(d, a)
    d_divides_b = divides_in_R(d, b)
    
    # Check if d is a greatest common divisor of a and b in R
    is_gcd = False
    if d_divides_a and d_divides_b:
        if a == 0 and b == 0:
            is_gcd = (d == 0)
        else:
            g = math.gcd(a, b)
            common_divisors = []
            for i in range(1, abs(g) + 1):
                if g % i == 0:
                    if in_R(i) and divides_in_R(i, a) and divides_in_R(i, b):
                        common_divisors.append(i)
                    if in_R(-i) and divides_in_R(-i, a) and divides_in_R(-i, b):
                        common_divisors.append(-i)
            
            is_gcd = True
            for c in common_divisors:
                if not divides_in_R(c, d):
                    is_gcd = False
                    break
                    
    neg_q = not is_gcd
    return h1, h2, neg_q

def conditions(witness):
    """
    Given a witness, checks if it is a valid counterexample.
    The standard counterexample is in a ring without identity, such as 2Z.
    """
    # 1. Check if witness is a SymPy ring tuple: (R, a, b, d)
    try:
        if isinstance(witness, tuple) and len(witness) == 4:
            R, a, b, d = witness
            if hasattr(R, 'is_domain') or hasattr(R, 'is_IntegralDomain'):
                h1 = bool(getattr(R, 'is_domain', False) or getattr(R, 'is_IntegralDomain', False))
                try:
                    g = R.gcd(a, b)
                    # Check if d and g are associates (i.e., generate the same ideal)
                    q1 = R.exquo(g, d)
                    q2 = R.exquo(d, g)
                    h2 = True
                except Exception:
                    h2 = False
                # In any SymPy domain (which has an identity), if (a, b) == (d), d is ALWAYS a GCD.
                neg_q = False
                return [h1, h2, neg_q]
    except Exception:
        pass

    # 2. Check if witness represents elements in kZ
    k = None
    a = None
    b = None
    d = None
    
    try:
        if isinstance(witness, dict):
            a = witness.get('a')
            b = witness.get('b')
            d = witness.get('d')
            k = witness.get('k')
        elif isinstance(witness, tuple):
            if len(witness) == 3:
                a, b, d = witness
            elif len(witness) >= 4:
                k, a, b, d = witness[:4]
        else:
            a = getattr(witness, 'a', None)
            b = getattr(witness, 'b', None)
            d = getattr(witness, 'd', None)
            k = getattr(witness, 'k', None)
            
        if a is not None and b is not None and d is not None:
            a = int(a)
            b = int(b)
            d = int(d)
            
            if k is not None:
                k = int(k)
                return list(check_kZ(k, a, b, d))
            else:
                # If k is not provided, search for a valid k that makes it a counterexample.
                # k must divide d, so we test all possible divisors >= 2.
                if d != 0:
                    for test_k in range(2, abs(d) + 1):
                        if d % test_k == 0:
                            res = check_kZ(test_k, a, b, d)
                            if res == (True, True, True):
                                return [True, True, True]
                
                # Fallback to k=1 (which represents Z, a ring with identity)
                return list(check_kZ(1, a, b, d))
    except Exception:
        pass
        
    return [False, False, False]

