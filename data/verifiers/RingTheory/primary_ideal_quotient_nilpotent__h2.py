import math
from sympy.ntheory import factorint

# Top-level setup
# Witnesses are expected to be tuples (n, m) representing the ring R = Z/nZ 
# and the ideal q = (m). 
# For example, (0, 1) represents R = Z and q = (1) = Z.
# (2, 1) represents R = Z/2Z and q = (1) = R.

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            n, m = witness
        elif isinstance(witness, int):
            n, m = witness, 1
        else:
            return [False, False]
            
        try:
            n = abs(int(n))
            m = abs(int(m))
        except (ValueError, TypeError):
            return [False, False]
            
        # H_1: R is a commutative ring with identity
        # Z/nZ is always a commutative ring with identity
        h1 = True
        
        # The ideal q = (m) in Z/nZ is generated by g = gcd(n, m)
        g = math.gcd(n, m) if n > 0 else m
        
        # Check if q is primary in R
        # An ideal is primary iff it is proper and every zero divisor in R/q is nilpotent.
        # In Z/nZ, q=(g) is proper iff g != 1.
        if g == 0:
            is_primary = True
        elif g == 1:
            is_primary = False
        else:
            factors = factorint(g)
            is_primary = (len(factors) == 1)
            
        # Check if every zero divisor in R/q is nilpotent
        # R/q is isomorphic to Z/gZ.
        # If g == 1, R/q is the zero ring. It has no zero divisors, so vacuously True.
        if g == 0 or g == 1:
            all_zd_nilpotent = True
        else:
            factors = factorint(g)
            all_zd_nilpotent = (len(factors) == 1)
            
        # Conclusion Q: q is primary iff every zero divisor in R/q is nilpotent
        q_conclusion = (is_primary == all_zd_nilpotent)
        neg_q = not q_conclusion
        
        return [h1, neg_q]
    except Exception:
        return [False, False]

