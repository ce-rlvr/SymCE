def conditions(witness):
    try:
        a, b, n = None, None, None
        if isinstance(witness, (tuple, list)):
            if len(witness) == 2:
                a, b = witness
            elif len(witness) == 3:
                n, a, b = witness
        elif isinstance(witness, dict):
            a = witness.get('x', witness.get('a'))
            b = witness.get('y', witness.get('b'))
            n = witness.get('n', witness.get('R'))
            
        if a is not None and b is not None:
            if n is None:
                if isinstance(a, (int, sympy.Integer)) and isinstance(b, (int, sympy.Integer)):
                    h1_ok = True
                    ideal_is_R = (math.gcd(int(a), int(b)) == 1)
                    eq_holds = (a + b + a * b == 1)
                    neg_q_ok = (ideal_is_R != eq_holds)
                    return [h1_ok, neg_q_ok]
            else:
                if isinstance(n, (int, sympy.Integer)) and isinstance(a, (int, sympy.Integer)) and isinstance(b, (int, sympy.Integer)):
                    if n >= 2:
                        h1_ok = True
                        ideal_is_R = (math.gcd(int(a), math.gcd(int(b), int(n))) == 1)
                        eq_holds = ((a + b + a * b) % n == 1 % n)
                        neg_q_ok = (ideal_is_R != eq_holds)
                        return [h1_ok, neg_q_ok]
                        
        return [False, False]
    except Exception:
        return [False, False]

