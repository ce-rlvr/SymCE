import sympy as sp

# Top-level setup: named object bindings that the witness expression may reference.
# We provide standard variables for polynomial rings.
x, y, z, w = sp.symbols('x y z w')

def is_monomial_poly(p, vars):
    try:
        poly = sp.Poly(p, *vars)
        return len(poly.terms()) == 1 and poly.coeffs()[0] == 1
    except Exception:
        return False

def monom_lcm(m1, m2, vars):
    p1 = sp.Poly(m1, *vars)
    p2 = sp.Poly(m2, *vars)
    exp1 = p1.monoms()[0]
    exp2 = p2.monoms()[0]
    lcm_exp = [max(e1, e2) for e1, e2 in zip(exp1, exp2)]
    res = 1
    for v, e in zip(vars, lcm_exp):
        res *= v**e
    return res

def simplify_monomial_ideal(gens, vars):
    if not gens:
        return []
    polys = [sp.Poly(g, *vars) for g in gens]
    exps = [p.monoms()[0] for p in polys]
    minimal = []
    for i, e1 in enumerate(exps):
        is_multiple = False
        for j, e2 in enumerate(exps):
            if i != j:
                # Check if e2 divides e1
                if all(e2[k] <= e1[k] for k in range(len(vars))):
                    # To handle duplicates, only remove if strictly smaller or same but earlier index
                    if sum(e2) < sum(e1) or (sum(e2) == sum(e1) and j < i):
                        is_multiple = True
                        break
        if not is_multiple:
            minimal.append(gens[i])
    return sorted(minimal, key=str)

def intersect_monomial_ideals(gens1, gens2, vars):
    if not gens1 or not gens2:
        return []
    res = []
    for g1 in gens1:
        for g2 in gens2:
            res.append(monom_lcm(g1, g2, vars))
    return simplify_monomial_ideal(res, vars)

def is_primary_monomial_ideal(gens, vars):
    gens = simplify_monomial_ideal(gens, vars)
    if not gens:
        return True # (0) is primary in a domain
    
    # (1) is not a proper ideal, hence not primary
    for g in gens:
        p = sp.Poly(g, *vars)
        if sum(p.monoms()[0]) == 0:
            return False
            
    appearing_vars = set()
    for g in gens:
        p = sp.Poly(g, *vars)
        exp = p.monoms()[0]
        for i, e in enumerate(exp):
            if e > 0:
                appearing_vars.add(i)
                
    # A monomial ideal is primary iff every variable that appears has a pure power in the ideal
    for i in appearing_vars:
        has_pure_power = False
        for g in gens:
            p = sp.Poly(g, *vars)
            exp = p.monoms()[0]
            if exp[i] > 0 and all(exp[j] == 0 for j in range(len(vars)) if j != i):
                has_pure_power = True
                break
        if not has_pure_power:
            return False
    return True

def is_radical_monomial_ideal(gens, vars):
    gens = simplify_monomial_ideal(gens, vars)
    for g in gens:
        p = sp.Poly(g, *vars)
        exp = p.monoms()[0]
        if any(e > 1 for e in exp):
            return False
    return True

def is_prime_monomial_ideal(gens, vars):
    gens = simplify_monomial_ideal(gens, vars)
    if not gens:
        return True
    for g in gens:
        p = sp.Poly(g, *vars)
        exp = p.monoms()[0]
        # A monomial ideal is prime iff it is generated by a subset of the variables
        if sum(exp) != 1 or any(e > 1 for e in exp):
            return False
    return True

def conditions(witness):
    """
    Checks if the witness is a valid counterexample.
    The witness should be a dictionary with:
      - 'vars': list of sympy symbols used
      - 'I': list of generators for the ideal I
      - 'Q': list of lists, where each sublist is the generators for a primary component Q_i
    """
    try:
        vars = witness['vars']
        I_gens = witness['I']
        Q_gens = witness['Q']
        
        if not Q_gens:
            h1 = False
        else:
            # We restrict to monomial ideals for simplicity and decidability
            all_monomials = True
            for g in I_gens:
                if not is_monomial_poly(g, vars):
                    all_monomials = False
            for q in Q_gens:
                for g in q:
                    if not is_monomial_poly(g, vars):
                        all_monomials = False
                        
            if not all_monomials:
                h1 = False
            else:
                # H_1: R is a commutative ring with identity and Q is a valid primary decomposition of I
                all_primary = all(is_primary_monomial_ideal(q, vars) for q in Q_gens)
                
                int_Q = Q_gens[0]
                for q in Q_gens[1:]:
                    int_Q = intersect_monomial_ideals(int_Q, q, vars)
                    
                int_Q_simp = simplify_monomial_ideal(int_Q, vars)
                I_simp = simplify_monomial_ideal(I_gens, vars)
                
                h1 = all_primary and (int_Q_simp == I_simp)
    except Exception:
        h1 = False

    try:
        if h1:
            # H_2: I is a radical ideal
            h2 = is_radical_monomial_ideal(I_gens, vars)
        else:
            h2 = False
    except Exception:
        h2 = False
        
    try:
        if h1:
            # neg_Q: There exists a primary component Q_i that is NOT a prime ideal
            all_prime = all(is_prime_monomial_ideal(q, vars) for q in Q_gens)
            neg_q = not all_prime
        else:
            neg_q = False
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

