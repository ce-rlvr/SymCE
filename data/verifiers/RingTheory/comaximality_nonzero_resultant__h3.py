import sympy
from sympy import Poly, gcd

x = sympy.Symbol('x')

def conditions(witness):
    try:
        f, g = witness
    except Exception:
        return [False, False, False]
    
    # H_1: Let k be a field
    # Implicitly true as we evaluate over the field of coefficients (e.g. QQ or CC)
    h1 = True
    
    # H_2: Let f and g be polynomials in the polynomial ring over k
    try:
        f = sympy.sympify(f)
        g = sympy.sympify(g)
        if not (f.free_symbols.issubset({x}) and g.free_symbols.issubset({x})):
            h2 = False
        else:
            poly_f = Poly(f, x)
            poly_g = Poly(g, x)
            h2 = True
    except Exception:
        h2 = False
        
    # ¬Q: The principal ideals (f) and (g) are NOT comaximal
    try:
        if not h2:
            neg_q = False
        else:
            d = gcd(f, g)
            poly_d = Poly(d, x)
            # In a polynomial ring over a field, (f) and (g) are comaximal 
            # iff their gcd is a non-zero constant (degree 0).
            is_comaximal = (poly_d.degree() == 0 and not poly_d.is_zero)
            neg_q = not is_comaximal
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

