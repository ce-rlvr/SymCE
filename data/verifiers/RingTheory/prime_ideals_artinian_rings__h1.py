def get_ideal_gen(w):
    if isinstance(w, str):
        try:
            w = sympy.sympify(w)
        except Exception:
            pass
    if isinstance(w, (list, tuple, set)):
        w = list(w)
        if len(w) == 1:
            return w[0]
        elif len(w) == 2 and isinstance(w[0], str):
            return w[1]
        elif len(w) == 2:
            return w[0]
    return w

def is_prime_ideal(w):
    gen = get_ideal_gen(w)
    if gen == 0:
        return True
    if isinstance(gen, (int, sympy.Integer)):
        n = abs(int(gen))
        return isprime(n)
    if isinstance(gen, sympy.Expr):
        try:
            factors = factor_list(gen)
            if len(factors[1]) == 1 and factors[1][0][1] == 1:
                return True
            return False
        except Exception:
            return False
    return False

def is_maximal_ideal(w):
    gen = get_ideal_gen(w)
    if gen == 0:
        return False
    if isinstance(gen, (int, sympy.Integer)):
        n = abs(int(gen))
        return isprime(n)
    if isinstance(gen, sympy.Expr):
        # A principal ideal generated by a single variable/polynomial is generally 
        # not maximal in rings like Z[x] or k[x, y].
        return False
    return False

def conditions(witness):
    try:
        h1 = bool(is_prime_ideal(witness))
    except Exception:
        h1 = False
        
    try:
        neg_q = not bool(is_maximal_ideal(witness))
    except Exception:
        neg_q = False
        
    return [h1, neg_q]

