import sympy

x, y, z = sympy.symbols('x y z')

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, tuple):
            if len(witness) == 3:
                f, g, v = witness
            elif len(witness) == 2:
                f, g = witness
                f_sym = f.free_symbols if hasattr(f, 'free_symbols') else set()
                g_sym = g.free_symbols if hasattr(g, 'free_symbols') else set()
                symbols = f_sym | g_sym
                v = x if x in symbols else (list(symbols)[0] if symbols else x)
            else:
                return [False, False, False]
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H_1: f and g are polynomials
    try:
        sympy.Poly(f, v)
        sympy.Poly(g, v)
        h1 = True
    except Exception:
        h1 = False

    # H_2: Sylvester resultant of f and g is non-zero
    try:
        res = sympy.resultant(f, g, v)
        h2 = bool(sympy.simplify(res) != 0)
    except Exception:
        h2 = False

    # ¬Q: The principal ideals (f) and (g) are not comaximal
    try:
        f_sym = f.free_symbols if hasattr(f, 'free_symbols') else set()
        g_sym = g.free_symbols if hasattr(g, 'free_symbols') else set()
        gens = list(f_sym | g_sym)
        if not gens:
            gens = [v]
            
        domain = 'ZZ'
        try:
            for poly in [f, g]:
                for coeff in sympy.Poly(poly, *gens).coeffs():
                    if not coeff.is_integer:
                        domain = None
                        break
        except Exception:
            domain = None

        if domain == 'ZZ':
            G = sympy.groebner([f, g], *gens, domain='ZZ')
        else:
            G = sympy.groebner([f, g], *gens)
            
        G_list = list(G)
        is_comaximal = (len(G_list) == 1 and G_list[0] in [1, -1])
        neg_q = not is_comaximal
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

