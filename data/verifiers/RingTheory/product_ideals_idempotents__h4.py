# Top-level setup
# The witness is expected to be a tuple: (R, e, f, I, J)
# where R is a ring (e.g., a sympy PolyRing), e and f are elements of R,
# and I and J are ideals of R.

def ideal_eq(I1, I2):
    """Helper function to check if two ideals are equal by checking mutual containment of generators."""
    try:
        for g in I1.gens:
            if g not in I2: 
                return False
        for g in I2.gens:
            if g not in I1: 
                return False
        return True
    except Exception:
        return False

def conditions(witness):
    try:
        R, e, f, I, J = witness
    except Exception:
        return [False] * 5

    # H_1: R is a commutative ring
    try:
        # In the context of SymPy, having an 'ideal' method is a strong proxy 
        # for being a commutative ring (like PolyRing).
        h1 = hasattr(R, 'ideal')
    except Exception:
        h1 = False

    # H_2: e is an idempotent element of R
    try:
        h2 = (e * e == e)
        if hasattr(e, 'ring'):
            h2 = h2 and (e.ring == R)
    except Exception:
        h2 = False

    # H_3: f is an idempotent element of R
    try:
        h3 = (f * f == f)
        if hasattr(f, 'ring'):
            h3 = h3 and (f.ring == R)
    except Exception:
        h3 = False

    # H_4: J is the principal ideal generated by f
    try:
        J_expected = R.ideal(f)
        h4 = ideal_eq(J, J_expected)
    except Exception:
        h4 = False

    # ¬Q: The product ideal IJ is not the principal ideal generated by ef
    try:
        # Compute the product ideal IJ
        IJ_gens = [a * b for a in I.gens for b in J.gens]
        IJ = R.ideal(*IJ_gens)
        
        # Compute the principal ideal generated by ef
        ef_ideal = R.ideal(e * f)
        
        # The conclusion fails if IJ is NOT equal to the ideal generated by ef
        neg_q = not ideal_eq(IJ, ef_ideal)
    except Exception:
        neg_q = False

    return [bool(h1), bool(h2), bool(h3), bool(h4), bool(neg_q)]

