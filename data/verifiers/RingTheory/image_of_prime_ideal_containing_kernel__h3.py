def is_prime_ideal(a, n):
    """
    Checks if the ideal generated by `a` is a prime ideal in Z/nZ.
    If n == 0, it checks in Z.
    """
    a = int(a)
    n = int(n)
    if n == 0:
        # In Z, (a) is prime iff a is 0 or a prime number
        return a == 0 or sympy.isprime(abs(a))
    else:
        # In Z/nZ, (a) is prime iff the quotient ring Z/gcd(a,n)Z is an integral domain,
        # which happens iff gcd(a, n) is a prime number.
        g = sympy.gcd(a, n)
        return sympy.isprime(g)

def conditions(witness):
    try:
        # Parse witness
        if isinstance(witness, dict):
            R_mod = witness.get('R_mod', 0)
            S_mod = witness.get('S_mod', 1)
            P_gen = witness.get('P_gen', 0)
        else:
            R_mod, S_mod, P_gen = witness
            
        R_mod = int(R_mod)
        S_mod = int(S_mod)
        P_gen = int(P_gen)
        
        # H1: R and S are commutative rings with identity, and P is a prime ideal of R.
        # Z/nZ is a commutative ring with identity as long as n != 1.
        h1 = (abs(R_mod) != 1) and (abs(S_mod) != 1) and is_prime_ideal(P_gen, R_mod)
        
        # H2: f: R -> S is a surjective ring homomorphism.
        # The natural projection x -> x mod S_mod is well-defined and surjective iff S_mod divides R_mod.
        if S_mod == 0:
            h2 = (R_mod == 0)
        elif R_mod == 0:
            h2 = True
        else:
            h2 = (R_mod % S_mod == 0)
            
        # neg_Q: The image f(P) is NOT a prime ideal of S.
        # f(P) is the ideal generated by P_gen in Z/S_mod Z.
        neg_q = not is_prime_ideal(P_gen, S_mod)
        
        return [bool(h1), bool(h2), bool(neg_q)]
    except Exception:
        return [False, False, False]

