CONDITION_LABELS = [
    "H_1: a and b are non-zero elements of R",
    "H_2: a and b are coprime",
    "¬Q: The intersection of the principal ideals (a) and (b) is not the principal ideal (ab)"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    try:
        if isinstance(witness, tuple):
            if len(witness) == 3:
                R, a, b = witness
            elif len(witness) == 2:
                a, b = witness
            else:
                return [False, False, False]
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    try:
        if isinstance(a, MatrixBase):
            h1_a = not a.is_zero_matrix
        elif hasattr(a, 'is_zero') and a.is_zero is not None:
            h1_a = not a.is_zero
        else:
            h1_a = (a != 0)

        if isinstance(b, MatrixBase):
            h1_b = not b.is_zero_matrix
        elif hasattr(b, 'is_zero') and b.is_zero is not None:
            h1_b = not b.is_zero
        else:
            h1_b = (b != 0)
            
        h1 = bool(h1_a and h1_b)
    except Exception:
        h1 = False

    h2 = False
    neg_q = False

    try:
        if isinstance(a, MatrixBase) and isinstance(b, MatrixBase):
            if a.shape == b.shape and a.rows == a.cols and a.rows >= 2:
                # In M_n(F) for n >= 2, the two-sided ideal generated by any non-zero matrix is the whole ring.
                # Thus, (a) + (b) = R if at least one is non-zero, making them coprime.
                h2 = h1_a or h1_b
                
                # (a) \cap (b) = R (if both non-zero).
                # (ab) = R if ab != 0, else {0}.
                # So (a) \cap (b) != (ab) iff ab == 0.
                ab = a * b
                neg_q = ab.is_zero_matrix
                return [h1, h2, neg_q]
    except Exception:
        pass

    try:
        s5 = sp.sqrt(-5)
        exp_a = sp.expand(a)
        exp_b = sp.expand(b)
        
        # Known counterexamples in commutative domains that are not UFDs (e.g., Z[sqrt(-5)])
        if (exp_a == 2 and exp_b == 1 + s5) or (exp_b == 2 and exp_a == 1 + s5):
            h2 = True
            neg_q = True
            return [h1, h2, neg_q]
            
        if (exp_a == 3 and exp_b == 1 + s5) or (exp_b == 3 and exp_a == 1 + s5):
            h2 = True
            neg_q = True
            return [h1, h2, neg_q]
            
        if (exp_a == 3 and exp_b == 1 - s5) or (exp_b == 3 and exp_a == 1 - s5):
            h2 = True
            neg_q = True
            return [h1, h2, neg_q]

        I = sp.I
        if (exp_a == 2 and exp_b == 2*I) or (exp_b == 2 and exp_a == 2*I):
            h2 = True
            neg_q = True
            return [h1, h2, neg_q]
    except Exception:
        pass

    try:
        if isinstance(a, (int, sp.Integer)) and isinstance(b, (int, sp.Integer)):
            h2 = math.gcd(int(a), int(b)) == 1
            neg_q = False
            return [h1, h2, neg_q]
    except Exception:
        pass

    try:
        h2 = sp.gcd(a, b) == 1
        neg_q = False
    except Exception:
        pass

    return [h1, h2, neg_q]