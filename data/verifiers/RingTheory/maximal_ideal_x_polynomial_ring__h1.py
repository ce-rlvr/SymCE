def conditions(witness) -> list[bool]:
    try:
        h1_ok = True
    except Exception:
        h1_ok = False

    try:
        is_field = False
        is_simple = False
        
        if hasattr(witness, 'is_Field'):
            is_field = bool(witness.is_Field)
        elif hasattr(witness, 'is_field'):
            is_field = bool(witness.is_field)
            
        if hasattr(witness, 'is_Simple'):
            is_simple = bool(witness.is_Simple)
        elif hasattr(witness, 'is_simple'):
            is_simple = bool(witness.is_simple)
            
        if isinstance(witness, str):
            w = witness.lower()
            if 'matrix' in w or 'm2' in w or 'm_2' in w or 'weyl' in w:
                is_simple = True
                is_field = False
            elif 'field' in w:
                is_field = True
                is_simple = True
                
        if isinstance(witness, tuple) and len(witness) == 2:
            domain, n = witness
            if hasattr(domain, 'is_Field') and domain.is_Field and isinstance(n, int) and n > 1:
                is_field = False
                is_simple = True
                
        neg_q = (is_simple != is_field)
    except Exception:
        neg_q = False

    return [h1_ok, neg_q]

