import sympy
from sympy import Symbol, Poly, sympify, Expr
from sympy.abc import x, y, z, u, v, w
from math import gcd
from functools import reduce

CONDITION_LABELS = [
    "H_1: R is a commutative ring",
    "H_2: X and Y are disjoint sets of indeterminates over R",
    "H_3: f is a polynomial over R with variables in X",
    "H_4: The constant term of f is zero",
    "¬Q: The content ideal of f+g does not satisfy c(f+g) = c(f) + c(g)"
]

N_HYP = 4
NEG_Q_INDEX = 4

def conditions(witness):
    """
    Given a witness, checks if it satisfies the remaining hypotheses and falsifies the conclusion.
    The witness can be a tuple (f, g) or (f, g, X, Y), or a dictionary with these keys.
    """
    f = g = None
    X = Y = set()
    
    try:
        if isinstance(witness, tuple):
            if len(witness) == 2:
                f, g = witness
                f = sympify(f)
                g = sympify(g)
                X = f.free_symbols if hasattr(f, 'free_symbols') else set()
                Y = set()
            elif len(witness) == 4:
                f, g, X, Y = witness
                f = sympify(f)
                g = sympify(g)
                X = set(X)
                Y = set(Y)
            else:
                return [False] * 5
        elif isinstance(witness, dict):
            f = sympify(witness.get('f'))
            g = sympify(witness.get('g'))
            X = set(witness.get('X', f.free_symbols if hasattr(f, 'free_symbols') else set()))
            Y = set(witness.get('Y', set()))
        else:
            return [False] * 5
    except Exception:
        return [False] * 5

    # H1: R is a commutative ring
    # We evaluate over the integers Z, which is a commutative ring.
    h1 = True

    # H2: X and Y are disjoint sets of indeterminates over R
    try:
        h2 = X.isdisjoint(Y) and all(isinstance(var, Symbol) for var in X | Y)
    except Exception:
        h2 = False

    # H3: f is a polynomial in R[X]
    try:
        if isinstance(f, Expr) and f.free_symbols.issubset(X):
            p_f = Poly(f, *X) if X else Poly(f)
            h3 = all(c.is_Integer for c in p_f.coeffs())
        else:
            h3 = False
    except Exception:
        h3 = False

    # H4: The constant term of f is zero
    try:
        if h3:
            const_term = f.subs({var: 0 for var in f.free_symbols})
            h4 = (const_term == 0)
        else:
            h4 = False
    except Exception:
        h4 = False

    # ¬Q: The content ideal of f+g does not satisfy c(f+g) = c(f) + c(g)
    try:
        if not isinstance(g, Expr):
            neg_q = False
        else:
            p_g = Poly(g, *g.free_symbols) if g.free_symbols else Poly(g)
            if not all(c.is_Integer for c in p_g.coeffs()):
                neg_q = False
            else:
                fg = f + g
                p_fg = Poly(fg, *fg.free_symbols) if fg.free_symbols else Poly(fg)
                
                def get_content(poly_obj):
                    coeffs = poly_obj.coeffs()
                    if not coeffs:
                        return 0
                    return abs(reduce(gcd, [int(c) for c in coeffs]))
                
                c_f = get_content(p_f) if h3 else get_content(Poly(f, *f.free_symbols) if f.free_symbols else Poly(f))
                c_g = get_content(p_g)
                c_fg = get_content(p_fg)
                
                # In Z, the sum of ideals <c_f> + <c_g> is generated by gcd(c_f, c_g)
                sum_ideal_gen = gcd(c_f, c_g)
                
                neg_q = (c_fg != sum_ideal_gen)
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]