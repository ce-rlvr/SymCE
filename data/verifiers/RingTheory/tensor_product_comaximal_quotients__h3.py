CONDITION_LABELS = [
    "H_1: R is a commutative ring",
    "H_2: I and J are ideals of R",
    "¬Q: R/I \\otimes_R R/J is not isomorphic to the zero module"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness) -> list[bool]:
    h1 = False
    h2 = False
    neg_q = False
    
    try:
        # Parse witness
        if isinstance(witness, tuple):
            if len(witness) == 3:
                R, I, J = witness
            elif len(witness) == 2:
                I, J = witness
            else:
                return [False, False, False]
        else:
            return [False, False, False]
            
        # H1: R is a commutative ring
        # We implicitly evaluate the ideals in Z or Q[x], which are commutative rings.
        h1 = True
        
        def get_gen(ideal):
            if isinstance(ideal, (list, tuple, set)):
                ideal_list = list(ideal)
                if len(ideal_list) == 0:
                    return Integer(0)
                g = sympify(ideal_list[0])
                for elem in ideal_list[1:]:
                    g = gcd(g, sympify(elem))
                return g
            else:
                return sympify(ideal)
                
        genI = get_gen(I)
        genJ = get_gen(J)
        
        # H2: I and J are ideals of R
        # Any element or list of elements generates an ideal in Z or Q[x].
        h2 = True
        
        # ¬Q: R/I \otimes_R R/J is not isomorphic to the zero module
        # R/I \otimes R/J is isomorphic to R/(I+J).
        # It is the zero module iff I+J = R, which means the generator of I+J is a unit.
        # I+J is generated by gcd(genI, genJ).
        g = gcd(genI, genJ)
        
        if g.is_Integer:
            # In Z, the only units are 1 and -1
            neg_q = abs(int(g)) != 1
        elif g.is_Rational:
            # In Q, any non-zero element is a unit
            neg_q = g == 0
        else:
            # In Q[x], the units are the non-zero constants
            if g == 0:
                neg_q = True
            else:
                neg_q = len(g.free_symbols) > 0
                
    except Exception:
        pass
        
    return [h1, h2, neg_q]