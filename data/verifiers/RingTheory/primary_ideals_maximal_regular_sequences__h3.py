import sympy
from sympy.abc import x, y, z, t, u, v, w
from itertools import combinations

def krull_dimension(I_gens, vars):
    """
    Computes the Krull dimension of the quotient ring Q[vars] / I_gens.
    Since we are working with local rings at the origin, this is equivalent
    to the dimension of the affine variety at the origin.
    """
    if not I_gens:
        return len(vars)
    
    I_gens = [p for p in I_gens if p != 0]
    if not I_gens:
        return len(vars)
        
    for d in range(len(vars), -1, -1):
        for subset in combinations(vars, d):
            other_vars = [v for v in vars if v not in subset]
            order = other_vars + list(subset)
            try:
                gb = sympy.groebner(I_gens, *order, order='lex')
            except Exception:
                raise
            
            subset_set = set(subset)
            intersection_is_zero = True
            for p in gb:
                if p == 0: 
                    continue
                # If all free symbols of p are in the subset, then p is in the elimination ideal
                if p.free_symbols.issubset(subset_set):
                    intersection_is_zero = False
                    break
            
            if intersection_is_zero:
                return d
    return -1

def conditions(witness):
    """
    witness format: (vars, I_gens, d, seq)
    - vars: list of sympy symbols (e.g., [x, y])
    - I_gens: list of polynomials in vars generating the ideal I.
              The local ring is R = (Q[vars]/I)_{(vars)}.
    - d: integer, the Krull dimension of R.
    - seq: list of d polynomials in vars.
    """
    try:
        vars, I_gens, d, seq = witness
    except Exception:
        return [False, False, False]
        
    # H_1: R is a commutative Noetherian local ring with maximal ideal M
    try:
        h1 = True
        if not isinstance(vars, list) or len(vars) == 0:
            h1 = False
        else:
            var_set = set(vars)
            for v in vars:
                if not hasattr(v, 'is_Symbol') or not v.is_Symbol:
                    h1 = False
            
            if h1:
                I_gens_sym = []
                for p in I_gens:
                    p_sym = sympy.sympify(p)
                    if not p_sym.free_symbols.issubset(var_set):
                        h1 = False
                        break
                    # To ensure R is a local ring at the origin, generators must evaluate to 0 at origin
                    if p_sym.subs({v: 0 for v in vars}) != 0:
                        h1 = False
                        break
                    I_gens_sym.append(p_sym)
                I_gens = I_gens_sym
    except Exception:
        h1 = False

    # H_2: d is the Krull dimension of R
    try:
        if h1:
            dim = krull_dimension(I_gens, vars)
            h2 = (d == dim)
        else:
            h2 = False
    except Exception:
        h2 = False

    # ¬Q: The ideal generated by the sequence x_1, ..., x_d is NOT M-primary
    try:
        if h1 and isinstance(seq, list) and len(seq) == d:
            seq_sym = []
            seq_ok = True
            for p in seq:
                p_sym = sympy.sympify(p)
                if not p_sym.free_symbols.issubset(var_set):
                    seq_ok = False
                    break
                seq_sym.append(p_sym)
            
            if seq_ok:
                # The ideal J generated by seq is M-primary in R iff the dimension of 
                # the ideal generated by I_gens + seq in the polynomial ring is exactly 0.
                # If dimension > 0, it's not M-primary.
                # If dimension == -1, it generates the whole ring (not a proper ideal, so not M-primary).
                dim_J = krull_dimension(I_gens + seq_sym, vars)
                neg_q = (dim_J != 0)
            else:
                neg_q = False
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

