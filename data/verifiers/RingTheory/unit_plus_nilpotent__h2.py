def conditions(witness):
    h1 = False
    h2 = False
    neg_q = False
    
    try:
        if isinstance(witness, tuple):
            if len(witness) == 3:
                n, x, u = witness
                try:
                    n = int(n)
                    x = int(x)
                    u = int(u)
                    
                    # H1: Z/nZ is a commutative ring (for n >= 2)
                    if n >= 2:
                        h1 = True
                        
                    # H2: x is nilpotent mod n iff every prime factor of n divides x
                    factors = factorint(n)
                    if all(x % p == 0 for p in factors.keys()):
                        h2 = True
                        
                    # neg_Q: u + x is not a unit mod n
                    if math.gcd((u + x) % n, n) != 1:
                        neg_q = True
                except (ValueError, TypeError):
                    pass

            elif len(witness) == 2:
                x, u = witness
                
                # Case: Matrices over a commutative ring
                if hasattr(x, 'is_Matrix') and x.is_Matrix and hasattr(u, 'is_Matrix') and u.is_Matrix:
                    if x.shape == u.shape and x.shape[0] == x.shape[1]:
                        # H1: The subring generated by x and u is commutative if they commute
                        if x * u == u * x:
                            h1 = True
                        
                        # H2: x is nilpotent
                        k = x.shape[0]
                        if (x**k).is_zero_matrix:
                            h2 = True
                            
                        # neg_Q: u + x is not a unit
                        det = (u + x).det()
                        if det == 0:
                            neg_q = True
                        else:
                            try:
                                def is_int(v):
                                    return getattr(v, 'is_integer', False) or isinstance(v, int)
                                # Over Z, a matrix is a unit iff its determinant is 1 or -1
                                if all(is_int(val) for val in (u + x)):
                                    if abs(det) != 1:
                                        neg_q = True
                            except Exception:
                                pass

                # Case: Integers (Ring Z)
                else:
                    try:
                        x_int = int(x)
                        u_int = int(u)
                        if x_int == x and u_int == u:
                            # H1: Z is a commutative ring
                            h1 = True
                            # H2: 0 is the only nilpotent element in Z
                            if x_int == 0:
                                h2 = True
                            # neg_Q: u + x is not a unit in Z (units are 1 and -1)
                            if abs(u_int + x_int) != 1:
                                neg_q = True
                    except (ValueError, TypeError):
                        pass
    except Exception:
        pass

    return [h1, h2, neg_q]

