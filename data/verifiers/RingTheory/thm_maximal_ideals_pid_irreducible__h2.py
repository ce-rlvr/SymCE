def is_irreducible(R, p):
    try:
        zero = getattr(R, 'zero', 0)
        if p == zero:
            return False
        if getattr(R, 'is_Field', False) or R == QQ:
            return False
        if R == ZZ:
            from sympy import isprime
            return isprime(abs(int(p)))
        if hasattr(R, 'domain') and getattr(R.domain, 'is_Field', False):
            poly = R(p)
            return poly.is_irreducible
    except Exception:
        pass
    return False

def conditions(witness):
    try:
        # The witness can be a tuple (R, p) or just the element p (defaulting R to QQ)
        if isinstance(witness, tuple) and len(witness) == 2:
            R, p = witness
        else:
            R = QQ
            p = witness
    except Exception:
        return [False, False]
    
    # H_1: R is a principal ideal domain
    try:
        if R in (ZZ, QQ):
            h1 = True
        elif hasattr(R, 'is_PID'):
            h1 = bool(R.is_PID)
        else:
            h1 = False
    except Exception:
        h1 = False
        
    # ¬Q: The equivalence between ideal(p) being maximal and p being irreducible fails
    try:
        zero = getattr(R, 'zero', 0)
        
        # Determine if the principal ideal generated by p is maximal in R
        if getattr(R, 'is_Field', False) or R == QQ:
            # In a field, the only ideals are {0} and the field itself.
            # {0} is the only maximal ideal.
            maximal = (p == zero)
        elif R == ZZ:
            # In ZZ, (p) is maximal iff |p| is prime.
            from sympy import isprime
            maximal = isprime(abs(int(p)))
        elif hasattr(R, 'is_PID') and R.is_PID:
            # In a PID that is not a field, non-zero prime ideals are maximal.
            maximal = (p != zero) and is_irreducible(R, p)
        else:
            maximal = False
            
        # Determine if p is an irreducible element of R
        irreducible = is_irreducible(R, p)
        
        # The conclusion is that maximal == irreducible. We want the negation.
        neg_q = bool(maximal != irreducible)
    except Exception:
        neg_q = False
        
    return [h1, neg_q]

