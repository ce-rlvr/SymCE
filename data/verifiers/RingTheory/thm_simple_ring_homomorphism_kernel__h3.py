class ZRing:
    """A simple implementation of the ring of integers modulo n."""
    def __init__(self, n):
        self.n = n
        self.elements = list(range(n))
        self.zero = 0
        
    def add(self, a, b):
        return (a + b) % self.n
        
    def mul(self, a, b):
        return (a * b) % self.n
        
    def __str__(self):
        return f"Z_{self.n}"
        
    def __repr__(self):
        return f"ZRing({self.n})"

