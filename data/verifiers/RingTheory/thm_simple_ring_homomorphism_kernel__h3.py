def check_ring(R):
    """Verifies that R satisfies the axioms of a ring."""
    try:
        elements = R.elements
        zero = R.zero
        if zero not in elements: 
            return False
        
        # Closure
        for a in elements:
            for b in elements:
                if R.add(a, b) not in elements: return False
                if R.mul(a, b) not in elements: return False
                
        # Commutativity of addition
        for a in elements:
            for b in elements:
                if R.add(a, b) != R.add(b, a): return False
                
        # Associativity and distributivity
        for a in elements:
            for b in elements:
                for c in elements:
                    if R.add(R.add(a, b), c) != R.add(a, R.add(b, c)): return False
                    if R.mul(R.mul(a, b), c) != R.mul(a, R.mul(b, c)): return False
                    if R.mul(a, R.add(b, c)) != R.add(R.mul(a, b), R.mul(a, c)): return False
                    if R.mul(R.add(a, b), c) != R.add(R.mul(a, c), R.mul(b, c)): return False
                    
        # Additive identity
        for a in elements:
            if R.add(a, zero) != a: return False
            
        # Additive inverses
        for a in elements:
            has_inv = False
            for b in elements:
                if R.add(a, b) == zero:
                    has_inv = True
                    break
            if not has_inv: return False
            
        return True
    except Exception:
        return False

def check_simple_ring(R):
    """Verifies that R is a simple ring (no non-trivial two-sided ideals)."""
    try:
        elements = R.elements
        zero = R.zero
        if len(elements) <= 1:
            return False
            
        for x in elements:
            if x == zero: 
                continue
            
            # Compute the two-sided ideal generated by x
            closure = set([x])
            while True:
                new_closure = set(closure)
                # Closure under addition
                for a in closure:
                    for b in closure:
                        new_closure.add(R.add(a, b))
                # Closure under left and right multiplication by R
                for a in closure:
                    for r in elements:
                        new_closure.add(R.mul(r, a))
                        new_closure.add(R.mul(a, r))
                        
                if len(new_closure) == len(closure):
                    break
                closure = new_closure
                
            # If the ideal generated by any non-zero element is not the whole ring, it's not simple
            if len(closure) < len(elements):
                return False
                
        return True
    except Exception:
        return False

def conditions(witness):
    """
    Checks if the witness satisfies the remaining hypotheses and falsifies the conclusion.
    Witness should be a tuple: (R, S, f)
    where R and S are ring objects (like Z2) and f is a dictionary or callable mapping R to S.
    """
    try:
        if len(witness) != 3:
            return [False, False, False]
        R, S, f = witness
    except Exception:
        return [False, False, False]
    
    # H_1: R and S are rings
    try:
        h1 = check_ring(R) and check_ring(S)
    except Exception:
        h1 = False
        
    # H_2: R is a simple ring
    try:
        h2 = check_simple_ring(R)
    except Exception:
        h2 = False
        
    # ¬Q: The conclusion fails (f is neither injective nor the zero homomorphism)
    try:
        if isinstance(f, dict):
            f_val = lambda x: f[x]
        else:
            f_val = f
            
        is_valid_func = True
        for x in R.elements:
            if f_val(x) not in S.elements:
                is_valid_func = False
                break
                
        if is_valid_func:
            kernel = set(x for x in R.elements if f_val(x) == S.zero)
            mapped_values = set(f_val(x) for x in R.elements)
            
            is_injective = (len(mapped_values) == len(R.elements))
            is_zero_hom = (kernel == set(R.elements))
            
            conclusion = is_injective or is_zero_hom
            neg_q = not conclusion
        else:
            neg_q = False
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

