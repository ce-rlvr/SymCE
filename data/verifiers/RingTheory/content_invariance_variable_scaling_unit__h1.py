CONDITION_LABELS = [
    "H_1: f(x) is a non-zero polynomial",
    "H_2: u is a unit in R",
    "not Q: The content of f(ux) is not associate to the content of f(x) in R"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    try:
        if len(witness) != 2:
            return [False, False, False]
        f, u = witness
        
        # Case 1: Witness is a list of matrix coefficients (non-commutative ring)
        if isinstance(f, list) and len(f) > 0 and hasattr(f[0], 'is_Matrix') and f[0].is_Matrix:
            H1 = any(not c.is_zero_matrix for c in f)
            if hasattr(u, 'is_Matrix') and u.is_Matrix:
                H2 = u.det() != 0
            else:
                H2 = (u != 0)
                
            A = sp.Matrix.vstack(*f)
            f_u = [f[i] * (u**i) for i in range(len(f))]
            B = sp.Matrix.vstack(*f_u)
            
            # In matrix rings, the left ideal generated by coefficients corresponds to the row space.
            # Two left ideals are equal iff their row spaces are equal.
            neg_Q = A.rref()[0] != B.rref()[0]
            return [bool(H1), bool(H2), bool(neg_Q)]
            
        # Case 2: Witness is a matrix expression (non-commutative ring)
        if hasattr(f, 'is_Matrix') and f.is_Matrix:
            syms = list(f.free_symbols)
            var = syms[0] if syms else sp.Symbol('x')
            
            max_deg = -1
            for i in range(f.rows):
                for j in range(f.cols):
                    try:
                        p = sp.Poly(f[i, j], var)
                        deg = p.degree()
                        if deg != -sp.oo and deg > max_deg:
                            max_deg = int(deg)
                    except Exception:
                        pass
            if max_deg == -1:
                max_deg = 0
                
            coeffs = []
            for d in range(max_deg + 1):
                C = sp.zeros(f.rows, f.cols)
                for i in range(f.rows):
                    for j in range(f.cols):
                        try:
                            C[i, j] = sp.Poly(f[i, j], var).coeff_monomial(var**d)
                        except Exception:
                            C[i, j] = 0
                coeffs.append(C)
                
            H1 = any(not c.is_zero_matrix for c in coeffs)
            if hasattr(u, 'is_Matrix') and u.is_Matrix:
                H2 = u.det() != 0
            else:
                H2 = (u != 0)
                
            A = sp.Matrix.vstack(*coeffs)
            f_u = [coeffs[i] * (u**i) for i in range(len(coeffs))]
            B = sp.Matrix.vstack(*f_u)
            
            neg_Q = A.rref()[0] != B.rref()[0]
            return [bool(H1), bool(H2), bool(neg_Q)]
            
        # Case 3: Witness is a standard commutative polynomial expression
        if isinstance(f, sp.Poly):
            expr = f.as_expr()
            var = f.gen
        else:
            expr = sp.sympify(f)
            syms = list(expr.free_symbols) if hasattr(expr, 'free_symbols') else []
            var = syms[0] if syms else sp.Symbol('x')
            
        u_sym = sp.sympify(u)
        
        P_f = sp.Poly(expr, var)
        try:
            P_u = sp.Poly(u_sym, var)
            domain = P_f.domain.unify(P_u.domain)
        except Exception:
            domain = P_f.domain
            
        P = sp.Poly(expr, var, domain=domain)
        H1 = not P.is_zero
        
        try:
            u_val = domain.from_sympy(u_sym)
            H2 = domain.is_unit(u_val)
        except Exception:
            H2 = False
            
        c1 = P.content()
        P_u_expr = sp.Poly(expr.subs(var, u_sym * var), var, domain=domain)
        c2 = P_u_expr.content()
        
        try:
            # Check if c1 and c2 are associate in the domain
            q1 = domain.exquo(c1, c2)
            q2 = domain.exquo(c2, c1)
            neg_Q = False
        except Exception:
            neg_Q = True
            
        return [bool(H1), bool(H2), bool(neg_Q)]
        
    except Exception:
        return [False, False, False]