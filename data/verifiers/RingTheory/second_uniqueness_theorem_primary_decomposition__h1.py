def conditions(witness):
    """
    Checks the hypotheses and negated conclusion for the false conjecture.
    The witness is expected to be a dictionary representing a finite ring and the ideals:
    {
        'n': int,
        'add': list[list[int]],
        'mul': list[list[int]],
        'I': list[int],
        'decomps': list[list[list[int]]],
        'P_i': list[int]
    }
    """
    try:
        n_ring = witness['n']
        add_table = witness['add']
        mul_table = witness['mul']
        I_target = set(witness['I'])
        decomps = witness['decomps']
        P_i_target = set(witness['P_i'])
    except Exception:
        return [False, False, False, False]

    def add(a, b): return add_table[a][b]
    def mul(a, b): return mul_table[a][b]

    try:
        # Verify ring axioms
        for a in range(n_ring):
            if add(a, 0) != a or add(0, a) != a: return [False, False, False, False]
            has_inv = False
            for b in range(n_ring):
                if add(a, b) == 0: has_inv = True
                if add(a, b) != add(b, a): return [False, False, False, False]
                for c in range(n_ring):
                    if add(a, add(b, c)) != add(add(a, b), c): return [False, False, False, False]
                    if mul(a, mul(b, c)) != mul(mul(a, b), c): return [False, False, False, False]
                    if mul(a, add(b, c)) != add(mul(a, b), mul(a, c)): return [False, False, False, False]
                    if mul(add(a, b), c) != add(mul(a, c), mul(b, c)): return [False, False, False, False]
            if not has_inv: return [False, False, False, False]
    except Exception:
        return [False, False, False, False]

    def is_ideal(S):
        if 0 not in S: return False
        for a in S:
            for b in S:
                if add(a, b) not in S: return False
        for a in S:
            for r in range(n_ring):
                if mul(r, a) not in S: return False
                if mul(a, r) not in S: return False
        return True

    try:
        # Precompute the ideal generated by each element
        gen_ideals = []
        for i in range(n_ring):
            I_gen = {i}
            while True:
                size = len(I_gen)
                I_gen.update({add(u, v) for u in I_gen for v in I_gen})
                I_gen.update({mul(r, u) for u in I_gen for r in range(n_ring)})
                I_gen.update({mul(u, r) for u in I_gen for r in range(n_ring)})
                if len(I_gen) == size:
                    break
            gen_ideals.append(frozenset(I_gen))
        
        # Find all ideals in the ring
        ideals = set(gen_ideals)
        while True:
            size = len(ideals)
            new_ideals = set(ideals)
            for I1 in ideals:
                for I2 in gen_ideals:
                    sum_ideal = frozenset({add(u, v) for u in I1 for v in I2})
                    new_ideals.add(sum_ideal)
            ideals = new_ideals
            if len(ideals) == size:
                break
        all_ideals = [set(I) for I in ideals]
    except Exception:
        return [False, False, False, False]

    def is_prime(S):
        if len(S) == n_ring: return False
        for a in range(n_ring):
            if a in S: continue
            for b in range(n_ring):
                if b in S: continue
                I_a = gen_ideals[a]
                I_b = gen_ideals[b]
                contained = True
                for u in I_a:
                    for v in I_b:
                        if mul(u, v) not in S:
                            contained = False
                            break
                    if not contained: break
                if contained:
                    return False
        return True

    try:
        primes = [I for I in all_ideals if is_prime(I)]
    except Exception:
        return [False, False, False, False]

    def radical(S):
        containing = [P for P in primes if S.issubset(P)]
        if not containing:
            return set(range(n_ring))
        res = set(containing[0])
        for P in containing[1:]:
            res = res.intersection(P)
        return res

    def is_primary(S):
        if len(S) == n_ring: return False
        rad = radical(S)
        for a in range(n_ring):
            if a in S: continue
            for b in range(n_ring):
                if b in rad: continue
                I_a = gen_ideals[a]
                I_b = gen_ideals[b]
                contained = True
                for u in I_a:
                    for v in I_b:
                        if mul(u, v) not in S:
                            contained = False
                            break
                    if not contained: break
                if contained:
                    return False
        return True

    # H1: I is a proper ideal of R
    try:
        h1 = is_ideal(I_target) and len(I_target) < n_ring
    except Exception:
        h1 = False

    # H2: I = Q_1 \cap Q_2 \cap \dots \cap Q_n is a minimal primary decomposition of I
    try:
        h2 = True
        if len(decomps) < 2:
            h2 = False
        
        for decomp in decomps:
            decomp_sets = [set(Q) for Q in decomp]
            
            # Check intersection equals I
            intersect = set(range(n_ring))
            for Q in decomp_sets:
                intersect = intersect.intersection(Q)
            if intersect != I_target:
                h2 = False
                break
            
            # Check each Q is primary
            for Q in decomp_sets:
                if not is_primary(Q):
                    h2 = False
                    break
            if not h2: break
            
            # Check radicals are distinct
            rads = [frozenset(radical(Q)) for Q in decomp_sets]
            if len(set(rads)) != len(rads):
                h2 = False
                break
            
            # Check minimality (no redundant components)
            for j in range(len(decomp_sets)):
                intersect_other = set(range(n_ring))
                for k in range(len(decomp_sets)):
                    if k != j:
                        intersect_other = intersect_other.intersection(decomp_sets[k])
                if intersect_other.issubset(decomp_sets[j]):
                    h2 = False
                    break
            if not h2: break
    except Exception:
        h2 = False

    # H3: P_i is an isolated (minimal) prime ideal associated to I, where P_i is the radical of Q_i
    try:
        h3 = True
        if not is_prime(P_i_target):
            h3 = False
        
        for decomp in decomps:
            decomp_sets = [set(Q) for Q in decomp]
            rads = [radical(Q) for Q in decomp_sets]
            if P_i_target not in rads:
                h3 = False
                break
            # Check minimality among associated primes
            for R_prime in rads:
                if R_prime != P_i_target and R_prime.issubset(P_i_target):
                    h3 = False
                    break
            if not h3: break
    except Exception:
        h3 = False

    # neg_Q: The primary component Q_i is not uniquely determined
    try:
        neg_q = False
        if h2 and h3:
            Q_i_list = []
            for decomp in decomps:
                decomp_sets = [set(Q) for Q in decomp]
                rads = [radical(Q) for Q in decomp_sets]
                if P_i_target in rads:
                    idx = rads.index(P_i_target)
                    Q_i_list.append(decomp_sets[idx])
            
            # Check if there are at least two different Q_i for the same P_i
            for i in range(len(Q_i_list)):
                for j in range(i + 1, len(Q_i_list)):
                    if Q_i_list[i] != Q_i_list[j]:
                        neg_q = True
                        break
                if neg_q:
                    break
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

