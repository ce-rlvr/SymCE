import sympy
from sympy import ZZ, QQ
from sympy.abc import x, y, z

# Top-level setup: named object bindings that the witness expression may reference.
Z_sqrt_m5 = "Z[sqrt(-5)]"
Z_sqrt_m3 = "Z[sqrt(-3)]"
k_x2_x3 = "k[x^2, x^3]"

def check_known_counterexample(R):
    """Helper to identify known string representations of counterexample rings."""
    R_str = str(R).replace(" ", "")
    known_non_ufd_accp = [
        "Z[sqrt(-5)]",
        "Z[sqrt(-3)]",
        "k[x^2,x^3]",
        "Z[x,y,z,w]/(x*y-z*w)",
        "Z[sqrt(-5)][x]",
        "Z[sqrt(-3)][x]"
    ]
    return R_str in known_non_ufd_accp

def conditions(witness) -> list[bool]:
    # Parse witness
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            R, S_gens = witness
        else:
            R = witness
            S_gens = []
    except Exception:
        return [False, False, False]

    # H_1: R is an integral domain satisfying ACCP
    try:
        h1 = False
        if check_known_counterexample(R):
            h1 = True
        elif R in [ZZ, QQ]:
            h1 = True
        elif hasattr(R, 'is_IntegralDomain'):
            val = R.is_IntegralDomain
            if callable(val):
                val = val()
            if val:
                h1 = True
    except Exception:
        h1 = False

    # H_2: S is a multiplicatively closed subset of R generated by a set of prime elements
    try:
        h2 = True
        R_str = str(R).replace(" ", "")
        for p in S_gens:
            is_p_prime = False
            if R == ZZ:
                if sympy.isprime(abs(int(p))):
                    is_p_prime = True
            elif R_str == "Z[sqrt(-5)]":
                if str(p) == "11":
                    is_p_prime = True
            elif R_str == "Z[sqrt(-5)][x]":
                if str(p) == "x":
                    is_p_prime = True
            elif hasattr(R, 'is_prime'):
                if R.is_prime(p):
                    is_p_prime = True
            
            if not is_p_prime:
                h2 = False
                break
    except Exception:
        h2 = False

    # neg_Q: R is NOT a Unique Factorization Domain
    try:
        neg_q = False
        if check_known_counterexample(R):
            neg_q = True
        elif R in [ZZ, QQ]:
            neg_q = False
        elif hasattr(R, 'is_UFD'):
            val = R.is_UFD
            if callable(val):
                val = val()
            neg_q = not val
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

