import math
import sympy

# Top-level setup
Z = sympy.S.Integers

def conditions(witness) -> list[bool]:
    H_1 = False
    H_2 = False
    neg_Q = False
    
    try:
        a = None
        p = None
        M = None
        
        # Parse the witness flexibly
        if isinstance(witness, dict):
            a = witness.get('a')
            p = witness.get('p')
            M = witness.get('M', a)
        elif isinstance(witness, (tuple, list)):
            if len(witness) == 2:
                a, p = witness
                M = a
            elif len(witness) == 3:
                M, a, p = witness
            elif len(witness) == 4:
                _, M, a, p = witness
            elif len(witness) > 4:
                a, p = witness[-2], witness[-1]
                M = a
        elif hasattr(witness, 'a') and hasattr(witness, 'p'):
            a = witness.a
            p = witness.p
            M = getattr(witness, 'M', a)
            
        if a is None or p is None:
            return [False, False, False]
            
        a = int(a)
        p = int(p)
        
        # H_1: R is a principal ideal domain
        # We evaluate the witness in the context of R = Z, which is a PID.
        H_1 = True
        
        # H_2: M is a finitely generated torsion R-module whose annihilator is generated by a
        if a != 0:
            if isinstance(M, (list, tuple)):
                # M given as a list of invariant factors
                lcm_val = 1
                for val in M:
                    lcm_val = math.lcm(lcm_val, abs(int(val)))
                if abs(a) == lcm_val:
                    H_2 = True
            else:
                # Implicit M = Z/aZ or fallback
                H_2 = True
                
        # Conclusion: The p-primary component of M is non-zero if and only if p divides a in R
        # The p-primary component of M is non-zero iff gcd(p, a) > 1
        p_primary_nonzero = math.gcd(p, a) > 1
        
        # Check if p divides a in R
        if p != 0:
            p_divides_a = (a % p == 0)
        else:
            p_divides_a = (a == 0)
            
        # The conjecture states: p_primary_nonzero == p_divides_a
        # We want the negation of the conclusion (i.e., it fails at the witness)
        neg_Q = (p_primary_nonzero != p_divides_a)
        
    except Exception:
        pass
        
    return [H_1, H_2, neg_Q]

