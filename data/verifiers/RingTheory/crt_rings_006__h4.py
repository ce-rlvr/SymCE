import sympy
from sympy import fraction, cancel, gcd, sympify
from sympy.abc import x, y, z
from functools import reduce

# Top-level setup for potential witness expressions
# We provide standard symbols for polynomial rings.
# The verifier assumes the ring R is either ZZ or Q[x] (or similar PIDs)
# based on the types of the generators provided in the witness.

def get_gen(gen):
    """Helper to extract a single generator from a list of generators using GCD,
    since in a PID any finitely generated ideal is principal."""
    if isinstance(gen, (list, tuple)):
        if not gen:
            return sympify(0)
        return reduce(gcd, [sympify(g) for g in gen])
    return sympify(gen)

def conditions(witness) -> list[bool]:
    """
    Check the hypotheses and negated conclusion for the false conjecture:
    Hypotheses:
      H1: R is a commutative ring with identity
      H2: I and J are ideals of R
      H3: I + J = R
    Conclusion:
      Q: I^m + J^n = R
    
    The dropped hypothesis is that m, n are positive integers.
    A valid counterexample will provide m, n <= 0.
    """
    try:
        # Extract I_gen, J_gen, m, n from the witness
        if isinstance(witness, dict):
            I_gen = witness['I']
            J_gen = witness['J']
            m = witness['m']
            n = witness['n']
        elif len(witness) == 4:
            I_gen, J_gen, m, n = witness
        elif len(witness) == 5:
            # Format: (R, I, J, m, n)
            _, I_gen, J_gen, m, n = witness
        else:
            return [False, False, False, False]
            
        I_gen = get_gen(I_gen)
        J_gen = get_gen(J_gen)
        m = sympify(m)
        n = sympify(n)
    except Exception:
        return [False, False, False, False]

    # H1: R is a commutative ring with identity
    # We evaluate this in ZZ or Q[x], which are commutative rings with identity.
    h1_ok = True
    
    # H2: I and J are ideals of R
    # Any element generates an ideal in these rings.
    h2_ok = True
    
    # H3: I + J = R
    try:
        g = gcd(I_gen, J_gen)
        if g.is_number:
            if g.is_Integer:
                h3_ok = (abs(g) == 1)
            else:
                # In a field like Q, any non-zero element is a unit
                h3_ok = (g != 0)
        else:
            # For polynomials, gcd == 1 means they are coprime, so I + J = R in Q[x]
            h3_ok = (g == 1 or g == -1)
    except Exception:
        h3_ok = False
        
    # neg_Q: I^m + J^n != R
    try:
        # Ideal powers are only defined for integer powers.
        if not (m.is_Integer and n.is_Integer):
            neg_q_ok = True
        elif (m <= 0 and I_gen == 0) or (n <= 0 and J_gen == 0):
            # 0 to a non-positive power is undefined
            neg_q_ok = True
        else:
            im = I_gen ** m
            jn = J_gen ** n
            
            # Extract numerators and denominators to handle fractional ideals
            im_n, im_d = fraction(cancel(im))
            jn_n, jn_d = fraction(cancel(jn))
            
            # The sum of fractional ideals (a/b) + (c/d) is generated by gcd(ad, bc) / bd
            num = gcd(im_n * jn_d, jn_n * im_d)
            den = im_d * jn_d
            
            if den == 0:
                neg_q_ok = True
            else:
                val = cancel(num / den)
                if val.is_number:
                    if I_gen.is_Integer and J_gen.is_Integer:
                        # If the ring is ZZ, the generator must be 1 or -1 to equal R
                        if val.is_Integer:
                            neg_q_ok = (abs(val) != 1)
                        else:
                            neg_q_ok = True
                    else:
                        # If the ring is Q, any non-zero generator equals R
                        neg_q_ok = (val == 0)
                else:
                    # For polynomial rings, it must be a unit (constant 1 or -1)
                    # Since we already cancelled, if it's not a number, it's not a unit.
                    neg_q_ok = True
    except Exception:
        # Any evaluation failure (e.g., undefined operations) means the conclusion fails
        neg_q_ok = True
        
    return [h1_ok, h2_ok, h3_ok, neg_q_ok]

