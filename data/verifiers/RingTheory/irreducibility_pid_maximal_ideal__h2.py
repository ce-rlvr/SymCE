import sympy
from sympy import ZZ, QQ, RR, CC
from sympy.abc import x

def conditions(witness):
    try:
        R, p = witness
    except Exception:
        return [False, False, False]
    
    def is_PID(R):
        if getattr(R, 'is_PID', False):
            return True
        if getattr(R, 'is_Field', False):
            return True
        if R == ZZ:
            return True
        if hasattr(R, 'domain') and getattr(R.domain, 'is_Field', False) and hasattr(R, 'symbols') and len(R.symbols) == 1:
            return True
        return False

    def is_unit(R, p):
        if p == 0:
            return False
        if getattr(R, 'is_Field', False):
            return True
        if R == ZZ:
            return abs(p) == 1
        if hasattr(R, 'domain') and getattr(R.domain, 'is_Field', False) and hasattr(R, 'symbols') and len(R.symbols) == 1:
            try:
                return R(p).degree() <= 0
            except Exception:
                return False
        return False

    def is_irreducible(R, p):
        if p == 0:
            return False
        if is_unit(R, p):
            return False
        if getattr(R, 'is_Field', False):
            return False
        if R == ZZ:
            from sympy import isprime
            return isprime(abs(p))
        if hasattr(R, 'domain') and getattr(R.domain, 'is_Field', False) and hasattr(R, 'symbols') and len(R.symbols) == 1:
            try:
                from sympy import factor_list
                poly = R(p)
                if poly.degree() <= 0:
                    return False
                expr = poly.as_expr()
                const, factors = factor_list(expr, domain=R.domain)
                if len(factors) == 1 and factors[0][1] == 1:
                    return True
                return False
            except Exception:
                return False
        return False

    try:
        h1 = is_PID(R)
    except Exception:
        h1 = False

    try:
        h2 = False
        if p in R:
            if p == 0:
                h2 = bool(getattr(R, 'is_Field', False))
            else:
                if not is_unit(R, p):
                    h2 = is_irreducible(R, p)
    except Exception:
        h2 = False

    try:
        neg_q = False
        if p in R:
            neg_q = not is_irreducible(R, p)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

