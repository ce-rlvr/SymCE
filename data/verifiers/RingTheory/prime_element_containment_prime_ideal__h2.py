import sympy
from sympy import ZZ, QQ, Poly, isprime, factor_list
import math

# Top-level setup for potential witness expressions
x = sympy.Symbol('x')
y = sympy.Symbol('y')

def conditions(witness):
    """
    Checks if the witness is a valid counterexample.
    The witness is expected to be a tuple (R, P_gens) where:
      - R is a SymPy ring/domain (e.g., ZZ, QQ.old_poly_ring(x))
      - P_gens is a list of generators for the ideal P in R
    """
    try:
        R, P_gens = witness
    except Exception:
        return [False, False]
        
    # H_1: R is a unique factorization domain
    try:
        h1 = bool(R.is_UFD)
    except Exception:
        h1 = False
        
    # ¬Q: The ideal P does NOT contain a non-zero prime element of R
    try:
        if all(g == 0 for g in P_gens):
            # The zero ideal contains no non-zero elements
            contains_prime = False
        elif getattr(R, 'is_Field', False):
            # Fields contain no prime elements (all non-zero elements are units)
            contains_prime = False
        elif R == ZZ:
            # In ZZ, an ideal is generated by the GCD of its generators
            g = 0
            for val in P_gens:
                g = math.gcd(g, int(val))
            if g == 0:
                contains_prime = False
            elif g == 1:
                contains_prime = True
            else:
                contains_prime = isprime(g)
        else:
            # For polynomial rings and other UFDs
            contains_prime = False
            for g in P_gens:
                try:
                    _, factors = factor_list(g)
                    # A unit (0 factors) generates the whole ring, which contains primes.
                    # An irreducible element (1 factor of multiplicity 1) is prime in a UFD.
                    if len(factors) == 0 or (len(factors) == 1 and factors[0][1] == 1):
                        contains_prime = True
                        break
                except Exception:
                    pass
            
            if not contains_prime:
                if len(P_gens) == 1:
                    # A principal ideal generated by a reducible non-unit contains no primes
                    contains_prime = False
                else:
                    # For multi-generated ideals where generators aren't prime, 
                    # we conservatively assume it might contain a prime to avoid false positives.
                    contains_prime = True
                    
        neg_q = not contains_prime
    except Exception:
        neg_q = False
        
    return [h1, neg_q]

