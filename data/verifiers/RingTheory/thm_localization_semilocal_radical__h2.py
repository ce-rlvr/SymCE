import sympy
from sympy.ntheory import factorint

# Top-level setup
# Integers are used directly to represent the ring Z/nZ.
# No additional named objects are required for this domain.

def conditions(witness) -> list[bool]:
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness is expected to be an integer n >= 2, representing the ring R = Z/nZ.
    """
    try:
        if isinstance(witness, tuple) and len(witness) == 1:
            witness = witness[0]
        if isinstance(witness, (int, sympy.Integer)):
            n = int(witness)
        else:
            return [False, False]
    except Exception:
        return [False, False]
        
    try:
        # H_1: R is a commutative semilocal ring with maximal ideals M_1, ..., M_k
        # The ring Z/nZ is a commutative semilocal ring for any integer n >= 2
        # because it is finite, hence Artinian, and thus has finitely many maximal ideals.
        h1_ok = (n >= 2)
    except Exception:
        h1_ok = False
        
    try:
        # ¬Q: The canonical ring homomorphism from R to S^{-1}R is NOT an isomorphism.
        # S is the complement of the Jacobson radical J(R).
        # For R = Z/nZ, J(R) is the nilradical, generated by the product of distinct prime factors of n.
        # S consists of elements not divisible by this product.
        # If n has > 1 distinct prime factors, S contains zero divisors of R.
        # Consequently, the multiplicative closure of S contains 0, making S^{-1}R the zero ring.
        # Since R is not the zero ring (n >= 2), the canonical map R -> 0 is not an isomorphism.
        # If n has exactly 1 prime factor (n is a prime power), R is a local ring, S is the set of units,
        # and S^{-1}R is isomorphic to R.
        if n >= 2:
            factors = factorint(n)
            neg_q_ok = len(factors) > 1
        else:
            neg_q_ok = False
    except Exception:
        neg_q_ok = False
        
    return [h1_ok, neg_q_ok]

