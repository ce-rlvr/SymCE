def parse_monomial(m):
    """
    Parses a SymPy expression into a dictionary of {Symbol: exponent}.
    Raises ValueError if the expression is not a valid monomial.
    """
    m = sympy.sympify(m)
    if m == 0:
        return {}
    
    if hasattr(m, 'as_powers_dict'):
        powers = m.as_powers_dict()
    else:
        raise ValueError("Not a valid SymPy expression")
        
    res = {}
    for base, exp in powers.items():
        if base.is_number:
            continue
        if isinstance(base, sympy.Symbol):
            if int(exp) != exp or exp <= 0:
                raise ValueError("Exponent must be a positive integer")
            res[base] = int(exp)
        else:
            raise ValueError(f"Not a monomial: base {base} is not a Symbol")
    return res

def conditions(witness):
    """
    Checks if the witness is a counterexample to the false conjecture.
    The witness is expected to be a list of SymPy monomials generating an ideal I 
    in the polynomial ring Q[V], where V is the set of variables appearing in the monomials.
    The ring R is Q[V]/I.
    """
    try:
        if not isinstance(witness, (list, tuple)):
            return [False, False, False]
            
        I_parsed = []
        for m in witness:
            if sympy.sympify(m) == 0:
                continue
            I_parsed.append(parse_monomial(m))
        
        # Extract all variables appearing in the ideal generators
        V_set = set()
        for m_dict in I_parsed:
            V_set.update(m_dict.keys())
        V = sorted(list(V_set), key=lambda s: s.name)
        
        # H_1: R is a commutative Noetherian ring
        # A quotient of a polynomial ring over a field by a finitely generated ideal is always commutative and Noetherian.
        h1_ok = True
        
        # H_2: R satisfies Serre's condition (R0)
        # Find all minimal primes of the monomial ideal (minimal hitting sets of the variables of the generators)
        hitting_sets = []
        for r in range(1, len(V) + 1):
            for subset in combinations(V, r):
                subset_set = set(subset)
                is_hitting = True
                for m_dict in I_parsed:
                    if not subset_set.intersection(m_dict.keys()):
                        is_hitting = False
                        break
                if is_hitting:
                    is_minimal = True
                    for hs in hitting_sets:
                        if hs.issubset(subset_set):
                            is_minimal = False
                            break
                    if is_minimal:
                        hitting_sets.append(subset_set)
                        
        if not I_parsed:
            hitting_sets = [set()]
            
        h2_ok = True
        for P in hitting_sets:
            # For R_P to be a field, for every variable v in P, there must exist a generator m in I
            # such that v has degree 1 in m, and no other variable from P appears in m.
            for v in P:
                found_m = False
                for m_dict in I_parsed:
                    if m_dict.get(v, 0) == 1:
                        other_vars_in_P = [u for u in P if u != v]
                        if all(m_dict.get(u, 0) == 0 for u in other_vars_in_P):
                            found_m = True
                            break
                if not found_m:
                    h2_ok = False
                    break
            if not h2_ok:
                break
                
        # neg_Q: R is NOT a reduced ring
        # A monomial ideal is radical (R is reduced) iff it is generated by square-free monomials.
        # This means the square-free part of every generator must be divisible by some generator in the ideal.
        is_reduced = True
        for m_dict in I_parsed:
            sq_part = {v: 1 for v in m_dict.keys()}
            divisible = False
            for g_dict in I_parsed:
                divides = True
                for v, exp in g_dict.items():
                    if exp > sq_part.get(v, 0):
                        divides = False
                        break
                if divides:
                    divisible = True
                    break
            if not divisible:
                is_reduced = False
                break
                
        neg_q = not is_reduced
        
        return [h1_ok, h2_ok, neg_q]
    except Exception:
        return [False, False, False]

