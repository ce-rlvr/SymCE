import sympy
from sympy.polys.domains import ZZ, QQ
from sympy import Symbol, factor_list

# Top-level setup: named object bindings
x = Symbol('x')
y = Symbol('y')
z = Symbol('z')

Zx = ZZ[x]
Qx = QQ[x]
Zxy = ZZ[x, y]
Qxy = QQ[x, y]

def is_prime_element(R, p):
    """Check if p is a prime element in the ring R."""
    if R in (ZZ, sympy.S.Integers):
        try:
            return sympy.isprime(abs(int(p)))
        except Exception:
            return False
            
    if hasattr(R, 'gens'):
        try:
            if hasattr(p, 'as_expr'):
                expr = p.as_expr()
            else:
                expr = sympy.sympify(p)
                
            cont, factors = factor_list(expr)
            
            if len(factors) == 0:
                # Constant polynomial
                if R.domain in (ZZ, sympy.S.Integers):
                    return sympy.isprime(abs(int(cont)))
                else:
                    return False
            elif len(factors) == 1 and factors[0][1] == 1:
                # Irreducible polynomial of degree >= 1
                if R.domain in (ZZ, sympy.S.Integers):
                    return abs(int(cont)) == 1
                elif getattr(R.domain, 'is_Field', False):
                    return True
            return False
        except Exception:
            return False
            
    return False

def is_quotient_field(R, p):
    """Check if the quotient ring R/<p> is a field."""
    if R in (ZZ, sympy.S.Integers):
        try:
            return sympy.isprime(abs(int(p)))
        except Exception:
            return False
            
    if hasattr(R, 'gens'):
        try:
            # In a polynomial ring over a field with 1 variable (a PID),
            # an ideal generated by a prime (irreducible) element is maximal.
            if getattr(R.domain, 'is_Field', False) and len(R.gens) == 1:
                return is_prime_element(R, p)
            else:
                # In rings like ZZ[x] or QQ[x, y], principal ideals are not maximal
                # (except trivial cases which are not prime ideals).
                return False
        except Exception:
            return False
            
    return False

def conditions(witness) -> list[bool]:
    try:
        R, p = witness
    except Exception:
        return [False, False]
        
    try:
        h1 = is_prime_element(R, p)
    except Exception:
        h1 = False
        
    try:
        q = is_quotient_field(R, p)
        neg_q = not q
    except Exception:
        neg_q = False
        
    return [h1, neg_q]

