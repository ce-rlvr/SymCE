def conditions(witness) -> list[bool]:
    try:
        ring = witness.ring
        gens = ring.gens
        n = len(gens)
        H1 = n > 0
    except Exception:
        H1 = False

    try:
        e_polys = []
        for k in range(1, n + 1):
            ek = ring.zero
            for comb in combinations(gens, k):
                term = ring.one
                for gen in comb:
                    term *= gen
                ek += term
            e_polys.append(ek)
        
        expected_ideal = ring.ideal(*e_polys)
        
        gb_witness = witness.groebner_basis()
        gb_expected = expected_ideal.groebner_basis()
        
        H2 = set(gb_witness) == set(gb_expected)
    except Exception:
        H2 = False

    try:
        gb = witness.groebner_basis()
        
        lms = []
        all_monic = True
        for p in gb:
            lc = p.LC
            if not ring.domain.is_unit(lc):
                all_monic = False
            lms.append(p.LM)
            
        if not all_monic:
            neg_Q = True
        else:
            is_zero_dim = True
            max_degrees = []
            for i in range(n):
                pure_power_found = False
                min_deg = float('inf')
                for lm in lms:
                    if all(lm[j] == 0 for j in range(n) if j != i):
                        pure_power_found = True
                        if lm[i] < min_deg:
                            min_deg = lm[i]
                if not pure_power_found:
                    is_zero_dim = False
                    break
                max_degrees.append(min_deg)
                
            if not is_zero_dim:
                neg_Q = True
            else:
                def count_sm(current_var_idx, current_monomial):
                    if current_var_idx == n:
                        for lm in lms:
                            if all(current_monomial[j] >= lm[j] for j in range(n)):
                                return 0
                        return 1
                    
                    total = 0
                    for d in range(max_degrees[current_var_idx]):
                        new_monomial = list(current_monomial)
                        new_monomial.append(d)
                        
                        divisible = False
                        for lm in lms:
                            if all(lm[j] == 0 for j in range(current_var_idx + 1, n)):
                                if all(new_monomial[j] >= lm[j] for j in range(current_var_idx + 1)):
                                    divisible = True
                                    break
                        if not divisible:
                            total += count_sm(current_var_idx + 1, new_monomial)
                    return total
                
                num_sm = count_sm(0, [])
                neg_Q = (num_sm != math.factorial(n))
                
    except Exception:
        neg_Q = False

    return [H1, H2, neg_Q]

