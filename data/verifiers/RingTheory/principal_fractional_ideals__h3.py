import sympy
from sympy import ZZ, QQ
from sympy.abc import x, y, z

def conditions(witness):
    """
    Given a witness, checks if it is a valid counterexample to the false conjecture.
    The witness should be a tuple (R, M) or (R, K, M) where:
      - R is a SymPy domain (e.g., ZZ)
      - K is the fraction field of R (e.g., QQ)
      - M is an R-submodule of K (e.g., QQ)
    """
    try:
        if isinstance(witness, tuple):
            if len(witness) == 3:
                R, K, M = witness
            elif len(witness) == 2:
                R, M = witness
                K = R.frac_field()
            else:
                return [False, False, False]
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H1: R is a principal ideal domain
    try:
        h1 = bool(R.is_PID)
    except Exception:
        h1 = False

    # H2: K is the field of fractions of R and M is an R-submodule of K
    try:
        is_frac = (K == R.frac_field())
        # Check if M is a valid R-submodule of K.
        # For SymPy domains, R <= M <= K ensures M is an R-module contained in K.
        if hasattr(M, 'unify'):
            is_submod = (R.unify(M) == M) and (M.unify(K) == K)
        else:
            is_submod = False
        h2 = bool(is_frac and is_submod)
    except Exception:
        h2 = False

    # neg_Q: M is not generated as an R-module by a single element of K
    try:
        # If M is the entire fraction field K, and R is not a field,
        # then K is infinitely generated over R, so it cannot be
        # generated by a single element (i.e., it is not a principal fractional ideal).
        if M == K and not getattr(R, 'is_Field', False):
            neg_q = True
        elif getattr(M, 'is_Field', False) and not getattr(R, 'is_Field', False):
            neg_q = True
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

