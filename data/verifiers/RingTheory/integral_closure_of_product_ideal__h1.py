def check_subset(I_bar, J_bar, IJ_bar):
    """
    Checks if the ideal generated by I_bar * J_bar is a subset of IJ_bar.
    It is sufficient to check if the product of their generators is in IJ_bar.
    """
    I_gens = I_bar.generators if hasattr(I_bar, 'generators') else I_bar
    J_gens = J_bar.generators if hasattr(J_bar, 'generators') else J_bar
    
    for x in I_gens:
        for y in J_gens:
            prod = x * y
            in_IJ = False
            
            # Try custom contains method
            if hasattr(IJ_bar, 'contains'):
                try:
                    in_IJ = IJ_bar.contains(prod)
                except Exception:
                    pass
            
            # Try standard 'in' operator
            if not in_IJ and hasattr(IJ_bar, '__contains__'):
                try:
                    in_IJ = prod in IJ_bar
                except Exception:
                    pass
            
            # Fallback to list iteration
            if not in_IJ:
                try:
                    in_IJ = prod in list(IJ_bar)
                except Exception:
                    pass
            
            if not in_IJ:
                return False
    return True

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the conjecture:
    \overline{I} \cdot \overline{J} \subseteq \overline{IJ}
    """
    # 1. Try if witness is a dictionary with boolean flags
    try:
        if isinstance(witness, dict) and 'conclusion_holds' in witness:
            h1 = bool(witness.get('I_is_ideal', True))
            h2 = bool(witness.get('J_is_ideal', True))
            neg_q = not bool(witness.get('conclusion_holds', True))
            return [h1, h2, neg_q]
    except Exception:
        pass

    # 2. Try if witness is an object with boolean flags
    try:
        if hasattr(witness, 'conclusion_holds'):
            h1 = bool(getattr(witness, 'I_is_ideal', True))
            h2 = bool(getattr(witness, 'J_is_ideal', True))
            neg_q = not bool(witness.conclusion_holds)
            return [h1, h2, neg_q]
    except Exception:
        pass

    # 3. Try if witness provides I_bar, J_bar, IJ_bar explicitly in a dict
    try:
        if isinstance(witness, dict) and 'I_bar' in witness:
            I_bar = witness['I_bar']
            J_bar = witness['J_bar']
            IJ_bar = witness['IJ_bar']
            
            h1 = True
            h2 = True
            subset = check_subset(I_bar, J_bar, IJ_bar)
            return [h1, h2, not subset]
    except Exception:
        pass

    # 4. Try if witness provides I_bar, J_bar, IJ_bar explicitly as attributes
    try:
        if hasattr(witness, 'I_bar') and hasattr(witness, 'J_bar') and hasattr(witness, 'IJ_bar'):
            I_bar = witness.I_bar
            J_bar = witness.J_bar
            IJ_bar = witness.IJ_bar
            
            h1 = True
            h2 = True
            subset = check_subset(I_bar, J_bar, IJ_bar)
            return [h1, h2, not subset]
    except Exception:
        pass

    # 5. Try if witness is a tuple (I, J, I_bar, J_bar, IJ_bar)
    try:
        if isinstance(witness, (tuple, list)) and len(witness) == 5:
            I, J, I_bar, J_bar, IJ_bar = witness
            h1 = True
            h2 = True
            subset = check_subset(I_bar, J_bar, IJ_bar)
            return [h1, h2, not subset]
    except Exception:
        pass

    # 6. Try if witness is a tuple (I, J) and they have an integral_closure() method
    try:
        if isinstance(witness, (tuple, list)) and len(witness) == 2:
            I, J = witness
            h1 = getattr(I, 'is_ideal', True)
            h2 = getattr(J, 'is_ideal', True)
            
            I_bar = I.integral_closure()
            J_bar = J.integral_closure()
            IJ = I * J
            IJ_bar = IJ.integral_closure()
            
            subset = check_subset(I_bar, J_bar, IJ_bar)
            return [bool(h1), bool(h2), not subset]
    except Exception:
        pass

    return [False, False, False]

