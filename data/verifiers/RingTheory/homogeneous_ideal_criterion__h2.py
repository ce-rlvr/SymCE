def conditions(witness):
    try:
        h1 = check_H1(witness)
    except Exception:
        h1 = False
        
    try:
        p1 = check_P1(witness)
        p2 = check_P2(witness)
        neg_q = not (p1 == p2)
    except Exception:
        neg_q = False
        
    return [h1, neg_q]

