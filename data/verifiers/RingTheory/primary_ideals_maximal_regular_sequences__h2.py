import sympy

# Top-level setup for potential witness expressions
x, y, z, w = sympy.symbols('x y z w')

def intersection(I, J, vars):
    if not I or not J:
        return []
    t = sympy.Symbol('t_intersect')
    gens = [t * p for p in I] + [(1 - t) * p for p in J]
    gb = sympy.groebner(gens, t, *vars, order='lex')
    res = []
    for p in gb:
        if not p.has(t):
            res.append(p)
    return res

def ideal_quotient(I, f, vars):
    if f == 0:
        return [sympy.S.One]
    if not I:
        return []
    inter = intersection(I, [f], vars)
    quot = []
    for p in inter:
        q = sympy.cancel(p / f)
        # Check if the denominator is a constant (no free symbols)
        if not q.as_numer_denom()[1].free_symbols:
            quot.append(q)
    return quot

def is_subset(A, B, vars):
    if not B:
        for p in A:
            if sympy.expand(p) != 0:
                return False
        return True
    gb = sympy.groebner(B, *vars, order='lex')
    for p in A:
        _, r = sympy.reduced(p, gb, *vars, order='lex')
        if r != 0:
            return False
    return True

def is_M_primary(I, vars):
    if not I:
        return False
    gb = sympy.groebner(I, *vars, order='lex')
    for v in vars:
        has_pure_power = False
        for p in gb:
            lm = sympy.LM(p, *vars, order='lex')
            if lm.free_symbols == {v}:
                has_pure_power = True
                break
        if not has_pure_power:
            return False
    return True

def check_H1(witness):
    """
    Check if R is a commutative Noetherian local ring with maximal ideal M.
    We represent this by requiring the witness to provide a list of variables 'vars'
    and a sequence of homogeneous polynomials 'seq' in those variables with no constant term.
    This implicitly defines R = k[vars]_{(vars)} and M = (vars).
    """
    try:
        vars = witness.get('vars', [])
        seq = witness.get('seq', [])
        if not vars or not seq:
            return False
        for v in vars:
            if not isinstance(v, sympy.Symbol):
                return False
        for s in seq:
            if not s.free_symbols.issubset(set(vars)):
                return False
            p = sympy.poly(s, *vars)
            if p.coeff_monomial(1) != 0:
                return False
            if not p.is_homogeneous:
                return False
        return True
    except Exception:
        return False

def check_H2(witness):
    """
    Check if x_1, ..., x_d is an M-regular sequence of length d.
    """
    try:
        vars = witness.get('vars', [])
        seq = witness.get('seq', [])
        if not vars or not seq:
            return False
        I = []
        for s in seq:
            quot = ideal_quotient(I, s, vars)
            if not is_subset(quot, I, vars):
                return False
            I.append(s)
        # Ensure the ideal generated by the sequence is proper
        if is_subset([sympy.S.One], I, vars):
            return False
        return True
    except Exception:
        return False

def check_neg_Q(witness):
    """
    Check if the conclusion FAILS: The ideal generated by the sequence is NOT M-primary.
    """
    try:
        vars = witness.get('vars', [])
        seq = witness.get('seq', [])
        if not vars or not seq:
            return False
        return not is_M_primary(seq, vars)
    except Exception:
        return False

def conditions(witness):
    return [
        check_H1(witness),
        check_H2(witness),
        check_neg_Q(witness)
    ]

