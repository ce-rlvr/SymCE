def conditions(witness):
    """
    Checks if the witness is a counterexample to the conjecture:
    "P is a prime ideal if and only if the quotient ring R/P is an integral domain"
    (The dropped hypothesis is that P must be a proper ideal, i.e., P != R).
    
    The witness can be an integer `n` (representing the ideal nZ in the ring Z),
    or a tuple `(m, n)` representing the ideal nZ_m in the ring Z_m.
    """
    try:
        m = None
        n = None
        if isinstance(witness, (tuple, list)):
            if len(witness) == 2:
                r, p = witness
                if str(r) in ['ZZ', 'QQ']:
                    m = 0
                else:
                    try:
                        m = int(r)
                    except Exception:
                        m = 0
                
                if str(p) in ['ZZ', 'QQ']:
                    n = 1
                else:
                    n = int(p)
            else:
                return [False, False]
        else:
            if str(witness) in ['ZZ', 'QQ']:
                m = 0
                n = 1
            else:
                m = 0
                n = int(witness)
                
        if m is None or n is None:
            return [False, False]
            
        if m < 0:
            m = abs(m)
            
        # H_1: R is a commutative ring with a non-zero identity
        # For Z_m, this means m != 1. For Z, m = 0 (which is != 1).
        h1 = (m != 1)
        
        # neg_Q: The conclusion fails.
        # Conclusion: P is a prime ideal iff R/P is an integral domain.
        if m == 0:
            n_abs = abs(n)
            # In Z, an ideal nZ is prime (without properness requirement) if n is prime, 0, or 1.
            is_prime_ideal = sympy.isprime(n_abs) or n_abs == 0 or n_abs == 1
            # Z/nZ is an integral domain if n is prime or 0. (Z/1Z is the zero ring, not an integral domain).
            is_integral_domain = sympy.isprime(n_abs) or n_abs == 0
            neg_q = (is_prime_ideal != is_integral_domain)
        else:
            # In Z_m, the ideal P generated by n
            P = set((k * n) % m for k in range(m))
            
            # Check if P is a prime ideal: ab in P => a in P or b in P
            is_prime_ideal = True
            for a in range(m):
                for b in range(m):
                    if (a * b) % m in P:
                        if a not in P and b not in P:
                            is_prime_ideal = False
                            break
                if not is_prime_ideal:
                    break
                    
            # Check if R/P is an integral domain:
            # 1. It must have a non-zero identity (1 not in P)
            # 2. It must have no zero divisors (which is equivalent to the prime ideal condition)
            is_integral_domain = (1 not in P) and is_prime_ideal
            
            neg_q = (is_prime_ideal != is_integral_domain)
            
        return [h1, neg_q]
    except Exception:
        return [False, False]

