import sympy

class AbstractModule:
    """
    Mock object to represent a module over a ring for the purpose of 
    evaluating abstract properties that cannot be computed directly in SymPy.
    """
    def __init__(self, is_finitely_generated: bool, is_flat: bool, is_projective: bool):
        self.is_finitely_generated = is_finitely_generated
        self.is_flat = is_flat
        self.is_projective = is_projective

# Known counterexample: 
# R = \prod_{n=1}^\infty \mathbb{F}_2 (a Boolean ring, hence von Neumann regular)
# I = \bigoplus_{n=1}^\infty \mathbb{F}_2 (an ideal of R)
# M = R/I
# M is finitely generated (cyclic, generated by 1 + I), flat (since R is von Neumann regular, all modules are flat), 
# but not projective (since I is not generated by an idempotent, being not finitely generated).
M_counterexample = AbstractModule(is_finitely_generated=True, is_flat=True, is_projective=False)

# Q as a Z-module (not finitely generated, flat, not projective)
M_Q_Z = AbstractModule(is_finitely_generated=False, is_flat=True, is_projective=False)

# Z as a Z-module (finitely generated, flat, projective)
M_Z_Z = AbstractModule(is_finitely_generated=True, is_flat=True, is_projective=True)


def conditions(witness) -> list[bool]:
    """
    Checks if the witness satisfies the remaining hypotheses and falsifies the conclusion.
    """
    try:
        if isinstance(witness, dict):
            h1 = bool(witness.get('is_finitely_generated', False))
            is_flat = bool(witness.get('is_flat', False))
            is_proj = bool(witness.get('is_projective', False))
        else:
            h1 = bool(witness.is_finitely_generated)
            is_flat = bool(witness.is_flat)
            is_proj = bool(witness.is_projective)
    except Exception:
        return [False, False]
        
    try:
        # The conclusion is: M is flat <==> M is projective
        # Negation of conclusion: M is flat XOR M is projective
        neg_q = (is_flat != is_proj)
    except Exception:
        neg_q = False
        
    return [h1, neg_q]


