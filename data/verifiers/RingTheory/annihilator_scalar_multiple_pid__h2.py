def is_int(val):
    return isinstance(val, (int, sympy.Integer))

def conditions(witness) -> list[bool]:
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness must provide:
      - a: generator of ann(x)
      - r: scalar to multiply x by
      - Either:
          - action(s, m): function computing scalar multiplication s*m
          - x: the element in M
          - zero: the zero element in M
        OR:
          - in_ann_x(s): boolean function returning True iff s is in ann(x)
          - in_ann_rx(s): boolean function returning True iff s is in ann(rx)
    """
    try:
        a = witness.a
        r = witness.r
    except Exception:
        return [False, False, False, False]

    has_action = hasattr(witness, 'action') and hasattr(witness, 'x') and hasattr(witness, 'zero')
    has_ann = hasattr(witness, 'in_ann_x') and hasattr(witness, 'in_ann_rx')

    if not (has_action or has_ann):
        return [False, False, False, False]

    # H_1: R is a principal ideal domain.
    # We restrict to R = Z for simplicity, which is a valid PID.
    try:
        h1 = is_int(a) and is_int(r)
    except Exception:
        h1 = False

    # H_2: x in M has annihilator generated by non-zero a in R
    try:
        if not is_int(a) or a == 0:
            h2 = False
        else:
            a_val = int(a)
            h2 = True
            # Test the annihilator property over a range of scalars
            for s in range(-100, 101):
                if has_action:
                    is_zero = (witness.action(s, witness.x) == witness.zero)
                else:
                    is_zero = bool(witness.in_ann_x(s))
                
                if s % a_val == 0:
                    if not is_zero:
                        h2 = False
                        break
                else:
                    if is_zero:
                        h2 = False
                        break
    except Exception:
        h2 = False

    # H_3: r is a non-zero element of R
    try:
        h3 = is_int(r) and r != 0
    except Exception:
        h3 = False

    # ¬Q: The annihilator of rx is NOT generated by a / gcd(a, r)
    try:
        a_val = int(a)
        r_val = int(r)
        g = abs(a_val) // math.gcd(a_val, r_val)
        
        if has_action:
            rx = witness.action(r_val, witness.x)
        
        is_generated_by_g = True
        for s in range(-100, 101):
            if has_action:
                is_zero = (witness.action(s, rx) == witness.zero)
            else:
                is_zero = bool(witness.in_ann_rx(s))
                
            if s % g == 0:
                if not is_zero:
                    is_generated_by_g = False
                    break
            else:
                if is_zero:
                    is_generated_by_g = False
                    break
        neg_q = not is_generated_by_g
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

