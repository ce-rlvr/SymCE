def conditions(witness):
    try:
        # Witness is expected to be a tuple (n, m)
        # representing the ring R = Z/nZ and the ideal I = (m).
        n, m = witness
        n = abs(int(n))
        m = int(m)
    except Exception:
        return [False, False, False]
        
    # H_1: Assume R is not a field
    try:
        if n == 0:
            h1 = True  # Z is not a field
        elif n >= 2:
            # Z/nZ is a field iff n is prime.
            h1 = not sympy.isprime(n)
        else:
            h1 = False
    except Exception:
        h1 = False
        
    # H_2: Let I be a proper ideal of R
    try:
        if n == 0:
            # In Z, proper ideals are generated by m where |m| != 1
            h2 = abs(m) != 1
        elif n >= 2:
            # In Z/nZ, the ideal (m) is proper iff it does not contain 1.
            # This is equivalent to gcd(m, n) > 1.
            h2 = math.gcd(m, n) > 1
        else:
            h2 = False
    except Exception:
        h2 = False
        
    # neg_Q: The intersection \bigcap_{k=1}^\infty I^k is NOT the zero ideal
    try:
        if n == 0:
            # In Z, the intersection of (m)^k for any proper ideal is (0).
            # So the conclusion holds, meaning neg_Q is False.
            neg_q = False
        elif n >= 2:
            # I^k is generated by m^k.
            # The sequence of ideals (m^k) stabilizes to (g) where g = gcd(m^k, n) for large k.
            g = math.gcd(m, n)
            
            # The maximum length of a strictly descending chain of ideals in Z/nZ is bounded by 
            # the number of prime factors of n, which is strictly less than n.bit_length().
            max_steps = n.bit_length() + 1
            for _ in range(max_steps):
                g = math.gcd(g * m, n)
                
            # The ideal (g) is the zero ideal in Z/nZ iff g is a multiple of n.
            # Since g divides n, this means g == n.
            # We want the intersection to NOT be the zero ideal, so g != n.
            neg_q = (g != n)
        else:
            neg_q = False
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

