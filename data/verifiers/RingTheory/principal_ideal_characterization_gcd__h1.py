import math

# Top-level setup for the verifier.
# The theorem holds in any commutative ring with identity.
# The dropped hypothesis is that the ring has an identity (or is an integral domain, which implies identity).
# A standard counterexample is the ring of even integers, 2Z, which lacks an identity.
# We will evaluate the witness in the context of R = 2Z.
# The witness should provide the elements a and b.

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness is expected to be a tuple (a, b) or (ring_name, a, b) representing elements in 2Z.
    """
    try:
        if isinstance(witness, tuple):
            if len(witness) == 3:
                _, a, b = witness
            elif len(witness) == 2:
                a, b = witness
            else:
                return [False, False]
        else:
            return [False, False]
            
        if not (isinstance(a, int) and isinstance(b, int)):
            return [False, False]
            
    except Exception:
        return [False, False]

    # H_1: a and b are elements of R (we interpret R as the ring of even integers 2Z)
    h1_ok = (a % 2 == 0) and (b % 2 == 0)
    
    neg_q_ok = False
    if h1_ok:
        try:
            # In 2Z, the ideal generated by a and b is Z * gcd(a, b).
            # A principal ideal (c) in 2Z is Z * c.
            # Thus, (a, b) is contained in (c) iff c divides gcd(a, b) in Z.
            g = math.gcd(a, b)
            c_list = []
            for c in range(-abs(g), abs(g) + 1):
                if c != 0 and c % 2 == 0 and g % c == 0:
                    c_list.append(abs(c))
            
            # The intersection of these principal ideals Z * c is Z * L, where L is their LCM.
            if not c_list:
                L = 2  # Intersection of the empty family of ideals in 2Z is 2Z itself
            else:
                L = c_list[0]
                for c in c_list[1:]:
                    L = (L * c) // math.gcd(L, c)
            
            def divides_in_2Z(x, y):
                if x == 0: return y == 0
                if y % x != 0: return False
                return (y // x) % 2 == 0

            # The conclusion states: For all d in R, d is a GCD iff (d) is the intersection.
            # We search for a d in 2Z that breaks this biconditional.
            for d in range(-100, 101, 2):
                if d == 0:
                    continue
                
                # Check if d is a GCD of a and b in 2Z
                is_common_div = divides_in_2Z(d, a) and divides_in_2Z(d, b)
                is_gcd = False
                if is_common_div:
                    is_gcd = True
                    # Check if all common divisors divide d
                    limit = max(abs(a), abs(b)) + 2
                    for c in range(-limit, limit + 1, 2):
                        if c != 0 and divides_in_2Z(c, a) and divides_in_2Z(c, b):
                            if not divides_in_2Z(c, d):
                                is_gcd = False
                                break
                
                # Check if (d) is the intersection of all principal ideals containing (a, b)
                # (d) = Z * d, which equals Z * L iff abs(d) == L
                is_intersection = (abs(d) == L)
                
                # If the biconditional fails for this d, the universally quantified conclusion fails.
                if is_gcd != is_intersection:
                    neg_q_ok = True
                    break
                    
        except Exception:
            pass

    return [h1_ok, neg_q_ok]

