import sympy
from sympy import Poly, expand, sympify, symbols
from sympy.abc import x, y, z, t, u, v, w, a, b, c, d

def parse_witness(witness):
    I = []
    ring_vars = []
    if isinstance(witness, tuple):
        if len(witness) == 5:
            f, g, poly_vars, ring_vars, I = witness
        elif len(witness) == 4:
            f, g, poly_vars, ring_vars = witness
        elif len(witness) == 3:
            f, g, poly_vars = witness
            if not isinstance(poly_vars, (list, tuple)):
                poly_vars = [poly_vars]
            ring_vars = list((sympify(f).free_symbols | sympify(g).free_symbols) - set(poly_vars))
        elif len(witness) == 2:
            f, g = witness
            poly_vars = list(sympify(f).free_symbols | sympify(g).free_symbols)
        else:
            return None
    else:
        return None
        
    if not isinstance(poly_vars, (list, tuple)):
        poly_vars = [poly_vars]
    if not isinstance(ring_vars, (list, tuple)):
        ring_vars = [ring_vars]
    if not isinstance(I, (list, tuple)):
        I = [I]
        
    I_exprs = []
    for eq in I:
        if isinstance(eq, sympy.Eq):
            I_exprs.append(eq.lhs - eq.rhs)
        else:
            I_exprs.append(sympify(eq))
            
    return f, g, poly_vars, ring_vars, I_exprs

def in_ideal(p, generators, ring_vars):
    p = expand(p)
    if not generators:
        return p == 0
    if not ring_vars:
        try:
            g = sympy.gcd_list(generators)
            if g == 0:
                return p == 0
            
            all_int = p.is_integer
            for gen in generators:
                if not getattr(gen, 'is_integer', False):
                    all_int = False
                    break
                    
            if all_int:
                return (p % g) == 0
            else:
                return True
        except Exception:
            return False
    
    try:
        gb = sympy.groebner(generators, *ring_vars)
        return gb.reduce(p)[1] == 0
    except Exception:
        return False

def conditions(witness) -> list[bool]:
    parsed = parse_witness(witness)
    if not parsed:
        return [False, False, False, False]
        
    f, g, poly_vars, ring_vars, I = parsed
    
    try:
        f_expr = sympify(f)
        g_expr = sympify(g)
        h1 = True
        h2 = True
    except Exception:
        return [False, False, False, False]
        
    try:
        f_poly = Poly(f_expr, *poly_vars)
        f_coeffs = f_poly.coeffs()
        h3 = in_ideal(1, f_coeffs + I, ring_vars)
    except Exception:
        h3 = False
        
    try:
        fg_expr = expand(f_expr * g_expr)
        fg_poly = Poly(fg_expr, *poly_vars)
        fg_coeffs = fg_poly.coeffs()
        
        g_poly = Poly(g_expr, *poly_vars)
        g_coeffs = g_poly.coeffs()
        
        subset1 = True
        for coeff in fg_coeffs:
            if not in_ideal(coeff, g_coeffs + I, ring_vars):
                subset1 = False
                break
                
        subset2 = True
        for coeff in g_coeffs:
            if not in_ideal(coeff, fg_coeffs + I, ring_vars):
                subset2 = False
                break
                
        c_eq = subset1 and subset2
        neg_q = not c_eq
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

