def conditions(witness):
    """
    Checks whether the given witness is a valid counterexample.
    The witness can be a tuple/dict specifying a known ring (like "2Z", "Z", "Z6") 
    and elements a, b, d, or a custom object implementing the required methods.
    """
    try:
        # Extract witness components
        if isinstance(witness, dict):
            ring = witness.get('ring')
            a = witness.get('a')
            b = witness.get('b')
            d = witness.get('d')
        elif isinstance(witness, tuple) and len(witness) == 4:
            ring, a, b, d = witness
        else:
            ring = getattr(witness, 'ring', None)
            a = getattr(witness, 'a', None)
            b = getattr(witness, 'b', None)
            d = getattr(witness, 'd', None)

        # Logic for the ring of even integers (2Z) - the standard counterexample
        if ring == "2Z":
            h1 = isinstance(a, int) and a % 2 == 0 and isinstance(b, int) and b % 2 == 0
            h2 = isinstance(d, int) and d % 2 == 0 and abs(d) == abs(math.gcd(a, b))
            
            def divides(x, y):
                if x == 0: return y == 0
                if y % x != 0: return False
                return (y // x) % 2 == 0
            
            def is_gcd(g, a, b):
                if not (divides(g, a) and divides(g, b)): return False
                if a == 0 and b == 0: return g == 0
                max_val = max(abs(a), abs(b))
                for c in range(-max_val, max_val + 1, 2):
                    if c == 0: continue
                    if divides(c, a) and divides(c, b):
                        if not divides(c, g): return False
                return True
            
            neg_q = not is_gcd(d, a, b)
            return [h1, h2, neg_q]
            
        # Logic for the ring of integers (Z)
        elif ring == "Z":
            h1 = isinstance(a, int) and isinstance(b, int)
            h2 = isinstance(d, int) and abs(d) == abs(math.gcd(a, b))
            
            def divides(x, y):
                if x == 0: return y == 0
                return y % x == 0
            
            def is_gcd(g, a, b):
                if not (divides(g, a) and divides(g, b)): return False
                if a == 0 and b == 0: return g == 0
                max_val = max(abs(a), abs(b))
                for c in range(-max_val, max_val + 1):
                    if c == 0: continue
                    if divides(c, a) and divides(c, b):
                        if not divides(c, g): return False
                return True
            
            neg_q = not is_gcd(d, a, b)
            return [h1, h2, neg_q]
            
        # Logic for integers modulo n (Zn)
        elif isinstance(ring, str) and ring.startswith("Z") and ring[1:].isdigit():
            n = int(ring[1:])
            h1 = isinstance(a, int) and 0 <= a < n and isinstance(b, int) and 0 <= b < n
            
            ideal_ab = set((x*a + y*b) % n for x in range(n) for y in range(n))
            ideal_d = set((x*d) % n for x in range(n))
            
            h2 = isinstance(d, int) and 0 <= d < n and ideal_ab == ideal_d
            
            def divides(x, y):
                return any((x * k) % n == y for k in range(n))
                
            def is_gcd(g, a, b):
                if not (divides(g, a) and divides(g, b)): return False
                for c in range(n):
                    if divides(c, a) and divides(c, b):
                        if not divides(c, g): return False
                return True
                
            neg_q = not is_gcd(d, a, b)
            return [h1, h2, neg_q]
            
        # Duck typing for custom witness objects
        else:
            try:
                h1 = bool(witness.is_in_R(a) and witness.is_in_R(b))
            except Exception:
                h1 = False
                
            try:
                h2 = bool(witness.ideal_is_principal(a, b, d))
            except Exception:
                h2 = False
                
            try:
                neg_q = not bool(witness.is_gcd(d, a, b))
            except Exception:
                neg_q = False
                
            return [h1, h2, neg_q]
            
    except Exception:
        return [False, False, False]