import sympy
from sympy import ZZ, QQ, Symbol
from sympy.polys.rings import ring

x = Symbol('x')
R_Z, x_Z = ring('x', ZZ)
R_Q, x_Q = ring('x', QQ)

def conditions(witness):
    H_1 = False
    try:
        if hasattr(witness, 'gens'):
            gens = list(witness.gens)
            if len(gens) == 1:
                gen = gens[0]
                if hasattr(gen, 'as_expr'):
                    expr = gen.as_expr()
                else:
                    expr = sympy.sympify(gen)
                
                diff = sympy.simplify(expr - (x**2 - x - 1))
                sum_ = sympy.simplify(expr + (x**2 - x - 1))
                if diff == 0 or sum_ == 0:
                    H_1 = True
    except Exception:
        H_1 = False

    neg_Q = False
    try:
        is_ZZ_x = False
        if hasattr(witness, 'ring'):
            ring_obj = witness.ring
            if hasattr(ring_obj, 'domain') and hasattr(ring_obj, 'gens'):
                if ring_obj.domain == ZZ and len(ring_obj.gens) == 1:
                    if str(ring_obj.gens[0]) == 'x':
                        is_ZZ_x = True
        
        if not is_ZZ_x:
            neg_Q = True
    except Exception:
        neg_Q = True

    return [H_1, neg_Q]

