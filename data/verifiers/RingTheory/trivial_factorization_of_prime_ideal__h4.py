def get_gen(x):
    if isinstance(x, (list, tuple, set)):
        if len(x) == 0:
            return 0
        g = 0
        for elem in x:
            g = math.gcd(g, abs(int(elem)))
        return g
    else:
        return abs(int(x))

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, tuple):
            if len(witness) == 4:
                R, p_raw, i_raw, j_raw = witness
            elif len(witness) == 3:
                p_raw, i_raw, j_raw = witness
            else:
                return [False] * 4
        else:
            return [False] * 4
            
        try:
            p = get_gen(p_raw)
            i = get_gen(i_raw)
            j = get_gen(j_raw)
        except (ValueError, TypeError):
            return [False] * 4

        # H_1: R is a commutative ring
        # We evaluate the ideals in Z, which is a commutative ring.
        h1 = True
        
        # H_2: P is a prime ideal of R
        # In Z, an ideal is prime if it is generated by 0 or a prime number.
        h2 = (p == 0) or sympy.isprime(p)
        
        # H_3: I and J are ideals of R
        # In Z, any integer generates an ideal.
        h3 = True
        
        # ¬Q: I != P and J != P
        neg_q = (i != p) and (j != p)

        return [h1, h2, h3, neg_q]
    except Exception:
        return [False] * 4