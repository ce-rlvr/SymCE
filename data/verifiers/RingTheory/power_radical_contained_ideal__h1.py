def conditions(witness):
    # Extract ideal if witness is a tuple like (Ring, Ideal)
    if isinstance(witness, tuple) and len(witness) == 2:
        witness = witness[1]
    
    # Wrap raw functions, lists, or dicts into the MonomialIdeal class
    if callable(witness) or isinstance(witness, (list, tuple, dict)):
        witness = MonomialIdeal(witness)
        
    # H_1: I is an ideal of R
    try:
        if hasattr(witness, 'is_ideal'):
            h1 = witness.is_ideal()
        elif 'Ideal' in type(witness).__name__:
            h1 = True
        else:
            h1 = False
    except Exception:
        h1 = False

    # ¬Q: For all k > 0, (\sqrt{I})^k \not\subseteq I
    try:
        if hasattr(witness, 'radical_power_contained'):
            neg_q = True
            # Check for k up to 100. If any power is contained, the conclusion holds (so neg_q is False).
            for k in range(1, 101):
                if witness.radical_power_contained(k):
                    neg_q = False
                    break
        else:
            # If it's a standard SymPy ideal, it belongs to a Noetherian ring, 
            # so the radical power is eventually contained.
            neg_q = False
    except Exception:
        neg_q = False

    return [bool(h1), bool(neg_q)]

