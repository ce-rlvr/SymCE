class MonomialIdeal:
    """
    Represents an ideal I = < x_n^{d(n)} > in the polynomial ring k[x_1, x_2, ...].
    d_func is a function that takes n (1-indexed) and returns the exponent d(n).
    """
    def __init__(self, d_func):
        if isinstance(d_func, (list, tuple)):
            self.d = lambda n: d_func[n-1] if n <= len(d_func) else float('inf')
        elif isinstance(d_func, dict):
            self.d = lambda n: d_func.get(n, float('inf'))
        else:
            self.d = d_func

    def is_ideal(self):
        return True

    def radical_power_contained(self, k):
        """
        Checks if (\\sqrt{I})^k \\subseteq I.
        \\sqrt{I} is generated by {x_n | d(n) < \\infty}.
        (\\sqrt{I})^k is generated by monomials of degree k using these variables.
        Such a monomial is in I iff its degree in some x_n is >= d(n).
        If the maximum possible degree of a monomial NOT in I is >= k, 
        then (\\sqrt{I})^k is NOT contained in I.
        """
        total = 0
        for n in range(1, max(k + 2, 1000)):
            try:
                val = self.d(n)
                if val <= 0:
                    # 1 is in I, so I is the whole ring, and (\sqrt{I})^k \subseteq I is trivially true
                    return True
                if val < float('inf'):
                    total += max(0, int(val) - 1)
                if total >= k:
                    return False
            except Exception:
                pass
        return True

# Aliases for the witness expression to use
