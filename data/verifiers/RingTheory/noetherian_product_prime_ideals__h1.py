# Top-level setup: named object bindings that the witness expression may reference.
# Since SymPy does not natively support infinite polynomial rings (which are required
# to construct a non-Noetherian counterexample for this theorem), we provide a custom
# class that models an ideal in k[x_1, x_2, ...].

class InfinitePolynomialRingIdeal:
    """
    Represents an ideal I = (x_1^p_1, x_2^p_2, ...) in the infinite polynomial ring k[x_1, x_2, ...].
    The sequence of powers is given by `gen_powers`, a callable where p_k = gen_powers(k).
    """
    def __init__(self, gen_powers):
        if callable(gen_powers):
            self.gen_powers = gen_powers
        elif isinstance(gen_powers, dict):
            self.gen_powers = lambda k: gen_powers.get(k, k + 1)
        else:
            self.gen_powers = lambda k: gen_powers[k] if k < len(gen_powers) else k + 1

    def is_proper_ideal(self):
        # An ideal generated by monomials is proper iff no generator is 1 (i.e. power <= 0).
        for k in range(1, 200):
            if self.gen_powers(k) <= 0:
                return False
        return True

    def contains_product_of_primes(self):
        # The radical of I is M = (x_1, x_2, ...).
        # M is the unique prime ideal containing I.
        # Any finite product of prime ideals containing I must be M^n for some n >= 1.
        # M^n contains the monomial x_{n+1}^n.
        # This monomial is in I iff its power n is >= the generator power for x_{n+1},
        # which is gen_powers(n+1).
        # If for all n >= 1, n < gen_powers(n+1), then M^n is never contained in I.
        for n in range(1, 200):
            if n >= self.gen_powers(n+1):
                return True
        return False

def _counterexample_powers(k):
    return k + 1

# A ready-to-use counterexample witness: I = (x_1^2, x_2^3, x_3^4, ...)
I_counterexample = InfinitePolynomialRingIdeal(_counterexample_powers)


def conditions(witness) -> list[bool]:
    """
    Evaluates the hypotheses and the negated conclusion for the given witness.
    Returns [H_1_ok, neg_Q_ok].
    """
    try:
        if hasattr(witness, "is_proper_ideal"):
            h1 = bool(witness.is_proper_ideal())
        else:
            h1 = False
    except Exception:
        h1 = False

    try:
        if hasattr(witness, "contains_product_of_primes"):
            # neg_Q is True if the conclusion FAILS (i.e., it does NOT contain such a product)
            neg_q = not bool(witness.contains_product_of_primes())
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, neg_q]


