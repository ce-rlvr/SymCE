import sympy
from sympy import symbols, sympify

# Top-level setup: define common variables that might be used in the witness
x, y, z, t = symbols('x y z t')

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness is expected to be a list of generators for an ideal I in a UFD.
    """
    h1_ok = False
    neg_q_ok = False
    
    try:
        # Extract generators of the ideal
        if hasattr(witness, 'gens'):
            gens = witness.gens
        elif isinstance(witness, tuple) and len(witness) == 2 and isinstance(witness[1], (list, tuple)):
            gens = witness[1]
        elif isinstance(witness, (list, tuple)):
            gens = witness
        else:
            gens = None
            
        if gens is not None and len(gens) > 0:
            gens = [sympify(p) for p in gens]
            
            # Check if all generators are valid polynomials
            all_poly = True
            for p in gens:
                if not hasattr(p, 'free_symbols'):
                    all_poly = False
                    break
                if p.is_polynomial() is not True:
                    all_poly = False
                    break
            
            if all_poly:
                # H_1: R is a unique factorization domain.
                # Polynomial rings over fields (like QQ) are UFDs.
                # We implicitly consider R to be QQ[vars].
                h1_ok = True
                
                # neg_Q: I cannot be expressed as a product of principal prime ideals.
                # In a UFD, an ideal is a product of principal prime ideals iff it is a principal ideal.
                # We check if the ideal is NOT principal by computing its reduced Groebner basis.
                # Over a field, an ideal is principal iff its reduced Groebner basis has exactly 1 element.
                free_syms = set()
                for p in gens:
                    free_syms.update(p.free_symbols)
                
                if not free_syms:
                    # Ideal generated by constants in a field is always principal (either <0> or <1>)
                    neg_q_ok = False
                else:
                    gb = sympy.groebner(gens, *list(free_syms), domain='QQ')
                    if len(gb) > 1:
                        neg_q_ok = True
    except Exception:
        pass

    return [h1_ok, neg_q_ok]

