import sympy
from sympy import Poly, groebner, reduced
from sympy.abc import x, y, z

def conditions(witness):
    try:
        I_gens, f = witness
    except Exception:
        return [False, False, False]
    
    try:
        gens = list(I_gens)
        all_exprs = gens + [f]
        free_symbols = set()
        for expr in all_exprs:
            if hasattr(expr, 'free_symbols'):
                free_symbols.update(expr.free_symbols)
        vars = sorted(list(free_symbols), key=lambda v: v.name)
        if not vars:
            vars = [sympy.Symbol('x')]
            
        if not gens:
            gb = []
            h1 = True
        else:
            gb = list(groebner(gens, *vars))
            h1 = True
            for g in gb:
                p = Poly(g, *vars)
                if len(p.terms()) > 1:
                    h1 = False
                    break
    except Exception:
        h1 = False

    try:
        Poly(f, *vars)
        h2 = True
    except Exception:
        h2 = False

    try:
        if not gb:
            rem = Poly(f, *vars).as_expr()
        else:
            rem = reduced(f, gb, *vars)[1]
        lhs = (sympy.expand(rem) == 0)
        
        M = []
        for g in gens:
            try:
                p = Poly(g, *vars)
                if len(p.terms()) == 1:
                    M.append(g)
            except Exception:
                pass
                
        f_poly = Poly(f, *vars)
        f_terms_expr = []
        for monom, coeff in f_poly.terms():
            term = sympy.sympify(coeff)
            for v, p_pow in zip(vars, monom):
                term *= v**p_pow
            f_terms_expr.append(term)
            
        rhs = True
        for term in f_terms_expr:
            term_is_multiple = False
            for m in M:
                if sympy.expand(m) == 0:
                    if sympy.expand(term) == 0:
                        term_is_multiple = True
                        break
                    continue
                rem_term = reduced(term, [m], *vars)[1]
                if sympy.expand(rem_term) == 0:
                    term_is_multiple = True
                    break
            if not term_is_multiple:
                rhs = False
                break
                
        q = (lhs == rhs)
        neg_q = not q
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

