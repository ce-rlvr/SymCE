def conditions(witness) -> list[bool]:
    """
    witness is expected to be a tuple: (a, u, primes, exponents)
    representing an element in R = Z.
    """
    try:
        a, u, primes, exponents = witness
    except Exception:
        return [False, False, False]
        
    # H_1: R is a principal ideal domain
    # We restrict the verifier to R = Z for simplicity, which is a PID.
    try:
        H1 = isinstance(a, (int, Integer))
    except Exception:
        H1 = False
        
    # H_2: a = u p_1^{k_1} ... p_m^{k_m} is a factorization of a, where u is a unit, 
    # p_i are pairwise non-associate prime elements, and k_i are positive integers
    try:
        val = u
        for p, k in zip(primes, exponents):
            val *= p**k
        is_fact = (a == val)
        u_is_unit = (u in [1, -1])
        primes_are_prime = all(isprime(abs(p)) for p in primes)
        abs_primes = [abs(p) for p in primes]
        pairwise_non_assoc = len(abs_primes) == len(set(abs_primes))
        pos_exponents = all(k > 0 for k in exponents)
        H2 = is_fact and u_is_unit and primes_are_prime and pairwise_non_assoc and pos_exponents
    except Exception:
        H2 = False
        
    # ¬Q: The radical of <a> is NOT the principal ideal generated by the product p_1 ... p_m
    try:
        if a == 0:
            true_rad = 0
        else:
            true_rad = 1
            for p in primefactors(a):
                true_rad *= p
                
        if len(primes) == 0:
            # If m=0 (e.g., a is a unit), the product of primes is empty/undefined.
            # In the context of the dropped hypothesis ("a is a non-unit"), 
            # the conclusion fails because there are no prime factors to form the product.
            neg_Q = True
        else:
            prod_primes = 1
            for p in primes:
                prod_primes *= p
            # In Z, ideals are equal iff their generators have the same absolute value
            neg_Q = abs(true_rad) != abs(prod_primes)
    except Exception:
        neg_Q = False
        
    return [H1, H2, neg_Q]

