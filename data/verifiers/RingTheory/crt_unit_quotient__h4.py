import math
from functools import reduce
from sympy import ZZ, QQ, Symbol, Expr, groebner

# Top-level setup for potential witness expressions
x = Symbol('x')
y = Symbol('y')
z = Symbol('z')

CONDITION_LABELS = [
    "H_1: R is a commutative ring",
    "H_2: I is an ideal of R",
    "H_3: a is an element of R",
    "¬Q: I and (a) are not comaximal in R"
]

N_HYP = 3
NEG_Q_INDEX = 3

def conditions(witness):
    try:
        # Witness can be (R, I_gens, a) or just (I_gens, a) assuming R = ZZ
        if len(witness) == 3:
            R, I_gens, a = witness
        elif len(witness) == 2:
            R = ZZ
            I_gens, a = witness
        else:
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]

    # H_1: R is a commutative ring
    try:
        h1 = (R in (ZZ, QQ)) or hasattr(R, 'is_commutative') or hasattr(R, 'to_sympy')
    except Exception:
        h1 = False

    # H_2: I is an ideal of R (represented by a list/tuple/set of generators)
    try:
        if isinstance(I_gens, (list, tuple, set)):
            if R == ZZ:
                h2 = all(isinstance(g, int) or g in ZZ for g in I_gens)
            else:
                h2 = all(g in R for g in I_gens)
        else:
            h2 = False
    except Exception:
        h2 = False

    # H_3: a is an element of R
    try:
        if R == ZZ:
            h3 = isinstance(a, int) or a in ZZ
        else:
            h3 = a in R
    except Exception:
        h3 = False

    # ¬Q: I and (a) are NOT comaximal in R
    # Comaximal means I + (a) = R, i.e., 1 is in the ideal generated by I_gens and a.
    try:
        if R == ZZ:
            gens = [int(g) for g in I_gens] + [int(a)]
            g = reduce(math.gcd, gens)
            neg_q = (g != 1 and g != -1)
        else:
            gens = list(I_gens) + [a]
            free_symbols = set()
            for g in gens:
                if isinstance(g, Expr):
                    free_symbols.update(g.free_symbols)
            
            if free_symbols:
                try:
                    gb = groebner(gens, *free_symbols, domain=R)
                except Exception:
                    gb = groebner(gens, *free_symbols)
                # If 1 is in the ideal, the reduced Groebner basis is [1]
                neg_q = not (len(gb) == 1 and gb[0] == 1)
            else:
                # If no free symbols and not ZZ, check if all generators are 0
                is_zero = all(g == 0 for g in gens)
                neg_q = is_zero
    except Exception:
        neg_q = False

    return [bool(h1), bool(h2), bool(h3), bool(neg_q)]