def conditions(witness):
    try:
        _ = witness * witness + witness
        h1 = True
    except Exception:
        h1 = False

    h2 = True

    try:
        neg_q = False
        if hasattr(witness, 'is_square') and witness.is_square:
            if hasattr(witness, 'as_explicit'):
                W = witness.as_explicit()
            else:
                W = witness
            n = W.shape[0]
            for i in range(n):
                for j in range(n):
                    E = zeros(n, n)
                    E[i, j] = 1
                    diff = W * E - E * W
                    if hasattr(diff, 'expand'):
                        diff = diff.expand()
                    
                    if hasattr(diff, 'is_zero_matrix'):
                        if diff.is_zero_matrix is True:
                            is_zero = True
                        elif diff.is_zero_matrix is False:
                            is_zero = False
                        else:
                            is_zero = all(e == 0 for e in diff)
                    else:
                        is_zero = all(e == 0 for e in diff)
                        
                    if not is_zero:
                        neg_q = True
                        break
                if neg_q:
                    break
        else:
            if getattr(witness, 'is_commutative', True) is False:
                neg_q = True
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

