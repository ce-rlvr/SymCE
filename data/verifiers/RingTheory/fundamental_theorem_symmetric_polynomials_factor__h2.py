def conditions(witness) -> list[bool]:
    """
    Checks if the witness is a valid counterexample to the conjecture.
    The theorem holds for all non-zero commutative rings. The dropped hypothesis
    is that R is a non-zero ring (since over the zero ring, the rank of a free 
    module is not uniquely defined, thus failing the strict definition of having rank n!).
    """
    try:
        # Check if witness is the zero ring
        if witness == 0 or str(witness) in ["Z1", "ZeroRing", "0", "trivial"]:
            return [True, True, True]
            
        # If witness is a tuple (R, n) or (n, R)
        if isinstance(witness, tuple) and len(witness) >= 1:
            for item in witness:
                if item == 0 or str(item) in ["Z1", "ZeroRing", "0", "trivial"]:
                    return [True, True, True]
            
            # If it's a valid tuple but not the zero ring, the theorem holds (neg_Q is False)
            return [True, True, False]
                
        # If witness is just an integer n > 0, it implicitly assumes a non-zero ring like QQ or ZZ
        if isinstance(witness, int):
            n = witness
            if n <= 0:
                return [False, False, False]
            return [True, True, False]
            
        return [False, False, False]
    except Exception:
        return [False, False, False]

