import sympy
from sympy import S

# Top-level setup: named object bindings
Z = S.Integers

def conditions(witness) -> list[bool]:
    """
    Check if the witness is a valid counterexample to the false conjecture.
    The missing hypothesis is that I must be a proper ideal.
    A valid witness is an ideal I = R (e.g., generated by 1 in Z).
    """
    # Case 1: Witness is explicitly the ring of integers, representing I = Z in R = Z.
    try:
        if witness == S.Integers:
            # H1: Z is a PID (True)
            # H2: Z is not a field (True)
            # neg_Q: Intersection of Z^n is Z, which is not {0} (True)
            return [True, True, True]
    except Exception:
        pass

    # Case 2: Witness is a tuple (R, I)
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            R, I = witness
            if R == S.Integers:
                if I == S.Integers:
                    return [True, True, True]
                elif isinstance(I, (int, sympy.Integer)):
                    return [True, True, abs(int(I)) == 1]
    except Exception:
        pass

    # Case 3: Witness is an integer, representing the generator of the ideal I in R = Z.
    try:
        if isinstance(witness, (int, sympy.Integer)):
            val = int(witness)
            # H1: Z is a PID (True)
            # H2: Z is not a field (True)
            # neg_Q: Intersection of (val)^n is not {0} iff |val| == 1
            return [True, True, abs(val) == 1]
    except Exception:
        pass

    # If witness doesn't match known forms or fails checks
    return [False, False, False]

