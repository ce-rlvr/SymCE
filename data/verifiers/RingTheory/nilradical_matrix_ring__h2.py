CONDITION_LABELS = [
    "H_1: R is a commutative ring",
    "H_2: n is a positive integer",
    "¬Q: The lower nilradical of the matrix ring M_n(R) is not equal to the matrix ring M_n(N)"
]

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The dropped hypothesis from the true theorem was "N is the lower nilradical of R".
    Therefore, the witness should be a tuple (R, n, N) where N is NOT the lower nilradical of R.
    """
    try:
        R, n, N = witness
    except Exception:
        return [False, False, False]
    
    # H_1: R is a commutative ring
    h1 = False
    try:
        if isinstance(R, int) and R > 0:
            # An integer > 0 can represent the commutative ring Z/RZ
            h1 = True
        elif hasattr(R, 'is_commutative'):
            h1 = bool(R.is_commutative)
        elif R in [sympy.ZZ, sympy.QQ, sympy.RR, sympy.CC]:
            h1 = True
    except Exception:
        pass

    # H_2: n is a positive integer
    h2 = False
    try:
        if isinstance(n, int) and n > 0:
            h2 = True
    except Exception:
        pass

    # ¬Q: The lower nilradical of M_n(R) is NOT equal to M_n(N)
    # The lower nilradical of M_n(R) is M_n(P(R)), where P(R) is the lower nilradical of R.
    # Thus, the conclusion fails if and only if N is NOT the lower nilradical of R.
    neg_q = False
    try:
        if isinstance(R, int) and R > 0:
            # For Z/RZ, the lower nilradical is generated by the product of its distinct prime factors.
            factors = sympy.ntheory.primefactors(R)
            rad = 1
            for p in factors:
                rad *= p
            
            if isinstance(N, int):
                # N represents the ideal generated by N in Z/RZ.
                # It is the lower nilradical if gcd(N, R) == rad.
                neg_q = math.gcd(N, R) != rad
            else:
                neg_q = True
        else:
            # For standard domains like ZZ, QQ, RR, CC, the lower nilradical is the zero ideal.
            if N == 0 or N == {0} or N == [0] or N == sympy.S.Zero:
                neg_q = False
            else:
                neg_q = True
    except Exception:
        pass

    return [h1, h2, neg_q]