# Top-level setup: named object bindings that the witness expression may reference.
# Since SymPy does not natively support localizations or abstract non-Noetherian rings,
# we provide mock classes for the witness to represent the counterexample ring.

class Ring:
    """
    Mock object to represent a ring with specific abstract properties.
    """
    def __init__(self, krull_dimension=0, is_maximal_ideal_principal=False, is_dvr=False):
        self.krull_dimension = krull_dimension
        self.is_maximal_ideal_principal = is_maximal_ideal_principal
        self.is_dvr = is_dvr

class LocalRing(Ring):
    """
    Mock object to represent a local ring with specific abstract properties.
    """
    pass


def conditions(witness) -> list[bool]:
    """
    Evaluates the hypotheses and the negated conclusion for the given witness.
    Returns [H_1_ok, H_2_ok, neg_Q_ok].
    """
    
    # H_1: The Krull dimension of R is 1
    try:
        if isinstance(witness, dict):
            if "krull_dimension" in witness:
                h1 = int(witness["krull_dimension"]) == 1
            elif "dim" in witness:
                h1 = int(witness["dim"]) == 1
            else:
                h1 = False
        elif isinstance(witness, tuple) and len(witness) >= 1:
            h1 = int(witness[0]) == 1
        else:
            if hasattr(witness, "krull_dimension"):
                h1 = int(witness.krull_dimension) == 1
            elif hasattr(witness, "dim"):
                h1 = int(witness.dim) == 1
            else:
                h1 = False
    except Exception:
        h1 = False

    # H_2: The maximal ideal of R is generated by a single element
    try:
        if isinstance(witness, dict):
            if "is_maximal_ideal_principal" in witness:
                h2 = bool(witness["is_maximal_ideal_principal"])
            elif "maximal_ideal_generators" in witness:
                h2 = int(witness["maximal_ideal_generators"]) == 1
            else:
                h2 = False
        elif isinstance(witness, tuple) and len(witness) >= 2:
            h2 = bool(witness[1])
        else:
            if hasattr(witness, "is_maximal_ideal_principal"):
                h2 = bool(witness.is_maximal_ideal_principal)
            elif hasattr(witness, "maximal_ideal_generators"):
                h2 = int(witness.maximal_ideal_generators) == 1
            else:
                h2 = False
    except Exception:
        h2 = False

    # neg_Q: R is not a Discrete Valuation Ring (DVR)
    try:
        if isinstance(witness, dict):
            if "is_dvr" in witness:
                neg_q = not bool(witness["is_dvr"])
            elif "is_discrete_valuation_ring" in witness:
                neg_q = not bool(witness["is_discrete_valuation_ring"])
            else:
                neg_q = False
        elif isinstance(witness, tuple) and len(witness) >= 3:
            neg_q = not bool(witness[2])
        else:
            if hasattr(witness, "is_dvr"):
                neg_q = not bool(witness.is_dvr)
            elif hasattr(witness, "is_discrete_valuation_ring"):
                neg_q = not bool(witness.is_discrete_valuation_ring)
            else:
                neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]


