import sympy
from sympy import Poly
from sympy.polys.domains import ZZ, QQ, RR, CC
from sympy.abc import x, y, z

def is_homog(g):
    try:
        if hasattr(g, 'as_expr'):
            expr = g.as_expr()
        else:
            expr = g
        if isinstance(expr, (int, float)) or getattr(expr, 'is_number', False):
            return True
        p = Poly(expr)
        return p.is_homogeneous
    except Exception:
        return False

def conditions(witness):
    if isinstance(witness, dict):
        R = witness.get('R')
        n = witness.get('n')
        I = witness.get('I')
    elif isinstance(witness, (tuple, list)) and len(witness) == 3:
        R, n, I = witness
    else:
        R, n, I = None, None, None

    h1_ok = False
    try:
        if R is not None:
            if hasattr(R, 'is_commutative'):
                h1_ok = bool(R.is_commutative)
            elif R in [ZZ, QQ, RR, CC]:
                h1_ok = True
            elif hasattr(R, 'is_CommutativeRing') and R.is_CommutativeRing:
                h1_ok = True
    except Exception:
        pass

    h2_ok = False
    try:
        if isinstance(n, int) and n > 0:
            h2_ok = True
    except Exception:
        pass

    h3_ok = False
    try:
        if I is not None:
            if hasattr(I, 'gens'):
                gens = I.gens
            elif isinstance(I, (list, tuple, set)):
                gens = I
            else:
                gens = None
            
            if gens is not None:
                all_homog = True
                for g in gens:
                    if not is_homog(g):
                        all_homog = False
                        break
                h3_ok = all_homog
    except Exception:
        pass

    neg_q_ok = False
    try:
        if I is not None:
            if isinstance(I, (list, tuple, set)):
                neg_q_ok = True
            elif not hasattr(I, 'ring'):
                neg_q_ok = True
            else:
                ring = I.ring
                if not hasattr(ring, 'gens') or len(ring.gens) != n:
                    neg_q_ok = True
                elif not hasattr(ring, 'domain'):
                    neg_q_ok = True
                else:
                    domain = ring.domain
                    if domain == R or str(domain) == str(R):
                        neg_q_ok = False
                    elif str(R) == 'Integers' and str(domain) == 'ZZ':
                        neg_q_ok = False
                    elif str(R) == 'Rationals' and str(domain) == 'QQ':
                        neg_q_ok = False
                    elif str(R) == 'Reals' and str(domain) == 'RR':
                        neg_q_ok = False
                    elif str(R) == 'Complexes' and str(domain) == 'CC':
                        neg_q_ok = False
                    else:
                        neg_q_ok = True
    except Exception:
        pass

    return [h1_ok, h2_ok, h3_ok, neg_q_ok]

