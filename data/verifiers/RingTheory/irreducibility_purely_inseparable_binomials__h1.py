import sympy as sp
from sympy.abc import x, y, z, t

QQ = sp.QQ
ZZ = sp.ZZ

CONDITION_LABELS = [
    "H_1: a is an element of K",
    "H_2: a is not a p-th power of any element in K",
    "¬Q: x^p - a is reducible over K"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    X = sp.Symbol('X_dummy_var_for_poly')
    
    try:
        if len(witness) == 3:
            K, p, a = witness
            domain = K
        elif len(witness) == 2:
            p, a = witness
            domain = None
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]
        
    # H1: a is an element of K
    try:
        if domain is not None:
            # Check if 'a' can be coerced into the specified domain
            domain.to_sympy(domain.from_sympy(a))
            h1 = True
        else:
            # If no domain is specified, 'a' is trivially in the field generated by its coefficients
            h1 = True
    except Exception:
        h1 = False

    # H2: a is not a p-th power of any element in K
    try:
        poly_expr = X**p - a
        if domain is not None:
            facs = sp.factor_list(poly_expr, domain=domain)[1]
        else:
            facs = sp.factor_list(poly_expr)[1]
            
        # 'a' is a p-th power in K iff X^p - a has a root in K, 
        # which is equivalent to having a linear factor over K.
        has_linear = any(sp.degree(f, X) == 1 for f, m in facs)
        h2 = not has_linear
    except Exception:
        h2 = False

    # neg_Q: x^p - a is reducible over K
    try:
        poly_expr = X**p - a
        if domain is not None:
            facs = sp.factor_list(poly_expr, domain=domain)[1]
        else:
            facs = sp.factor_list(poly_expr)[1]
            
        if p <= 1:
            neg_q = False
        else:
            # A polynomial is reducible if it has more than one irreducible factor (counting multiplicity)
            total_factors = sum(m for f, m in facs)
            neg_q = total_factors > 1
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]