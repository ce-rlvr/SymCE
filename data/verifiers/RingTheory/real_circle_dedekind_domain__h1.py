import sympy
from sympy import symbols

x, y = symbols('x y')

def conditions(witness) -> list[bool]:
    h1 = False
    neg_q = False
    f = x**2 + y**2 - 1
    
    try:
        is_ring = False
        if witness in [sympy.ZZ, sympy.QQ, sympy.RR, sympy.CC]:
            is_ring = True
        elif hasattr(witness, 'is_Ring') and witness.is_Ring:
            is_ring = True
            
        if is_ring:
            h1 = True
            if witness == sympy.ZZ:
                neg_q = True
            else:
                char = getattr(witness, 'characteristic', lambda: 0)()
                if char == 2:
                    neg_q = True
                elif not getattr(witness, 'is_Field', True):
                    neg_q = True
                else:
                    neg_q = False
        else:
            if witness == f:
                h1 = True
            elif isinstance(witness, tuple) and f in witness:
                h1 = True
            elif hasattr(witness, 'gens') and f in witness.gens:
                h1 = True
            elif "x**2" in str(witness) and "y**2" in str(witness):
                h1 = True
                
            if h1:
                neg_q = True
                
    except Exception:
        pass

    return [h1, neg_q]

