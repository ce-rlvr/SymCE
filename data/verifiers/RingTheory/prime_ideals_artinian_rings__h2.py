def parse_witness(witness):
    """
    Parses the witness into a tuple (n, m) representing the ring Z/nZ 
    and the ideal generated by m.
    """
    if isinstance(witness, dict):
        n = int(witness.get('n', 0))
        m = int(witness.get('m', 0))
        return n, m
    if hasattr(witness, "__iter__") and not isinstance(witness, str):
        w = list(witness)
        if len(w) >= 2:
            return int(w[0]), int(w[1])
        elif len(w) == 1:
            return int(w[0]), 0
    return int(witness), 0

def conditions(witness) -> list[bool]:
    try:
        n, m = parse_witness(witness)
        # R = Z/nZ is a commutative Artinian ring with identity iff n >= 2
        h1 = (n >= 2)
    except Exception:
        h1 = False

    try:
        n, m = parse_witness(witness)
        if n < 2:
            neg_q = False
        else:
            # In Z/nZ, the ideal generated by m is identical to the ideal generated by gcd(n, m).
            # This ideal is maximal if and only if gcd(n, m) is a prime number.
            g = sympy.gcd(n, m)
            is_maximal = sympy.isprime(g)
            neg_q = not is_maximal
    except Exception:
        neg_q = False

    return [h1, neg_q]

