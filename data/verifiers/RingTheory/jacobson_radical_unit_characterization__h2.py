N_HYP = 3
NEG_Q_INDEX = 3

def conditions(witness):
    h1, h2, h3, neg_q = False, False, False, False
    
    # 1. Try object-oriented witness
    try:
        R = witness.R
        x = witness.x
        y = witness.y
        h1 = bool(R.is_commutative and R.has_identity)
        h2 = bool(x in R.J())
        h3 = bool(y in R)
        neg_q = not bool(R.is_unit(R.one - x * y))
        return [h1, h2, h3, neg_q]
    except Exception:
        pass

    # 2. Try dictionary or tuple witness representing Z/nZ
    try:
        witness_tuple = None
        if isinstance(witness, dict) and 'n' in witness:
            witness_tuple = (int(witness['n']), int(witness['x']), int(witness['y']))
        elif isinstance(witness, (tuple, list)):
            if len(witness) == 3:
                witness_tuple = (int(witness[0]), int(witness[1]), int(witness[2]))
            elif len(witness) == 4 and witness[0] == 'Zn':
                witness_tuple = (int(witness[1]), int(witness[2]), int(witness[3]))
            elif len(witness) == 3 and witness[0] == 'Z':
                witness_tuple = (0, int(witness[1]), int(witness[2]))

        if witness_tuple is not None:
            n, x, y = witness_tuple
            h1 = True  # Z/nZ is a commutative ring with identity
            
            if n == 0:
                # Ring is Z
                h2 = (x == 0)  # J(Z) = {0}
                h3 = True
                neg_q = (abs(1 - x * y) != 1)
            elif abs(n) == 1:
                # Ring is trivial ring {0}
                h2 = True
                h3 = True
                neg_q = False  # 0 is a unit in the trivial ring
            else:
                # Ring is Z/nZ
                n_abs = abs(n)
                primes = factorint(n_abs).keys()
                rad = 1
                for p in primes:
                    rad *= p
                
                # J(Z/nZ) is the ideal generated by the radical of n
                h2 = (x % rad == 0)
                h3 = True
                
                val = (1 - x * y) % n_abs
                neg_q = (math.gcd(val, n_abs) != 1)
                
            return [h1, h2, h3, neg_q]
    except Exception:
        pass

    return [h1, h2, h3, neg_q]