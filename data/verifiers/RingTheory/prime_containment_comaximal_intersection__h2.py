import sympy
from sympy import lcm
from sympy.abc import x, y, z

# Top-level setup for potential witness expressions
ZZ = sympy.S.Integers
QQ = sympy.S.Rationals

def extract_gen(val):
    """Helper to extract an integer generator from various possible witness formats."""
    if hasattr(val, 'gens'):
        val = val.gens[0]
    if isinstance(val, (tuple, list, set)):
        val = list(val)[0]
    return int(val)

def conditions(witness) -> list[bool]:
    """
    Checks the hypotheses and negated conclusion for the conjecture:
    "If P is a prime ideal and I \cap J \subseteq P, then either I \subseteq P or J \subseteq P, but not both."
    
    We evaluate this in the ring of integers Z, where ideals are generated by a single integer.
    The witness is expected to provide the generators for P, I, and J.
    """
    try:
        if isinstance(witness, dict):
            p = witness.get('P', witness.get('p'))
            a = witness.get('I', witness.get('a', witness.get('i')))
            b = witness.get('J', witness.get('b', witness.get('j')))
            if p is None or a is None or b is None:
                return [False, False, False]
        elif len(witness) == 3:
            p, a, b = witness
        elif len(witness) == 4:
            # Ignore the ring identifier if provided as (R, P, I, J)
            _, p, a, b = witness
        else:
            return [False, False, False]
        
        p = extract_gen(p)
        a = extract_gen(a)
        b = extract_gen(b)
    except Exception:
        return [False, False, False]

    # H_1: P is a prime ideal
    # In Z, an ideal (p) is prime iff |p| is prime or 0.
    try:
        p_abs = abs(p)
        h1_ok = (p_abs == 0) or sympy.isprime(p_abs)
    except Exception:
        h1_ok = False

    # H_2: I \cap J \subseteq P
    # In Z, I \cap J is generated by lcm(a, b). Subset means p divides lcm(a, b).
    try:
        intersection_gen = lcm(a, b)
        if p == 0:
            h2_ok = (intersection_gen == 0)
        else:
            h2_ok = (intersection_gen % p == 0)
    except Exception:
        h2_ok = False

    # ¬Q: It is NOT the case that exactly one of I or J is contained in P
    # The conclusion is (I \subseteq P) XOR (J \subseteq P).
    # We want the negation of this conclusion to be True.
    try:
        if p == 0:
            i_sub = (a == 0)
            j_sub = (b == 0)
        else:
            i_sub = (a % p == 0)
            j_sub = (b % p == 0)
        
        neg_q_ok = not (i_sub ^ j_sub)
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, neg_q_ok]

