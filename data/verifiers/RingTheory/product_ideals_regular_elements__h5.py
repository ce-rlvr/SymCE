CONDITION_LABELS = [
    "H_1: R is a commutative ring",
    "H_2: I is an ideal of R",
    "H_3: J is an ideal of R",
    "H_4: I contains at least one regular element",
    "¬Q: The product ideal IJ contains NO regular elements"
]

N_HYP = 4
NEG_Q_INDEX = 4

def conditions(witness):
    res = [False, False, False, False, False]
    try:
        R, I, J = witness
    except Exception:
        return res

    try:
        # Case 1: R is an integer n >= 2 (representing Z_n)
        if isinstance(R, (int, sympy.Integer)) and R >= 1:
            n = int(R)
            if n > 1000:  # Prevent performance issues with excessively large rings
                return res
            res[0] = True
            
            try:
                I_set = set(I)
                J_set = set(J)
            except Exception:
                return res
                
            def is_ideal(S):
                if not S: return False
                if not all(isinstance(x, (int, sympy.Integer)) and 0 <= x < n for x in S): return False
                # Check additive closure
                for a in S:
                    for b in S:
                        if (a + b) % n not in S: return False
                # Check absorbing property
                for a in S:
                    for r in range(n):
                        if (a * r) % n not in S: return False
                return True
                
            res[1] = is_ideal(I_set)
            res[2] = is_ideal(J_set)
            
            def is_regular(x):
                for y in range(n):
                    if (x * y) % n == 0 and y != 0:
                        return False
                return True
                
            res[3] = any(is_regular(x) for x in I_set)
            
            # Compute the product ideal IJ
            IJ_gens = {(a * b) % n for a in I_set for b in J_set}
            IJ_set = set(IJ_gens)
            added = True
            # Additive closure of the products
            while added:
                added = False
                for a in list(IJ_set):
                    for b in list(IJ_set):
                        if (a + b) % n not in IJ_set:
                            IJ_set.add((a + b) % n)
                            added = True
                            
            res[4] = not any(is_regular(x) for x in IJ_set)
            return res

        # Case 2: R is sympy.ZZ or sympy.S.Integers
        if R in (sympy.ZZ, sympy.S.Integers):
            res[0] = True
            
            def get_gen(ideal_rep):
                if isinstance(ideal_rep, (int, sympy.Integer)):
                    return int(ideal_rep)
                if ideal_rep in (sympy.ZZ, sympy.S.Integers):
                    return 1
                if isinstance(ideal_rep, (set, list, tuple)):
                    if len(ideal_rep) == 0:
                        return 0
                    if all(isinstance(x, (int, sympy.Integer)) for x in ideal_rep):
                        g = 0
                        for x in ideal_rep:
                            g = math.gcd(g, int(x))
                        return g
                return None
                
            gen_I = get_gen(I)
            gen_J = get_gen(J)
            
            if gen_I is not None:
                res[1] = True
            if gen_J is not None:
                res[2] = True
                
            if gen_I is not None and gen_J is not None:
                # In ZZ, regular elements are exactly the non-zero elements
                res[3] = (gen_I != 0)
                # IJ is generated by gen_I * gen_J. It contains no regular elements iff it is the zero ideal.
                res[4] = (gen_I * gen_J == 0)
                
            return res
            
    except Exception:
        pass

    return res