import sympy
import math
from sympy import S

# Top-level setup
# We use the integers Z as our commutative ring.
Z = S.Integers

def conditions(witness) -> list[bool]:
    """
    Expects a witness of the form (R_name, S_gens, q, p) or (S_gens, q, p)
    where:
      - R_name is 'Z' or sympy.S.Integers
      - S_gens is a list of integers generating the multiplicatively closed set S
      - q is the integer generating the P-primary ideal Q
      - p is the prime integer generating the prime ideal P
    """
    try:
        if len(witness) == 4:
            R_name, S_gens, q, p = witness
        elif len(witness) == 3:
            S_gens, q, p = witness
            R_name = 'Z'
        else:
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]
        
    try:
        # H_1: R is a commutative ring with identity
        h1 = bool(R_name == 'Z' or R_name == Z)
    except Exception:
        h1 = False
        
    try:
        # H_2: S is a multiplicatively closed subset of R
        if isinstance(S_gens, (int, sympy.Integer)):
            S_gens = [S_gens]
        h2 = bool(isinstance(S_gens, (list, set, tuple)) and all(isinstance(x, (int, sympy.Integer)) for x in S_gens))
    except Exception:
        h2 = False
        
    try:
        # H_3: Q is a P-primary ideal of R
        # In Z, P is generated by prime p, and Q is generated by q = p^n (n >= 1)
        if not isinstance(p, (int, sympy.Integer)) or not isinstance(q, (int, sympy.Integer)):
            h3 = False
        elif not sympy.isprime(p):
            h3 = False
        else:
            n = 1
            temp = p
            while temp < q and n < 10000:
                temp *= p
                n += 1
            h3 = bool((temp == q) and (q > 1))
    except Exception:
        h3 = False
        
    try:
        # ¬Q: The contraction of the extended ideal (S^{-1}Q)^c in R is not equal to Q
        # The contraction of Q=(q) in Z is generated by min_{s \in S} (q / gcd(q, s)).
        # The contraction equals Q iff gcd(q, s) == 1 for all s \in S.
        # Since S is generated by S_gens, this holds iff gcd(q, g) == 1 for all g \in S_gens.
        if not (h1 and h2 and h3):
            neg_q = False
        else:
            conclusion_holds = all(math.gcd(int(q), int(g)) == 1 for g in S_gens)
            neg_q = not conclusion_holds
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

