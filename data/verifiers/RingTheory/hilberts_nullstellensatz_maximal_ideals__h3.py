import sympy
from sympy import symbols

# Top-level setup: named object bindings that the witness expression may reference.
x1, x2, x3, x4, x5 = symbols('x1 x2 x3 x4 x5')

def is_ideal_generated_by_linear(M_gens_list, expected_vars, all_vars):
    """
    Helper function to check if the ideal generated by M_gens_list in the polynomial ring
    k[all_vars] is exactly generated by {v - a_v | v in expected_vars}.
    """
    if not M_gens_list:
        return False
    try:
        # Compute the Groebner basis of the ideal
        gb = sympy.groebner(M_gens_list, *all_vars).polys
    except Exception:
        return False
    
    # The reduced Groebner basis must have exactly the same number of elements as expected_vars
    if len(gb) != len(expected_vars):
        return False
        
    matched_vars = set()
    for poly in gb:
        expr = poly.as_expr()
        # Find which variables from all_vars are present in this basis polynomial
        vars_in_expr = [v for v in all_vars if expr.has(v)]
        
        # It must contain exactly one variable from all_vars
        if len(vars_in_expr) != 1:
            return False
            
        v = vars_in_expr[0]
        
        # That variable must be one of the expected variables
        if v not in expected_vars:
            return False
            
        # The polynomial must be linear in that variable
        if expr.degree(v) != 1:
            return False
            
        matched_vars.add(v)
        
    # Ensure all expected variables are covered
    return len(matched_vars) == len(expected_vars)

def conditions(witness) -> list[bool]:
    """
    Given a witness tuple: (k_name, n, num_vars, M_gens_list)
    where:
      - k_name is a string representing the field (e.g., 'CC')
      - n is the integer from the hypothesis
      - num_vars is the number of variables in the ring R = k[x_1, ..., x_{num_vars}] where M lives
      - M_gens_list is a list of sympy expressions generating the ideal M in R
    """
    try:
        k_name, n, num_vars, M_gens_list = witness
    except Exception:
        return [False, False, False]
        
    # H_1: k is an algebraically closed field
    try:
        h1_ok = isinstance(k_name, str) and k_name in ['CC', 'C', 'AlgebraicField']
    except Exception:
        h1_ok = False
        
    # H_2: n >= 1 is an integer
    try:
        h2_ok = isinstance(n, int) and n >= 1
    except Exception:
        h2_ok = False
        
    # ¬Q: The conclusion FAILS at the witness.
    # Conclusion: M is a maximal ideal iff M is generated by n polynomials of the form x_i - a_i.
    try:
        if not isinstance(num_vars, int) or num_vars < 1:
            neg_q_ok = False
        else:
            # Evaluate P: "M is a maximal ideal"
            # In k[x_1, ..., x_{num_vars}], an ideal is maximal iff it is generated by num_vars linear polynomials.
            vars_m = [sympy.Symbol(f'x{i}') for i in range(1, num_vars + 1)]
            p_true = is_ideal_generated_by_linear(M_gens_list, vars_m, vars_m)
            
            # Evaluate Q: "M is generated by x_1 - a_1, ..., x_n - a_n"
            # We check this in a ring large enough to contain both the ideal's variables and x_1...x_n.
            max_vars = max(n, num_vars)
            vars_q_all = [sympy.Symbol(f'x{i}') for i in range(1, max_vars + 1)]
            vars_q_exp = [sympy.Symbol(f'x{i}') for i in range(1, n + 1)]
            q_true = is_ideal_generated_by_linear(M_gens_list, vars_q_exp, vars_q_all)
            
            # The conclusion is P <==> Q. It fails when P != Q.
            neg_q_ok = bool(p_true != q_true)
    except Exception:
        neg_q_ok = False
        
    return [h1_ok, h2_ok, neg_q_ok]

