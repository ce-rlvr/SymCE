import sympy
from sympy import factor_list, isprime, Poly

def conditions(witness):
    """
    Checks if the witness is a counterexample to the false conjecture.
    The conjecture claims: M is a maximal ideal of R[[x]] iff M is generated by m and x
    for some maximal ideal m of R.
    """
    h1, h2, neg_q = False, False, False
    
    try:
        if hasattr(witness, 'R') and hasattr(witness, 'M'):
            R = witness.R
            M = witness.M
        elif isinstance(witness, tuple) and len(witness) == 2:
            R, M = witness
        else:
            M = witness
            R = M.ring.domain if hasattr(M, 'ring') else None

        if R is not None:
            if hasattr(R, 'is_commutative'):
                h1 = bool(R.is_commutative)
            else:
                h1 = True
        else:
            if hasattr(witness, 'is_commutative_ring'):
                h1 = bool(witness.is_commutative_ring)
            else:
                h1 = True

        if hasattr(M, 'ring') or hasattr(M, 'is_ideal'):
            h2 = True
        elif hasattr(witness, 'is_ideal'):
            h2 = bool(witness.is_ideal)
        else:
            h2 = True

        P = False
        Q = False
        
        if hasattr(witness, 'P') and hasattr(witness, 'Q'):
            P = bool(witness.P)
            Q = bool(witness.Q)
        else:
            if hasattr(witness, 'is_maximal'):
                P = bool(witness.is_maximal)
            elif hasattr(M, 'is_maximal'):
                P = bool(M.is_maximal() if callable(M.is_maximal) else M.is_maximal)
            elif hasattr(M, 'ring'):
                ring = M.ring
                domain = ring.domain
                gens = M.groebner_basis() if hasattr(M, 'groebner_basis') else M.gens
                
                if domain.is_Field:
                    if len(gens) == 1:
                        f = gens[0]
                        x_sym = ring.gens[0].as_expr()
                        poly = Poly(f.as_expr(), x_sym, domain=domain)
                        if poly.is_irreducible:
                            P = True
                elif domain.is_IntegerRing:
                    if len(gens) == 2:
                        g1, g2 = gens
                        t1 = g1.terms()
                        t2 = g2.terms()
                        is_p = lambda t: len(t) == 1 and sum(t[0][0]) == 0 and isprime(abs(t[0][1]))
                        p = None
                        f = None
                        if is_p(t1):
                            p = abs(t1[0][1])
                            f = g2
                        elif is_p(t2):
                            p = abs(t2[0][1])
                            f = g1
                        if p is not None:
                            x_sym = ring.gens[0].as_expr()
                            poly = Poly(f.as_expr(), x_sym, modulus=p)
                            if poly.is_irreducible:
                                P = True

            if hasattr(witness, 'is_generated_by_m_and_x'):
                Q = bool(witness.is_generated_by_m_and_x)
            elif hasattr(M, 'is_generated_by_m_and_x'):
                Q = bool(M.is_generated_by_m_and_x() if callable(M.is_generated_by_m_and_x) else M.is_generated_by_m_and_x)
            elif hasattr(M, 'ring'):
                ring = M.ring
                domain = ring.domain
                gens = M.groebner_basis() if hasattr(M, 'groebner_basis') else M.gens
                
                if domain.is_Field:
                    if len(gens) == 1:
                        f = gens[0]
                        terms = f.terms()
                        if len(terms) == 1 and sum(terms[0][0]) == 1 and terms[0][0][0] == 1:
                            Q = True
                elif domain.is_IntegerRing:
                    if len(gens) == 2:
                        g1, g2 = gens
                        t1 = g1.terms()
                        t2 = g2.terms()
                        is_x = lambda t: len(t) == 1 and sum(t[0][0]) == 1 and t[0][0][0] == 1 and abs(t[0][1]) == 1
                        is_p = lambda t: len(t) == 1 and sum(t[0][0]) == 0 and isprime(abs(t[0][1]))
                        if (is_x(t1) and is_p(t2)) or (is_x(t2) and is_p(t1)):
                            Q = True

        neg_q = (P != Q)

    except Exception:
        pass

    return [h1, h2, neg_q]

