import sympy
from sympy import Poly, gcd, ZZ, QQ, sympify
from sympy.abc import x
from sympy import groebner

# Top-level setup: named object bindings that the witness expression may reference.
# The witness may use ZZ, QQ, and x.

def parse_witness(witness):
    if isinstance(witness, tuple):
        if len(witness) == 3:
            domain, p1, p2 = witness
            if isinstance(domain, str):
                if domain == 'ZZ':
                    domain = ZZ
                elif domain == 'QQ':
                    domain = QQ
                else:
                    raise ValueError("Unsupported domain")
        elif len(witness) == 2:
            domain = ZZ
            p1, p2 = witness
        else:
            raise ValueError("Witness must be a tuple of length 2 or 3")
        
        p1 = sympify(p1, locals={'x': x})
        p2 = sympify(p2, locals={'x': x})
            
        return domain, p1, p2
    raise ValueError("Witness must be a tuple")

def check_h1(witness):
    try:
        domain, p1, p2 = parse_witness(witness)
        if not p1.free_symbols.issubset({x}): return False
        if not p2.free_symbols.issubset({x}): return False
        Poly(p1, x, domain=domain)
        Poly(p2, x, domain=domain)
        return True
    except Exception:
        return False

def check_h2(witness):
    try:
        domain, p1, p2 = parse_witness(witness)
        g = gcd(p1, p2, domain=domain)
        poly_g = Poly(g, x, domain=domain)
        if poly_g.degree() == 0:
            c = poly_g.LC()
            if domain.is_Field:
                return c != 0
            else:
                return abs(c) == 1
        return False
    except Exception:
        return False

def is_one_in_ideal(p1, p2, domain):
    try:
        gb = groebner([p1, p2], x, domain=domain)
        for poly in gb.polys:
            if poly.degree() == 0:
                c = poly.LC()
                if domain.is_Field:
                    if c != 0:
                        return True
                else:
                    if abs(c) == 1:
                        return True
        return False
    except Exception:
        return False

def check_neg_q(witness):
    try:
        domain, p1, p2 = parse_witness(witness)
        # The rings F[x]/(p1*p2) and F[x]/(p1) x F[x]/(p2) are isomorphic
        # if and only if the ideal generated by p1 and p2 is the whole ring F[x].
        # The conclusion fails (they are NOT isomorphic) iff 1 is NOT in the ideal (p1, p2).
        return not is_one_in_ideal(p1, p2, domain)
    except Exception:
        return False

def conditions(witness):
    return [
        check_h1(witness),
        check_h2(witness),
        check_neg_q(witness)
    ]

