import sympy
from sympy.ntheory import factorint

# Top-level setup
Z = sympy.Symbol('Z')

def conditions(witness):
    """
    Checks if the witness is a counterexample to the conjecture:
    "In a PID, I is a primary ideal iff I = (p^n) for some prime p and n >= 1."
    
    The dropped hypothesis from the true theorem is that I must be a NON-ZERO ideal.
    Thus, the zero ideal in any PID (e.g., Z) is a valid counterexample.
    """
    try:
        # Extract the generator of the ideal.
        # The witness could be the generator itself, or a tuple like (Ring, generator).
        if isinstance(witness, tuple) and len(witness) == 2:
            I = witness[1]
        else:
            I = witness
            
        if hasattr(I, 'is_zero') and I.is_zero:
            k = 0
        else:
            k = int(I)
            
        # H_1: R is a Principal Ideal Domain.
        # We evaluate the properties in the ring of integers Z, which is a PID.
        h1_ok = True
        
        # Evaluate if the ideal (k) is primary in Z.
        # In Z, (0) is prime (hence primary). Proper non-zero ideals are primary iff they are prime powers.
        if k == 0:
            is_primary = True
        elif abs(k) == 1:
            is_primary = False
        else:
            factors = factorint(abs(k))
            is_primary = (len(factors) == 1)
            
        # Evaluate if the ideal (k) is of the form (p^n) for prime p and n >= 1.
        if k == 0 or abs(k) == 1:
            is_pn = False
        else:
            factors = factorint(abs(k))
            is_pn = (len(factors) == 1)
            
        # ¬Q: The conclusion fails if the equivalence does not hold.
        neg_q_ok = (is_primary != is_pn)
        
        return [h1_ok, neg_q_ok]
    except Exception:
        return [False, False]

