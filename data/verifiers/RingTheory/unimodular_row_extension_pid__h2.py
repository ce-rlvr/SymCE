def conditions(witness):
    h1_ok = False
    vec = None
    try:
        # Handle potential (R, v) tuple where R is a domain and v is the vector
        if isinstance(witness, tuple) and len(witness) == 2:
            if isinstance(witness[1], (list, tuple, Matrix)):
                witness = witness[1]

        if isinstance(witness, Matrix):
            if witness.rows == 1 or witness.cols == 1:
                vec = list(witness)
        elif isinstance(witness, (list, tuple)):
            vec = list(witness)
            
        if vec is not None and len(vec) > 0:
            # Check if all elements are integers. 
            # The ring of integers ZZ is a Principal Ideal Domain (PID).
            if all(isinstance(x, int) or (hasattr(x, 'is_integer') and x.is_integer) for x in vec):
                h1_ok = True
    except Exception:
        h1_ok = False

    neg_q_ok = False
    try:
        if h1_ok and vec is not None:
            # For R = ZZ, an invertible n x n matrix exists with first row v 
            # if and only if the ideal generated by the elements of v is the whole ring ZZ.
            # This is equivalent to the greatest common divisor of the elements being 1.
            # If gcd != 1, no such invertible matrix exists (conclusion fails).
            g = reduce(gcd, vec)
            if abs(g) != 1:
                neg_q_ok = True
    except Exception:
        neg_q_ok = False

    return [h1_ok, neg_q_ok]

