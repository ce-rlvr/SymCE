def conditions(witness):
    """
    witness is expected to be a dictionary with:
      'R': list of elements in the finite ring
      'add': callable(x, y) for ring addition
      'mul': callable(x, y) for ring multiplication
      'neg': callable(x) for additive inverse
      'zero': the additive identity element
      'S': list of elements (generators for ideal I)
      'T': list of elements (generators for ideal J)
      'I': (optional) list of elements in ideal I
      'J': (optional) list of elements in ideal J
    """
    try:
        R = witness['R']
        add = witness['add']
        mul = witness['mul']
        neg = witness['neg']
        zero = witness['zero']
        S = witness['S']
        T = witness['T']
    except Exception:
        return [False, False, False]

    def is_ring():
        # check closure
        for a in R:
            if neg(a) not in R: return False
            for b in R:
                if add(a, b) not in R: return False
                if mul(a, b) not in R: return False
        # check axioms
        for a in R:
            if add(a, zero) != a: return False
            if add(zero, a) != a: return False
            if add(a, neg(a)) != zero: return False
            if add(neg(a), a) != zero: return False
            for b in R:
                if add(a, b) != add(b, a): return False
                for c in R:
                    if add(add(a, b), c) != add(a, add(b, c)): return False
                    if mul(mul(a, b), c) != mul(a, mul(b, c)): return False
                    if mul(a, add(b, c)) != add(mul(a, b), mul(a, c)): return False
                    if mul(add(a, b), c) != add(mul(a, c), mul(b, c)): return False
        return True

    def get_ideal(generators):
        closure = []
        for g in generators:
            if g not in closure:
                closure.append(g)
        if zero not in closure:
            closure.append(zero)
            
        changed = True
        while changed:
            if len(closure) > 1000:
                raise ValueError("Ideal too large or infinite")
            changed = False
            new_elements = []
            for x in closure:
                nx = neg(x)
                if nx not in closure and nx not in new_elements:
                    new_elements.append(nx)
                for y in closure:
                    s = add(x, y)
                    if s not in closure and s not in new_elements:
                        new_elements.append(s)
                for r in R:
                    p1 = mul(r, x)
                    if p1 not in closure and p1 not in new_elements:
                        new_elements.append(p1)
                    p2 = mul(x, r)
                    if p2 not in closure and p2 not in new_elements:
                        new_elements.append(p2)
            if new_elements:
                closure.extend(new_elements)
                changed = True
        return closure

    def set_eq(A, B):
        return all(a in B for a in A) and all(b in A for b in B)

    try:
        h1_ring = is_ring()
        h1_S = all(s in R for s in S)
        I = witness.get('I', get_ideal(S))
        h1_I = set_eq(I, get_ideal(S))
        h1 = h1_ring and h1_S and h1_I
    except Exception:
        h1 = False

    try:
        h2_T = all(t in R for t in T)
        J = witness.get('J', get_ideal(T))
        h2_J = set_eq(J, get_ideal(T))
        h2 = h2_T and h2_J
    except Exception:
        h2 = False

    try:
        if not (h1 and h2):
            neg_q = False
        else:
            # Compute the product ideal IJ
            IJ_generators = [mul(x, y) for x in I for y in J]
            IJ = get_ideal(IJ_generators)
            
            # Compute the ideal generated by {st | s in S, t in T}
            ST_generators = [mul(s, t) for s in S for t in T]
            ST_ideal = get_ideal(ST_generators)
            
            # The conclusion is that IJ is generated by ST.
            # We negate this conclusion.
            neg_q = not set_eq(IJ, ST_ideal)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

