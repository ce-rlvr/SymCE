def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness is expected to represent two ideals M1 and M2.
    It can be a tuple (g1, g2) of generators, or (ring_name, g1, g2).
    """
    try:
        if isinstance(witness, tuple) and len(witness) == 3:
            ring, g1, g2 = witness
        elif isinstance(witness, tuple) and len(witness) == 2:
            g1, g2 = witness
            ring = None
        else:
            return [False, False, False]
            
        # Extract single generators if provided as 1-element lists/tuples
        if isinstance(g1, (list, tuple)) and len(g1) == 1:
            g1 = g1[0]
        if isinstance(g2, (list, tuple)) and len(g2) == 1:
            g2 = g2[0]
            
        # Auto-detect ring if not specified
        if ring is None:
            if hasattr(g1, 'free_symbols') and g1.free_symbols:
                ring = "Q[x]"
            elif hasattr(g2, 'free_symbols') and g2.free_symbols:
                ring = "Q[x]"
            else:
                ring = "Z"
                
        # H_1: R is a commutative ring with identity
        h1 = ring in ("Z", "Q[x]", "R[x]", "C[x]")
        
        # H_2: M_1 != M_2
        # In a PID, two ideals are equal iff their generators divide each other
        if ring == "Z":
            h2 = abs(int(g1)) != abs(int(g2))
        else:
            if g1 == 0 and g2 == 0:
                h2 = False
            elif g1 == 0 or g2 == 0:
                h2 = True
            else:
                q1, r1 = div(g1, g2)
                q2, r2 = div(g2, g1)
                if r1 == 0 and r2 == 0:
                    h2 = False
                else:
                    h2 = True
                    
        # ¬Q: M_1 + M_2 != R
        # M_1 + M_2 is generated by gcd(g1, g2). It equals R iff the gcd is a unit.
        g = gcd(g1, g2)
        if ring == "Z":
            neg_q = abs(int(g)) != 1
        else:
            if g == 0:
                neg_q = True
            else:
                neg_q = degree(g) > 0
                
        return [bool(h1), bool(h2), bool(neg_q)]
    except Exception:
        return [False, False, False]

