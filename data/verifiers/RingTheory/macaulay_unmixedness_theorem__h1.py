import sympy
from sympy import symbols, groebner, reduced, cancel, fraction
import sympy.abc as abc

# Top-level setup for witness expressions
x, y, z, w, u, v = symbols('x y z w u v')

def in_ideal(p, I_gens, vars_list):
    if not I_gens:
        return sympy.expand(p) == 0
    try:
        gb = groebner(I_gens, *vars_list)
        _, rem = reduced(p, gb, *vars_list)
        return sympy.expand(rem) == 0
    except Exception:
        return False

def ideal_intersection(A_gens, B_gens, vars_list):
    if not A_gens or not B_gens:
        return []
    t = symbols('__t_intersect__')
    tA = [t * a for a in A_gens]
    one_minus_t_B = [(1 - t) * b for b in B_gens]
    try:
        gb = groebner(tA + one_minus_t_B, t, *vars_list, order='lex')
        intersection_gens = []
        for p in gb:
            if t not in p.free_symbols:
                intersection_gens.append(p)
        return intersection_gens
    except Exception:
        return []

def check_h1(witness):
    """
    Check Hypothesis 1: I is a proper ideal of R generated by a regular sequence of length k.
    Witness format: (vars_list, J_gens, I_gens, P_gens, x_elem, Q_gens)
    where R = k[vars_list] / J_gens, and I is generated by I_gens modulo J_gens.
    """
    try:
        vars_list, J_gens, I_gens, P_gens, x_elem, Q_gens = witness
        k = len(I_gens)
        if k < 1:
            return False
        
        for i in range(k):
            a_i = I_gens[i]
            K = J_gens + I_gens[:i]
            
            # a_i must not be in K (otherwise it's a zero divisor)
            if in_ideal(a_i, K, vars_list):
                return False
            
            # a_i must be a non-zero-divisor modulo K
            # This is true iff K \cap (a_i) \subseteq a_i K
            if K:
                int_gens = ideal_intersection(K, [a_i], vars_list)
                a_i_K = [a_i * k_gen for k_gen in K]
                for g in int_gens:
                    if not in_ideal(g, a_i_K, vars_list):
                        return False
                        
        # I must be a proper ideal
        if in_ideal(sympy.S.One, J_gens + I_gens, vars_list):
            return False
            
        return True
    except Exception:
        return False

def check_neg_q(witness):
    """
    Check Negated Conclusion: I has an associated prime of height != k, or I has embedded primes.
    We verify that P = (I : x_elem) is an embedded prime by showing it strictly contains 
    another prime Q which contains I.
    """
    try:
        vars_list, J_gens, I_gens, P_gens, x_elem, Q_gens = witness
        
        # P_gens and Q_gens must be subsets of the variables to easily guarantee primality
        if not set(P_gens).issubset(set(vars_list)):
            return False
        if not set(Q_gens).issubset(set(vars_list)):
            return False
            
        # Q must be strictly contained in P
        if not (set(Q_gens) < set(P_gens)):
            return False
            
        # J must vanish when P_gens are 0, meaning J \subseteq (P_gens)
        subs_P = {v: 0 for v in P_gens}
        if any(sympy.expand(j.subs(subs_P)) != 0 for j in J_gens):
            return False
            
        # J must vanish when Q_gens are 0, meaning J \subseteq (Q_gens)
        subs_Q = {v: 0 for v in Q_gens}
        if any(sympy.expand(j.subs(subs_Q)) != 0 for j in J_gens):
            return False
            
        # I must vanish when Q_gens are 0, meaning I \subseteq (Q_gens)
        if any(sympy.expand(i.subs(subs_Q)) != 0 for i in I_gens):
            return False
            
        K_gens = J_gens + I_gens
        
        # x_elem must not be in I
        if in_ideal(x_elem, K_gens, vars_list):
            return False
            
        # P * x_elem \subseteq I
        for p in P_gens:
            if not in_ideal(p * x_elem, K_gens, vars_list):
                return False
                
        # (I : x_elem) \subseteq P
        int_gens = ideal_intersection(K_gens, [x_elem], vars_list)
        for g in int_gens:
            q_expr = sympy.cancel(g / x_elem)
            num, den = sympy.fraction(q_expr)
            if den != 1:
                return False
            q = num
            if sympy.expand(q.subs(subs_P)) != 0:
                return False
                
        return True
    except Exception:
        return False

def conditions(witness) -> list[bool]:
    return [check_h1(witness), check_neg_q(witness)]

