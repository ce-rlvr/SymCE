import sympy
from sympy.ntheory import factorint
from sympy import Poly
import math
from sympy.abc import x, y, z
from sympy import Rational, Integer

def conditions(witness):
    # 1. Try interpreting the witness as an integer ideal or a pair of integers (R, I)
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            n, m = witness
        else:
            n = 0
            m = witness
            
        # Prevent floats from being silently truncated
        if isinstance(n, float) or isinstance(m, float):
            raise ValueError
        # Prevent SymPy symbols from being converted to int
        if isinstance(n, sympy.Expr) and not n.is_Integer:
            raise ValueError
        if isinstance(m, sympy.Expr) and not m.is_Integer:
            raise ValueError
            
        n_int = int(n)
        m_int = int(m)
        
        # In Z/nZ, any integer m defines an ideal generated by gcd(n, m)
        if n_int == 0:
            m_eff = m_int
        else:
            m_eff = math.gcd(n_int, m_int)
            
        h1 = True
        
        # The quotient ring is Z/m_eff Z.
        # It is semisimple iff it is a finite product of fields, 
        # which happens iff m_eff is square-free and non-zero.
        if m_eff == 0:
            neg_q = True
        elif abs(m_eff) == 1:
            neg_q = False
        else:
            factors = factorint(abs(m_eff))
            is_sq_free = all(v == 1 for v in factors.values())
            neg_q = not is_sq_free
            
        return [h1, neg_q]
    except Exception:
        pass

    # 2. Try interpreting the witness as a polynomial ideal or a pair (R_poly, I_poly)
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            R_poly, I_poly = witness
        else:
            I_poly = witness
            
        f = Poly(I_poly)
        h1 = True
        
        # The quotient ring k[x]/<f> is semisimple iff f is square-free and non-zero.
        if f.is_zero:
            neg_q = True
        elif f.degree() == 0:
            neg_q = False
        else:
            neg_q = not f.is_squarefree
            
        return [h1, neg_q]
    except Exception:
        pass

    return [False, False]

