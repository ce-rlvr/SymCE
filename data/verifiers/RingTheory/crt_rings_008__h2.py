import math
from sympy.ntheory import factorint

# Top-level setup
# No special named objects are required for this ring theory conjecture.
# The witness is expected to be a list of integers representing generators 
# of ideals in the ring of integers Z, or a similar structure.

def get_elem_divs(m):
    """
    Computes the elementary divisors of the group of units of Z/mZ.
    Returns a sorted list of prime powers.
    """
    if m == 0:
        # The group of units of Z is {1, -1}, which is isomorphic to Z_2.
        return [2]
    if m == 1 or m == -1:
        # The group of units of Z/1Z (the zero ring) is {0}, the trivial group.
        return []
    
    m = abs(m)
    factors = factorint(m)
    invs = []
    
    for p, k in factors.items():
        if p == 2:
            if k == 1:
                pass
            elif k == 2:
                invs.append(2)
            else:
                invs.append(2)
                invs.append(2**(k-2))
        else:
            phi = (p**(k-1)) * (p - 1)
            invs.append(phi)
            
    elem_divs = []
    for n in invs:
        f = factorint(n)
        for q, e in f.items():
            elem_divs.append(q**e)
            
    return sorted(elem_divs)

def conditions(witness) -> list[bool]:
    """
    Evaluates the remaining hypotheses and the negated conclusion at the witness.
    The witness is expected to be a list of integers [m_1, ..., m_n] representing
    ideals I_k = m_k Z in the ring R = Z.
    """
    try:
        if not isinstance(witness, list):
            return [False, False, False]
            
        # H1: R is a commutative ring with identity.
        # For R = Z, this is always True.
        h1 = True
        
        # H2: I_i + I_j = R for all i != j.
        # In Z, this means gcd(m_i, m_j) == 1 for all i != j.
        h2 = True
        for i in range(len(witness)):
            for j in range(i+1, len(witness)):
                if math.gcd(witness[i], witness[j]) != 1:
                    h2 = False
                    break
            if not h2:
                break
                
        # neg_Q: The group of units (R/(\bigcap_{k=1}^n I_k))^\times is NOT isomorphic 
        # to \prod_{k=1}^n (R/I_k)^\times.
        # We compute the elementary divisors of both sides to check for isomorphism.
        
        # Left side: intersection of ideals is generated by the LCM of the generators.
        lcm_val = 1
        if len(witness) == 0:
            # Intersection of an empty family of ideals in Z is Z itself (generated by 1).
            lcm_val = 1
        else:
            for m in witness:
                if m == 0:
                    lcm_val = 0
                    break
                lcm_val = (lcm_val * m) // math.gcd(lcm_val, m)
                
        left_divs = get_elem_divs(lcm_val)
        
        # Right side: direct product of the unit groups of Z/m_k Z.
        right_divs = []
        for m in witness:
            right_divs.extend(get_elem_divs(m))
        right_divs.sort()
        
        neg_q = (left_divs != right_divs)
        
        return [h1, h2, neg_q]
        
    except Exception:
        return [False, False, False]

