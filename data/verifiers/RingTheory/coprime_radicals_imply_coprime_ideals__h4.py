import sympy
from sympy import ZZ, QQ, Symbol, S

# Top-level setup for potential witness expressions
x = Symbol('x')
Z = ZZ
Q = QQ

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "If R is a commutative ring, I and J are ideals of R, then I + J = R."
    
    A valid witness is a tuple (R, I, J) where:
      - R is a SymPy domain (e.g., ZZ, QQ, or QQ.old_poly_ring(x))
      - I is a list of generators for the first ideal
      - J is a list of generators for the second ideal
    """
    try:
        R, I, J = witness
    except Exception:
        return [False, False, False, False]

    def normalize_gens(gens):
        if hasattr(gens, 'gens'):
            try:
                return list(gens.gens)
            except Exception:
                pass
        if isinstance(gens, (list, tuple, set)):
            return list(gens)
        return [gens]

    # H_1: R is a commutative ring
    try:
        h1 = isinstance(R, sympy.polys.domains.domain.Domain) or R in (sympy.S.Integers, sympy.S.Rationals)
    except Exception:
        h1 = False

    # H_2: I is an ideal of R
    try:
        I_gens = normalize_gens(I)
        h2 = all(g in R for g in I_gens)
    except Exception:
        h2 = False

    # H_3: J is an ideal of R
    try:
        J_gens = normalize_gens(J)
        h3 = all(g in R for g in J_gens)
    except Exception:
        h3 = False

    # ¬Q: I + J != R
    # I + J = R iff the ideal generated by I_gens U J_gens contains 1 (i.e., their gcd is a unit in R)
    try:
        from sympy import sympify, gcd
        I_sym = [sympify(g) for g in I_gens]
        J_sym = [sympify(g) for g in J_gens]
        
        g_val = 0
        for gen in I_sym + J_sym:
            g_val = gcd(g_val, gen)
            
        if R == sympy.ZZ or R == sympy.S.Integers:
            # In Z, the only units are 1 and -1
            neg_q = (abs(g_val) != 1)
        elif R == sympy.QQ or R == sympy.S.Rationals:
            # In Q, any non-zero element is a unit
            neg_q = (g_val == 0)
        else:
            # For polynomial rings or other domains, check if g_val is a non-zero constant
            if hasattr(g_val, 'is_constant'):
                is_unit = g_val.is_constant() and g_val != 0
            elif hasattr(g_val, 'is_number'):
                is_unit = g_val.is_number and g_val != 0
            else:
                is_unit = (g_val in [1, -1])
            neg_q = not is_unit
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

