import sympy
import math

# Top-level setup
# No special objects needed; we use integers to represent ideals in the ring of integers Z.
# A witness is expected to be a tuple of three integers (I, J, P) representing the ideals (I), (J), and (P).

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, tuple) and len(witness) == 3:
            I, J, P = witness
        elif isinstance(witness, list) and len(witness) == 3:
            I, J, P = witness
        else:
            return [False, False, False, False]
            
        if not isinstance(I, (int, sympy.Integer)) or \
           not isinstance(J, (int, sympy.Integer)) or \
           not isinstance(P, (int, sympy.Integer)):
            return [False, False, False, False]
            
        I = abs(int(I))
        J = abs(int(J))
        P = abs(int(P))
    except Exception:
        return [False, False, False, False]

    # H_1: I and J are comaximal ideals of R
    # In Z, ideals (I) and (J) are comaximal iff gcd(I, J) == 1
    try:
        h1 = (math.gcd(I, J) == 1)
    except Exception:
        h1 = False

    # H_2: P is a prime ideal of R
    # In Z, (P) is a prime ideal iff P is 0, 1, or a prime number.
    # Note: The conjecture dropped the "proper" hypothesis, so P=1 is allowed as a prime ideal.
    try:
        h2 = (P == 0 or P == 1 or sympy.isprime(P))
    except Exception:
        h2 = False

    # H_3: I \cap J \subseteq P
    # In Z, I \cap J is generated by lcm(I, J).
    # (A) \subseteq (B) iff B divides A.
    try:
        lcm_IJ = math.lcm(I, J)
        if P == 0:
            h3 = (lcm_IJ == 0)
        else:
            h3 = (lcm_IJ % P == 0)
    except Exception:
        h3 = False

    # ¬Q: It is not the case that exactly one of I \subseteq P or J \subseteq P holds
    # I \subseteq P iff P divides I
    # J \subseteq P iff P divides J
    try:
        if P == 0:
            i_in_p = (I == 0)
            j_in_p = (J == 0)
        else:
            i_in_p = (I % P == 0)
            j_in_p = (J % P == 0)
            
        # Q is true if exactly one of them is a subset of P
        q = (i_in_p != j_in_p)
        neg_q = not q
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

