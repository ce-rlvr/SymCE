import sympy
from sympy.abc import x, y, z

CONDITION_LABELS = [
    "H_1: R is a commutative Noetherian ring",
    "H_2: I is a proper ideal of R",
    "¬Q: There does not exist x in R \\ I such that (I:x) = P"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    try:
        # The witness is expected to be a tuple (I_gens, P_gens) or (R, I_gens, P_gens)
        # representing the generators of the ideals I and P.
        if isinstance(witness, tuple):
            if len(witness) == 2:
                I_raw, P_raw = witness
            elif len(witness) == 3:
                _, I_raw, P_raw = witness
            else:
                return [False, False, False]
        else:
            return [False, False, False]

        def get_principal_gen(gens):
            if not isinstance(gens, (list, tuple, set)):
                gens = [gens]
            gens = list(gens)
            if len(gens) == 0:
                return sympy.S(0)
            g = sympy.sympify(gens[0])
            for i in range(1, len(gens)):
                g = sympy.gcd(g, sympy.sympify(gens[i]))
            return g

        I_val = get_principal_gen(I_raw)
        P_val = get_principal_gen(P_raw)

        is_poly = False
        if hasattr(I_val, 'free_symbols') and len(I_val.free_symbols) > 0:
            is_poly = True
        elif hasattr(P_val, 'free_symbols') and len(P_val.free_symbols) > 0:
            is_poly = True

        # Z and Q[x] are commutative Noetherian rings
        h1 = True

        if is_poly:
            I_expr = sympy.sympify(I_val)
            P_expr = sympy.sympify(P_val)

            if I_expr == 0:
                h2 = True
            else:
                # In Q[x], a proper ideal cannot be generated by a non-zero constant
                h2 = len(I_expr.free_symbols) > 0

            if I_expr == 0:
                neg_q = (P_expr != 0)
            elif P_expr == 0:
                neg_q = True
            else:
                # Check if P divides I in Q[x]
                ratio = sympy.cancel(I_expr / P_expr)
                denom = ratio.as_numer_denom()[1]
                
                if len(denom.free_symbols) == 0:
                    # P divides I. Let A = I / P. Then (I:A) = P.
                    # We need A \notin I, which means I does not divide A.
                    # This is true iff P is not a unit (not a constant).
                    if len(P_expr.free_symbols) > 0:
                        neg_q = False
                    else:
                        neg_q = True
                else:
                    neg_q = True
        else:
            I_sym = sympy.sympify(I_val)
            P_sym = sympy.sympify(P_val)
            
            if not I_sym.is_integer or not P_sym.is_integer:
                return [False, False, False]
            
            I_int = abs(int(I_sym))
            P_int = abs(int(P_sym))

            # In Z, proper ideal means it's not generated by 1
            h2 = (I_int != 1)

            if I_int == 0:
                neg_q = (P_int != 0)
            elif P_int == 0:
                neg_q = True
            else:
                # Check if P divides I in Z
                if I_int % P_int == 0 and P_int > 1:
                    neg_q = False
                else:
                    neg_q = True

        return [bool(h1), bool(h2), bool(neg_q)]
    except Exception:
        return [False, False, False]