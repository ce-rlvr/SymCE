import sympy
from sympy import symbols, S
from sympy.abc import x, y, z
from math import gcd
from functools import reduce
from sympy.ntheory import factorint, isprime

# Top-level setup for the namespace
ZZ = S.Integers
QQ = S.Rationals

def conditions(witness):
    try:
        ints = []
        polys = []
        
        def extract(obj):
            if isinstance(obj, (int, sympy.Integer)):
                ints.append(int(obj))
            elif isinstance(obj, sympy.Expr) and obj.free_symbols:
                polys.append(obj)
            elif hasattr(obj, 'gens'):
                for g in obj.gens:
                    extract(g)
            elif isinstance(obj, (tuple, list, set)):
                for item in obj:
                    extract(item)
                    
        extract(witness)
        
        # If both integers and polynomials are present, it's an ambiguous or mixed ideal
        if ints and polys:
            return [False, False]
            
        if ints:
            gen = abs(reduce(gcd, ints))
            
            # Check if primary in Z
            if gen == 1:
                h1 = False
            elif gen == 0:
                h1 = True
            else:
                h1 = len(factorint(gen)) == 1
                
            # Check if not maximal in Z
            neg_q = not isprime(gen)
            
            return [bool(h1), bool(neg_q)]
            
        elif polys:
            from sympy import gcd as poly_gcd
            from sympy import factor_list
            
            gen = reduce(poly_gcd, polys)
            
            if gen == 0:
                return [True, True]
                
            try:
                factors = factor_list(gen)
            except Exception:
                return [False, False]
                
            # Check if primary in F[x] (power of a single irreducible)
            if len(factors[1]) == 0:
                h1 = False
            elif len(factors[1]) == 1:
                h1 = True
            else:
                h1 = False
                
            # Check if not maximal
            all_symbols = set()
            for p in polys:
                all_symbols.update(p.free_symbols)
                
            # A principal ideal is maximal iff it's generated by an irreducible polynomial in 1 variable
            if len(factors[1]) == 1 and factors[1][0][1] == 1 and len(all_symbols) <= 1:
                neg_q = False
            else:
                neg_q = True
                
            return [bool(h1), bool(neg_q)]
            
    except Exception:
        pass
        
    return [False, False]

