import sympy as sp
from sympy import Poly
import math

# Top-level setup
x = sp.Symbol('x')

CONDITION_LABELS = [
    "H_1: a is an element of R",
    "H_2: f is the constant polynomial defined by f(x) = a",
    "¬Q: The content ideal c(f) is not equal to the principal ideal (a)"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    try:
        # Fallback for pre-evaluated witness
        if isinstance(witness, dict) and 'h1' in witness:
            return [
                bool(witness.get('h1', False)),
                bool(witness.get('h2', False)),
                bool(witness.get('neg_q', False))
            ]

        n = None
        a = None
        f_expr = None

        # Extract witness components
        if isinstance(witness, dict):
            if 'n' in witness:
                n = int(witness['n'])
            elif 'R' in witness:
                n = int(witness['R'])
            a = witness.get('a')
            f_expr = witness.get('f')
        elif isinstance(witness, (tuple, list)):
            if len(witness) == 3:
                n, a, f_expr = witness
            elif len(witness) == 2:
                a, f_expr = witness
        else:
            if hasattr(witness, 'n'):
                n = int(witness.n)
            elif hasattr(witness, 'R'):
                n = int(witness.R)
            a = getattr(witness, 'a', None)
            f_expr = getattr(witness, 'f', None)

        if f_expr is None or a is None:
            return [False, False, False]

        f = Poly(f_expr, x)
        
        # Infer the ring Z/nZ if not explicitly provided
        if n is None:
            if f.domain.is_FiniteField:
                n = f.domain.order
            else:
                n = max(2, int(a) + 1)
                for test_n in range(2, 20):
                    a_mod = int(a) % test_n
                    if all(int((f.eval(v) - a_mod) % test_n) == 0 for v in range(test_n)):
                        c_f_test = test_n
                        for c in f.all_coeffs():
                            c_f_test = math.gcd(c_f_test, int(sp.sympify(c)) % test_n)
                        if c_f_test != math.gcd(a_mod, test_n):
                            n = test_n
                            break

        n = int(n)
        a = int(a) % n

        # H1: a is an element of R
        # In our model, a is an integer modulo n, which is always an element of Z/nZ
        h1 = True

        # H2: f is the constant polynomial defined by f(x) = a
        # i.e., the polynomial function evaluates to a for all elements in Z/nZ
        h2 = all(int((f.eval(v) - a) % n) == 0 for v in range(n))

        # ¬Q: c(f) != (a)
        # In Z/nZ, the ideal generated by a set of elements is the principal ideal 
        # generated by the GCD of those elements and n.
        coeffs = f.all_coeffs()
        c_f = n
        for c in coeffs:
            c_val = int(sp.sympify(c)) % n
            c_f = math.gcd(c_f, c_val)
            
        ideal_a = math.gcd(a, n)

        neg_q = (c_f != ideal_a)

        return [h1, h2, neg_q]
    
    except Exception:
        return [False, False, False]