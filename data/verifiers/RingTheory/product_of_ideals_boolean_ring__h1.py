def extract_gen(ideal):
    """Helper to extract the generator if an actual principal ideal object is passed."""
    if hasattr(ideal, 'gens') and len(ideal.gens) == 1:
        return ideal.gens[0]
    return ideal

def conditions(witness) -> list[bool]:
    # H_1: I and J are ideals of R
    try:
        if isinstance(witness, tuple):
            if len(witness) == 2:
                I, J = witness
            elif len(witness) == 3:
                R, I, J = witness
            else:
                return [False, False]
        else:
            return [False, False]
            
        I = extract_gen(I)
        J = extract_gen(J)
        
        I = sympy.sympify(I)
        J = sympy.sympify(J)
        
        # We represent ideals by their generators in Z or a polynomial ring.
        h1 = isinstance(I, (sympy.Integer, sympy.Expr)) and isinstance(J, (sympy.Integer, sympy.Expr))
    except Exception:
        h1 = False

    # ¬Q: IJ != I \cap J
    try:
        if isinstance(witness, tuple):
            if len(witness) == 2:
                I, J = witness
            elif len(witness) == 3:
                R, I, J = witness
            else:
                return [False, False]
        else:
            return [False, False]
            
        I = extract_gen(I)
        J = extract_gen(J)
        
        I = sympy.sympify(I)
        J = sympy.sympify(J)
        
        # The product ideal is generated by the product of the generators.
        prod_gen = sympy.simplify(I * J)
        # The intersection ideal is generated by the least common multiple of the generators.
        int_gen = sympy.lcm(I, J)
        
        if int_gen == 0:
            is_same_ideal = (prod_gen == 0)
        elif I.is_Integer and J.is_Integer:
            # In Z, ideals are equal iff their generators are equal up to sign.
            is_same_ideal = abs(prod_gen) == abs(int_gen)
        else:
            # In polynomial rings over a field, ideals are equal iff generators differ by a unit (constant).
            q1 = sympy.simplify(prod_gen / int_gen)
            is_same_ideal = q1.is_constant() and q1 != 0
            
        neg_q = not is_same_ideal
    except Exception:
        neg_q = False

    return [h1, neg_q]

