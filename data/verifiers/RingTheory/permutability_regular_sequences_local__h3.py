import sympy as sp
from itertools import permutations

# Top-level setup: named object bindings that the witness expression may reference.
# We provide standard variables for polynomial rings.
x, y, z, w, u, v = sp.symbols('x y z w u v')

def is_regular(vars, ideal_gens, seq):
    """
    Checks if `seq` is a regular sequence in the ring K[vars] / (ideal_gens).
    Assumes ideal_gens and seq consist of homogeneous polynomials, which makes
    the computation equivalent to checking regularity in the local ring K[vars]_{(vars)} / (ideal_gens).
    """
    if not vars:
        return len(seq) == 0
        
    J = list(ideal_gens)
    if not J:
        J = [0]
        
    for y_elem in seq:
        GB_J = list(sp.groebner(J, *vars, order='lex', domain='QQ'))
        
        # Check if y_elem is in J (i.e., y_elem == 0 in the quotient ring)
        rem = sp.reduced(y_elem, GB_J, *vars, order='lex')[1]
        if rem == 0:
            return False
            
        # Compute the intersection ideal J \cap (y_elem)
        t = sp.Symbol('t_intersect_var')
        I_temp = [t * g for g in J] + [(1 - t) * y_elem]
        GB_temp = list(sp.groebner(I_temp, t, *vars, order='lex', domain='QQ'))
        
        H = [h for h in GB_temp if t not in h.free_symbols]
        
        # Compute the ideal quotient J : y_elem and check if it is contained in J
        for h in H:
            q = sp.reduced(h, [y_elem], *vars, order='lex')[0][0]
            rem_q = sp.reduced(q, GB_J, *vars, order='lex')[1]
            if rem_q != 0:
                return False # y_elem is a zero divisor
                
        J.append(y_elem)
        
    # Check if the ideal generated by the sequence and J is the whole ring
    GB_J = list(sp.groebner(J, *vars, order='lex', domain='QQ'))
    if len(GB_J) == 1 and GB_J[0] == 1:
        return False
        
    return True

def conditions(witness):
    """
    Given a witness of the form (vars, ideal_gens, seq),
    returns a list of booleans: [H1, H2, H3, neg_Q].
    """
    try:
        vars, ideal_gens, seq = witness
    except Exception:
        return [False, False, False, False]
        
    # H_1: R is a commutative Noetherian ring
    # Our representation K[vars] / I is always a commutative Noetherian ring.
    h1 = True
    
    # H_2: R is a local ring with maximal ideal m
    # We interpret R as the localization K[vars]_{(vars)} / I.
    # We enforce that I is generated by homogeneous polynomials to ensure global Groebner bases
    # correctly compute syzygies for the local ring.
    try:
        h2 = True
        J_init = list(ideal_gens) if ideal_gens else [0]
        if not vars:
            if any(c != 0 for c in J_init):
                h2 = False
        else:
            GB_init = list(sp.groebner(J_init, *vars, order='lex', domain='QQ'))
            if len(GB_init) == 1 and GB_init[0] == 1:
                h2 = False
            for g in J_init:
                if g != 0 and not sp.Poly(g, *vars).is_homogeneous:
                    h2 = False
                    break
    except Exception:
        h2 = False
        
    # H_3: The elements x_1, x_2, ..., x_n belong to the maximal ideal m
    # They must evaluate to 0 at the origin and be homogeneous.
    try:
        h3 = True
        for y_elem in seq:
            if y_elem.subs({v: 0 for v in vars}) != 0:
                h3 = False
                break
            if y_elem != 0 and not sp.Poly(y_elem, *vars).is_homogeneous:
                h3 = False
                break
    except Exception:
        h3 = False
        
    # ¬Q: There exists a permutation \sigma such that the sequence is NOT regular
    try:
        neg_q = False
        for p in permutations(seq):
            if not is_regular(vars, ideal_gens, list(p)):
                neg_q = True
                break
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

