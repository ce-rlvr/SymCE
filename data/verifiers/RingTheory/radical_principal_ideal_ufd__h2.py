import sympy
from sympy import Rational, Integer
from sympy.abc import x, y, z

def conditions(witness):
    """
    Checks if the given witness is a valid counterexample to the false conjecture.
    The witness is expected to be a tuple: (a, u, primes, exponents)
    representing the element a, the unit u, the list of primes, and the list of exponents.
    All elements are evaluated in the UFD Z (the integers).
    """
    try:
        a, u, primes, exponents = witness
    except Exception:
        return [False, False, False]
        
    def is_int(val):
        return isinstance(val, (int, sympy.Integer))
        
    # H_1: R is a Unique Factorization Domain
    # We use R = Z, which is a UFD. We verify the witness components are valid integers/lists.
    try:
        h1 = (is_int(a) and is_int(u) and 
              isinstance(primes, (list, tuple)) and isinstance(exponents, (list, tuple)) and
              all(is_int(p) for p in primes) and 
              all(is_int(e) for e in exponents))
    except Exception:
        h1 = False

    # H_2: The prime factorization of a is u p_1^{e_1} \dots p_k^{e_k}, 
    # where u is a unit and p_1, \dots, p_k are pairwise non-associated prime elements
    try:
        if not h1:
            h2 = False
        else:
            # In Z, the only units are 1 and -1
            is_unit = (abs(u) == 1)
            
            # Check if all p_i are prime elements
            are_primes = all(sympy.isprime(abs(p)) for p in primes)
            
            # Check if p_i are pairwise non-associated (in Z, this means distinct absolute values)
            abs_primes = [abs(p) for p in primes]
            are_non_assoc = (len(abs_primes) == len(set(abs_primes)))
            
            # Exponents must be non-negative for a factorization in Z
            non_neg_exp = all(e >= 0 for e in exponents)
            
            if len(primes) != len(exponents):
                h2 = False
            else:
                # Check if the product actually equals a
                prod = u
                for p, e in zip(primes, exponents):
                    prod *= (p ** e)
                
                h2 = is_unit and are_primes and are_non_assoc and non_neg_exp and (prod == a)
    except Exception:
        h2 = False

    # ¬Q: The radical of the principal ideal (a) is NOT the principal ideal generated by the product p_1 p_2 \dots p_k
    try:
        if not h1:
            neg_q = False
        else:
            # Compute the generator of the radical of (a) in Z
            if a == 0:
                rad_a = 0
            else:
                factors = sympy.factorint(abs(a))
                rad_a = 1
                for p in factors:
                    rad_a *= p
            
            # Compute the product of the given primes
            b = 1
            for p in primes:
                b *= p
                
            # In Z, two principal ideals (x) and (y) are equal iff |x| == |y|
            # The conclusion fails if the ideals are NOT equal
            neg_q = (abs(rad_a) != abs(b))
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

