import math
from sympy.ntheory import factorint

# Top-level setup
# Witness is expected to be a tuple of three integers (m, a, b)
# representing the ring R = mZ, and ideals I = aZ, J = bZ.
# For example, witness = (2, 4, 4) represents R = 2Z, I = 4Z, J = 4Z.
# This provides a counterexample because R does not have an identity.

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, dict):
            m = witness.get('m', witness.get('R', None))
            a = witness.get('a', witness.get('I', None))
            b = witness.get('b', witness.get('J', None))
        else:
            m, a, b = witness
        m = int(m)
        a = int(a)
        b = int(b)
    except Exception:
        return [False, False, False]
        
    # H_1: I and J are ideals of R
    try:
        h1 = (m != 0) and (a % m == 0) and (b % m == 0)
    except Exception:
        h1 = False
        
    # H_2: \sqrt{I} and \sqrt{J} denote the radical ideals of I and J
    # This is true by definition in our evaluation logic
    h2 = h1
    
    # ¬Q: I and J are comaximal if and only if their radicals are comaximal
    try:
        # I and J are comaximal in R iff I + J = R
        # I + J is generated by gcd(a, b)
        I_comaximal_J = (math.gcd(a, b) == abs(m))
        
        def rad(n):
            if n == 0:
                return 0
            n = abs(n)
            if n == 1:
                return 1
            res = 1
            for p in factorint(n).keys():
                res *= p
            return res
            
        rad_a = rad(a)
        rad_b = rad(b)
        
        def lcm(x, y):
            if x == 0 or y == 0:
                return 0
            return abs(x * y) // math.gcd(x, y)
            
        # The radical of aZ in mZ is generated by lcm(m, rad(a))
        sqrt_I_gen = lcm(abs(m), rad_a)
        sqrt_J_gen = lcm(abs(m), rad_b)
        
        # \sqrt{I} and \sqrt{J} are comaximal in R iff \sqrt{I} + \sqrt{J} = R
        sqrt_I_comaximal_sqrt_J = (math.gcd(sqrt_I_gen, sqrt_J_gen) == abs(m))
        
        Q = (I_comaximal_J == sqrt_I_comaximal_sqrt_J)
        neg_q = not Q
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

