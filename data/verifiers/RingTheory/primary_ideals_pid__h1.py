import sympy as sp
from sympy import symbols
import math
from sympy.ntheory import factorint

x, y, z = symbols('x y z')

def conditions(witness) -> list[bool]:
    try:
        gens = list(witness)
    except Exception:
        return [False, False]
    
    if not gens:
        return [False, False]
        
    vars_set = set()
    for g in gens:
        if hasattr(g, 'free_symbols'):
            vars_set.update(g.free_symbols)
    vars_list = list(vars_set)
    vars_list.sort(key=lambda v: v.name)
    
    if not vars_list:
        try:
            nums = [int(g) for g in gens]
            g_val = nums[0]
            for n in nums[1:]:
                g_val = math.gcd(g_val, n)
            g_val = abs(g_val)
            
            if g_val == 0 or g_val == 1:
                h1 = False
                neg_q = True
            else:
                factors = factorint(g_val)
                if len(factors) == 1:
                    h1 = True
                    neg_q = False
                else:
                    h1 = False
                    neg_q = True
            return [h1, neg_q]
        except Exception:
            return [False, False]

    try:
        gb = sp.groebner(gens, *vars_list, domain='QQ')
        gb_list = list(gb)
    except Exception:
        return [False, False]
        
    h1 = False
    try:
        if len(gb_list) == 1 and gb_list[0] == 0:
            h1 = False
        elif len(gb_list) == 1 and gb_list[0] == 1:
            h1 = False
        else:
            is_monomial = True
            for g in gb_list:
                p = sp.Poly(g, *vars_list)
                if len(p.terms()) > 1:
                    is_monomial = False
                    break
            
            if is_monomial:
                is_primary = True
                for g in gb_list:
                    p = sp.Poly(g, *vars_list)
                    monom = p.terms()[0][0]
                    for i, exp in enumerate(monom):
                        if exp > 0:
                            has_pure = False
                            for g2 in gb_list:
                                p2 = sp.Poly(g2, *vars_list)
                                monom2 = p2.terms()[0][0]
                                is_pure = True
                                for j, exp2 in enumerate(monom2):
                                    if j != i and exp2 > 0:
                                        is_pure = False
                                        break
                                if is_pure and monom2[i] > 0:
                                    has_pure = True
                                    break
                            if not has_pure:
                                is_primary = False
                                break
                    if not is_primary:
                        break
                h1 = is_primary
            else:
                if len(gb_list) == 1:
                    f = gb_list[0]
                    factors = sp.factor_list(f)
                    if len(factors[1]) == 1:
                        h1 = True
                    else:
                        h1 = False
                else:
                    h1 = False
    except Exception:
        h1 = False

    neg_q = False
    try:
        if len(gb_list) > 1:
            neg_q = True
        else:
            f = gb_list[0]
            if f == 0 or f == 1:
                neg_q = True
            else:
                factors = sp.factor_list(f)
                if len(factors[1]) == 1:
                    neg_q = False
                else:
                    neg_q = True
    except Exception:
        neg_q = False

    return [h1, neg_q]

