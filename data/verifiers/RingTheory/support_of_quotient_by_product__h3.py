import sympy
from sympy import S, Rational
from sympy.ntheory import factorint
from sympy.abc import x, y, z

# Top-level setup for standard rings
ZZ = S.Integers
QQ = S.Rationals

def get_supp_Z(val):
    """
    Computes the support of the ideal generated by val in Z.
    Returns the set of prime factors, or 'all_primes' for the zero ideal.
    Raises ValueError if val is not a valid integer ideal generator.
    """
    if val == 0:
        return 'all_primes'
    if isinstance(val, (int, sympy.Integer)):
        if val in (1, -1):
            return set()
        return set(factorint(abs(val)).keys())
    raise ValueError("Not an ideal in Z")

def conditions(witness):
    """
    Checks whether the witness is a valid counterexample to the false conjecture.
    The witness should provide a ring R, an ideal I, and an object J.
    """
    try:
        if isinstance(witness, tuple) and len(witness) == 3:
            R, I, J = witness
        else:
            R = witness.R
            I = witness.I
            J = witness.J
    except Exception:
        return [False, False, False]

    # H_1: R is a commutative ring
    try:
        if R in (ZZ, QQ):
            h1 = True
        elif hasattr(R, 'is_commutative_ring'):
            h1 = R.is_commutative_ring()
        elif hasattr(R, 'is_commutative'):
            h1 = R.is_commutative
        else:
            h1 = False
    except Exception:
        h1 = False

    # H_2: I is an ideal of R
    try:
        if R == ZZ:
            h2 = isinstance(I, (int, sympy.Integer))
        elif R == QQ:
            h2 = isinstance(I, (int, sympy.Integer, sympy.Rational, float))
        elif hasattr(R, 'is_ideal'):
            h2 = R.is_ideal(I)
        elif hasattr(I, 'is_ideal'):
            h2 = I.is_ideal(R)
        else:
            h2 = False
    except Exception:
        h2 = False

    # ¬Q: Supp(R/(IJ)) != Supp(R/I) U Supp(R/J)
    try:
        if R == ZZ:
            supp_IJ = get_supp_Z(I * J)
            supp_I = get_supp_Z(I)
            supp_J = get_supp_Z(J)
            
            if supp_IJ == 'all_primes':
                q_ok = (supp_I == 'all_primes' or supp_J == 'all_primes')
            else:
                if supp_I == 'all_primes' or supp_J == 'all_primes':
                    q_ok = False
                else:
                    q_ok = (supp_IJ == supp_I.union(supp_J))
                    
        elif R == QQ:
            def get_supp_Q(val):
                if val == 0:
                    return {0}
                if isinstance(val, (int, sympy.Integer, sympy.Rational, float)):
                    return set()
                raise ValueError("Not an ideal in QQ")
            
            supp_IJ = get_supp_Q(I * J)
            supp_I = get_supp_Q(I)
            supp_J = get_supp_Q(J)
            q_ok = (supp_IJ == supp_I.union(supp_J))
            
        else:
            # Fallback for custom ring objects that implement their own `supp` method
            IJ = I * J
            
            def get_supp(ring, ideal):
                if hasattr(ring, 'supp'):
                    return ring.supp(ideal)
                if hasattr(ideal, 'supp'):
                    return ideal.supp(ring)
                raise ValueError("Supp not implemented for this ring/ideal")

            supp_IJ = get_supp(R, IJ)
            supp_I = get_supp(R, I)
            supp_J = get_supp(R, J)
            
            if supp_IJ == 'all_primes':
                q_ok = (supp_I == 'all_primes' or supp_J == 'all_primes')
            else:
                if supp_I == 'all_primes' or supp_J == 'all_primes':
                    q_ok = False
                else:
                    q_ok = (supp_IJ == supp_I.union(supp_J))
    except Exception:
        # If evaluation fails (e.g., J is not an ideal, making Supp(R/J) undefined),
        # the equality is considered to not hold.
        q_ok = False

    neg_q = not q_ok

    return [bool(h1), bool(h2), bool(neg_q)]

