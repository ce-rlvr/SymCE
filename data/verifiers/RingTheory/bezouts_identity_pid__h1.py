import sympy
from sympy import symbols, Poly, ZZ, QQ
from sympy.polys.polytools import groebner
from sympy.abc import x, y, z

# Top-level setup
# (No group theory or linear algebra objects needed for Ring Theory)

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness should be a tuple (a, b, d, domain) or (a, b, d) where domain defaults to ZZ.
    The ring R is implicitly the polynomial ring over `domain` generated by the free symbols in a, b, d.
    """
    try:
        if isinstance(witness, tuple):
            if len(witness) == 4:
                a, b, d, domain = witness
            elif len(witness) == 3:
                a, b, d = witness
                domain = ZZ
            else:
                return [False, False, False]
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]
        
    try:
        # Extract variables to define the polynomial ring
        gens = list(set().union(
            getattr(a, 'free_symbols', set()),
            getattr(b, 'free_symbols', set()),
            getattr(d, 'free_symbols', set())
        ))
        gens = sorted(gens, key=lambda s: s.name)
        if not gens:
            gens = [x] # Fallback to a single variable if a, b, d are constants
    except Exception:
        return [False, False, False]

    # H1: a and b are non-zero elements of R
    try:
        a_poly = Poly(a, *gens, domain=domain)
        b_poly = Poly(b, *gens, domain=domain)
        d_poly = Poly(d, *gens, domain=domain)
        h1 = (not a_poly.is_zero) and (not b_poly.is_zero)
    except Exception:
        h1 = False

    # H2: d is a greatest common divisor of a and b
    try:
        # Check if d divides a and b
        rem_a = a_poly.rem(d_poly)
        rem_b = b_poly.rem(d_poly)
        
        # Check if d is the greatest common divisor (associates with the actual gcd)
        g = a_poly.gcd(b_poly)
        rem_d = d_poly.rem(g)
        rem_g = g.rem(d_poly)
        
        h2 = rem_a.is_zero and rem_b.is_zero and rem_d.is_zero and rem_g.is_zero
    except Exception:
        h2 = False

    # neg_Q: There do NOT exist x, y in R such that d = ax + by
    try:
        # This is equivalent to checking if d is NOT in the ideal generated by a and b
        G = groebner([a, b], *gens, domain=domain)
        neg_q = not G.contains(d)
    except Exception:
        neg_q = False

    return [bool(h1), bool(h2), bool(neg_q)]

