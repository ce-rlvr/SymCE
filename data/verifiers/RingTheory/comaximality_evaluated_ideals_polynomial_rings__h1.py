def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the conjecture.
    The witness is expected to be a tuple (A, B, a) of sympy.Matrix objects representing
    elements in the matrix ring R = M_n(K).
    I is the two-sided ideal generated by (x - A) in R[x].
    J is the two-sided ideal generated by (x - B) in R[x].
    """
    try:
        if len(witness) != 3:
            return [False, False, False, False]
            
        A, B, a = witness
        
        if not (isinstance(A, sympy.Matrix) and isinstance(B, sympy.Matrix) and isinstance(a, sympy.Matrix)):
            return [False, False, False, False]
            
        n = a.shape[0]
        if n < 2 or a.shape[1] != n:
            return [False, False, False, False]
            
        if A.shape != (n, n) or B.shape != (n, n):
            return [False, False, False, False]
            
        # Check if A and B are scalar matrices.
        # This ensures x - A and x - B are central in R[x], making I(a) = R(a - A).
        I_n = sympy.eye(n)
        c1 = A[0, 0]
        c2 = B[0, 0]
        
        if A != c1 * I_n or B != c2 * I_n:
            return [False, False, False, False]
            
        # H_1: I and J are ideals in the polynomial ring
        h1 = True
        
        # H_2: I and J are comaximal in the polynomial ring
        # I + J = R[x] iff A - B is invertible. Since they are scalar, this means c1 != c2.
        h2 = bool(c1 != c2)
        
        # H_3: a is an element of R
        h3 = True
        
        # Conclusion: The evaluation ideals I(a) and J(a) are comaximal in R.
        # For I(a) and J(a) to be comaximal ideals, they must first actually be two-sided ideals in R.
        # I(a) = R(a - A) is a two-sided ideal in M_n(K) iff (a - A) is 0 or invertible.
        M_I = a - A
        M_J = a - B
        
        det_I = M_I.det()
        det_J = M_J.det()
        
        is_ideal_I = bool(det_I != 0 or M_I == sympy.zeros(n, n))
        is_ideal_J = bool(det_J != 0 or M_J == sympy.zeros(n, n))
        
        # The conclusion holds if both are valid ideals (since A-B is invertible, their sum would be R).
        conclusion = is_ideal_I and is_ideal_J
        
        neg_q = not conclusion
        
        return [h1, h2, h3, neg_q]
    except Exception:
        return [False, False, False, False]

