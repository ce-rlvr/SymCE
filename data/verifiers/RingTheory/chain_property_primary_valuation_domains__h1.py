import sympy
from sympy import symbols, Poly

x, y, z, w = symbols('x y z w')

def conditions(witness):
    try:
        vars, P_gens, Q1_gens, Q2_gens = witness
        if not vars:
            return [False, False]
        if not P_gens: P_gens = [0]
        if not Q1_gens: Q1_gens = [0]
        if not Q2_gens: Q2_gens = [0]
    except Exception:
        return [False, False]

    # H_1: P is a prime ideal of R
    try:
        gb_P_obj = sympy.groebner(P_gens, *vars)
        gb_P_polys = gb_P_obj.polys
        is_prime = True
        if not gb_P_polys:
            is_prime = True
        elif len(gb_P_polys) == 1 and gb_P_polys[0].is_zero:
            is_prime = True
        else:
            for p in gb_P_polys:
                # A sufficient condition for primality in our polynomial ring setup:
                # The ideal is generated by a subset of the variables.
                if not p.is_monomial or p.total_degree() != 1:
                    is_prime = False
                    break
        h1_ok = is_prime
    except Exception:
        h1_ok = False

    # ¬Q: The set of all P-primary ideals in R is not totally ordered under inclusion
    try:
        def is_P_primary(Q_gens, P_gens, vars):
            gb_P_obj = sympy.groebner(P_gens, *vars)
            gb_P_expr = list(gb_P_obj)
            gb_P_polys = gb_P_obj.polys
            
            P_vars = set()
            is_P_var_generated = True
            for p in gb_P_polys:
                if not p.is_monomial or p.total_degree() != 1:
                    is_P_var_generated = False
                    break
                syms = p.as_expr().free_symbols.intersection(set(vars))
                if len(syms) != 1:
                    is_P_var_generated = False
                    break
                P_vars.add(list(syms)[0])
                
            gb_Q_obj = sympy.groebner(Q_gens, *vars)
            gb_P_list = list(gb_P_obj)
            gb_Q_list = list(gb_Q_obj)
            
            # Check Q is a subset of P
            for q in Q_gens:
                if sympy.reduced(q, gb_P_list, *vars)[1] != 0:
                    return False
                    
            # Check P is a subset of radical(Q)
            for p in gb_P_expr:
                found = False
                for n in range(1, 15):
                    if sympy.reduced(p**n, gb_Q_list, *vars)[1] == 0:
                        found = True
                        break
                if not found:
                    return False
                    
            # If P is maximal and radical(Q) == P, then Q is P-primary
            if len(gb_P_polys) == len(vars) and is_P_var_generated:
                return True
                
            # If P is not maximal, we check if Q is a monomial ideal generated only by variables in P
            is_Q_monomial = True
            for q in Q_gens:
                if not sympy.Poly(q, *vars).is_monomial:
                    is_Q_monomial = False
                    break
                    
            if is_P_var_generated and is_Q_monomial:
                for q in Q_gens:
                    for v in vars:
                        if v not in P_vars and v in sympy.sympify(q).free_symbols:
                            return False
                return True
                
            return False

        def not_subset(A_gens, B_gens, vars):
            gb_B_list = list(sympy.groebner(B_gens, *vars))
            for a in A_gens:
                if sympy.reduced(a, gb_B_list, *vars)[1] != 0:
                    return True
            return False

        q1_primary = is_P_primary(Q1_gens, P_gens, vars)
        q2_primary = is_P_primary(Q2_gens, P_gens, vars)
        incomparable = not_subset(Q1_gens, Q2_gens, vars) and not_subset(Q2_gens, Q1_gens, vars)
        
        neg_q_ok = bool(q1_primary and q2_primary and incomparable)
    except Exception:
        neg_q_ok = False

    return [h1_ok, neg_q_ok]

