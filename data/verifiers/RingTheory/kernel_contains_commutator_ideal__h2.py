import itertools
from sympy import Matrix

# Setup M2Z2 (2x2 matrices over Z_2) as a standard witness
M2Z2_elements = [Matrix(2, 2, entries) for entries in itertools.product([0, 1], repeat=4)]

def M2Z2_add(A, B):
    return Matrix(2, 2, [(A[i] + B[i]) % 2 for i in range(4)])

def M2Z2_mul(A, B):
    return Matrix(2, 2, [
        (A[0]*B[0] + A[1]*B[2]) % 2,
        (A[0]*B[1] + A[1]*B[3]) % 2,
        (A[2]*B[0] + A[3]*B[2]) % 2,
        (A[2]*B[1] + A[3]*B[3]) % 2
    ])

def M2Z2_neg(A):
    return Matrix(2, 2, [(-A[i]) % 2 for i in range(4)])

M2Z2_zero = Matrix([[0, 0], [0, 0]])
M2Z2_one = Matrix([[1, 0], [0, 1]])

def M2Z2_eq(A, B):
    return A == B

M2Z2 = {
    'elements': M2Z2_elements,
    'add': M2Z2_add,
    'mul': M2Z2_mul,
    'neg': M2Z2_neg,
    'zero': M2Z2_zero,
    'one': M2Z2_one,
    'f': lambda x: x,
    'f_zero': M2Z2_zero,
    'f_one': M2Z2_one,
    'eq': M2Z2_eq,
    'f_eq': M2Z2_eq,
    'f_add': M2Z2_add,
    'f_mul': M2Z2_mul
}

def conditions(witness):
    try:
        elements = witness['elements']
        add = witness['add']
        mul = witness['mul']
        zero = witness['zero']
        neg = witness['neg']
        f = witness['f']
        f_zero = witness.get('f_zero', zero)
        eq = witness.get('eq', lambda x, y: x == y)
        f_eq = witness.get('f_eq', eq)
        f_add = witness.get('f_add', add)
        f_mul = witness.get('f_mul', mul)
    except Exception:
        return [False, False, False]

    # H1: R is a ring
    h1 = True
    try:
        if not elements:
            h1 = False
        else:
            if not any(eq(zero, x) for x in elements):
                h1 = False
            
            for a in elements:
                if not eq(add(a, zero), a) or not eq(add(zero, a), a):
                    h1 = False; break
                if not eq(add(a, neg(a)), zero) or not eq(add(neg(a), a), zero):
                    h1 = False; break
                for b in elements:
                    add_ab = add(a, b)
                    mul_ab = mul(a, b)
                    if not any(eq(add_ab, x) for x in elements):
                        h1 = False; break
                    if not any(eq(mul_ab, x) for x in elements):
                        h1 = False; break
                    if not eq(add_ab, add(b, a)):
                        h1 = False; break
                    for c in elements:
                        if not eq(add(add_ab, c), add(a, add(b, c))):
                            h1 = False; break
                        if not eq(mul(mul_ab, c), mul(a, mul(b, c))):
                            h1 = False; break
                        if not eq(mul(a, add(b, c)), add(mul_ab, mul(a, c))):
                            h1 = False; break
                        if not eq(mul(add_ab, c), add(mul(a, c), mul(b, c))):
                            h1 = False; break
                if not h1: break
    except Exception:
        h1 = False

    # H2: f is a ring homomorphism
    h2 = True
    try:
        if 'one' in witness and 'f_one' in witness:
            if not f_eq(f(witness['one']), witness['f_one']):
                h2 = False
                
        for a in elements:
            for b in elements:
                if not f_eq(f(add(a, b)), f_add(f(a), f(b))):
                    h2 = False; break
                if not f_eq(f(mul(a, b)), f_mul(f(a), f(b))):
                    h2 = False; break
            if not h2: break
    except Exception:
        h2 = False

    # Negated Conclusion: exists a, b in R such that f(ab - ba) != f_zero
    neg_q = False
    try:
        for a in elements:
            for b in elements:
                commutator = add(mul(a, b), neg(mul(b, a)))
                if not f_eq(f(commutator), f_zero):
                    neg_q = True
                    break
            if neg_q: break
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

