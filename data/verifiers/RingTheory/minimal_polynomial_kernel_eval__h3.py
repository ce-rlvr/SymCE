def conditions(witness) -> list[bool]:
    try:
        F, E, alpha = witness
    except Exception:
        return [False, False, False]

    # H_1: E is an extension field of F
    try:
        h1 = False
        if hasattr(F, 'is_Field') and F.is_Field and hasattr(E, 'is_Field') and E.is_Field:
            if hasattr(F, 'unify'):
                h1 = (F.unify(E) == E)
    except Exception:
        h1 = False

    # H_2: alpha is an element of E
    try:
        h2 = False
        if hasattr(E, 'from_sympy'):
            E.from_sympy(alpha)
            h2 = True
        elif hasattr(E, '__contains__'):
            h2 = alpha in E
    except Exception:
        h2 = False

    # neg_Q: The kernel is NOT a non-zero principal ideal generated by a unique monic irreducible polynomial
    try:
        X = Dummy('X')
        alpha_sym = alpha
        if hasattr(E, 'to_sympy'):
            try:
                alpha_sym = E.to_sympy(alpha)
            except Exception:
                pass
        elif hasattr(alpha, 'as_expr'):
            try:
                alpha_sym = alpha.as_expr()
            except Exception:
                pass
        
        # If minpoly succeeds, alpha is algebraic over F.
        # Thus the kernel is generated by the minimal polynomial, which is non-zero, monic, and irreducible.
        # In this case, the conclusion holds, so its negation is False.
        poly = minpoly(alpha_sym, X, domain=F)
        neg_q = False
    except Exception:
        # If minpoly fails (e.g., raises NotAlgebraic), alpha is transcendental over F.
        # The kernel is the zero ideal, which is NOT generated by a non-zero polynomial.
        # In this case, the conclusion fails, so its negation is True.
        neg_q = True

    return [h1, h2, neg_q]

