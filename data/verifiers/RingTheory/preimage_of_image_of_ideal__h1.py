class ZnRing:
    def __init__(self, n):
        self.n = n
        self.elements = list(range(n))
        self.zero = 0
        self.one = 1 if n > 1 else 0
    def add(self, a, b): return (a + b) % self.n
    def mul(self, a, b): return (a * b) % self.n
    def neg(self, a): return (-a) % self.n
    def eq(self, a, b): return a == b

