class RingWrapper:
    def __init__(self, ring):
        if isinstance(ring, dict):
            self.elements = list(ring['elements'])
            self.add = ring['add']
            self.mul = ring['mul']
            self.zero = ring['zero']
            self.eq = ring.get('eq', lambda a, b: a == b)
            self.one = ring.get('one', None)
            self.neg = ring.get('neg', None)
        else:
            self.elements = list(ring.elements)
            self.add = ring.add
            self.mul = ring.mul
            self.zero = ring.zero
            self.eq = getattr(ring, 'eq', lambda a, b: a == b)
            self.one = getattr(ring, 'one', None)
            self.neg = getattr(ring, 'neg', None)

def conditions(witness):
    try:
        if isinstance(witness, dict):
            R_raw = witness['R']
            S_raw = witness['S']
            f = witness['f']
            I = witness['I']
        else:
            R_raw = witness.R
            S_raw = witness.S
            f = witness.f
            I = witness.I
            
        R = RingWrapper(R_raw)
        S = RingWrapper(S_raw)
    except Exception:
        return [False, False, False]
        
    # H1: f is a ring homomorphism
    try:
        h1 = True
        for x in R.elements:
            fx = f(x)
            if not any(S.eq(fx, y) for y in S.elements):
                h1 = False
                break
        if h1:
            for x in R.elements:
                for y in R.elements:
                    if not S.eq(f(R.add(x, y)), S.add(f(x), f(y))):
                        h1 = False
                        break
                if not h1: break
        if h1:
            for x in R.elements:
                for y in R.elements:
                    if not S.eq(f(R.mul(x, y)), S.mul(f(x), f(y))):
                        h1 = False
                        break
                if not h1: break
        if h1 and R.one is not None and S.one is not None:
            if not S.eq(f(R.one), S.one):
                h1 = False
    except Exception:
        h1 = False

    # H2: I is an ideal of R
    try:
        h2 = True
        if not I:
            h2 = False
        if h2:
            for x in I:
                if not any(R.eq(x, r) for r in R.elements):
                    h2 = False
                    break
        if h2:
            has_zero = any(R.eq(x, R.zero) for x in I)
            if not has_zero:
                h2 = False
        if h2:
            if R.neg is not None:
                for x in I:
                    nx = R.neg(x)
                    if not any(R.eq(nx, i) for i in I):
                        h2 = False
                        break
            else:
                for x in I:
                    inv_found = False
                    for r in R.elements:
                        if R.eq(R.add(x, r), R.zero):
                            if any(R.eq(r, i) for i in I):
                                inv_found = True
                            break
                    if not inv_found:
                        h2 = False
                        break
        if h2:
            for x in I:
                for y in I:
                    if not any(R.eq(R.add(x, y), i) for i in I):
                        h2 = False
                        break
                if not h2: break
        if h2:
            for i in I:
                for r in R.elements:
                    if not any(R.eq(R.mul(r, i), j) for j in I):
                        h2 = False
                        break
                    if not any(R.eq(R.mul(i, r), j) for j in I):
                        h2 = False
                        break
                if not h2: break
    except Exception:
        h2 = False

    # neg_Q: f^{-1}(<f(I)>) != I + ker(f)
    try:
        ker = []
        for x in R.elements:
            if S.eq(f(x), S.zero):
                ker.append(x)
                
        I_plus_ker = []
        for i in I:
            for k in ker:
                s_val = R.add(i, k)
                if not any(R.eq(s_val, x) for x in I_plus_ker):
                    I_plus_ker.append(s_val)
                    
        f_I = []
        for i in I:
            fi = f(i)
            if not any(S.eq(fi, x) for x in f_I):
                f_I.append(fi)
                
        J = list(f_I)
        if not any(S.eq(S.zero, x) for x in J):
            J.append(S.zero)
            
        changed = True
        iterations = 0
        while changed and iterations < 100:
            changed = False
            new_elements = []
            
            if S.neg is not None:
                for j in J:
                    nj = S.neg(j)
                    if not any(S.eq(nj, x) for x in J) and not any(S.eq(nj, x) for x in new_elements):
                        new_elements.append(nj)
            else:
                for j in J:
                    for s in S.elements:
                        if S.eq(S.add(j, s), S.zero):
                            if not any(S.eq(s, x) for x in J) and not any(S.eq(s, x) for x in new_elements):
                                new_elements.append(s)
                            break
                            
            for j1 in J:
                for j2 in J:
                    s_add = S.add(j1, j2)
                    if not any(S.eq(s_add, x) for x in J) and not any(S.eq(s_add, x) for x in new_elements):
                        new_elements.append(s_add)
                        
            for s in S.elements:
                for j in J:
                    p1 = S.mul(s, j)
                    if not any(S.eq(p1, x) for x in J) and not any(S.eq(p1, x) for x in new_elements):
                        new_elements.append(p1)
                    p2 = S.mul(j, s)
                    if not any(S.eq(p2, x) for x in J) and not any(S.eq(p2, x) for x in new_elements):
                        new_elements.append(p2)
                        
            if new_elements:
                J.extend(new_elements)
                changed = True
            iterations += 1
            
        preimage_J = []
        for x in R.elements:
            fx = f(x)
            if any(S.eq(fx, j) for j in J):
                preimage_J.append(x)
                
        is_subset1 = True
        for x in preimage_J:
            if not any(R.eq(x, y) for y in I_plus_ker):
                is_subset1 = False
                break
                
        is_subset2 = True
        for x in I_plus_ker:
            if not any(R.eq(x, y) for y in preimage_J):
                is_subset2 = False
                break
                
        neg_q = not (is_subset1 and is_subset2)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]