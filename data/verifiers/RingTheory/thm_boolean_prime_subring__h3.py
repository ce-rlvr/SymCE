def is_boolean_ring(R):
    elements = list(R.elements)
    zero = R.zero
    
    # Check closure and basic ring axioms
    for a in elements:
        if R.add(a, zero) != a: return False
        if R.add(zero, a) != a: return False
        if R.mul(a, zero) != zero: return False
        if R.mul(zero, a) != zero: return False
        # Boolean ring condition: a^2 = a
        if R.mul(a, a) != a: return False
        
        # Additive inverse
        has_inv = False
        for b in elements:
            if R.add(a, b) == zero and R.add(b, a) == zero:
                has_inv = True
                break
        if not has_inv: return False

    # Check associativity and distributivity
    for a in elements:
        for b in elements:
            if R.add(a, b) != R.add(b, a): return False
            ab_add = R.add(a, b)
            ab_mul = R.mul(a, b)
            for c in elements:
                if R.add(ab_add, c) != R.add(a, R.add(b, c)): return False
                if R.mul(ab_mul, c) != R.mul(a, R.mul(b, c)): return False
                if R.mul(a, R.add(b, c)) != R.add(ab_mul, R.mul(a, c)): return False
                if R.mul(ab_add, c) != R.add(R.mul(a, c), R.mul(b, c)): return False
    return True

def has_identity_1_neq_0(R):
    elements = list(R.elements)
    zero = R.zero
    for e in elements:
        if e == zero: continue
        is_id = True
        for a in elements:
            if R.mul(e, a) != a or R.mul(a, e) != a:
                is_id = False
                break
        if is_id:
            return True
    return False

def P_is_isomorphic_to_Z2(witness):
    if isinstance(witness, tuple) and len(witness) == 2:
        R, P = witness
    else:
        R = witness
        if hasattr(witness, 'P'):
            P = witness.P
        else:
            # Compute prime subring generated by the identity
            elements = list(R.elements)
            zero = R.zero
            identity = None
            for e in elements:
                if e == zero: continue
                is_id = True
                for a in elements:
                    if R.mul(e, a) != a or R.mul(a, e) != a:
                        is_id = False
                        break
                if is_id:
                    identity = e
                    break
            if identity is None:
                return False
            
            P = []
            curr = zero
            while curr not in P:
                P.append(curr)
                curr = R.add(curr, identity)
    
    if hasattr(P, 'elements'):
        P_elements = list(P.elements)
        add_func = P.add if hasattr(P, 'add') else R.add
        mul_func = P.mul if hasattr(P, 'mul') else R.mul
    else:
        P_elements = list(P)
        add_func = R.add
        mul_func = R.mul

    if len(P_elements) != 2:
        return False

    z = None
    u = None
    for x in P_elements:
        is_z = True
        for y in P_elements:
            if add_func(x, y) != y or add_func(y, x) != y:
                is_z = False
                break
        if is_z:
            z = x
            break
    if z is None: return False
    
    for x in P_elements:
        if x == z: continue
        is_u = True
        for y in P_elements:
            if mul_func(x, y) != y or mul_func(y, x) != y:
                is_u = False
                break
        if is_u:
            u = x
            break
    if u is None: return False
    
    if add_func(u, u) != z: return False
    
    return True

