import sympy
from sympy import zeros, eye, Integer, isprime
from sympy.ntheory import factorint

# Top-level setup for witness evaluation
class MatrixRingClass:
    def __init__(self, *args, **kwargs):
        pass

class CommutativeRingClass:
    def __init__(self, *args, **kwargs):
        pass

def MatrixRing(*args, **kwargs):
    return MatrixRingClass()

def ZeroIdeal(*args, **kwargs):
    n = 2
    for arg in args:
        if isinstance(arg, int) and arg >= 2:
            n = arg
    return zeros(n, n)

QQ = CommutativeRingClass()
ZZ = CommutativeRingClass()
RR = CommutativeRingClass()
CC = CommutativeRingClass()

O2 = zeros(2, 2)
O3 = zeros(3, 3)
I2 = eye(2)
I3 = eye(3)

CONDITION_LABELS = [
    "H_1: P is a prime ideal in R",
    "¬Q: P is not a P-primary ideal in R"
]

N_HYP = 1
NEG_Q_INDEX = 1

def conditions(witness):
    P = witness
    is_matrix_ring = False
    
    # Extract the ideal P and check if the ring is explicitly a matrix ring
    if isinstance(witness, (list, tuple)):
        for item in witness:
            if isinstance(item, MatrixRingClass):
                is_matrix_ring = True
            elif hasattr(item, 'is_Matrix') and item.is_Matrix:
                P = item
        
        if not hasattr(P, 'is_Matrix') and len(witness) > 0:
            if P is witness:
                P = witness[-1]

    h1 = False
    neg_q = False

    # Check if P is the zero ideal in a matrix ring M_n(R) for n >= 2
    # In M_n(R), the zero ideal is prime but not primary.
    try:
        if hasattr(P, 'is_Matrix') and P.is_Matrix:
            if P.is_zero_matrix and P.shape[0] == P.shape[1] and P.shape[0] >= 2:
                h1 = True
                neg_q = True
    except Exception:
        pass

    # Unwrap single-element lists/tuples/sets that might represent an ideal generated by one element
    try:
        if isinstance(P, (list, tuple, set)) and len(P) == 1:
            elem = list(P)[0]
            if isinstance(elem, (int, Integer)):
                P = elem
    except Exception:
        pass

    # Check if P is an integer, representing an ideal in Z (or 0 in a matrix ring)
    try:
        if isinstance(P, (int, Integer)):
            val = abs(int(P))
            if is_matrix_ring and val == 0:
                h1 = True
                neg_q = True
            else:
                if val == 0:
                    h1 = True
                    neg_q = False
                elif val == 1:
                    h1 = False
                    neg_q = True
                else:
                    if isprime(val):
                        h1 = True
                    else:
                        h1 = False
                    
                    factors = factorint(val)
                    if len(factors) == 1:
                        neg_q = False
                    else:
                        neg_q = True
    except Exception:
        pass

    return [h1, neg_q]