import sympy as sp
from sympy.abc import x, y, z, u, v, w

CONDITION_LABELS = [
    "H_1: M is a finitely generated R-module",
    "H_2: M is a torsion-free module",
    "¬Q: M is not a free R-module"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    """
    Checks if the witness is a valid counterexample.
    The witness is interpreted as a list of generators for an ideal M 
    in the polynomial ring R = Z[V] or Q[V], where V are the free symbols.
    """
    try:
        # Normalize witness to a list of expressions
        if isinstance(witness, sp.Matrix):
            witness = list(witness)
        elif isinstance(witness, set):
            witness = list(witness)
            
        if not isinstance(witness, (list, tuple)):
            if isinstance(witness, sp.Expr) or isinstance(witness, (int, float)):
                witness = [witness]
            else:
                return [False, False, False]
                
        # H_1: M is a finitely generated R-module
        # True by definition since it's generated by a finite list of elements.
        h1 = True
        for expr in witness:
            if not isinstance(expr, sp.Expr) and not isinstance(expr, (int, float)):
                h1 = False
                break
        if not h1 or len(witness) == 0:
            return [False, False, False]
            
        witness = [sp.sympify(expr) for expr in witness]
            
        # H_2: M is a torsion-free module
        # An ideal in a polynomial ring over an integral domain is always torsion-free.
        h2 = True
        
        # ¬Q: M is not a free R-module
        # An ideal in an integral domain is a free module if and only if it is principal.
        # We check if the ideal is principal by checking if its GCD generates it.
        g = witness[0]
        for expr in witness[1:]:
            g = sp.gcd(g, expr)
            
        free_symbols = set()
        for expr in witness:
            free_symbols.update(expr.free_symbols)
            
        vars_list = list(free_symbols)
        vars_list.sort(key=lambda sym: sym.name)
        
        if not vars_list:
            # If there are no variables, the ring is a field or Z, which are PIDs.
            # Any ideal is principal, hence free.
            neg_q = False
        else:
            is_princ_ZZ = None
            try:
                # Check if principal over Z[V]
                G_ZZ = sp.groebner(witness, *vars_list, domain='ZZ')
                rem_ZZ = sp.reduced(g, G_ZZ, *vars_list, domain='ZZ')[1]
                is_princ_ZZ = (rem_ZZ == 0 or sp.simplify(rem_ZZ) == 0)
            except Exception:
                pass

            is_princ_QQ = None
            try:
                # Check if principal over Q[V]
                G_QQ = sp.groebner(witness, *vars_list, domain='QQ')
                rem_QQ = sp.reduced(g, G_QQ, *vars_list, domain='QQ')[1]
                is_princ_QQ = (rem_QQ == 0 or sp.simplify(rem_QQ) == 0)
            except Exception:
                pass

            # If it fails to be principal in either domain, it's a valid counterexample
            # for that respective ring.
            if is_princ_ZZ is False:
                neg_q = True
            elif is_princ_QQ is False:
                neg_q = True
            elif is_princ_ZZ is True or is_princ_QQ is True:
                neg_q = False
            else:
                # Could not evaluate Groebner basis in either domain
                return [h1, h2, False]
                
        return [h1, h2, neg_q]
    except Exception:
        return [False, False, False]