CONDITION_LABELS = [
    "H_1: M is a finitely generated module over R",
    "H_2: T is the torsion submodule of M",
    "¬Q: T is not a direct summand of M"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    try:
        if isinstance(witness, sympy.Matrix):
            mat = witness
        else:
            try:
                mat = sympy.Matrix(witness)
            except Exception:
                if isinstance(witness, dict):
                    if 'matrix' in witness:
                        mat = witness['matrix']
                    elif 'M' in witness:
                        mat = witness['M']
                    else:
                        mat = list(witness.values())[0]
                elif isinstance(witness, (tuple, list)):
                    mat = witness[0]
                else:
                    mat = witness
                mat = sympy.Matrix(mat)
        h1 = isinstance(mat, sympy.Matrix)
    except Exception:
        h1 = False

    # H_2 is definitional; if M is a valid finitely generated module, T is well-defined.
    h2 = h1

    neg_q = False
    try:
        if h1:
            m = mat.shape[0]
            n = mat.shape[1]
            # We check if the presentation matrix implies T=0 but M is not free.
            if m < n:
                if m == 1:
                    is_full_rank = any(mat[0, i] != 0 for i in range(n))
                else:
                    is_full_rank = (mat.rank() == m)
                    
                if is_full_rank:
                    minors = []
                    for cols in itertools.combinations(range(n), m):
                        submat = mat[:, cols]
                        minors.append(submat.det())
                    
                    if all(isinstance(e, sympy.Expr) for e in minors):
                        g = minors[0]
                        for e in minors[1:]:
                            g = sympy.gcd(g, e)
                        
                        # If gcd of maximal minors is 1, then T = 0.
                        if g == 1 or g == -1:
                            free_syms = mat.free_symbols
                            if free_syms:
                                syms = list(free_syms)
                                # Check if the ideal generated by minors is the whole ring R.
                                # If not, M is not free, hence M does not split as T \oplus F.
                                for pt in itertools.product(range(-5, 6), repeat=len(syms)):
                                    val_dict = dict(zip(syms, pt))
                                    vals = [e.subs(val_dict) for e in minors]
                                    if all(v.is_Integer for v in vals):
                                        v_g = vals[0]
                                        for v in vals[1:]:
                                            v_g = sympy.gcd(v_g, v)
                                        if abs(v_g) != 1:
                                            neg_q = True
                                            break
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]