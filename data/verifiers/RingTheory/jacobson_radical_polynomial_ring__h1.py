class GF2Matrix:
    def __init__(self, mat):
        self.mat = mat.applyfunc(lambda x: x % 2)
    def __add__(self, other):
        return GF2Matrix(self.mat + other.mat)
    def __sub__(self, other):
        return GF2Matrix(self.mat - other.mat)
    def __mul__(self, other):
        return GF2Matrix(self.mat * other.mat)
    def __eq__(self, other):
        if not isinstance(other, GF2Matrix):
            return False
        return self.mat == other.mat
    def __hash__(self):
        return hash(tuple(self.mat))
    def __repr__(self):
        return f"GF2Matrix({self.mat.tolist()})"

# M_2(GF(2)) is a standard counterexample for this theorem
M2_GF2_R = []
for entries in product([0, 1], repeat=4):
    M2_GF2_R.append(GF2Matrix(Matrix(2, 2, entries)))

# The Jacobson radical of M_2(GF(2))[x] is {0}
M2_GF2_J = [GF2Matrix(Matrix(2, 2, [0, 0, 0, 0]))]
M2_GF2 = (M2_GF2_R, M2_GF2_J)

class Z4Element:
    def __init__(self, val):
        self.val = val % 4
    def __add__(self, other):
        return Z4Element(self.val + other.val)
    def __sub__(self, other):
        return Z4Element(self.val - other.val)
    def __mul__(self, other):
        return Z4Element(self.val * other.val)
    def __eq__(self, other):
        if not isinstance(other, Z4Element):
            return False
        return self.val == other.val
    def __hash__(self):
        return hash(self.val)
    def __repr__(self):
        return f"Z4({self.val})"

# Z_4 is a commutative ring where the theorem holds (not a counterexample)
Z4_R = [Z4Element(i) for i in range(4)]
Z4_J = [Z4Element(0), Z4Element(2)]
Z4 = (Z4_R, Z4_J)


def is_right_quasi_regular(u, R, zero):
    for v in R:
        try:
            if u + v - u * v == zero:
                return True
        except Exception:
            pass
    return False

def is_in_jacobson_radical(x, R, zero):
    for y in R:
        try:
            u = x * y
            if not is_right_quasi_regular(u, R, zero):
                return False
        except Exception:
            return False
    return True

def is_nilpotent(x, zero):
    curr = x
    for _ in range(50):
        try:
            if curr == zero:
                return True
            curr = curr * x
        except Exception:
            return False
    return False

def conditions(witness) -> list[bool]:
    # Handle string aliases for convenience
    if isinstance(witness, str):
        if witness in ["M_2(GF(2))", "M_2(Z_2)", "M2(F2)"]:
            witness = M2_GF2
        elif witness in ["Z4", "Z_4"]:
            witness = Z4

    try:
        if isinstance(witness, dict):
            R = witness.get('R', [])
            J = witness.get('J', [])
        elif isinstance(witness, tuple) and len(witness) == 2:
            R, J = witness
        else:
            R = witness
            J = None
    except Exception:
        return [False, False]

    try:
        if not isinstance(R, list) or len(R) == 0:
            return [False, False]
    except Exception:
        return [False, False]

    # Find the additive identity (zero) of the ring
    try:
        zero = None
        for x in R:
            if x + x == x:
                zero = x
                break
        if zero is None:
            zero = R[0] - R[0]
    except Exception:
        return [False, False]

    # If J is not provided, compute it as the Jacobson radical of R[x]
    # For finite rings, J(R[x]) = J(R)[x], so we just find J(R)
    if J is None:
        try:
            J = [x for x in R if is_in_jacobson_radical(x, R, zero)]
        except Exception:
            return [False, False]

    # H_1: J is the Jacobson radical of the polynomial ring R[x]
    try:
        expected_J = [x for x in R if is_in_jacobson_radical(x, R, zero)]
        h1_ok = True
        if len(J) != len(expected_J):
            h1_ok = False
        else:
            for x in J:
                if x not in expected_J:
                    h1_ok = False
                    break
    except Exception:
        h1_ok = False

    # ¬Q: J is NOT the ideal generated by the nilradical of R
    # The conclusion claims J consists of all polynomials whose coefficients are nilpotent elements of R.
    # We check if the set of coefficients in J is exactly the set of nilpotent elements in R.
    try:
        nilpotents = [x for x in R if is_nilpotent(x, zero)]
        j_is_nilpotents = True
        if len(J) != len(nilpotents):
            j_is_nilpotents = False
        else:
            for x in J:
                if x not in nilpotents:
                    j_is_nilpotents = False
                    break
        neg_q_ok = not j_is_nilpotents
    except Exception:
        neg_q_ok = False

    return [h1_ok, neg_q_ok]

