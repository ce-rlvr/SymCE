import sympy
from sympy import symbols, sympify
from sympy.abc import x, y, z

# Top-level setup for potential witness expressions
x, y, z = symbols('x y z')

def conditions(witness):
    """
    Checks the hypotheses and negated conclusion for the false conjecture:
    Hypotheses:
      - R is a commutative ring.
      - J is a principal ideal of R generated by an element b.
    Conclusion:
      - The product ideal IJ is a principal ideal generated by the product element ab.
      
    The witness should be a dictionary providing the generators for ideals I and J, 
    and the elements a and b. For example:
    witness = {'I': [x, y], 'J': [x], 'a': x, 'b': x}
    """
    try:
        I_gens = witness['I']
        J_gens = witness['J']
        a = witness['a']
        b = witness['b']
    except Exception:
        return [False, False, False]
    
    # H_1: R is a commutative ring
    try:
        I_gens = [sympify(g) for g in I_gens]
        J_gens = [sympify(g) for g in J_gens]
        a = sympify(a)
        b = sympify(b)
        
        if not I_gens:
            I_gens = [sympy.Integer(0)]
        if not J_gens:
            J_gens = [sympy.Integer(0)]
            
        all_exprs = I_gens + J_gens + [a, b]
        # In SymPy, standard expressions are commutative. We verify none are explicitly non-commutative.
        h1_ok = all(expr.is_commutative is not False for expr in all_exprs)
    except Exception:
        h1_ok = False

    # H_2: J is a principal ideal of R generated by an element b
    try:
        free_symbols = set()
        for expr in all_exprs:
            free_symbols.update(expr.free_symbols)
        vars = sorted(list(free_symbols), key=lambda v: v.name)
        
        if not vars:
            vars = [sympy.Symbol('x')]
            
        # Compute reduced Groebner bases over QQ to check ideal equality
        gb_J = sympy.groebner(J_gens, *vars, domain='QQ')
        gb_b = sympy.groebner([b], *vars, domain='QQ')
        
        gb_J_exprs = set(e.as_expr() if hasattr(e, 'as_expr') else sympify(e) for e in gb_J)
        gb_b_exprs = set(e.as_expr() if hasattr(e, 'as_expr') else sympify(e) for e in gb_b)
        
        h2_ok = (gb_J_exprs == gb_b_exprs)
    except Exception:
        h2_ok = False

    # ¬Q: The product ideal IJ is NOT a principal ideal generated by the product element ab
    try:
        IJ_gens = [i * j for i in I_gens for j in J_gens]
        if not IJ_gens:
            IJ_gens = [sympy.Integer(0)]
            
        ab = a * b
        
        gb_IJ = sympy.groebner(IJ_gens, *vars, domain='QQ')
        gb_ab = sympy.groebner([ab], *vars, domain='QQ')
        
        gb_IJ_exprs = set(e.as_expr() if hasattr(e, 'as_expr') else sympify(e) for e in gb_IJ)
        gb_ab_exprs = set(e.as_expr() if hasattr(e, 'as_expr') else sympify(e) for e in gb_ab)
        
        neg_q_ok = (gb_IJ_exprs != gb_ab_exprs)
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, neg_q_ok]

