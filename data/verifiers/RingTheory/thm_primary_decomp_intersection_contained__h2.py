import sympy
from sympy.ntheory import factorint

# Top-level setup for ring theory witnesses
ZZ = sympy.Symbol('ZZ')
Z = sympy.Symbol('Z')

def extract_generator(expr):
    """
    Helper to extract the integer generator from various possible witness formats.
    Handles raw integers, SymPy integers, and expressions like 4*ZZ or 12*Z.
    """
    try:
        if isinstance(expr, (int, float)):
            return int(expr)
        if hasattr(expr, 'is_Integer') and expr.is_Integer:
            return int(expr)
        if isinstance(expr, sympy.Expr):
            if expr == ZZ or expr == Z:
                return 1
            c_ZZ = expr.coeff(ZZ)
            if c_ZZ != 0 and c_ZZ.is_Integer:
                return int(c_ZZ)
            c_Z = expr.coeff(Z)
            if c_Z != 0 and c_Z.is_Integer:
                return int(c_Z)
        return int(expr)
    except Exception:
        return None

def conditions(witness) -> list[bool]:
    # H_1: R is a commutative ring and I, J, Q are ideals
    # We interpret the witness as generators for principal ideals in the ring of integers Z.
    try:
        if isinstance(witness, dict):
            i = extract_generator(witness.get('I', witness.get('i')))
            j = extract_generator(witness.get('J', witness.get('j')))
            q = extract_generator(witness.get('Q', witness.get('q')))
        else:
            if len(witness) < 3:
                return [False, False, False, False]
            # Extract the last 3 elements to handle formats like (R, I, J, Q) or just (I, J, Q)
            i_expr, j_expr, q_expr = witness[-3:]
            i = extract_generator(i_expr)
            j = extract_generator(j_expr)
            q = extract_generator(q_expr)
            
        h1 = (i is not None and j is not None and q is not None)
        if not h1:
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]

    # H_2: I \cap J \subseteq Q
    # In Z, I \cap J is generated by lcm(i, j). Subset means q divides lcm(i, j).
    try:
        L = sympy.lcm(i, j)
        if q == 0:
            h2 = (L == 0)
        else:
            h2 = (L % q == 0)
    except Exception:
        h2 = False

    # H_3: I \not\subseteq Q
    # In Z, this means q does not divide i.
    try:
        if q == 0:
            h3 = (i != 0)
        else:
            h3 = (i % q != 0)
    except Exception:
        h3 = False

    # ¬Q: J \not\subseteq \sqrt{Q}
    # In Z, \sqrt{Q} is generated by the radical of q (product of distinct prime factors).
    # Subset fails if rad(q) does not divide j.
    try:
        if q == 0:
            r = 0
        else:
            r = 1
            for p in factorint(abs(q)):
                r *= p
        
        if r == 0:
            neg_q = (j != 0)
        else:
            neg_q = (j % r != 0)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

