def conditions(witness) -> list[bool]:
    """
    Evaluates the conjecture for a given witness.
    The expected witness is a tuple of two integers (n, k), which represents:
      - The ring R = Z/nZ
      - The projective R-module P = R
      - The submodule M = kR (the ideal generated by k)
    """
    try:
        if not (isinstance(witness, tuple) and len(witness) == 2):
            return [False, False, False]
        
        n, k = witness
        
        # Ensure n and k are integers
        if not (isinstance(n, int) and isinstance(k, int)):
            return [False, False, False]
        
        # H_1: P is a projective R-module
        # P = Z/nZ is a free module over R = Z/nZ, hence it is always projective.
        # We require n >= 2 for a valid non-trivial ring Z/nZ.
        h1 = (n >= 2)
        
        # H_2: M is a submodule of P
        # M = kZ/nZ is an ideal of R, hence it is always a submodule of P.
        h2 = (n >= 2)
        
        # ¬Q: M is not a projective R-module
        # In the ring Z/nZ, an ideal (d) is projective if and only if it is generated 
        # by an idempotent. This occurs if and only if gcd(d, n/d) == 1.
        # Therefore, M is NOT projective when gcd(d, n/d) > 1.
        d = math.gcd(k, n)
        if d == 0:
            neg_q = False
        else:
            neg_q = (math.gcd(d, n // d) > 1)
        
        return [h1, h2, neg_q]
    
    except Exception:
        return [False, False, False]

