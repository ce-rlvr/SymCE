import sympy
from sympy import Matrix
from itertools import combinations
import math

# Top-level setup
Z = sympy.S.Integers
Q = sympy.S.Rationals

def conditions(witness):
    try:
        if not isinstance(witness, dict):
            return [False] * 6
            
        # H1: R is a commutative ring
        # We restrict the witness to R = Z for simplicity, which is a valid commutative ring.
        R = witness.get('R')
        h1 = (R == 'Z' or R == Z)
    except Exception:
        h1 = False

    try:
        # H2: k is the residue field R/m
        # For R = Z, m must be a prime number p so that Z/pZ is a field.
        m = witness.get('m')
        h2 = sympy.isprime(m)
    except Exception:
        h2 = False

    try:
        # H3: M is a finitely generated R-module
        # Represented as a list of invariant factors [a_1, ..., a_k] where M = Z/a_1 Z x ... x Z/a_k Z
        M = witness.get('M')
        h3 = isinstance(M, list) and all(isinstance(a, (int, sympy.Integer)) and a >= 0 for a in M)
    except Exception:
        h3 = False

    try:
        # H4: m_1, ..., m_n are elements of M
        # Represented as a list of lists, each of length k
        elements = witness.get('elements')
        k = len(M) if h3 else 0
        h4 = isinstance(elements, list) and all(isinstance(e, list) and len(e) == k for e in elements)
        if h4:
            for e in elements:
                if not all(isinstance(x, (int, sympy.Integer)) for x in e):
                    h4 = False
                    break
    except Exception:
        h4 = False

    try:
        # H5: The images of m_1, ..., m_n in M/mM form a basis for M/mM as a vector space over k
        if not (h2 and h3 and h4):
            h5 = False
        else:
            p = int(witness['m'])
            M = witness['M']
            elements = witness['elements']
            
            # M/mM is isomorphic to (Z/pZ)^d where d is the number of invariant factors divisible by p (or 0)
            indices = [i for i, a in enumerate(M) if a == 0 or a % p == 0]
            d = len(indices)
            n = len(elements)
            
            if n != d:
                h5 = False
            elif d == 0:
                # M/mM is the zero module, basis is empty
                h5 = True
            else:
                # Construct the d x d matrix of the images in M/mM
                mat = []
                for e in elements:
                    row = [int(e[i]) % p for i in indices]
                    mat.append(row)
                
                A = Matrix(mat)
                det = A.det()
                h5 = (det % p != 0)
    except Exception:
        h5 = False

    try:
        # neg_Q: The elements m_1, ..., m_n do NOT generate M as an R-module
        if not (h3 and h4):
            neg_q = False
        else:
            M = witness['M']
            elements = witness['elements']
            k = len(M)
            n = len(elements)
            
            if k == 0:
                # The zero module is generated by the empty set
                neg_q = False
            elif n + k > 15:
                # Fallback to Smith Normal Form for larger matrices to avoid TLE
                try:
                    from sympy.matrices.normalforms import smith_normal_form
                    cols = []
                    for e in elements:
                        cols.append([int(x) for x in e])
                    for i, a in enumerate(M):
                        col = [0] * k
                        col[i] = int(a)
                        cols.append(col)
                    mat = Matrix(cols).T
                    snf = smith_normal_form(mat)
                    prod = 1
                    for j in range(k):
                        prod *= abs(int(snf[j, j]))
                    neg_q = (prod != 1)
                except Exception:
                    neg_q = False
            else:
                # Construct block matrix [A | D] where A has columns m_i and D is diag(a_i)
                cols = []
                for e in elements:
                    cols.append([int(x) for x in e])
                for i, a in enumerate(M):
                    col = [0] * k
                    col[i] = int(a)
                    cols.append(col)
                
                mat = Matrix(cols).T
                
                # The elements generate M iff the GCD of all k x k minors of [A | D] is 1
                gcd_minors = 0
                for sub_cols in combinations(range(n + k), k):
                    sub_mat = mat[:, sub_cols]
                    minor = abs(int(sub_mat.det()))
                    gcd_minors = math.gcd(gcd_minors, minor)
                    if gcd_minors == 1:
                        break
                
                neg_q = (gcd_minors != 1)
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, h5, neg_q]

