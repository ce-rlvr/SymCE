import sympy as sp

# Top-level setup
# No specific named bindings needed for this Ring Theory conjecture,
# as witnesses are expected to be integers representing elements in ZZ or Z_n.

def conditions(witness) -> list[bool]:
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness can be a tuple (x, y) for the ring ZZ, 
    or (x, y, n) for the ring Z_n.
    Alternatively, a dictionary with keys 'x', 'y', and optionally 'n' can be provided.
    """
    try:
        if isinstance(witness, dict):
            if 'x' not in witness or 'y' not in witness:
                return [False, False, False]
            x = witness['x']
            y = witness['y']
            n = witness.get('n', 0)
        elif isinstance(witness, (tuple, list)):
            if len(witness) == 2:
                x, y = witness
                n = 0
            elif len(witness) == 3:
                x, y, n = witness
            else:
                return [False, False, False]
        else:
            return [False, False, False]
            
        # H_1: x and y are elements of R
        if not (isinstance(x, (int, sp.Integer)) and isinstance(y, (int, sp.Integer))):
            return [False, False, False]
        if not isinstance(n, (int, sp.Integer)):
            return [False, False, False]
            
        x_val = int(x)
        y_val = int(y)
        n_val = abs(int(n))
        h1 = True

        # H_2: I is the ideal generated by x and y
        # We implicitly define I as the ideal generated by x and y, so this is True.
        h2 = True

        # ¬Q: I is not the principal ideal generated by x + y + xy
        if n_val != 0:
            # In Z_n, the ideal generated by a set of elements is generated by their gcd with n.
            # Two principal ideals (a) and (b) are equal iff gcd(a, n) == gcd(b, n).
            x_val %= n_val
            y_val %= n_val
            I_val = sp.gcd(sp.gcd(x_val, y_val), n_val)
            
            gen_Q = (x_val + y_val + x_val * y_val) % n_val
            I_Q = sp.gcd(gen_Q, n_val)
            
            neg_q = bool(I_val != I_Q)
        else:
            # In ZZ, the ideal generated by x and y is generated by gcd(x, y).
            # Two principal ideals (a) and (b) are equal iff abs(a) == abs(b).
            I_val = sp.gcd(x_val, y_val)
            gen_Q = x_val + y_val + x_val * y_val
            
            neg_q = bool(abs(I_val) != abs(gen_Q))

        return [h1, h2, neg_q]
    except Exception:
        return [False, False, False]

