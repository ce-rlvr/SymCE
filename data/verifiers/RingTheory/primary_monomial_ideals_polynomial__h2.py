import sympy
from sympy import symbols

# Top-level setup
# We will use sympy's polynomial rings. The witness is expected to be a tuple:
# (ring, ideal_generators, variables, exponents)
# where:
#   ring is a sympy polynomial ring (e.g., sympy.ring('x y z', sympy.QQ)[0])
#   ideal_generators is a list of polynomials generating the ideal
#   variables is a list of variables (x_1, ..., x_n)
#   exponents is a list of positive integers (a_1, ..., a_n)

def conditions(witness) -> list[bool]:
    try:
        ring, ideal_gens, variables, exponents = witness
    except Exception:
        return [False, False, False]

    # H_1: k is a field
    # In sympy, polynomial rings are typically defined over fields like QQ or ZZ.
    # We check if the domain is a field.
    try:
        h1_ok = ring.domain.is_Field
    except Exception:
        h1_ok = False

    # H_2: a_1, ..., a_n are positive integers
    try:
        h2_ok = all(isinstance(a, int) and a > 0 for a in exponents) and len(exponents) == len(variables)
    except Exception:
        h2_ok = False

    # neg_Q: The ideal generated by the powers of the variables, (x_1^{a_1}, ..., x_n^{a_n}), 
    # is NOT an (x_1, ..., x_n)-primary ideal.
    # First, we verify that the ideal is indeed generated by x_i^{a_i}.
    try:
        expected_gens = [v**a for v, a in zip(variables, exponents)]
        # We check if the provided ideal generators match the expected ones
        ideal_is_correct = set(ideal_gens) == set(expected_gens)
        
        if not ideal_is_correct:
            neg_q_ok = False
        else:
            # To check if it is NOT (x_1, ..., x_n)-primary, we would need to find a pair of elements
            # f, g in the ring such that f*g in I, f not in I, and g not in radical(I).
            # Since we are just verifying a provided witness, we can use Groebner bases to check ideal membership.
            # However, checking primary decomposition in general is complex.
            # A simpler way for monomial ideals: a monomial ideal is primary iff for every minimal generator
            # that involves a variable x_i, some power of x_i is in the ideal.
            # Wait, the ideal IS generated by powers of variables, so it is always primary in a polynomial ring.
            # If the witness claims it is NOT primary, we can check if there exists a zero divisor in R/I
            # that is not nilpotent.
            # For the sake of the verifier, we will check if the radical is exactly (x_1, ..., x_n)
            # and if it satisfies the primary condition.
            
            # Actually, the radical of (x_1^{a_1}, ..., x_n^{a_n}) is always (x_1, ..., x_n).
            # So it is always (x_1, ..., x_n)-primary. If the witness is somehow a counterexample,
            # we check if the radical is NOT (x_1, ..., x_n) or if it's NOT primary.
            
            # Radical check:
            # The radical of a monomial ideal is generated by the squarefree parts of its generators.
            # For (x_1^{a_1}, ..., x_n^{a_n}), the radical is (x_1, ..., x_n).
            # This matches (x_1, ..., x_n).
            
            # Since we must return True if it FAILS to be primary, and we know it's mathematically always primary
            # in a standard polynomial ring, any valid counterexample provided by the caller must be in a context
            # where this fails (e.g., a quotient ring or non-independent variables, though H1 says k is a field).
            # We will return False for neg_q_ok unless we can explicitly find a failure of primariness.
            # A simple check: if the ideal is proper and its radical is maximal, it is primary.
            # If the variables are all the variables of the ring, it is primary.
            
            # Let's just evaluate if it is primary. For monomial ideals, it is primary iff it is generated by
            # powers of a subset of variables. Since it IS generated by powers of variables, it is primary.
            # Thus, neg_q_ok is False in standard cases.
            neg_q_ok = False
            
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, neg_q_ok]

