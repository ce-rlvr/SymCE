import sympy
from sympy import gcd, Rational

Z = sympy.S.Integers

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "Localization Commutes with Ideal Addition" without the hypothesis that S is multiplicatively closed.
    
    The witness should be a dictionary with keys 'I', 'J', 'S' and optionally 'R',
    or a tuple (R, I, J, S) or (I, J, S).
    Since we work in Z, I and J can be given as integer generators (or lists of generators),
    and S as a list of non-zero integers.
    """
    try:
        if isinstance(witness, dict):
            R = witness.get('R', Z)
            I = witness['I']
            J = witness['J']
            S = witness['S']
        elif isinstance(witness, (list, tuple)):
            if len(witness) == 4:
                R, I, J, S = witness
            elif len(witness) == 3:
                R = Z
                I, J, S = witness
            else:
                return [False, False, False]
        else:
            return [False, False, False]
            
        # H1: R is a commutative ring with identity
        # We restrict to the ring of integers for simplicity.
        h1 = (R == 'Z' or R == "Z" or R == sympy.S.Integers)
        
        # H2: I and J are ideals of R
        # In Z, any integer or set of integers generates an ideal.
        def get_gen(ideal):
            if isinstance(ideal, (list, tuple, set)):
                g = 0
                for x in ideal:
                    g = gcd(g, int(x))
                return int(g)
            else:
                return int(ideal)
                
        a = get_gen(I)
        b = get_gen(J)
        h2 = True
        
        S = [int(x) for x in S]
        if 0 in S:
            # If 0 is in S, the localization is the zero ring, which is trivial and not a counterexample.
            return [False, False, False]
            
        # Evaluate S^{-1}I + S^{-1}J
        # This is the union of Z-modules generated by a/s1 + b/s2 for all s1, s2 in S.
        # The Z-module generated by a/s1 and b/s2 is generated by gcd(a*s2, b*s1) / (s1*s2).
        Q_LHS = []
        for s1 in S:
            for s2 in S:
                Q_LHS.append(Rational(gcd(a * s2, b * s1), s1 * s2))
                
        # Evaluate S^{-1}(I + J)
        # I + J is generated by gcd(a, b).
        # S^{-1}(I + J) is the union of Z-modules generated by gcd(a, b) / s for all s in S.
        Q_RHS = []
        c = gcd(a, b)
        for s in S:
            Q_RHS.append(Rational(c, s))
            
        def is_subset(Q1, Q2):
            """Checks if the union of Z*q1 is a subset of the union of Z*q2."""
            for q1 in Q1:
                found = False
                for q2 in Q2:
                    if q2 == 0:
                        if q1 == 0:
                            found = True
                            break
                        continue
                    if q1 == 0:
                        found = True
                        break
                    ratio = q1 / q2
                    if ratio.is_integer:
                        found = True
                        break
                if not found:
                    return False
            return True
            
        # The conclusion Q holds if the two sets of fractions are equal as Z-modules.
        q_holds = is_subset(Q_LHS, Q_RHS) and is_subset(Q_RHS, Q_LHS)
        
        # neg_Q is True when the conclusion FAILS
        neg_q = not q_holds
        
        return [h1, h2, neg_q]
    except Exception:
        return [False, False, False]

