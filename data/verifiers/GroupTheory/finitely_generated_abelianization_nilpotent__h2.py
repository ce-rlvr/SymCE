def conditions(witness) -> list[bool]:
    # H_1: G is a nilpotent group
    try:
        h1 = False
        if hasattr(witness, 'is_nilpotent'):
            val = witness.is_nilpotent
            h1 = bool(val()) if callable(val) else bool(val)
        elif hasattr(witness, 'is_abelian'):
            val = witness.is_abelian
            h1 = bool(val()) if callable(val) else bool(val)
    except Exception:
        h1 = False

    # ¬Q: G is not a finitely generated group
    try:
        q = True  # Assume finitely generated by default unless explicitly stated otherwise
        if hasattr(witness, 'is_finitely_generated'):
            val = witness.is_finitely_generated
            q = bool(val()) if callable(val) else bool(val)
        elif isinstance(witness, PermutationGroup) or type(witness).__name__ == 'FpGroup':
            q = True
            
        neg_q = not q
    except Exception:
        neg_q = False

    return [h1, neg_q]

