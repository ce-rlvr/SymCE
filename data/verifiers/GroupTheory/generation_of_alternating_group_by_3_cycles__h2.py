def conditions(witness):
    try:
        if isinstance(witness, bool):
            h1 = False
        elif isinstance(witness, (int, sympy.Integer)):
            h1 = bool(witness >= 3)
        else:
            h1 = False
    except Exception:
        h1 = False

    try:
        if not h1:
            neg_q = False
        else:
            n_int = int(witness)
            if n_int > 20:
                neg_q = False
            else:
                cycles = []
                for p in itertools.permutations(range(n_int), 3):
                    if p[0] == min(p):
                        cycles.append(Permutation([list(p)], size=n_int))
                
                if not cycles:
                    G_order = 1
                else:
                    G = PermutationGroup(cycles)
                    G_order = G.order()
                
                An = AlternatingGroup(n_int)
                An_order = An.order()
                
                neg_q = bool(G_order != An_order)
    except Exception:
        neg_q = False

    return [h1, neg_q]

