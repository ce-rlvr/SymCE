def is_automorphism(G, gens, images, order):
    """
    Checks if the mapping of generators to images extends to a valid automorphism of G.
    Returns the full mapping dictionary if valid, otherwise None.
    """
    try:
        id_elem = G.identity
    except AttributeError:
        id_elem = list(G.elements)[0] ** 0

    mapping = {id_elem: id_elem}
    queue = [id_elem]
    head = 0
    
    while head < len(queue):
        curr = queue[head]
        head += 1
        curr_img = mapping[curr]
        
        for g, img in zip(gens, images):
            nxt = curr * g
            nxt_img = curr_img * img
            if nxt in mapping:
                if mapping[nxt] != nxt_img:
                    return None
            else:
                mapping[nxt] = nxt_img
                queue.append(nxt)
                
    if len(set(mapping.values())) == order:
        return mapping
    return None

def conditions(witness):
    try:
        G, H, n = witness
    except Exception:
        return [False, False, False]
        
    # H_1: G is a group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False
        
    # H_2: H is the subgroup of G generated by the set of all elements in G of order n
    try:
        if not isinstance(H, PermutationGroup) or not H.is_subgroup(G):
            h2 = False
        else:
            elements_of_order_n = [g for g in G.elements if g.order() == n]
            if not elements_of_order_n:
                try:
                    id_elem = G.identity
                except AttributeError:
                    id_elem = list(G.elements)[0] ** 0
                gen_subgroup = PermutationGroup([id_elem])
            else:
                gen_subgroup = PermutationGroup(elements_of_order_n)
            h2 = set(H.elements) == set(gen_subgroup.elements)
    except Exception:
        h2 = False
        
    # neg_Q: H is NOT a characteristic subgroup of G
    try:
        if not isinstance(H, PermutationGroup) or not H.is_subgroup(G):
            neg_q = False
        else:
            gens = G.generators
            elements = list(G.elements)
            candidates = [[x for x in elements if x.order() == g.order()] for g in gens]
            h_elements = set(H.elements)
            
            neg_q = False
            for p in itertools.product(*candidates):
                mapping = is_automorphism(G, gens, p, int(G.order()))
                if mapping is not None:
                    # Check if this automorphism preserves H
                    for h in H.generators:
                        if mapping[h] not in h_elements:
                            neg_q = True
                            break
                if neg_q:
                    break
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

