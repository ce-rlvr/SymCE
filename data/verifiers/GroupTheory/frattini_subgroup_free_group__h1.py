CONDITION_LABELS = [
    "H_1: The rank of F is at least 2",
    "¬Q: The Frattini subgroup of F is NOT trivial"
]

N_HYP = 1
NEG_Q_INDEX = 1

def conditions(witness):
    try:
        # A finite group has rank >= 2 iff it is not cyclic
        h1 = not witness.is_cyclic
    except Exception:
        h1 = False

    try:
        order = witness.order()
        if order == 1:
            neg_q = False
        else:
            factors = factorint(order)
            if len(factors) == 1:
                # For a p-group, the Frattini subgroup is generated by p-th powers and commutators.
                # It is trivial iff all p-th powers and commutators are the identity.
                p = list(factors.keys())[0]
                elements = list(witness.elements)
                is_trivial = True
                for g in elements:
                    if g**p != witness.identity:
                        is_trivial = False
                        break
                if is_trivial:
                    for g in elements:
                        for h in elements:
                            if g**-1 * h**-1 * g * h != witness.identity:
                                is_trivial = False
                                break
                        if not is_trivial:
                            break
                neg_q = not is_trivial
            else:
                # For non-p-groups, we find all subgroups to identify the maximal ones.
                elements = list(witness.elements)
                current_subgroups = {frozenset([witness.identity])}
                
                for g in elements:
                    if g == witness.identity:
                        continue
                    new_subgroups = set()
                    for H_set in current_subgroups:
                        if g not in H_set:
                            new_H = PermutationGroup(list(H_set) + [g])
                            new_H_set = frozenset(new_H.elements)
                            if new_H_set not in current_subgroups:
                                new_subgroups.add(new_H_set)
                    current_subgroups.update(new_subgroups)
                    
                proper_subgroups = [S for S in current_subgroups if len(S) < order]
                maximal_subgroups = []
                for S in proper_subgroups:
                    is_maximal = True
                    for other in proper_subgroups:
                        if len(S) < len(other) and S.issubset(other):
                            is_maximal = False
                            break
                    if is_maximal:
                        maximal_subgroups.append(S)
                        
                if not maximal_subgroups:
                    neg_q = False
                else:
                    # The Frattini subgroup is the intersection of all maximal subgroups
                    frattini_elements = set(maximal_subgroups[0]).intersection(*maximal_subgroups[1:])
                    neg_q = len(frattini_elements) > 1
    except Exception:
        neg_q = False

    return [h1, neg_q]