def get_order(group):
    order_attr = group.order
    if callable(order_attr):
        return order_attr()
    return order_attr

def conditions(witness):
    try:
        G, A, action = witness
    except Exception:
        return [False, False, False, False]
        
    # H_1: G is a finite group
    try:
        h1 = bool(get_order(G) > 0)
    except Exception:
        h1 = False
        
    # H_2: A is a finite abelian group
    try:
        h2 = bool(getattr(A, 'is_abelian', False) and get_order(A) > 0)
    except Exception:
        h2 = False
        
    # H_3: The orders of G and A are coprime
    try:
        h3 = bool(math.gcd(get_order(G), get_order(A)) == 1)
    except Exception:
        h3 = False
        
    # ¬Q: A does not decompose as the direct sum C_A(G) and commutator of G and A
    try:
        A_elements = list(A.elements)
        G_elements = list(G.elements)
        
        if not A_elements or not G_elements:
            raise ValueError("Groups cannot be empty")
            
        id_A = None
        for a in A_elements:
            if getattr(a, 'is_Identity', False):
                id_A = a
                break
        if id_A is None:
            id_A = A_elements[0] * (A_elements[0]**-1)
            
        id_G = None
        for g in G_elements:
            if getattr(g, 'is_Identity', False):
                id_G = g
                break
        if id_G is None:
            id_G = G_elements[0] * (G_elements[0]**-1)
            
        A_elements_set = set(A_elements)
        
        # Validate that the provided action is a valid group action
        for a in A_elements:
            if action(id_G, a) != a:
                raise ValueError("Not a valid group action: identity does not act trivially")
                
        for g in G_elements:
            for h in G_elements:
                gh = g * h
                for a in A_elements:
                    act_h_a = action(h, a)
                    if act_h_a not in A_elements_set:
                        raise ValueError("Action must map to A")
                    if action(g, act_h_a) != action(gh, a):
                        raise ValueError("Not a valid group action: not compatible with group multiplication")
        
        # C_A(G) = { a in A | action(g, a) == a for all g in G }
        C_A_G = set()
        for a in A_elements:
            is_fixed = True
            for g in G_elements:
                if action(g, a) != a:
                    is_fixed = False
                    break
            if is_fixed:
                C_A_G.add(a)
                
        # Check if C_A(G) is a subgroup
        is_subgroup_C = True
        if id_A not in C_A_G:
            is_subgroup_C = False
        else:
            for x in C_A_G:
                for y in C_A_G:
                    if (x * y) not in C_A_G:
                        is_subgroup_C = False
                        break
                if not is_subgroup_C:
                    break
            if is_subgroup_C:
                for x in C_A_G:
                    if (x**-1) not in C_A_G:
                        is_subgroup_C = False
                        break
                        
        # commutator of G and A = subgroup generated by { action(g, a) * a**-1 | g in G, a in A }
        commutators = []
        for g in G_elements:
            for a in A_elements:
                val = action(g, a) * (a**-1)
                commutators.append(val)
                
        if not commutators:
            commutators = [id_A]
            
        G_A_subgroup = PermutationGroup(commutators)
        
        # Check direct sum conditions
        if not is_subgroup_C:
            conclusion = False
        else:
            intersection = C_A_G.intersection(set(G_A_subgroup.elements))
            if intersection != {id_A}:
                conclusion = False
            else:
                if len(C_A_G) * get_order(G_A_subgroup) != get_order(A):
                    conclusion = False
                else:
                    conclusion = True
                    
        neg_q = not conclusion
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

