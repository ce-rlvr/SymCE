def conditions(witness):
    """
    Checks whether the given witness is a valid counterexample to the false conjecture.
    The witness should be a tuple (F, X, Y, H).
    """
    try:
        F, X, Y, H = witness
    except Exception:
        return [False, False, False, False]
        
    # H_1: F is a free group
    try:
        h1 = type(F).__name__ == 'FreeGroup' and hasattr(F, 'generators')
    except Exception:
        h1 = False
        
    # H_2: X is a free basis for F
    try:
        h2 = set(X) == set(F.generators)
    except Exception:
        h2 = False
        
    # H_3: Y is a subset of X
    try:
        h3 = set(Y).issubset(set(X))
    except Exception:
        h3 = False
        
    # ¬Q: H is not a free factor of F, or Y does not freely generate H
    try:
        Y_set = set(Y)
        
        # If Y freely generates H, then H must be exactly the subgroup generated by Y.
        # Since Y is a subset of the free basis X, <Y> is always a free factor of F.
        # Thus, the conclusion holds iff Y freely generates H (i.e., <H> == <Y>).
        # We check if H contains any elements outside of <Y>. If it does, Y definitely
        # does not generate H, making the conclusion false (so neg_q should be True).
        if type(H).__name__ == 'FreeGroup':
            y_gens_h = True
        else:
            if hasattr(H, 'generators') and type(H).__name__ != 'FreeGroup':
                H_elements = H.generators
            elif isinstance(H, (list, set, tuple)):
                H_elements = H
            else:
                H_elements = None
                
            if H_elements is not None:
                y_gens_h = True
                for h in H_elements:
                    gens = set()
                    if hasattr(h, 'array_form'):
                        for g, exp in h.array_form:
                            gens.add(g)
                    # If an element of H uses generators not in Y, H is not a subset of <Y>
                    if not gens.issubset(Y_set):
                        y_gens_h = False
                        break
                
                # If H is trivial but Y is not, Y does not freely generate H
                if y_gens_h and not H_elements and Y_set:
                    y_gens_h = False
            else:
                y_gens_h = True
                
        neg_q = not y_gens_h
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

