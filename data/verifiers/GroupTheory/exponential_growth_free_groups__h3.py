def conditions(witness) -> list[bool]:
    try:
        F, S = witness
    except Exception:
        return [False, False, False]
    
    # H_1: F is a free group of finite rank k
    try:
        h1 = isinstance(F, FreeGroup) and len(F.generators) < float('inf')
    except Exception:
        h1 = False
        
    # H_2: k >= 2
    try:
        k = len(F.generators)
        h2 = k >= 2
    except Exception:
        h2 = False
        
    # neg_Q: The word growth function of F with respect to S is NOT strictly exponential.
    # In a free group, a subgroup has strictly exponential growth iff it is non-abelian.
    # Thus, the growth is NOT strictly exponential iff the subgroup generated by S is abelian,
    # which is equivalent to all elements in S commuting with each other.
    try:
        if not isinstance(S, (list, tuple, set)):
            neg_q = False
        else:
            # Check that all elements in S belong to F
            if not all(hasattr(s, 'group') and s.group == F for s in S):
                neg_q = False
            else:
                neg_q = True
                S_list = list(S)
                for i in range(len(S_list)):
                    for j in range(i + 1, len(S_list)):
                        if S_list[i] * S_list[j] != S_list[j] * S_list[i]:
                            neg_q = False
                            break
                    if not neg_q:
                        break
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

