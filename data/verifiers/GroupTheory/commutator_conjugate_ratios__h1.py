def get_elements(G):
    if hasattr(G, 'elements'):
        return list(G.elements)
    elif hasattr(G, 'generate'):
        return list(G.generate())
    else:
        return list(G)

def generate_subgroup_elements(generators, identity):
    closure = set(generators)
    if not closure:
        return {identity}
    
    queue = list(closure)
    while queue:
        x = queue.pop(0)
        for y in list(closure):
            xy = x * y
            if xy not in closure:
                closure.add(xy)
                queue.append(xy)
            yx = y * x
            if yx not in closure:
                closure.add(yx)
                queue.append(yx)
    return closure

def conditions(witness):
    try:
        # The witness is expected to be a tuple (G, obj)
        # where obj can be the set S, the conjugacy class C, or a representative element x of C.
        if isinstance(witness, tuple) and len(witness) == 2:
            G, obj = witness
        else:
            return [False, False]
            
        elements = get_elements(G)
        if not elements:
            return [False, False]
            
        # Find the identity element
        identity = None
        for e in elements:
            if e * e == e:
                identity = e
                break
        if identity is None:
            identity = elements[0]**0
            
        # Compute all conjugacy classes of G
        classes = []
        seen = set()
        for g in elements:
            if g not in seen:
                C = set()
                for h in elements:
                    C.add(h**-1 * g * h)
                classes.append(C)
                seen.update(C)
                
        H1 = False
        S = None
        
        try:
            is_single = obj in elements
        except Exception:
            is_single = False
            
        if is_single:
            H1 = True
            for C in classes:
                if obj in C:
                    S = set(x**-1 * y for x in C for y in C)
                    break
        else:
            try:
                if hasattr(obj, 'generate'):
                    obj_set = set(obj.generate())
                elif hasattr(obj, 'elements'):
                    obj_set = set(obj.elements)
                else:
                    obj_set = set(obj)
            except TypeError:
                return [False, False]
                
            # Check if obj is the set S for some conjugacy class C
            for C in classes:
                S_C = set(x**-1 * y for x in C for y in C)
                if obj_set == S_C:
                    H1 = True
                    S = S_C
                    break
                    
            # Check if obj is the conjugacy class C itself
            if not H1:
                for C in classes:
                    if obj_set == C:
                        H1 = True
                        S = set(x**-1 * y for x in C for y in C)
                        break
                        
        if not H1 or S is None:
            return [False, False]
            
        # Compute the derived subgroup G'
        commutators = set()
        for a in elements:
            for b in elements:
                commutators.add(a**-1 * b**-1 * a * b)
                
        G_prime_elements = generate_subgroup_elements(commutators, identity)
        
        # Compute the subgroup generated by S
        S_gen = generate_subgroup_elements(S, identity)
        
        # The conclusion fails if G' is NOT generated by S
        neg_Q = (S_gen != G_prime_elements)
        
        return [H1, neg_Q]
    except Exception:
        return [False, False]

