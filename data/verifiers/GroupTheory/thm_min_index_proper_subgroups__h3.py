def is_semisimple(G):
    """
    A finite group is semisimple if it has no non-trivial normal abelian subgroups.
    Equivalently, its solvable radical is trivial.
    """
    if getattr(G, "order", lambda: 0)() == 1:
        return True
    
    try:
        classes = G.conjugacy_classes()
        for c in classes:
            elements = list(c)
            if not elements:
                continue
            x = elements[0]
            if x.is_Identity:
                continue
            # The normal closure of <x> is generated by its conjugacy class
            N = PermutationGroup(*elements)
            if N.is_abelian:
                return False
        return True
    except Exception:
        pass

    # Fallback: BFS to find conjugacy classes and check normal closures
    try:
        seen = set()
        gens = G.generators
        for x in G.generate():
            if x.is_Identity:
                continue
            if x in seen:
                continue
            
            conjugates = {x}
            queue = [x]
            while queue:
                curr = queue.pop(0)
                for g in gens:
                    conj = g * curr * ~g
                    if conj not in conjugates:
                        conjugates.add(conj)
                        queue.append(conj)
            seen.update(conjugates)
            
            N = PermutationGroup(*list(conjugates))
            if N.is_abelian:
                return False
        return True
    except Exception:
        return False

def conditions(witness):
    # The witness should be a tuple (G, H) where H is a proper subgroup of G
    try:
        if isinstance(witness, tuple):
            G, H = witness
        else:
            G = witness
            H = None
    except Exception:
        return [False, False, False]

    # H_1: G is a semisimple finite group
    try:
        h1 = is_semisimple(G)
    except Exception:
        h1 = False

    # H_2: G is not the trivial group
    try:
        h2 = G.order() > 1
    except Exception:
        h2 = False

    # ¬Q: The index of H in G is less than 5
    try:
        if H is not None:
            is_sub = all(g in G for g in H.generators)
            if is_sub and H.order() < G.order():
                idx = G.order() // H.order()
                neg_q = idx < 5
            else:
                neg_q = False
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [bool(h1), bool(h2), bool(neg_q)]

