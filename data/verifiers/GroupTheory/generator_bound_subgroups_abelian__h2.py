def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, dict):
            G = witness['G']
            H = witness['H']
            n = witness['n']
        else:
            G, H, n = witness
    except Exception:
        return [False, False, False]

    # H_1: G is an abelian group
    try:
        h1_ok = bool(G.is_abelian)
    except Exception:
        h1_ok = False

    # H_2: H is a subgroup of G
    try:
        h2_ok = bool(H.is_subgroup(G))
    except Exception:
        h2_ok = False

    # ¬Q: H cannot be generated by at most n elements
    try:
        if not isinstance(n, int):
            neg_q_ok = False
        else:
            elements = list(H.generate())
            order = H.order()
            
            if order == 1:
                can_generate = (n >= 0)
            elif n >= order:
                can_generate = True
            else:
                can_generate = False
                for k in range(1, n + 1):
                    for subset in itertools.combinations(elements, k):
                        if PermutationGroup(*subset).order() == order:
                            can_generate = True
                            break
                    if can_generate:
                        break
            neg_q_ok = not can_generate
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, neg_q_ok]

