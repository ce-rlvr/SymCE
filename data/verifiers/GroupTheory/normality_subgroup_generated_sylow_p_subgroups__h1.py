def get_normal_closure(G, P):
    if P.order() == 1:
        return P
    closure_gens = list(P.generators)
    current_group = PermutationGroup(closure_gens)
    G_gens = list(G.generators)
    
    while True:
        order = current_group.order()
        new_gens = list(closure_gens)
        for g in G_gens:
            ginv = ~g
            for x in closure_gens:
                new_gens.append(g * x * ginv)
                new_gens.append(ginv * x * g)
        
        next_group = PermutationGroup(new_gens)
        if next_group.order() == order:
            return current_group
        closure_gens = list(next_group.generators)
        current_group = next_group

def is_normal_subgroup(G, H):
    try:
        if not H.is_subgroup(G):
            return False
    except Exception:
        for h in H.generators:
            if h not in G:
                return False
                
    for g in G.generators:
        ginv = ~g
        for h in H.generators:
            if (g * h * ginv) not in H:
                return False
            if (ginv * h * g) not in H:
                return False
    return True

def conditions(witness):
    try:
        G, H, p = witness
    except Exception:
        return [False, False, False]
        
    # H_1: p is a prime number
    try:
        h1_ok = bool(sympy.ntheory.isprime(p))
    except Exception:
        h1_ok = False
        
    # H_2: H is the subgroup of G generated by the union of all Sylow p-subgroups of G
    try:
        P = G.sylow_subgroup(p)
        K = get_normal_closure(G, P)
        h2_ok = bool(H.is_subgroup(K) and K.is_subgroup(H))
    except Exception:
        h2_ok = False
        
    # neg_Q: H is NOT a normal subgroup of G
    try:
        neg_q = not is_normal_subgroup(G, H)
    except Exception:
        neg_q = False
        
    return [h1_ok, h2_ok, neg_q]

