def is_cyclic_subgroup(F, gens):
    """
    Checks if a finitely generated subgroup of the multiplicative group of a field is cyclic.
    """
    # Any subgroup of the multiplicative group of a finite field is cyclic.
    if getattr(F, 'is_FiniteField', False):
        return True
        
    # Remove 1s as they don't affect the generated subgroup
    gens = [g for g in gens if g != 1]
    
    # Remove duplicates
    unique_gens = []
    for g in gens:
        if g not in unique_gens:
            unique_gens.append(g)
    gens = unique_gens
    
    # A subgroup generated by 0 or 1 element is trivially cyclic
    if len(gens) <= 1:
        return True
        
    try:
        rationals = [Rational(g) for g in gens]
    except Exception:
        # If elements cannot be parsed as rationals, we conservatively assume it's not cyclic
        # (Counterexamples for this theorem are typically found in Q).
        return False
        
    signs = []
    exponents = []
    primes = set()
    
    for r in rationals:
        if r == 0:
            return False
        if r < 0:
            signs.append(1)
            r = -r
        else:
            signs.append(0)
            
        num, den = r.as_numer_denom()
        f_num = sympy.factorint(num)
        f_den = sympy.factorint(den)
        
        exp_dict = {}
        for p, e in f_num.items():
            exp_dict[p] = exp_dict.get(p, 0) + e
            primes.add(p)
        for p, e in f_den.items():
            exp_dict[p] = exp_dict.get(p, 0) - e
            primes.add(p)
            
        exponents.append(exp_dict)
        
    primes = sorted(list(primes))
    
    E = []
    for exp_dict in exponents:
        E.append([exp_dict.get(p, 0) for p in primes])
        
    first_nonzero = -1
    for i, row in enumerate(E):
        if any(x != 0 for x in row):
            first_nonzero = i
            break
            
    if first_nonzero == -1:
        # All elements are in {-1, 1}, which generates a finite (hence cyclic) subgroup
        return True
        
    E_first = E[first_nonzero]
    g_gcd = 0
    for x in E_first:
        g_gcd = math.gcd(g_gcd, abs(x))
        
    X1 = [x // g_gcd for x in E_first]
    
    idx = -1
    for i, x in enumerate(X1):
        if x != 0:
            idx = i
            break
            
    qs = []
    for i, row in enumerate(E):
        if all(x == 0 for x in row):
            qs.append(0)
            continue
            
        if row[idx] % X1[idx] != 0:
            return False
        q = row[idx] // X1[idx]
        
        if row != [q * x for x in X1]:
            return False
            
        qs.append(q)
        
    c = 0
    for q in qs:
        c = math.gcd(c, abs(q))
        
    cs = [q // c if c != 0 else 0 for q in qs]
    
    # Check if there's a valid sign assignment for the generator
    if all(signs[i] == 0 for i in range(len(signs))):
        return True
        
    if all(signs[i] == (cs[i] % 2) for i in range(len(signs))):
        return True
        
    return False

def conditions(witness) -> list[bool]:
    try:
        if len(witness) != 2:
            return [False, False, False, False]
        F, G = witness
    except Exception:
        return [False, False, False, False]
        
    try:
        iter(G)
        G_list = list(G)
    except TypeError:
        G_list = [G]
        
    # H_1: F is a field
    try:
        h1 = bool(getattr(F, 'is_Field', False)) or F in (sympy.S.Reals, sympy.S.Complexes, sympy.S.Rationals)
    except Exception:
        h1 = False
        
    # H_2: F^\times is the multiplicative group of non-zero elements of F
    try:
        h2 = all(g in F for g in G_list) and all(g != 0 for g in G_list)
    except Exception:
        h2 = False
        
    # H_3: G is a subgroup of F^\times
    # (Represented by a list of generators in F^\times, which inherently forms a subgroup)
    try:
        h3 = h2
    except Exception:
        h3 = False
        
    # ¬Q: G is not a cyclic group
    try:
        neg_q = not is_cyclic_subgroup(F, G_list)
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

