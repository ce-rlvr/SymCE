def conditions(witness) -> list[bool]:
    # The witness is expected to be the matrix A.
    # If a tuple (n, A) is provided, we unpack it.
    if isinstance(witness, tuple) and len(witness) == 2:
        n, A = witness
    else:
        A = witness
        try:
            n = A.rows
        except Exception:
            n = 0

    try:
        h1_ok = isinstance(n, (int, sympy.Integer)) and n > 0
    except Exception:
        h1_ok = False

    try:
        h2_ok = hasattr(A, 'is_square') and A.is_square and getattr(A, 'rows', -1) == n and getattr(A, 'cols', -1) == n
    except Exception:
        h2_ok = False

    try:
        h3_ok = all(sympy.sympify(e).is_integer for e in A)
    except Exception:
        h3_ok = False

    try:
        # The conclusion states that the index of H in G is finite and equal to |det(A)|.
        # For a subgroup H generated by the columns of an integer matrix A in Z^n,
        # the index is finite if and only if det(A) != 0.
        # If det(A) != 0, the index is exactly |det(A)|.
        # Therefore, the conclusion fails (is false) if and only if det(A) == 0,
        # in which case the index is infinite.
        neg_q_ok = (A.det() == 0)
    except Exception:
        neg_q_ok = False

    return [bool(h1_ok), bool(h2_ok), bool(h3_ok), bool(neg_q_ok)]

