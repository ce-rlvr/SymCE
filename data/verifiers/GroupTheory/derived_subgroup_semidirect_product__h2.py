def generate_subgroup(gens, identity, mul_op):
    closure = set(gens)
    closure.add(identity)
    added = True
    while added:
        added = False
        new_elements = set()
        for x in closure:
            for y in closure:
                xy = mul_op(x, y)
                if xy not in closure:
                    new_elements.add(xy)
        if new_elements:
            closure.update(new_elements)
            added = True
    return closure

def conditions(witness):
    try:
        N, H, phi = witness
    except Exception:
        return [False, False, False, False]

    try:
        h1 = isinstance(N, PermutationGroup) and isinstance(H, PermutationGroup)
    except Exception:
        h1 = False

    try:
        h2 = True
        N_elems = list(N.generate())
        H_elems = list(H.generate())
        id_N = N.identity
        id_H = H.identity

        for h in H_elems:
            for n1 in N_elems:
                for n2 in N_elems:
                    if phi(h, n1 * n2) != phi(h, n1) * phi(h, n2):
                        h2 = False
        for h1_elem in H_elems:
            for h2_elem in H_elems:
                for n in N_elems:
                    if phi(h1_elem, phi(h2_elem, n)) != phi(h1_elem * h2_elem, n):
                        h2 = False
        for n in N_elems:
            if phi(id_H, n) != n:
                h2 = False
    except Exception:
        h2 = False

    h3 = h1 and h2

    try:
        def G_mul(x, y):
            n1, h1_elem = x
            n2, h2_elem = y
            return (n1 * phi(h1_elem, n2), h1_elem * h2_elem)

        def G_inv(x):
            n, h_elem = x
            h_inv = h_elem**-1
            return (phi(h_inv, n**-1), h_inv)

        G_elems = [(n, h) for n in N_elems for h in H_elems]
        G_id = (id_N, id_H)

        G_commutators = set()
        for x in G_elems:
            for y in G_elems:
                xy = G_mul(x, y)
                x_inv = G_inv(x)
                y_inv = G_inv(y)
                x_inv_y_inv = G_mul(x_inv, y_inv)
                comm = G_mul(xy, x_inv_y_inv)
                G_commutators.add(comm)

        G_prime = generate_subgroup(G_commutators, G_id, G_mul)

        N_commutators = set()
        for n1 in N_elems:
            for n2 in N_elems:
                N_commutators.add(n1 * n2 * (n1**-1) * (n2**-1))
        N_prime = generate_subgroup(N_commutators, id_N, lambda x, y: x * y)

        H_commutators = set()
        for h1_elem in H_elems:
            for h2_elem in H_elems:
                H_commutators.add(h1_elem * h2_elem * (h1_elem**-1) * (h2_elem**-1))
        H_prime = generate_subgroup(H_commutators, id_H, lambda x, y: x * y)

        NH_gens = set()
        for n in N_elems:
            for h in H_elems:
                NH_gens.add((n**-1) * phi(h, n))
        NH_comm = generate_subgroup(NH_gens, id_N, lambda x, y: x * y)

        K_gens = N_prime.union(NH_comm)
        K = generate_subgroup(K_gens, id_N, lambda x, y: x * y)

        RHS = set()
        for k in K:
            for hp in H_prime:
                RHS.add((k, hp))

        neg_q = (G_prime != RHS)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

