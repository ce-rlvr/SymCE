def get_elements(G):
    """Return all elements of a PermutationGroup as a set."""
    return set(list(G.generate()))

def group_intersection(G1, G2):
    """Compute the intersection of two PermutationGroups."""
    elts = get_elements(G1).intersection(get_elements(G2))
    return PermutationGroup(list(elts))

def is_normal(G, N):
    """Check if N is a normal subgroup of G."""
    if not N.is_subgroup(G): 
        return False
    n_elts = get_elements(N)
    for g in G.generators:
        for n in N.generators:
            if (~g * n * g) not in n_elts: 
                return False
            if (g * n * ~g) not in n_elts: 
                return False
    return True

def is_nonabelian_simple(M):
    """Check if a group is a non-abelian simple group."""
    if M.order() <= 1: 
        return False
    if M.is_abelian: 
        return False
    # A group is simple iff it has exactly 2 normal subgroups (trivial and itself)
    return len(M.normal_subgroups()) == 2

def is_prod_nonabelian_simple(H):
    """Check if a group is isomorphic to a direct product of non-abelian simple groups."""
    if H.order() == 1: 
        return False
    if H.is_abelian: 
        return False
    
    normals = H.normal_subgroups()
    minimals = []
    
    # Find all minimal normal subgroups
    for N in normals:
        if N.order() == 1: 
            continue
        is_min = True
        for K in normals:
            if K.order() == 1 or K.order() >= N.order(): 
                continue
            if K.is_subgroup(N):
                is_min = False
                break
        if is_min:
            minimals.append(N)
            
    if not minimals: 
        return False
        
    # Each minimal normal subgroup must be a non-abelian simple group
    for M in minimals:
        if not is_nonabelian_simple(M):
            return False
            
    # The group must be generated by its minimal normal subgroups
    gens = []
    for M in minimals:
        gens.extend(M.generators)
        
    gen_group = PermutationGroup(gens)
    return gen_group.order() == H.order()

def conditions(witness):
    """
    Check the hypotheses and the negated conclusion for the given witness.
    The witness is expected to be a tuple: (G, N_1, N_2)
    """
    try:
        G, N_1, N_2 = witness
    except Exception:
        return [False, False, False, False]
        
    # H_1: G is a finite group (and N_1, N_2 are valid subgroups)
    try:
        h1 = isinstance(G, PermutationGroup) and G.order() > 0
        if not (isinstance(N_1, PermutationGroup) and isinstance(N_2, PermutationGroup)):
            h1 = False
        elif not (N_1.is_subgroup(G) and N_2.is_subgroup(G)):
            h1 = False
    except Exception:
        h1 = False

    # H_2: G is isomorphic to a direct product of non-abelian simple groups
    try:
        h2 = is_prod_nonabelian_simple(G)
    except Exception:
        h2 = False

    # H_3: N_2 is a normal subgroup of G
    try:
        h3 = is_normal(G, N_2)
    except Exception:
        h3 = False

    # ¬Q: The intersection N_1 \cap N_2 is neither the trivial subgroup 
    # nor isomorphic to a direct product of non-abelian simple groups.
    try:
        I = group_intersection(N_1, N_2)
        if I.order() == 1:
            concl = True
        else:
            concl = is_prod_nonabelian_simple(I)
        neg_q = not concl
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

