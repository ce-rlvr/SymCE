def conditions(witness) -> list[bool]:
    try:
        involutions = [g for g in witness.elements if g.order() == 2]
        if not involutions:
            neg_q = bool(witness.order() > 1)
        else:
            H = PermutationGroup(involutions)
            neg_q = bool(H.order() < witness.order())
    except Exception:
        neg_q = False

    return [neg_q]

