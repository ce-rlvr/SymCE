def conditions(witness):
    try:
        h1 = isinstance(witness, (int, sympy.Integer))
    except Exception:
        h1 = False

    try:
        if h1:
            neg_q = not sympy.ntheory.isprime(witness)
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, neg_q]

