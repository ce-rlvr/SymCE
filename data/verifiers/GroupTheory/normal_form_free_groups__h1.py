def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness should be a tuple: (F, X, w, word1, word2) where:
      - F is a FreeGroup
      - X is a list of elements in F that generates F
      - w is an element of F
      - word1 and word2 are two DIFFERENT reduced words over X U X^-1 that both evaluate to w
    """
    try:
        F, X, w, word1, word2 = witness
    except Exception:
        return [False, False, False]
        
    try:
        # H_1: F(X) is the free group generated by X
        # We verify F is a FreeGroup, X is a subset of F, and X generates F 
        # (sufficiently checked if all free generators of F are in X).
        h1 = type(F).__name__ == 'FreeGroup'
        if h1:
            h1 = all(x in F for x in X) and all(g in X for g in F.generators)
    except Exception:
        h1 = False
        
    try:
        # H_2: w is an element of F(X)
        h2 = w in F
    except Exception:
        h2 = False
        
    try:
        # ¬Q: w can NOT be uniquely represented by a reduced word over X U X^-1
        # We verify this by checking if word1 and word2 are two distinct valid reduced words for w.
        word1 = list(word1)
        word2 = list(word2)
        X_inv = [x**-1 for x in X]
        alphabet = list(X) + X_inv
        
        def is_valid_word(word):
            return all(u in alphabet for u in word)
            
        id_elem = w**0
        
        def is_reduced(word):
            # A word is reduced if no adjacent elements are inverses of each other
            for i in range(len(word) - 1):
                if word[i] * word[i+1] == id_elem:
                    return False
            return True
            
        def evaluate(word):
            res = id_elem
            for u in word:
                res = res * u
            return res

        neg_q = (
            is_valid_word(word1) and 
            is_valid_word(word2) and 
            is_reduced(word1) and 
            is_reduced(word2) and 
            word1 != word2 and 
            evaluate(word1) == w and 
            evaluate(word2) == w
        )
    except Exception:
        neg_q = False
        
    return [bool(h1), bool(h2), bool(neg_q)]

