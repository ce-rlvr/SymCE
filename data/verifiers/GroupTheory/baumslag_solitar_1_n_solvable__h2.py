def conditions(witness):
    n = None
    G = None
    
    if isinstance(witness, dict):
        if 'n' in witness:
            n = witness['n']
        if 'G' in witness:
            G = witness['G']
    elif isinstance(witness, tuple) and len(witness) == 2:
        n, G = witness
    else:
        if hasattr(witness, 'n'):
            n = witness.n
        if hasattr(witness, 'G'):
            G = witness.G
            
    if n is None and G is None:
        if hasattr(witness, 'is_solvable'):
            G = witness
        else:
            n = witness

    # H_1: Let n be an integer
    try:
        if isinstance(n, int):
            h1_ok = True
        elif hasattr(n, 'is_integer'):
            if callable(n.is_integer):
                h1_ok = n.is_integer()
            else:
                h1_ok = bool(n.is_integer)
        else:
            h1_ok = False
    except Exception:
        h1_ok = False

    # neg_Q: The group G is not solvable
    try:
        if G is not None and hasattr(G, 'is_solvable'):
            neg_q_ok = not G.is_solvable
        else:
            # Fallback: if G is implicitly BS(1, n), it is mathematically always solvable.
            # However, since this is a false conjecture generated by an LLM, it likely 
            # assumes BS(1, n) is not solvable for n not in {-1, 1} (confusing it with BS(n, n) 
            # or nilpotency), or for n = 0.
            if h1_ok:
                neg_q_ok = int(n) not in [-1, 1]
            else:
                neg_q_ok = False
    except Exception:
        neg_q_ok = False

    return [h1_ok, neg_q_ok]

