def conditions(witness) -> list[bool]:
    try:
        G, x = witness
    except Exception:
        return [False, False, False]
    
    # H_1: x is an element of G
    try:
        h1 = bool(G.contains(x))
    except Exception:
        h1 = False
        
    # H_2: G is generated by the set Z(G) \cup \{x\}
    try:
        Z = G.center()
        gens = list(Z.generators) + [x]
        H = PermutationGroup(gens)
        # Check if H is a subgroup of G and has the same order
        is_sub = all(G.contains(g) for g in gens)
        h2 = bool(is_sub and H.order() == G.order())
    except Exception:
        h2 = False
        
    # ¬Q: G is not an abelian group
    try:
        neg_q = not bool(G.is_abelian)
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

