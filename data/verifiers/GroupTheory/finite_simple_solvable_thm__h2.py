Z6 = CyclicGroup(6)
trivial = CyclicGroup(1)

def conditions(witness):
    try:
        h1 = isinstance(witness, PermutationGroup)
    except Exception:
        h1 = False

    try:
        h2 = bool(witness.is_solvable)
    except Exception:
        h2 = False

    try:
        neg_q = not isprime(witness.order())
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

