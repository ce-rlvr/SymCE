def conditions(witness):
    try:
        G, a, b, m, n = witness
    except Exception:
        return [False] * 5 + [False]
        
    # H_1: G is a group
    try:
        h1 = bool(isinstance(G, PermutationGroup))
    except Exception:
        h1 = False
        
    # H_2: a and b are elements of G
    try:
        h2 = bool(a in G and b in G)
    except Exception:
        h2 = False
        
    # H_3: a and b commute (ab = ba)
    try:
        h3 = bool(a * b == b * a)
    except Exception:
        h3 = False
        
    # H_4: The order of a is a finite integer m
    try:
        h4 = bool(isinstance(m, int) and a.order() == m)
    except Exception:
        h4 = False
        
    # H_5: \gcd(m, n) = 1
    try:
        h5 = bool(isinstance(n, int) and math.gcd(m, n) == 1)
    except Exception:
        h5 = False
        
    # ¬Q: The order of the product ab is mn, and the subgroup generated by ab is a cyclic group of order mn.
    try:
        neg_q = bool((a * b).order() != m * n)
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, h4, h5, neg_q]

