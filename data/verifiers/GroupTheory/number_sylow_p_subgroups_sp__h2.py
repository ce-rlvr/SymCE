import sympy
from sympy.combinatorics import SymmetricGroup, AlternatingGroup, DihedralGroup, CyclicGroup
import math

# Top-level setup
S3 = SymmetricGroup(3)
S4 = SymmetricGroup(4)
A4 = AlternatingGroup(4)
D4 = DihedralGroup(4)
C4 = CyclicGroup(4)
V4 = AlternatingGroup(4)
Z2 = CyclicGroup(2)
Z3 = CyclicGroup(3)
Z4 = CyclicGroup(4)
Z6 = CyclicGroup(6)
trivial = CyclicGroup(1)

CONDITION_LABELS = [
    "H_1: p is a prime number",
    "¬Q: The number of Sylow p-subgroups of S_p is not (p-2)!"
]

N_HYP = 1
NEG_Q_INDEX = 1

def conditions(witness):
    try:
        p = int(witness)
        h1 = bool(sympy.isprime(p))
    except Exception:
        h1 = False

    try:
        if not h1:
            neg_q = False
        else:
            # For a prime p, the order of S_p is p!
            # The highest power of p dividing p! is p^1.
            # Thus, Sylow p-subgroups of S_p have order p and are generated by p-cycles.
            # The number of p-cycles in S_p is (p-1)!
            # Each Sylow p-subgroup of order p contains exactly p-1 elements of order p.
            # Therefore, the actual number of Sylow p-subgroups is (p-1)! / (p-1).
            actual_sylow_p = math.factorial(p - 1) // (p - 1)
            expected = math.factorial(p - 2)
            
            neg_q = bool(actual_sylow_p != expected)
    except Exception:
        neg_q = True

    return [h1, neg_q]