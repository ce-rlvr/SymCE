def conditions(witness) -> list[bool]:
    h1_ok = False
    h2_ok = False
    neg_q = False
    
    # Parse witness
    try:
        if isinstance(witness, dict):
            n = witness.get('n')
            sigma = witness.get('sigma')
        elif isinstance(witness, tuple) and len(witness) == 2:
            n, sigma = witness
        elif isinstance(witness, Permutation):
            sigma = witness
            n = sigma.size
            if n < 2:
                n = 2
        else:
            n, sigma = None, None
    except Exception:
        pass

    # H_1: n is an integer greater than or equal to 2
    try:
        if n is not None and int(n) == n and n >= 2:
            h1_ok = True
            n = int(n)
    except Exception:
        h1_ok = False

    # H_2: C(σ) is the centralizer of σ in S_n (implies σ is a permutation in S_n)
    try:
        h2_ok = isinstance(sigma, Permutation) and sigma.size <= n
    except Exception:
        h2_ok = False

    # ¬Q: C(σ) is NOT the cyclic subgroup generated by σ
    try:
        if h1_ok and h2_ok:
            # Calculate the size of the centralizer of sigma in S_n
            cycles = sigma.cyclic_form
            lengths = [len(c) for c in cycles]
            num_1_cycles = n - sum(lengths)
            
            if num_1_cycles >= 0:
                lengths.extend([1] * num_1_cycles)
                
                freq = {}
                for length in lengths:
                    freq[length] = freq.get(length, 0) + 1
                    
                c_size = 1
                for length, count in freq.items():
                    c_size *= (length ** count) * math.factorial(count)
                
                # The cyclic subgroup generated by sigma has size equal to its order
                order = sigma.order()
                
                # The centralizer is the cyclic subgroup iff their sizes are equal
                neg_q = bool(c_size != order)
    except Exception:
        neg_q = False

    return [h1_ok, h2_ok, neg_q]

