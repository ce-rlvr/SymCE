def conditions(witness):
    try:
        G, alpha = witness
    except Exception:
        return [False, False, False, False]

    # H1: G is a finite group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False

    # H2: G is a semisimple group
    # A finite group is semisimple iff it has no non-trivial abelian normal subgroups.
    # Equivalently, the normal closure of any non-trivial element is non-abelian.
    try:
        if not h1:
            h2 = False
        else:
            elements = list(G.generate())
            h2 = True
            for x in elements:
                if x == x**2:  # x is the identity
                    continue
                # The normal closure of x is generated by its conjugates.
                conjugates = list({g**-1 * x * g for g in elements})
                is_ab = True
                # Check if all generators of the normal closure commute
                for i in range(len(conjugates)):
                    for j in range(i + 1, len(conjugates)):
                        if conjugates[i] * conjugates[j] != conjugates[j] * conjugates[i]:
                            is_ab = False
                            break
                    if not is_ab:
                        break
                # If they all commute, the normal closure is abelian
                if is_ab:
                    h2 = False
                    break
    except Exception:
        h2 = False

    # H3: alpha is an automorphism of G
    try:
        if not h1:
            h3 = False
        else:
            elements = list(G.generate())
            if isinstance(alpha, dict):
                mapping = alpha
            elif callable(alpha) or hasattr(alpha, '__call__'):
                mapping = {x: alpha(x) for x in elements}
            else:
                mapping = None
            
            if mapping is None:
                h3 = False
            else:
                domain = set(mapping.keys())
                codomain = set(mapping.values())
                set_elements = set(elements)
                if domain != set_elements or codomain != set_elements:
                    h3 = False
                else:
                    h3 = True
                    for x in elements:
                        for y in elements:
                            if mapping[x * y] != mapping[x] * mapping[y]:
                                h3 = False
                                break
                        if not h3:
                            break
    except Exception:
        h3 = False

    # neg_Q: alpha is not the identity automorphism on G
    try:
        if not h1:
            neg_q = False
        else:
            elements = list(G.generate())
            if isinstance(alpha, dict):
                mapping = alpha
            elif callable(alpha) or hasattr(alpha, '__call__'):
                mapping = {x: alpha(x) for x in elements}
            else:
                mapping = None
                
            if mapping is None:
                neg_q = False
            else:
                neg_q = False
                for x in elements:
                    if mapping[x] != x:
                        neg_q = True
                        break
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

