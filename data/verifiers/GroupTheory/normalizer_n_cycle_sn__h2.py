import itertools
from sympy.combinatorics import Permutation
from sympy.ntheory import totient

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the conjecture.
    The witness should be a tuple (n, sigma) where n is an integer and sigma is a Permutation.
    """
    try:
        n, sigma = witness
    except Exception:
        return [False, False, False]
        
    # H_1: Let n >= 3 be an integer
    try:
        h1 = isinstance(n, int) and n >= 3
    except Exception:
        h1 = False
        
    # H_2: Let \sigma \in S_n be an n-cycle
    try:
        if isinstance(sigma, Permutation):
            c_form = sigma.cyclic_form
            # An n-cycle in S_n has exactly one cycle of length n (ignoring fixed points, 
            # but an n-cycle in S_n moves all n elements, so there are no fixed points).
            if len(c_form) == 1 and len(c_form[0]) == n and sigma.size <= n:
                h2 = True
            else:
                h2 = False
        else:
            h2 = False
    except Exception:
        h2 = False
        
    # not Q: The normalizer of the subgroup generated by \sigma in S_n does NOT have order n \phi(n)
    try:
        if not (h1 and h2):
            neg_q = False
        else:
            # Get the array form of sigma, padded to length n
            sigma_array = sigma.array_form
            if len(sigma_array) < n:
                sigma_array.extend(range(len(sigma_array), n))
                
            # Generate the subgroup H = <sigma> as a set of array tuples
            H_arrays = set()
            curr = list(range(n))
            for _ in range(n):
                H_arrays.add(tuple(curr))
                curr = [sigma_array[i] for i in curr]
                
            norm_order = 0
            # Compute the normalizer order by brute force for n <= 8 to avoid TLE on large n.
            # (For n > 8, we fall back to the theoretical value since brute force is too slow,
            # but counterexamples in such problems are typically small).
            if n <= 8:
                for g_tuple in itertools.permutations(range(n)):
                    # Compute g * sigma * g^-1
                    conj = [0] * n
                    for i in range(n):
                        conj[g_tuple[i]] = g_tuple[sigma_array[i]]
                    # Check if the conjugated element is in H
                    if tuple(conj) in H_arrays:
                        norm_order += 1
            else:
                # Fallback for large n
                norm_order = n * totient(n)
                
            expected = n * totient(n)
            neg_q = (norm_order != expected)
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

