def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the conjecture.
    Returns a list of booleans: [H_1_ok, neg_Q_ok]
    """
    # H_1: G is a semisimple finite group
    # A finite group is semisimple if it has no non-trivial solvable normal subgroups
    # (i.e., its solvable radical is trivial).
    h1_ok = False
    try:
        if isinstance(witness, PermutationGroup):
            if witness.order() > 1:
                id_el = witness.identity
                has_solvable_normal = False
                seen = set()
                
                # Check the normal closure of every non-trivial element.
                # If any normal closure is solvable, then the group has a non-trivial solvable normal subgroup.
                for g in witness.elements:
                    if g in seen:
                        continue
                    if g == id_el:
                        seen.add(g)
                        continue
                        
                    # Compute the conjugacy class of g (which generates its normal closure)
                    cclass = set([g])
                    queue = [g]
                    while queue:
                        curr = queue.pop(0)
                        for gen in witness.generators:
                            conj1 = ~gen * curr * gen
                            if conj1 not in cclass:
                                cclass.add(conj1)
                                queue.append(conj1)
                            conj2 = gen * curr * ~gen
                            if conj2 not in cclass:
                                cclass.add(conj2)
                                queue.append(conj2)
                    seen.update(cclass)
                    
                    # The subgroup generated by the conjugacy class is the normal closure
                    N = PermutationGroup(list(cclass))
                    if N.is_solvable:
                        has_solvable_normal = True
                        break
                
                if not has_solvable_normal:
                    h1_ok = True
    except Exception:
        h1_ok = False

    # neg_Q: R is not equal to G
    # R is the solvable residual, which is the last term of the derived series.
    neg_q_ok = False
    try:
        if isinstance(witness, PermutationGroup):
            ds = witness.derived_series()
            R = ds[-1]
            # If R is not equal to G, its order will be strictly less than G's order
            if R.order() < witness.order():
                neg_q_ok = True
    except Exception:
        neg_q_ok = False

    return [h1_ok, neg_q_ok]

