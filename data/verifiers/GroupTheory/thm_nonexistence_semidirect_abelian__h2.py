def conditions(witness) -> list[bool]:
    try:
        G, N, H = witness
    except Exception:
        return [False, False, False]
        
    # H1: G is a semisimple finite group
    # A finite group is semisimple iff it has no non-trivial abelian normal subgroups.
    # This is equivalent to saying no non-identity element has an abelian normal closure.
    # The normal closure of g is abelian iff the conjugacy class of g consists of pairwise commuting elements.
    try:
        elements = list(G.generate())
        id_el = G.identity
        seen = set()
        h1 = True
        for g in elements:
            if g == id_el or g in seen:
                continue
            
            C = set()
            C_list = []
            commutes = True
            
            for x in elements:
                conj = x * g * ~x
                if conj not in C:
                    for c in C_list:
                        if conj * c != c * conj:
                            commutes = False
                            break
                    if not commutes:
                        break
                    C.add(conj)
                    C_list.append(conj)
            
            if not commutes:
                seen.add(g)
                seen.update(C)
            else:
                # Found a non-trivial abelian normal subgroup (generated by the conjugacy class)
                h1 = False
                break
    except Exception:
        h1 = False

    # H2: H is a subgroup of G such that G is the internal semidirect product of N and H
    try:
        G_elements = set(G.generate())
        
        n_sub = all(gen in G_elements for gen in N.generators)
        h_sub = all(gen in G_elements for gen in H.generators)
        
        if not (n_sub and h_sub):
            h2 = False
        else:
            N_elements = set(N.generate())
            H_elements = set(H.generate())
            
            # Check if N is normal in G
            n_normal = True
            for g in G_elements:
                for n in N.generators:
                    if g * n * ~g not in N_elements:
                        n_normal = False
                        break
                if not n_normal:
                    break
                    
            # Check intersection N ∩ H = {id}
            trivial_int = (N_elements.intersection(H_elements) == {G.identity})
            
            # Check NH = G (via sizes since intersection is trivial)
            prod_size = (len(N_elements) * len(H_elements) == len(G_elements))
            
            h2 = n_normal and trivial_int and prod_size
    except Exception:
        h2 = False

    # neg_Q: N is not the trivial subgroup or H != G
    try:
        N_elements = set(N.generate())
        H_elements = set(H.generate())
        G_elements = set(G.generate())
        
        n_trivial = (len(N_elements) == 1)
        h_eq_g = (len(H_elements) == len(G_elements)) and all(gen in G_elements for gen in H.generators)
        
        neg_q = not (n_trivial and h_eq_g)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

