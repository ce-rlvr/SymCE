def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, (int, sympy.Integer)) and not isinstance(witness, bool):
            n = int(witness)
            h1 = n >= 5
        else:
            h1 = False
    except Exception:
        h1 = False

    try:
        if isinstance(witness, (int, sympy.Integer)) and not isinstance(witness, bool) and witness >= 1:
            n = int(witness)
            if n <= 12:
                perms = []
                # Generate all permutations in A_n that are products of two disjoint transpositions
                for combo in combinations(range(n), 4):
                    a, b, c, d = combo
                    perms.append(Permutation([[a, b], [c, d]], size=n))
                    perms.append(Permutation([[a, c], [b, d]], size=n))
                    perms.append(Permutation([[a, d], [b, c]], size=n))
                
                expected_order = math.factorial(n) // 2 if n >= 2 else 1
                if not perms:
                    # If no such permutations exist, they generate the trivial group
                    neg_q = (expected_order != 1)
                else:
                    G = PermutationGroup(perms)
                    neg_q = G.order() != expected_order
            else:
                # For n > 12, the set of products of two disjoint transpositions
                # forms a non-trivial conjugacy class in A_n. Since A_n is simple
                # for n >= 5, this conjugacy class always generates A_n.
                neg_q = False
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, neg_q]

