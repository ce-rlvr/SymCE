def mutual_commutator_subgroup(G, A, B):
    """
    Computes the mutual commutator subgroup generated by 
    all commutators a^-1 b^-1 a b for a in A and b in B.
    """
    def get_elems(S):
        if isinstance(S, Permutation):
            return [S]
        if hasattr(S, 'generate'):
            return list(S.generate())
        elif hasattr(S, 'elements'):
            return list(S.elements)
        else:
            return list(S)
            
    A_elems = get_elems(A)
    B_elems = get_elems(B)
    
    gens = []
    for a in A_elems:
        for b in B_elems:
            # Commutator [a, b]
            comm = (~a) * (~b) * a * b
            if comm not in gens:
                gens.append(comm)
                
    if not gens:
        return PermutationGroup([G.identity])
    return PermutationGroup(gens)

def conditions(witness):
    try:
        G, X, Y, Z = witness
    except Exception:
        return [False, False, False, False]
        
    # H_1: G is a group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False
        
    # H_2: The mutual commutator subgroup of commutator(X, Y) and Z is trivial
    try:
        XY = mutual_commutator_subgroup(G, X, Y)
        XY_Z = mutual_commutator_subgroup(G, XY, Z)
        h2 = bool(XY_Z.is_trivial)
    except Exception:
        h2 = False
        
    # H_3: The mutual commutator subgroup of commutator(Y, Z) and X is trivial
    try:
        YZ = mutual_commutator_subgroup(G, Y, Z)
        YZ_X = mutual_commutator_subgroup(G, YZ, X)
        h3 = bool(YZ_X.is_trivial)
    except Exception:
        h3 = False
        
    # ¬Q: The mutual commutator subgroup of commutator(Z, X) and Y is not trivial
    try:
        ZX = mutual_commutator_subgroup(G, Z, X)
        ZX_Y = mutual_commutator_subgroup(G, ZX, Y)
        neg_q = not bool(ZX_Y.is_trivial)
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

