def conditions(witness) -> list[bool]:
    try:
        if len(witness) == 3:
            F, H, g = witness
        elif len(witness) == 2:
            F, H = witness
            g = F.identity if type(F).__name__ == 'FreeGroup' else None
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H1: F is a free group
    try:
        h1 = type(F).__name__ == 'FreeGroup'
    except Exception:
        h1 = False

    # H2: H is a proper free factor of F
    try:
        h2 = False
        base_gens = set()
        if h1:
            if not isinstance(H, (list, tuple, set)):
                H_list = [H]
            else:
                H_list = H
                
            is_subset = True
            for h in H_list:
                if hasattr(h, 'array_form') and len(h.array_form) == 1 and abs(h.array_form[0][1]) == 1:
                    gen = h.array_form[0][0]
                    if gen in F.generators:
                        base_gens.add(gen)
                    else:
                        is_subset = False
                        break
                else:
                    is_subset = False
                    break
            if is_subset and len(base_gens) < len(F.generators):
                h2 = True
    except Exception:
        h2 = False

    # neg_Q: The intersection H \cap gHg^{-1} is NOT the trivial subgroup
    try:
        neg_q = False
        if h1 and h2 and hasattr(g, 'group') and g.group == F:
            # For a proper free factor H generated by a subset of base generators,
            # the intersection H \cap gHg^{-1} is non-trivial if and only if
            # H is non-trivial and g \in H.
            g_in_H = True
            for gen, exp in g.array_form:
                if gen not in base_gens:
                    g_in_H = False
                    break
            if g_in_H and len(base_gens) > 0:
                neg_q = True
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

