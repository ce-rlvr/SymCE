def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness should be a tuple (G, p) where G is a PermutationGroup and p is a prime.
    """
    try:
        if isinstance(witness, (tuple, list)) and len(witness) == 2:
            G, p = witness
        else:
            return [False, False]
    except Exception:
        return [False, False]

    # H_1: G is a non-abelian finite simple group
    try:
        if not isinstance(G, PermutationGroup):
            h1 = False
        elif G.is_abelian:
            h1 = False
        else:
            # A group is simple iff its composition series has exactly 2 elements (G and {e})
            comp = G.composition_series()
            h1 = (len(comp) == 2)
    except Exception:
        h1 = False

    # neg_Q: The subgroup generated by the union of all Sylow p-subgroups of G is not equal to G
    try:
        if not isinstance(G, PermutationGroup):
            neg_q = False
        elif not isprime(p):
            neg_q = False
        else:
            P = G.sylow_subgroup(p)
            if P.order() == 1:
                # If p does not divide |G|, the Sylow p-subgroups are trivial.
                # The subgroup generated by them is trivial.
                neg_q = (G.order() != 1)
            else:
                # The subgroup generated by the union of all Sylow p-subgroups
                # is the normal closure of any single Sylow p-subgroup P.
                closure_gens = list(P.generators)
                closure = PermutationGroup(closure_gens)
                
                while True:
                    added = False
                    for g in G.generators:
                        ginv = ~g
                        for c in list(closure_gens):
                            # Conjugate by g
                            conj1 = g * c * ginv
                            if conj1 not in closure:
                                closure_gens.append(conj1)
                                closure = PermutationGroup(closure_gens)
                                added = True
                            
                            # Conjugate by g^-1
                            conj2 = ginv * c * g
                            if conj2 not in closure:
                                closure_gens.append(conj2)
                                closure = PermutationGroup(closure_gens)
                                added = True
                    if not added:
                        break
                
                neg_q = (closure.order() != G.order())
    except Exception:
        neg_q = False

    return [h1, neg_q]

