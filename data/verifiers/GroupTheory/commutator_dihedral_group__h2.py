def conditions(witness):
    # The witness could be just n, or a tuple (n, r)
    try:
        if isinstance(witness, tuple):
            if len(witness) == 2:
                n, r_wit = witness
            else:
                n = witness[0]
                r_wit = None
        else:
            n = witness
            r_wit = None
    except Exception:
        n = witness
        r_wit = None

    # H_1: n >= 3 is an integer
    try:
        h1_ok = isinstance(n, int) and n >= 3
    except Exception:
        h1_ok = False

    # H_2: r is the generator of the rotation subgroup of D_{2n}
    try:
        if r_wit is not None and h1_ok:
            G1 = DihedralGroup(n)
            G2 = DihedralGroup(2 * n)
            h2_ok = (r_wit in G1.elements and r_wit.order() == n) or \
                    (r_wit in G2.elements and r_wit.order() == 2 * n)
        else:
            h2_ok = True
    except Exception:
        h2_ok = False

    # ¬Q: The commutator subgroup of D_{2n} is not the cyclic subgroup generated by r^2
    try:
        neg_q_ok = False
        if h1_ok:
            if r_wit is not None:
                G1 = DihedralGroup(n)
                G2 = DihedralGroup(2 * n)
                if r_wit in G1.elements and r_wit.order() == n:
                    G = G1
                elif r_wit in G2.elements and r_wit.order() == 2 * n:
                    G = G2
                else:
                    G = G1
                
                C = G.derived_subgroup()
                r2 = r_wit**2
                r2_subgroup = set()
                elem = r2
                for _ in range(G.order()):
                    r2_subgroup.add(elem)
                    elem = elem * r2
                
                if set(C.elements) != r2_subgroup:
                    neg_q_ok = True
            else:
                # Check interpretation 1: D_{2n} means dihedral group of order 2n
                G1 = DihedralGroup(n)
                r1 = None
                for g in G1.elements:
                    if g.order() == n:
                        r1 = g
                        break
                if r1 is not None:
                    C1 = G1.derived_subgroup()
                    r1_2 = r1**2
                    r1_2_subgroup = set()
                    elem = r1_2
                    for _ in range(n + 1):
                        r1_2_subgroup.add(elem)
                        elem = elem * r1_2
                    if set(C1.elements) != r1_2_subgroup:
                        neg_q_ok = True

                # Check interpretation 2: D_{2n} means dihedral group of order 4n
                G2 = DihedralGroup(2 * n)
                r2 = None
                for g in G2.elements:
                    if g.order() == 2 * n:
                        r2 = g
                        break
                if r2 is not None:
                    C2 = G2.derived_subgroup()
                    r2_2 = r2**2
                    r2_2_subgroup = set()
                    elem = r2_2
                    for _ in range(2 * n + 1):
                        r2_2_subgroup.add(elem)
                        elem = elem * r2_2
                    if set(C2.elements) != r2_2_subgroup:
                        neg_q_ok = True
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, neg_q_ok]

