def conditions(witness) -> list[bool]:
    # Unpack witness
    try:
        if len(witness) == 5:
            G, a, b, m, n = witness
        elif len(witness) == 4:
            a, b, m, n = witness
            G = PermutationGroup([a, b])
        else:
            return [False] * 6
    except Exception:
        return [False] * 6

    # H_1: G is a group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False

    # H_2: a and b are elements of G
    try:
        h2 = (a in G) and (b in G)
    except Exception:
        h2 = False

    # H_3: a and b commute (ab = ba)
    try:
        h3 = (a * b == b * a)
    except Exception:
        h3 = False

    # H_4: The order of b is a finite integer n
    try:
        h4 = (int(n) == n) and (b.order() == n)
    except Exception:
        h4 = False

    # H_5: \gcd(m, n) = 1
    try:
        h5 = (int(m) == m) and (int(n) == n) and (math.gcd(int(m), int(n)) == 1)
    except Exception:
        h5 = False

    # ¬Q: The order of ab is not mn
    # (If the order is not mn, then the subgroup generated by ab cannot be a cyclic group of order mn)
    try:
        ab = a * b
        order_ab = ab.order()
        neg_q = (order_ab != m * n)
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, h5, neg_q]

