def conditions(witness):
    """
    Checks the hypotheses and the negated conclusion for the given witness.
    The witness can be a dictionary {'G': G, 'a': a, 'n': n, 'k': k} or a tuple (G, a, n, k) or (G, a, k).
    """
    try:
        if isinstance(witness, dict):
            G = witness.get('G')
            a = witness.get('a')
            n = witness.get('n', None)
            k = witness.get('k')
        elif len(witness) == 4:
            G, a, n, k = witness
        elif len(witness) == 3:
            G, a, k = witness
            n = None
        else:
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]

    # H_1: Let G be a cyclic group.
    try:
        is_cyc = G.is_cyclic
        if callable(is_cyc):
            is_cyc = is_cyc()
        h1 = bool(is_cyc)
    except Exception:
        h1 = False

    # H_2: Let G be generated by an element a.
    try:
        H_a = PermutationGroup(a)
        order_G = G.order() if callable(getattr(G, 'order', None)) else G.order
        order_Ha = H_a.order() if callable(getattr(H_a, 'order', None)) else H_a.order
        h2 = bool(G.contains(a) and order_Ha == order_G)
    except Exception:
        h2 = False

    # H_3: Let the order of G be a finite integer n.
    try:
        order_G = G.order() if callable(getattr(G, 'order', None)) else G.order
        if n is None:
            n = order_G
            h3 = bool(order_G < float('inf'))
        else:
            h3 = bool(order_G == n and order_G < float('inf'))
    except Exception:
        h3 = False

    # ¬Q: The subgroup generated by a^k is NOT equal to the subgroup generated by a^gcd(k,n).
    try:
        ak = a**k
        g = math.gcd(int(k), int(n))
        ag = a**g
        
        H_ak = PermutationGroup(ak)
        H_ag = PermutationGroup(ag)
        
        # Two cyclic subgroups are equal if they contain each other's generators
        are_equal = bool(H_ag.contains(ak) and H_ak.contains(ag))
        neg_q = not are_equal
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

