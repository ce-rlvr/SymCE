def get_order(x):
    if hasattr(x, 'order'):
        if callable(x.order):
            return x.order()
        return x.order
    if hasattr(x, 'period'):
        if callable(x.period):
            return x.period()
        return x.period
    if hasattr(x, 'is_Matrix') and x.is_Matrix:
        curr = x
        I = eye(x.shape[0])
        for i in range(1, 1000):
            if curr == I:
                return i
            curr = curr * x
    raise ValueError("Cannot determine order")

def conditions(witness) -> list[bool]:
    try:
        if len(witness) == 3:
            G, a, b = witness
        elif len(witness) == 2:
            a, b = witness
            G = None
        else:
            return [False] * 6
    except Exception:
        return [False] * 6

    # H1: G is a group
    try:
        if G is None:
            h1 = False
        else:
            from sympy.combinatorics import PermutationGroup
            if isinstance(G, PermutationGroup):
                h1 = True
            elif hasattr(G, 'is_group') and G.is_group:
                h1 = True
            elif hasattr(G, 'is_Group') and G.is_Group:
                h1 = True
            else:
                h1 = False
    except Exception:
        h1 = False

    # H2: a and b commute
    try:
        h2 = bool(a * b == b * a)
    except Exception:
        h2 = False

    # H3: order of a is finite integer m
    try:
        m = get_order(a)
        h3 = isinstance(m, int) and m > 0
    except Exception:
        h3 = False

    # H4: order of b is finite integer n
    try:
        n = get_order(b)
        h4 = isinstance(n, int) and n > 0
    except Exception:
        h4 = False

    # H5: gcd(m, n) == 1
    try:
        h5 = False
        if h3 and h4:
            h5 = bool(math.gcd(m, n) == 1)
    except Exception:
        h5 = False

    # neg_Q: order of ab is not mn
    try:
        neg_q = False
        if h3 and h4:
            ab = a * b
            o_ab = get_order(ab)
            if o_ab != m * n:
                neg_q = True
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, h5, neg_q]

