def conditions(witness) -> list[bool]:
    """
    Given a witness (n, H), checks if it is a valid counterexample to the false conjecture.
    The conjecture claims that any group H whose index in S_n is 2 must be A_n.
    However, if the hypothesis "H is a subgroup of S_n" is dropped, H could be any group 
    (or permutation group on a larger set) whose order is n! / 2.
    """
    try:
        n, H = witness
    except Exception:
        return [False, False, False]

    # H_1: n is an integer greater than or equal to 2
    try:
        h1_ok = isinstance(n, int) and n >= 2
    except Exception:
        h1_ok = False

    # H_2: The index of H in S_n is 2
    # In the context of the dropped hypothesis, this is interpreted as the ratio of their orders being 2.
    # If H is actually a subgroup of S_n, its index is exactly 2.
    try:
        sn_order = math.factorial(n)
        h2_ok = (sn_order % H.order() == 0) and (sn_order // H.order() == 2)
        # If H is a PermutationGroup, we also ensure it's a valid group object
        if not isinstance(H, PermutationGroup):
            h2_ok = False
    except Exception:
        h2_ok = False

    # neg_Q: H is NOT the alternating group A_n
    try:
        # We check if H is exactly the alternating group A_n.
        # A_n is generated by the even permutations of degree n.
        # If H is not A_n, then neg_Q is True.
        if n >= 3:
            An = AlternatingGroup(n)
            # Two permutation groups are equal if they are subgroups of each other
            is_An = H.is_subgroup(An) and An.is_subgroup(H)
        else:
            # For n=2, A_2 is the trivial group
            is_An = H.order() == 1
            
        neg_q_ok = not is_An
    except Exception:
        # If we can't evaluate equality, we assume it's not A_n
        neg_q_ok = True

    return [h1_ok, h2_ok, neg_q_ok]

