def groups_equal(g1, g2):
    try:
        if g1.order() != g2.order():
            return False
        for gen in g1.generators:
            if gen not in g2:
                return False
        return True
    except Exception:
        return False

def conditions(witness) -> list[bool]:
    try:
        # The witness is expected to be a tuple (G, N, H) where G is the internal 
        # semidirect product of N and H.
        if not (isinstance(witness, tuple) and len(witness) == 3):
            return [False, False, False]
            
        G, N, H = witness
        
        # Evaluate remaining hypotheses
        h1 = bool(N.is_abelian)
        h2 = bool(H.is_abelian)
        
        # Verify that G is indeed the internal semidirect product of N and H.
        # If the setup is invalid, we return False for the negated conclusion.
        if G.order() != N.order() * H.order():
            return [h1, h2, False]
            
        n_elements = list(N.generate())
        h_elements = list(H.generate())
        
        n_set = set(n_elements)
        h_set = set(h_elements)
        
        # N and H must have trivial intersection
        if len(n_set.intersection(h_set)) != 1:
            return [h1, h2, False]
            
        # N must be a normal subgroup of G
        is_normal = True
        for g in G.generators:
            for n in N.generators:
                if (g * n * (g**-1)) not in n_set:
                    is_normal = False
                    break
            if not is_normal:
                break
                
        if not is_normal:
            return [h1, h2, False]
            
        # Compute the subgroup generated by elements of the form n^{-1} \phi_h(n)
        # In the internal semidirect product, \phi_h(n) = h * n * h^{-1}
        # So n^{-1} \phi_h(n) = n^{-1} * h * n * h^{-1}
        elements = []
        for n in n_elements:
            for h in h_elements:
                elements.append((n**-1) * h * n * (h**-1))
                
        if elements:
            gen_subgroup = PermutationGroup(elements)
        else:
            id_perm = getattr(G, 'identity', None)
            if id_perm is None:
                id_perm = list(G.generators)[0]**0 if G.generators else Permutation()
            gen_subgroup = PermutationGroup([id_perm])
            
        # Compute the derived subgroup of G
        G_prime = G.derived_subgroup()
        
        # The conclusion states that G_prime is exactly gen_subgroup.
        # The negated conclusion is True if they are NOT equal.
        is_eq = groups_equal(G_prime, gen_subgroup)
        neg_q = not is_eq
        
        return [h1, h2, neg_q]
        
    except Exception:
        return [False, False, False]

