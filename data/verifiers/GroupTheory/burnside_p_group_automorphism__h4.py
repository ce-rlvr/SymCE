def conditions(witness) -> list[bool]:
    try:
        G, alpha = witness
    except Exception:
        return [False, False, False, False]

    p = None
    alpha_dict = None
    elements = None

    # H1: G is a finite p-group for some prime p
    try:
        if not isinstance(G, PermutationGroup):
            h1 = False
        else:
            order = G.order()
            factors = factorint(order)
            if len(factors) == 1:
                p = list(factors.keys())[0]
                h1 = True
            else:
                h1 = False
    except Exception:
        h1 = False

    # H2: alpha is an automorphism of G
    try:
        if not h1:
            h2 = False
        else:
            elements = list(G.generate())
            if isinstance(alpha, dict):
                alpha_dict = alpha
            elif callable(alpha):
                alpha_dict = {x: alpha(x) for x in elements}
            else:
                alpha_dict = None
            
            if alpha_dict is None:
                h2 = False
            elif set(alpha_dict.keys()) != set(elements) or set(alpha_dict.values()) != set(elements):
                h2 = False
            else:
                h2 = True
                for x in elements:
                    for y in elements:
                        if alpha_dict[x * y] != alpha_dict[x] * alpha_dict[y]:
                            h2 = False
                            break
                    if not h2:
                        break
    except Exception:
        h2 = False

    # H3: alpha(x*Phi(G)) = x*Phi(G) for all x in G
    try:
        if not (h1 and h2 and p is not None and elements is not None and alpha_dict is not None):
            h3 = False
        else:
            # For a finite p-group, the Frattini subgroup Phi(G) is generated by 
            # the p-th powers and the commutators of elements of G.
            p_powers = [x**p for x in elements]
            commutators = [(x**-1) * (y**-1) * x * y for x in elements for y in elements]
            gens = list(set(p_powers + commutators))
            Phi = PermutationGroup(gens)
            
            h3 = True
            for x in elements:
                # alpha(x * Phi(G)) = x * Phi(G) is equivalent to x^-1 * alpha(x) in Phi(G)
                diff = (x**-1) * alpha_dict[x]
                if diff not in Phi:
                    h3 = False
                    break
    except Exception:
        h3 = False

    # neg_Q: alpha is not the identity automorphism of G
    try:
        if not (h1 and h2 and elements is not None and alpha_dict is not None):
            neg_q = False
        else:
            neg_q = False
            for x in elements:
                if alpha_dict[x] != x:
                    neg_q = True
                    break
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

