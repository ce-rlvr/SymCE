def conditions(witness):
    try:
        if not isinstance(witness, (tuple, list)) or len(witness) != 2:
            return [False, False, False]
        G, x = witness
    except Exception:
        return [False, False, False]

    # H_1: G is a group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False

    # H_2: x is an element of G
    try:
        h2 = False
        if h1 and isinstance(x, Permutation):
            h2 = bool(x in G)
    except Exception:
        h2 = False

    # ¬Q: G is not an abelian group
    try:
        neg_q = False
        if h1:
            neg_q = not bool(G.is_abelian)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

