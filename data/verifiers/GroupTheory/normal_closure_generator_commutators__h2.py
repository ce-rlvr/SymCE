def conditions(witness) -> list[bool]:
    h1 = False
    neg_q = False
    
    # Check Hypothesis 1: G is a group and S is a subset of G
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            G, S = witness
            if isinstance(G, PermutationGroup) and isinstance(S, (list, tuple, set)):
                h1 = all(isinstance(s, Permutation) and s in G for s in S)
    except Exception:
        h1 = False

    # Check Negated Conclusion: G' is NOT the normal closure of the subgroup generated by commutators of S
    try:
        if h1:
            G, S = witness
            
            # Compute the set of commutators C = { [s, t] | s, t \in S }
            # [s, t] = s * t * s^-1 * t^-1
            C = []
            for s in S:
                for t in S:
                    C.append(s * t * (~s) * (~t))
            
            id_elem = G.generators[0]**0 if G.generators else Permutation()
            
            # Compute the normal closure of C in G
            if not C:
                N = PermutationGroup([id_elem])
            else:
                N = PermutationGroup(C)
                while True:
                    gens = N.generators
                    new_gens = list(gens)
                    for g in G.generators:
                        for c in gens:
                            new_gens.append(g * c * ~g)
                            new_gens.append((~g) * c * g)
                    N_new = PermutationGroup(new_gens)
                    if N_new.order() == N.order():
                        break
                    N = N_new
            
            # Compute the commutator subgroup G'
            G_prime = G.derived_subgroup()
            
            # The conclusion fails if N != G'
            # Since N is always a subgroup of G', we can just compare their orders
            neg_q = N.order() != G_prime.order()
    except Exception:
        neg_q = False

    return [h1, neg_q]

