def is_subgroup(H, G):
    if not isinstance(H, PermutationGroup) or not isinstance(G, PermutationGroup):
        return False
    for gen in H.generators:
        if gen.is_Identity:
            continue
        if gen not in G:
            return False
    return True

def is_semisimple(G):
    """
    A finite group is semisimple if it has no non-trivial abelian normal subgroups.
    This is equivalent to saying that for every non-identity element x in G,
    the normal closure of x in G is non-abelian.
    """
    if not isinstance(G, PermutationGroup):
        return False
    if G.order() <= 1:
        return False
    
    elements = list(G.elements)
    for x in elements:
        if x.is_Identity:
            continue
        
        # Generate the conjugacy class of x
        cclass = set()
        for g in elements:
            conj = ~g * x * g
            cclass.add(conj)
        
        # Check if the subgroup generated by the conjugacy class is abelian.
        # It is abelian iff all elements in the conjugacy class commute with each other.
        is_abelian_closure = True
        cclass_list = list(cclass)
        for i in range(len(cclass_list)):
            for j in range(i + 1, len(cclass_list)):
                if cclass_list[i] * cclass_list[j] != cclass_list[j] * cclass_list[i]:
                    is_abelian_closure = False
                    break
            if not is_abelian_closure:
                break
        
        # If we found a non-identity element whose normal closure is abelian,
        # then G has a non-trivial abelian normal subgroup.
        if is_abelian_closure:
            return False
            
    return True

def check_sylow(G, P, p=None):
    if not is_subgroup(P, G):
        return False
            
    order_G = G.order()
    order_P = P.order()
    
    if p is not None:
        if not isprime(p):
            return False
        if order_P == 1:
            if order_G % p == 0:
                return False
            return True
        
        temp = order_P
        while temp % p == 0:
            temp //= p
        if temp != 1:
            return False
            
        if (order_G // order_P) % p == 0:
            return False
        return True
    else:
        if order_P == 1:
            return True
            
        factors = factorint(order_P)
        if len(factors) != 1:
            return False
        p = list(factors.keys())[0]
        
        if (order_G // order_P) % p == 0:
            return False
        return True

def is_normal_subgroup(G, P):
    if not is_subgroup(P, G):
        return False
    for g in G.generators:
        for h in P.generators:
            if h.is_Identity:
                continue
            conj = ~g * h * g
            if not conj.is_Identity and conj not in P:
                return False
    return True

def conditions(witness) -> list[bool]:
    # witness can be (G, P) or (G, P, p)
    if isinstance(witness, tuple):
        if len(witness) == 2:
            G, P = witness
            p = None
        elif len(witness) == 3:
            G, P, p = witness
        else:
            return [False, False, False, False]
    else:
        return [False, False, False, False]
        
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False
        
    try:
        h2 = is_semisimple(G)
    except Exception:
        h2 = False
        
    try:
        h3 = check_sylow(G, P, p)
    except Exception:
        h3 = False
        
    try:
        neg_q = is_normal_subgroup(G, P)
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

