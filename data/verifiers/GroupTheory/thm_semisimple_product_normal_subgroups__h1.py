def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, dict):
            G = witness['G']
            N = witness['N']
            M = witness['M']
        else:
            G, N, M = witness
    except Exception:
        return [False, False, False]

    def is_normal_subgroup(A, B):
        try:
            for gen in A.generators:
                if not B.contains(gen):
                    return False
            for g in A.generators:
                for h in B.generators:
                    if not A.contains(h * g * ~h):
                        return False
            return True
        except Exception:
            return False

    def is_semisimple(H):
        # A finite group is semisimple if it has no non-trivial abelian normal subgroups.
        # Equivalently, its solvable radical (Fitting subgroup) is trivial.
        try:
            if H.order() == 1:
                return True
            
            # Try using conjugacy classes first
            try:
                classes = H.conjugacy_classes()
                for C in classes:
                    C_list = list(C)
                    if not C_list or C_list[0].is_Identity:
                        continue
                    
                    # If the normal closure of an element is abelian, all its conjugates commute.
                    is_ab = True
                    for i in range(len(C_list)):
                        for j in range(i + 1, len(C_list)):
                            if C_list[i] * C_list[j] != C_list[j] * C_list[i]:
                                is_ab = False
                                break
                        if not is_ab:
                            break
                    if is_ab:
                        return False
                return True
            except Exception:
                # Fallback to generating elements
                elements = list(H.generate())
                seen = set()
                for g in elements:
                    if g.is_Identity or g in seen:
                        continue
                    C = set()
                    for h in elements:
                        C.add(h * g * ~h)
                    seen.update(C)
                    
                    is_ab = True
                    C_list = list(C)
                    for i in range(len(C_list)):
                        for j in range(i + 1, len(C_list)):
                            if C_list[i] * C_list[j] != C_list[j] * C_list[i]:
                                is_ab = False
                                break
                        if not is_ab:
                            break
                    if is_ab:
                        return False
                return True
        except Exception:
            return False

    # H_1: N is a normal semisimple subgroup of G
    try:
        h1 = is_normal_subgroup(N, G) and is_semisimple(N)
    except Exception:
        h1 = False

    # H_2: M is a normal semisimple subgroup of G
    try:
        h2 = is_normal_subgroup(M, G) and is_semisimple(M)
    except Exception:
        h2 = False

    # ¬Q: The subgroup generated by N and M is NOT a normal semisimple subgroup of G
    try:
        gens_N = list(N.generators) if hasattr(N, 'generators') else []
        gens_M = list(M.generators) if hasattr(M, 'generators') else []
        gens_NM = gens_N + gens_M
        
        if not gens_NM:
            NM = PermutationGroup([Permutation()])
        else:
            NM = PermutationGroup(gens_NM)
            
        c_normal = is_normal_subgroup(NM, G)
        c_semi = is_semisimple(NM)
        
        neg_q = not (c_normal and c_semi)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

