def conditions(witness):
    # Extract G from witness (allow tuple like (G, X) or just G)
    try:
        if isinstance(witness, tuple):
            G = witness[0]
        else:
            G = witness
    except Exception:
        G = witness

    # H_1: G is a finite group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False

    # H_2: G is a semisimple group
    # A finite group is semisimple iff it has no non-trivial abelian normal subgroups.
    # This is equivalent to saying that the normal closure of any non-trivial element is non-abelian.
    try:
        if h1:
            if G.order() > 10000:
                h2 = False  # Too large to verify quickly, minimal counterexamples are small
            else:
                h2 = True
                elements = list(G.generate())
                if elements:
                    id_el = elements[0] * elements[0]**-1
                    seen = set()
                    for g in elements:
                        if g == id_el or g in seen:
                            continue
                        # The normal closure of g is generated by its conjugacy class
                        cclass = set()
                        for h in elements:
                            cclass.add(h * g * h**-1)
                        seen.update(cclass)
                        
                        N = PermutationGroup(*list(cclass))
                        if N.is_abelian:
                            h2 = False
                            break
        else:
            h2 = False
    except Exception:
        h2 = False

    # H_3: Let X be a set
    try:
        # A PermutationGroup implicitly defines its domain set X = {0, 1, ..., degree-1}
        h3 = isinstance(G, PermutationGroup)
    except Exception:
        h3 = False

    # H_4: G acts on the set X
    try:
        # A PermutationGroup naturally acts faithfully on its domain
        h4 = isinstance(G, PermutationGroup)
    except Exception:
        h4 = False

    # ¬Q: The action of G on X is not the trivial action
    try:
        if h1:
            # The action is trivial iff all elements act as the identity.
            # For a faithful action (PermutationGroup), this means the group is trivial.
            neg_q = G.order() > 1
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]

