def conditions(witness) -> list[bool]:
    n = None
    G_ok = True
    a_ok = True
    H_ok = True
    
    try:
        if isinstance(witness, dict):
            if 'n' in witness:
                n = int(witness['n'])
            else:
                # If dictionary doesn't have 'n', we cannot evaluate
                return [False, False, False, False]
        elif isinstance(witness, tuple):
            # Try to extract n from the tuple (assume it's the last integer)
            for item in reversed(witness):
                try:
                    n = int(item)
                    break
                except Exception:
                    continue
        else:
            n = int(witness)
    except Exception:
        pass

    if n is None:
        return [False, False, False, False]

    # If witness is a tuple of length 4, it might be (G, a, H, n)
    if isinstance(witness, tuple) and len(witness) == 4:
        G = witness[0]
        try:
            # If a group is provided and it is finite, it violates H1
            if hasattr(G, 'order') and G.order() != float('inf'):
                G_ok = False
        except Exception:
            pass

    h1 = G_ok
    h2 = a_ok
    h3 = H_ok
    
    try:
        if n == 0:
            index = float('inf')
        else:
            index = abs(n)
        neg_q = (index != n)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

