def conditions(witness) -> list[bool]:
    try:
        G, x, y = witness
    except Exception:
        return [False, False, False]

    # H_1: G is a group
    try:
        h1_ok = isinstance(G, PermutationGroup)
    except Exception:
        h1_ok = False

    # H_2: x and y are elements of G
    try:
        h2_ok = bool(x in G and y in G)
    except Exception:
        h2_ok = False

    # ¬Q: The order of x is not equal to the order of y
    try:
        neg_q_ok = bool(x.order() != y.order())
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, neg_q_ok]

