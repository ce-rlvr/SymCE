def is_nilpotent(grp):
    if hasattr(grp, 'is_nilpotent'):
        val = grp.is_nilpotent
        if callable(val):
            return val()
        return val
    return False

def conditions(witness):
    try:
        # H_1: G is isomorphic to a direct product of non-abelian simple groups
        if not isinstance(witness, PermutationGroup):
            h1_ok = False
        else:
            if witness.order() == 1:
                h1_ok = True
            elif witness.is_abelian:
                h1_ok = False
            else:
                try:
                    # A direct product of non-abelian simple groups is perfect and has a trivial center
                    if witness.derived_subgroup().order() != witness.order():
                        h1_ok = False
                    elif witness.center().order() != 1:
                        h1_ok = False
                    else:
                        normals = witness.normal_subgroups()
                        non_trivial_normals = [N for N in normals if N.order() > 1]
                        if not non_trivial_normals:
                            h1_ok = False
                        else:
                            # Find all minimal normal subgroups
                            minimal_normals = []
                            for N in non_trivial_normals:
                                is_minimal = True
                                for M in non_trivial_normals:
                                    if M.order() < N.order() and all(g in N for g in M.generators):
                                        is_minimal = False
                                        break
                                if is_minimal:
                                    minimal_normals.append(N)
                            
                            h1_ok = True
                            # Each minimal normal subgroup must be a non-abelian simple group
                            for M in minimal_normals:
                                if M.is_abelian:
                                    h1_ok = False
                                    break
                                if len(M.normal_subgroups()) != 2:
                                    h1_ok = False
                                    break
                            
                            # The group must be generated by its minimal normal subgroups
                            if h1_ok:
                                gens = []
                                for M in minimal_normals:
                                    gens.extend(M.generators)
                                if not gens:
                                    h1_ok = False
                                else:
                                    gen_group = PermutationGroup(gens)
                                    if gen_group.order() != witness.order():
                                        h1_ok = False
                except Exception:
                    h1_ok = False
    except Exception:
        h1_ok = False

    try:
        # ¬Q: The Fitting subgroup of G is not the trivial subgroup
        # The Fitting subgroup is the subgroup generated by all nilpotent normal subgroups.
        # It is non-trivial if and only if there exists at least one non-trivial nilpotent normal subgroup.
        if not isinstance(witness, PermutationGroup):
            neg_q_ok = False
        else:
            neg_q_ok = False
            normals = witness.normal_subgroups()
            for N in normals:
                if N.order() > 1 and is_nilpotent(N):
                    neg_q_ok = True
                    break
    except Exception:
        neg_q_ok = False

    return [bool(h1_ok), bool(neg_q_ok)]