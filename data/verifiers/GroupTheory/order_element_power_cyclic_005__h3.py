def conditions(witness) -> list[bool]:
    try:
        # The witness can be either (G, n, a, k) or (G, a, k)
        if len(witness) == 4:
            G, n, a, k = witness
        elif len(witness) == 3:
            G, a, k = witness
            n = G.order()
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]
        
    # H1: G is a finite cyclic group of order n
    try:
        h1 = G.is_cyclic and G.order() == n
    except Exception:
        h1 = False
        
    # H2: G is generated by the element a
    try:
        # In a finite group, an element generates the group iff it is in the group 
        # and its order equals the group's order.
        h2 = (a in G) and (a.order() == G.order())
    except Exception:
        h2 = False
        
    # Conclusion: The order of the element a^k is n / gcd(n, k)
    try:
        ak = a**k
        ak_order = ak.order()
        expected = sympy.Rational(n, sympy.gcd(n, k))
        q = (ak_order == expected)
        neg_q = not q
    except Exception:
        # If evaluating the conclusion raises an error (e.g., k is not an integer),
        # the conclusion fails to hold, making its negation True.
        neg_q = True
        
    return [bool(h1), bool(h2), bool(neg_q)]

