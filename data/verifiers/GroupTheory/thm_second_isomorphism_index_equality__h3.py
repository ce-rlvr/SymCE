def conditions(witness):
    try:
        G, H, N = witness
    except Exception:
        return [False, False, False, False]
    
    # H_1: G is a group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False

    # H_2: H is a subgroup of G
    try:
        h2 = isinstance(H, PermutationGroup) and all(g in G for g in H.generators)
    except Exception:
        h2 = False

    # H_3: The index of H cap N in H is finite
    try:
        if not isinstance(N, PermutationGroup) or not all(g in G for g in N.generators):
            h3 = False
        else:
            H_elements = set(H.generate())
            N_elements = set(N.generate())
            H_cap_N = H_elements.intersection(N_elements)
            h3 = (len(H_elements) % len(H_cap_N) == 0)
    except Exception:
        h3 = False

    # neg_Q: The conclusion fails
    try:
        H_elements = set(H.generate())
        N_elements = set(N.generate())
        H_cap_N = H_elements.intersection(N_elements)
        
        gen_HN = PermutationGroup(list(H.generators) + list(N.generators))
        expected_HN_size = len(H_elements) * len(N_elements) // len(H_cap_N)
        
        # HN is a subgroup if and only if the subgroup generated by H and N 
        # has exactly the size of the set product HN.
        HN_is_subgroup = (gen_HN.order() == expected_HN_size)
        
        if not HN_is_subgroup:
            # If HN is not a subgroup, the index of N in HN is undefined in the standard sense,
            # or if interpreted as the generated subgroup, it will be strictly greater.
            neg_q = True
        else:
            index_HN_N = gen_HN.order() // len(N_elements)
            index_H_HcapN = len(H_elements) // len(H_cap_N)
            neg_q = (index_HN_N != index_H_HcapN)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

