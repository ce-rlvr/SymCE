def is_subgroup(sub, super_group):
    try:
        if not isinstance(sub, PermutationGroup) or not isinstance(super_group, PermutationGroup):
            return False
        for g in sub.generators:
            if not super_group.contains(g):
                return False
        return True
    except Exception:
        return False

def is_normal(sub, super_group):
    try:
        if not is_subgroup(sub, super_group):
            return False
        for g in super_group.generators:
            g_inv = ~g
            for n in sub.generators:
                conj = g * n * g_inv
                if not sub.contains(conj):
                    return False
        return True
    except Exception:
        return False

def conditions(witness):
    """
    Checks if the witness satisfies the remaining hypotheses and falsifies the conclusion.
    The witness should be a tuple (G, N, H, K) of sympy PermutationGroups.
    """
    try:
        G, N, H, K = witness
    except Exception:
        return [False, False]
    
    try:
        h1_ok = False
        # Check if N and H are subgroups of G, and K is a subgroup of H
        if is_subgroup(N, G) and is_subgroup(H, G) and is_subgroup(K, H):
            # Check if N is normal in G
            if is_normal(N, G):
                # Check if G is the internal semidirect product of N and H
                # Since N is normal, NH is a subgroup. If |N|*|H| == |G|, then N intersect H is trivial and NH = G.
                if N.order() * H.order() == G.order():
                    h1_ok = True
    except Exception:
        h1_ok = False
        
    try:
        # The product NK is generated by the generators of N and K
        NK_gens = list(N.generators) + list(K.generators)
        NK = PermutationGroup(NK_gens)
        
        # The conclusion is that NK forms a normal subgroup of G.
        # We want the negation of the conclusion (i.e., NK is NOT normal in G).
        neg_q = not is_normal(NK, G)
    except Exception:
        neg_q = False
        
    return [h1_ok, neg_q]

