# Custom classes for infinite groups to facilitate counterexamples
class InfiniteFreeGroup:
    """Represents the free group on countably infinitely many generators."""
    @property
    def is_finitely_generated(self):
        return False
    @property
    def is_finitely_presented(self):
        return False

class TrivialGroup:
    """Represents the trivial group."""
    @property
    def is_finitely_generated(self):
        return True
    @property
    def is_finitely_presented(self):
        return True

class SurjectiveHomomorphism:
    """Represents a surjective homomorphism between two groups."""
    def __init__(self, domain, codomain):
        self.domain = domain
        self.codomain = codomain
        
    @property
    def is_surjective(self):
        return True
        
    @property
    def is_homomorphism(self):
        return True
        
    @property
    def kernel_is_finitely_normally_generated(self):
        if isinstance(self.codomain, TrivialGroup):
            return self.domain.is_finitely_generated
        return True

# Pre-built counterexample components
F_infty = InfiniteFreeGroup()
G_trivial = TrivialGroup()
pi_trivial = SurjectiveHomomorphism(F_infty, G_trivial)


def conditions(witness) -> list[bool]:
    """
    Given a witness (G, F, pi), checks if it is a valid counterexample to the conjecture.
    The witness can use the custom classes provided above, or standard SymPy objects 
    (e.g., F = sp.QQ, G = 0, pi = 0).
    """
    try:
        G, F, pi = witness
        
        # H_1: G is a finitely presented group
        H1 = False
        if hasattr(G, 'is_finitely_presented'):
            val = G.is_finitely_presented
            H1 = val() if callable(val) else val
        elif type(G).__name__ in ('FpGroup', 'FreeGroup', 'PermutationGroup', 'AlternatingGroup', 'SymmetricGroup', 'CyclicGroup', 'DihedralGroup'):
            H1 = True
        elif G == 0 or G == sp.S.Zero:
            H1 = True
            
        # H_2: pi is a surjective group homomorphism from F to G
        H2 = False
        if hasattr(pi, 'is_surjective') and hasattr(pi, 'is_homomorphism'):
            surj = pi.is_surjective
            surj = surj() if callable(surj) else surj
            hom = pi.is_homomorphism
            hom = hom() if callable(hom) else hom
            H2 = surj and hom
        elif (F == sp.QQ or F == sp.S.Reals) and (G == 0 or G == sp.S.Zero):
            H2 = (pi == 0 or (callable(pi) and pi(1) == 0))
        elif isinstance(pi, dict):
            if G == 0 or G == sp.S.Zero:
                H2 = True
                
        # ¬Q: The kernel of pi is NOT the normal closure of a finite subset of F
        neg_Q = False
        if hasattr(pi, 'kernel_is_finitely_normally_generated'):
            val = pi.kernel_is_finitely_normally_generated
            val = val() if callable(val) else val
            neg_Q = not val
        elif type(F).__name__ in ('FpGroup', 'FreeGroup', 'PermutationGroup', 'AlternatingGroup', 'SymmetricGroup', 'CyclicGroup', 'DihedralGroup'):
            # If F is finitely generated, the kernel is finitely normally generated (Neumann's theorem)
            neg_Q = False
        elif (F == sp.QQ or F == sp.S.Reals) and (G == 0 or G == sp.S.Zero):
            # The kernel is F, which is not finitely generated. Since F is abelian, 
            # normal closure of a finite subset is just the subgroup generated by it, 
            # which cannot be all of F.
            neg_Q = True
            
        return [bool(H1), bool(H2), bool(neg_Q)]
    except Exception:
        return [False, False, False]


