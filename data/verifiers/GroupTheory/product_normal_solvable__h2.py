CONDITION_LABELS = [
    "H_1: G is a group",
    "H_2: H is a solvable group",
    "H_3: K is a solvable group",
    "¬Q: The product HK is not a normal solvable subgroup of G"
]

N_HYP = 3
NEG_Q_INDEX = 3

def conditions(witness) -> list[bool]:
    try:
        if not isinstance(witness, tuple) or len(witness) != 3:
            return [False, False, False, False]
        G, H, K = witness
    except Exception:
        return [False, False, False, False]

    # H_1: G is a group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False

    # H_2: H is a solvable group (and implicitly a subgroup of G)
    try:
        h2 = isinstance(H, PermutationGroup) and all(g in G for g in H.generators) and H.is_solvable
    except Exception:
        h2 = False

    # H_3: K is a solvable group (and implicitly a subgroup of G)
    try:
        h3 = isinstance(K, PermutationGroup) and all(g in G for g in K.generators) and K.is_solvable
    except Exception:
        h3 = False

    # ¬Q: The product HK is not a normal solvable subgroup of G
    try:
        HK_elements = set()
        for h in H.elements:
            for k in K.elements:
                HK_elements.add(h * k)
        
        # The subgroup generated by H and K
        J = PermutationGroup(list(H.generators) + list(K.generators))
        
        # HK is a group if and only if its size equals the order of the subgroup it generates
        if len(HK_elements) != J.order():
            neg_q = True
        elif not all(j in G for j in J.generators):
            neg_q = True
        else:
            # Check if J (which is exactly HK) is normal in G
            is_normal = True
            for g in G.generators:
                g_inv = ~g
                for j in J.generators:
                    if g * j * g_inv not in J:
                        is_normal = False
                        break
                if not is_normal:
                    break
            
            # Check if J is solvable
            is_solv = J.is_solvable
            
            # The conclusion fails if HK is either not normal or not solvable
            neg_q = not (is_normal and is_solv)
    except Exception:
        neg_q = False

    return [bool(h1), bool(h2), bool(h3), bool(neg_q)]