def is_normal(G, N):
    """Check if N is a normal subgroup of G."""
    try:
        # Check if N is a subgroup of G
        for n in N.generators:
            if n not in G:
                return False
        
        # Check normality condition
        gens_G = list(G.generators)
        gens_N = list(N.generators)
        for g in gens_G:
            g_inv = ~g
            for n in gens_N:
                if (g * n * g_inv) not in N:
                    return False
                if (g_inv * n * g) not in N:
                    return False
        return True
    except Exception:
        return False

def is_semisimple(H):
    """
    Check if a finite group H is semisimple 
    (i.e., it is a direct product of non-abelian simple groups).
    This is equivalent to H being perfect and having no non-trivial solvable normal subgroups.
    """
    try:
        if H.order() == 1:
            return True
            
        # A semisimple group must be perfect
        if H.derived_subgroup().order() != H.order():
            return False
        
        gens = list(H.generators)
        gens_inv = [~g for g in gens]
        all_gens = gens + gens_inv
        
        checked = set()
        
        # Check that no non-trivial normal closure is solvable
        for x in list(H.generate()):
            if x == x**0 or x in checked:
                continue
            
            # Compute the normal closure of x in H
            conjugates = set([x])
            queue = [x]
            while queue:
                curr = queue.pop(0)
                for g in all_gens:
                    conj = g * curr * (~g)
                    if conj not in conjugates:
                        conjugates.add(conj)
                        queue.append(conj)
            
            checked.update(conjugates)
            
            NC = PermutationGroup(list(conjugates))
            if NC.is_solvable:
                return False
                
        return True
    except Exception:
        return False

def conditions(witness):
    """
    Given a witness (G, N, M), check the remaining hypotheses and the negated conclusion.
    Returns [H_1_ok, H_2_ok, neg_Q_ok].
    """
    try:
        G, N, M = witness
    except Exception:
        return [False, False, False]
        
    try:
        if isinstance(N, list):
            N = PermutationGroup(N)
        if isinstance(M, list):
            M = PermutationGroup(M)
    except Exception:
        pass
    
    # H_1: G is a finite group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False
        
    # H_2: N is a normal semisimple subgroup of G
    try:
        if not isinstance(N, PermutationGroup):
            h2 = False
        else:
            h2 = is_normal(G, N) and is_semisimple(N)
    except Exception:
        h2 = False
        
    # ¬Q: The subgroup generated by N and M is NOT a normal semisimple subgroup of G
    try:
        if not isinstance(M, PermutationGroup):
            neg_q = False
        else:
            gens = list(N.generators) + list(M.generators)
            if not gens:
                K = N
            else:
                K = PermutationGroup(gens)
            
            # The conclusion is that K is a normal semisimple subgroup of G
            q = is_normal(G, K) and is_semisimple(K)
            neg_q = not q
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

