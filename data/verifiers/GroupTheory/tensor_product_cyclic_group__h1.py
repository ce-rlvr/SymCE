CONDITION_LABELS = [
    "H_1: n is a positive integer",
    "¬Q: G ⊗_Z (Z/nZ) is not isomorphic to G/nG"
]

N_HYP = 1
NEG_Q_INDEX = 1

def conditions(witness):
    try:
        G, n = witness
    except Exception:
        return [False, False]
    
    # H_1: n is a positive integer
    try:
        h1 = (int(n) == n) and (n > 0)
    except Exception:
        h1 = False
        
    # ¬Q: G ⊗_Z (Z/nZ) is not isomorphic to G/nG
    try:
        # The tensor product of a group G with a Z-module Z/nZ is isomorphic to G_ab ⊗_Z (Z/nZ),
        # which is isomorphic to G_ab / n G_ab. This is an abelian group.
        # G/nG is the quotient G/N where N is the subgroup generated by {g^n | g in G}.
        # If G/N is not abelian, it cannot be isomorphic to the abelian group G_ab / n G_ab.
        # G/N is abelian if and only if the derived subgroup G' is a subgroup of N.
        
        elements = list(G.elements)
        n_powers = [g**n for g in elements]
        N = PermutationGroup(n_powers)
        
        G_prime = G.derived_subgroup()
        
        # Check if G' is a subgroup of N. If not, G/N is not abelian, so it's not isomorphic to G ⊗_Z (Z/nZ).
        neg_q = not all(g in N for g in G_prime.generators)
    except Exception:
        neg_q = False
        
    return [h1, neg_q]