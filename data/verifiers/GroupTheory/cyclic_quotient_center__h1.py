def conditions(witness):
    # H1: Z(G) is the center of G
    try:
        if not isinstance(witness, PermutationGroup):
            h1 = False
        else:
            # Verify we can compute the center
            Z = witness.center()
            h1 = True
    except Exception:
        h1 = False

    # H2: The quotient group G/Z(G) is a cyclic group
    try:
        if not h1:
            h2 = False
        else:
            Z = witness.center()
            q_order = witness.order() // Z.order()
            if q_order == 1:
                h2 = True
            else:
                h2 = False
                # If G/Z(G) is cyclic, it can be generated by a single element gZ.
                # Thus, G would be generated by Z and g.
                if witness.order() <= 2000:
                    Z_gens = list(Z.generators)
                    for g in witness.generate():
                        H = PermutationGroup(Z_gens + [g])
                        if H.order() == witness.order():
                            h2 = True
                            break
                else:
                    # For very large groups, we rely on the mathematical fact that 
                    # if G/Z(G) is cyclic, then G is abelian, so q_order must be 1.
                    # Since q_order > 1 here, G/Z(G) cannot be cyclic.
                    h2 = False
    except Exception:
        h2 = False

    # neg_Q: G is not an abelian group
    try:
        if not h1:
            neg_q = False
        else:
            neg_q = not witness.is_abelian
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

