def conditions(witness) -> list[bool]:
    try:
        # H_1: F_n is the free group on n generators
        # The witness represents the rank n (or the group itself).
        if type(witness).__name__ == 'FreeGroup':
            h1 = True
        elif witness == sympy.oo or witness == math.inf:
            h1 = True
        elif isinstance(witness, (int, sympy.Integer)) and witness >= 0:
            h1 = True
        elif isinstance(witness, str) and witness.lower() in ['infinity', 'inf', 'oo']:
            h1 = True
        else:
            h1 = False
    except Exception:
        h1 = False

    try:
        # ¬Q: Aut(F_n) is NOT generated by Nielsen transformations
        # This is true if and only if the rank n is infinite.
        if type(witness).__name__ == 'FreeGroup':
            # SymPy FreeGroups are of finite rank
            neg_q = False
        elif witness == sympy.oo or witness == math.inf:
            neg_q = True
        elif isinstance(witness, str) and witness.lower() in ['infinity', 'inf', 'oo']:
            neg_q = True
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, neg_q]

