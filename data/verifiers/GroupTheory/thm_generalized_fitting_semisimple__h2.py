def get_identity(G):
    if G.generators:
        return G.generators[0]**0
    return Permutation()

def normal_closure(H_gens, G):
    if not H_gens:
        return PermutationGroup([get_identity(G)])
    H_gens = [h for h in H_gens if not h.is_Identity]
    if not H_gens:
        return PermutationGroup([get_identity(G)])
    closure_group = PermutationGroup(H_gens)
    while True:
        old_order = closure_group.order()
        new_gens = list(closure_group.generators)
        for g in G.generators:
            for h in closure_group.generators:
                conj = (g**-1) * h * g
                new_gens.append(conj)
        closure_group = PermutationGroup(new_gens)
        if closure_group.order() == old_order:
            break
    return closure_group

def commutator_subgroup(A, G):
    gens = []
    for a in A.generators:
        for g in G.generators:
            c = (a**-1) * (g**-1) * a * g
            if not c.is_Identity:
                gens.append(c)
    return normal_closure(gens, G)

def nilpotent_residual(G):
    L = G
    while True:
        next_L = commutator_subgroup(L, G)
        if next_L.order() == L.order():
            break
        L = next_L
    return L

def is_perfect(G):
    if G.order() == 1:
        return True
    der = commutator_subgroup(G, G)
    return der.order() == G.order()

def O_p(G, p):
    S = G.sylow_subgroup(p)
    op_gens = []
    try:
        elements = list(S.generate())
    except AttributeError:
        elements = list(S.elements)
    for x in elements:
        if x.is_Identity:
            continue
        N = normal_closure([x], G)
        order = N.order()
        factors = factorint(order)
        if list(factors.keys()) == [p]:
            op_gens.append(x)
    if not op_gens:
        return PermutationGroup([get_identity(G)])
    return PermutationGroup(op_gens)

def fitting_subgroup(G):
    n = G.order()
    if n == 1:
        return G
    primes = list(factorint(n).keys())
    f_gens = []
    for p in primes:
        Op = O_p(G, p)
        f_gens.extend(Op.generators)
    if not f_gens:
        return PermutationGroup([get_identity(G)])
    return PermutationGroup(f_gens)

def check_F_star_eq_G(G):
    """
    Checks if the generalized Fitting subgroup F^*(G) is equal to G.
    F^*(G) = G iff the nilpotent residual L = \gamma_\infty(G) is perfect
    and G is generated by F(G) and L.
    """
    F = fitting_subgroup(G)
    L = nilpotent_residual(G)
    if not is_perfect(L):
        return False
    gens = list(F.generators) + list(L.generators)
    if not gens:
        return G.order() == 1
    FL = PermutationGroup(gens)
    return FL.order() == G.order()

def conditions(witness) -> list[bool]:
    # H_1: G is a finite group
    try:
        h1_ok = isinstance(witness, PermutationGroup)
    except Exception:
        h1_ok = False

    # neg_Q: The generalized Fitting subgroup F^*(G) of G is not equal to G
    try:
        if not h1_ok:
            neg_q_ok = False
        else:
            neg_q_ok = not check_F_star_eq_G(witness)
    except Exception:
        neg_q_ok = False

    return [h1_ok, neg_q_ok]

