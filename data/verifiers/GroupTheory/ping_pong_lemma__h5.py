def conditions(witness) -> list[bool]:
    try:
        a = witness['a']
        b = witness['b']
        mul = witness.get('mul')
        inv = witness.get('inv')
        id_elem = witness.get('id')
        action = witness.get('action')
        X2_iterable = witness['X2']
        in_X1 = witness['in_X1']
        X1_sample = witness.get('X1_sample')
        in_X = witness.get('in_X', lambda x: True)
        eq = witness.get('eq', lambda x, y: x == y)

        # Default implementations for common algebraic structures (e.g., permutations, matrices)
        if mul is None:
            mul = lambda x, y: x * y
        if inv is None:
            inv = lambda x: x**-1 if hasattr(x, '__pow__') else ~x
        if id_elem is None:
            id_elem = mul(a, inv(a))
        if action is None:
            action = lambda g, x: g(x) if callable(g) else g * x
            
        X2 = list(X2_iterable)
    except Exception:
        return [False, False, False, False, False]

    # H_1: G is a group acting on a set X
    h1_ok = False
    try:
        S = [id_elem, a, b, inv(a), inv(b), mul(a, b), mul(b, a)]
        h1_ok = True
        # Check basic group axioms on a small generated subset
        for g in S:
            if not eq(mul(g, id_elem), g) or not eq(mul(id_elem, g), g):
                h1_ok = False
            if not eq(mul(g, inv(g)), id_elem) or not eq(mul(inv(g), g), id_elem):
                h1_ok = False
        for g1 in [id_elem, a, b]:
            for g2 in [id_elem, a, b]:
                for g3 in [id_elem, a, b]:
                    if not eq(mul(mul(g1, g2), g3), mul(g1, mul(g2, g3))):
                        h1_ok = False
        
        # Check action axioms
        test_X = list(X2)
        if X1_sample is not None:
            test_X.append(X1_sample)
        for x in test_X:
            if action(id_elem, x) != x:
                h1_ok = False
            for g1 in [id_elem, a, b]:
                for g2 in [id_elem, a, b]:
                    if action(mul(g1, g2), x) != action(g1, action(g2, x)):
                        h1_ok = False
    except Exception:
        h1_ok = False

    # H_2: X1 and X2 are disjoint non-empty subsets of X
    h2_ok = False
    try:
        h2_ok = True
        if not X2:
            h2_ok = False
        if X1_sample is None or not in_X1(X1_sample):
            h2_ok = False
        for x in X2:
            if in_X1(x):
                h2_ok = False
            if not in_X(x):
                h2_ok = False
        if X1_sample is not None and not in_X(X1_sample):
            h2_ok = False
    except Exception:
        h2_ok = False

    # H_3: a and b are elements of G
    # By definition, G is the group containing a and b (or generated by them)
    h3_ok = True

    # H_4: For all non-zero integers n, the image of X2 under a^n is a subset of X1
    h4_ok = False
    try:
        h4_ok = True
        # Precompute powers of a to speed up checks
        a_pos = {0: id_elem}
        a_neg = {0: id_elem}
        curr_pos = id_elem
        curr_neg = id_elem
        inv_a = inv(a)
        for i in range(1, 101):
            curr_pos = mul(curr_pos, a)
            a_pos[i] = curr_pos
            curr_neg = mul(curr_neg, inv_a)
            a_neg[i] = curr_neg

        # Check a bounded range of n as a proxy for "all non-zero integers"
        for n in range(-100, 101):
            if n == 0:
                continue
            g = a_pos[n] if n > 0 else a_neg[-n]
            for x in X2:
                img = action(g, x)
                if not in_X1(img):
                    h4_ok = False
                    break
            if not h4_ok:
                break
    except Exception:
        h4_ok = False

    # ¬Q: The subgroup of G generated by {a, b} is not isomorphic to the free group of rank 2
    neg_q = False
    try:
        gens = {1: a, 2: b, -1: inv(a), -2: inv(b)}
        # Search for a non-trivial relation of length up to 6
        for length in range(1, 7):
            for word in itertools.product([1, 2, -1, -2], repeat=length):
                # Check if the word is freely reduced
                reduced = True
                for i in range(len(word) - 1):
                    if word[i] == -word[i+1]:
                        reduced = False
                        break
                if not reduced:
                    continue
                
                # Evaluate the reduced word
                val = id_elem
                for w in word:
                    val = mul(val, gens[w])
                
                # If a non-trivial reduced word evaluates to the identity, the group is not free
                if eq(val, id_elem):
                    neg_q = True
                    break
            if neg_q:
                break
    except Exception:
        neg_q = False

    return [h1_ok, h2_ok, h3_ok, h4_ok, neg_q]

