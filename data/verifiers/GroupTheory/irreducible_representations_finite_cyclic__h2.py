def extract_matrices(witness):
    matrices = []
    if isinstance(witness, sp.Matrix):
        matrices.append(witness)
    elif isinstance(witness, dict):
        matrices.extend([v for v in witness.values() if isinstance(v, sp.Matrix)])
    elif isinstance(witness, (list, tuple)):
        for item in witness:
            if isinstance(item, sp.Matrix):
                matrices.append(item)
            elif isinstance(item, dict):
                matrices.extend([v for v in item.values() if isinstance(v, sp.Matrix)])
            elif isinstance(item, (list, tuple)):
                matrices.extend([v for v in item if isinstance(v, sp.Matrix)])
    return matrices

def conditions(witness):
    try:
        matrices = extract_matrices(witness)
        if not matrices:
            return [False, False, False]
            
        # Find the matrix that acts as the generator (largest finite order)
        best_M = None
        max_order = 0
        for M in matrices:
            if M.shape[0] != M.shape[1]:
                continue
            d = M.shape[0]
            I = sp.eye(d)
            A = M
            order = 0
            for i in range(1, 1001):
                if A == I:
                    order = i
                    break
                A = A * M
            if order > max_order:
                max_order = order
                best_M = M
                
        if best_M is None or max_order == 0:
            return [False, False, False]
            
        d = best_M.shape[0]
        
        # Check that all provided matrices belong to the cyclic group <best_M>
        group_elements = []
        A = sp.eye(d)
        for _ in range(max_order):
            group_elements.append(A)
            A = A * best_M
            
        for M in matrices:
            if M.shape != (d, d):
                return [False, False, False]
            if M not in group_elements:
                return [False, False, False]
                
        # Check if any explicit group in witness is cyclic
        groups = []
        if hasattr(witness, 'is_cyclic'):
            groups.append(witness)
        elif isinstance(witness, (list, tuple)):
            for item in witness:
                if hasattr(item, 'is_cyclic'):
                    groups.append(item)
                    
        h1 = True
        if groups:
            for g in groups:
                if not getattr(g, 'is_cyclic', False):
                    h1 = False
                    break
                    
        # H2: Irreducibility
        # A representation of a cyclic group is irreducible over the field F
        # iff the characteristic polynomial of its generator is irreducible over F.
        x = sp.Symbol('x')
        char_poly = best_M.charpoly(x)
        
        try:
            # Construct the domain (field) generated by the matrix entries
            entries = list(best_M)
            domain = sp.polys.domains.construct_domain(entries, field=True)[0]
            p = sp.Poly(char_poly, x, domain=domain)
            h2 = bool(p.is_irreducible)
        except Exception:
            # Fallback to default irreducibility check
            try:
                h2 = bool(char_poly.is_irreducible)
            except Exception:
                h2 = False
                
        # ¬Q: The dimension of V is not exactly 1
        neg_q = (d != 1)
        
        return [h1, h2, neg_q]
    except Exception:
        return [False, False, False]