def conditions(witness) -> list[bool]:
    try:
        if not isinstance(witness, (tuple, list)) or len(witness) != 2:
            return [False, False, False]
        G, N = witness
    except Exception:
        return [False, False, False]

    # H_1: G is a group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False

    # H_2: N is a normal subgroup of G
    try:
        h2 = isinstance(N, PermutationGroup) and N.is_subgroup(G) and N.is_normal(G)
    except Exception:
        h2 = False

    # ¬Q: N is not a subgroup of the center Z(G) of G
    try:
        if not (isinstance(G, PermutationGroup) and isinstance(N, PermutationGroup)):
            neg_q = False
        else:
            Z = G.center()
            neg_q = not N.is_subgroup(Z)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

