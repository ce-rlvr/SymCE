def get_order(group):
    """Safely get the order of a PermutationGroup, handling both method and property."""
    if callable(group.order):
        return group.order()
    return group.order

def conditions(witness):
    """
    Check if the witness is a valid counterexample to the false conjecture:
    If G is a group, N is a normal subgroup of G, H is a subgroup of G, and G = NH,
    then G/N is isomorphic to H.
    
    Witness should be a tuple (G, N, H) of sympy PermutationGroup objects.
    """
    try:
        if not isinstance(witness, tuple) or len(witness) != 3:
            return [False, False, False, False, False]
        G, N, H = witness
    except Exception:
        return [False, False, False, False, False]

    # H_1: G is a group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False

    # H_2: N is a normal subgroup of G
    try:
        if isinstance(N, PermutationGroup) and N.is_subgroup(G):
            h2 = True
            for g in G.generators:
                g_inv = g**-1
                for n in N.generators:
                    if (g * n * g_inv) not in N:
                        h2 = False
                        break
                if not h2:
                    break
        else:
            h2 = False
    except Exception:
        h2 = False

    # H_3: H is a subgroup of G
    try:
        h3 = isinstance(H, PermutationGroup) and H.is_subgroup(G)
    except Exception:
        h3 = False

    # H_4: G = NH
    # Since N is normal, NH is a subgroup. The subgroup generated by N and H is exactly NH.
    try:
        if h1 and h2 and h3:
            gens = list(N.generators) + list(H.generators)
            if not gens:
                h4 = (get_order(G) == 1)
            else:
                K = PermutationGroup(gens)
                h4 = (get_order(K) == get_order(G))
        else:
            h4 = False
    except Exception:
        h4 = False

    # neg_Q: G/N is not isomorphic to H
    # By the Second Isomorphism Theorem, G/N = NH/N \cong H/(N \cap H).
    # For finite groups, G/N \cong H if and only if |N \cap H| = 1, which is equivalent to |G| = |N| * |H|.
    try:
        if h1 and h2 and h3:
            neg_q = (get_order(G) != get_order(N) * get_order(H))
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]

