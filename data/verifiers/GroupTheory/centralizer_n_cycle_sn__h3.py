def conditions(witness):
    try:
        if isinstance(witness, tuple):
            if len(witness) == 2:
                n, sigma = witness
                G = None
            elif len(witness) == 3:
                n, G, sigma = witness
            else:
                return [False, False, False]
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    try:
        h1 = isinstance(n, int) and n >= 2
    except Exception:
        h1 = False

    try:
        if not isinstance(sigma, Permutation):
            sigma = Permutation(sigma)
        
        cycles = [c for c in sigma.cyclic_form if len(c) > 1]
        is_n_cycle = (len(cycles) == 1 and len(cycles[0]) == n)
        
        support = sigma.support()
        in_Sn = (set(support) == set(range(n)))
            
        h2 = bool(is_n_cycle and in_Sn)
    except Exception:
        h2 = False

    try:
        if G is None:
            m = sigma.size
            if m < n:
                m = n
            cent_size = n * math.factorial(m - n)
            neg_q = (cent_size != n)
        else:
            count = 0
            if hasattr(G, 'generate'):
                gen = G.generate()
            elif hasattr(G, 'elements'):
                gen = G.elements
            else:
                gen = G
            for g in gen:
                if g * sigma == sigma * g:
                    count += 1
                if count > n:
                    break
            neg_q = (count != n)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

