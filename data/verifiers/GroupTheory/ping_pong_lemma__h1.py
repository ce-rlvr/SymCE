def check_unsat(expr):
    s = z3.Solver()
    s.set("timeout", 2000)
    s.add(expr)
    return s.check() == z3.unsat

def check_sat(expr):
    s = z3.Solver()
    s.set("timeout", 2000)
    s.add(expr)
    return s.check() == z3.sat

def conditions(witness):
    use_z3 = witness.get('use_z3', False)
    
    # H1: X1 and X2 are disjoint non-empty subsets of X
    try:
        X1 = witness['X1']
        X2 = witness['X2']
        if use_z3:
            x = witness['x_var']
            disjoint = check_unsat(z3.And(X1(x), X2(x)))
            non_empty_X1 = check_sat(X1(x))
            non_empty_X2 = check_sat(X2(x))
            h1_ok = disjoint and non_empty_X1 and non_empty_X2
        else:
            domain = witness['domain']
            disjoint = all(not (X1(x) and X2(x)) for x in domain)
            non_empty_X1 = any(X1(x) for x in domain)
            non_empty_X2 = any(X2(x) for x in domain)
            h1_ok = disjoint and non_empty_X1 and non_empty_X2
    except Exception:
        h1_ok = False

    # H2: a and b are elements of G
    try:
        h2_ok = callable(witness['a_action']) and callable(witness['b_action'])
    except Exception:
        h2_ok = False

    # H3: For all non-zero integers n, the image of X2 under a^n is a subset of X1
    try:
        a_action = witness['a_action']
        if use_z3:
            x = witness['x_var']
            n = witness['n_var']
            h3_ok = check_unsat(z3.Not(z3.Implies(z3.And(n != 0, X2(x)), X1(a_action(n, x)))))
        else:
            domain = witness['domain']
            n_range = witness.get('n_range', range(-20, 21))
            h3_ok = True
            for n in n_range:
                if n == 0: continue
                for x in domain:
                    if X2(x):
                        if not X1(a_action(n, x)):
                            h3_ok = False
                            break
                if not h3_ok: break
    except Exception:
        h3_ok = False

    # H4: For all non-zero integers n, the image of X1 under b^n is a subset of X2
    try:
        b_action = witness['b_action']
        if use_z3:
            x = witness['x_var']
            n = witness['n_var']
            h4_ok = check_unsat(z3.Not(z3.Implies(z3.And(n != 0, X1(x)), X2(b_action(n, x)))))
        else:
            domain = witness['domain']
            n_range = witness.get('n_range', range(-20, 21))
            h4_ok = True
            for n in n_range:
                if n == 0: continue
                for x in domain:
                    if X1(x):
                        if not X2(b_action(n, x)):
                            h4_ok = False
                            break
                if not h4_ok: break
    except Exception:
        h4_ok = False

    # ¬Q: The subgroup of G generated by {a, b} is not isomorphic to the free group of rank 2
    try:
        relation = witness['relation']
        a_action = witness['a_action']
        b_action = witness['b_action']
        
        if not relation:
            neg_q_ok = False
        else:
            reduced = []
            for char, power in relation:
                if power == 0: continue
                if reduced and reduced[-1][0] == char:
                    p = reduced.pop()[1] + power
                    if p != 0: reduced.append((char, p))
                else:
                    reduced.append((char, power))
            
            if len(reduced) == 0:
                neg_q_ok = False
            else:
                if 'a_mat' in witness and 'b_mat' in witness:
                    a_mat = witness['a_mat']
                    b_mat = witness['b_mat']
                    curr_mat = sympy.eye(a_mat.shape[0])
                    for char, power in reversed(relation):
                        if char == 'a':
                            curr_mat = (a_mat**power) * curr_mat
                        elif char == 'b':
                            curr_mat = (b_mat**power) * curr_mat
                    curr_mat = sympy.simplify(curr_mat)
                    neg_q_ok = curr_mat == sympy.eye(a_mat.shape[0])
                elif use_z3:
                    x = witness['x_var']
                    curr = x
                    for char, power in reversed(relation):
                        if char == 'a':
                            curr = a_action(power, curr)
                        elif char == 'b':
                            curr = b_action(power, curr)
                    neg_q_ok = check_unsat(curr != x)
                else:
                    domain = witness['domain']
                    is_identity = True
                    for x in domain:
                        curr = x
                        for char, power in reversed(relation):
                            if char == 'a':
                                curr = a_action(power, curr)
                            elif char == 'b':
                                curr = b_action(power, curr)
                        if curr != x:
                            is_identity = False
                            break
                    neg_q_ok = is_identity
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, h3_ok, h4_ok, neg_q_ok]