CONDITION_LABELS = ["H_1: G is a finite group", "H_2: P is a Sylow p-subgroup of G", "not Q: P intersect derived subgroup is not generated by the focal set"]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    try:
        G, P = witness
    except Exception:
        return [False, False, False]
    
    # H_1: G is a finite group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False
        
    # H_2: P is a Sylow p-subgroup of G
    try:
        h2 = False
        if isinstance(P, PermutationGroup) and isinstance(G, PermutationGroup):
            if all(G.contains(g) for g in P.generators):
                order_P = P.order()
                order_G = G.order()
                if order_P == 1:
                    h2 = True
                else:
                    factors = factorint(order_P)
                    if len(factors) == 1:
                        p = list(factors.keys())[0]
                        if order_G % (order_P * p) != 0:
                            h2 = True
    except Exception:
        h2 = False
        
    # neg_Q: P \cap [G, G] is not generated by the set
    try:
        neg_q = False
        if h1 and h2:
            P_elements_set = set(P.generate())
            G_elements = list(G.generate())
            D = G.derived_subgroup()
            
            intersection_elements = set(x for x in P_elements_set if D.contains(x))
            
            S = set()
            for x in P_elements_set:
                for g in G_elements:
                    y = ~g * x * g
                    if y in P_elements_set:
                        S.add(~x * y)
            
            if not S:
                gen_S_size = 1
            else:
                H = PermutationGroup(list(S))
                gen_S_size = H.order()
                
            if gen_S_size != len(intersection_elements):
                neg_q = True
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]