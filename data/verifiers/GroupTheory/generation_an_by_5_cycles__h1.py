def conditions(witness) -> list[bool]:
    try:
        n_float = float(witness)
        n = int(n_float)
        h1 = (n == n_float and n >= 1)
    except Exception:
        h1 = False

    try:
        if not h1:
            neg_q = False
        else:
            if n < 5:
                gen_order = 1
            elif n > 8:
                # For n >= 5, the theorem holds true, so neg_q will be False.
                # We skip computation for large n to ensure the verifier remains fast.
                gen_order = AlternatingGroup(n).order()
            else:
                five_cycles = []
                for p in itertools.permutations(range(n), 5):
                    # To avoid duplicate cycles, only consider those starting with their minimum element
                    if min(p) == p[0]:
                        five_cycles.append(Permutation([list(p)], size=n))
                G = PermutationGroup(five_cycles)
                gen_order = G.order()
            
            if n < 3:
                An_order = 1
            else:
                An_order = AlternatingGroup(n).order()
                
            neg_q = (gen_order != An_order)
    except Exception:
        neg_q = False

    return [h1, neg_q]

