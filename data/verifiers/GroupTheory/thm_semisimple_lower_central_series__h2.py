def conditions(witness):
    # H_1: G is a finite semisimple group
    # A finite group is semisimple iff it has no non-trivial normal abelian subgroups.
    # This is equivalent to saying that no non-trivial element has an abelian normal closure.
    try:
        # Limit order to prevent hanging on excessively large witness groups
        if witness.order() > 2000:
            h1_ok = False
        else:
            elements = list(witness.elements)
            seen = set()
            is_semisimple = True
            for g in elements:
                if g.is_Identity or g in seen:
                    continue
                
                # Compute the conjugacy class of g
                cclass = set()
                for x in elements:
                    cclass.add(x**-1 * g * x)
                seen.update(cclass)
                
                # The normal closure of g is generated by its conjugacy class
                N_g = PermutationGroup(*list(cclass))
                if N_g.is_abelian:
                    is_semisimple = False
                    break
            h1_ok = is_semisimple
    except Exception:
        h1_ok = False

    # neg_Q: The n-th term of the lower central series is NOT equal to G
    # The lower central series stabilizes at G iff G is perfect (i.e., derived subgroup equals G).
    # Therefore, the conclusion fails iff G is NOT perfect.
    try:
        neg_q_ok = witness.derived_subgroup().order() != witness.order()
    except Exception:
        neg_q_ok = False

    return [h1_ok, neg_q_ok]

