def eval_f(f, x):
    if isinstance(f, dict):
        return f[x]
    else:
        return f(x)

def conditions(witness) -> list[bool]:
    # H1: G and H are groups, S is a subset of G
    try:
        G = witness['G']
        H = witness['H']
        S = witness['S']
        h1 = isinstance(G, PermutationGroup) and isinstance(H, PermutationGroup)
        if h1:
            G_elements = set(G.elements)
            for s in S:
                if s not in G_elements:
                    h1 = False
                    break
    except Exception:
        h1 = False

    # H2: f is a homomorphism from G to H
    try:
        G = witness['G']
        H = witness['H']
        f = witness['f']
        h2 = True
        H_elements = set(H.elements)
        G_elements = list(G.elements)
        for g1 in G_elements:
            fg1 = eval_f(f, g1)
            if fg1 not in H_elements:
                h2 = False
                break
            for g2 in G_elements:
                fg2 = eval_f(f, g2)
                fg12 = eval_f(f, g1 * g2)
                if fg12 != fg1 * fg2:
                    h2 = False
                    break
            if not h2:
                break
    except Exception:
        h2 = False

    # neg_Q: <f(S)> != f(G)
    try:
        G = witness['G']
        H = witness['H']
        f = witness['f']
        S = witness['S']
        
        f_G_elements = set()
        for g in G.elements:
            f_G_elements.add(eval_f(f, g))
            
        f_S_elements = set()
        for s in S:
            f_S_elements.add(eval_f(f, s))
            
        if not f_S_elements:
            gen_f_S = PermutationGroup([H.identity])
        else:
            gen_f_S = PermutationGroup(list(f_S_elements))
            
        gen_f_S_elements = set(gen_f_S.elements)
        
        neg_q = gen_f_S_elements != f_G_elements
    except Exception:
        neg_q = False

    return [bool(h1), bool(h2), bool(neg_q)]

