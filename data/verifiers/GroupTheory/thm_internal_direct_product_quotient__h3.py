def conditions(witness):
    try:
        G, H, K = witness
    except Exception:
        return [False, False, False, False]
    
    # H_1: G is a group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False
        
    # H_2: H and K are normal subgroups of G
    try:
        def is_normal(grp, sub):
            if not isinstance(sub, PermutationGroup):
                return False
            # Check if sub is a subgroup of grp
            if not all(g in grp for g in sub.generators):
                return False
            # Check normality: g * h * g^-1 in sub for all generators
            for g in grp.generators:
                g_inv = ~g
                for h in sub.generators:
                    if g * h * g_inv not in sub:
                        return False
            return True
        
        h2 = is_normal(G, H) and is_normal(G, K)
    except Exception:
        h2 = False
        
    # H_3: HK = G
    try:
        # Since H and K are normal, the subgroup generated by their union is HK.
        gens = list(H.generators) + list(K.generators)
        if not all(g in G for g in gens):
            h3 = False
        else:
            HK = PermutationGroup(gens)
            h3 = (HK.order() == G.order())
    except Exception:
        h3 = False
        
    # ¬Q: G is not isomorphic to H × K or G/H is not isomorphic to K
    try:
        # For finite groups, if H and K are normal and HK = G, 
        # G is isomorphic to H × K (and G/H ≅ K) if and only if H ∩ K = {e}.
        # This is equivalent to |G| == |H| * |K|.
        # Thus, the conclusion fails if and only if |G| != |H| * |K|.
        neg_q = (G.order() != H.order() * K.order())
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

