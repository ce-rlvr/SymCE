def is_semisimple(G):
    """
    A finite group is semisimple if it has no non-trivial abelian normal subgroups.
    Equivalently, for every non-identity element g, the normal closure of <g> is non-abelian.
    The normal closure of <g> is generated by the conjugacy class of g.
    If all elements in the conjugacy class of g commute, they generate an abelian normal subgroup.
    """
    if not isinstance(G, PermutationGroup):
        return False
    if G.order() == 1:
        return True
        
    gens = G.generators
    
    try:
        elements = list(G.elements)
    except AttributeError:
        elements = list(G.generate())
        
    id_perm = None
    for e in elements:
        if e == e**2:
            id_perm = e
            break
            
    checked = set([id_perm])
    
    for g in elements:
        if g in checked:
            continue
        
        # Find the conjugacy class of g using BFS
        class_g = set([g])
        queue = [g]
        while queue:
            curr = queue.pop(0)
            for gen in gens:
                conj = ~gen * curr * gen
                if conj not in class_g:
                    class_g.add(conj)
                    queue.append(conj)
        
        checked.update(class_g)
        
        class_g_list = list(class_g)
        
        # If the conjugacy class has size 1, g is in the center.
        # Since g != id, the center is a non-trivial abelian normal subgroup.
        if len(class_g_list) == 1:
            return False
            
        is_abelian = True
        for i in range(len(class_g_list)):
            for j in range(i + 1, len(class_g_list)):
                if class_g_list[i] * class_g_list[j] != class_g_list[j] * class_g_list[i]:
                    is_abelian = False
                    break
            if not is_abelian:
                break
        
        # If all elements in the conjugacy class commute, they generate an abelian normal subgroup.
        if is_abelian:
            return False
            
    return True

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, dict):
            G = witness.get('G')
            H = witness.get('H')
        else:
            G = witness[0]
            H = witness[1]
    except Exception:
        return [False, False]
        
    try:
        h1 = is_semisimple(G)
    except Exception:
        h1 = False
        
    try:
        if not isinstance(H, PermutationGroup):
            neg_q = False
        else:
            neg_q = not is_semisimple(H)
    except Exception:
        neg_q = False
        
    return [h1, neg_q]

