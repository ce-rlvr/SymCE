CONDITION_LABELS = [
    "H_1: H is a finitely generated subgroup of F",
    "H_2: K is a finitely generated subgroup of F",
    "¬Q: H \\cap K is not a finitely generated subgroup of F"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness) -> list[bool]:
    # Extract F, H, K from the witness
    try:
        if isinstance(witness, dict):
            F = witness['F']
            H = witness['H']
            K = witness['K']
        elif hasattr(witness, 'F') and hasattr(witness, 'H') and hasattr(witness, 'K'):
            F = witness.F
            H = witness.H
            K = witness.K
        else:
            F, H, K = witness
    except Exception:
        return [False, False, False]

    def is_fg(g):
        if hasattr(g, 'is_finitely_generated'):
            fg = getattr(g, 'is_finitely_generated')
            if callable(fg):
                return bool(fg())
            return bool(fg)
        # Fallback for standard SymPy groups which are finitely generated by definition
        if hasattr(g, 'generators') or hasattr(g, 'gens'):
            return True
        raise AttributeError("is_finitely_generated not found")

    def is_sub(sub, group):
        if hasattr(sub, 'is_subgroup'):
            subg = getattr(sub, 'is_subgroup')
            if callable(subg):
                try:
                    return bool(subg(group))
                except TypeError:
                    return bool(subg())
            return bool(subg)
        else:
            return bool(sub <= group)

    def get_intersection(h, k):
        if hasattr(h, 'intersect'):
            return h.intersect(k)
        elif hasattr(h, 'intersection'):
            return h.intersection(k)
        else:
            return h & k

    # Evaluate Hypothesis 1
    try:
        h1_ok = is_fg(H) and is_sub(H, F)
    except Exception:
        h1_ok = False

    # Evaluate Hypothesis 2
    try:
        h2_ok = is_fg(K) and is_sub(K, F)
    except Exception:
        h2_ok = False

    # Evaluate Negated Conclusion
    try:
        int_HK = get_intersection(H, K)
        # The conclusion is that H \cap K is a finitely generated subgroup of F.
        # The negation is that it is NOT finitely generated (while still being a valid subgroup).
        neg_q_ok = (not is_fg(int_HK)) and is_sub(int_HK, F)
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, neg_q_ok]