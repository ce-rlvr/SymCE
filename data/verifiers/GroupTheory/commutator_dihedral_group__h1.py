def conditions(witness):
    try:
        if isinstance(witness, int):
            n = witness
            if n < 1:
                return [False, False, False]
            h1 = True
            h2 = True
            if n == 1:
                G = PermutationGroup([Permutation(0, 1)])
                r = G.identity
            elif n == 2:
                G = PermutationGroup([Permutation(0, 1)(2, 3), Permutation(0, 2)(1, 3)])
                r = Permutation(0, 1)(2, 3)
            else:
                G = DihedralGroup(n)
                r = None
                for g in G.generators:
                    if g.order() == n:
                        r = g
                        break
                if r is None:
                    for g in G.elements:
                        if g.order() == n:
                            r = g
                            break
                if r is None:
                    return [False, False, False]
        else:
            if isinstance(witness, tuple):
                if len(witness) == 2:
                    G, r = witness
                elif len(witness) == 3:
                    _, G, r = witness
                else:
                    return [False, False, False]
            else:
                return [False, False, False]
                
            order = G.order()
            if order % 2 != 0:
                h1 = False
            else:
                n = order // 2
                if n == 1:
                    h1 = G.is_abelian and order == 2
                elif n == 2:
                    h1 = G.is_abelian and order == 4 and all(g.order() in (1, 2) for g in G.elements)
                else:
                    h1 = False
                    for g in G.elements:
                        if g.order() == n:
                            for s in G.elements:
                                if s.order() == 2 and s * g * s == g**-1:
                                    if PermutationGroup([g, s]).order() == order:
                                        h1 = True
                                        break
                        if h1:
                            break
            
            if not h1:
                h2 = False
            else:
                n = G.order() // 2
                if n == 1:
                    h2 = (r.order() == 1 and r in G)
                elif n == 2:
                    h2 = (r.order() == 2 and r in G)
                else:
                    h2 = (r.order() == n and r in G)
    except Exception:
        return [False, False, False]

    try:
        C = G.derived_subgroup()
        r2 = r**2
        order_r2 = r2.order()
        gen_r2 = set([r2**i for i in range(1, order_r2 + 1)])
        C_elements = set(C.elements)
        neg_q = (C_elements != gen_r2)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

