def conditions(witness):
    try:
        if len(witness) == 4:
            G, a, k, n = witness
        elif len(witness) == 3:
            G, a, k = witness
            n = G.order()
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]
        
    # H1: G is a finite cyclic group of order n
    try:
        h1 = False
        if hasattr(G, 'order') and hasattr(G, 'elements'):
            if G.order() == n:
                h1 = any(g.order() == n for g in G.elements)
    except Exception:
        h1 = False
        
    # H2: G is generated by the element a
    try:
        h2 = False
        if hasattr(G, 'elements'):
            h2 = (a in G.elements) and hasattr(a, 'order') and (a.order() == n)
    except Exception:
        h2 = False
        
    # Q: The element a^k generates G if and only if gcd(k, n) = 1
    try:
        ak = a**k
        ak_generates = (hasattr(ak, 'order') and ak.order() == n)
        gcd_val = sympy.gcd(k, n)
        gcd_is_1 = (gcd_val == 1)
        q = (ak_generates == gcd_is_1)
        neg_q = not q
    except Exception:
        neg_q = False
        
    return [bool(h1), bool(h2), bool(neg_q)]

