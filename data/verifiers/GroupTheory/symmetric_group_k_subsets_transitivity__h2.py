def conditions(witness) -> list[bool]:
    """
    Given a witness object, checks whether it is a valid counterexample 
    to the false conjecture.
    """
    try:
        if isinstance(witness, tuple):
            if len(witness) == 2:
                n, k = witness
                try:
                    X = set(frozenset(c) for c in itertools.combinations(range(1, n+1), k))
                except Exception:
                    X = None
            elif len(witness) == 3:
                n, k, X = witness
            else:
                return [False, False, False]
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H_1: n and k are integers with 0 <= k <= n.
    try:
        h1_ok = isinstance(n, int) and isinstance(k, int) and (0 <= k <= n)
    except Exception:
        h1_ok = False

    # H_2: X is the set of all k-element subsets of {1, 2, ..., n}.
    try:
        if not h1_ok or X is None:
            h2_ok = False
        else:
            expected_X = set(frozenset(c) for c in itertools.combinations(range(1, n+1), k))
            if isinstance(X, set) and all(isinstance(x, frozenset) for x in X):
                h2_ok = (X == expected_X)
            else:
                try:
                    actual_X = set(frozenset(x) for x in X)
                    h2_ok = (actual_X == expected_X)
                except Exception:
                    h2_ok = False
    except Exception:
        h2_ok = False

    # ¬Q: The natural induced action of S_n on X is NOT transitive.
    try:
        if not (h1_ok and h2_ok):
            neg_q = False
        else:
            if len(X) == 0:
                is_transitive = False
            elif n <= 1:
                is_transitive = True
            elif len(X) > 5000:
                # For very large sets that perfectly match H2, we know mathematically 
                # that S_n is k-homogeneous, so it is transitive.
                is_transitive = True
            else:
                # Explicitly compute the orbits of S_n on X using BFS.
                # S_n is generated by (1 2) and (1 2 ... n) for n >= 2.
                elements = list(range(1, n+1))
                
                g1 = {i: i for i in elements}
                if n >= 2:
                    g1[1] = 2
                    g1[2] = 1
                
                g2 = {i: i+1 for i in elements}
                if n >= 1:
                    g2[n] = 1
                
                def apply_g(g, subset):
                    return frozenset(g.get(i, i) for i in subset)
                    
                start = next(iter(X))
                visited = set([start])
                queue = [start]
                head = 0
                
                is_transitive = True
                while head < len(queue):
                    curr = queue[head]
                    head += 1
                    for g in (g1, g2):
                        nxt = apply_g(g, curr)
                        if nxt not in X:
                            is_transitive = False
                            break
                        if nxt not in visited:
                            visited.add(nxt)
                            queue.append(nxt)
                    if not is_transitive:
                        break
                
                if is_transitive:
                    is_transitive = (len(visited) == len(X))
            
            neg_q = not is_transitive
    except Exception:
        neg_q = False

    return [h1_ok, h2_ok, neg_q]

