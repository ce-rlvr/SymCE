def _lcm(x, y):
    return abs(x * y) // math.gcd(x, y) if x and y else 0

def is_subgroup_generated_by(subgroup, generator):
    if subgroup is None:
        return False
        
    try:
        if subgroup == generator:
            return True
    except Exception:
        pass
        
    # Integer ideal representation (subgroups of Z)
    if isinstance(subgroup, (int, sympy.Integer)) and isinstance(generator, (int, sympy.Integer)):
        return abs(int(subgroup)) == abs(int(generator))
        
    # PermutationGroup representation
    try:
        from sympy.combinatorics import PermutationGroup
        if isinstance(subgroup, PermutationGroup):
            gen_group = PermutationGroup([generator])
            return subgroup.is_subgroup(gen_group) and gen_group.is_subgroup(subgroup)
    except Exception:
        pass
        
    # Set/List representation
    try:
        from sympy import FiniteSet
        if isinstance(subgroup, (set, frozenset, list, tuple, FiniteSet)):
            gen_list = []
            current = generator
            for _ in range(1000):
                if current not in gen_list:
                    gen_list.append(current)
                else:
                    break
                try:
                    current = current * generator
                except Exception:
                    break
                # Prevent massive integers from blowing up memory
                if isinstance(current, (int, float)) and abs(current) > 10**6:
                    break
            
            if len(subgroup) != len(gen_list):
                return False
            for elem in subgroup:
                if elem not in gen_list:
                    return False
            return True
    except Exception:
        pass
        
    return False

def get_intersection(H, K):
    # Intersection of ideals in Z
    if isinstance(H, (int, sympy.Integer)) and isinstance(K, (int, sympy.Integer)):
        return _lcm(int(H), int(K))
    
    try:
        if hasattr(H, 'intersection'):
            return H.intersection(K)
    except Exception:
        pass
        
    try:
        if hasattr(H, 'intersect'):
            return H.intersect(K)
    except Exception:
        pass
        
    try:
        return H & K
    except Exception:
        pass
        
    # Intersection of PermutationGroups
    try:
        from sympy.combinatorics import PermutationGroup
        if isinstance(H, PermutationGroup) and isinstance(K, PermutationGroup):
            if H.order() < 1000 and K.order() < 1000:
                elems_H = set(list(H.generate()))
                elems_K = set(list(K.generate()))
                common = elems_H.intersection(elems_K)
                return PermutationGroup(list(common))
    except Exception:
        pass

    # Intersection of standard collections
    try:
        if isinstance(H, (set, frozenset)) and isinstance(K, (set, frozenset)):
            return H.intersection(K)
        if isinstance(H, (list, tuple)) and isinstance(K, (list, tuple)):
            return [x for x in H if x in K]
    except Exception:
        pass

    return None

def conditions(witness):
    def get_attr(w, name):
        if isinstance(w, dict):
            return w.get(name)
        return getattr(w, name, None)
        
    m = get_attr(witness, 'm')
    n = get_attr(witness, 'n')
    a = get_attr(witness, 'a')
    H = get_attr(witness, 'H')
    K = get_attr(witness, 'K')
    
    # H_1: m and n are positive integers
    try:
        h1 = isinstance(m, (int, sympy.Integer)) and isinstance(n, (int, sympy.Integer)) and m > 0 and n > 0
    except Exception:
        h1 = False
        
    # H_2: H is the subgroup generated by a^m
    try:
        if h1 and a is not None and H is not None:
            a_m = a ** m
            h2 = is_subgroup_generated_by(H, a_m)
        else:
            h2 = False
    except Exception:
        h2 = False
        
    # H_3: K is the subgroup generated by a^n
    try:
        if h1 and a is not None and K is not None:
            a_n = a ** n
            h3 = is_subgroup_generated_by(K, a_n)
        else:
            h3 = False
    except Exception:
        h3 = False
        
    # ¬Q: The intersection H \cap K is NOT the subgroup generated by a^{\operatorname{lcm}(m,n)}
    try:
        if h1 and a is not None and H is not None and K is not None:
            H_cap_K = get_intersection(H, K)
            if H_cap_K is None:
                neg_q = False
            else:
                lcm_mn = _lcm(int(m), int(n))
                a_lcm = a ** lcm_mn
                neg_q = not is_subgroup_generated_by(H_cap_K, a_lcm)
        else:
            neg_q = False
    except Exception:
        neg_q = False
        
    return [bool(h1), bool(h2), bool(h3), bool(neg_q)]