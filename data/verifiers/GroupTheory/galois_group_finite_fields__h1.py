def conditions(witness) -> list[bool]:
    # Check H_1: E is a finite field extension of F
    try:
        if isinstance(witness, Poly):
            p = witness
        else:
            # If witness is an algebraic element (no 'x' in free symbols), compute its minimal polynomial
            if hasattr(witness, 'free_symbols') and x not in witness.free_symbols:
                p = Poly(minpoly(witness, x), x)
            else:
                p = Poly(witness, x)
        
        # A finite field extension can be represented by an irreducible polynomial of degree >= 1
        h1 = p.degree() >= 1 and p.is_irreducible
    except Exception:
        h1 = False

    # Check ¬Q: The Galois group Gal(E/F) is NOT a cyclic group generated by the Frobenius automorphism
    try:
        if isinstance(witness, Poly):
            p = witness
        else:
            if hasattr(witness, 'free_symbols') and x not in witness.free_symbols:
                p = Poly(minpoly(witness, x), x)
            else:
                p = Poly(witness, x)
            
        domain = p.domain
        is_finite = getattr(domain, 'is_FiniteField', False)
        
        if is_finite:
            # If the base field is finite, the Galois group IS cyclic and generated by Frobenius.
            # Thus, the conclusion holds, and its negation is False.
            neg_q = False
        else:
            # If the base field is not finite (e.g., QQ), the Frobenius automorphism either 
            # does not exist (characteristic 0) or does not generate the Galois group.
            # The conclusion fails as long as the extension is non-trivial (degree > 1).
            neg_q = p.degree() > 1
    except Exception:
        neg_q = False

    return [bool(h1), bool(neg_q)]

