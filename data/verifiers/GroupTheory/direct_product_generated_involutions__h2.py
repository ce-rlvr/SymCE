def direct_product(G, H):
    """Constructs the direct product of two permutation groups."""
    n = G.degree
    m = H.degree
    if n == 0: n = 1
    if m == 0: m = 1
    gens = []
    
    for g in G.generators:
        arr = g.array_form
        arr = arr + list(range(len(arr), n))
        arr = arr + list(range(n, n + m))
        gens.append(Permutation(arr))
        
    for h in H.generators:
        arr = h.array_form
        arr = arr + list(range(len(arr), m))
        arr = list(range(n)) + [x + n for x in arr]
        gens.append(Permutation(arr))
        
    if not gens:
        return PermutationGroup([Permutation(0)])
    return PermutationGroup(gens)

def is_generated_by_involutions(grp):
    """Checks if a permutation group is generated by its involutions."""
    if grp.order() == 1:
        return True
    involutions = [g for g in list(grp.elements) if g.order() == 2]
    if not involutions:
        return False
    gen_grp = PermutationGroup(involutions)
    return gen_grp.order() == grp.order()

def conditions(witness) -> list[bool]:
    try:
        if not isinstance(witness, (list, tuple)) or len(witness) != 2:
            return [False, False, False]
        G, H = witness
    except Exception:
        return [False, False, False]
    
    # H_1: G and H are groups
    try:
        h1 = isinstance(G, PermutationGroup) and isinstance(H, PermutationGroup)
    except Exception:
        h1 = False
        
    # H_2: H is generated by a set of involutions
    try:
        h2 = False
        if h1:
            h2 = is_generated_by_involutions(H)
    except Exception:
        h2 = False
        
    # ¬Q: G x H is NOT generated by a set of involutions
    try:
        neg_q = False
        if h1:
            GxH = direct_product(G, H)
            neg_q = not is_generated_by_involutions(GxH)
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

