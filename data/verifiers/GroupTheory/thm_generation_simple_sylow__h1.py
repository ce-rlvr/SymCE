def normal_closure(G, P):
    """
    Computes the normal closure of subgroup P in group G.
    This is equivalent to the subgroup generated by all conjugates of P in G.
    """
    if P.order() == 1:
        return P
    group = P
    while True:
        new_gens = list(group.generators)
        for g in G.generators:
            for x in group.generators:
                new_gens.append(g * x * g**-1)
                new_gens.append(g**-1 * x * g)
        new_group = PermutationGroup(new_gens)
        if new_group.order() == group.order():
            break
        group = new_group
    return group

def conditions(witness):
    try:
        G, p = witness
    except Exception:
        return [False, False]
    
    try:
        h1 = isprime(p) and G.order() % p == 0
    except Exception:
        h1 = False
        
    try:
        if not hasattr(G, 'sylow_subgroup'):
            neg_q = False
        else:
            # The subgroup generated by the union of all Sylow p-subgroups 
            # is exactly the normal closure of any single Sylow p-subgroup.
            P = G.sylow_subgroup(p)
            N = normal_closure(G, P)
            neg_q = N.order() != G.order()
    except Exception:
        neg_q = False
        
    return [bool(h1), bool(neg_q)]

