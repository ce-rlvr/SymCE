def conditions(witness) -> list[bool]:
    try:
        if len(witness) == 3:
            F, n, Fn = witness
        elif len(witness) == 2:
            F, n = witness
            Fn = None
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H1: n is a positive integer
    try:
        h1 = isinstance(n, (int, sympy.Integer)) and n > 0
    except Exception:
        h1 = False

    # H2: F^n is the subgroup of F generated by the set of all n-th powers of elements in F
    try:
        if not isinstance(F, PermutationGroup):
            h2 = False
        else:
            elements = list(F.generate())
            nth_powers = set()
            for g in elements:
                nth_powers.add(g**n)
            expected_Fn = PermutationGroup(list(nth_powers))
            if Fn is None:
                Fn = expected_Fn
                h2 = True
            else:
                if not isinstance(Fn, PermutationGroup):
                    h2 = False
                else:
                    h2 = Fn.is_subgroup(expected_Fn) and expected_Fn.is_subgroup(Fn)
    except Exception:
        h2 = False

    # neg_Q: F^n is NOT a fully characteristic subgroup of F
    try:
        if not isinstance(F, PermutationGroup):
            neg_q = False
        elif not isinstance(Fn, PermutationGroup):
            neg_q = True
        else:
            elements = list(F.generate())
            gens = F.generators
            if not gens:
                identity = elements[0]
            else:
                identity = gens[0]**0
            
            valid_mappings = []
            for images in itertools.product(elements, repeat=len(gens)):
                mapping = {identity: identity}
                valid = True
                queue = [identity]
                while queue:
                    curr = queue.pop(0)
                    for i, g in enumerate(gens):
                        nxt = curr * g
                        nxt_img = mapping[curr] * images[i]
                        if nxt in mapping:
                            if mapping[nxt] != nxt_img:
                                valid = False
                                break
                        else:
                            mapping[nxt] = nxt_img
                            queue.append(nxt)
                    if not valid:
                        break
                if valid:
                    valid_mappings.append(mapping)
            
            is_fully_char = True
            for phi in valid_mappings:
                for g in Fn.generators:
                    img = phi.get(g)
                    if img is None:
                        is_fully_char = False
                        break
                    try:
                        if not Fn.contains(img):
                            is_fully_char = False
                            break
                    except Exception:
                        is_fully_char = False
                        break
                if not is_fully_char:
                    break
            
            neg_q = not is_fully_char
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

