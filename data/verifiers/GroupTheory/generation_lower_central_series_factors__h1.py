def conditions(witness):
    try:
        G, S, k = witness
    except Exception:
        return [False, False, False]
    
    # H_1: S is a generating set for G
    try:
        if not all(s in G for s in S):
            h1 = False
        else:
            H = PermutationGroup(list(S))
            h1 = H.order() == G.order()
    except Exception:
        h1 = False
        
    # H_2: k is a positive integer
    try:
        h2 = isinstance(k, int) and not isinstance(k, bool) and k > 0
    except Exception:
        h2 = False
        
    # ¬Q: The quotient group gamma_k(G)/gamma_{k+1}(G) is NOT generated by the images of the simple commutators of weight k formed by elements of S
    try:
        lcs = G.lower_central_series()
        def gamma(n):
            if n - 1 < len(lcs):
                return lcs[n - 1]
            else:
                return lcs[-1]
        
        gamma_k = gamma(k)
        gamma_k_plus_1 = gamma(k + 1)
        
        def simple_commutators(S_set, weight):
            if weight == 1:
                return set(S_set)
            prev = simple_commutators(S_set, weight - 1)
            curr = set()
            for c in prev:
                for s in S_set:
                    curr.add(~c * ~s * c * s)
            return curr
            
        C_k = simple_commutators(S, k)
        
        if G.generators:
            id_perm = list(G.generators)[0]**0
        else:
            id_perm = Permutation()
            
        gens = list(C_k) + list(gamma_k_plus_1.generators) + [id_perm]
        H_gen = PermutationGroup(gens)
        
        neg_q = H_gen.order() != gamma_k.order()
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

