def conditions(witness) -> list[bool]:
    try:
        n, G, P = witness
    except Exception:
        return [False, False, False]
    
    # H_1: n is an odd integer greater than 1
    try:
        h1 = int(n) == n and n % 2 == 1 and n > 1
    except Exception:
        h1 = False

    # H_2: G is the dihedral group D_{2n} of order 2n
    try:
        h2 = False
        if getattr(G, 'is_group', False) and G.order() == 2 * n:
            if G == DihedralGroup(n):
                h2 = True
            elif n < 1000:
                elements = list(G.elements)
                reflections = [g for g in elements if g.order() == 2]
                if len(reflections) == n:
                    h2 = True
    except Exception:
        h2 = False

    # Q: P has order 2 and is generated by a single reflection element
    try:
        q = False
        if getattr(P, 'is_group', False) and P.order() == 2:
            P_elements = list(P.elements)
            # Check if P is a subgroup of G. In D_{2n} with n odd, any element of order 2 is a reflection.
            if all(g in G for g in P_elements):
                q = True
    except Exception:
        q = False

    neg_q = not q

    return [h1, h2, neg_q]

