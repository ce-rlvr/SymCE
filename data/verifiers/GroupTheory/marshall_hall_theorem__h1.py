def conditions(witness):
    """
    Checks if the witness is a valid counterexample.
    
    The conjecture states: Let F be a group, H a finitely generated subgroup.
    Then there exists K of finite index in F such that H is a free factor of K.
    
    Finite groups cannot be counterexamples (if F is finite, K=H has finite index 
    and H is a free factor of K).
    We use finitely generated abelian groups F = Z^n.
    
    Witness should be a sympy Matrix M (or a list of lists).
    F is interpreted as Z^n where n = M.cols.
    H is interpreted as the subgroup generated by the rows of M.
    """
    try:
        if isinstance(witness, (list, tuple)):
            M = Matrix(witness)
        else:
            M = witness
            
        if not isinstance(M, Matrix):
            return [False, False]
            
        n = M.cols
        
        # H_1: H is a finitely generated subgroup of F
        # The rows of the matrix represent a finite set of generators for H.
        # Thus H is finitely generated.
        h1_ok = True
        
        # neg_Q: The conclusion fails.
        # Conclusion: There exists K of finite index in Z^n such that H is a free factor of K.
        # Since Z^n is abelian, any subgroup K is abelian.
        # A free product K = H * L is abelian iff H = 1 or L = 1.
        # If H = 1, rank(H) = 0.
        # If L = 1, K = H. For K to have finite index in Z^n, we must have rank(H) = n.
        # Thus, the conclusion holds iff rank(H) == 0 or rank(H) == n.
        # The conclusion fails (neg_Q is True) iff 0 < rank(H) < n.
        r = M.rank()
        neg_q_ok = bool(0 < r < n)
        
        return [h1_ok, neg_q_ok]
    except Exception:
        return [False, False]

