CONDITION_LABELS = [
    "H_1: G is a group",
    "H_2: S is a finite subset of G",
    "H_3: S is invariant under conjugation by all elements of G",
    "¬Q: The subgroup generated by S is not a finite normal subgroup of G"
]

N_HYP = 3
NEG_Q_INDEX = 3

def conditions(witness):
    try:
        G, S = witness
    except Exception:
        return [False, False, False, False]

    # H_1: G is a group
    try:
        h1 = isinstance(G, PermutationGroup)
        if not h1:
            if hasattr(G, 'generators') and hasattr(G, 'identity'):
                h1 = True
    except Exception:
        h1 = False

    # H_2: S is a finite subset of G
    try:
        h2 = isinstance(S, (set, list, tuple))
        if h2:
            for s in S:
                if s not in G:
                    h2 = False
                    break
    except Exception:
        h2 = False

    # H_3: S is invariant under conjugation by all elements of G
    try:
        h3 = True
        if h1 and h2:
            gens = list(G.generators)
            gens_inv = [g**-1 for g in gens]
            all_gens = gens + gens_inv
            for g in all_gens:
                for s in S:
                    conj = g * s * g**-1
                    if conj not in S:
                        h3 = False
                        break
                if not h3:
                    break
        else:
            h3 = False
    except Exception:
        h3 = False

    # ¬Q: The subgroup generated by S is not a finite normal subgroup of G
    try:
        neg_q = False
        if h1 and h2:
            is_finite = True
            
            # By Dietzmann's Lemma, if S is finite and invariant under conjugation,
            # the subgroup <S> is infinite if and only if S contains an element of infinite order.
            if isinstance(G, PermutationGroup):
                # All permutation groups are finite.
                is_finite = True
            else:
                # Fallback for other group types: check if any element has infinite order.
                # In a free group, all non-identity elements have infinite order.
                if type(G).__name__ == 'FreeGroup':
                    if any(s != G.identity for s in S):
                        is_finite = False
                else:
                    for s in S:
                        if hasattr(s, 'order'):
                            try:
                                ord_s = s.order()
                                if ord_s == float('inf') or ord_s == sympy.oo:
                                    is_finite = False
                                    break
                            except Exception:
                                pass
                        elif hasattr(s, 'is_identity'):
                            if not s.is_identity:
                                # Assume infinite order if we can't determine
                                is_finite = False
                                break
            
            if not is_finite:
                neg_q = True
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]