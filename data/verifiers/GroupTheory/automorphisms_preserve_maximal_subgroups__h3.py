def is_maximal_subgroup(G, M):
    try:
        if not M.is_subgroup(G):
            return False
        if M.order() == G.order():
            return False
        
        M_elements = set(M.elements)
        for g in G.elements:
            if g not in M_elements:
                gen = list(M.generators) + [g]
                H = PermutationGroup(gen)
                if H.order() != G.order():
                    return False
        return True
    except Exception:
        return False

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness should be a tuple (G, M, alpha) where:
      - G is a PermutationGroup
      - M is a PermutationGroup (maximal subgroup of G)
      - alpha is a callable or dict mapping elements of G to elements of G
    """
    try:
        G, M, alpha = witness
    except Exception:
        return [False, False, False]
    
    # H_1: G is a group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False
        
    # H_2: M is a maximal subgroup of G
    try:
        h2 = is_maximal_subgroup(G, M)
    except Exception:
        h2 = False
        
    # ¬Q: The image alpha(M) is NOT a maximal subgroup of G
    try:
        if isinstance(alpha, dict):
            image_M_elements = set(alpha[m] for m in M.elements)
        else:
            image_M_elements = set(alpha(m) for m in M.elements)
            
        image_M_list = list(image_M_elements)
        
        # Create a group generated by the image elements
        H_image = PermutationGroup(image_M_list)
        
        # If the generated group is larger than the set of elements, 
        # the image is not closed under the group operation (not a subgroup).
        if H_image.order() != len(image_M_elements):
            is_max = False
        else:
            is_max = is_maximal_subgroup(G, H_image)
            
        neg_q = not is_max
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

