def conditions(witness) -> list[bool]:
    try:
        G, N, p, P = witness
    except Exception:
        return [False, False, False, False]
    
    # H_1: G is a finite group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False
        
    # H_2: N is a normal subgroup of G
    try:
        h2 = isinstance(N, PermutationGroup) and N.is_subgroup(G) and N.is_normal(G)
    except Exception:
        h2 = False
        
    # H_3: p is a prime number
    try:
        h3 = bool(isprime(p))
    except Exception:
        h3 = False
        
    # ¬Q: PN/N is not a Sylow p-subgroup of G/N
    try:
        if not (isinstance(P, PermutationGroup) and P.is_subgroup(G)):
            neg_q = False
        else:
            # PN is the subgroup generated by P and N
            gens = list(P.generators) + list(N.generators)
            PN = PermutationGroup(gens)
            
            order_G_N = G.order() // N.order()
            order_PN_N = PN.order() // N.order()
            
            # Calculate the p-part of the order of G/N
            p_part = 1
            temp = order_G_N
            if p > 1:
                while temp % p == 0:
                    p_part *= p
                    temp //= p
                    
            # PN/N is a Sylow p-subgroup iff its order is exactly the p-part of |G/N|
            neg_q = (order_PN_N != p_part)
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

