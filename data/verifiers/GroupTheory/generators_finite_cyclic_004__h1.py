def conditions(witness):
    G = a = k = n = None
    try:
        if isinstance(witness, dict):
            G = witness.get('G')
            a = witness.get('a')
            k = witness.get('k')
            n = witness.get('n')
        elif isinstance(witness, (tuple, list)):
            if len(witness) == 4:
                G, a, k, n = witness
            else:
                return [False, False, False]
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H1: G is generated by the element a
    try:
        H1 = bool(G == PermutationGroup([a]))
    except Exception:
        H1 = False

    # H2: k is an integer
    try:
        H2 = isinstance(k, int) or (hasattr(k, 'is_integer') and k.is_integer)
        H2 = bool(H2)
    except Exception:
        H2 = False

    # neg_Q: The element a^k generates G if and only if gcd(k, n) = 1
    try:
        ak = a**k
        ak_generates_G = bool(G == PermutationGroup([ak]))
        gcd_eq_1 = bool(gcd(k, n) == 1)
        neg_Q = bool(ak_generates_G != gcd_eq_1)
    except Exception:
        neg_Q = False

    return [H1, H2, neg_Q]

