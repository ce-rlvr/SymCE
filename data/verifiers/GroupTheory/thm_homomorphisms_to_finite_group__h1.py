def conditions(witness) -> list[bool]:
    try:
        F, G, n = witness
    except Exception:
        return [False, False]
        
    # H_1: G is a finite group
    try:
        if not isinstance(G, PermutationGroup):
            h1 = False
        else:
            # In SymPy, PermutationGroup instances are finite groups
            h1 = True
    except Exception:
        h1 = False
        
    # ¬Q: The number of distinct group homomorphisms from F to G is NOT exactly |G|^n
    try:
        if not isinstance(F, PermutationGroup) or not isinstance(G, PermutationGroup):
            neg_q = False
        else:
            degree_F = F.degree
            degree_G = G.degree
            
            f_gens = F.generators
            try:
                g_elements = list(G.elements)
            except AttributeError:
                g_elements = list(G.generate())
                
            num_homomorphisms = 0
            
            # A map from generators of F to elements of G extends to a homomorphism
            # if and only if the subgroup of F x G generated by (f_i, g_i) has the same order as F.
            for images in itertools.product(g_elements, repeat=len(f_gens)):
                gens = []
                for f_gen, g_gen in zip(f_gens, images):
                    f_array = f_gen.array_form
                    if len(f_array) < degree_F:
                        f_array = f_array + list(range(len(f_array), degree_F))
                        
                    g_array = g_gen.array_form
                    if len(g_array) < degree_G:
                        g_array = g_array + list(range(len(g_array), degree_G))
                        
                    g_array_shifted = [x + degree_F for x in g_array]
                    
                    combined_array = f_array + g_array_shifted
                    gens.append(Permutation(combined_array))
                
                if not gens:
                    H_order = 1
                else:
                    H = PermutationGroup(gens)
                    H_order = H.order()
                    
                if H_order == F.order():
                    num_homomorphisms += 1
                    
            expected = (G.order()) ** n
            neg_q = bool(num_homomorphisms != expected)
    except Exception:
        neg_q = False
        
    return [h1, neg_q]

