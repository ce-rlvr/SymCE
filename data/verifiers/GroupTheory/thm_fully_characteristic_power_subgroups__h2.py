def get_all_endomorphisms(F):
    try:
        gens = F.generators
        elements = list(F.generate())
        
        id_perm = None
        if elements:
            id_perm = elements[0]**0
        else:
            id_perm = Permutation()
            
        endomorphisms = []
        
        for target in itertools.product(elements, repeat=len(gens)):
            mapping = dict(zip(gens, target))
            
            image = {id_perm: id_perm}
            queue = [id_perm]
            valid = True
            
            while queue:
                u = queue.pop(0)
                for g in gens:
                    v = u * g
                    img_v = image[u] * mapping[g]
                    if v in image:
                        if image[v] != img_v:
                            valid = False
                            break
                    else:
                        image[v] = img_v
                        queue.append(v)
                if not valid:
                    break
                    
            if valid and len(image) == len(elements):
                endomorphisms.append(image)
                
        return endomorphisms
    except Exception:
        return []

def conditions(witness):
    try:
        if isinstance(witness, tuple):
            if len(witness) == 2:
                F, n = witness
                H = None
            elif len(witness) == 3:
                F, n, H = witness
            else:
                return [False, False, False]
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H_1: F is a free group
    try:
        if type(F).__name__ == 'FreeGroup':
            h1 = True
        else:
            # For finite permutation groups, it is free iff it is the trivial group
            h1 = (hasattr(F, 'order') and F.order() == 1)
    except Exception:
        h1 = False

    # H_2: F^n is the subgroup of F generated by the set of all n-th powers of elements in F
    try:
        if H is not None:
            if type(F).__name__ == 'FreeGroup':
                h2 = False
            else:
                if hasattr(F, 'order') and F.order() > 120:
                    h2 = False
                else:
                    elements = list(F.generate())
                    nth_powers = list(set(g**n for g in elements))
                    H_expected = PermutationGroup(nth_powers)
                    h2 = (set(H.generate()) == set(H_expected.generate()))
        else:
            h2 = True
    except Exception:
        h2 = False

    # ¬Q: F^n is not a fully characteristic subgroup of F
    try:
        if type(F).__name__ == 'FreeGroup':
            # F^n is mathematically always fully characteristic in any group
            neg_q = False
        else:
            if hasattr(F, 'order') and F.order() > 120:
                neg_q = False
            else:
                if H is None:
                    elements = list(F.generate())
                    nth_powers = list(set(g**n for g in elements))
                    H_actual = PermutationGroup(nth_powers)
                else:
                    H_actual = H
                
                endos = get_all_endomorphisms(F)
                H_elements = set(H_actual.generate())
                
                is_fc = True
                for f in endos:
                    for h in H_elements:
                        if f[h] not in H_elements:
                            is_fc = False
                            break
                    if not is_fc:
                        break
                
                neg_q = not is_fc
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]