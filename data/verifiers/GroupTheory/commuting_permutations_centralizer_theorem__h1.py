def conditions(witness) -> list[bool]:
    # witness can be a tuple (n, sigma) or just sigma (where n is inferred from sigma.size)
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            n, sigma = witness
        else:
            sigma = witness
            n = sigma.size
    except Exception:
        return [False, False, False]
        
    # H1: S_n is the symmetric group on a set of size n
    try:
        if int(n) == n:
            n = int(n)
            h1 = (n >= 1)
        else:
            h1 = False
    except Exception:
        h1 = False
        
    # H2: sigma in S_n is an n-cycle
    try:
        if not isinstance(sigma, Permutation):
            h2 = False
        else:
            # Check if sigma is in S_n (moves only elements in {0, ..., n-1})
            if any(i >= n for i in sigma.support()):
                h2 = False
            elif any(i < 0 for i in sigma.support()):
                h2 = False
            else:
                if n == 1:
                    h2 = sigma.is_Identity
                else:
                    cycles = sigma.cyclic_form
                    h2 = (len(cycles) == 1 and len(cycles[0]) == n)
    except Exception:
        h2 = False
        
    # neg_Q: The centralizer of sigma in S_n is NOT exactly the cyclic subgroup <sigma>
    try:
        if not isinstance(sigma, Permutation) or not isinstance(n, int) or n < 1:
            neg_q = False
        else:
            cycles = sigma.cyclic_form
            moved = sum(len(c) for c in cycles)
            fixed = n - moved
            
            if fixed < 0:
                # sigma moves more elements than n, so it's not in S_n
                neg_q = False
            else:
                # Calculate the size of the centralizer of sigma in S_n
                cycle_lengths = [len(c) for c in cycles] + [1] * fixed
                counts = {}
                for length in cycle_lengths:
                    counts[length] = counts.get(length, 0) + 1
                
                cent_size = 1
                for length, count in counts.items():
                    cent_size *= (length ** count) * math.factorial(count)
                    
                sigma_order = sigma.order()
                
                # The centralizer is exactly <sigma> iff their sizes are equal
                neg_q = (cent_size != sigma_order)
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

