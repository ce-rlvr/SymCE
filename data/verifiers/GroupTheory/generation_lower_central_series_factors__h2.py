def conditions(witness) -> list[bool]:
    try:
        G, k, S = witness
    except Exception:
        return [False, False, False]

    # H_1: G is a nilpotent group
    try:
        h1_ok = bool(G.is_nilpotent)
    except Exception:
        h1_ok = False

    # H_2: k is a positive integer
    try:
        h2_ok = isinstance(k, int) and k > 0
    except Exception:
        h2_ok = False

    # ¬Q: The quotient group \gamma_k(G)/\gamma_{k+1}(G) is NOT generated by the images of the simple commutators
    try:
        if not h2_ok:
            neg_q_ok = False
        else:
            lcs = G.lower_central_series()
            
            def gamma(n):
                if n - 1 < len(lcs):
                    return lcs[n - 1]
                return lcs[-1]
                
            g_k = gamma(k)
            g_k_plus_1 = gamma(k + 1)
            
            def simple_commutators(S_list, weight):
                if weight == 1:
                    return S_list
                prev = simple_commutators(S_list, weight - 1)
                comms = []
                for c in prev:
                    for s in S_list:
                        # Commutator [c, s] = c^-1 * s^-1 * c * s
                        comms.append(~c * ~s * c * s)
                return comms
                
            comms = simple_commutators(list(S), k)
            
            # The subgroup generated by the commutators and \gamma_{k+1}(G)
            gens = list(comms) + list(g_k_plus_1.generators)
            if not gens:
                degree = getattr(G, "degree", 0)
                H = PermutationGroup([Permutation(degree - 1)]) if degree > 0 else PermutationGroup([Permutation()])
            else:
                H = PermutationGroup(gens)
                
            # Check if H is equal to \gamma_k(G)
            is_equal = H.is_subgroup(g_k) and g_k.is_subgroup(H)
            
            # The conclusion fails if they are NOT equal
            neg_q_ok = not is_equal
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, neg_q_ok]

