def conditions(witness) -> list[bool]:
    # Extract n and sigma from witness
    try:
        if isinstance(witness, tuple):
            n, sigma = witness
        else:
            sigma = witness
            n = sigma.size
    except Exception:
        return [False, False, False]

    # H_1: S_n is the symmetric group on n letters
    try:
        Sn = SymmetricGroup(n)
        h1 = True
    except Exception:
        h1 = False

    # H_2: \sigma \in S_n is an n-cycle
    try:
        in_Sn = sigma in Sn
        if n == 1:
            is_n_cycle = sigma.is_Identity
        else:
            cycles = [c for c in sigma.cyclic_form if len(c) > 1]
            is_n_cycle = (len(cycles) == 1 and len(cycles[0]) == n)
        h2 = bool(in_Sn and is_n_cycle)
    except Exception:
        h2 = False

    # ¬Q: The normalizer of the subgroup generated by \sigma in S_n does NOT have order n \phi(n)
    try:
        expected_order = n * totient(n)
        
        H = PermutationGroup([sigma])
        H_elements = list(H.generate())
        
        if n <= 6:
            normalizer_order = 0
            for tau in Sn.generate():
                # tau normalizes H iff tau * sigma * tau^-1 is in H
                if (tau * sigma * ~tau) in H_elements:
                    normalizer_order += 1
        else:
            # For n > 6, if sigma is an n-cycle, the normalizer order is mathematically always n * phi(n).
            # We use this to avoid timeout on large groups.
            if h2:
                normalizer_order = n * totient(n)
            else:
                normalizer_order = -1 # Invalid witness anyway
                
        neg_q = bool(normalizer_order != expected_order)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

