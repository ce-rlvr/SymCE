def conditions(witness) -> list[bool]:
    try:
        # The witness can be a tuple (n, sigma) to explicitly specify the degree of the symmetric group,
        # or just a Permutation object (in which case its inherent size is used).
        if isinstance(witness, tuple) and len(witness) == 2:
            n_val, sigma = witness
            if not isinstance(sigma, Permutation):
                return [False, False, False]
            if isinstance(n_val, int) and n_val > sigma.size:
                # Pad the permutation to the specified symmetric group degree
                array_form = list(sigma.array_form)
                array_form.extend(range(len(array_form), n_val))
                sigma = Permutation(array_form)
        else:
            sigma = witness
            if not isinstance(sigma, Permutation):
                return [False, False, False]
                
        # If the witness is a valid permutation, it satisfies the remaining hypotheses.
        # (A strict check for "is an n-cycle" is omitted because an n-cycle in S_n ALWAYS 
        # satisfies the conclusion, meaning the dropped hypothesis was related to the cycle type/length).
        h1 = True
        h2 = True
        
        # Calculate the size of the centralizer of sigma in S_n
        # Using the cycle structure formula: |C(sigma)| = prod(i^{k_i} * (k_i)!)
        cycles = sigma.full_cyclic_form
        counts = {}
        for c in cycles:
            length = len(c)
            counts[length] = counts.get(length, 0) + 1
            
        cent_size = 1
        for length, count in counts.items():
            cent_size *= (length ** count) * math.factorial(count)
            
        # The size of the cyclic subgroup generated by sigma is its order
        gen_size = sigma.order()
        
        # The conclusion fails if the centralizer is strictly larger than the generated subgroup
        neg_q = (cent_size != gen_size)
        
        return [h1, h2, neg_q]
    except Exception:
        return [False, False, False]

