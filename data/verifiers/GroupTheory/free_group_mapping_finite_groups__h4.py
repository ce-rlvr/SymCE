def conditions(witness) -> list[bool]:
    try:
        n_or_F, G = witness
        if isinstance(n_or_F, int):
            n = n_or_F
            h2_ok = True
        else:
            n = len(n_or_F.generators)
            h2_ok = isinstance(n_or_F, FreeGroup)
        h1_ok = isinstance(n, int) and n > 0
    except Exception:
        h1_ok = False
        h2_ok = False

    try:
        h3_ok = isinstance(G, PermutationGroup)
    except Exception:
        h3_ok = False

    try:
        if not (h1_ok and h3_ok):
            neg_q = False
        else:
            elements = list(G.generate())
            order_G = G.order()
            can_generate = False
            for gens in itertools.combinations_with_replacement(elements, n):
                if PermutationGroup(*gens).order() == order_G:
                    can_generate = True
                    break
            neg_q = not can_generate
    except Exception:
        neg_q = False

    return [h1_ok, h2_ok, h3_ok, neg_q]

