def conditions(witness):
    try:
        G, S, H, T = witness
        T = list(T)
        S = list(S)
    except Exception:
        return [False, False, False, False]

    # H1: H is a subgroup of G
    try:
        h1 = bool(H.is_subgroup(G))
    except Exception:
        h1 = False

    # H2: T is a right transversal for H in G
    try:
        h2 = True
        if not all(t in G for t in T):
            h2 = False
        elif len(T) * H.order() != G.order():
            h2 = False
        else:
            for t1, t2 in itertools.combinations(T, 2):
                if t1 * t2**-1 in H:
                    h2 = False
                    break
        h2 = bool(h2)
    except Exception:
        h2 = False

    # H3: The representative of the coset H in T is the identity element of G
    try:
        id_perm = Permutation()
        reps_in_H = [t for t in T if t in H]
        h3 = bool(len(reps_in_H) == 1 and reps_in_H[0] == id_perm)
    except Exception:
        h3 = False

    # neg_Q: H is not generated by the set { t * s * (\overline{t * s})^{-1} | t \in T, s \in S }
    try:
        gens = []
        t_bar_found = True
        for t in T:
            for s in S:
                x = t * s
                t_bar = None
                for cand in T:
                    if x * cand**-1 in H:
                        t_bar = cand
                        break
                if t_bar is None:
                    t_bar_found = False
                    break
                gens.append(t * s * t_bar**-1)
            if not t_bar_found:
                break
        
        if not t_bar_found:
            neg_q = True
        else:
            if not gens:
                gens = [Permutation()]
            K = PermutationGroup(gens)
            neg_q = bool(not (K.is_subgroup(H) and K.order() == H.order()))
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

