def rank_at_least_2(G):
    """
    Checks if the rank (minimum number of generators) of the group is at least 2.
    """
    if hasattr(G, 'rank'):
        return G.rank >= 2
    
    if isinstance(G, PermutationGroup):
        # Non-abelian groups cannot be generated by a single element (rank >= 2)
        if not getattr(G, 'is_abelian', True):
            return True
        # For abelian groups, check if it is cyclic
        try:
            order = G.order()
            # If any element has order equal to the group order, it is cyclic (rank 1)
            for g in G.elements:
                if g.order() == order:
                    return False
            # If no such element exists, it requires >= 2 generators
            return True
        except Exception:
            pass
            
    return False

def is_amenable(G):
    """
    Checks if the group is amenable.
    Finite groups, abelian groups, and solvable groups are amenable.
    Free groups of rank >= 2 are not amenable.
    """
    # All finite groups are amenable
    if isinstance(G, PermutationGroup):
        return True
    
    # Abelian and solvable groups are amenable
    if getattr(G, 'is_abelian', False):
        return True
    if getattr(G, 'is_solvable', False):
        return True
        
    # Free groups are amenable iff their rank is <= 1
    if type(G).__name__ == 'FreeGroup':
        return getattr(G, 'rank', 0) <= 1
        
    return False

def conditions(witness) -> list[bool]:
    try:
        h1 = bool(rank_at_least_2(witness))
    except Exception:
        h1 = False
        
    try:
        # The conclusion is "F is not an amenable group"
        # So the negated conclusion is "F IS an amenable group"
        neg_q = bool(is_amenable(witness))
    except Exception:
        neg_q = False
        
    return [h1, neg_q]

