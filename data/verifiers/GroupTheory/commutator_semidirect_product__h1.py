def is_subgroup(sub, supergroup):
    try:
        for g in sub.generators:
            if g not in supergroup:
                return False
        return True
    except Exception:
        return False

def is_normal(sub, supergroup):
    try:
        if not is_subgroup(sub, supergroup):
            return False
        for g in supergroup.generators:
            for n in sub.generators:
                if (g * n * (g**-1)) not in sub:
                    return False
        return True
    except Exception:
        return False

def conditions(witness):
    try:
        G, N, H = witness
    except Exception:
        return [False, False]
        
    # H1: G is the internal semidirect product of a normal subgroup N and a subgroup H
    try:
        h1_ok = False
        if is_subgroup(N, G) and is_subgroup(H, G):
            if is_normal(N, G):
                n_elements = set(N.generate())
                h_elements = set(H.generate())
                if len(n_elements.intersection(h_elements)) == 1:
                    if G.order() == N.order() * H.order():
                        h1_ok = True
    except Exception:
        h1_ok = False
        
    # Conclusion: G' == <N', H', [N, H]>
    try:
        neg_q_ok = False
        G_prime = G.derived_subgroup()
        N_prime = N.derived_subgroup()
        H_prime = H.derived_subgroup()
        
        gens = list(N_prime.generators) + list(H_prime.generators)
        for n in N.generate():
            for h in H.generate():
                gens.append(n * h * (n**-1) * (h**-1))
                
        if not gens:
            if G_prime.order() != 1:
                neg_q_ok = True
            else:
                neg_q_ok = False
        else:
            K = PermutationGroup(gens)
            if G_prime.order() != K.order() or not is_subgroup(K, G_prime) or not is_subgroup(G_prime, K):
                neg_q_ok = True
            else:
                neg_q_ok = False
    except Exception:
        neg_q_ok = False
        
    return [h1_ok, neg_q_ok]

