def check_schreier_transversal(F, H, max_steps=500):
    if not H:
        return False
        
    id_el = F.identity
    gens = list(F.generators)
    letters = gens + [g**-1 for g in gens]
    
    def get_shortest_uncovered(covered):
        queue = [id_el]
        seen = {id_el}
        if id_el not in covered:
            return id_el
        head = 0
        while head < len(queue):
            curr = queue[head]
            head += 1
            for letter in letters:
                nxt = curr * letter
                if nxt not in seen:
                    if nxt not in covered:
                        return nxt
                    seen.add(nxt)
                    queue.append(nxt)
        return None

    def get_prefixes(w):
        prefixes = [w]
        curr = w
        while len(curr) > 0:
            for g in letters:
                if len(curr * g) < len(curr):
                    curr = curr * g
                    prefixes.append(curr)
                    break
        return prefixes[::-1]

    step_count = [0]
    
    def search(T, covered):
        step_count[0] += 1
        if step_count[0] > max_steps:
            return True
            
        w = get_shortest_uncovered(covered)
        if w is None:
            return True
            
        for h in H:
            t = h**-1 * w
            prefixes = get_prefixes(t)
            
            valid = True
            new_T = set(T)
            new_covered = set(covered)
            
            for p in prefixes:
                if p not in new_T:
                    Hp = {h_el * p for h_el in H}
                    if not Hp.isdisjoint(new_covered):
                        valid = False
                        break
                    new_T.add(p)
                    new_covered.update(Hp)
            
            if valid:
                if search(new_T, new_covered):
                    return True
                    
        return False

    return search({id_el}, set(H))

def conditions(witness):
    try:
        if len(witness) != 3:
            return [False, False]
        F, X, H = witness
    except Exception:
        return [False, False]
        
    try:
        if type(F).__name__ != 'FreeGroup':
            h1 = False
        else:
            h1 = (set(F.generators) == set(X))
    except Exception:
        h1 = False
        
    try:
        if type(F).__name__ != 'FreeGroup':
            neg_q = False
        else:
            if not isinstance(H, (list, set, tuple)):
                neg_q = False
            else:
                H_set = set(H)
                if not H_set:
                    neg_q = True
                else:
                    valid_H = True
                    for h in H_set:
                        if type(h).__name__ != 'FreeGroupElement' or h.group != F:
                            valid_H = False
                            break
                    if not valid_H:
                        neg_q = False
                    else:
                        neg_q = not check_schreier_transversal(F, H_set)
    except Exception:
        neg_q = False
        
    return [h1, neg_q]

