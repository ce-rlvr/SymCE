def conditions(witness) -> list[bool]:
    # Extract witness components
    try:
        if isinstance(witness, dict):
            n = witness.get('n')
            G = witness.get('G')
            P = witness.get('P')
        else:
            n, G, P = witness
    except Exception:
        return [False, False, False]

    # H_1: n is an odd integer greater than 1
    try:
        h1 = (int(n) == n) and (n % 2 == 1) and (n > 1)
    except Exception:
        h1 = False

    # H_2: P is a Sylow 2-subgroup of G
    try:
        is_sub = True
        for g in P.generators:
            if hasattr(G, 'contains'):
                if not G.contains(g):
                    is_sub = False
                    break
            else:
                if g not in G:
                    is_sub = False
                    break
        
        if is_sub:
            g_order = G.order()
            p_order = P.order()
            k = 0
            while g_order % (2**(k+1)) == 0:
                k += 1
            h2 = (p_order == 2**k)
        else:
            h2 = False
    except Exception:
        h2 = False

    # ¬Q: P does not have order 2 (or is not generated by a single reflection element)
    try:
        neg_q = (P.order() != 2)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

