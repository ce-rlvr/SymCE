def conditions(witness) -> list[bool]:
    try:
        G, H, S, f, g = witness
    except Exception:
        return [False, False, False, False]
    
    def evaluate(func, x):
        if isinstance(func, dict):
            return func[x]
        return func(x)

    # H_1: G and H are groups
    try:
        h1 = isinstance(G, PermutationGroup) and isinstance(H, PermutationGroup)
        if h1:
            # Implicitly, f and g must be well-defined functions from G to H
            for x in G.elements:
                if evaluate(f, x) not in H or evaluate(g, x) not in H:
                    h1 = False
                    break
    except Exception:
        h1 = False

    # H_2: S is a subset of G such that the subgroup generated by S is G
    try:
        S_list = list(S)
        if not all(s in G for s in S_list):
            h2 = False
        else:
            if not S_list:
                gen_G = PermutationGroup([G.identity])
            else:
                gen_G = PermutationGroup(S_list)
            h2 = gen_G.order() == G.order()
    except Exception:
        h2 = False

    # H_3: For every s \in S, f(s) = g(s)
    try:
        h3 = all(evaluate(f, s) == evaluate(g, s) for s in S_list)
    except Exception:
        h3 = False

    # neg_Q: f(x) != g(x) for some x \in G
    try:
        neg_q = any(evaluate(f, x) != evaluate(g, x) for x in G.elements)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

