def direct_product(G, H):
    deg_G = G.degree
    deg_H = H.degree
    gens = []
    for g in G.generators:
        arr = list(g.array_form)
        if len(arr) < deg_G:
            arr.extend(range(len(arr), deg_G))
        arr.extend([deg_G + i for i in range(deg_H)])
        gens.append(Permutation(arr))
    for h in H.generators:
        arr = [i for i in range(deg_G)]
        h_arr = list(h.array_form)
        if len(h_arr) < deg_H:
            h_arr.extend(range(len(h_arr), deg_H))
        arr.extend([deg_G + x for x in h_arr])
        gens.append(Permutation(arr))
    if not gens:
        if deg_G + deg_H == 0:
            return PermutationGroup([Permutation()])
        return PermutationGroup([Permutation(deg_G + deg_H - 1)])
    return PermutationGroup(gens)

def is_generated_by_involutions(grp):
    try:
        involutions = [g for g in grp.generate() if g.order() == 2]
        if not involutions:
            return grp.order() == 1
        subgrp = PermutationGroup(involutions)
        return subgrp.order() == grp.order()
    except Exception:
        return False

