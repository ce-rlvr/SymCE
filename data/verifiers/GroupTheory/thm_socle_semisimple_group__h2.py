def conditions(witness):
    try:
        h1_ok = isinstance(witness, PermutationGroup)
    except Exception:
        h1_ok = False
        
    try:
        if not h1_ok:
            neg_q_ok = False
        else:
            if witness.order() == 1:
                socle_eq_G = True
            else:
                elements = list(witness.generate())
                id_elem = elements[0]**0
                
                # Find the normal closure for each non-identity element.
                # Every minimal normal subgroup is the normal closure of any of its non-identity elements.
                normal_closures = []
                for x in elements:
                    if x == id_elem:
                        continue
                    
                    conjugates = set()
                    for g in elements:
                        conjugates.add(g * x * ~g)
                    
                    Nx = PermutationGroup(list(conjugates))
                    Nx_elems = frozenset(Nx.generate())
                    
                    if Nx_elems not in normal_closures:
                        normal_closures.append(Nx_elems)
                        
                # Filter to find minimal normal subgroups (minimal elements by inclusion)
                minimal_normal = []
                for N in normal_closures:
                    is_minimal = True
                    for M in normal_closures:
                        if M != N and M.issubset(N):
                            is_minimal = False
                            break
                    if is_minimal:
                        minimal_normal.append(N)
                        
                # The socle is generated by the union of all minimal normal subgroups
                socle_gens = set()
                for N in minimal_normal:
                    socle_gens.update(N)
                    
                socle_group = PermutationGroup(list(socle_gens))
                socle_eq_G = (socle_group.order() == witness.order())
                
            neg_q_ok = not socle_eq_G
    except Exception:
        neg_q_ok = False
        
    return [h1_ok, neg_q_ok]

