def conditions(witness):
    try:
        N, H, phi = witness
    except Exception:
        return [False, False, False]

    def get_phi(h, n, phi_obj):
        if callable(phi_obj):
            return phi_obj(h, n)
        else:
            return phi_obj[h][n]

    def invert(g):
        try:
            return ~g
        except Exception:
            return g**-1

    try:
        N_elems = list(N.elements)
        H_elems = list(H.elements)
        if not N_elems or not H_elems:
            return [False, False, False]
        id_N = next(n for n in N_elems if all(n * x == x for x in N_elems))
        id_H = next(h for h in H_elems if all(h * x == x for x in H_elems))
    except Exception:
        return [False, False, False]

    # H1: H is an abelian group
    try:
        h1_ok = bool(H.is_abelian)
    except Exception:
        h1_ok = False

    # H2: phi is a homomorphism from H to Aut(N)
    try:
        h2_ok = True
        for h in H_elems:
            image = set()
            for n in N_elems:
                pn = get_phi(h, n, phi)
                if pn not in N_elems:
                    h2_ok = False
                    break
                image.add(pn)
            if not h2_ok: break
            if len(image) != len(N_elems):
                h2_ok = False
                break
            
            for n1 in N_elems:
                for n2 in N_elems:
                    if get_phi(h, n1 * n2, phi) != get_phi(h, n1, phi) * get_phi(h, n2, phi):
                        h2_ok = False
                        break
                if not h2_ok: break
            if not h2_ok: break
            
        if h2_ok:
            for h1 in H_elems:
                for h2 in H_elems:
                    h12 = h1 * h2
                    for n in N_elems:
                        if get_phi(h12, n, phi) != get_phi(h1, get_phi(h2, n, phi), phi):
                            h2_ok = False
                            break
                    if not h2_ok: break
                if not h2_ok: break
    except Exception:
        h2_ok = False

    # neg_Q: Derived subgroup is NOT exactly the subgroup generated by (n^-1 phi_h(n), 1_H)
    try:
        G_elems = [(n, h) for n in N_elems for h in H_elems]

        def mul(x, y):
            n1, h1 = x
            n2, h2 = y
            return (n1 * get_phi(h1, n2, phi), h1 * h2)

        def inv(x):
            n, h = x
            h_inv = invert(h)
            n_inv = invert(n)
            return (get_phi(h_inv, n_inv, phi), h_inv)

        def commutator(x, y):
            return mul(inv(x), mul(inv(y), mul(x, y)))

        commutators = set()
        for x in G_elems:
            for y in G_elems:
                commutators.add(commutator(x, y))

        S = set()
        for n in N_elems:
            for h in H_elems:
                val = (invert(n) * get_phi(h, n, phi), id_H)
                S.add(val)

        def get_closure(generators):
            closure = set(generators)
            closure.add((id_N, id_H))
            added = True
            while added:
                added = False
                new_elems = set()
                for x in closure:
                    for y in closure:
                        xy = mul(x, y)
                        if xy not in closure and xy not in new_elems:
                            new_elems.add(xy)
                if new_elems:
                    closure.update(new_elems)
                    added = True
            return closure

        derived_subgroup = get_closure(commutators)
        S_subgroup = get_closure(S)

        neg_q = (derived_subgroup != S_subgroup)
    except Exception:
        neg_q = False

    return [h1_ok, h2_ok, neg_q]

