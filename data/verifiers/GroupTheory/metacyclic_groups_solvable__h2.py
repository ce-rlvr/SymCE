def conditions(witness) -> list[bool]:
    try:
        h1 = isinstance(witness, PermutationGroup)
    except Exception:
        h1 = False

    try:
        neg_q = not witness.is_solvable
    except Exception:
        neg_q = False

    return [h1, neg_q]

