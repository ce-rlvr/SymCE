def conditions(witness):
    try:
        # H1: n is an integer >= 1
        h1 = isinstance(witness, (int, sympy.Integer)) and int(witness) == witness and witness >= 1
    except Exception:
        h1 = False

    try:
        if not h1:
            neg_q = False
        else:
            n = int(witness)
            if n <= 1:
                an_order = 1
            else:
                an_order = math.factorial(n) // 2
                
            S = []
            for combo in itertools.combinations(range(n), 4):
                a, b, c, d = combo
                
                # (a, b)(c, d)
                arr1 = list(range(n))
                arr1[a], arr1[b] = b, a
                arr1[c], arr1[d] = d, c
                S.append(Permutation(arr1))
                
                # (a, c)(b, d)
                arr2 = list(range(n))
                arr2[a], arr2[c] = c, a
                arr2[b], arr2[d] = d, b
                S.append(Permutation(arr2))
                
                # (a, d)(b, c)
                arr3 = list(range(n))
                arr3[a], arr3[d] = d, a
                arr3[b], arr3[c] = c, b
                S.append(Permutation(arr3))
                
            if not S:
                generates_An = (an_order == 1)
            else:
                H = PermutationGroup(*S)
                generates_An = (H.order() == an_order)
                
            neg_q = not generates_An
    except Exception:
        neg_q = False

    return [h1, neg_q]

