def conditions(witness) -> list[bool]:
    try:
        # Witness should be a tuple: (G, n, action_gens)
        # where G is a PermutationGroup, n is the size of set X,
        # and action_gens is a list of Permutations defining the action of G.generators on X.
        G, n, action_gens = witness
    except Exception:
        return [False] * 5

    # H_1: G is a finite group (and a valid action homomorphism is provided)
    try:
        if not isinstance(G, PermutationGroup):
            h1 = False
        elif not isinstance(action_gens, (list, tuple)):
            h1 = False
        elif len(G.generators) != len(action_gens):
            h1 = False
        else:
            valid_types = True
            for p in action_gens:
                if not isinstance(p, Permutation):
                    valid_types = False
                    break
            if not valid_types:
                h1 = False
            else:
                id_G = G.generators[0] ** 0 if G.generators else Permutation()
                id_Sn = Permutation([i for i in range(n)]) if n > 0 else Permutation()
                mapping = {id_G: id_Sn}
                queue = [id_G]
                valid = True
                count = 0
                while queue:
                    count += 1
                    if count > 5000:  # Safeguard against extremely large groups
                        valid = False
                        break
                    curr = queue.pop(0)
                    curr_p = mapping[curr]
                    for i, gen in enumerate(G.generators):
                        nxt = curr * gen
                        nxt_p = curr_p * action_gens[i]
                        if nxt in mapping:
                            # Compare permutations on the domain 0..n-1
                            for pt in range(n):
                                val_nxt = mapping[nxt](pt) if pt < mapping[nxt].size else pt
                                val_nxt_p = nxt_p(pt) if pt < nxt_p.size else pt
                                if val_nxt != val_nxt_p:
                                    valid = False
                                    break
                            if not valid:
                                break
                        else:
                            mapping[nxt] = nxt_p
                            queue.append(nxt)
                    if not valid:
                        break
                h1 = valid
    except Exception:
        h1 = False

    # H_2: G is a semisimple group
    # A finite group is semisimple iff it has no non-trivial abelian normal subgroups.
    # Equivalently, for every non-identity element g, its normal closure is non-abelian.
    # The normal closure of g is generated by its conjugacy class.
    try:
        if not h1:
            h2 = False
        else:
            elements = list(G.generate())
            is_semi = True
            for g in elements:
                if g.is_Identity:
                    continue
                
                # Find the conjugacy class of g
                conj_class = set([g])
                q = [g]
                while q:
                    curr = q.pop(0)
                    for gen in G.generators:
                        c1 = gen * curr * (~gen)
                        if c1 not in conj_class:
                            conj_class.add(c1)
                            q.append(c1)
                        c2 = (~gen) * curr * gen
                        if c2 not in conj_class:
                            conj_class.add(c2)
                            q.append(c2)
                
                # Check if the subgroup generated by the conjugacy class is abelian
                # (i.e., check if all elements in the conjugacy class commute with each other)
                conj_list = list(conj_class)
                is_abelian = True
                for i in range(len(conj_list)):
                    for j in range(i + 1, len(conj_list)):
                        if conj_list[i] * conj_list[j] != conj_list[j] * conj_list[i]:
                            is_abelian = False
                            break
                    if not is_abelian:
                        break
                
                if is_abelian:
                    is_semi = False
                    break
            h2 = is_semi
    except Exception:
        h2 = False

    # H_3: X is a set
    try:
        h3 = isinstance(n, int) and n >= 0
    except Exception:
        h3 = False

    # H_4: The cardinality of X is less than or equal to 4
    try:
        h4 = h3 and n <= 4
    except Exception:
        h4 = False

    # ¬Q: The action of G on X is not the trivial action
    try:
        if not h1:
            neg_q = False
        else:
            is_trivial = True
            for p in action_gens:
                for i in range(n):
                    val = p(i) if i < p.size else i
                    if val != i:
                        is_trivial = False
                        break
                if not is_trivial:
                    break
            neg_q = not is_trivial
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]

