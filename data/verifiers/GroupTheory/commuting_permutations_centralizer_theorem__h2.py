def conditions(witness) -> list[bool]:
    # Extract n and sigma from the witness
    try:
        if isinstance(witness, dict):
            n = witness.get('n')
            sigma = witness.get('sigma')
        elif isinstance(witness, (list, tuple)) and len(witness) == 2:
            n, sigma = witness
        else:
            sigma = witness
            n = getattr(sigma, 'size', None)
    except Exception:
        n, sigma = None, None

    # H_1: n is an integer with n >= 1
    try:
        n_int = int(n)
        h1 = (n_int == n) and (n_int >= 1)
    except Exception:
        h1 = False

    # H_2: sigma \in S_n is an n-cycle
    try:
        if not isinstance(sigma, Permutation):
            h2 = False
        else:
            n_int = int(n)
            # Check if sigma is in S_n (it must not move any element >= n)
            if sigma.size > n_int and any(sigma(i) != i for i in range(n_int, sigma.size)):
                h2 = False
            else:
                cycles = sigma.cyclic_form
                if n_int == 1:
                    # In S_1, the only element is the identity, which is a 1-cycle
                    h2 = len(cycles) == 0 or (len(cycles) == 1 and len(cycles[0]) == 1)
                else:
                    # An n-cycle has exactly one cycle of length n (singletons are omitted in cyclic_form)
                    h2 = len(cycles) == 1 and len(cycles[0]) == n_int
    except Exception:
        h2 = False

    # neg_Q: The centralizer of sigma in S_n is NOT exactly the cyclic subgroup <sigma> generated by sigma
    try:
        n_int = int(n)
        if not (n_int >= 1 and isinstance(sigma, Permutation)):
            neg_q = False
        elif sigma.size > n_int and any(sigma(i) != i for i in range(n_int, sigma.size)):
            neg_q = False
        else:
            # Normalize sigma to be exactly of size n_int for accurate equality comparisons
            sigma_norm = Permutation([sigma(i) for i in range(n_int)])
            Sn = SymmetricGroup(n_int)
            
            # Compute the centralizer of sigma in S_n
            C = Sn.centralizer(sigma_norm)
            centralizer_elements = set(C.generate())
            
            # Compute the cyclic subgroup generated by sigma
            cyclic_subgroup_elements = set()
            current = Permutation([], size=n_int)  # Identity permutation of size n_int
            while current not in cyclic_subgroup_elements:
                cyclic_subgroup_elements.add(current)
                current = current * sigma_norm
                
            # The conclusion fails if the centralizer is not equal to the cyclic subgroup
            neg_q = centralizer_elements != cyclic_subgroup_elements
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

