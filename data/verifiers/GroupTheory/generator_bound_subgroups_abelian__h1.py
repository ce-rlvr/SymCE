def conditions(witness):
    try:
        if len(witness) != 3:
            return [False, False, False]
        G, H, n = witness
        n = int(n)
    except Exception:
        return [False, False, False]
        
    # H_1: G can be generated by n elements
    try:
        if len(G.generators) <= n:
            h1 = True
        else:
            try:
                g_order = G.order()
            except TypeError:
                g_order = G.order
            except Exception:
                g_order = float('inf')
                
            if g_order > 100:
                h1 = False
            else:
                elements = list(G.generate())
                h1 = False
                if n >= len(elements):
                    h1 = True
                elif n == 0:
                    h1 = (len(elements) == 1)
                else:
                    for gens in itertools.combinations(elements, n):
                        try:
                            subG = PermutationGroup(*gens)
                            try:
                                sub_order = subG.order()
                            except TypeError:
                                sub_order = subG.order
                            except Exception:
                                sub_order = len(list(subG.generate()))
                                
                            if sub_order == len(elements):
                                h1 = True
                                break
                        except Exception:
                            pass
    except Exception:
        h1 = False
        
    # H_2: H is a subgroup of G
    try:
        h2 = H.is_subgroup(G)
        if not h2:
            h2 = True
            for g in H.generators:
                g_padded = g
                if hasattr(g, 'size') and hasattr(G, 'degree'):
                    if g.size < G.degree:
                        g_padded = Permutation(g.array_form + list(range(g.size, G.degree)))
                if g_padded not in G:
                    h2 = False
                    break
    except Exception:
        h2 = False
        
    # neg_Q: H cannot be generated by at most n elements
    try:
        try:
            h_order = H.order()
        except TypeError:
            h_order = H.order
        except Exception:
            h_order = float('inf')
            
        if h_order > 100:
            neg_q = False
        else:
            elements = list(H.generate())
            if n >= len(elements):
                neg_q = False
            elif n == 0:
                neg_q = (len(elements) > 1)
            else:
                neg_q = True
                for gens in itertools.combinations(elements, n):
                    try:
                        subG = PermutationGroup(*gens)
                        try:
                            sub_order = subG.order()
                        except TypeError:
                            sub_order = subG.order
                        except Exception:
                            sub_order = len(list(subG.generate()))
                            
                        if sub_order == len(elements):
                            neg_q = False
                            break
                    except Exception:
                        pass
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

