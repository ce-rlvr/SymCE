def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, dict):
            n = witness.get('n')
            G = witness.get('G')
        elif isinstance(witness, tuple) and len(witness) == 2:
            n, G = witness
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H_1: Let n be an integer strictly greater than 1.
    try:
        h1 = bool((isinstance(n, int) or isinstance(n, sympy.Integer)) and n > 1)
    except Exception:
        h1 = False

    # H_2: Let G be a group defined by the presentation <a, b | R>.
    # This implies G can be generated by at most 2 elements.
    try:
        h2 = bool(hasattr(G, 'generators') and len(G.generators) <= 2)
    except Exception:
        h2 = False

    # ¬Q: The group G is NOT isomorphic to the dicyclic group Dic_n of order 4n.
    try:
        if not h1:
            return [h1, h2, False]
            
        try:
            if G.order() != 4 * n:
                return [h1, h2, True]
        except Exception:
            # If order computation fails, it's likely infinite or not Dic_n
            return [h1, h2, True]
            
        try:
            ab = G.abelian_invariants()
            expected_ab = [2, 2] if n % 2 == 0 else [4]
            if sorted(ab) != sorted(expected_ab):
                return [h1, h2, True]
        except Exception:
            pass
            
        try:
            if hasattr(G, 'elements'):
                elements = list(G.elements)
                order_2_count = sum(1 for g in elements if g.order() == 2)
                if order_2_count != 1:
                    return [h1, h2, True]
        except Exception:
            pass
            
        # If it has the correct abelian invariants, correct order, and 1 element of order 2,
        # it is isomorphic to Dic_n (the conclusion holds, so ¬Q is False).
        neg_q = False
        
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

