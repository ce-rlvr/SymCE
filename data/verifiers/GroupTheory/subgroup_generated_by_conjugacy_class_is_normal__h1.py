def conditions(witness):
    try:
        G, S = witness
    except Exception:
        return [False, False]
    
    # H_1: S is a conjugacy class of G
    try:
        if not isinstance(G, PermutationGroup):
            h1 = False
        else:
            S_list = list(S)
            if not S_list:
                h1 = False
            else:
                S_set = set(S_list)
                x = S_list[0]
                if x not in G:
                    h1 = False
                else:
                    conj_class = {x}
                    queue = [x]
                    gens = G.generators
                    while queue:
                        curr = queue.pop(0)
                        for g in gens:
                            nxt = g * curr * ~g
                            if nxt not in conj_class:
                                conj_class.add(nxt)
                                queue.append(nxt)
                            nxt2 = ~g * curr * g
                            if nxt2 not in conj_class:
                                conj_class.add(nxt2)
                                queue.append(nxt2)
                    h1 = (S_set == conj_class)
    except Exception:
        h1 = False

    # neg_Q: The subgroup ⟨S⟩ generated by S is not a normal subgroup of G
    try:
        if not isinstance(G, PermutationGroup):
            neg_q = False
        else:
            H = PermutationGroup(list(S))
            is_subgroup = True
            for gen in H.generators:
                if gen not in G:
                    is_subgroup = False
                    break
            
            is_normal = True
            if is_subgroup:
                for g in G.generators:
                    for h in H.generators:
                        if (g * h * ~g) not in H:
                            is_normal = False
                            break
                    if not is_normal:
                        break
            else:
                is_normal = False
                
            neg_q = not is_normal
    except Exception:
        neg_q = False

    return [h1, neg_q]

