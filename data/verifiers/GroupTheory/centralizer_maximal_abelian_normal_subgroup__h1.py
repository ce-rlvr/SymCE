def is_maximal_abelian_normal(G, A):
    # 1. Check if A is a subgroup of G
    for gen in A.generators:
        if gen not in G:
            return False
            
    # 2. Check if A is abelian
    if not A.is_abelian:
        return False
        
    # 3. Check if A is normal in G
    for g in G.generators:
        for a in A.generators:
            if (g * a * ~g) not in A:
                return False
                
    # 4. Check if A is maximal among abelian normal subgroups
    # If there is a strictly larger abelian normal subgroup N, it must contain some x in G \ A.
    # The normal closure of x in G, combined with A, would generate an abelian normal subgroup.
    for x in G.generate():
        if x in A:
            continue
        
        # Find the conjugacy class of x in G
        C_x = set([x])
        queue = [x]
        while queue:
            curr = queue.pop(0)
            for g in G.generators:
                conj = g * curr * ~g
                if conj not in C_x:
                    C_x.add(conj)
                    queue.append(conj)
                    
        # Check if C_x commutes with A.generators
        commutes_with_A = True
        for c in C_x:
            for a in A.generators:
                if c * a != a * c:
                    commutes_with_A = False
                    break
            if not commutes_with_A:
                break
        if not commutes_with_A:
            continue
            
        # Check if C_x commutes with itself
        commutes_with_self = True
        for c1 in C_x:
            for c2 in C_x:
                if c1 * c2 != c2 * c1:
                    commutes_with_self = False
                    break
            if not commutes_with_self:
                break
                
        # If C_x commutes with A and with itself, the subgroup generated by A and C_x is abelian.
        # Since it is also normal and strictly contains A, A is not maximal.
        if commutes_with_self:
            return False
            
    return True

def centralizer_not_equal(G, A):
    # Since A is abelian, A <= C_G(A). 
    # C_G(A) != A iff there is some g in G \ A that commutes with all generators of A.
    for g in G.generate():
        if g not in A:
            commutes = True
            for a in A.generators:
                if g * a != a * g:
                    commutes = False
                    break
            if commutes:
                return True
    return False

def conditions(witness):
    try:
        G, A = witness
    except Exception:
        return [False, False]
        
    try:
        if not hasattr(A, 'is_subgroup'):
            if isinstance(A, (list, tuple, set)):
                A = PermutationGroup(*A)
            else:
                A = PermutationGroup(A)
    except Exception:
        pass

    try:
        h1_ok = is_maximal_abelian_normal(G, A)
    except Exception:
        h1_ok = False
        
    try:
        neg_q_ok = centralizer_not_equal(G, A)
    except Exception:
        neg_q_ok = False
        
    return [h1_ok, neg_q_ok]

