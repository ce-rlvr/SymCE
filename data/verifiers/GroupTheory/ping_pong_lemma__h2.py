def get_order(g):
    if hasattr(g, 'order'):
        try:
            return g.order()
        except Exception:
            pass
    try:
        id_elem = g ** 0
        curr = g
        for i in range(1, 1000):
            if curr == id_elem:
                return i
            curr = curr * g
    except Exception:
        pass
    return float('inf')

def apply_action(g, x):
    try:
        return g(x)
    except Exception:
        pass
    try:
        return g * x
    except Exception:
        pass
    return x

def conditions(witness):
    try:
        G, X, X1, X2, a, b = witness
    except Exception:
        return [False] * (N_HYP + 1)

    # H_1: G is a group acting on a set X
    try:
        h1 = hasattr(G, 'contains') and isinstance(X, (set, list, tuple))
    except Exception:
        h1 = False

    # H_2: a and b are elements of G
    try:
        h2 = bool(G.contains(a) and G.contains(b))
    except Exception:
        h2 = False

    # H_3: For all non-zero integers n, the image of X2 under a^n is a subset of X1
    try:
        X1_set = set(X1)
        X2_set = set(X2)
        order_a = get_order(a)
        if order_a == float('inf'):
            h3 = False
        else:
            h3 = True
            for i in range(1, order_a + 1):
                p = a ** i
                image = {apply_action(p, x) for x in X2_set}
                if not image.issubset(X1_set):
                    h3 = False
                    break
    except Exception:
        h3 = False

    # H_4: For all non-zero integers n, the image of X1 under b^n is a subset of X2
    try:
        X1_set = set(X1)
        X2_set = set(X2)
        order_b = get_order(b)
        if order_b == float('inf'):
            h4 = False
        else:
            h4 = True
            for i in range(1, order_b + 1):
                p = b ** i
                image = {apply_action(p, x) for x in X1_set}
                if not image.issubset(X2_set):
                    h4 = False
                    break
    except Exception:
        h4 = False

    # ¬Q: The subgroup of G generated by {a, b} is not isomorphic to the free group of rank 2
    try:
        if isinstance(G, PermutationGroup):
            neg_q = True
        elif get_order(a) < float('inf') or get_order(b) < float('inf'):
            neg_q = True
        elif a * b == b * a:
            neg_q = True
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]