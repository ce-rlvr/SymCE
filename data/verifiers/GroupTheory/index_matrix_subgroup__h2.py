def get_vol(M):
    n, m = M.shape
    if m < n:
        return 0
    vol = 0
    for cols in itertools.combinations(range(m), n):
        d = M[:, cols].det()
        if sympy.sympify(d).is_integer != True:
            raise ValueError("Matrix must have integer entries")
        vol = math.gcd(vol, int(abs(d)))
        if vol == 1:
            break
    return vol

def conditions(witness):
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            G, A = witness
        elif isinstance(witness, dict):
            G = witness.get('G')
            A = witness.get('A')
        else:
            return [False] * 5
            
        if not isinstance(A, Matrix):
            A = Matrix(A)
        if not isinstance(G, Matrix):
            G = Matrix(G)
    except Exception:
        return [False] * 5

    try:
        n = A.shape[0]
        h1_ok = bool((A.shape[0] == A.shape[1]) and (n >= 1))
    except Exception:
        h1_ok = False

    try:
        h2_ok = bool(h1_ok and all(sympy.sympify(x).is_integer == True for x in A))
    except Exception:
        h2_ok = False

    try:
        det_A = int(A.det())
        h3_ok = bool(det_A != 0)
    except Exception:
        h3_ok = False

    try:
        vol_G = get_vol(G)
        GA = G.row_join(A)
        vol_GA = get_vol(GA)
        h4_ok = bool((vol_G != 0) and (vol_G == vol_GA))
    except Exception:
        h4_ok = False

    try:
        if vol_G == 0:
            neg_q = True
        else:
            conclusion_holds = bool(vol_G == 1)
            neg_q = not conclusion_holds
    except Exception:
        neg_q = False

    return [h1_ok, h2_ok, h3_ok, h4_ok, neg_q]

