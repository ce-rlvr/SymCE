def conditions(witness) -> list[bool]:
    try:
        G = witness.get('G')
        X = witness.get('X')
        X1 = witness.get('X1')
        X2 = witness.get('X2')
        a = witness.get('a')
        b = witness.get('b')
        action = witness.get('action')
    except Exception:
        return [False, False, False, False, False]

    try:
        h1_ok = False
        if G is not None and X is not None and action is not None:
            id_G = G.identity if hasattr(G, 'identity') else (G.eye if hasattr(G, 'eye') else None)
            if id_G is not None:
                h1_ok = all(action(id_G, x) == x for x in X)
            else:
                h1_ok = True
    except Exception:
        h1_ok = False

    try:
        h2_ok = False
        if X1 and X2 and isinstance(X1, (set, list)) and isinstance(X2, (set, list)):
            set_X1 = set(X1)
            set_X2 = set(X2)
            set_X = set(X)
            if set_X1.issubset(set_X) and set_X2.issubset(set_X):
                if len(set_X1) > 0 and len(set_X2) > 0 and set_X1.isdisjoint(set_X2):
                    h2_ok = True
    except Exception:
        h2_ok = False

    try:
        h3_ok = True
        for n in range(-5, 6):
            if n == 0:
                continue
            a_n = a**n
            for x in X2:
                if action(a_n, x) not in X1:
                    h3_ok = False
                    break
            if not h3_ok:
                break
    except Exception:
        h3_ok = False

    try:
        h4_ok = True
        for n in range(-5, 6):
            if n == 0:
                continue
            b_n = b**n
            for x in X1:
                if action(b_n, x) not in X2:
                    h4_ok = False
                    break
            if not h4_ok:
                break
    except Exception:
        h4_ok = False

    try:
        neg_q_ok = False
        words = [
            (a * b * a**-1 * b**-1),
            (a**2 * b**-2),
            (a * b),
            (a**2),
            (b**2),
            (a**3),
            (b**3),
            (a**4),
            (b**4)
        ]
        for w in words:
            if all(action(w, x) == x for x in X):
                neg_q_ok = True
                break
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, h3_ok, h4_ok, neg_q_ok]

