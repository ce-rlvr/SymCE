def conditions(witness) -> list[bool]:
    try:
        G, N, p = witness
    except Exception:
        return [False, False, False, False]
    
    # H_1: G is a semisimple group
    # A finite group is semisimple if it is a direct product of simple groups.
    # Equivalently, it is generated by its minimal normal subgroups.
    try:
        if G.order() == 1:
            h1 = True
        else:
            normals = G.normal_subgroups()
            non_trivial_normals = [sub for sub in normals if sub.order() > 1]
            if not non_trivial_normals:
                # G is a simple group
                h1 = True
            else:
                minimal_normals = []
                for sub in non_trivial_normals:
                    is_minimal = True
                    for other in non_trivial_normals:
                        if other.order() < sub.order() and other.is_subgroup(sub):
                            is_minimal = False
                            break
                    if is_minimal:
                        minimal_normals.append(sub)
                
                gens = []
                for sub in minimal_normals:
                    gens.extend(sub.generators)
                
                join_group = PermutationGroup(gens)
                h1 = (join_group.order() == G.order())
    except Exception:
        h1 = False

    # H_2: N is a normal subgroup of G
    try:
        h2 = N.is_subgroup(G) and N.is_normal(G)
    except Exception:
        try:
            # Fallback in case of domain mismatch or missing methods
            gens_in_G = all(g in G for g in N.generators)
            if not gens_in_G:
                h2 = False
            else:
                is_norm = True
                for g in G.generators:
                    for n in N.generators:
                        conj = g * n * (~g)
                        if conj not in N:
                            is_norm = False
                            break
                    if not is_norm:
                        break
                h2 = is_norm
        except Exception:
            h2 = False

    # H_3: p is a prime number
    try:
        h3 = bool(isprime(p))
    except Exception:
        h3 = False

    # ¬Q: The order of the subgroup N is equal to p
    try:
        neg_q = (N.order() == p)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

