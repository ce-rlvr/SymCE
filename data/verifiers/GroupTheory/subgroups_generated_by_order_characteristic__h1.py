def get_automorphisms(G):
    gens = G.generators
    elements = list(G.elements)
    if not elements:
        return []
    identity = elements[0]**0
    n_elements = len(elements)
    autos = []
    
    for img_gens in product(elements, repeat=len(gens)):
        mapping = {identity: identity}
        queue = [identity]
        
        valid = True
        for g, img_g in zip(gens, img_gens):
            if g in mapping:
                if mapping[g] != img_g:
                    valid = False
                    break
            else:
                mapping[g] = img_g
                queue.append(g)
                
        if not valid:
            continue
            
        head = 0
        while head < len(queue):
            curr = queue[head]
            head += 1
            curr_img = mapping[curr]
            for g, img_g in zip(gens, img_gens):
                nxt = curr * g
                nxt_img = curr_img * img_g
                if nxt in mapping:
                    if mapping[nxt] != nxt_img:
                        valid = False
                        break
                else:
                    mapping[nxt] = nxt_img
                    queue.append(nxt)
            if not valid:
                break
                
        if valid and len(mapping) == n_elements:
            if len(set(mapping.values())) == n_elements:
                autos.append(mapping)
                
    return autos

def is_characteristic(G, H):
    autos = get_automorphisms(G)
    H_elements = set(H.elements)
    for mapping in autos:
        for h in H_elements:
            if mapping[h] not in H_elements:
                return False
    return True

def conditions(witness):
    try:
        if isinstance(witness, dict):
            G = witness.get('G')
            n = witness.get('n')
            H = witness.get('H')
        elif hasattr(witness, 'G') and hasattr(witness, 'n') and hasattr(witness, 'H'):
            G = witness.G
            n = witness.n
            H = witness.H
        else:
            G, n, H = witness
    except Exception:
        return [False, False, False]
        
    # H_1: n is a positive integer
    try:
        h1 = isinstance(n, (int, sympy.Integer)) and int(n) > 0
    except Exception:
        h1 = False
        
    # H_2: H is the subgroup of G generated by the set of all elements in G of order n
    try:
        if not isinstance(G, PermutationGroup) or not isinstance(H, PermutationGroup):
            h2 = False
        else:
            elements = list(G.elements)
            if not elements:
                h2 = False
            else:
                identity = elements[0]**0
                elements_of_order_n = [g for g in elements if g.order() == n]
                if not elements_of_order_n:
                    elements_of_order_n = [identity]
                
                expected_H = PermutationGroup(elements_of_order_n)
                h2 = set(H.elements) == set(expected_H.elements)
    except Exception:
        h2 = False
        
    # neg_Q: H is NOT a characteristic subgroup of G
    try:
        if not isinstance(G, PermutationGroup) or not isinstance(H, PermutationGroup):
            neg_q = False
        elif not set(H.elements).issubset(set(G.elements)):
            neg_q = True
        else:
            neg_q = not is_characteristic(G, H)
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

