def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture:
    "If G is a group and H is a subgroup of G, then H is a maximal subgroup of G."
    """
    try:
        G, H = witness
    except Exception:
        return [False, False, False]

    # H_1: G is a group
    try:
        h1_ok = isinstance(G, PermutationGroup)
    except Exception:
        h1_ok = False

    # H_2: H is a subgroup of G
    try:
        h2_ok = isinstance(H, PermutationGroup) and H.is_subgroup(G)
    except Exception:
        h2_ok = False

    # ¬Q: H is NOT a maximal subgroup of G
    try:
        if not (isinstance(G, PermutationGroup) and isinstance(H, PermutationGroup)):
            neg_q_ok = False
        elif not H.is_subgroup(G):
            neg_q_ok = False
        else:
            # A subgroup H is maximal in G if it is a proper subgroup (H != G)
            # and there is no proper subgroup K of G that strictly contains H.
            if H.order() == G.order():
                # H is not a proper subgroup, so it cannot be maximal
                neg_q_ok = True
            else:
                is_max = True
                H_elements = set(H.generate())
                
                # If H is maximal, then for any x in G \ H, the group generated by H and x must be G.
                for x in G.generate():
                    if x not in H_elements:
                        gens = list(H.generators) + [x]
                        K = PermutationGroup(*gens)
                        if K.order() < G.order():
                            # Found an intermediate proper subgroup K strictly containing H
                            is_max = False
                            break
                
                neg_q_ok = not is_max
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, neg_q_ok]

