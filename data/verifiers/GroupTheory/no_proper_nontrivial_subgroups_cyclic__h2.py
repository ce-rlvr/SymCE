trivial = CyclicGroup(1)

def conditions(witness) -> list[bool]:
    try:
        h1 = isinstance(witness, PermutationGroup)
    except Exception:
        h1 = False

    try:
        order = witness.order() if callable(witness.order) else witness.order
        neg_q = bool((order > 1) and not isprime(order))
    except Exception:
        neg_q = False

    return [h1, neg_q]

