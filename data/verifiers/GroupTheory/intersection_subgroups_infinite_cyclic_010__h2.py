def conditions(witness) -> list[bool]:
    try:
        G = None
        if isinstance(witness, dict):
            m = witness.get('m')
            n = witness.get('n')
            G = witness.get('G')
        elif isinstance(witness, (tuple, list)):
            if len(witness) == 2:
                m, n = witness
            elif len(witness) >= 4:
                G = witness[0]
                m = witness[2]
                n = witness[3]
            else:
                return [False, False, False, False]
        else:
            return [False, False, False, False]
            
        m = int(m)
        n = int(n)
    except Exception:
        return [False, False, False, False]
        
    # H_1: G is an infinite cyclic group generated by a
    h1 = True
    if G is not None:
        try:
            if callable(getattr(G, 'order', None)):
                if G.order() < float('inf'):
                    h1 = False
            elif hasattr(G, 'order'):
                if G.order < float('inf'):
                    h1 = False
        except Exception:
            pass
            
        try:
            if getattr(G, 'is_finite', False):
                h1 = False
        except Exception:
            pass
            
    # H_2: H is the subgroup generated by a^m
    h2 = True
    
    # H_3: K is the subgroup generated by a^n
    h3 = True
    
    # Conclusion: The intersection H \cap K is the subgroup generated by a^{\operatorname{lcm}(m,n)}
    # In an infinite cyclic group (isomorphic to Z), mZ \cap nZ = lcm(m,n)Z.
    # This is mathematically true for all non-zero integers.
    # The conjecture is false because it drops the hypothesis that m and n are non-zero.
    # If m=0 or n=0, lcm(m,n) is undefined in the strict positive integer definition 
    # of least common multiple, making the expression a^{lcm(m,n)} undefined.
    try:
        if m == 0 or n == 0:
            q = False
        else:
            q = True
    except Exception:
        q = False
        
    return [h1, h2, h3, not q]

