def get_order(G):
    o = G.order
    if callable(o):
        return o()
    return o

def is_subgroup(H, G):
    for g in H.generators:
        if g not in G:
            return False
    return True

def is_normal(G, S):
    for g in G.generators:
        for s in S.generators:
            if (g * s * ~g) not in S:
                return False
    return True

def is_semisimple(S):
    # A finite group is semisimple (has trivial solvable radical) iff 
    # it has no non-trivial abelian normal subgroups.
    # This is equivalent to having no non-trivial conjugacy class 
    # whose elements mutually commute.
    if get_order(S) == 1:
        return True
    
    elements = list(S.generate())
    classes = []
    seen = set()
    
    for g in elements:
        if g in seen:
            continue
        if g * g == g:  # Identity element
            seen.add(g)
            continue
        
        cclass = set()
        for s in elements:
            cclass.add(s * g * ~s)
        
        seen.update(cclass)
        classes.append(list(cclass))
    
    for cclass in classes:
        commute = True
        for i in range(len(cclass)):
            for j in range(i + 1, len(cclass)):
                if cclass[i] * cclass[j] != cclass[j] * cclass[i]:
                    commute = False
                    break
            if not commute:
                break
        if commute:
            # Found a non-trivial conjugacy class whose elements mutually commute.
            # The normal subgroup generated by this class is abelian.
            return False
            
    return True

def get_solvable_residual(G):
    # The solvable residual is the limit of the derived series
    current = G
    while True:
        nxt = current.derived_subgroup()
        if get_order(nxt) == get_order(current):
            return current
        current = nxt

def conditions(witness):
    try:
        G, S = witness
    except Exception:
        return [False, False, False]
    
    # H_1: S is a normal semisimple subgroup of G
    try:
        h1 = bool(is_subgroup(S, G) and is_normal(G, S) and is_semisimple(S))
    except Exception:
        h1 = False
        
    # H_2: The quotient group G/S is solvable
    # G/S is solvable iff the solvable residual of G is contained in S
    try:
        R = get_solvable_residual(G)
        h2 = bool(is_subgroup(R, S))
    except Exception:
        h2 = False
        
    # ¬Q: S is not the solvable residual of G
    try:
        R = get_solvable_residual(G)
        is_eq = is_subgroup(S, R) and is_subgroup(R, S)
        neg_q = not is_eq
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]