def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, dict):
            G = witness['G']
            x = witness['x']
            y = witness['y']
        else:
            G, x, y = witness
    except Exception:
        return [False, False, False]
        
    def get_elements(group):
        if hasattr(group, 'elements'):
            return list(group.elements)
        return list(group)
        
    def get_inv(g):
        try:
            return ~g
        except Exception:
            pass
        try:
            return g.inv()
        except Exception:
            pass
        return g**-1

    try:
        elements = get_elements(G)
    except Exception:
        return [False, False, False]

    # H_1: x and y are elements of G
    try:
        if hasattr(G, '__contains__'):
            h1 = (x in G) and (y in G)
        else:
            h1 = any(x == e for e in elements) and any(y == e for e in elements)
    except Exception:
        h1 = False

    # H_2: x and y are conjugate in G
    try:
        h2 = False
        for g in elements:
            if g * x * get_inv(g) == y:
                h2 = True
                break
    except Exception:
        h2 = False

    # ¬Q: The cyclic subgroup generated by x is not conjugate to the cyclic subgroup generated by y in G
    try:
        def cyclic_subgroup(elem):
            subgroup = []
            curr = elem
            for _ in range(10000):
                if any(curr == h for h in subgroup):
                    break
                subgroup.append(curr)
                curr = curr * elem
            return subgroup
            
        def subsets_equal(A, B):
            for a in A:
                if not any(a == b for b in B):
                    return False
            for b in B:
                if not any(a == b for a in A):
                    return False
            return True

        Hx = cyclic_subgroup(x)
        Hy = cyclic_subgroup(y)
        
        q = False
        for g in elements:
            g_inv = get_inv(g)
            conj_Hx = [g * h * g_inv for h in Hx]
            if subsets_equal(conj_Hx, Hy):
                q = True
                break
        neg_q = not q
    except Exception:
        neg_q = False

    return [bool(h1), bool(h2), bool(neg_q)]

