def conditions(witness) -> list[bool]:
    try:
        G, S = witness
    except Exception:
        return [False, False]
    
    # H_1: G is a group
    try:
        h1_ok = isinstance(G, PermutationGroup)
    except Exception:
        h1_ok = False
        
    # neg_Q: There does not exist a surjective group homomorphism from F_{|S|} onto G
    # This is equivalent to saying G CANNOT be generated by |S| elements.
    try:
        try:
            k = len(S)
        except TypeError:
            k = int(S)
            
        if k < 0:
            neg_q_ok = True
        elif k == 0:
            neg_q_ok = (G.order() > 1)
        elif len(G.generators) <= k:
            neg_q_ok = False
        elif getattr(G, 'is_abelian', False):
            try:
                min_gens = len(G.abelian_invariants())
                neg_q_ok = (min_gens > k)
            except Exception:
                neg_q_ok = True
                for combo in itertools.combinations(list(G.elements), k):
                    if PermutationGroup(*combo).order() == G.order():
                        neg_q_ok = False
                        break
        else:
            # The maximum number of generators for a group of order N is floor(log2(N)).
            # If k >= log2(N), i.e., 2^k >= N, then G can definitely be generated by k elements.
            if G.order() <= 2**k:
                neg_q_ok = False
            else:
                neg_q_ok = True
                elements = list(G.elements)
                for combo in itertools.combinations(elements, k):
                    H = PermutationGroup(*combo)
                    if H.order() == G.order():
                        neg_q_ok = False
                        break
    except Exception:
        neg_q_ok = False
        
    return [h1_ok, neg_q_ok]

