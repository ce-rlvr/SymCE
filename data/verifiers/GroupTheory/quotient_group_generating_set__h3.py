def conditions(witness) -> list[bool]:
    try:
        G, N, S = witness
    except Exception:
        return [False, False, False]
    
    # H_1: G is a group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False
        
    # H_2: N is a normal subgroup of G
    try:
        if isinstance(N, PermutationGroup):
            # Verify N is a subgroup first to safely call is_normal
            is_sub = all(g in G for g in N.generators)
            if is_sub:
                h2 = bool(N.is_normal(G))
            else:
                h2 = False
        else:
            h2 = False
    except Exception:
        h2 = False
        
    # neg_Q: The set of cosets {sN | s \in S} does NOT generate G/N
    try:
        if not isinstance(S, (list, set, tuple)):
            neg_q = False
        elif not all(s in G for s in S):
            neg_q = False
        else:
            # By the correspondence theorem, {sN | s \in S} generates G/N 
            # if and only if the subgroup generated by N \cup S equals G.
            gens = list(N.generators) + list(S)
            if not gens:
                # If both N and S are empty/trivial, they generate the trivial group
                neg_q = G.order() > 1
            else:
                H = PermutationGroup(gens)
                # If the generated subgroup is strictly smaller than G, it fails to generate G/N
                neg_q = H.order() < G.order()
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

