def conditions(witness):
    try:
        G, x, y = witness
    except Exception:
        return [False, False, False]
    
    # H1: G is a group
    try:
        if isinstance(G, PermutationGroup):
            h1 = True
            elements = list(G.elements)
        else:
            elements = list(G)
            h1 = len(elements) > 0
    except Exception:
        h1 = False
        elements = []

    # H2: x and y are conjugate in G
    try:
        if not h1:
            h2 = False
        else:
            if x not in elements or y not in elements:
                h2 = False
            else:
                h2 = False
                for g in elements:
                    try:
                        if g * x * g**-1 == y:
                            h2 = True
                            break
                    except Exception:
                        pass
    except Exception:
        h2 = False

    # neg_Q: The cyclic subgroup generated by x is NOT conjugate to the cyclic subgroup generated by y in G
    try:
        if not h1:
            neg_q = False
        else:
            def generate_cyclic(elem):
                subgroup = []
                current = elem
                for _ in range(1000):
                    if current not in subgroup:
                        subgroup.append(current)
                    else:
                        break
                    current = current * elem
                return subgroup
            
            hx_elements = generate_cyclic(x)
            hy_elements = generate_cyclic(y)
            
            is_conjugate = False
            for g in elements:
                try:
                    conj_hx = []
                    for h in hx_elements:
                        conj_hx.append(g * h * g**-1)
                    
                    if len(conj_hx) == len(hy_elements):
                        if all(c in hy_elements for c in conj_hx):
                            is_conjugate = True
                            break
                except Exception:
                    pass
            
            neg_q = not is_conjugate
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

