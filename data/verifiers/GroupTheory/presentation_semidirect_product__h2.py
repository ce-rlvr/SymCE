def conditions(witness):
    try:
        X_sym = witness['X_symbols']
        Y_sym = witness['Y_symbols']
        R = witness['R']
        S = witness['S']
        N = witness['N']
        X = witness['X']
        H = witness['H']
        Y = witness['Y']
        phi = witness['phi']
        W = witness['W']
        
        sym_to_X = dict(zip(X_sym, X))
        N_identity = N.generators[0] ** 0 if N.generators else Permutation()
        H_identity = H.generators[0] ** 0 if H.generators else Permutation()
    except Exception:
        return [False, False, False, False]

    def eval_word(word, sym_to_elem, identity):
        res = identity
        for sym, p in word:
            res = res * (sym_to_elem[sym] ** p)
        return res

    # H_1: N is a group generated by a set X with defining relations R
    h1_ok = False
    try:
        if isinstance(N, PermutationGroup) and isinstance(H, PermutationGroup):
            if PermutationGroup(*X) == N:
                r_valid = all(eval_word(r, sym_to_X, N_identity) == N_identity for r in R)
                if r_valid:
                    F_X, x_gens = free_group(','.join(X_sym))
                    
                    def to_F_word_X(word):
                        res = F_X.identity
                        gens_dict = dict(zip(X_sym, x_gens))
                        for sym, p in word:
                            res = res * (gens_dict[sym] ** p)
                        return res
                    
                    R_F = [to_F_word_X(r) for r in R]
                    N_fp = FpGroup(F_X, R_F)
                    if N_fp.order() == N.order():
                        h1_ok = True
    except Exception:
        h1_ok = False

    # H_2: phi: H -> Aut(N) is a group homomorphism
    h2_ok = False
    try:
        is_hom = True
        for h in H.elements:
            if h not in phi:
                is_hom = False
                break
            phi_h_eval = {}
            for x_s in X_sym:
                phi_h_eval[x_s] = eval_word(phi[h][x_s], sym_to_X, N_identity)
            
            for r in R:
                if eval_word(r, phi_h_eval, N_identity) != N_identity:
                    is_hom = False
                    break
            if not is_hom: break
            
        if is_hom:
            for h1 in H.elements:
                phi_h1_eval = {s: eval_word(phi[h1][s], sym_to_X, N_identity) for s in X_sym}
                for h2 in H.elements:
                    h12 = h1 * h2
                    for x_s in X_sym:
                        w2 = phi[h2][x_s]
                        val1 = eval_word(w2, phi_h1_eval, N_identity)
                        val2 = eval_word(phi[h12][x_s], sym_to_X, N_identity)
                        if val1 != val2:
                            is_hom = False
                            break
                    if not is_hom: break
                if not is_hom: break
        
        if is_hom:
            for x_s in X_sym:
                if eval_word(phi[H_identity][x_s], sym_to_X, N_identity) != sym_to_X[x_s]:
                    is_hom = False
                    break
                    
        h2_ok = is_hom
    except Exception:
        h2_ok = False

    # H_3: For each x in X and y in Y, w_{y,x} is a word in X representing phi_y(x) in N
    h3_ok = False
    try:
        sym_to_Y = dict(zip(Y_sym, Y))
        is_w_valid = True
        for y_s in Y_sym:
            y_elem = sym_to_Y[y_s]
            for x_s in X_sym:
                w = W.get((y_s, x_s))
                if w is None:
                    is_w_valid = False
                    break
                val_w = eval_word(w, sym_to_X, N_identity)
                val_phi = eval_word(phi[y_elem][x_s], sym_to_X, N_identity)
                if val_w != val_phi:
                    is_w_valid = False
                    break
            if not is_w_valid: break
        h3_ok = is_w_valid
    except Exception:
        h3_ok = False

    # ¬Q: The presentation does not define the external semidirect product N rtimes_phi H
    neg_q = False
    try:
        all_sym = X_sym + Y_sym
        F_all, all_gens = free_group(','.join(all_sym))
        gens_dict = dict(zip(all_sym, all_gens))
        
        def to_F_word(word):
            res = F_all.identity
            for sym, p in word:
                res = res * (gens_dict[sym] ** p)
            return res
            
        R_F = [to_F_word(r) for r in R]
        S_F = [to_F_word(s) for s in S]
        
        W_F = []
        for y_s in Y_sym:
            for x_s in X_sym:
                w = W[(y_s, x_s)]
                y_gen = gens_dict[y_s]
                x_gen = gens_dict[x_s]
                lhs = y_gen * x_gen * (y_gen ** -1)
                rhs = to_F_word(w)
                W_F.append(lhs * (rhs ** -1))
                
        P = FpGroup(F_all, R_F + S_F + W_F)
    except Exception:
        return [h1_ok, h2_ok, h3_ok, False]

    try:
        p_order = P.order()
        if p_order != N.order() * H.order():
            neg_q = True
    except Exception:
        # If order computation fails (e.g., infinite group), the presentation
        # does not define the finite group N rtimes H.
        neg_q = True

    return [h1_ok, h2_ok, h3_ok, neg_q]

