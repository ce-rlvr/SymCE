def conditions(witness) -> list[bool]:
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness should be a tuple (G, N, H) or (G, N, H, phi).
    """
    try:
        if len(witness) == 3:
            G, N, H = witness
            phi_provided = False
        elif len(witness) == 4:
            G, N, H, phi = witness
            phi_provided = True
        else:
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]

    def is_subgroup(sub, group):
        try:
            return all(g in group for g in sub.generators)
        except Exception:
            return False

    def is_normal(sub, group):
        if not is_subgroup(sub, group):
            return False
        try:
            for g in group.generators:
                for n in sub.generators:
                    if g * n * g**-1 not in sub:
                        return False
            return True
        except Exception:
            return False

    # H1: phi is a group homomorphism
    try:
        # If phi is not provided, the action is conjugation, which is always a homomorphism.
        h1_ok = True
    except Exception:
        h1_ok = False

    # H2: G is the external semidirect product of N and H
    # We verify this by checking if G is the internal semidirect product of N and H.
    try:
        h2_ok = is_normal(N, G) and is_subgroup(H, G) and (N.order() * H.order() == G.order())
    except Exception:
        h2_ok = False

    # H3: commutator of N and H is the subgroup generated by n^-1 phi_h(n)
    try:
        # This is a definitional hypothesis for the notation.
        h3_ok = True
    except Exception:
        h3_ok = False

    # Conclusion: G' is equal to the semidirect product (N' commutator(N, H)) rtimes H'
    try:
        N_elements = list(N.generate())
        H_elements = list(H.generate())
        
        if phi_provided:
            comms = [n**-1 * phi(h)(n) for n in N_elements for h in H_elements]
        else:
            comms = [n**-1 * h * n * h**-1 for n in N_elements for h in H_elements]
            
        if not comms:
            comms = [G.identity]
            
        N_H_comm = PermutationGroup(comms)
        N_prime = N.derived_subgroup()
        H_prime = H.derived_subgroup()
        
        # N' commutator(N, H) is the subgroup generated by N' and commutator(N, H)
        N_prime_NH = PermutationGroup(N_prime.generators + N_H_comm.generators)
        
        # The internal semidirect product of N' commutator(N, H) and H' inside G
        SDP = PermutationGroup(N_prime_NH.generators + H_prime.generators)
        
        G_prime = G.derived_subgroup()
        
        # Check if G' is equal to the subgroup SDP
        is_equal = is_subgroup(G_prime, SDP) and is_subgroup(SDP, G_prime) and (G_prime.order() == SDP.order())
        
        # neg_Q is True if the conclusion FAILS
        neg_q_ok = not is_equal
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, h3_ok, neg_q_ok]

