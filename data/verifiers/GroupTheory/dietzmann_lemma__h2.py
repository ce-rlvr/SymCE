def eval_word(gens, word):
    if not gens:
        return None
    res = gens[0].eye(gens[0].shape[0])
    for idx in word:
        if idx == 0:
            continue
        if idx > 0:
            res = res * gens[idx-1]
        else:
            res = res * gens[-idx-1].inv()
    return res

def conditions(witness):
    """
    The witness is expected to be a dictionary (or object) providing:
      - G_gens: list of invertible SymPy matrices generating G.
      - S_gens: list of SymPy matrices generating S (S is implicitly the conjugacy closure of S_gens in G).
      - S_gens_words: list of words (lists of 1-based indices) showing how to form S_gens from G_gens.
      - inf_word: a word (list of 1-based indices) in S_gens that evaluates to an element of infinite order.
    """
    try:
        if isinstance(witness, dict):
            G_gens = witness.get('G_gens', [])
            S_gens = witness.get('S_gens', [])
            S_gens_words = witness.get('S_gens_words', [])
            inf_word = witness.get('inf_word', [])
        else:
            G_gens = getattr(witness, 'G_gens', [])
            S_gens = getattr(witness, 'S_gens', [])
            S_gens_words = getattr(witness, 'S_gens_words', [])
            inf_word = getattr(witness, 'inf_word', [])
            
        if not G_gens or not S_gens or not S_gens_words or not inf_word:
            return [False, False, False, False]
            
        # H1: G is a group
        # We verify that G_gens are valid invertible matrices of size <= 5 over Q.
        h1 = True
        for g in G_gens:
            if not hasattr(g, 'shape') or g.shape[0] != g.shape[1]:
                h1 = False
                break
            if g.shape[0] > 5:
                h1 = False
                break
            if not all(getattr(x, 'is_Rational', False) for x in g):
                h1 = False
                break
            if g.det() == 0:
                h1 = False
                break
                
        # H2: Every element of S has finite order
        # Since S is the conjugacy closure of S_gens, we only need to check S_gens.
        # For matrices of size <= 5 over Q, the maximum finite order is 12. 
        # We check up to 60 iterations to be absolutely certain.
        h2 = True
        for s in S_gens:
            I = s.eye(s.shape[0])
            curr = s
            is_finite = False
            for _ in range(60):
                if curr == I:
                    is_finite = True
                    break
                curr = curr * s
            if not is_finite:
                h2 = False
                break
                
        # H3: S is invariant under conjugation by all elements of G
        # This is true by definition of S as the conjugacy closure of S_gens in G.
        # We just need to verify that S_gens are actually elements of G.
        h3 = True
        if len(S_gens) != len(S_gens_words):
            h3 = False
        else:
            for s, word in zip(S_gens, S_gens_words):
                if s != eval_word(G_gens, word):
                    h3 = False
                    break
                    
        # neg_Q: <S> is not a finite normal subgroup of G
        # We evaluate inf_word on S_gens to get an element in <S>.
        # If it has infinite order, <S> is infinite, so the conclusion fails.
        neg_q = False
        inf_elem = eval_word(S_gens, inf_word)
        if inf_elem is not None:
            I = inf_elem.eye(inf_elem.shape[0])
            curr = inf_elem
            is_finite = False
            for _ in range(60):
                if curr == I:
                    is_finite = True
                    break
                curr = curr * inf_elem
            if not is_finite:
                neg_q = True
                
        return [h1, h2, h3, neg_q]
    except Exception:
        return [False, False, False, False]