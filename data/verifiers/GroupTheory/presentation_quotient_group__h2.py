CONDITION_LABELS = [
    "H_1: G is a group with presentation <X | R>",
    "H_2: N is the normal closure in G of the subgroup generated by the images of the words in S under the canonical evaluation map",
    "¬Q: The quotient group G/N does NOT have the presentation <X | R U S>"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    """
    Checks the witness against the hypotheses and negated conclusion.
    The witness should be a dictionary containing:
      - 'X_free': a FreeGroup instance representing the generators X
      - 'R': a list of FreeGroupElements representing the relations R
      - 'G': a PermutationGroup representing the group G
      - 'X_eval': a list of Permutations representing the images of X in G
      - 'S': a list of elements (either FreeGroupElements or Permutations)
      - 'N': a PermutationGroup representing the normal subgroup N
    """
    try:
        X_free = witness['X_free']
        R = witness['R']
        G = witness['G']
        X_eval = witness['X_eval']
        S = witness['S']
        N = witness['N']
    except Exception:
        return [False, False, False]
        
    # H_1: G has presentation <X | R>
    h1 = False
    try:
        H_eval = PermutationGroup(X_eval)
        # Check if X_eval generates G
        if all(g in G for g in H_eval.generators) and all(g in H_eval for g in G.generators):
            id_perm = G.generators[0]**0 if G.generators else Permutation()
            r_evals_to_id = True
            # Check if all relations in R evaluate to the identity in G
            for r in R:
                val = id_perm
                for letter in r.letters:
                    if letter in X_free.generators:
                        idx = X_free.generators.index(letter)
                        val = val * X_eval[idx]
                    else:
                        idx = X_free.generators.index(letter**-1)
                        val = val * (X_eval[idx]**-1)
                if val != id_perm:
                    r_evals_to_id = False
                    break
            
            if r_evals_to_id:
                # Check if the order of the presented group matches the order of G
                fp_G = FpGroup(X_free, R)
                if fp_G.order() == G.order():
                    h1 = True
    except Exception:
        h1 = False

    # H_2: N is the normal closure in G of the subgroup generated by the images of S
    h2 = False
    try:
        id_perm = G.generators[0]**0 if G.generators else Permutation()
        images = []
        for s in S:
            if isinstance(s, Permutation):
                images.append(s)
            elif hasattr(s, 'parent') and s.parent() == X_free:
                val = id_perm
                for letter in s.letters:
                    if letter in X_free.generators:
                        idx = X_free.generators.index(letter)
                        val = val * X_eval[idx]
                    else:
                        idx = X_free.generators.index(letter**-1)
                        val = val * (X_eval[idx]**-1)
                images.append(val)
            else:
                raise ValueError("Elements of S must be Permutations or FreeGroupElements of X_free")
        
        # Compute the normal closure of the images in G
        conjugates = [id_perm]
        for img in images:
            for g in list(G.elements):
                conjugates.append(g**-1 * img * g)
        
        N_expected = PermutationGroup(conjugates)
        # Check if N matches the expected normal closure
        if all(g in N for g in N_expected.generators) and all(g in N_expected for g in N.generators):
            h2 = True
    except Exception:
        h2 = False

    # ¬Q: G/N does NOT have the presentation <X | R U S>
    neg_q = False
    try:
        # If S contains elements of G (Permutations) rather than words in X, 
        # creating the presentation <X | R U S> will raise an exception.
        fp_quotient = FpGroup(X_free, R + S)
        expected_order = G.order() // N.order()
        
        # If it doesn't raise, check if the orders mismatch
        if fp_quotient.order() != expected_order:
            neg_q = True
    except Exception:
        # The presentation is invalid, so G/N does not have this presentation
        neg_q = True

    return [h1, h2, neg_q]