def has_relation(A_mat, B_mat, max_depth=12):
    """
    Performs a breadth-first search to find if there is any non-trivial reduced word
    of length up to `max_depth` in A and B that evaluates to the identity matrix.
    If such a relation exists, the group generated by A and B is not freely generated by them.
    """
    A = (int(A_mat[0,0]), int(A_mat[0,1]), int(A_mat[1,0]), int(A_mat[1,1]))
    B = (int(B_mat[0,0]), int(B_mat[0,1]), int(B_mat[1,0]), int(B_mat[1,1]))
    
    if A == (1, 0, 0, 1) or B == (1, 0, 0, 1):
        return True
        
    def inv(M):
        a, b, c, d = M
        # Since det is 1, the inverse is simply:
        return (d, -b, -c, a)
        
    A_inv = inv(A)
    B_inv = inv(B)
    
    gens = (A, A_inv, B, B_inv)
    
    # To ensure we only check reduced words, we prevent a generator from being 
    # immediately followed by its inverse.
    # Indices: 0: A, 1: A_inv, 2: B, 3: B_inv
    allowed_gens = (
        (0, 2, 3), # last was A (0), cannot be A_inv (1)
        (1, 2, 3), # last was A_inv (1), cannot be A (0)
        (0, 1, 2), # last was B (2), cannot be B_inv (3)
        (0, 1, 3)  # last was B_inv (3), cannot be B (2)
    )
    
    current_level = []
    for i in range(4):
        if gens[i] == (1, 0, 0, 1):
            return True
        current_level.append((gens[i], i))
    
    for depth in range(2, max_depth + 1):
        next_level = []
        append = next_level.append
        for mat, last_idx in current_level:
            a, b, c, d = mat
            for i in allowed_gens[last_idx]:
                e, f, g, h = gens[i]
                new_mat = (a*e+b*g, a*f+b*h, c*e+d*g, c*f+d*h)
                if new_mat == (1, 0, 0, 1):
                    return True
                append((new_mat, i))
        current_level = next_level
        
    return False

def conditions(witness):
    # H_1: B is a 2x2 matrix over integers with determinant 1
    try:
        if not isinstance(witness, Matrix):
            h1_ok = False
        elif witness.shape != (2, 2):
            h1_ok = False
        else:
            is_int = True
            for x in witness:
                if isinstance(x, int):
                    continue
                if hasattr(x, 'is_integer') and x.is_integer:
                    continue
                is_int = False
                break
            
            if not is_int:
                h1_ok = False
            else:
                h1_ok = bool(witness.det() == 1)
    except Exception:
        h1_ok = False

    # neg_Q: A and B do not generate a free group of rank 2
    try:
        if not h1_ok:
            neg_q = False
        else:
            A_mat = Matrix([[1, 2], [0, 1]])
            # If a relation of length <= 12 is found, they do not freely generate F_2
            neg_q = bool(has_relation(A_mat, witness, max_depth=12))
    except Exception:
        neg_q = False

    return [h1_ok, neg_q]