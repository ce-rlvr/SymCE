def conditions(witness) -> list[bool]:
    try:
        G, N, S = witness
        S = list(S)
    except Exception:
        return [False, False, False]
        
    # H1: N is a normal subgroup of G
    try:
        h1 = bool(N.is_subgroup(G) and N.is_normal(G))
    except Exception:
        h1 = False
        
    # H2: S is a subset of G that generates G
    try:
        is_subset = all(s in G for s in S)
        if not is_subset:
            h2 = False
        else:
            if not S:
                id_el = G.generators[0]**0 if G.generators else Permutation()
                S_group = PermutationGroup([id_el])
            else:
                S_group = PermutationGroup(S)
            h2 = bool(S_group == G)
    except Exception:
        h2 = False
        
    # neg_Q: The set of cosets {sN | s \in S} does NOT generate G/N
    # By the Correspondence Theorem, the subgroup of G/N generated by {sN | s \in S}
    # corresponds to the subgroup of G generated by S \cup N.
    # Thus, {sN} generates G/N if and only if <S \cup N> = G.
    try:
        gens = S + list(N.generators)
        if not gens:
            id_el = G.generators[0]**0 if G.generators else Permutation()
            SN_group = PermutationGroup([id_el])
        else:
            SN_group = PermutationGroup(gens)
        
        q = bool(SN_group == G)
        neg_q = not q
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

