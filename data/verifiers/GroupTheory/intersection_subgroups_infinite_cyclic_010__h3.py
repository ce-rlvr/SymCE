# In this context, we model the infinite cyclic group G as the integers Z under addition.
# The generator 'a' corresponds to 1.
# Subgroups are represented by their non-negative integer generators.
# A witness is expected to provide m, n, and the generators for H and K.

def to_int(val):
    if isinstance(val, int):
        return val
    if hasattr(val, 'is_integer') and val.is_integer:
        return int(val)
    return val

def conditions(witness):
    try:
        if isinstance(witness, dict):
            m = witness.get('m')
            n = witness.get('n')
            H_gen = witness.get('H')
            if H_gen is None:
                H_gen = witness.get('H_gen')
            K_gen = witness.get('K')
            if K_gen is None:
                K_gen = witness.get('K_gen', n)
        elif isinstance(witness, (tuple, list)):
            if len(witness) < 3:
                return [False, False, False, False]
            m = witness[0]
            n = witness[1]
            H_gen = witness[2]
            K_gen = witness[3] if len(witness) > 3 else n
        else:
            return [False, False, False, False]

        m = to_int(m)
        n = to_int(n)
        H_gen = to_int(H_gen)
        K_gen = to_int(K_gen)

        # H_1: G is an infinite cyclic group generated by a
        # We implicitly work in Z, which is an infinite cyclic group.
        h1 = True
        
        # H_2: m and n are positive integers
        h2 = isinstance(m, int) and isinstance(n, int) and m > 0 and n > 0
        
        # H_3: K is the subgroup generated by a^n
        # In Z, a^n corresponds to n. So K must be generated by n (or -n).
        h3 = isinstance(K_gen, int) and abs(K_gen) == abs(n) if h2 else False
        
        # Conclusion: H \cap K is the subgroup generated by a^{lcm(m,n)}
        # In Z, H \cap K is generated by lcm(H_gen, K_gen).
        if not isinstance(H_gen, int):
            return [h1, h2, h3, False]
            
        def get_lcm(x, y):
            if x == 0 or y == 0:
                return 0
            return abs(x * y) // math.gcd(x, y)
            
        actual_lcm = get_lcm(H_gen, K_gen)
        expected_lcm = get_lcm(m, n) if h2 else 0
        
        neg_q = actual_lcm != expected_lcm
        
        return [h1, h2, h3, neg_q]
    except Exception:
        return [False, False, False, False]

