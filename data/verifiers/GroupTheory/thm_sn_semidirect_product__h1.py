def conditions(witness) -> list[bool]:
    """
    Given a witness, evaluates the remaining hypotheses and the negated conclusion.
    The conjecture is that S_n is the internal semidirect product of A_n and H,
    where H is generated by a single transposition.
    This is true for all finite n >= 2, but fails for infinite n.
    """
    # 1. Check if witness represents infinity
    is_inf = False
    try:
        if witness == sympy.oo:
            is_inf = True
        elif isinstance(witness, str) and witness.lower() in ['oo', 'infinity', 'infinite']:
            is_inf = True
        elif isinstance(witness, float) and math.isinf(witness):
            is_inf = True
    except Exception:
        pass

    if is_inf:
        # For infinite degree, A_n H is the finitary symmetric group, which is a proper
        # subgroup of the full infinite symmetric group S_n. Thus, it is NOT the semidirect product.
        return [True, True, True]

    # 2. Check if witness is a tuple (G, N, H)
    try:
        if isinstance(witness, tuple) and len(witness) == 3:
            G, N, H = witness
            if hasattr(G, 'degree') and hasattr(N, 'is_normal') and hasattr(H, 'generators'):
                n = G.degree
                h1 = N.is_normal(G) and N.order() * 2 == G.order()
                h2 = False
                if len(H.generators) == 1:
                    gen = list(H.generators)[0]
                    if hasattr(gen, 'cyclic_form'):
                        cycles = gen.cyclic_form
                        non_trivial = [c for c in cycles if len(c) > 1]
                        if len(non_trivial) == 1 and len(non_trivial[0]) == 2:
                            h2 = True
                
                intersect_trivial = True
                for g in H.elements:
                    if g != G.identity and g in N:
                        intersect_trivial = False
                        break
                is_semidirect = intersect_trivial and (N.order() * H.order() == G.order())
                neg_q = not is_semidirect
                
                return [bool(h1), bool(h2), bool(neg_q)]
    except Exception:
        pass

    # 3. Check if witness is a tuple (n, H) or (n,)
    try:
        if isinstance(witness, tuple) and len(witness) >= 1:
            n_val = witness[0]
            if n_val == sympy.oo or (isinstance(n_val, str) and n_val.lower() in ['oo', 'infinity', 'infinite']) or (isinstance(n_val, float) and math.isinf(n_val)):
                return [True, True, True]
            
            n = int(n_val)
            if n >= 2:
                h2 = True
                if len(witness) >= 2:
                    H = witness[1]
                    if hasattr(H, 'generators'):
                        if len(H.generators) == 1:
                            gen = list(H.generators)[0]
                            if hasattr(gen, 'cyclic_form'):
                                cycles = gen.cyclic_form
                                non_trivial = [c for c in cycles if len(c) > 1]
                                if len(non_trivial) == 1 and len(non_trivial[0]) == 2:
                                    if hasattr(gen, 'size') and gen.size <= n:
                                        h2 = True
                                    else:
                                        h2 = False
                                else:
                                    h2 = False
                            else:
                                h2 = False
                        else:
                            h2 = False
                return [True, h2, False]
            elif n >= 0:
                return [True, False, False]
    except Exception:
        pass

    # 4. Check if witness is an integer n
    try:
        n = int(witness)
        if n >= 2:
            return [True, True, False]
        elif n >= 0:
            return [True, False, False]
    except Exception:
        pass

    # 5. Check if witness is a SymPy group
    try:
        if hasattr(witness, 'degree'):
            n = witness.degree
            if n >= 2:
                return [True, True, False]
            else:
                return [True, False, False]
    except Exception:
        pass

    return [False, False, False]

