def conditions(witness) -> list[bool]:
    try:
        # The witness might be provided as just the group G, or a tuple (G, k, S_list)
        if isinstance(witness, tuple):
            G = witness[0]
        else:
            G = witness
    except Exception:
        return [False, False, False]

    # H_1: Let G be a finite group
    try:
        h1 = isinstance(G, PermutationGroup) and G.order() < float('inf')
    except Exception:
        h1 = False

    # H_2: Let G be a semisimple group
    # neg_Q: The composition factors of G are not exactly its simple components
    h2 = False
    neg_q = False
    try:
        if h1:
            elements = list(G.elements)
            id_elem = elements[0]**0
            
            # Compute conjugacy classes
            classes = []
            unseen = set(elements)
            while unseen:
                x = unseen.pop()
                c = set()
                for g in elements:
                    c.add(g * x * ~g)
                classes.append(list(c))
                unseen -= c
                
            # Compute normal subgroups generated by each non-trivial conjugacy class
            normal_subgroups = []
            for c in classes:
                if c[0] == id_elem:
                    continue
                closure = set(c)
                closure.add(id_elem)
                queue = list(c)
                while queue:
                    x = queue.pop(0)
                    for g in c:
                        y = x * g
                        if y not in closure:
                            closure.add(y)
                            queue.append(y)
                normal_subgroups.append(closure)
                
            # Find minimal normal subgroups
            min_normals = []
            for N in normal_subgroups:
                is_minimal = True
                for M in normal_subgroups:
                    if M != N and M.issubset(N):
                        is_minimal = False
                        break
                if is_minimal:
                    if N not in min_normals:
                        min_normals.append(N)
                        
            # A group is semisimple if it has no non-trivial abelian normal subgroups.
            # It suffices to check if any minimal normal subgroup is abelian.
            h2 = True
            for N in min_normals:
                N_list = list(N)
                is_ab = True
                for i in range(len(N_list)):
                    for j in range(i + 1, len(N_list)):
                        if N_list[i] * N_list[j] != N_list[j] * N_list[i]:
                            is_ab = False
                            break
                    if not is_ab:
                        break
                if is_ab:
                    h2 = False
                    break
            
            # The conclusion states that the composition factors are exactly the simple components S_1...S_k.
            # This holds iff G is a direct product of its minimal normal subgroups.
            # Since minimal normal subgroups intersect trivially, their product is direct.
            # Thus, G is their direct product iff the product of their sizes equals |G|.
            prod = 1
            for N in min_normals:
                prod *= len(N)
                
            if G.order() != prod:
                neg_q = True
            else:
                neg_q = False
    except Exception:
        h2 = False
        neg_q = False

    return [h1, h2, neg_q]

