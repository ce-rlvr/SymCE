def conditions(witness) -> list[bool]:
    """
    Given a witness (m, n), checks if it satisfies the hypotheses and fails the conclusion.
    """
    try:
        # The witness is expected to be a tuple of two integers (m, n)
        m, n = witness
    except Exception:
        return [False, False, False]
        
    # H_1: mZ is a subgroup of Z, which implies m is an integer.
    try:
        h1 = sympy.S(m).is_integer
    except Exception:
        h1 = False
        
    # H_2: nZ is a subgroup of Z, which implies n is an integer.
    try:
        h2 = sympy.S(n).is_integer
    except Exception:
        h2 = False
        
    # ¬Q: The intersection H \cap K is NOT the subgroup lcm(m, n)Z.
    try:
        if not (h1 and h2):
            neg_q = False
        else:
            m_int = sympy.Integer(m)
            n_int = sympy.Integer(n)
            
            # In the integers Z, the intersection of ideals/subgroups mZ and nZ 
            # is mathematically generated by lcm(m, n).
            actual_gen = sympy.lcm(m_int, n_int)
            
            # The conclusion claims the intersection is lcm(m, n)Z.
            claimed_gen = sympy.lcm(m_int, n_int)
            
            # Two subgroups aZ and bZ are equal iff |a| == |b|.
            # We check if the actual intersection differs from the claimed one.
            neg_q = abs(actual_gen) != abs(claimed_gen)
    except Exception:
        neg_q = False
        
    return [bool(h1), bool(h2), bool(neg_q)]

