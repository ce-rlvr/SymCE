def conditions(witness) -> list[bool]:
    try:
        G, S = witness
    except Exception:
        return [False, False]

    # H_1: G is a group and S is a subset of G
    try:
        h1 = (isinstance(G, PermutationGroup) and 
              isinstance(S, (list, set, tuple)) and 
              all(g in G for g in S))
    except Exception:
        h1 = False

    # ¬Q: The subgroup generated by S is NOT a normal subgroup of G
    try:
        if not h1:
            neg_q = False
        else:
            if len(S) == 0:
                id_el = getattr(G, 'identity', None)
                if id_el is None:
                    id_el = G.generators[0]**0 if G.generators else Permutation()
                H = PermutationGroup([id_el])
            else:
                H = PermutationGroup(list(S))
            
            neg_q = not H.is_normal(G)
    except Exception:
        neg_q = False

    return [h1, neg_q]

