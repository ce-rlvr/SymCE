def conditions(witness):
    """
    Given a witness tuple (n, F, G), checks if it is a valid counterexample.
    """
    try:
        n, F, G = witness
    except Exception:
        return [False, False, False, False]
        
    # H1: n is a positive integer
    try:
        h1 = isinstance(n, int) and n > 0
    except Exception:
        h1 = False
        
    # H2: F is a free group of rank n
    try:
        h2 = type(F).__name__ == 'FreeGroup' and len(F.generators) == n
    except Exception:
        h2 = False
        
    # H3: G can be generated by a set of n or fewer elements
    try:
        h3 = False
        if hasattr(G, 'generators'):
            if len(G.generators) <= n:
                h3 = True
            elif hasattr(G, 'generate'):
                elements = list(G.generate())
                if len(elements) <= 100:  # Prevent timeout for large groups
                    for subset in itertools.combinations(elements, n):
                        try:
                            H = PermutationGroup(list(subset))
                            if H.is_subgroup(G) and G.is_subgroup(H):
                                h3 = True
                                break
                        except Exception:
                            pass
        elif hasattr(G, 'gens'):
            h3 = len(G.gens) <= n
        elif isinstance(G, (list, set, tuple)):
            h3 = len(G) <= n
    except Exception:
        h3 = False
        
    # neg_Q: There does NOT exist a surjective group homomorphism from F onto G
    try:
        # Mathematically, if F is a free group of rank n and G is ANY group generated 
        # by n elements, there ALWAYS exists a surjective group homomorphism from F onto G.
        # Therefore, the conclusion can only fail (neg_Q is True) if G is NOT a group.
        is_group = False
        group_class_names = (
            'PermutationGroup', 'FreeGroup', 'FpGroup', 'FinitelyGeneratedGroup', 
            'CyclicGroup', 'DihedralGroup', 'AlternatingGroup', 'SymmetricGroup'
        )
        if type(G).__name__ in group_class_names:
            is_group = True
        elif hasattr(G, 'generators') and hasattr(G, 'identity'):
            is_group = True
            
        neg_q = not is_group
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

