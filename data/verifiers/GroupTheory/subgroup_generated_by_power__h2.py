CONDITION_LABELS = [
    "H_1: G is a cyclic group",
    "H_2: The order of G is a finite integer n",
    "H_3: k is an integer",
    "¬Q: The subgroup generated by a^k is not equal to the subgroup generated by a^gcd(k,n)"
]

def conditions(witness):
    if isinstance(witness, dict):
        G = witness.get('G')
        n = witness.get('n')
        k = witness.get('k')
        a = witness.get('a')
    else:
        try:
            G, n, k, a = witness
        except Exception:
            return [False, False, False, False]

    # H_1: G is a cyclic group
    try:
        h1 = bool(G.is_cyclic)
    except Exception:
        h1 = False

    # H_2: The order of G is a finite integer n
    try:
        h2 = bool(G.order() == n and isinstance(n, (int, Integer)) and n > 0)
    except Exception:
        h2 = False

    # H_3: k is an integer
    try:
        h3 = isinstance(k, (int, Integer))
    except Exception:
        h3 = False

    # neg_Q: <a^k> != <a^gcd(k,n)>
    try:
        m = None
        # Try to get the order of the element 'a' using a built-in method
        if hasattr(a, 'order') and callable(a.order):
            try:
                m_val = a.order()
                if m_val != math.inf and m_val != float('inf'):
                    m = int(m_val)
            except Exception:
                pass
        
        # Fallback: compute the order manually by finding the smallest positive power that yields the identity
        if m is None:
            try:
                identity = a**0
                for i in range(1, 1001):
                    if a**i == identity:
                        m = i
                        break
            except Exception:
                pass

        # In a cyclic group <a>, the subgroups <a^x> and <a^y> are equal if and only if they have the same order.
        # The order of <a^x> is |a| / gcd(x, |a|).
        # Thus, <a^k> == <a^gcd(k,n)> iff gcd(k, |a|) == gcd(gcd(k,n), |a|).
        if m is not None:
            gcd_k_m = math.gcd(int(k), m)
            gcd_k_n_m = math.gcd(math.gcd(int(k), int(n)), m)
            neg_q = bool(gcd_k_m != gcd_k_n_m)
        else:
            # If 'a' has infinite order, <a^x> == <a^y> iff |x| == |y|
            neg_q = bool(abs(int(k)) != abs(math.gcd(int(k), int(n))))
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]