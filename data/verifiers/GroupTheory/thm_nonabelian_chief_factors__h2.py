def is_semisimple(G):
    """
    A finite group is semisimple if it has no non-trivial abelian normal subgroups.
    Equivalently, for every non-identity element, its normal closure is non-abelian.
    """
    try:
        if G.order() == 1:
            return True
        
        elements = list(G.elements)
        id_el = G.identity
        checked = set([id_el])
        
        for x in elements:
            if x in checked:
                continue
                
            # The normal closure of x is generated by its conjugacy class.
            conjugates = set([x])
            queue = [x]
            while queue:
                curr = queue.pop(0)
                for g in G.generators:
                    conj = g * curr * ~g
                    if conj not in conjugates:
                        conjugates.add(conj)
                        queue.append(conj)
                        
            checked.update(conjugates)
            
            # The normal closure is abelian iff all its generators (the conjugacy class) commute.
            conjugates_list = list(conjugates)
            is_abelian = True
            for i in range(len(conjugates_list)):
                for j in range(i + 1, len(conjugates_list)):
                    if conjugates_list[i] * conjugates_list[j] != conjugates_list[j] * conjugates_list[i]:
                        is_abelian = False
                        break
                if not is_abelian:
                    break
                    
            if is_abelian:
                # Found a non-trivial abelian normal subgroup (the normal closure of x)
                return False
                
        return True
    except Exception:
        return False

def conditions(witness):
    try:
        G, M, N = witness
    except Exception:
        return [False, False]
        
    # H1: G is a semisimple finite group
    try:
        h1 = is_semisimple(G)
    except Exception:
        h1 = False
        
    # neg_Q: The quotient group N/M is abelian
    try:
        neg_q = True
        
        # Check N <= G
        for n in N.generators:
            if n.is_Identity:
                continue
            if n not in G:
                neg_q = False
                break
                
        # Check M <= N
        if neg_q:
            for m in M.generators:
                if m.is_Identity:
                    continue
                if m not in N:
                    neg_q = False
                    break
                    
        # Check M is normal in N
        if neg_q:
            for n in N.generators:
                for m in M.generators:
                    conj = n * m * ~n
                    if conj.is_Identity:
                        continue
                    if conj not in M:
                        neg_q = False
                        break
                if not neg_q:
                    break
                    
        # Check N/M is abelian (commutators of generators of N must be in M)
        if neg_q:
            for x in N.generators:
                for y in N.generators:
                    comm = x * y * ~x * ~y
                    if comm.is_Identity:
                        continue
                    if comm not in M:
                        neg_q = False
                        break
                if not neg_q:
                    break
    except Exception:
        neg_q = False
        
    return [h1, neg_q]

