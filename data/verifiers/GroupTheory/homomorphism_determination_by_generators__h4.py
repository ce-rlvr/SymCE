def apply_map(m, x):
    if callable(m):
        return m(x)
    return m[x]

def conditions(witness) -> list[bool]:
    try:
        G, H, S, f, g = witness
    except Exception:
        return [False, False, False, False]

    # H_1: G and H are groups
    try:
        h1 = isinstance(G, PermutationGroup) and isinstance(H, PermutationGroup)
    except Exception:
        h1 = False

    # H_2: S is a subset of G such that the subgroup generated by S is G
    try:
        s_in_G = all(s in G for s in S)
        if not S:
            h2 = s_in_G and G.order() == 1
        else:
            gen_G = PermutationGroup(*list(S))
            h2 = s_in_G and gen_G.order() == G.order()
    except Exception:
        h2 = False

    # H_3: f and g are group homomorphisms from G to H
    try:
        h3 = True
        if not h1:
            h3 = False
        else:
            elements = list(G.generate())
            for x in elements:
                fx = apply_map(f, x)
                gx = apply_map(g, x)
                if fx not in H or gx not in H:
                    h3 = False
                    break
                for y in elements:
                    fxy = apply_map(f, x * y)
                    gxy = apply_map(g, x * y)
                    fy = apply_map(f, y)
                    gy = apply_map(g, y)
                    if fxy != fx * fy:
                        h3 = False
                        break
                    if gxy != gx * gy:
                        h3 = False
                        break
                if not h3:
                    break
    except Exception:
        h3 = False

    # neg_Q: f(x) != g(x) for some x in G
    try:
        neg_q = False
        if h1:
            elements = list(G.generate())
            for x in elements:
                if apply_map(f, x) != apply_map(g, x):
                    neg_q = True
                    break
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

