def conditions(witness) -> list[bool]:
    try:
        G, H = witness
    except Exception:
        return [False, False, False, False]
    
    # H_1: G is a semisimple group
    # A finite group is semisimple if it has no non-trivial abelian normal subgroups.
    # Equivalently, the normal closure of any non-identity element is non-abelian.
    try:
        if not hasattr(G, 'generate'):
            h1 = False
        else:
            elements = list(G.generate())
            h1 = True
            for x in elements:
                if x.is_Identity:
                    continue
                # Generate the conjugacy class of x
                C = list({g * x * ~g for g in elements})
                # The normal closure is the subgroup generated by the conjugacy class
                N_x = PermutationGroup(*C)
                if N_x.is_abelian:
                    h1 = False
                    break
    except Exception:
        h1 = False

    # H_2: G is a non-trivial group
    try:
        h2 = G.order() > 1
    except Exception:
        h2 = False

    # H_3: H is a proper subgroup of G
    try:
        if H.order() >= G.order():
            h3 = False
        else:
            try:
                h3 = bool(H.is_subgroup(G))
            except Exception:
                # Fallback if is_subgroup fails
                h3 = all(g in G for g in H.generators)
    except Exception:
        h3 = False

    # neg_Q: The index of H in G is strictly greater than 4 (Conclusion FAILS -> index <= 4)
    try:
        if G.order() % H.order() != 0:
            neg_q = False
        else:
            index = G.order() // H.order()
            neg_q = bool(index <= 4)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

