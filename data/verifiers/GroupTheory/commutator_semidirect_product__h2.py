def conditions(witness):
    try:
        G, N, H = witness
    except Exception:
        return [False, False]
    
    # H_1: G is a group, N and H are subgroups of G
    try:
        if not (isinstance(G, PermutationGroup) and isinstance(N, PermutationGroup) and isinstance(H, PermutationGroup)):
            h1 = False
        else:
            h1 = all(g in G for g in N.generators) and all(g in G for g in H.generators)
    except Exception:
        h1 = False

    # neg_Q: G_prime != <N_prime, H_prime, commutator(N, H)>
    try:
        if not h1:
            neg_q = False
        elif G.order() > 2000 or N.order() > 500 or H.order() > 500:
            neg_q = False
        else:
            G_prime = G.derived_subgroup()
            N_prime = N.derived_subgroup()
            H_prime = H.derived_subgroup()
            
            commutators = []
            for n in N.generate():
                for h in H.generate():
                    commutators.append(~n * ~h * n * h)
            
            gens = list(N_prime.generators) + list(H_prime.generators) + commutators
            if not gens:
                is_equal = G_prime.is_trivial
            else:
                K = PermutationGroup(gens)
                # Check equality by mutual subgroup inclusion of generators
                is_equal = all(g in K for g in G_prime.generators) and all(g in G_prime for g in K.generators)
            
            neg_q = not is_equal
    except Exception:
        neg_q = False

    return [h1, neg_q]

