def conditions(witness) -> list[bool]:
    # H_1: The rank of F is at least 2.
    # For a group, rank >= 2 means it cannot be generated by a single element,
    # which is equivalent to saying the group is not cyclic.
    try:
        cyclic = witness.is_cyclic
        if callable(cyclic):
            cyclic = cyclic()
        h1_ok = bool(not cyclic)
    except Exception:
        h1_ok = False

    # ¬Q: F IS a nilpotent group.
    # The original conclusion is "F is not a nilpotent group", so it fails when F is nilpotent.
    try:
        nilpotent = witness.is_nilpotent
        if callable(nilpotent):
            nilpotent = nilpotent()
        neg_q_ok = bool(nilpotent)
    except Exception:
        neg_q_ok = False

    return [h1_ok, neg_q_ok]

