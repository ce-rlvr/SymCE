def conditions(witness) -> list[bool]:
    try:
        G, K, H = witness
    except Exception:
        return [False] * 5

    # H_1: G is a group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False

    # H_2: K is a subgroup of G
    try:
        h2 = bool(K.is_subgroup(G))
    except Exception:
        h2 = False

    # H_3: K contains H
    try:
        h3 = bool(all(g in K for g in H.generators))
    except Exception:
        h3 = False

    # H_4: H is a normal subgroup of K
    try:
        h4 = bool(H.is_normal(K))
    except Exception:
        h4 = False

    # ¬Q: K is not a subgroup of the normalizer N_G(H)
    try:
        # K is a subgroup of N_G(H) if K is a subgroup of G and K normalizes H.
        # N_G(H) = {g in G | g * H * g^-1 = H}.
        # Since K is generated by K.generators, we check if every generator of K normalizes H.
        if not K.is_subgroup(G):
            is_subgroup_normalizer = False
        else:
            is_subgroup_normalizer = True
            for k in K.generators:
                for h in H.generators:
                    if (k * h * ~k) not in H:
                        is_subgroup_normalizer = False
                        break
                if not is_subgroup_normalizer:
                    break
        neg_q = not is_subgroup_normalizer
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]

