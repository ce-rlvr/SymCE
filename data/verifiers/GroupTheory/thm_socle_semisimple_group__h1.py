def conditions(witness):
    try:
        if not isinstance(witness, PermutationGroup):
            return [False, False]
            
        elements = list(witness.generate())
        n = len(elements)
        if n == 1:
            # The trivial group is semisimple (no non-trivial abelian normal subgroups)
            # Its socle is itself. Thus the conclusion holds, so neg_Q is False.
            return [True, False]
            
        computed_for = set()
        N_g_unique = []
        gens = witness.generators
        
        # Find all normal closures of non-identity elements
        for g in elements:
            if g.is_Identity:
                continue
            if g in computed_for:
                continue
                
            # BFS to find the conjugacy class of g
            cls = set()
            queue = [g]
            cls.add(g)
            for curr in queue:
                for gen in gens:
                    conj1 = ~gen * curr * gen
                    if conj1 not in cls:
                        cls.add(conj1)
                        queue.append(conj1)
                    conj2 = gen * curr * ~gen
                    if conj2 not in cls:
                        cls.add(conj2)
                        queue.append(conj2)
            
            computed_for.update(cls)
            
            # The normal closure of g is the subgroup generated by its conjugacy class
            Ng = PermutationGroup(list(cls))
            Ng_elements = frozenset(Ng.generate())
            
            if Ng_elements not in N_g_unique:
                N_g_unique.append(Ng_elements)
                
        # H_1: G is a semisimple group
        # A finite group is semisimple iff it has no non-trivial abelian normal subgroups.
        # This is equivalent to saying no non-trivial normal subgroup is solvable.
        # Since any non-trivial normal subgroup contains the normal closure of at least one 
        # of its non-identity elements, G is semisimple iff no N_g is solvable.
        is_semisimple = True
        for Ng_elems in N_g_unique:
            Ng = PermutationGroup(list(Ng_elems))
            if Ng.is_solvable:
                is_semisimple = False
                break
                
        if not is_semisimple:
            return [False, False]
            
        # Find minimal normal subgroups
        # A normal subgroup in N_g_unique is minimal if it does not strictly contain another
        minimal_normals = []
        for Ng1 in N_g_unique:
            is_minimal = True
            for Ng2 in N_g_unique:
                if Ng1 != Ng2 and Ng2.issubset(Ng1):
                    is_minimal = False
                    break
            if is_minimal:
                minimal_normals.append(Ng1)
                
        # Compute the socle (subgroup generated by all minimal normal subgroups)
        socle_gens = set()
        for M in minimal_normals:
            socle_gens.update(M)
            
        if not socle_gens:
            socle_order = 1
        else:
            socle_group = PermutationGroup(list(socle_gens))
            socle_order = socle_group.order()
            
        # ¬Q: The socle of G is not equal to G
        neg_Q = (socle_order != n)
        
        return [True, neg_Q]
        
    except Exception:
        return [False, False]

