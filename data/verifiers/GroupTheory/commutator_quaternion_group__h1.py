def conditions(witness) -> list[bool]:
    try:
        G = witness
        
        # Calculate the commutator (derived) subgroup and the center
        D = G.derived_subgroup()
        Z = G.center()
        
        # Condition 1: G' == Z(G)
        # We check if they have the same order and if D is a subgroup of Z
        cond1 = (D.order() == Z.order() and all(Z.contains(g) for g in D.generators))
        
        # Condition 2: Z(G) has order 2
        cond2 = (Z.order() == 2)
        
        # Condition 3: Z(G) is the unique subgroup of order 2
        # A subgroup of order 2 is generated by a single element of order 2.
        # Thus, exactly one subgroup of order 2 means exactly one element of order 2 in the entire group.
        cond3 = (sum(1 for g in G.elements if g.order() == 2) == 1)
        
        # The conclusion holds if all conditions are met
        Q = cond1 and cond2 and cond3
        
        # We want the negated conclusion (True if the conclusion fails at the witness)
        neg_Q = not Q
    except Exception:
        neg_Q = False
        
    return [neg_Q]

