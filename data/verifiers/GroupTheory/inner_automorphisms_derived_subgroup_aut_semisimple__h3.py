def is_semisimple(G):
    elements = list(G.generate())
    if len(elements) == 1:
        return True
        
    seen = set()
    gens = G.generators
    for g in elements:
        if g in seen:
            continue
            
        # Compute conjugacy class of g
        c = set([g])
        queue = [g]
        while queue:
            curr = queue.pop(0)
            for gen in gens:
                conj = ~gen * curr * gen
                if conj not in c:
                    c.add(conj)
                    queue.append(conj)
        seen.update(c)
        
        if g == G.identity:
            continue
            
        # Check if the subgroup generated by this conjugacy class is abelian.
        # This is true iff all elements in the conjugacy class commute with each other.
        c_list = list(c)
        is_ab = True
        for i in range(len(c_list)):
            for j in range(i + 1, len(c_list)):
                if c_list[i] * c_list[j] != c_list[j] * c_list[i]:
                    is_ab = False
                    break
            if not is_ab:
                break
                
        if is_ab:
            # Found a non-trivial abelian normal subgroup
            return False
            
    return True

def check_conclusion(G):
    elements = list(G.generate())
    n = len(elements)
    if n == 1:
        return True
        
    elem_to_idx = {e: i for i, e in enumerate(elements)}
    
    gens = G.generators
    gen_indices = [elem_to_idx[g] for g in gens]
    
    # Precompute multiplication table for fast lookups
    mult_table = [[0] * n for _ in range(n)]
    for i in range(n):
        for j in range(n):
            mult_table[i][j] = elem_to_idx[elements[i] * elements[j]]
            
    # Find possible images for each generator (must preserve order)
    possible_images = []
    for g in gens:
        o = g.order()
        possible_images.append([i for i, e in enumerate(elements) if e.order() == o])
        
    automorphisms = []
    for img_indices in itertools.product(*possible_images):
        mapping = [-1] * n
        id_idx = elem_to_idx[G.identity]
        mapping[id_idx] = id_idx
        
        queue = [id_idx]
        head = 0
        is_valid = True
        
        # BFS to build the homomorphism
        while head < len(queue):
            curr = queue[head]
            head += 1
            
            curr_img = mapping[curr]
            
            for k, g_idx in enumerate(gen_indices):
                nxt = mult_table[curr][g_idx]
                nxt_img = mult_table[curr_img][img_indices[k]]
                
                if mapping[nxt] == -1:
                    mapping[nxt] = nxt_img
                    queue.append(nxt)
                elif mapping[nxt] != nxt_img:
                    is_valid = False
                    break
            if not is_valid:
                break
                
        # If valid and bijective, it's an automorphism
        if is_valid and len(queue) == n:
            if len(set(mapping)) == n:
                automorphisms.append(mapping)
                
    aut_perms = [Permutation(mapping) for mapping in automorphisms]
    AutG = PermutationGroup(aut_perms)
    AutG_derived = AutG.derived_subgroup()
    
    # Construct the inner automorphism group Inn(G)
    inn_perms = []
    for g_idx in range(n):
        mapping = [-1] * n
        g_inv_idx = elem_to_idx[~elements[g_idx]]
        for x_idx in range(n):
            gx = mult_table[g_idx][x_idx]
            conj = mult_table[gx][g_inv_idx]
            mapping[x_idx] = conj
        inn_perms.append(Permutation(mapping))
        
    InnG = PermutationGroup(inn_perms)
    
    # Check if Inn(G) is a subgroup of Aut(G)'
    for gen in InnG.generators:
        if not AutG_derived.contains(gen):
            return False
    return True

def conditions(witness):
    try:
        h1 = isinstance(witness, PermutationGroup)
    except Exception:
        h1 = False

    try:
        h2 = is_semisimple(witness)
    except Exception:
        h2 = False

    try:
        h3 = isinstance(witness, PermutationGroup)
    except Exception:
        h3 = False

    try:
        neg_q = not check_conclusion(witness)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

