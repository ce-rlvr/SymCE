def generates(subset, order, id_G):
    if not subset:
        return order == 1
    visited = {id_G}
    queue = [id_G]
    head = 0
    while head < len(queue):
        u = queue[head]
        head += 1
        for g in subset:
            v = u * g
            if v not in visited:
                visited.add(v)
                queue.append(v)
                if len(visited) == order:
                    return True
    return len(visited) == order

def can_be_generated_by(G, n):
    if not hasattr(G, 'generators'):
        return False
    if len(G.generators) <= n:
        return True
        
    try:
        if not hasattr(G, 'order'):
            return False
        if G.order() >= float('inf'):
            return False
        elements = list(G.generate())
        order = G.order()
        id_G = G.generators[0]**0
    except Exception:
        return False
        
    for subset in itertools.combinations(elements, n):
        if generates(subset, order, id_G):
            return True
    return False

def exists_surjective_homomorphism(F, G):
    if type(F).__name__ == 'FreeGroup':
        return can_be_generated_by(G, len(F.generators))
        
    if not hasattr(F, 'order') or not hasattr(G, 'order'):
        return False
        
    try:
        if F.order() >= float('inf') or G.order() >= float('inf'):
            return False
        if F.order() < G.order():
            return False
    except Exception:
        return False
        
    try:
        if not F.generators:
            return G.order() == 1
    except Exception:
        pass
    
    try:
        id_F = F.generators[0]**0
        id_G = G.generators[0]**0
    except Exception:
        return False

    try:
        gens_F = F.generators
        elements_G = list(G.generate())
    except Exception:
        return False
    
    for target_tuple in itertools.product(elements_G, repeat=len(gens_F)):
        gen_mapping = dict(zip(gens_F, target_tuple))
        
        mapping = {id_F: id_G}
        queue = [id_F]
        is_homo = True
        
        head = 0
        while head < len(queue):
            u = queue[head]
            head += 1
            for g in gens_F:
                v = u * g
                val = mapping[u] * gen_mapping[g]
                if v in mapping:
                    if mapping[v] != val:
                        is_homo = False
                        break
                else:
                    mapping[v] = val
                    queue.append(v)
            if not is_homo:
                break
                
        if is_homo:
            if len(set(mapping.values())) == G.order():
                return True
                
    return False

def conditions(witness) -> list[bool]:
    if isinstance(witness, dict):
        F = witness.get('F')
        n = witness.get('n')
        G = witness.get('G')
    else:
        try:
            F, n, G = witness
        except Exception:
            return [False, False, False, False]

    # H_1: n is a positive integer
    try:
        h1 = isinstance(n, int) and n > 0
    except Exception:
        h1 = False

    # H_2: G is a finite group
    try:
        h2 = hasattr(G, 'is_group') and G.is_group and hasattr(G, 'order') and G.order() < float('inf')
    except Exception:
        h2 = False

    # H_3: G can be generated by a set of n or fewer elements
    try:
        h3 = can_be_generated_by(G, n)
    except Exception:
        h3 = False

    # neg_Q: There does NOT exist a surjective group homomorphism from F onto G
    try:
        neg_q = not exists_surjective_homomorphism(F, G)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

