def conditions(witness) -> list[bool]:
    try:
        G, S = witness
    except Exception:
        try:
            G = witness.G
            S = witness.S
        except Exception:
            return [False, False, False, False]

    # H1: S is a finite subset of G
    try:
        h1 = False
        S_list = []
        is_finite = True
        for i, s in enumerate(S):
            if i > 10000:
                is_finite = False
                break
            S_list.append(s)
        
        if is_finite:
            all_in_G = True
            for s in S_list:
                if s not in G:
                    all_in_G = False
                    break
            h1 = all_in_G
    except Exception:
        h1 = False

    # H2: Every element of S has finite order
    try:
        h2 = True
        for s in S_list:
            try:
                ord_s = s.order()
            except AttributeError:
                if hasattr(s, 'is_Matrix') and s.is_Matrix:
                    current = s
                    ord_s = 1
                    I = eye(s.shape[0])
                    while current != I and ord_s < 1000:
                        current = current * s
                        ord_s += 1
                    if current != I:
                        ord_s = oo
                else:
                    raise
            if ord_s == oo or ord_s == 0:
                h2 = False
                break
    except Exception:
        h2 = False

    # H3: S is invariant under conjugation by all elements of G
    try:
        h3 = True
        if hasattr(G, 'generators'):
            gens = G.generators
            for g in gens:
                g_inv = g**-1
                for s in S_list:
                    if (g * s * g_inv) not in S_list:
                        h3 = False
                        break
                    if (g_inv * s * g) not in S_list:
                        h3 = False
                        break
                if not h3:
                    break
        else:
            count = 0
            for g in G:
                if count > 1000:
                    break
                count += 1
                try:
                    g_inv = g**-1
                except Exception:
                    g_inv = g.inverse()
                for s in S_list:
                    if (g * s * g_inv) not in S_list:
                        h3 = False
                        break
                if not h3:
                    break
    except Exception:
        h3 = False

    # neg_Q: The subgroup generated by S is NOT a finite normal subgroup of G
    try:
        neg_q = False
        if not S_list:
            neg_q = False
        elif hasattr(G, 'is_finite_normal_subgroup'):
            neg_q = not G.is_finite_normal_subgroup(S_list)
        elif hasattr(witness, 'is_finite_normal_subgroup'):
            neg_q = not witness.is_finite_normal_subgroup(G, S_list)
        elif isinstance(G, PermutationGroup):
            H = PermutationGroup(S_list)
            is_normal = True
            for h in H.generators:
                for g in G.generators:
                    if not H.contains(g * h * g**-1):
                        is_normal = False
                        break
                if not is_normal:
                    break
            neg_q = not is_normal
        else:
            if hasattr(G, 'generators'):
                gens = set(G.generators)
                S_set = set(S_list)
                generates_G = True
                for g in gens:
                    if g not in S_set and g**-1 not in S_set:
                        generates_G = False
                        break
                if generates_G:
                    if G.order() == oo:
                        neg_q = True
                    else:
                        neg_q = False
                else:
                    neg_q = False
            else:
                neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

