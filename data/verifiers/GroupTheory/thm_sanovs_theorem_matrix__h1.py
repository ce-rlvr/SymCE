def conditions(witness):
    try:
        if isinstance(witness, dict):
            G = witness.get('G', [])
            A = witness.get('A', None)
            B = witness.get('B', None)
            H = witness.get('H', [])
        elif isinstance(witness, tuple) and len(witness) == 4:
            G, A, B, H = witness
        else:
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]

    def is_A(m):
        try:
            if hasattr(m, 'tolist'):
                m = m.tolist()
            if isinstance(m, (list, tuple)) and len(m) == 2 and isinstance(m[0], (list, tuple)):
                flat = [m[0][0], m[0][1], m[1][0], m[1][1]]
            else:
                flat = list(m)
            return [int(x) for x in flat] == [1, 2, 0, 1]
        except Exception:
            return False

    def is_B(m):
        try:
            if hasattr(m, 'tolist'):
                m = m.tolist()
            if isinstance(m, (list, tuple)) and len(m) == 2 and isinstance(m[0], (list, tuple)):
                flat = [m[0][0], m[0][1], m[1][0], m[1][1]]
            else:
                flat = list(m)
            return [int(x) for x in flat] == [1, 0, 2, 1]
        except Exception:
            return False

    h1, h2, h3, neg_q = False, False, False, False

    try:
        if A is not None:
            in_G = False
            try:
                if hasattr(G, '__iter__'):
                    in_G = any(is_A(m) for m in G)
                else:
                    in_G = A in G
            except Exception:
                in_G = False
            h1 = is_A(A) and in_G
        else:
            h1 = any(is_A(m) for m in G)
            if h1:
                A = next(m for m in G if is_A(m))
    except Exception:
        h1 = False

    try:
        if B is not None:
            in_G = False
            try:
                if hasattr(G, '__iter__'):
                    in_G = any(is_B(m) for m in G)
                else:
                    in_G = B in G
            except Exception:
                in_G = False
            h2 = is_B(B) and in_G
        else:
            h2 = any(is_B(m) for m in G)
            if h2:
                B = next(m for m in G if is_B(m))
    except Exception:
        h2 = False

    try:
        if h1 and h2:
            A_imm = ImmutableMatrix(A)
            B_imm = ImmutableMatrix(B)
            H_imm = set()
            for m in H:
                try:
                    H_imm.add(ImmutableMatrix(m))
                except Exception:
                    pass
            
            if hasattr(G, '__iter__'):
                G_imm = set()
                for m in G:
                    try:
                        G_imm.add(ImmutableMatrix(m))
                    except Exception:
                        pass
                is_subset = H_imm.issubset(G_imm)
            else:
                is_subset = True
            
            if A_imm in H_imm and B_imm in H_imm and is_subset:
                possible_ns = [0] + list(range(2, 100))
                for n in possible_ns:
                    try:
                        def mul(x, y, mod=n):
                            res = x * y
                            if mod > 0:
                                return ImmutableMatrix(2, 2, [v % mod for v in res])
                            return ImmutableMatrix(res)
                        
                        if mul(A_imm, B_imm) not in H_imm:
                            continue
                            
                        generated = {A_imm, B_imm}
                        queue = [A_imm, B_imm]
                        valid = True
                        
                        while queue:
                            curr = queue.pop(0)
                            for gen in (A_imm, B_imm):
                                nxt = mul(curr, gen)
                                if nxt not in generated:
                                    if nxt not in H_imm:
                                        valid = False
                                        break
                                    generated.add(nxt)
                                    queue.append(nxt)
                            if not valid or len(generated) > len(H_imm):
                                break
                                
                        if valid and len(generated) == len(H_imm):
                            h3 = True
                            break
                    except Exception:
                        pass
    except Exception:
        pass

    try:
        if h3:
            neg_q = True
    except Exception:
        pass

    return [h1, h2, h3, neg_q]