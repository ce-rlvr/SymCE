def conditions(witness) -> list[bool]:
    # Parse witness: can be (G, a, b) or just (a, b)
    try:
        if isinstance(witness, tuple):
            if len(witness) == 3:
                G, a, b = witness
            elif len(witness) == 2:
                a, b = witness
                G = PermutationGroup([a, b])
            else:
                return [False] * 6
        else:
            return [False] * 6
    except Exception:
        return [False] * 6

    # H_1: G is a group
    try:
        h1 = isinstance(G, PermutationGroup) or (hasattr(G, 'is_group') and bool(G.is_group))
    except Exception:
        h1 = False

    # H_2: a and b are elements of G
    try:
        if hasattr(G, 'contains'):
            h2 = bool(G.contains(a) and G.contains(b))
        elif hasattr(G, '__contains__'):
            h2 = bool(a in G and b in G)
        else:
            h2 = False
    except Exception:
        h2 = False

    # H_3: a and b commute (ab = ba)
    try:
        h3 = bool(a * b == b * a)
    except Exception:
        h3 = False

    # H_4: The order of a is a finite integer m
    m = None
    try:
        if hasattr(a, 'order'):
            m = a.order() if callable(a.order) else a.order
            h4 = (isinstance(m, int) or (hasattr(m, 'is_integer') and m.is_integer)) and m > 0
        else:
            h4 = False
    except Exception:
        h4 = False

    # H_5: The order of b is a finite integer n
    n = None
    try:
        if hasattr(b, 'order'):
            n = b.order() if callable(b.order) else b.order
            h5 = (isinstance(n, int) or (hasattr(n, 'is_integer') and n.is_integer)) and n > 0
        else:
            h5 = False
    except Exception:
        h5 = False

    # ¬Q: The order of the product ab is not mn
    try:
        if h4 and h5:
            ab = a * b
            if hasattr(ab, 'order'):
                order_ab = ab.order() if callable(ab.order) else ab.order
                neg_q = bool(order_ab != m * n)
            else:
                neg_q = False
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, h5, neg_q]

