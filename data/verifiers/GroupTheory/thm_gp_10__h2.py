def conditions(witness) -> list[bool]:
    # Hypothesis 1: witness is a group with a presentation (FpGroup in sympy)
    try:
        H1 = isinstance(witness, FpGroup)
    except Exception:
        H1 = False

    # Conclusion: The abelianization G^{ab} is isomorphic to the group defined by the presentation 
    # < X | R \cup {x^{-1}y^{-1}xy | x,y \in X} >
    try:
        if not H1:
            neg_Q = False
        else:
            F = witness.free_group
            rels = list(witness.relators)
            
            # Add the commutators x^{-1} y^{-1} x y for all x, y in X
            for x in F.generators:
                for y in F.generators:
                    comm = x**-1 * y**-1 * x * y
                    rels.append(comm)
            
            G_new = FpGroup(F, rels)
            
            # The abelianization of G is given by its abelian invariants.
            # Since G_new is generated by mutually commuting elements, it is abelian,
            # so its abelian invariants completely determine it up to isomorphism.
            inv_G = witness.abelian_invariants()
            inv_G_new = G_new.abelian_invariants()
            
            # Check if they are isomorphic
            is_isomorphic = sorted(inv_G) == sorted(inv_G_new)
            
            # neg_Q is True if the conclusion FAILS
            neg_Q = not is_isomorphic
    except Exception:
        neg_Q = False

    return [H1, neg_Q]

