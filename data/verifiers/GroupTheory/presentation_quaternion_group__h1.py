def get_G(witness):
    if isinstance(witness, tuple) and len(witness) == 3:
        return witness[0]
    elif isinstance(witness, (list, tuple)) and len(witness) == 2 and isinstance(witness[0], Permutation):
        return PermutationGroup(list(witness))
    else:
        return witness

def check_h1(witness):
    try:
        if isinstance(witness, tuple) and len(witness) == 3:
            G, a, b = witness
            if not isinstance(G, PermutationGroup):
                return False
            if G.order() > 8:
                return False
            if a not in G or b not in G:
                return False
            if PermutationGroup([a, b]).order() != G.order():
                return False
            if (a**4).is_Identity and a**2 == b**2 and ~b * a * b == ~a:
                return True
            return False
        elif isinstance(witness, (list, tuple)) and len(witness) == 2 and isinstance(witness[0], Permutation):
            a, b = witness
            G = PermutationGroup([a, b])
            if G.order() > 8:
                return False
            if (a**4).is_Identity and a**2 == b**2 and ~b * a * b == ~a:
                return True
            return False
        else:
            G = witness
            if not isinstance(G, PermutationGroup):
                return False
            if G.order() > 8:
                return False
            elements = list(G.generate())
            for a in elements:
                for b in elements:
                    if (a**4).is_Identity and a**2 == b**2 and ~b * a * b == ~a:
                        if PermutationGroup([a, b]).order() == G.order():
                            return True
            return False
    except Exception:
        return False

def is_isomorphic_to_Q8(G):
    try:
        if not isinstance(G, PermutationGroup):
            return False
        if G.order() != 8:
            return False
        if G.is_abelian:
            return False
        elements = list(G.generate())
        order_2_count = sum(1 for x in elements if x.order() == 2)
        return order_2_count == 1
    except Exception:
        return False

def conditions(witness):
    h1 = check_h1(witness)
    
    try:
        G = get_G(witness)
        q = is_isomorphic_to_Q8(G)
        neg_q = not q
    except Exception:
        neg_q = True
        
    return [h1, neg_q]

