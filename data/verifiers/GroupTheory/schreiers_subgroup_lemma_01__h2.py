def conditions(witness) -> list[bool]:
    """
    Check if the witness satisfies the remaining hypotheses and falsifies the conclusion.
    Witness is expected to be a tuple: (G, S, H, T)
    where:
      G is a PermutationGroup
      S is a list/set of generators (Permutations)
      H is a list/set of elements in G (subset, not necessarily a subgroup)
      T is a list/set of elements in G (right transversal)
    """
    try:
        G, S, H, T = witness
    except Exception:
        return [False, False, False, False]

    # Extract the identity element of G safely
    try:
        gens = list(G.generators)
        if gens:
            iden = gens[0] ** 0
        else:
            iden = Permutation()
    except Exception:
        return [False, False, False, False]

    # H_1: G is a group generated by a subset S
    try:
        if not S:
            S_group = PermutationGroup([iden])
        else:
            S_group = PermutationGroup(list(S))
            
        h1 = isinstance(G, PermutationGroup) and \
             all(s in G for s in S) and \
             S_group.order() == G.order()
    except Exception:
        h1 = False

    # H_2: T is a right transversal for H in G
    try:
        if not all(h in G for h in H) or not all(t in G for t in T):
            h2 = False
        else:
            products = set()
            for h in H:
                for t in T:
                    products.add(h * t)
            # T is a right transversal for H iff the products h*t uniquely cover G
            h2 = (len(products) == G.order()) and (len(H) * len(T) == G.order())
    except Exception:
        h2 = False

    # H_3: The representative of the coset H in T is the identity element of G
    try:
        h3 = iden in T
    except Exception:
        h3 = False

    # ¬Q: H is NOT generated by the set { t * s * (\overline{t * s})^{-1} | t \in T, s \in S }
    try:
        X = set()
        rep = {}
        # Precompute the representative mapping: g -> t_prime
        for h in H:
            for t in T:
                rep[h * t] = t
                
        for t in T:
            for s in S:
                x = t * s
                if x not in rep:
                    raise ValueError("x not in rep mapping; T is not a transversal")
                t_prime = rep[x]
                # gen_element = t * s * (\overline{t * s})^{-1}
                gen_element = x * (~t_prime)
                X.add(gen_element)
                
        if not X:
            H_group_elements = {iden}
        else:
            H_group = PermutationGroup(list(X))
            H_group_elements = set(H_group.generate())
            
        H_set = set(H)
        # The conclusion fails if the generated group does not exactly equal the set H
        neg_q = (H_group_elements != H_set)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

