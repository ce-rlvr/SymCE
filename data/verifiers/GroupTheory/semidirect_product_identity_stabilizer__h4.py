def conditions(witness):
    try:
        if isinstance(witness, dict):
            G = witness.get('G')
            N = witness.get('N')
            H = witness.get('H')
        elif hasattr(witness, 'G') and hasattr(witness, 'N') and hasattr(witness, 'H'):
            G = witness.G
            N = witness.N
            H = witness.H
        else:
            G, N, H = witness
    except Exception:
        return [False, False, False, False]

    # H1: N and H are groups
    try:
        h1 = hasattr(N, 'elements') and hasattr(H, 'elements') and hasattr(N, 'identity') and hasattr(H, 'identity')
    except Exception:
        h1 = False

    # H2: G = N \rtimes H is the semidirect product of N and H
    try:
        # Check N is normal in G
        is_normal = True
        for g in G.elements:
            for n in N.elements:
                if g * n * g**-1 not in N.elements:
                    is_normal = False
                    break
            if not is_normal:
                break
        
        # Check intersection is trivial
        n_elements = list(N.elements)
        h_elements = list(H.elements)
        intersection = [x for x in n_elements if x in h_elements]
        is_trivial_int = len(intersection) == 1 and intersection[0] == G.identity
        
        # Check G is generated by N and H (since G = NH, sizes must match)
        is_semidirect = is_normal and is_trivial_int and len(list(G.elements)) == len(n_elements) * len(h_elements)
        h2 = bool(is_semidirect)
    except Exception:
        h2 = False

    # H3: G acts on N via the action (n, h) \cdot x = n h x h^{-1}
    try:
        def decompose(g):
            for n in N.elements:
                for h in H.elements:
                    if n * h == g:
                        return n, h
            return None, None

        def action(g, x):
            n, h = decompose(g)
            if n is None: return None
            return n * h * x * h**-1

        is_action = True
        for x in N.elements:
            if action(G.identity, x) != x:
                is_action = False
                break
            for g1 in G.elements:
                for g2 in G.elements:
                    act2 = action(g2, x)
                    if act2 not in N.elements:
                        is_action = False
                        break
                    act12 = action(g1, act2)
                    act_comp = action(g1 * g2, x)
                    if act12 != act_comp:
                        is_action = False
                        break
                if not is_action: break
            if not is_action: break
        h3 = bool(is_action)
    except Exception:
        h3 = False

    # Conclusion: The stabilizer of e_N under this action is exactly the subgroup H of G
    try:
        stabilizer = []
        e_N = N.identity
        for g in G.elements:
            if action(g, e_N) == e_N:
                stabilizer.append(g)
        
        # Check if stabilizer is exactly H
        is_exact = len(stabilizer) == len(list(H.elements)) and all(h in stabilizer for h in H.elements)
        neg_Q = not is_exact
    except Exception:
        neg_Q = False

    return [h1, h2, h3, neg_Q]

