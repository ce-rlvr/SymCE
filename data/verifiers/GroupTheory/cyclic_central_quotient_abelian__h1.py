CONDITION_LABELS = [
    "H_1: Z(G) is the center of G",
    "H_2: The quotient group G/Z(G) is a cyclic group",
    "¬Q: G is not an abelian group"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    try:
        # H_1: Z(G) is the center of G
        # We verify that the witness is a valid group object that can compute its center.
        if not hasattr(witness, 'center') or not hasattr(witness, 'elements'):
            return [False, False, False]
        h1_ok = True
    except Exception:
        h1_ok = False

    try:
        # H_2: The quotient group G/Z(G) is a cyclic group
        # G/Z(G) is cyclic iff there exists g in G such that G is generated by g and Z(G).
        Z_elements = witness.center()
        Z_order = len(Z_elements)
        target_order = witness.order()
        
        if Z_order == target_order:
            # If G is abelian, Z(G) = G, so G/Z(G) is the trivial group (which is cyclic)
            h2_ok = True
        else:
            Z_group = PermutationGroup(Z_elements)
            Z_gens = Z_group.generators
            h2_ok = False
            target_quotient_order = target_order // Z_order
            
            for g in witness.elements:
                # Optimization: the order of gZ in G/Z divides the order of g in G.
                # For gZ to generate G/Z, its order must be exactly target_quotient_order.
                if g.order() % target_quotient_order == 0:
                    H = PermutationGroup([g] + Z_gens)
                    if H.order() == target_order:
                        h2_ok = True
                        break
    except Exception:
        h2_ok = False

    try:
        # ¬Q: G is not an abelian group
        neg_q = not witness.is_abelian
    except Exception:
        neg_q = False

    return [h1_ok, h2_ok, neg_q]