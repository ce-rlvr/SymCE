def is_semisimple(G):
    """
    A finite group is semisimple if it has no non-trivial abelian normal subgroups
    (equivalently, its solvable radical is trivial).
    """
    try:
        if not isinstance(G, PermutationGroup):
            return False
        if G.order() == 1:
            return True
        for H in G.normal_subgroups():
            if H.order() == 1:
                continue
            if H.is_abelian:
                return False
        return True
    except Exception:
        return False

def groups_equal(G1, G2):
    """Check if two permutation groups are equal by comparing orders and generators."""
    if G1.order() != G2.order():
        return False
    return all(g in G2 for g in G1.generators)

def get_socle(G):
    """
    Returns the socle of G, which is the subgroup generated by all minimal normal subgroups.
    For a semisimple group, the socle is a direct product of non-abelian simple groups.
    """
    normals = G.normal_subgroups()
    minimals = []
    for N in normals:
        if N.order() == 1:
            continue
        is_min = True
        for M in normals:
            if M.order() == 1 or M.order() >= N.order():
                continue
            if all(g in N for g in M.generators):
                is_min = False
                break
        if is_min:
            minimals.append(N)
    
    if not minimals:
        return G
        
    gens = []
    for N in minimals:
        gens.extend(N.generators)
        
    return PermutationGroup(gens)

def conclusion_holds(G):
    """
    The conclusion implicitly requires G to be a direct product of non-abelian simple groups
    so that the simple components S_i and their multiplicities k_i are well-defined.
    A semisimple group is a direct product of non-abelian simple groups iff it equals its socle.
    """
    try:
        Soc = get_socle(G)
        return groups_equal(G, Soc)
    except Exception:
        return False

def conditions(witness):
    H1 = is_semisimple(witness)
    neg_Q = not conclusion_holds(witness)
    return [H1, neg_Q]

