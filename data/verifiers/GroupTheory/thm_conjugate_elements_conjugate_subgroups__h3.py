def conditions(witness) -> list[bool]:
    try:
        G, x, y = witness
    except Exception:
        return [False, False, False]
    
    try:
        h1_ok = isinstance(G, PermutationGroup)
    except Exception:
        h1_ok = False
        
    try:
        h2_ok = isinstance(x, Permutation) and isinstance(y, Permutation) and (x in G) and (y in G)
    except Exception:
        h2_ok = False
        
    try:
        if not (h1_ok and h2_ok):
            neg_q_ok = False
        else:
            def get_cyclic_subgroup(p):
                H = set()
                curr = p
                while curr not in H:
                    H.add(curr)
                    curr = curr * p
                return H
            
            H_x = get_cyclic_subgroup(x)
            H_y = get_cyclic_subgroup(y)
            
            if len(H_x) != len(H_y):
                neg_q_ok = True
            else:
                is_conjugate = False
                for g in G.generate():
                    conj_H_x = {g * h * ~g for h in H_x}
                    if conj_H_x == H_y:
                        is_conjugate = True
                        break
                neg_q_ok = not is_conjugate
    except Exception:
        neg_q_ok = False
        
    return [h1_ok, h2_ok, neg_q_ok]

