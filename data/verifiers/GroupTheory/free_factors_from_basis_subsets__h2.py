CONDITION_LABELS = [
    "H_1: F is a free group",
    "H_2: Y is a subset of X",
    "H_3: H is the subgroup of F generated by Y",
    "¬Q: H is not a free factor of F, or Y does not freely generate H"
]

N_HYP = 3
NEG_Q_INDEX = 3

def conditions(witness):
    """
    Given a witness, which is expected to be a tuple (F, X, Y) or (F, X, Y, H),
    evaluates the remaining hypotheses and the negated conclusion.
    """
    
    # H_1: F is a free group
    try:
        F = witness[0]
        h1 = type(F).__name__ == 'FreeGroup'
    except Exception:
        h1 = False

    # H_2: Y is a subset of X
    try:
        F = witness[0]
        X = witness[1]
        Y = witness[2]
        X_list = list(X)
        Y_list = list(Y)
        # Check that Y is a subset of X, and X consists of elements of F
        h2 = all(y in X_list for y in Y_list) and all(hasattr(x, 'group') and x.group == F for x in X_list)
    except Exception:
        h2 = False

    # H_3: H is the subgroup of F generated by Y
    try:
        F = witness[0]
        Y = witness[2]
        Y_list = list(Y)
        # We verify that Y consists of valid elements of F. 
        # The subgroup H is implicitly defined by Y.
        h3 = all(hasattr(y, 'group') and y.group == F for y in Y_list)
    except Exception:
        h3 = False

    # neg_Q: H is not a free factor of F, or Y does not freely generate H
    try:
        F = witness[0]
        Y = witness[2]
        Y_list = list(Y)
        
        if not Y_list:
            # The empty set freely generates the trivial subgroup, which is a free factor.
            # Thus the conclusion holds, so neg_Q is False.
            neg_q = False
        else:
            n = len(F.generators)
            m = len(Y_list)
            
            if m > n:
                # Rank of H exceeds rank of F, so it cannot be a free factor.
                neg_q = True
            else:
                # Abelianization test: if H is a free factor freely generated by Y, 
                # the abelianization of Y must form a direct summand of F_ab.
                # This means the GCD of all m x m minors of the abelianization matrix must be 1.
                M = []
                for y in Y_list:
                    vec = [0] * n
                    for sym, exp in y.array_form:
                        idx = F.symbols.index(sym)
                        vec[idx] += exp
                    M.append(vec)
                
                mat = Matrix(M)
                minors = []
                
                for cols in itertools.combinations(range(n), m):
                    submat = mat[:, cols]
                    minors.append(abs(submat.det()))
                
                gcd_val = 0
                for minor in minors:
                    gcd_val = math.gcd(gcd_val, int(minor))
                    if gcd_val == 1:
                        break
                
                if gcd_val != 1:
                    # Fails the abelianization test: definitely not a free factor 
                    # or Y does not freely generate H.
                    neg_q = True
                else:
                    # Passes the abelianization test.
                    # While this is only a necessary condition for being a free factor,
                    # it is sufficient to catch standard counterexamples (e.g. Y = {x^2}).
                    neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]