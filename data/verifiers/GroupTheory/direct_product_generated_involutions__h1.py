def is_generated_by_involutions(grp):
    involutions = []
    for g in grp.generate():
        if g.order() == 2:
            involutions.append(g)
    if not involutions:
        return grp.order() == 1
    subgrp = PermutationGroup(involutions)
    return subgrp.order() == grp.order()

def direct_product(G, H):
    degG = G.degree
    degH = H.degree
    gens = []
    for g in G.generators:
        p = [g(i) for i in range(degG)] + list(range(degG, degG + degH))
        gens.append(Permutation(p))
    for h in H.generators:
        p = list(range(degG)) + [h(i) + degG for i in range(degH)]
        gens.append(Permutation(p))
    if not gens:
        return PermutationGroup([Permutation(degG + degH - 1)])
    return PermutationGroup(gens)

def conditions(witness):
    """
    Checks if the witness satisfies the hypotheses and fails the conclusion.
    The witness should be a tuple of two PermutationGroup objects: (G, H).
    """
    try:
        G, H = witness
    except Exception:
        return [False, False, False]
    
    try:
        h1_ok = is_generated_by_involutions(G)
    except Exception:
        h1_ok = False

    try:
        h2_ok = is_generated_by_involutions(H)
    except Exception:
        h2_ok = False

    try:
        GxH = direct_product(G, H)
        q = is_generated_by_involutions(GxH)
        neg_q_ok = not q
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, neg_q_ok]

