CONDITION_LABELS = [
    "H_1: F is a free group of rank at least 2",
    "H_2: g is a non-identity element of F",
    "¬Q: N is finitely generated"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness):
    try:
        if isinstance(witness, dict):
            F = witness.get('F')
            g = witness.get('g')
            # If N is not provided, default to the subgroup generated by g
            N = witness.get('N', [g])
        elif isinstance(witness, (list, tuple)):
            if len(witness) == 3:
                F, g, N = witness
            elif len(witness) == 2:
                F, g = witness
                N = [g]
            else:
                return [False, False, False]
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H1: F is a free group of rank at least 2
    try:
        h1 = type(F).__name__ == 'FreeGroup' and len(F.generators) >= 2
    except Exception:
        h1 = False

    # H2: g is a non-identity element of F
    try:
        h2 = (g in F) and (g != F.identity)
    except Exception:
        h2 = False

    # neg_Q: N is finitely generated
    try:
        if type(N).__name__ == 'FgpSubgroup':
            neg_q = (N.parent == F)
        elif type(N).__name__ == 'FreeGroup':
            neg_q = (N == F) and len(N.generators) < float('inf')
        elif isinstance(N, (list, tuple, set)):
            neg_q = all(x in F for x in N)
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]