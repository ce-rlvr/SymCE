def conditions(witness):
    """
    Check if the witness is a counterexample to the conjecture.
    The conjecture states that S_n is generated by adjacent transpositions.
    This is true for finite n, but false for infinite n (where it only generates 
    the finitary symmetric group, a proper subgroup of the full symmetric group).
    """
    try:
        # Check if witness represents infinity
        is_inf = False
        if witness == sympy.oo:
            is_inf = True
        elif isinstance(witness, str) and witness.lower() in ['infinity', 'oo', 'aleph_0', 'infty', 'inf']:
            is_inf = True
        elif isinstance(witness, tuple):
            for w in witness:
                if w == sympy.oo or (isinstance(w, str) and w.lower() in ['infinity', 'oo', 'aleph_0', 'infty', 'inf']):
                    is_inf = True
                    break
        
        if is_inf:
            return [True, True]
            
        # If not infinity, try to parse as an integer
        n = None
        if isinstance(witness, tuple):
            for w in witness:
                try:
                    n = int(w)
                    break
                except Exception:
                    continue
        else:
            n = int(witness)
            
        if n is None:
            return [False, False]
            
        h1 = n >= 1
        
        if n <= 1:
            neg_q = False
        elif n > 50:
            # For any finite n, S_n is generated by adjacent transpositions.
            # We bypass the computation to avoid timeout for large n.
            neg_q = False
        else:
            # SymPy uses 0-based indexing for permutations
            gens = [Permutation(i, i+1, size=n) for i in range(n-1)]
            G = PermutationGroup(*gens)
            neg_q = G.order() != math.factorial(n)
            
        return [bool(h1), bool(neg_q)]
    except Exception:
        return [False, False]

