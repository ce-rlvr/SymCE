def pad_perm(p, degree):
    """Pad a permutation to a given degree to avoid size mismatch errors."""
    if p.size < degree:
        return Permutation(p.array_form + list(range(p.size, degree)))
    return p

def is_subgroup(G, H):
    try:
        degree = max(G.degree, H.degree)
        H_padded = PermutationGroup([pad_perm(h, degree) for h in H.generators])
        for g in G.generators:
            if not H_padded.contains(pad_perm(g, degree)):
                return False
        return True
    except Exception:
        return False

def is_normal(G, H):
    try:
        degree = max(G.degree, H.degree)
        G_padded = PermutationGroup([pad_perm(g, degree) for g in G.generators])
        H_padded = PermutationGroup([pad_perm(h, degree) for h in H.generators])
        for g in G_padded.generators:
            for h in H_padded.generators:
                conj = h * g * (h**-1)
                if not G_padded.contains(conj):
                    return False
        return True
    except Exception:
        return False

def is_solvable(G):
    try:
        if hasattr(G, 'is_solvable'):
            res = G.is_solvable
            if callable(res): 
                return res()
            return res
        
        # Fallback: compute derived series
        current = G
        while current.order() > 1:
            next_derived = current.derived_subgroup()
            if next_derived.order() == current.order():
                return False
            current = next_derived
        return True
    except Exception:
        return False

def is_semisimple(G):
    try:
        if G.order() == 1:
            return True
        
        normal_subs = G.normal_subgroups()
        
        # Definition 1: Direct product of simple groups (generated by minimal normal subgroups)
        minimal_normals = []
        for N in normal_subs:
            if N.order() == 1:
                continue
            is_minimal = True
            for M in normal_subs:
                if M.order() == 1 or M.order() == N.order():
                    continue
                if M.is_subgroup(N):
                    is_minimal = False
                    break
            if is_minimal:
                minimal_normals.append(N)
        
        gens = []
        for N in minimal_normals:
            gens.extend(N.generators)
        
        if gens:
            socle = PermutationGroup(gens)
            if socle.order() == G.order():
                return True
                
        # Definition 2: Perfect group where the solvable radical is exactly the center
        if G.derived_subgroup().order() == G.order():
            rad = None
            max_order = 0
            for N in normal_subs:
                if is_solvable(N) and N.order() > max_order:
                    rad = N
                    max_order = N.order()
            c = G.center()
            if rad is not None and rad.order() == c.order():
                if rad.is_subgroup(c):
                    return True
                    
        return False
    except Exception:
        return False

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            G, H = witness
        elif hasattr(witness, 'G') and hasattr(witness, 'H'):
            G = witness.G
            H = witness.H
        else:
            # If only one group is provided, assume H = G
            G = witness
            H = witness
    except Exception:
        return [False, False]
        
    # H_1: G is a normal semisimple subgroup of H
    h1 = False
    try:
        if is_subgroup(G, H) and is_normal(G, H) and is_semisimple(G):
            h1 = True
    except Exception:
        pass
        
    # neg_Q: The intersection of G and C_H(G) in H is NOT the trivial subgroup
    # Note: G \cap C_H(G) is mathematically exactly the center of G, Z(G).
    nq = False
    try:
        if G.center().order() > 1:
            nq = True
    except Exception:
        pass
        
    return [h1, nq]

