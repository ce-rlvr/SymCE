def conditions(witness):
    """
    witness is expected to be a dictionary with:
      - 'N_gens': list of lists representing permutations for N (e.g., [[(0, 1, 2)]])
      - 'H_gens': list of lists representing permutations for H (e.g., [[(0, 1)]])
      - 'R': list of words for N, where a word is a list of (gen_idx, power)
      - 'S': list of words for H
      - 'phi': dict mapping y_idx to a dict mapping x_idx to a word in X
      - 'W': dict mapping (y_idx, x_idx) to a word in X
    """
    try:
        N_gens_raw = witness['N_gens']
        H_gens_raw = witness['H_gens']
        R = witness['R']
        S = witness['S']
        phi = witness['phi']
        W = witness['W']
    except Exception:
        return [False, False, False, False]

    try:
        N_gens = [Permutation(g) for g in N_gens_raw]
        N = PermutationGroup(N_gens)
    except Exception:
        N_gens = []
        N = None

    try:
        H_gens = [Permutation(g) for g in H_gens_raw]
        H = PermutationGroup(H_gens)
    except Exception:
        H_gens = []
        H = None

    def eval_word(word, gens):
        if not gens: 
            return Permutation()
        res = gens[0]**0  # Identity permutation of the correct size
        for idx, power in word:
            res = res * (gens[idx]**power)
        return res

    # H_1: N is a group generated by a set X with defining relations R
    try:
        h1_ok = True
        if N is None or not N_gens:
            h1_ok = False
        else:
            for r in R:
                if not eval_word(r, N_gens).is_Identity:
                    h1_ok = False
                    break
    except Exception:
        h1_ok = False

    # H_2: H is a group generated by a set Y with defining relations S
    try:
        h2_ok = True
        if H is None or not H_gens:
            h2_ok = False
        else:
            for s in S:
                if not eval_word(s, H_gens).is_Identity:
                    h2_ok = False
                    break
    except Exception:
        h2_ok = False

    # H_3: \phi: H \to \text{Aut}(N) is a group homomorphism
    try:
        h3_ok = True
        if h1_ok and h2_ok:
            for y_idx in range(len(H_gens)):
                if y_idx not in phi:
                    h3_ok = False
                    break
                # Check that phi(y) preserves the relations R of N
                for r in R:
                    mapped_r_word = []
                    for x_idx, power in r:
                        mapped_x_word = phi[y_idx][x_idx]
                        if power > 0:
                            for _ in range(power):
                                mapped_r_word.extend(mapped_x_word)
                        else:
                            inv_word = [(i, -p) for i, p in reversed(mapped_x_word)]
                            for _ in range(-power):
                                mapped_r_word.extend(inv_word)
                    if not eval_word(mapped_r_word, N_gens).is_Identity:
                        h3_ok = False
                        break
                if not h3_ok: break
            
            # Check that phi respects the relations S of H
            if h3_ok:
                for s in S:
                    for x_idx in range(len(N_gens)):
                        current_word = [(x_idx, 1)]
                        for y_idx, power in reversed(s):
                            if power > 0:
                                for _ in range(power):
                                    temp = []
                                    for i, p in current_word:
                                        if p > 0:
                                            for _ in range(p): 
                                                temp.extend(phi[y_idx][i])
                                        else:
                                            inv = [(j, -q) for j, q in reversed(phi[y_idx][i])]
                                            for _ in range(-p): 
                                                temp.extend(inv)
                                    current_word = temp
                            else:
                                h3_ok = False
                                break
                        if not h3_ok: break
                        if eval_word(current_word, N_gens) != N_gens[x_idx]:
                            h3_ok = False
                            break
                    if not h3_ok: break
        else:
            h3_ok = False
    except Exception:
        h3_ok = False

    # ¬Q: The presented group is not isomorphic to the semidirect product
    try:
        neg_q_ok = False
        if h1_ok and h2_ok and h3_ok:
            # If W specifies w_{y,x} = x for all y, x, the presented group is forced to be abelian
            # (assuming N and H are abelian).
            pres_abelian = True
            for y_idx in range(len(H_gens)):
                for x_idx in range(len(N_gens)):
                    w_word = W.get((y_idx, x_idx), [(x_idx, 1)])
                    if eval_word(w_word, N_gens) != N_gens[x_idx]:
                        pres_abelian = False
                        break
                if not pres_abelian: break
            
            if pres_abelian and N.is_abelian and H.is_abelian:
                # The presented group is abelian.
                # Check if the semidirect product is abelian (which happens iff phi is trivial).
                sdp_abelian = True
                for y_idx in range(len(H_gens)):
                    for x_idx in range(len(N_gens)):
                        mapped_x = eval_word(phi[y_idx][x_idx], N_gens)
                        if mapped_x != N_gens[x_idx]:
                            sdp_abelian = False
                            break
                    if not sdp_abelian: break
                
                # If the presented group is abelian but the semidirect product is not,
                # they cannot be isomorphic.
                if not sdp_abelian:
                    neg_q_ok = True
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, h3_ok, neg_q_ok]

