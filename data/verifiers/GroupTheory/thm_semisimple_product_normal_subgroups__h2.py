def is_semisimple(H):
    """
    A finite group is semisimple if it has no non-trivial abelian normal subgroups.
    This is equivalent to saying that for every non-identity element x in H,
    the normal closure of x in H is non-abelian.
    """
    if not isinstance(H, PermutationGroup):
        return False
    if H.order() == 1:
        return True
    elements = list(H.generate())
    id_el = H.identity
    for x in elements:
        if x == id_el:
            continue
        # Check if x commutes with all its conjugates.
        # If it does, its normal closure is abelian.
        is_abelian = True
        for h in elements:
            c = h * x * ~h
            if x * c != c * x:
                is_abelian = False
                break
        if is_abelian:
            return False
    return True

def is_normal_subgroup(G, M):
    if not isinstance(G, PermutationGroup) or not isinstance(M, PermutationGroup):
        return False
    if M.order() == 1:
        return True
    # check if M is a subgroup
    for gen in M.generators:
        if gen not in G:
            return False
    # check normality
    for g in G.generators:
        for m in M.generators:
            if g * m * ~g not in M:
                return False
    return True

def conditions(witness):
    try:
        if isinstance(witness, dict):
            G = witness.get('G')
            M = witness.get('M')
            N = witness.get('N')
        else:
            G, M, N = witness
    except Exception:
        return [False, False, False]

    # H_1: G is a finite group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False

    # H_2: M is a normal semisimple subgroup of G
    try:
        h2 = is_normal_subgroup(G, M) and is_semisimple(M)
    except Exception:
        h2 = False

    # ¬Q: The subgroup generated by N and M is NOT a normal semisimple subgroup of G
    try:
        if not isinstance(N, PermutationGroup):
            neg_q = False
        else:
            gens = list(N.generators) + list(M.generators)
            if not gens:
                K = PermutationGroup([G.identity])
            else:
                K = PermutationGroup(gens)
            
            is_K_normal = is_normal_subgroup(G, K)
            is_K_semisimple = is_semisimple(K)
            neg_q = not (is_K_normal and is_K_semisimple)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

