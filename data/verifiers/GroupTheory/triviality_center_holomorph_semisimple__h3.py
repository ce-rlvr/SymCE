def is_semisimple(G):
    """
    A finite group is semisimple (i.e., a direct product of simple groups)
    if and only if it is generated by its minimal normal subgroups.
    """
    normal_subs = G.normal_subgroups()
    
    minimal_normals = []
    for N in normal_subs:
        if N.order() == 1:
            continue
        is_minimal = True
        for M in normal_subs:
            if M.order() == 1 or M.order() == N.order():
                continue
            # Check if M is a proper subgroup of N
            if all(g in N for g in M.generators):
                is_minimal = False
                break
        if is_minimal:
            minimal_normals.append(N)
            
    if not minimal_normals:
        return G.order() == 1
        
    all_gens = []
    for N in minimal_normals:
        all_gens.extend(N.generators)
        
    gen_subgroup = PermutationGroup(all_gens)
    return gen_subgroup.order() == G.order()

def get_automorphisms(G):
    elements = list(G.generate())
    n = len(elements)
    idx = {e: i for i, e in enumerate(elements)}
    
    identity = None
    for e in elements:
        if e * e == e:
            identity = e
            break
    id_idx = idx[identity]
    
    mult_table = [[0]*n for _ in range(n)]
    for i in range(n):
        for j in range(n):
            mult_table[i][j] = idx[elements[i] * elements[j]]
            
    gens = G.generators
    gen_indices = [idx[g] for g in gens]
    
    words = {}
    queue = [(id_idx, [])]
    visited = {id_idx}
    words[id_idx] = []
    
    head = 0
    while head < len(queue):
        curr, word = queue[head]
        head += 1
        for i, g_idx in enumerate(gen_indices):
            nxt = mult_table[curr][g_idx]
            if nxt not in visited:
                visited.add(nxt)
                new_word = word + [i]
                words[nxt] = new_word
                queue.append((nxt, new_word))
                
    gen_orders = [elements[g].order() for g in gen_indices]
    valid_targets = []
    for order in gen_orders:
        valid_targets.append([i for i in range(n) if elements[i].order() == order])
        
    auts = []
    for target_gens in itertools.product(*valid_targets):
        mapping = [0]*n
        seen = [False]*n
        valid = True
        for i in range(n):
            curr = id_idx
            for w in words[i]:
                curr = mult_table[curr][target_gens[w]]
            if seen[curr]:
                valid = False
                break
            seen[curr] = True
            mapping[i] = curr
            
        if not valid:
            continue
            
        for i in range(n):
            for j in range(n):
                if mapping[mult_table[i][j]] != mult_table[mapping[i]][mapping[j]]:
                    valid = False
                    break
            if not valid:
                break
                
        if valid:
            auts.append(mapping)
            
    return auts, elements, idx, identity

def center_of_holomorph_is_trivial(G):
    """
    The center of Hol(G) is isomorphic to the subgroup of Z(G)
    consisting of elements that are fixed by all automorphisms of G.
    """
    auts, elements, idx, identity = get_automorphisms(G)
    
    gens = G.generators
    Z_G = []
    for e in elements:
        is_center = True
        for g in gens:
            if e * g != g * e:
                is_center = False
                break
        if is_center:
            Z_G.append(e)
            
    for e in Z_G:
        if e == identity:
            continue
        e_idx = idx[e]
        fixed_by_all = True
        for aut in auts:
            if aut[e_idx] != e_idx:
                fixed_by_all = False
                break
        if fixed_by_all:
            return False
            
    return True

def conditions(witness):
    try:
        h1 = isinstance(witness, PermutationGroup)
    except Exception:
        h1 = False
        
    try:
        h2 = False
        if h1:
            h2 = is_semisimple(witness)
    except Exception:
        h2 = False
        
    try:
        neg_q = False
        if h1:
            neg_q = not center_of_holomorph_is_trivial(witness)
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

