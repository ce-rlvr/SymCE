import sympy
from sympy.combinatorics.free_groups import FreeGroup, free_group, FreeGroupElement
import itertools
import math

# Top-level setup: named object bindings that the witness expression may reference.
F2, x, y = free_group("x, y")
F3, a, b, c = free_group("a, b, c")

def conditions(witness) -> list[bool]:
    # Extract F and N from the witness
    try:
        if isinstance(witness, dict):
            F = witness.get('F')
            N = witness.get('N')
        else:
            F, N = witness
    except Exception:
        return [False, False, False]
        
    # H_1: F is a free group
    try:
        h1 = isinstance(F, FreeGroup)
    except Exception:
        h1 = False
        
    # H_2: The rank of F is strictly greater than 1
    try:
        h2 = h1 and len(F.generators) > 1
    except Exception:
        h2 = False
        
    # ¬Q: The subgroup N has infinite index in F
    try:
        neg_q = False
        if h1 and h2:
            # Normalize N to a list of FreeGroupElements
            if isinstance(N, FreeGroupElement):
                N_list = [N]
            elif isinstance(N, (list, tuple, set)):
                N_list = list(N)
            else:
                return [h1, h2, False]
                
            # Ensure all elements in N actually belong to F
            if not all(hasattr(word, 'group') and word.group == F for word in N_list):
                return [h1, h2, False]
                
            r = len(F.generators)
            k = len(N_list)
            
            # Prevent performance issues with absurdly large inputs
            if k > 20 or r > 10:
                return [h1, h2, False]
            
            # By Schreier's index formula, if N has finite index j, its rank is j(r-1) + 1.
            # Since N is generated by k elements, its rank is <= k.
            # Therefore, j(r-1) + 1 <= k  =>  j <= (k-1)/(r-1).
            j_max = (k - 1) // (r - 1)
            
            if j_max < 1:
                # The maximum possible finite index is < 1, so the index must be infinite.
                neg_q = True
            else:
                # Further necessary condition: The abelianization of F/N must be finite.
                # We compute the exponent sum matrix of the generators of N.
                matrix_rows = []
                for word in N_list:
                    exp_sums = {g: 0 for g in F.generators}
                    for factor in word.array_form:
                        gen, exp = factor
                        for g in F.generators:
                            if gen == g:
                                exp_sums[g] += exp
                    matrix_rows.append([exp_sums[g] for g in F.generators])
                    
                M = sympy.Matrix(matrix_rows)
                
                # The size of the abelianization of F/N is given by the GCD of all r x r minors of M.
                minors = []
                for rows in itertools.combinations(range(k), r):
                    submatrix = M[list(rows), :]
                    minors.append(abs(submatrix.det()))
                    
                D = 0
                for m in minors:
                    D = math.gcd(D, int(m))
                    
                if D == 0:
                    # Rank of M is < r, so the abelianization is infinite, meaning F/N is infinite.
                    neg_q = True
                else:
                    # The size of the abelianization (D) must divide the index of N in F.
                    # We check if there is any valid finite index j in [1, j_max] that is a multiple of D.
                    possible = False
                    for j in range(1, j_max + 1):
                        if j % D == 0:
                            possible = True
                            break
                    if not possible:
                        neg_q = True
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

