def conditions(witness) -> list[bool]:
    # Unpack witness
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            p, G = witness
        else:
            G = witness
            order = G.order()
            if order == 1:
                p = 2
            else:
                factors = sympy.ntheory.factorint(order)
                if len(factors) == 1:
                    p = list(factors.keys())[0]
                else:
                    p = 0
    except Exception:
        p, G = 0, None

    # H_1: p is a prime number
    try:
        h1 = sympy.isprime(p)
    except Exception:
        h1 = False

    # H_2: G is a finite p-group
    try:
        if not hasattr(G, 'order'):
            h2 = False
        else:
            order = G.order()
            if order == 1:
                h2 = True
            else:
                factors = sympy.ntheory.factorint(order)
                h2 = (len(factors) == 1 and list(factors.keys())[0] == p)
    except Exception:
        h2 = False

    # neg_Q: G is NOT a regular p-group
    try:
        if not (h1 and h2):
            neg_q = False
        else:
            is_regular = True
            elements = list(G.generate())
            for x in elements:
                for y in elements:
                    # Commuting elements trivially satisfy the regularity condition
                    if x * y == y * x:
                        continue
                    
                    xy_p = (x * y)**p
                    x_p = x**p
                    y_p = y**p
                    
                    # We check if (xy)^p \in x^p y^p \mho_1(H')
                    # Equivalently, target = (x^p y^p)^{-1} (xy)^p \in \mho_1(H')
                    target = (x_p * y_p)**-1 * xy_p
                    
                    if target.is_Identity:
                        continue
                        
                    H = PermutationGroup([x, y])
                    H_prime = H.derived_subgroup()
                    H_prime_elements = list(H_prime.generate())
                    
                    # \mho_1(H') is the subgroup generated by p-th powers of elements in H'
                    p_powers = [c**p for c in H_prime_elements]
                    M = PermutationGroup(p_powers)
                    
                    if not M.contains(target):
                        is_regular = False
                        break
                if not is_regular:
                    break
            neg_q = not is_regular
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

