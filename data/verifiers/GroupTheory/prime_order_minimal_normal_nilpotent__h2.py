def conditions(witness):
    try:
        G, N = witness
    except Exception:
        return [False, False, False]
        
    # H_1: G is a finite group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False
        
    # H_2: N is a minimal normal subgroup of G
    try:
        h2 = False
        if isinstance(N, PermutationGroup) and N.order() > 1:
            # Check if N is a subgroup of G
            is_sub = all(n in G for n in N.generators)
            if is_sub:
                # Check if N is normal in G
                is_norm = True
                for g in G.generators:
                    for n in N.generators:
                        if (g * n * ~g) not in N:
                            is_norm = False
                            break
                    if not is_norm:
                        break
                
                if is_norm:
                    # Check minimality: normal closure of any non-identity element must be N
                    elements = list(N.generate())
                    is_min = True
                    for x in elements:
                        if x.is_Identity:
                            continue
                        
                        # Find all G-conjugates of x
                        conjugates = set()
                        queue = [x]
                        conjugates.add(x)
                        
                        while queue:
                            curr = queue.pop(0)
                            for g in G.generators:
                                nxt = g * curr * ~g
                                if nxt not in conjugates:
                                    conjugates.add(nxt)
                                    queue.append(nxt)
                                nxt_inv = (~g) * curr * g
                                if nxt_inv not in conjugates:
                                    conjugates.add(nxt_inv)
                                    queue.append(nxt_inv)
                                    
                        # The subgroup generated by the conjugates is the normal closure
                        H = PermutationGroup(*list(conjugates))
                        if H.order() < N.order():
                            is_min = False
                            break
                    h2 = is_min
    except Exception:
        h2 = False
        
    # neg_Q: The order of N is not a prime number
    try:
        neg_q = not isprime(N.order())
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

