def normal_closure(gens, G):
    """Computes the normal closure of a set of generators in the group G."""
    if not gens:
        return PermutationGroup([G.identity])
    
    closure_gens = list(set(gens))
    H = PermutationGroup(closure_gens)
    G_gens = G.generators
    
    unprocessed = list(closure_gens)
    while unprocessed:
        g = unprocessed.pop(0)
        for x in G_gens:
            # Conjugate by x and x^-1
            for conj in [(~x) * g * x, x * g * (~x)]:
                if conj not in H:
                    closure_gens.append(conj)
                    unprocessed.append(conj)
                    H = PermutationGroup(closure_gens)
    return H

def commutator_subgroup(H, K):
    """Computes the commutator subgroup [H, K]."""
    comms = []
    for h in H.generators:
        for k in K.generators:
            comms.append((~h) * (~k) * h * k)
    HK = PermutationGroup(H.generators + K.generators)
    return normal_closure(comms, HK)

def product_subgroup(H, K):
    """Computes the subgroup generated by H and K."""
    return PermutationGroup(H.generators + K.generators)

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness is expected to be a tuple (G, N, i).
    """
    try:
        if len(witness) == 3:
            G, N, i = witness
        elif len(witness) == 2:
            G, N = witness
            i = 0  # Default to a failing case if i is not provided
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H_1: G is a group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False

    # H_2: N is a normal subgroup of G
    try:
        h2 = isinstance(N, PermutationGroup) and N.is_subgroup(G) and N.is_normal(G)
    except Exception:
        h2 = False

    # neg_Q: The i-th term of the lower central series of G/N is NOT equal to (\gamma_i(G)N)/N
    try:
        i_val = int(i)
        if i_val < 1:
            # Mathematically undefined for i < 1, so the equality fails
            neg_q = True
        else:
            # Compute the preimage of the i-th term of the lower central series of G/N in G
            P = G
            for _ in range(1, i_val):
                C = commutator_subgroup(P, G)
                P = product_subgroup(C, N)
            
            # Compute \gamma_i(G) N
            lcs = G.lower_central_series()
            if i_val - 1 < len(lcs):
                gamma_i = lcs[i_val - 1]
            else:
                gamma_i = lcs[-1]
            
            rhs = product_subgroup(gamma_i, N)
            
            # Check equality of the two subgroups
            is_equal = P.is_subgroup(rhs) and rhs.is_subgroup(P)
            neg_q = not is_equal
    except Exception:
        # If any error occurs (e.g., i is not an integer), the conclusion fails
        neg_q = True

    return [h1, h2, neg_q]

