import sympy
from sympy import isprime

class FiniteField:
    def __init__(self, p, degree=1):
        self.p = p
        self.degree = degree

class AlgebraicClosure:
    def __init__(self, base_field):
        self.base_field = base_field

class RationalFunctionField:
    def __init__(self, base_field):
        self.base_field = base_field

class FieldExtension:
    def __init__(self, E, F):
        self.E = E
        self.F = F

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            E, F = witness
        else:
            E = witness.E
            F = witness.F
        h1 = isinstance(F, FiniteField) and isprime(F.p) and isinstance(F.degree, int) and F.degree >= 1
    except Exception:
        h1 = False

    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            E, F = witness
        else:
            E = witness.E
            F = witness.F
        
        is_valid_ext = False
        is_cyclic = False
        
        if isinstance(E, FiniteField) and isinstance(F, FiniteField):
            if E.p == F.p and E.degree % F.degree == 0:
                is_valid_ext = True
                is_cyclic = True
        elif isinstance(E, AlgebraicClosure):
            if isinstance(E.base_field, FiniteField) and E.base_field.p == F.p and E.base_field.degree == F.degree:
                is_valid_ext = True
                is_cyclic = False
        elif isinstance(E, RationalFunctionField):
            if isinstance(E.base_field, FiniteField) and E.base_field.p == F.p and E.base_field.degree == F.degree:
                is_valid_ext = True
                is_cyclic = False
                
        if not is_valid_ext:
            neg_q = False
        else:
            neg_q = not is_cyclic
            
    except Exception:
        neg_q = False

    return [h1, neg_q]

