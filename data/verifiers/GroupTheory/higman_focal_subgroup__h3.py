def is_sylow_p_subgroup(G, P):
    for gen in P.generators:
        if not G.contains(gen):
            return False
            
    order_P = P.order() if callable(P.order) else P.order
    order_G = G.order() if callable(G.order) else G.order
    
    if order_G % order_P != 0:
        return False
        
    if order_P == 1:
        return True
        
    factors = factorint(order_P)
    if len(factors) != 1:
        return False
    p = list(factors.keys())[0]
    
    m = order_G // order_P
    if m % p == 0:
        return False
        
    return True

def conditions(witness):
    try:
        G, P = witness
    except Exception:
        return [False, False, False]
        
    # H1: G is a finite group
    try:
        if not isinstance(G, PermutationGroup):
            h1 = False
        else:
            h1 = True
    except Exception:
        h1 = False
        
    # H2: P is a Sylow p-subgroup of G
    try:
        if not isinstance(P, PermutationGroup):
            h2 = False
        else:
            h2 = is_sylow_p_subgroup(G, P)
    except Exception:
        h2 = False
        
    # neg_Q: P \cap G' is NOT generated by the set of all elements of the form x y^{-1}, 
    # where x, y \in P and x is conjugate to y in G
    try:
        G_elements = list(G.generate())
        P_elements = list(P.generate())
        
        G_prime = G.derived_subgroup() if callable(G.derived_subgroup) else G.derived_subgroup
        G_prime_elements = set(G_prime.generate())
        
        intersection_elements = set(P_elements).intersection(G_prime_elements)
        
        generators = set()
        for x in P_elements:
            class_x = set()
            for g in G_elements:
                class_x.add(g * x * ~g)
            for y in P_elements:
                if y in class_x:
                    generators.add(x * ~y)
                    
        generators = list(generators)
        if not generators:
            focal_elements = {G.identity if hasattr(G, 'identity') else list(G.generate())[0] * ~list(G.generate())[0]}
        else:
            focal_subgroup = PermutationGroup(generators)
            focal_elements = set(focal_subgroup.generate())
            
        neg_q = (focal_elements != intersection_elements)
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

