def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, dict):
            G = witness.get('G')
            S = witness.get('S')
            if G is None or S is None:
                return [False, False]
        else:
            G, S = witness
    except Exception:
        return [False, False]

    # H_1: Let G be a group.
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False

    # neg_Q: The derived subgroup G' is NOT generated by the set S.
    try:
        G_prime = G.derived_subgroup()
        
        if isinstance(S, Permutation):
            S_list = [S]
        else:
            S_list = list(S)
            
        if not S_list:
            order_G_prime = G_prime.order() if callable(G_prime.order) else G_prime.order
            neg_q = order_G_prime != 1
        else:
            H = PermutationGroup(*S_list)
            order_H = H.order() if callable(H.order) else H.order
            order_G_prime = G_prime.order() if callable(G_prime.order) else G_prime.order
            
            # H is generated by S. We check if H and G_prime are the same group.
            # They are equal if they have the same order and H is a subgroup of G_prime.
            is_equal = (order_H == order_G_prime) and all(g in G_prime for g in H.generators)
            neg_q = not is_equal
    except Exception:
        neg_q = False

    return [h1, neg_q]

