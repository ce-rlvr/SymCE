def conditions(witness) -> list[bool]:
    try:
        G, N, H = witness
    except Exception:
        return [False, False, False, False]

    # H1: G is a group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False

    # H2: N is a normal subgroup of G
    try:
        h2 = False
        if isinstance(N, PermutationGroup):
            # Check if N is a subgroup of G
            is_sub = True
            for gen in N.generators:
                if gen not in G:
                    is_sub = False
                    break
            
            # Check if N is normal in G
            is_norm = True
            if is_sub:
                for g in G.generators:
                    for n_gen in N.generators:
                        if (g * n_gen * (~g)) not in N:
                            is_norm = False
                            break
                    if not is_norm:
                        break
            h2 = is_sub and is_norm
    except Exception:
        h2 = False

    # H3: H is a subgroup of G
    try:
        h3 = False
        if isinstance(H, PermutationGroup):
            is_sub = True
            for gen in H.generators:
                if gen not in G:
                    is_sub = False
                    break
            h3 = is_sub
    except Exception:
        h3 = False

    # neg_Q: The mixed commutator subgroup of N and H is NOT a normal subgroup of G
    try:
        commutators = []
        # The mixed commutator subgroup is generated by all commutators n * h * n^-1 * h^-1
        for n in N.generate():
            for h in H.generate():
                c = n * h * (~n) * (~h)
                commutators.append(c)
        
        NH_comm = PermutationGroup(commutators)
        
        # Check if the mixed commutator subgroup is normal in G
        is_normal = True
        for g in G.generators:
            for c in NH_comm.generators:
                if (g * c * (~g)) not in NH_comm:
                    is_normal = False
                    break
            if not is_normal:
                break
                
        neg_q = not is_normal
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

