def has_finite_index(F, words):
    """
    Uses Stallings fold (bouquet of circles) to determine if the subgroup 
    generated by `words` has finite index in the free group `F`.
    """
    if not words:
        return len(F.generators) == 0
        
    edges = []
    next_v = 1
    for w in words:
        if w.is_identity:
            continue
        letters = []
        for gen, exp in w.array_form:
            sign = 1 if exp > 0 else -1
            for _ in range(abs(exp)):
                letters.append((gen, sign))
        
        if not letters:
            continue
            
        curr = 0
        for i, (gen, sign) in enumerate(letters):
            if i == len(letters) - 1:
                nxt = 0
            else:
                nxt = next_v
                next_v += 1
                
            if sign == 1:
                edges.append([curr, nxt, gen])
            else:
                edges.append([nxt, curr, gen])
            curr = nxt

    # Fold the graph
    changed = True
    while changed:
        changed = False
        
        # Fold outgoing edges
        out_edges = {}
        for e in edges:
            u, v, gen = e
            if (u, gen) in out_edges:
                v_other = out_edges[(u, gen)]
                if v != v_other:
                    v_keep = min(v, v_other)
                    v_replace = max(v, v_other)
                    for e2 in edges:
                        if e2[0] == v_replace: e2[0] = v_keep
                        if e2[1] == v_replace: e2[1] = v_keep
                    changed = True
                    break
            else:
                out_edges[(u, gen)] = v
                
        if changed:
            new_edges = []
            seen = set()
            for e in edges:
                t = tuple(e)
                if t not in seen:
                    seen.add(t)
                    new_edges.append(e)
            edges = new_edges
            continue
            
        # Fold incoming edges
        in_edges = {}
        for e in edges:
            u, v, gen = e
            if (v, gen) in in_edges:
                u_other = in_edges[(v, gen)]
                if u != u_other:
                    u_keep = min(u, u_other)
                    u_replace = max(u, u_other)
                    for e2 in edges:
                        if e2[0] == u_replace: e2[0] = u_keep
                        if e2[1] == u_replace: e2[1] = u_keep
                    changed = True
                    break
            else:
                in_edges[(v, gen)] = u
                
        if changed:
            new_edges = []
            seen = set()
            for e in edges:
                t = tuple(e)
                if t not in seen:
                    seen.add(t)
                    new_edges.append(e)
            edges = new_edges
            continue

    # Check if the core graph is a regular covering of the bouquet
    vertices = set()
    for u, v, gen in edges:
        vertices.add(u)
        vertices.add(v)
        
    if 0 not in vertices:
        vertices.add(0)
        
    gen_symbols = [g.array_form[0][0] for g in F.generators]
        
    for v in vertices:
        for gen_sym in gen_symbols:
            out_c = sum(1 for e in edges if e[0] == v and e[2] == gen_sym)
            if out_c != 1:
                return False
            in_c = sum(1 for e in edges if e[1] == v and e[2] == gen_sym)
            if in_c != 1:
                return False
                
    return True

def conditions(witness):
    """
    Checks if the witness is a valid counterexample.
    Expected witness format: (F, N_gens)
    where F is a FreeGroup and N_gens is a list of FreeGroupElements generating N.
    """
    try:
        if not isinstance(witness, tuple) or len(witness) != 2:
            return [False, False, False]
        F, N_gens = witness
    except Exception:
        return [False, False, False]
        
    # H_1: F is a non-abelian free group
    try:
        h1 = F.__class__.__name__ == 'FreeGroup' and len(F.generators) >= 2
    except Exception:
        h1 = False
        
    # H_2: N is finitely generated
    try:
        h2 = isinstance(N_gens, (list, tuple)) and all(hasattr(w, 'group') and w.group == F for w in N_gens)
    except Exception:
        h2 = False
        
    # ¬Q: N is not the trivial subgroup AND N does not have finite index in F
    try:
        if not h1 or not h2:
            neg_q = False
        else:
            is_trivial = all(w.is_identity for w in N_gens)
            if is_trivial:
                neg_q = False
            else:
                neg_q = not has_finite_index(F, N_gens)
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

