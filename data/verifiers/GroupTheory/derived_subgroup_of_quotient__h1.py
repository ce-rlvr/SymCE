def conditions(witness):
    """
    Given a witness (G, N), checks if it is a counterexample to the conjecture.
    """
    try:
        G, N = witness
    except Exception:
        return [False, False]
    
    try:
        h1 = bool(N.is_subgroup(G) and G.is_normal(N))
    except Exception:
        h1 = False
        
    try:
        # The conclusion is that (G/N)' == G'N/N.
        # We verify this by checking if their preimages in G are equal.
        # The preimage of G'N/N is simply the subgroup generated by G' and N.
        G_prime = G.derived_subgroup()
        preimage_rhs = PermutationGroup(G_prime.generators + N.generators)
        
        # The derived subgroup of G/N is generated by commutators of elements in G/N.
        # Its preimage in G is generated by the commutators of elements in G, together with N.
        # This is exactly the subgroup generated by G' and N.
        preimage_lhs = PermutationGroup(G.derived_subgroup().generators + N.generators)
        
        q = bool(preimage_lhs.is_subgroup(preimage_rhs) and preimage_rhs.is_subgroup(preimage_lhs))
        neg_q = not q
    except Exception:
        neg_q = False
        
    return [h1, neg_q]

