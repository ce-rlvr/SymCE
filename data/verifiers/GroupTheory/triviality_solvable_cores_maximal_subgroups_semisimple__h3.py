def is_semisimple(G):
    """
    A finite group is semisimple if it has no non-trivial solvable normal subgroups.
    Equivalently, its solvable radical is trivial.
    """
    try:
        if G.order() == 1:
            return False
    except Exception:
        return False
        
    seen = set()
    try:
        elements = list(G.generate())
        gens = list(G.generators)
    except Exception:
        return False
        
    for g in elements:
        if g.is_Identity or g in seen:
            continue
        
        # Compute the conjugacy class of g in G
        orbit = set([g])
        queue = [g]
        while queue:
            curr = queue.pop(0)
            for x in gens:
                conj = x * curr * (~x)
                if conj not in orbit:
                    orbit.add(conj)
                    queue.append(conj)
                conj2 = (~x) * curr * x
                if conj2 not in orbit:
                    orbit.add(conj2)
                    queue.append(conj2)
        seen.update(orbit)
        
        # The subgroup generated by a conjugacy class is the normal closure of g.
        # If any normal closure is solvable, G has a non-trivial solvable normal subgroup.
        try:
            N = PermutationGroup(list(orbit))
            if N.is_solvable:
                return False
        except Exception:
            return False
            
    return True

def is_maximal_subgroup(G, M):
    """
    Checks if M is a maximal subgroup of G.
    """
    try:
        if M.order() >= G.order():
            return False
            
        # Check if M is a subgroup of G
        for gen in M.generators:
            if gen not in G:
                return False
                
        M_elements = set(M.generate())
        G_order = G.order()
        
        # Check maximality: for any g in G \ M, <M, g> must be G
        for g in G.generate():
            if g not in M_elements:
                H = PermutationGroup(list(M.generators) + [g])
                if H.order() < G_order:
                    return False
        return True
    except Exception:
        return False

def is_core_trivial(G, M):
    """
    Checks if the core of M in G is the trivial subgroup.
    The core is trivial iff no non-trivial normal subgroup of G is contained in M.
    """
    try:
        M_elements = set(M.generate())
        seen = set()
        gens = list(G.generators)
        
        for g in M_elements:
            if g.is_Identity or g in seen:
                continue
                
            orbit = set([g])
            queue = [g]
            contained_in_M = True
            
            while queue:
                curr = queue.pop(0)
                for x in gens:
                    conj = x * curr * (~x)
                    if conj not in orbit:
                        orbit.add(conj)
                        queue.append(conj)
                        if conj not in M_elements:
                            contained_in_M = False
                    
                    conj2 = (~x) * curr * x
                    if conj2 not in orbit:
                        orbit.add(conj2)
                        queue.append(conj2)
                        if conj2 not in M_elements:
                            contained_in_M = False
                
                if not contained_in_M:
                    break
                    
            # If the entire conjugacy class of g in G is contained in M,
            # then the normal closure of g is contained in M, so the core is non-trivial.
            if contained_in_M:
                return False
                
            seen.update(orbit)
            
        return True
    except Exception:
        return True

def conditions(witness):
    try:
        G, M = witness
    except Exception:
        return [False, False, False]
        
    try:
        h1 = bool(is_semisimple(G))
    except Exception:
        h1 = False
        
    try:
        h2 = bool(is_maximal_subgroup(G, M))
    except Exception:
        h2 = False
        
    try:
        neg_q = not is_core_trivial(G, M)
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

