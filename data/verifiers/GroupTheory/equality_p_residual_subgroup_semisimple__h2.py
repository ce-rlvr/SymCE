def is_semisimple(G):
    """
    A finite group is semisimple if it has no non-trivial abelian normal subgroups.
    This is equivalent to saying that no non-identity element has an abelian normal closure.
    We check this by verifying that no non-identity conjugacy class consists of mutually commuting elements.
    """
    if not isinstance(G, PermutationGroup):
        return False
    try:
        id_elem = G.identity
        seen = {id_elem}
        for g in G.elements:
            if g in seen:
                continue
            
            # Compute the conjugacy class (orbit under conjugation by generators)
            orbit = {g}
            queue = [g]
            while queue:
                curr = queue.pop(0)
                for gen in G.generators:
                    conj = gen * curr * ~gen
                    if conj not in orbit:
                        orbit.add(conj)
                        queue.append(conj)
            seen.update(orbit)
            
            # Check if all elements in the conjugacy class commute with each other
            orbit_list = list(orbit)
            commutes = True
            for i in range(len(orbit_list)):
                for j in range(i + 1, len(orbit_list)):
                    if orbit_list[i] * orbit_list[j] != orbit_list[j] * orbit_list[i]:
                        commutes = False
                        break
                if not commutes:
                    break
            
            # If we found a non-identity element whose conjugacy class commutes, 
            # its normal closure is abelian, so the group is not semisimple.
            if commutes:
                return False
                
        return True
    except Exception:
        return False

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            G, p = witness
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]
        
    # H_1: G is a semisimple finite group
    try:
        h1 = is_semisimple(G)
    except Exception:
        h1 = False
        
    # H_2: p is a prime (validating the definition of p-residual)
    try:
        h2 = sympy.isprime(p)
    except Exception:
        h2 = False
        
    # ¬Q: O^p(G) is not equal to G
    # O^p(G) is generated by all elements of G whose order is coprime to p.
    try:
        gens = []
        for g in G.elements:
            if math.gcd(g.order(), p) == 1:
                gens.append(g)
        if not gens:
            gens = [G.identity]
        Op = PermutationGroup(gens)
        
        # The conclusion fails if O^p(G) is a proper subgroup of G
        neg_q = Op.order() < G.order()
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

