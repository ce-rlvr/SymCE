def abelian_invariants(F, rels):
    """
    Computes the abelian invariants (elementary divisors) of the group 
    presented by < F.generators | rels >.
    """
    gens = F.generators
    n = len(gens)
    m = len(rels)
    if n == 0:
        return []
    if m == 0:
        return [0] * n
    
    gen_symbols = [g.array_form[0][0] for g in gens]
    
    M = Matrix(m, n, [0]*(m*n))
    for i, r in enumerate(rels):
        for sym, exp in r.array_form:
            try:
                j = gen_symbols.index(sym)
                M[i, j] += exp
            except ValueError:
                pass
                
    try:
        SNF = smith_normal_form(M)
    except Exception:
        return None
        
    invariants = []
    for i in range(min(m, n)):
        val = abs(SNF[i, i])
        if val != 1:
            invariants.append(val)
    for i in range(min(m, n), n):
        invariants.append(0)
        
    # Sort invariants: non-zero integers first, then zeros (which represent Z)
    invariants = sorted([v for v in invariants if v != 0]) + [0]*invariants.count(0)
    return invariants

def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness should provide the free group F, relations R, set of words S, 
    and the normal subgroup generators N.
    Format: tuple (F, R, S, N) or dict {'F': F, 'R': R, 'S': S, 'N': N}
    """
    try:
        if isinstance(witness, dict):
            F = witness['F']
            R = witness['R']
            S = witness['S']
            N = witness['N']
        else:
            F, R, S, N = witness
    except Exception:
        return [False, False, False]
        
    # H_1: G is a group with presentation <X | R>
    try:
        h1 = isinstance(F, FreeGroup) and all(r in F for r in R)
    except Exception:
        h1 = False
        
    # H_2: S is a set of words in the free group generated by X
    try:
        h2 = all(s in F for s in S)
    except Exception:
        h2 = False
        
    # ¬Q: The quotient group G/N does NOT have the presentation <X | R ∪ S>
    # We verify this by showing that their abelianizations are not isomorphic.
    try:
        inv_GN = abelian_invariants(F, list(R) + list(N))
        inv_RS = abelian_invariants(F, list(R) + list(S))
        if inv_GN is None or inv_RS is None:
            neg_q = False
        else:
            neg_q = (inv_GN != inv_RS)
    except Exception:
        neg_q = False
        
    return [bool(h1), bool(h2), bool(neg_q)]

