def conditions(witness) -> list[bool]:
    # H_1: G is a group
    try:
        if isinstance(witness, tuple):
            G = witness[0]
        else:
            G = witness
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False

    # H_2: G is generated by Z(G) U {x}
    try:
        if isinstance(witness, tuple):
            G, x = witness
            if x not in G:
                h2 = False
            else:
                Z = G.center()
                gens = list(Z.generators) + [x]
                H = PermutationGroup(gens)
                h2 = bool(H.order() == G.order())
        else:
            G = witness
            Z = G.center()
            h2 = False
            for x in G.elements:
                gens = list(Z.generators) + [x]
                H = PermutationGroup(gens)
                if H.order() == G.order():
                    h2 = True
                    break
    except Exception:
        h2 = False

    # ¬Q: G is not an abelian group
    try:
        if isinstance(witness, tuple):
            G = witness[0]
        else:
            G = witness
        neg_q = not bool(G.is_abelian)
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

