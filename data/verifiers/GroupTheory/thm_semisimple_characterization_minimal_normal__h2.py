def conditions(witness) -> list[bool]:
    # H1: G is a finite group
    try:
        if hasattr(witness, 'is_finite') and witness.is_finite is False:
            return [False, False, False]
        
        if hasattr(witness, 'elements'):
            elements = list(witness.elements)
        elif hasattr(witness, 'generate'):
            elements = list(witness.generate())
        else:
            elements = None
            
        if elements is None or len(elements) == 0:
            return [False, False, False]
            
        # Ensure elements are hashable
        try:
            hash(elements[0])
        except TypeError:
            elements = [e.as_immutable() if hasattr(e, 'as_immutable') else e for e in elements]
            
        h1_ok = True
    except Exception:
        return [False, False, False]

    # H2: G is generated by the set of all its minimal normal subgroups
    try:
        try:
            id_el = witness.identity
        except AttributeError:
            id_el = None
            for e in elements:
                try:
                    if e * e == e:
                        id_el = e
                        break
                except Exception:
                    pass
            if id_el is None:
                raise ValueError("No identity element found")
        
        # Find conjugacy classes
        seen = set()
        classes = []
        for x in elements:
            if x in seen:
                continue
            cclass = set()
            for g in elements:
                try:
                    inv_g = ~g
                except Exception:
                    inv_g = g**-1
                cclass.add(g * x * inv_g)
            classes.append(cclass)
            seen.update(cclass)
            
        # Compute normal closures for each conjugacy class (excluding identity)
        normal_closures = []
        for cclass in classes:
            rep = next(iter(cclass))
            if rep == id_el:
                continue
            
            gens = cclass
            closure = set(gens)
            closure.add(id_el)
            queue = list(closure)
            while queue:
                curr = queue.pop(0)
                for gen in gens:
                    nxt = curr * gen
                    if nxt not in closure:
                        closure.add(nxt)
                        queue.append(nxt)
            normal_closures.append(closure)

        # Find unique normal closures
        unique_closures = []
        for C in normal_closures:
            if C not in unique_closures:
                unique_closures.append(C)
                
        # Minimal normal subgroups are the minimal elements among the normal closures
        minimal_closures = []
        for C in unique_closures:
            is_minimal = True
            for other in unique_closures:
                if other != C and other.issubset(C):
                    is_minimal = False
                    break
            if is_minimal:
                minimal_closures.append(C)
                
        # Check if the union of all minimal normal subgroups generates G
        all_gens = set()
        for N in minimal_closures:
            all_gens.update(N)
        
        if not all_gens:
            all_gens.add(id_el)
            
        closure_h2 = set(all_gens)
        queue_h2 = list(all_gens)
        while queue_h2:
            curr = queue_h2.pop(0)
            for gen in all_gens:
                nxt = curr * gen
                if nxt not in closure_h2:
                    closure_h2.add(nxt)
                    queue_h2.append(nxt)
                    
        h2_ok = (closure_h2 == set(elements))
    except Exception:
        h2_ok = False
        minimal_closures = []

    # ¬Q: G is NOT isomorphic to a direct product of non-abelian simple groups
    try:
        if not h2_ok:
            # If it's not generated by minimal normal subgroups, it cannot be a direct product of simple groups
            conclusion = False
        else:
            # If H2 holds, G is a direct product of non-abelian simple groups iff ALL its minimal normal subgroups are non-abelian
            all_non_abelian = True
            for N in minimal_closures:
                is_ab = True
                N_list = list(N)
                for i in range(len(N_list)):
                    for j in range(i + 1, len(N_list)):
                        if N_list[i] * N_list[j] != N_list[j] * N_list[i]:
                            is_ab = False
                            break
                    if not is_ab:
                        break
                if is_ab:
                    all_non_abelian = False
                    break
            conclusion = all_non_abelian
            
        neg_q = not conclusion
    except Exception:
        neg_q = False

    return [h1_ok, h2_ok, neg_q]

