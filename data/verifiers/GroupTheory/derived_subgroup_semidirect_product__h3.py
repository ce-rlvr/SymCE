def conditions(witness):
    """
    Given a witness, checks if it is a valid counterexample to the false conjecture.
    The witness should be a tuple (G, N, H, phi) where:
      - G is the group for which we are evaluating the derived subgroup G'
      - N and H are groups
      - phi is a callable phi(h, n) representing the homomorphism H -> Aut(N)
    """
    try:
        if len(witness) == 4:
            G, N, H, phi = witness
        else:
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]
        
    # H_1: N and H are groups
    try:
        h1 = isinstance(N, PermutationGroup) and isinstance(H, PermutationGroup)
    except Exception:
        h1 = False
        
    # H_2: phi is a group homomorphism from H to Aut(N)
    try:
        h2 = True
        # Check if phi(h) is an automorphism of N for all h in H
        for h in H.elements:
            for n1 in N.elements:
                for n2 in N.elements:
                    if phi(h, n1 * n2) != phi(h, n1) * phi(h, n2):
                        h2 = False
                        break
            if not h2:
                break
        # Check if phi is a homomorphism: phi(h1 * h2) == phi(h1) o phi(h2)
        if h2:
            for h1_el in H.elements:
                for h2_el in H.elements:
                    for n in N.elements:
                        if phi(h1_el * h2_el, n) != phi(h1_el, phi(h2_el, n)):
                            h2 = False
                            break
                    if not h2:
                        break
                if not h2:
                    break
    except Exception:
        h2 = False
        
    # H_3: [N, H] is the subgroup of N generated by { n^-1 phi_h(n) | n in N, h in H }
    try:
        gens = []
        for n in N.elements:
            for h in H.elements:
                gens.append(n**-1 * phi(h, n))
        if not gens:
            gens = [N.identity]
        NH_comm = PermutationGroup(gens)
        h3 = True
    except Exception:
        h3 = False
        
    # neg_Q: The derived subgroup G' is NOT equal to the semidirect product (N'[N,H]) rtimes H'
    try:
        G_prime = G.derived_subgroup()
        N_prime = N.derived_subgroup()
        H_prime = H.derived_subgroup()
        
        N_prime_NH_gens = list(N_prime.generators) + list(NH_comm.generators)
        if not N_prime_NH_gens:
            N_prime_NH_gens = [N.identity]
        N_prime_NH = PermutationGroup(N_prime_NH_gens)
        
        # The order of the external semidirect product is the product of the orders of the two groups
        order_semidirect = N_prime_NH.order() * H_prime.order()
        
        # If G' is equal to the semidirect product, their orders must match.
        # The conjecture claims they are equal, so we check if they are NOT equal.
        neg_q = G_prime.order() != order_semidirect
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

