def conditions(witness) -> list[bool]:
    # Ensure the witness is a PermutationGroup (which inherently acts on its domain X = range(degree))
    try:
        if not isinstance(witness, PermutationGroup):
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]

    # H_1: G is a group
    try:
        h1 = True
    except Exception:
        h1 = False

    # H_2: X is a set with at least two elements
    try:
        h2 = bool(witness.degree >= 2)
    except Exception:
        h2 = False

    # H_3: G acts transitively on X
    try:
        h3 = bool(witness.is_transitive())
    except Exception:
        h3 = False

    # neg_Q: The action of G on X is primitive if and only if the stabilizer subgroup G_x is a maximal subgroup of G.
    # We evaluate both sides independently and check if the equivalence fails.
    try:
        # Left side: Is the action primitive?
        is_prim = bool(witness.is_primitive())

        # Right side: Is the stabilizer G_x a maximal subgroup of G?
        # We use x = 0 as the representative point.
        H = witness.stabilizer(0)
        
        if H.order() == witness.order():
            is_max = False
        else:
            is_max = True
            # Check if there is any proper subgroup strictly containing H
            for g in witness.elements:
                if g in H:
                    continue
                # Subgroup generated by H and g
                gens = list(H.generators) + [g]
                K = PermutationGroup(gens)
                if K.order() < witness.order():
                    is_max = False
                    break

        # The conclusion FAILS if the equivalence does not hold
        neg_q = (is_prim != is_max)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

