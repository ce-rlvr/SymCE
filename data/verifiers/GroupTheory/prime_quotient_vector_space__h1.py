def conditions(witness):
    try:
        A, p = witness
    except Exception:
        return [False, False, False]
    
    # H_1: p is a prime number
    try:
        h1_ok = bool(isprime(p))
    except Exception:
        h1_ok = False

    # H_2: pA = {a^p | a \in A} is a subgroup of A
    try:
        elements = list(A.elements)
        p_powers = set()
        for g in elements:
            p_powers.add(g**p)
            
        p_powers_list = list(p_powers)
        h2_ok = True
        # Since A is finite, closure under multiplication is sufficient for a subset to be a subgroup
        for x in p_powers_list:
            for y in p_powers_list:
                if (x * y) not in p_powers:
                    h2_ok = False
                    break
            if not h2_ok:
                break
    except Exception:
        h2_ok = False

    # ¬Q: A/pA does NOT possess a natural structure as a vector space over F_p
    # A/pA is a vector space over F_p iff it is an elementary abelian p-group.
    # Since pA is generated by p-th powers, every element in A/pA already has order dividing p.
    # Thus, A/pA is a vector space over F_p iff A/pA is abelian.
    # A/pA is abelian iff pA contains the commutator subgroup [A, A].
    try:
        gens = A.generators
        is_abelian_quotient = True
        for x in gens:
            for y in gens:
                commutator = (x**-1) * (y**-1) * x * y
                if commutator not in p_powers:
                    is_abelian_quotient = False
                    break
            if not is_abelian_quotient:
                break
        neg_q_ok = not is_abelian_quotient
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, neg_q_ok]

