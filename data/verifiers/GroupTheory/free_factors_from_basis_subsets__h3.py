def conditions(witness):
    try:
        if len(witness) == 3:
            F_wit, X, Y = witness
            H_ok = True
        elif len(witness) == 4:
            F_wit, X, Y, H = witness
            H_ok = True
        else:
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]

    # H_1: F is a free group
    try:
        h1 = isinstance(F_wit, FreeGroup)
    except Exception:
        h1 = False

    # H_2: X is a free basis for F
    try:
        h2 = False
        if h1:
            if isinstance(X, FreeGroupElement):
                X_list = [X]
            else:
                X_list = list(X)
                
            if len(X_list) == len(F_wit.generators):
                M_cols = []
                for x_elem in X_list:
                    vec = [0] * len(F_wit.generators)
                    for gen, power in x_elem.array_form:
                        try:
                            idx = F_wit.generators.index(gen)
                            vec[idx] += power
                        except ValueError:
                            pass
                    M_cols.append(vec)
                M = sympy.Matrix(M_cols).T
                if abs(M.det()) == 1:
                    h2 = True
    except Exception:
        h2 = False

    # H_3: H is the subgroup of F generated by Y
    try:
        h3 = False
        if h1:
            if isinstance(Y, FreeGroupElement):
                Y_list = [Y]
            else:
                Y_list = list(Y)
            h3 = H_ok and all(isinstance(y_elem, FreeGroupElement) and y_elem.group == F_wit for y_elem in Y_list)
    except Exception:
        h3 = False

    # neg_Q: H is NOT a free factor of F, OR Y does NOT freely generate H
    try:
        neg_q = False
        if h1 and h2 and h3:
            if len(Y_list) > len(X_list):
                neg_q = True
            elif len(Y_list) > 0:
                M_cols = []
                for y_elem in Y_list:
                    vec = [0] * len(F_wit.generators)
                    for gen, power in y_elem.array_form:
                        try:
                            idx = F_wit.generators.index(gen)
                            vec[idx] += power
                        except ValueError:
                            pass
                    M_cols.append(vec)
                
                M = sympy.Matrix(M_cols).T
                k = len(Y_list)
                
                minors = []
                for row_indices in itertools.combinations(range(len(X_list)), k):
                    submatrix = M[list(row_indices), :]
                    minors.append(int(submatrix.det()))
                    
                g = functools.reduce(math.gcd, minors, 0)
                
                # If the gcd of the k x k minors of the exponent sum matrix is not 1,
                # then the abelianization of H is not a direct summand of rank k in F_ab.
                # This implies H is either not a free factor, or Y does not freely generate H.
                if abs(g) != 1:
                    neg_q = True
                else:
                    # Also fails if any generator is the identity
                    if any(len(y_elem) == 0 for y_elem in Y_list):
                        neg_q = True
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

