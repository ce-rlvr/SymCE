import sympy
from sympy.combinatorics import AlternatingGroup
from sympy.combinatorics.permutations import Permutation
import itertools

# Top-level setup
# No specific named objects are required for this conjecture, as the witness is just an integer n.

def conditions(witness) -> list[bool]:
    """
    Check if the witness is a valid counterexample to the false conjecture.
    
    Remaining hypotheses:
      - n is an integer with n >= 3.
      - X is the set {1, 2, ..., n}.
      
    Conclusion (must FAIL at the witness):
      The natural action of A_n on X is (n-2)-transitive.
    """
    # H_1: n is an integer with n >= 3
    try:
        n = int(witness)
        h1_ok = (n >= 3 and n == witness)
    except Exception:
        h1_ok = False

    # H_2: X is the set {1, 2, ..., n}
    # This is a definitional hypothesis, so it holds vacuously if H_1 holds.
    h2_ok = h1_ok

    # neg_Q: The natural action of A_n on X is NOT (n-2)-transitive.
    # A group action is k-transitive if it acts transitively on the set of all k-tuples of distinct elements.
    neg_q_ok = False
    if h1_ok:
        try:
            k = n - 2
            if k == 0:
                # 0-transitive is vacuously true, so it doesn't fail.
                neg_q_ok = False
            else:
                # Generate all k-tuples of distinct elements from {0, 1, ..., n-1}
                elements = list(range(n))
                k_tuples = list(itertools.permutations(elements, k))
                
                # We need to check if A_n acts transitively on k_tuples.
                # Since A_n is generated by 3-cycles, we can compute the orbit of the first k-tuple.
                # If the orbit size equals the number of k-tuples, it is k-transitive.
                
                # A_n generators
                A_n = AlternatingGroup(n)
                generators = list(A_n.generators)
                
                start_tuple = k_tuples[0]
                orbit = set([start_tuple])
                queue = [start_tuple]
                
                while queue:
                    current = queue.pop(0)
                    for g in generators:
                        # Apply g to the current k-tuple
                        next_tuple = tuple(g(x) for x in current)
                        if next_tuple not in orbit:
                            orbit.add(next_tuple)
                            queue.append(next_tuple)
                            
                # If the orbit size is less than the total number of k-tuples, it is NOT k-transitive.
                neg_q_ok = len(orbit) < len(k_tuples)
        except Exception:
            neg_q_ok = False

    return [h1_ok, h2_ok, neg_q_ok]

