def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, tuple) and len(witness) == 3:
            G, p, P = witness
        else:
            G = witness.G
            p = witness.p
            P = witness.P
    except Exception:
        return [False, False, False]
        
    # H1: p is a prime number
    try:
        h1 = bool(sympy.isprime(p))
    except Exception:
        h1 = False
        
    # H2: P is a Sylow p-subgroup of G
    try:
        if hasattr(witness, 'is_sylow'):
            h2 = bool(witness.is_sylow() if callable(witness.is_sylow) else witness.is_sylow)
        else:
            is_subgroup = bool(P.is_subgroup(G))
            order_P = P.order()
            order_G = G.order()
            
            if order_G == sympy.oo:
                h2 = False
            else:
                k = sympy.ntheory.factorint(order_P).get(p, 0)
                if order_P == p**k and order_P > 0:
                    index = order_G // order_P
                    h2 = is_subgroup and (index % p != 0)
                else:
                    h2 = False
    except Exception:
        h2 = False
        
    # neg_Q: P intersect G_prime is NOT generated by the set S
    try:
        if hasattr(witness, 'P_cap_G_prime'):
            intersection_elements = set(witness.P_cap_G_prime() if callable(witness.P_cap_G_prime) else witness.P_cap_G_prime)
        elif hasattr(P, 'intersect') and hasattr(G, 'derived_subgroup'):
            intersection = P.intersect(G.derived_subgroup())
            intersection_elements = set(intersection.elements)
        else:
            G_prime = G.derived_subgroup() if callable(G.derived_subgroup) else G.derived_subgroup
            intersection_elements = set(P.elements).intersection(set(G_prime.elements))
            
        P_elements = list(P.elements)
        P_set = set(P_elements)
        S = set()
        
        if hasattr(G, 'is_conjugate'):
            for x in P_elements:
                for y in P_elements:
                    if G.is_conjugate(x, y):
                        S.add(x**-1 * y)
        else:
            G_elements = list(G.elements)
            for x in P_elements:
                for g in G_elements:
                    y = g**-1 * x * g
                    if y in P_set:
                        S.add(x**-1 * y)
                        
        S_subgroup_elements = set(S)
        if hasattr(G, 'identity'):
            identity = G.identity
        else:
            identity = P_elements[0]**0 if P_elements else None
            
        if identity is not None:
            S_subgroup_elements.add(identity)
            
        S_inv = {b**-1 for b in S}
        S_gen = S.union(S_inv)
        
        added = True
        while added:
            added = False
            new_elements = set()
            for a in S_subgroup_elements:
                for b in S_gen:
                    c = a * b
                    if c not in S_subgroup_elements:
                        new_elements.add(c)
                        added = True
            S_subgroup_elements.update(new_elements)
            
        neg_q = bool(intersection_elements != S_subgroup_elements)
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]