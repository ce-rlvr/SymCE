def conditions(witness):
    try:
        if isinstance(witness, dict):
            G = witness.get('G')
            a = witness.get('a')
            k = witness.get('k')
            n = witness.get('n')
        else:
            G, a, k, n = witness
    except Exception:
        return [False, False, False, False]

    # H_1: G is a cyclic group
    try:
        h1 = isinstance(G, PermutationGroup) and any(g.order() == G.order() for g in G.elements)
    except Exception:
        h1 = False

    # H_2: G is generated by an element a
    try:
        h2 = a in G and a.order() == G.order()
    except Exception:
        h2 = False

    # H_3: k is an integer
    try:
        h3 = isinstance(k, (int, sympy.Integer))
    except Exception:
        h3 = False

    # neg_Q: The subgroup generated by a^k is not equal to the subgroup generated by a^gcd(k,n)
    try:
        ak = a ** k
        agcd = a ** sympy.gcd(k, n)
        
        H_k = PermutationGroup([ak])
        H_gcd = PermutationGroup([agcd])
        
        elements_k = list(H_k.elements)
        elements_gcd = list(H_gcd.elements)
        
        neg_q = len(elements_k) != len(elements_gcd) or any(e not in elements_gcd for e in elements_k)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

