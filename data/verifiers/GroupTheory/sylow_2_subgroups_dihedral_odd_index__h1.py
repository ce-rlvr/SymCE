def is_dihedral(G):
    """Check if G is isomorphic to the dihedral group D_{2n} of order 2n."""
    try:
        if not hasattr(G, 'order'): return False
        order = G.order()
        if order % 2 != 0: return False
        if order > 2000: return False # Protect against excessively large groups
        n = order // 2
        elements = list(G.elements)
        for r in elements:
            if r.order() == n:
                H = set()
                curr = r
                for _ in range(n):
                    H.add(curr)
                    curr = curr * r
                if len(H) != n:
                    continue
                is_d = True
                for x in elements:
                    if x not in H:
                        if x.order() != 2:
                            is_d = False
                            break
                if is_d:
                    return True
        return False
    except Exception:
        return False

def is_sylow_2_subgroup(G, P):
    """Check if P is a Sylow 2-subgroup of G."""
    try:
        if not hasattr(P, 'generators'): return False
        for g in P.generators:
            if g not in G:
                return False
        order_G = G.order()
        order_P = P.order()
        if order_P < 1: return False
        # Check if order_P is a power of 2
        if order_P & (order_P - 1) != 0: return False
        # Check if the index of P in G is odd
        if (order_G // order_P) % 2 == 0: return False
        return True
    except Exception:
        return False

def is_reflection(G, g):
    """Check if g is a reflection element in the dihedral group G."""
    try:
        if g not in G: return False
        if g.order() != 2: return False
        n = G.order() // 2
        elements = list(G.elements)
        for r in elements:
            if r.order() == n:
                H = set()
                curr = r
                for _ in range(n):
                    H.add(curr)
                    curr = curr * r
                if len(H) == n:
                    is_d = True
                    for x in elements:
                        if x not in H and x.order() != 2:
                            is_d = False
                            break
                    if is_d:
                        if g not in H:
                            return True
        return False
    except Exception:
        return False

def conclusion_holds(G, P):
    """Check if P has order 2 and is generated by a single reflection element."""
    try:
        if P.order() != 2:
            return False
        for g in P.elements:
            if g.order() == 2:
                return is_reflection(G, g)
        return False
    except Exception:
        return False

def conditions(witness):
    try:
        G, P = witness
    except Exception:
        return [False, False, False]
    
    try:
        h1 = is_dihedral(G)
    except Exception:
        h1 = False
        
    try:
        h2 = is_sylow_2_subgroup(G, P)
    except Exception:
        h2 = False
        
    try:
        neg_q = not conclusion_holds(G, P)
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

