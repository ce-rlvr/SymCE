def conditions(witness):
    try:
        G, N = witness
        h1 = isinstance(G, PermutationGroup) and isinstance(N, PermutationGroup)
    except Exception:
        h1 = False

    try:
        G, N = witness
        h2 = bool(N.is_subgroup(G) and N.is_normal(G))
    except Exception:
        h2 = False

    try:
        G, N = witness
        D = G.derived_subgroup()
        gens = list(D.generators) + list(N.generators)
        if not gens:
            DN_order = 1
        else:
            DN = PermutationGroup(gens)
            DN_order = DN.order()
        # G/N is perfect iff the subgroup generated by G' and N equals G
        neg_q = bool(DN_order != G.order())
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

