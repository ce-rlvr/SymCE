def get_attr(witness, attr):
    if isinstance(witness, dict):
        return witness[attr]
    return getattr(witness, attr)

def conditions(witness) -> list[bool]:
    try:
        G = get_attr(witness, 'G')
        H = get_attr(witness, 'H')
        S = get_attr(witness, 'S')
        f = get_attr(witness, 'f')
        g = get_attr(witness, 'g')
    except Exception:
        return [False, False, False, False]

    # H_1: S is a subset of G such that the subgroup generated by S is G
    try:
        h1 = True
        for s in S:
            if s not in G:
                h1 = False
                break
        if h1:
            if len(S) == 0:
                id_elem = list(G.elements)[0]
                id_elem = id_elem * (~id_elem)
                gen_G = PermutationGroup([id_elem])
            else:
                gen_G = PermutationGroup(*S)
            if gen_G.order() != G.order():
                h1 = False
    except Exception:
        h1 = False

    # H_2: f: G \to H and g: G \to H are group homomorphisms
    try:
        h2 = True
        elements = list(G.elements)
        for x in elements:
            fx = f(x) if callable(f) else f[x]
            gx = g(x) if callable(g) else g[x]
            if fx not in H or gx not in H:
                h2 = False
                break
        if h2:
            for x in elements:
                for y in elements:
                    fx = f(x) if callable(f) else f[x]
                    fy = f(y) if callable(f) else f[y]
                    fxy = f(x*y) if callable(f) else f[x*y]
                    if fxy != fx * fy:
                        h2 = False
                        break
                    
                    gx = g(x) if callable(g) else g[x]
                    gy = g(y) if callable(g) else g[y]
                    gxy = g(x*y) if callable(g) else g[x*y]
                    if gxy != gx * gy:
                        h2 = False
                        break
                if not h2:
                    break
    except Exception:
        h2 = False

    # H_3: For every s \in S, f(s) = g(s)
    try:
        h3 = True
        for s in S:
            fs = f(s) if callable(f) else f[s]
            gs = g(s) if callable(g) else g[s]
            if fs != gs:
                h3 = False
                break
    except Exception:
        h3 = False

    # ¬Q: f(x) != g(x) for some x \in G
    try:
        neg_q = False
        elements = list(G.elements)
        for x in elements:
            fx = f(x) if callable(f) else f[x]
            gx = g(x) if callable(g) else g[x]
            if fx != gx:
                neg_q = True
                break
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

