def is_semisimple(G):
    """
    A finite group is semisimple if it has no non-trivial abelian normal subgroups.
    Equivalently, the normal closure of every non-identity element is non-abelian.
    """
    try:
        if G.order() == 1:
            return True
            
        gens = G.generators
        id_el = G.identity
        seen = set([id_el])
        
        for x in G.elements:
            if x in seen:
                continue
                
            # Find the conjugacy class of x using BFS
            conjugates = set([x])
            queue = [x]
            while queue:
                curr = queue.pop(0)
                for g in gens:
                    for conj in (g * curr * ~g, ~g * curr * g):
                        if conj not in conjugates:
                            conjugates.add(conj)
                            queue.append(conj)
                            
            seen.update(conjugates)
            
            # The normal closure of x is generated by its conjugacy class.
            # It is abelian iff all elements in the conjugacy class commute.
            conj_list = list(conjugates)
            is_abelian = True
            for i in range(len(conj_list)):
                for j in range(i + 1, len(conj_list)):
                    if conj_list[i] * conj_list[j] != conj_list[j] * conj_list[i]:
                        is_abelian = False
                        break
                if not is_abelian:
                    break
                    
            if is_abelian:
                return False
                
        return True
    except Exception:
        return False

def is_subgroup(H, G):
    try:
        if not isinstance(H, PermutationGroup): 
            return False
        if H.order() == 1:
            return True
        for g in H.generators:
            if g == H.identity:
                continue
            in_G = False
            try:
                in_G = G.contains(g)
            except Exception:
                in_G = False
            if not in_G:
                return False
        return True
    except Exception:
        return False

def is_normal_subgroup(H, G):
    try:
        if not is_subgroup(H, G): 
            return False
        if H.order() == 1:
            return True
        for h in H.generators:
            if h == H.identity:
                continue
            for g in G.generators:
                try:
                    conj1 = g * h * ~g
                    in_H1 = H.contains(conj1)
                except Exception:
                    in_H1 = False
                if not in_H1: return False
                
                try:
                    conj2 = ~g * h * g
                    in_H2 = H.contains(conj2)
                except Exception:
                    in_H2 = False
                if not in_H2: return False
        return True
    except Exception:
        return False

def trivial_intersection(H, K):
    try:
        if H.order() > K.order():
            H, K = K, H
        for h in H.elements:
            if h == H.identity:
                continue
            in_K = False
            try:
                in_K = K.contains(h)
            except Exception:
                in_K = False
            if in_K:
                return False
        return True
    except Exception:
        return False

def is_internal_direct_product(G, H, K):
    try:
        if not is_normal_subgroup(H, G): return False
        if not is_normal_subgroup(K, G): return False
        if H.order() * K.order() != G.order(): return False
        if not trivial_intersection(H, K): return False
        return True
    except Exception:
        return False

def conditions(witness):
    try:
        if len(witness) != 3:
            return [False, False, False, False]
        G, H, K = witness
    except Exception:
        return [False, False, False, False]
        
    # H1: G is a finite semisimple group
    try:
        h1 = isinstance(G, PermutationGroup) and is_semisimple(G)
    except Exception:
        h1 = False
        
    # H2: H and K are subgroups of G
    try:
        h2 = is_subgroup(H, G) and is_subgroup(K, G)
    except Exception:
        h2 = False
        
    # H3: G is the internal direct product of H and K
    try:
        h3 = is_internal_direct_product(G, H, K)
    except Exception:
        h3 = False
        
    # neg_Q: H is not the trivial subgroup or K is not equal to G
    try:
        neg_q = not (H.order() == 1 and K.order() == G.order())
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

