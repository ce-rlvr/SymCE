def conditions(witness):
    # H_1: G is the alternating group A_p on p letters
    try:
        if isinstance(witness, PermutationGroup):
            p = witness.degree
            if p >= 2:
                # A_p has order p! / 2 and is generated by even permutations
                if witness.order() == math.factorial(p) // 2:
                    h1 = all(g.is_even for g in witness.generators)
                else:
                    h1 = False
            elif p == 1:
                # A_1 is the trivial group
                if witness.order() == 1:
                    h1 = True
                else:
                    h1 = False
            else:
                h1 = False
        else:
            h1 = False
    except Exception:
        h1 = False

    # neg_Q: The number of Sylow p-subgroups of G is not exactly (p-2)!
    try:
        if isinstance(witness, PermutationGroup):
            p = witness.degree
            # Sylow p-subgroups are only defined when p is a prime number.
            # If p is not prime, the concept is undefined, so the number is not (p-2)!.
            if not isprime(p):
                neg_q = True
            else:
                # If p is prime, the theorem holds and the number of Sylow p-subgroups is exactly (p-2)!.
                neg_q = False
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, neg_q]

