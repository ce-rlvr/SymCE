def can_be_generated_by_at_most_n(grp, n):
    if n < 0:
        return False
    if n == 0:
        return getattr(grp, 'is_trivial', False)
    if getattr(grp, 'is_trivial', False):
        return True
    if getattr(grp, 'is_abelian', False):
        try:
            return len(grp.abelian_invariants()) <= n
        except Exception:
            pass
            
    # Fallback for PermutationGroup
    try:
        if hasattr(grp, 'generators') and n >= len(grp.generators):
            return True
            
        if hasattr(grp, 'generate') and hasattr(grp, 'order'):
            elems = list(grp.generate())
            order = grp.order()
            if n == 1:
                return any(PermutationGroup([g]).order() == order for g in elems)
                
            if len(elems) <= 60 and n <= 3:
                for subset in combinations(elems, n):
                    if PermutationGroup(list(subset)).order() == order:
                        return True
                return False
    except Exception:
        pass
        
    return True # Safe fallback

def conditions(witness):
    try:
        if isinstance(witness, dict):
            G = witness['G']
            n = witness['n']
            H = witness['H']
        else:
            G, n, H = witness
    except Exception:
        return [False, False, False]
        
    # H1: G is an abelian group
    try:
        h1 = bool(G.is_abelian)
    except Exception:
        h1 = False
        
    # H2: G can be generated by n elements
    try:
        h2 = bool(can_be_generated_by_at_most_n(G, n))
    except Exception:
        h2 = False
        
    # neg_Q: H CANNOT be generated by at most n elements
    try:
        neg_q = not can_be_generated_by_at_most_n(H, n)
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]

