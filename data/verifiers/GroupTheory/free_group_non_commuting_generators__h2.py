CONDITION_LABELS = [
    "H_1: F is a free group",
    "H_2: a and b do not commute",
    "¬Q: The subgroup generated by a and b is not isomorphic to the free group of rank 2"
]

N_HYP = 2
NEG_Q_INDEX = 2

def conditions(witness) -> list[bool]:
    try:
        F, a, b = witness
    except Exception:
        return [False, False, False]
        
    # H_1: F is a free group
    try:
        h1 = (type(F).__name__ == 'FreeGroup')
    except Exception:
        h1 = False
        
    # H_2: a and b do not commute
    try:
        h2 = bool(a * b != b * a)
    except Exception:
        h2 = False
        
    # ¬Q: The subgroup generated by a and b is not isomorphic to the free group of rank 2
    try:
        # If a and b are elements of the same free group and don't commute, they generate F_2.
        if type(a).__name__ == 'FreeGroupElement' and type(b).__name__ == 'FreeGroupElement':
            if hasattr(a, 'group') and hasattr(b, 'group') and a.group == b.group:
                generates_f2 = bool(a * b != b * a)
            else:
                generates_f2 = False
        else:
            # For permutations, finite matrices, or other typical counterexample elements, 
            # they generate a finite or non-free group.
            generates_f2 = False
            
        neg_q = not generates_f2
    except Exception:
        neg_q = False
        
    return [h1, h2, neg_q]