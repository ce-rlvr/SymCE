def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, dict):
            G = witness.get('G')
            P = witness.get('P')
            p = witness.get('p')
            n_p = witness.get('n_p')
        else:
            G, P, p, n_p = witness
    except Exception:
        return [False, False, False, False]

    # H1: G is a finite group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False

    # H2: P is a Sylow p-subgroup of G
    try:
        h2 = False
        if isinstance(P, PermutationGroup) and isinstance(G, PermutationGroup):
            G_elements = set(G.elements)
            is_sub = all(gen in G_elements for gen in P.generators)
            if is_sub and isinstance(p, int) and p > 1:
                order_G = G.order()
                order_P = P.order()
                max_pow = 1
                while order_G % (max_pow * p) == 0:
                    max_pow *= p
                if order_P == max_pow:
                    h2 = True
    except Exception:
        h2 = False

    # H3: n_p is the number of Sylow p-subgroups of G
    try:
        h3 = False
        if h2 and isinstance(n_p, int):
            K = P.order()
            elements = list(G.elements)
            valid_elements = [e for e in elements if K % e.order() == 0]
            seen = set()
            n_valid = len(valid_elements)
            
            # For small groups, any subgroup of order K can be generated by at most 2 elements
            for i in range(n_valid):
                e1 = valid_elements[i]
                for j in range(i, n_valid):
                    e2 = valid_elements[j]
                    H = PermutationGroup([e1, e2])
                    if H.order() == K:
                        seen.add(frozenset(H.elements))
                        
            if len(seen) == n_p:
                h3 = True
    except Exception:
        h3 = False

    # neg_Q: The index of the normalizer N_G(P) in G is NOT equal to n_p
    try:
        neg_q = False
        if h2 and isinstance(n_p, int):
            P_elements = set(P.elements)
            P_gens = P.generators
            normalizer_order = 0
            
            for g in G.elements:
                normalizes = True
                for x in P_gens:
                    conj = g * x * (~g)
                    if conj not in P_elements:
                        normalizes = False
                        break
                if normalizes:
                    normalizer_order += 1
            
            index = G.order() // normalizer_order
            if index != n_p:
                neg_q = True
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

