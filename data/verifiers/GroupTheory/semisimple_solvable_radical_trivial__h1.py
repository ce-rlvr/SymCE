def conditions(witness):
    try:
        if not isinstance(witness, PermutationGroup):
            return [False, False]
            
        if witness.order() == 1:
            # The trivial group is the empty direct product of non-abelian simple groups.
            # Its solvable radical is trivial.
            return [True, False]
            
        gens = list(witness.generators) + [~gen for gen in witness.generators]
        visited = set()
        closures = []
        has_trivial_rad = True
        
        for g in witness.generate():
            if g in visited:
                continue
            if g.is_Identity:
                visited.add(g)
                continue
                
            # Compute the conjugacy class of g
            conj_class = set([g])
            queue = [g]
            while queue:
                curr = queue.pop(0)
                for gen in gens:
                    conj = ~gen * curr * gen
                    if conj not in conj_class:
                        conj_class.add(conj)
                        queue.append(conj)
            visited.update(conj_class)
            
            # If we haven't found a non-trivial abelian normal subgroup yet, check this normal closure.
            # The normal closure is abelian iff all its generators (the conjugacy class) commute.
            if has_trivial_rad:
                is_abelian = True
                conj_list = list(conj_class)
                for i in range(len(conj_list)):
                    for j in range(i + 1, len(conj_list)):
                        if conj_list[i] * conj_list[j] != conj_list[j] * conj_list[i]:
                            is_abelian = False
                            break
                    if not is_abelian:
                        break
                if is_abelian:
                    has_trivial_rad = False
                    
            # The normal closure of g is the group generated by its conjugacy class
            C = PermutationGroup(list(conj_class))
            
            # Maintain only the minimal normal subgroups
            is_minimal = True
            to_remove = []
            for M in closures:
                # Check if M is a subgroup of C
                m_in_c = True
                for m_gen in M.generators:
                    if not C.contains(m_gen):
                        m_in_c = False
                        break
                if m_in_c:
                    is_minimal = False
                    break
                    
                # Check if C is a subgroup of M
                c_in_m = True
                for c_gen in C.generators:
                    if not M.contains(c_gen):
                        c_in_m = False
                        break
                if c_in_m:
                    to_remove.append(M)
                    
            if is_minimal:
                for M in to_remove:
                    closures.remove(M)
                closures.append(C)
                
        # The conclusion is that the solvable radical is trivial.
        # neg_Q is True if the conclusion fails (i.e., solvable radical is NOT trivial).
        neg_Q = not has_trivial_rad
        
        # H1: G is isomorphic to a direct product of non-abelian simple groups.
        # A finite group is a direct product of non-abelian simple groups iff 
        # it has a trivial solvable radical and is generated by its minimal normal subgroups (i.e., G == Socle(G)).
        if not has_trivial_rad:
            H1 = False
        else:
            socle_gens = []
            for M in closures:
                socle_gens.extend(M.generators)
            socle = PermutationGroup(socle_gens)
            H1 = (socle.order() == witness.order())
            
        return [H1, neg_Q]
    except Exception:
        return [False, False]

