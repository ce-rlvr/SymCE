def conditions(witness):
    """
    Checks whether the given witness is a valid counterexample to the false conjecture.
    The witness should be a tuple (N, H, phi) where:
      - N and H are SymPy PermutationGroups.
      - phi is a callable phi(h, n) returning the action of h on n, or a dict-like object.
    """
    try:
        N, H, phi = witness
        if callable(phi):
            phi_func = phi
        else:
            phi_func = lambda h, n: phi[h][n]
    except Exception:
        return [False, False, False]

    # H_1: N is an abelian group
    try:
        elements_N = list(N.generate())
        h1_ok = True
        for a in elements_N:
            for b in elements_N:
                if a * b != b * a:
                    h1_ok = False
                    break
            if not h1_ok:
                break
    except Exception:
        h1_ok = False

    # H_2: phi: H -> Aut(N) is a group homomorphism
    try:
        elements_H = list(H.generate())
        id_H = next(e for e in elements_H if all(e * x == x for x in elements_H))
        id_N = next(e for e in elements_N if all(e * x == x for x in elements_N))
        
        h2_ok = True
        # Check that phi_h is an endomorphism of N for all h
        for h in elements_H:
            for n1 in elements_N:
                for n2 in elements_N:
                    pn1 = phi_func(h, n1)
                    if pn1 not in elements_N:
                        h2_ok = False
                    pn2 = phi_func(h, n2)
                    if phi_func(h, n1 * n2) != pn1 * pn2:
                        h2_ok = False
        
        # Check that phi is a homomorphism from H to Aut(N)
        if h2_ok:
            for h1 in elements_H:
                for h2 in elements_H:
                    for n in elements_N:
                        if phi_func(h1 * h2, n) != phi_func(h1, phi_func(h2, n)):
                            h2_ok = False
                            
        # Check that phi_{1_H} is the identity on N
        if h2_ok:
            for n in elements_N:
                if phi_func(id_H, n) != n:
                    h2_ok = False
    except Exception:
        h2_ok = False

    # neg_Q: The derived subgroup of N rtimes H is NOT exactly the subgroup generated by (n^-1 phi_h(n), 1_H)
    try:
        def mul(x, y):
            return (x[0] * phi_func(x[1], y[0]), x[1] * y[1])
            
        def inv(x):
            h_inv = x[1]**-1
            n_inv = x[0]**-1
            return (phi_func(h_inv, n_inv), h_inv)
            
        G_elements = [(n, h) for n in elements_N for h in elements_H]
        
        commutators = set()
        for x in G_elements:
            for y in G_elements:
                xy = mul(x, y)
                x_inv = inv(x)
                y_inv = inv(y)
                x_inv_y_inv = mul(x_inv, y_inv)
                comm = mul(xy, x_inv_y_inv)
                commutators.add(comm)
                
        def get_closure(generators, mul_func, identity):
            closure = set(generators)
            closure.add(identity)
            queue = list(closure)
            while queue:
                x = queue.pop(0)
                for y in list(closure):
                    xy = mul_func(x, y)
                    if xy not in closure:
                        closure.add(xy)
                        queue.append(xy)
                    yx = mul_func(y, x)
                    if yx not in closure:
                        closure.add(yx)
                        queue.append(yx)
            return closure
            
        G_prime = get_closure(commutators, mul, (id_N, id_H))
        
        S_generators = set()
        for n in elements_N:
            for h in elements_H:
                n_inv = n**-1
                val = n_inv * phi_func(h, n)
                S_generators.add((val, id_H))
                
        S_subgroup = get_closure(S_generators, mul, (id_N, id_H))
        
        neg_q_ok = (G_prime != S_subgroup)
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, neg_q_ok]

