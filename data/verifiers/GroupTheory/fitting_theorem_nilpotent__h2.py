def conditions(witness) -> list[bool]:
    try:
        G, M, N = witness
    except Exception:
        return [False, False, False, False, False]

    # H1: G is a group, M and N are subgroups of G
    try:
        h1 = (isinstance(G, PermutationGroup) and 
              isinstance(M, PermutationGroup) and 
              isinstance(N, PermutationGroup) and 
              all(g in G for g in M.generators) and 
              all(g in G for g in N.generators))
    except Exception:
        h1 = False

    # H2: N is a normal subgroup of G
    try:
        h2 = True
        for g in G.generators:
            for n in N.generators:
                if (g * n * ~g) not in N:
                    h2 = False
                    break
            if not h2:
                break
    except Exception:
        h2 = False

    # H3: M is a nilpotent group
    try:
        h3 = bool(M.is_nilpotent)
    except Exception:
        h3 = False

    # H4: N is a nilpotent group
    try:
        h4 = bool(N.is_nilpotent)
    except Exception:
        h4 = False

    # neg_Q: The product MN is NOT a normal nilpotent subgroup of G
    try:
        M_elems = list(M.generate())
        N_elems = list(N.generate())
        MN_set = set(m * n for m in M_elems for n in N_elems)
        
        gens = list(M.generators) + list(N.generators)
        if not gens:
            gens = [G.identity]
        MN_group = PermutationGroup(gens)
        
        # If the size of the set MN is not equal to the order of the subgroup generated by M and N,
        # then MN is not a subgroup.
        if len(MN_set) != MN_group.order():
            neg_q = True
        else:
            # MN is a subgroup. Check if it is normal in G.
            is_normal = True
            for g in G.generators:
                for n in MN_group.generators:
                    if (g * n * ~g) not in MN_group:
                        is_normal = False
                        break
                if not is_normal:
                    break
            
            # Check if MN is nilpotent.
            is_nilpotent = bool(MN_group.is_nilpotent)
            
            neg_q = not (is_normal and is_nilpotent)
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]

