def conditions(witness) -> list[bool]:
    try:
        if len(witness) != 4:
            return [False, False, False]
        G, N, H, p = witness
    except Exception:
        return [False, False, False]
    
    # H1: G is a finite group that is the semidirect product of a normal subgroup N and a subgroup H.
    try:
        h1 = False
        if isinstance(G, PermutationGroup) and isinstance(N, PermutationGroup) and isinstance(H, PermutationGroup):
            if N.is_subgroup(G) and H.is_subgroup(G) and N.is_normal(G):
                # For a semidirect product, we need G = NH and N ∩ H = {id}.
                # Since N is normal, NH is exactly the subgroup generated by N and H.
                # If |N| * |H| == |G| and |NH| == |G|, it mathematically forces N ∩ H = {id} and G = NH.
                if N.order() * H.order() == G.order():
                    gen_G = PermutationGroup(list(N.generators) + list(H.generators))
                    if gen_G.order() == G.order():
                        h1 = True
    except Exception:
        h1 = False

    # H2: p is a prime number dividing the order of H.
    try:
        h2 = False
        if isprime(p) and isinstance(H, PermutationGroup) and H.order() % p == 0:
            h2 = True
    except Exception:
        h2 = False

    # neg_Q: Every Sylow p-subgroup of G is conjugate to a Sylow p-subgroup of H.
    # Negation: There exists a Sylow p-subgroup of G that is not conjugate to a Sylow p-subgroup of H.
    # Since all Sylow p-subgroups of G are conjugate to each other, they fail to be conjugate to 
    # a Sylow p-subgroup of H if and only if they have strictly different orders.
    try:
        neg_q = False
        if isinstance(G, PermutationGroup) and isinstance(H, PermutationGroup):
            order_G = G.order()
            order_H = H.order()
            
            def highest_power(n, pr):
                if pr <= 1: 
                    return 0
                count = 0
                while n % pr == 0:
                    count += 1
                    n //= pr
                return pr ** count
            
            if highest_power(order_G, p) != highest_power(order_H, p):
                neg_q = True
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

