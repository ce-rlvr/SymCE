def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, dict):
            G = witness.get('G')
            a = witness.get('a')
            k = witness.get('k')
            n = witness.get('n')
        elif isinstance(witness, (tuple, list)):
            if len(witness) == 4:
                G, a, k, n = witness
            elif len(witness) == 3:
                a, k, n = witness
                G = PermutationGroup([a])
            else:
                return [False, False, False]
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]

    # H_1: G is generated by the element a
    try:
        if isinstance(G, PermutationGroup):
            h1_ok = (a in G) and (G.order() == a.order())
        else:
            h1_ok = False
    except Exception:
        h1_ok = False

    # H_2: k is an integer
    try:
        h2_ok = isinstance(k, (int, sympy.Integer))
    except Exception:
        h2_ok = False

    # ¬Q: The order of the element a^k is not n / gcd(n, k)
    try:
        ak = a ** k
        order_ak = ak.order()
        gcd_nk = math.gcd(abs(int(n)), abs(int(k)))
        expected = int(n) / gcd_nk
        neg_q_ok = order_ak != expected
    except Exception:
        neg_q_ok = False

    return [bool(h1_ok), bool(h2_ok), bool(neg_q_ok)]

