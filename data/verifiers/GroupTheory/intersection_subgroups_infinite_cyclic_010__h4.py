def conditions(witness):
    try:
        if isinstance(witness, dict):
            m = witness.get('m')
            n = witness.get('n')
            H = witness.get('H', m)
            K = witness.get('K')
        elif isinstance(witness, (tuple, list)):
            if len(witness) == 6:
                _, _, m, n, H, K = witness
            elif len(witness) == 4:
                m, n, H, K = witness
            elif len(witness) == 3:
                m, n, K = witness
                H = m
            else:
                return [False, False, False]
        else:
            return [False, False, False]
            
        # H_1: m and n are positive integers
        try:
            m_val = int(m)
            n_val = int(n)
            h1 = (m_val == m) and (n_val == n) and (m_val > 0) and (n_val > 0)
            m = m_val
            n = n_val
        except Exception:
            h1 = False
            
        # H_2: H is the subgroup generated by a^m
        try:
            H_val = int(H)
            h2 = (H_val == H) and (abs(H_val) == m)
            H = H_val
        except Exception:
            h2 = False
            
        # ¬Q: The intersection H \cap K is not the subgroup generated by a^{lcm(m,n)}
        try:
            K_val = int(K)
            if K_val != K:
                neg_q = False
            else:
                K = K_val
                intersection_gen = math.lcm(abs(H), abs(K))
                expected_gen = math.lcm(m, n)
                neg_q = intersection_gen != expected_gen
        except Exception:
            neg_q = False
            
        return [h1, h2, neg_q]
    except Exception:
        return [False, False, False]

