def conditions(witness) -> list[bool]:
    try:
        G, M, N = witness
    except Exception:
        return [False, False, False, False, False]
    
    # H1: G is a group, M and N are subgroups of G
    try:
        h1 = (isinstance(G, PermutationGroup) and 
              isinstance(M, PermutationGroup) and 
              isinstance(N, PermutationGroup) and 
              all(G.contains(g) for g in M.generators) and 
              all(G.contains(g) for g in N.generators))
    except Exception:
        h1 = False

    # H2: M is a normal subgroup of G
    try:
        h2 = False
        if h1:
            h2 = True
            for h in M.generators:
                for g in G.generators:
                    if not M.contains(~g * h * g):
                        h2 = False
                        break
                    if not M.contains(g * h * ~g):
                        h2 = False
                        break
                if not h2:
                    break
    except Exception:
        h2 = False

    # H3: M is a nilpotent group
    try:
        if callable(M.is_nilpotent):
            h3 = M.is_nilpotent()
        else:
            h3 = bool(M.is_nilpotent)
    except Exception:
        h3 = False

    # H4: N is a nilpotent group
    try:
        if callable(N.is_nilpotent):
            h4 = N.is_nilpotent()
        else:
            h4 = bool(N.is_nilpotent)
    except Exception:
        h4 = False

    # neg_Q: The product MN is NOT a normal nilpotent subgroup of G
    try:
        neg_q = False
        if h1:
            # Since M is normal in G, MN is guaranteed to be a subgroup.
            # The subgroup generated by M and N is exactly the set MN.
            MN = PermutationGroup(list(M.generators) + list(N.generators))
            
            is_MN_normal = True
            for h in MN.generators:
                for g in G.generators:
                    if not MN.contains(~g * h * g):
                        is_MN_normal = False
                        break
                    if not MN.contains(g * h * ~g):
                        is_MN_normal = False
                        break
                if not is_MN_normal:
                    break
            
            if callable(MN.is_nilpotent):
                is_MN_nilpotent = MN.is_nilpotent()
            else:
                is_MN_nilpotent = bool(MN.is_nilpotent)
            
            neg_q = not (is_MN_normal and is_MN_nilpotent)
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]

