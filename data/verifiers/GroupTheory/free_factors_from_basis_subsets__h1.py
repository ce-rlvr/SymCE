def safe_eq(A, B):
    try:
        if len(A) != len(B): return False
        for a in A:
            if a not in B: return False
        for b in B:
            if b not in A: return False
        return True
    except Exception:
        return False

def safe_subset(A, B):
    try:
        for a in A:
            if a not in B: return False
        return True
    except Exception:
        return False

def conditions(witness) -> list[bool]:
    try:
        if isinstance(witness, dict):
            F = witness.get('F')
            X = witness.get('X')
            Y = witness.get('Y')
            H = witness.get('H')
        else:
            F = witness[0]
            X = witness[1]
            Y = witness[2]
            H = witness[3]
    except Exception:
        try:
            F = witness.F
            X = witness.X
            Y = witness.Y
            H = witness.H
        except Exception:
            return [False, False, False, False]

    # H1: X is a free basis for F
    try:
        if hasattr(F, 'is_free_basis'):
            h1 = F.is_free_basis(X)
        elif hasattr(X, 'is_free_basis_for'):
            h1 = X.is_free_basis_for(F)
        elif hasattr(F, 'free_basis'):
            h1 = safe_eq(X, F.free_basis)
        elif hasattr(F, 'generators'):
            h1 = safe_eq(X, F.generators)
        else:
            h1 = False
    except Exception:
        h1 = False

    # H2: Y is a subset of X
    try:
        h2 = safe_subset(Y, X)
    except Exception:
        h2 = False

    # H3: H is the subgroup of F generated by Y
    try:
        if hasattr(H, 'is_subgroup_generated_by'):
            h3 = H.is_subgroup_generated_by(Y, F)
        elif hasattr(F, 'subgroup_generated_by'):
            h3 = H == F.subgroup_generated_by(Y)
        elif hasattr(H, 'generators'):
            h3 = safe_eq(H.generators, Y)
        else:
            h3 = False
    except Exception:
        h3 = False

    # Conclusion: H is a free factor of F, and Y freely generates H
    try:
        from sympy.combinatorics.free_groups import FreeGroup
        from sympy.combinatorics.fp_groups import FpGroup
        
        if isinstance(F, FreeGroup):
            is_ff = True
            is_fg = True
        elif isinstance(F, FpGroup):
            if len(F.relators) == 0:
                is_ff = True
                is_fg = True
            elif len(Y) == 0:
                is_ff = True
                is_fg = True
            else:
                is_ff = False
                is_fg = False
        else:
            if hasattr(F, 'is_free_factor'):
                is_ff = F.is_free_factor(H)
            elif hasattr(H, 'is_free_factor_of'):
                is_ff = H.is_free_factor_of(F)
            else:
                is_ff = False
                
            if hasattr(H, 'is_freely_generated_by'):
                is_fg = H.is_freely_generated_by(Y)
            elif hasattr(Y, 'freely_generates'):
                is_fg = Y.freely_generates(H)
            elif hasattr(H, 'is_free_basis'):
                is_fg = H.is_free_basis(Y)
            elif hasattr(H, 'generators'):
                is_fg = safe_eq(H.generators, Y)
            else:
                is_fg = False
            
        q = is_ff and is_fg
        neg_q = not q
    except Exception:
        neg_q = False

    return [bool(h1), bool(h2), bool(h3), bool(neg_q)]

