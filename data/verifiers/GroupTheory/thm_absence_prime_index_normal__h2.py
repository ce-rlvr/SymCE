def get_order(G):
    order = getattr(G, 'order', None)
    return order() if callable(order) else order

def get_derived_subgroup(G):
    ds = getattr(G, 'derived_subgroup', None)
    return ds() if callable(ds) else ds

def is_solvable(G):
    solv = getattr(G, 'is_solvable', None)
    return solv() if callable(solv) else solv

def get_elements(G):
    elems = getattr(G, 'elements', [])
    return elems() if callable(elems) else elems

def is_semisimple(G):
    """
    A finite group is semisimple if it has no non-trivial abelian normal subgroups.
    Equivalently, its solvable radical is trivial.
    We check this by ensuring no non-identity element has a solvable normal closure.
    """
    if not isinstance(G, PermutationGroup):
        return False
    if get_order(G) == 1:
        return True
    
    checked = set()
    for g in get_elements(G):
        if g.is_Identity or g in checked:
            continue
        
        # Compute the conjugacy class of g
        cc = set([g])
        queue = [g]
        G_gens = G.generators
        while queue:
            curr = queue.pop(0)
            for gen in G_gens:
                conj = gen * curr * (gen**-1)
                if conj not in cc:
                    cc.add(conj)
                    queue.append(conj)
        
        checked.update(cc)
        
        # The normal closure of g is the subgroup generated by its conjugacy class
        N = PermutationGroup(*list(cc))
        if is_solvable(N):
            return False
            
    return True

def conditions(witness):
    """
    Checks if the witness is a valid counterexample.
    The witness can be either a group G, or a tuple (G, N) where N is a normal subgroup.
    """
    try:
        if isinstance(witness, tuple) and len(witness) == 2:
            G, N = witness
            h1 = is_semisimple(G)
            
            neg_q = False
            if isinstance(N, PermutationGroup):
                # Check if N is a subgroup of G
                is_sub = all(gen in G for gen in N.generators)
                if is_sub:
                    # Check if N is normal in G
                    is_norm = True
                    for g in G.generators:
                        for n in N.generators:
                            if (g * n * (g**-1)) not in N:
                                is_norm = False
                                break
                        if not is_norm:
                            break
                    
                    if is_norm:
                        idx = get_order(G) // get_order(N)
                        neg_q = isprime(idx)
        else:
            G = witness
            h1 = is_semisimple(G)
            
            # If the witness is just G, the negated conclusion is that G has SOME normal subgroup of prime index.
            # A finite group has a normal subgroup of prime index iff it is not perfect.
            if isinstance(G, PermutationGroup):
                neg_q = get_order(get_derived_subgroup(G)) < get_order(G)
            else:
                neg_q = False
                
    except Exception:
        h1 = False
        neg_q = False

    return [h1, neg_q]

