def conditions(witness) -> list[bool]:
    try:
        if len(witness) == 3:
            G, a, n = witness
            H = PermutationGroup([a**n])
        elif len(witness) == 4:
            G, a, n, H = witness
        else:
            return [False, False, False, False]
    except Exception:
        return [False, False, False, False]

    # H1: a is a generator of G
    try:
        h1 = (a in G) and (PermutationGroup([a]).order() == G.order())
    except Exception:
        h1 = False

    # H2: n is a positive integer
    try:
        h2 = isinstance(n, (int, sympy.Integer)) and n > 0
    except Exception:
        h2 = False

    # H3: H is the subgroup of G generated by a^n
    try:
        H_gen = PermutationGroup([a**n])
        h3 = (H.order() == H_gen.order()) and (a**n in H) and H.is_subgroup(G)
    except Exception:
        h3 = False

    # neg_Q: The index of H in G is NOT equal to n
    try:
        neg_q = (G.order() != n * H.order())
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

