def simple_commutators(S, k):
    if k == 1:
        return list(S)
    prev = simple_commutators(S, k - 1)
    comms = []
    for c in prev:
        for s in S:
            comms.append(~c * ~s * c * s)
    return comms

def check_k(G, S, k):
    lcs = G.lower_central_series()
    if k - 1 < len(lcs):
        gamma_k = lcs[k - 1]
    else:
        gamma_k = lcs[-1]
        
    if k < len(lcs):
        gamma_k_plus_1 = lcs[k]
    else:
        gamma_k_plus_1 = lcs[-1]
        
    comms = simple_commutators(S, k)
    gens = list(gamma_k_plus_1.generators) + comms
    if not gens:
        gens = [G.identity] if hasattr(G, 'identity') else [Permutation()]
    H = PermutationGroup(gens)
    return gamma_k.is_subgroup(H)

def conditions(witness) -> list[bool]:
    try:
        if len(witness) == 3:
            G, S, k_list = witness[0], witness[1], [witness[2]]
        else:
            G, S = witness[0], witness[1]
            lcs = G.lower_central_series()
            k_list = list(range(1, len(lcs) + 1))
    except Exception:
        return [False, False, False]

    # H1: G is a nilpotent group
    try:
        h1 = bool(G.is_nilpotent)
    except Exception:
        h1 = False

    # H2: S is a generating set for G
    try:
        H_S = PermutationGroup(list(S))
        h2 = bool(H_S.is_subgroup(G) and G.is_subgroup(H_S))
    except Exception:
        h2 = False

    # Conclusion: The quotient group gamma_k(G)/gamma_{k+1}(G) is generated by the images of the simple commutators
    try:
        concl = True
        for k in k_list:
            if not check_k(G, S, k):
                concl = False
                break
        neg_q = not concl
    except Exception:
        neg_q = False

    return [h1, h2, neg_q]

