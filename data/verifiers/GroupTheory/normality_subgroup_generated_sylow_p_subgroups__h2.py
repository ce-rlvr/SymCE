def get_normal_closure_fast(G, P):
    """
    Computes the normal closure of subgroup P in group G.
    The normal closure is the subgroup generated by the union of all conjugates of P.
    """
    if P.order() == 1:
        if G.generators:
            g = G.generators[0]
            id_perm = g * ~g
        else:
            id_perm = Permutation()
        return PermutationGroup([id_perm])
        
    N_gens = list(P.generators)
    N = PermutationGroup(N_gens)
    
    G_gens = list(G.generators)
    G_gens_inv = [~g for g in G_gens]
    all_G_gens = G_gens + G_gens_inv
    
    # Iteratively close the generator set under conjugation by generators of G
    while True:
        added = False
        for g in all_G_gens:
            for n in N_gens:
                conj = g * n * ~g
                if conj not in N:
                    N_gens.append(conj)
                    N = PermutationGroup(N_gens)
                    added = True
                    break
            if added:
                break
        if not added:
            break
            
    return N

def conditions(witness) -> list[bool]:
    try:
        if len(witness) == 3:
            G, H, p = witness
        elif len(witness) == 2:
            G, p = witness
            H = None
        else:
            return [False, False, False]
    except Exception:
        return [False, False, False]
        
    # H_1: G is a finite group
    try:
        h1_ok = isinstance(G, PermutationGroup)
    except Exception:
        h1_ok = False
        
    # H_2: H is the subgroup of G generated by the union of all Sylow p-subgroups of G
    try:
        if not isprime(p):
            h2_ok = False
        else:
            # In a finite group, all Sylow p-subgroups are conjugate.
            # Thus, the subgroup generated by their union is exactly the normal closure of any one of them.
            P = G.sylow_subgroup(p)
            H_expected = get_normal_closure_fast(G, P)
            
            if H is None:
                H = H_expected
                h2_ok = True
            else:
                h2_ok = isinstance(H, PermutationGroup) and H.is_subgroup(H_expected) and H_expected.is_subgroup(H)
    except Exception:
        h2_ok = False
        
    # ¬Q: H is not a normal subgroup of G
    try:
        if H is None:
            neg_q_ok = False
        else:
            neg_q_ok = not H.is_normal(G)
    except Exception:
        neg_q_ok = False
        
    return [h1_ok, h2_ok, neg_q_ok]

