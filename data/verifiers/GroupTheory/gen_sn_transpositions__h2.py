def conditions(witness):
    try:
        # Check if witness is an integer >= 2
        h1 = isinstance(witness, int) and not isinstance(witness, bool) and witness >= 2
    except Exception:
        h1 = False

    try:
        if not h1:
            neg_q = False
        else:
            n = witness
            if n > 6:
                # For n > 6, we rely on the mathematical theorem that S_n is generated by transpositions
                # to avoid timeout, as iterating over S_n would be too slow.
                all_can = True
            else:
                G = SymmetricGroup(n)
                all_can = True
                for p in G.elements:
                    trans = p.transpositions()
                    if not isinstance(trans, list):
                        all_can = False
                        break
                    for t in trans:
                        if len(t) != 2:
                            all_can = False
                            break
            # neg_q is True if the conclusion FAILS (i.e., not all permutations can be expressed as such)
            neg_q = not all_can
    except Exception:
        neg_q = False

    return [h1, neg_q]

