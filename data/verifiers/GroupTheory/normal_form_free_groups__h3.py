def conditions(witness) -> list[bool]:
    try:
        X, F_X, w = witness
    except Exception:
        return [False, False, False]

    # H_1: X is a set
    try:
        h1 = isinstance(X, (set, list, tuple))
    except Exception:
        h1 = False

    # H_2: F(X) is the free group generated by X
    try:
        h2 = False
        if type(F_X).__name__ == 'FreeGroup':
            gen_set = set(F_X.generators)
            if set(X) == gen_set:
                h2 = True
            else:
                x_strs = set(str(g) for g in X)
                gen_strs = set(str(g) for g in gen_set)
                if x_strs == gen_strs:
                    h2 = True
    except Exception:
        h2 = False

    # ¬Q: w cannot be uniquely represented by a reduced word over the alphabet X U X^-1
    try:
        if w in F_X:
            neg_q = False
        else:
            neg_q = True
    except Exception:
        neg_q = True

    return [h1, h2, neg_q]

