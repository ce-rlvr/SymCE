def conditions(witness):
    try:
        G, H, phi = witness
    except Exception:
        return [False, False, False, False]
        
    # H1: G and H are groups
    try:
        h1 = isinstance(G, PermutationGroup) and isinstance(H, PermutationGroup)
    except Exception:
        h1 = False
        
    # H2: G is a simple group
    try:
        h2 = False
        if h1:
            order = G.order()
            if order > 1:
                if sympy.isprime(order):
                    h2 = True
                else:
                    elems = list(G.generate())
                    is_simp = True
                    for g in elems:
                        if g.is_Identity:
                            continue
                        # The normal closure of g is the group generated by all its conjugates
                        conjugates = list(set(x * g * (x**-1) for x in elems))
                        N = PermutationGroup(*conjugates)
                        if N.order() < order:
                            is_simp = False
                            break
                    h2 = is_simp
    except Exception:
        h2 = False
        
    # H3: ϕ: G → H is a group homomorphism
    try:
        h3 = False
        if h1:
            elems = list(G.generate())
            H_elems = list(H.generate())
            
            if callable(phi):
                phi_dict = {g: phi(g) for g in elems}
            elif isinstance(phi, dict):
                phi_dict = phi
            else:
                phi_dict = None
                
            if phi_dict is not None:
                h3 = True
                for g in elems:
                    if g not in phi_dict or phi_dict[g] not in H_elems:
                        h3 = False
                        break
                if h3:
                    for x in elems:
                        for y in elems:
                            if phi_dict[x * y] != phi_dict[x] * phi_dict[y]:
                                h3 = False
                                break
                        if not h3:
                            break
    except Exception:
        h3 = False
        
    # ¬Q: ϕ is not injective or G is not isomorphic to ϕ(G)
    try:
        neg_q = False
        if h1:
            elems = list(G.generate())
            if callable(phi):
                values = [phi(g) for g in elems]
            elif isinstance(phi, dict):
                values = [phi.get(g, None) for g in elems]
            else:
                values = []
                
            if len(values) == len(elems) and all(v is not None for v in values):
                is_injective = len(set(values)) == len(elems)
                # For finite groups, an injective homomorphism is an isomorphism onto its image.
                # Thus, the conclusion fails if and only if ϕ is not injective.
                neg_q = not is_injective
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

