def conditions(witness):
    try:
        h1 = isinstance(witness, int) and witness >= 2
    except Exception:
        h1 = False

    try:
        if not h1:
            neg_q = False
        else:
            n = witness
            # In 0-indexed SymPy, the adjacent transpositions (1 2), (2 3), ..., (n-1 n)
            # correspond to (0 1), (1 2), ..., (n-2 n-1).
            transpositions = [Permutation(i, i+1, size=n) for i in range(n-1)]
            G = PermutationGroup(transpositions)
            
            # The group Sn has order n!. If the generated subgroup has order n!, 
            # then it is the entire symmetric group Sn.
            is_generated = (G.order() == math.factorial(n))
            neg_q = not is_generated
    except Exception:
        neg_q = False

    return [h1, neg_q]

