def conditions(witness):
    """
    Checks whether the given witness is a valid counterexample.
    The witness is expected to provide n (a positive integer) and a (an integer representing 
    an element of the infinite cyclic group Z).
    """
    try:
        if isinstance(witness, dict):
            n = int(witness['n'])
            a = int(witness['a'])
        else:
            ints = []
            # Extract integers from the witness tuple/list
            for x in witness:
                if isinstance(x, int) and not isinstance(x, bool):
                    ints.append(x)
                elif hasattr(x, 'is_integer') and x.is_integer and not isinstance(x, bool):
                    ints.append(int(x))
            
            if len(ints) >= 2:
                n, a = ints[0], ints[1]
                # If n is not positive but a is, they might be swapped
                if n <= 0 and a > 0:
                    n, a = a, n
            else:
                n, a = None, None
    except Exception:
        n, a = None, None

    # H_1: G is an infinite cyclic group
    # We model G as the additive group of integers Z, which is an infinite cyclic group.
    try:
        h1 = (n is not None and a is not None)
    except Exception:
        h1 = False

    # H_2: n is a positive integer
    try:
        h2 = isinstance(n, int) and n > 0
    except Exception:
        h2 = False

    # H_3: H is the subgroup of G generated by a^n
    # In our additive model Z, a^n corresponds to n * a.
    # The subgroup H is <n * a>, which is inherently true by our definition of the index check.
    try:
        h3 = (n is not None and a is not None)
    except Exception:
        h3 = False

    # ¬Q: The index of H in G is not equal to n
    # The index of the subgroup <n * a> in Z is |n * a|.
    # If n * a == 0, the subgroup is {0} and its index in Z is infinite.
    try:
        if n is not None and a is not None:
            index = abs(n * a) if (n * a) != 0 else float('inf')
            neg_q = index != n
        else:
            neg_q = False
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]