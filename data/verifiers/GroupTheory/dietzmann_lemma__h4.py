def conditions(witness) -> list[bool]:
    try:
        G, S = witness
    except Exception:
        return [False, False, False, False]
    
    # H_1: G is a group
    try:
        h1 = isinstance(G, PermutationGroup)
    except Exception:
        h1 = False
        
    # H_2: S is a finite subset of G
    try:
        h2 = isinstance(S, (list, set, tuple))
        if h2:
            for s in S:
                if not isinstance(s, Permutation) or s not in G:
                    h2 = False
                    break
    except Exception:
        h2 = False
        
    # H_3: Every element of S has finite order
    try:
        h3 = True
        if isinstance(S, (list, set, tuple)):
            for s in S:
                if not isinstance(s, Permutation):
                    h3 = False
                    break
                if s.order() <= 0 or s.order() == float('inf'):
                    h3 = False
                    break
        else:
            h3 = False
    except Exception:
        h3 = False
        
    # neg_Q: The subgroup generated by S is NOT a finite normal subgroup of G
    try:
        if not isinstance(S, (list, set, tuple)):
            neg_q = False
        elif not S:
            # The subgroup generated by the empty set is the trivial group,
            # which is always a finite normal subgroup.
            neg_q = False
        else:
            H = PermutationGroup(list(S))
            
            # Check if H is a subgroup of G
            is_subgroup = True
            for h in H.generators:
                if h not in G:
                    is_subgroup = False
                    break
            
            if not is_subgroup:
                neg_q = True
            else:
                # Check if H is normal in G
                is_normal = True
                for g in G.generators:
                    for h in H.generators:
                        if (g * h * ~g) not in H:
                            is_normal = False
                            break
                        if (~g * h * g) not in H:
                            is_normal = False
                            break
                    if not is_normal:
                        break
                
                # Since H is a PermutationGroup, it is inherently finite.
                # Thus, it fails to be a finite normal subgroup iff it is not normal.
                neg_q = not is_normal
    except Exception:
        neg_q = False
        
    return [h1, h2, h3, neg_q]

