def conditions(witness) -> list[bool]:
    try:
        # The witness could be just n, or a tuple specifying n and the permutations
        if isinstance(witness, (tuple, list)):
            n = int(witness[0])
            try:
                # Case: witness is (n, a, b) where (a, b) is the transposition
                if len(witness) == 3:
                    a = int(witness[1])
                    b = int(witness[2])
                    p1 = Permutation(a, b)
                    p2 = Permutation(*range(n))
                else:
                    raise ValueError
            except (ValueError, TypeError):
                # Case: witness contains explicit permutation objects or tuples
                if len(witness) >= 3:
                    def make_perm(p):
                        if isinstance(p, Permutation):
                            return p
                        elif isinstance(p, (tuple, list)):
                            return Permutation(p)
                        else:
                            raise ValueError
                    p1 = make_perm(witness[1])
                    p2 = make_perm(witness[2])
                elif len(witness) == 2:
                    p1 = witness[1] if isinstance(witness[1], Permutation) else Permutation(witness[1])
                    p2 = Permutation(*range(n))
                else:
                    p1 = Permutation(0, 1)
                    p2 = Permutation(*range(n))
        else:
            # Case: witness is just n
            n = int(witness)
            p1 = Permutation(0, 1)
            p2 = Permutation(*range(n))
            
        h1 = (n >= 2)
    except Exception:
        return [False, False]
        
    try:
        G = PermutationGroup(p1, p2)
        # The conclusion states S_n is generated by the TWO elements.
        # This implies they must be distinct and together generate S_n.
        q = (p1 != p2) and (G.order() == math.factorial(n))
        neg_q = not q
    except Exception:
        neg_q = False

    return [h1, neg_q]

