def conditions(witness):
    """
    Checks if the witness is a valid counterexample to the false conjecture.
    The witness should be a dictionary containing:
      - 'F': a SymPy FreeGroup generated by X \cup Y
      - 'X': list of generators for N
      - 'Y': list of generators for H
      - 'R': list of relations (words in X) for N
      - 'S': list of relations (words in Y) for H
      - 'phi': dict mapping (y, x) to a word in X
    """
    try:
        F = witness['F']
        X = witness['X']
        Y = witness['Y']
        R = witness['R']
        S = witness['S']
        phi = witness['phi']
    except (KeyError, TypeError):
        return [False, False, False, False]
        
    # H1: N is a group generated by a set X with defining relations R
    try:
        h1 = True
        # X and Y should be disjoint sets of generators
        if set(X).intersection(set(Y)):
            h1 = False
        for rel in R:
            if not all(g in X for g, exp in rel.array_form):
                h1 = False
                break
    except Exception:
        h1 = False

    # H2: H is a group generated by a set Y with defining relations S
    try:
        h2 = True
        for rel in S:
            if not all(g in Y for g, exp in rel.array_form):
                h2 = False
                break
    except Exception:
        h2 = False

    # H3: For each x in X and y in Y, w_{y,x} is a word in X representing phi_y(x)
    try:
        h3 = True
        for x in X:
            for y in Y:
                if (y, x) not in phi:
                    h3 = False
                    break
                w = phi[(y, x)]
                if not all(g in X for g, exp in w.array_form):
                    h3 = False
                    break
    except Exception:
        h3 = False

    # ¬Q: The external semidirect product N \rtimes_\phi H admits the group presentation...
    # If the presentation defines a group whose order is not |N| * |H|, then it cannot be 
    # the external semidirect product (which as a set has size |N| * |H|).
    try:
        # Order of N = <X | R>
        N_group = FpGroup(F, R + Y)
        N_order = N_group.order()
        
        # Order of H = <Y | S>
        H_group = FpGroup(F, S + X)
        H_order = H_group.order()
        
        # Order of the presented group G = <X U Y | R U S U {y x y^-1 = w_{y,x}}>
        cross_rels = []
        for x in X:
            for y in Y:
                # y * x * y^-1 = w_{y,x}  =>  y * x * y^-1 * w_{y,x}^-1 = 1
                cross_rels.append(y * x * y**-1 * phi[(y, x)]**-1)
                
        G = FpGroup(F, R + S + cross_rels)
        G_order = G.order()
        
        # The conclusion fails if the presented group does not have the correct order.
        # We require N_order > 1 and H_order > 1 to avoid trivial degenerate cases.
        neg_q = (N_order > 1) and (H_order > 1) and (G_order != N_order * H_order)
    except Exception:
        neg_q = False

    return [h1, h2, h3, neg_q]

