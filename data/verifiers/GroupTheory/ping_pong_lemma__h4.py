def conditions(witness) -> list[bool]:
    if isinstance(witness, dict):
        class W: pass
        w = W()
        w.__dict__.update(witness)
        witness = w

    # Helper functions for group operations and actions
    try:
        if hasattr(witness, 'mul'):
            mul = witness.mul
        else:
            mul = lambda x, y: x * y
            
        if hasattr(witness, 'inv'):
            inv = witness.inv
        else:
            def inv(g):
                try: return g.inv()
                except Exception: return g**-1
                
        if hasattr(witness, 'is_id'):
            is_id = witness.is_id
        else:
            def is_id(g):
                if hasattr(g, 'is_Identity'): return g.is_Identity
                if hasattr(g, 'shape'):
                    from sympy import eye
                    return g == eye(g.shape[0])
                try: return bool(g == 1)
                except Exception: return False

        def power(g, n):
            if n == 0:
                raise ValueError("n=0")
            if n > 0:
                res = g
                for _ in range(n - 1):
                    res = mul(res, g)
                return res
            else:
                g_inv = inv(g)
                res = g_inv
                for _ in range(-n - 1):
                    res = mul(res, g_inv)
                return res

        def act(g, x):
            if hasattr(witness, 'act'):
                return witness.act(g, x)
            try:
                return g * x
            except Exception:
                return g(x)
    except Exception:
        pass

    # H_1: G is a group acting on a set X
    try:
        a = witness.a
        b = witness.b
        _ = inv(a)
        _ = inv(b)
        _ = mul(a, b)
        if hasattr(witness, 'X1_samples') and witness.X1_samples:
            _ = act(a, witness.X1_samples[0])
        h1_ok = True
    except Exception:
        h1_ok = False

    # H_2: X1 and X2 are disjoint non-empty subsets of X
    try:
        x1_samples = witness.X1_samples
        x2_samples = witness.X2_samples
        if not x1_samples or not x2_samples:
            h2_ok = False
        else:
            h2_ok = True
            for x in x1_samples:
                if not bool(witness.in_X1(x)) or bool(witness.in_X2(x)):
                    h2_ok = False
                    break
            for x in x2_samples:
                if not bool(witness.in_X2(x)) or bool(witness.in_X1(x)):
                    h2_ok = False
                    break
    except Exception:
        h2_ok = False

    # H_3: a and b are elements of G
    try:
        _ = witness.a
        _ = witness.b
        h3_ok = True
    except Exception:
        h3_ok = False

    # H_4: For all non-zero integers n, the image of X1 under b^n is a subset of X2
    try:
        h4_ok = True
        b = witness.b
        # Check a reasonable range of non-zero integers
        for n in range(-20, 21):
            if n == 0:
                continue
            bn = power(b, n)
            for x in witness.X1_samples:
                y = act(bn, x)
                if not bool(witness.in_X2(y)):
                    h4_ok = False
                    break
            if not h4_ok:
                break
    except Exception:
        h4_ok = False

    # ¬Q: The subgroup of G generated by {a, b} is not isomorphic to the free group of rank 2
    # We verify this by checking if the witness provides a valid non-trivial relation that evaluates to the identity.
    try:
        relation = witness.relation
        if not relation:
            neg_q_ok = False
        else:
            is_reduced = True
            for i in range(len(relation) - 1):
                if relation[i][0] == relation[i+1][0]:
                    is_reduced = False
            for sym, p in relation:
                if p == 0:
                    is_reduced = False
            
            if not is_reduced:
                neg_q_ok = False
            else:
                val = None
                for sym, p in relation:
                    if sym == 'a':
                        term = power(witness.a, p)
                    elif sym == 'b':
                        term = power(witness.b, p)
                    else:
                        raise ValueError("Unknown symbol")
                    
                    if val is None:
                        val = term
                    else:
                        val = mul(val, term)
                
                if is_id(val):
                    neg_q_ok = True
                else:
                    # Fallback: check if the evaluated relation acts trivially on all sample points
                    acts_trivially = True
                    for x in witness.X1_samples + witness.X2_samples:
                        if act(val, x) != x:
                            acts_trivially = False
                            break
                    neg_q_ok = acts_trivially
    except Exception:
        neg_q_ok = False

    return [h1_ok, h2_ok, h3_ok, h4_ok, neg_q_ok]

