def is_subgroup(H, G):
    if not isinstance(H, PermutationGroup) or not isinstance(G, PermutationGroup):
        return False
    for gen in H.generators:
        if not G.contains(gen):
            return False
    return True

def is_normal_subgroup(N, G):
    if not is_subgroup(N, G):
        return False
    for g in G.generators:
        g_inv = g**-1
        for n in N.generators:
            if not N.contains(g * n * g_inv):
                return False
            if not N.contains(g_inv * n * g):
                return False
    return True

def get_multiplicity(p, n):
    if p <= 1 or n <= 0:
        return 0
    count = 0
    while n % p == 0:
        count += 1
        n //= p
    return count

def conditions(witness) -> list[bool]:
    try:
        G = witness['G']
        N = witness['N']
        H = witness['H']
        p = witness['p']
        P_N = witness['P_N']
        P_H = witness['P_H']
    except Exception:
        return [False, False, False, False, False]

    # H1: G = N \rtimes H is a finite semidirect product
    try:
        h1 = (isinstance(G, PermutationGroup) and 
              is_subgroup(H, G) and 
              is_normal_subgroup(N, G) and 
              N.order() * H.order() == G.order())
    except Exception:
        h1 = False

    # H2: p is a prime number
    try:
        h2 = isprime(p)
    except Exception:
        h2 = False

    # H3: P_H is a Sylow p-subgroup of H
    try:
        h_order = H.order()
        p_power_h = p ** get_multiplicity(p, h_order)
        h3 = is_subgroup(P_H, H) and P_H.order() == p_power_h
    except Exception:
        h3 = False

    # H4: P_N is a Sylow p-subgroup of N
    try:
        n_order = N.order()
        p_power_n = p ** get_multiplicity(p, n_order)
        h4 = is_subgroup(P_N, N) and P_N.order() == p_power_n
    except Exception:
        h4 = False

    # neg_Q: P_N \rtimes P_H is NOT a Sylow p-subgroup of G
    # The set P_N P_H has the correct size to be a Sylow p-subgroup.
    # It forms a Sylow p-subgroup if and only if it is a valid subgroup,
    # which happens iff the group generated by P_N and P_H has exactly that size.
    try:
        gens = list(P_N.generators) + list(P_H.generators)
        if not gens:
            expected_order = P_N.order() * P_H.order()
            is_sylow = (expected_order == 1)
        else:
            gen_group = PermutationGroup(gens)
            expected_order = P_N.order() * P_H.order()
            is_sylow = (gen_group.order() == expected_order)
        neg_q = not is_sylow
    except Exception:
        neg_q = False

    return [h1, h2, h3, h4, neg_q]

